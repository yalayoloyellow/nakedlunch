# nakedlunch — профиль референсного текста и цепочка пайплайна из него.
#
# ЗАЧЕМ. Требование (2026-08-03): после калибровки в пайплайн вставляется референтный текст и
# процент референтности, и структура назначается сама..
#
# Это ответ на его же более раннюю претензию — «я не имею контроля над
# выдачей». Крутить абстрактные веса вслепую он не хочет и прав: замером
# доказано (Раунд 32, спайк на его данных), что предсказать «нравится» по
# прошлому выбору нельзя — кластера нет. Но референс — не классификатор, а
# МИШЕНЬ: мы не угадываем вкус, мы меряем конкретный текст и повторяем его
# профиль. Это считается точно и проверяется тем же измерителем.
#
# ЧЕСТНАЯ ГРАНИЦА. Корпус — нарезка прозы из книг. Синтаксис и образность
# референса машина не воспроизведёт. Повторяемо ровно четыре вещи: каркас
# (сколько частей, какой длины, какая рифмовка), звук (ярус рифм, клаузула),
# фактура (мат, частотность) и связность. Их и меряем — остальное было бы
# враньём о своих возможностях.
#
# Числа откалиброваны по трём текстам пользователя («Москва», «харакири»,
# «Рассвет»), см. DECISIONS.md Раунд 44.

from __future__ import annotations

import re
import statistics as st

import numpy as np

import clean
import corpus as corpus_mod
import embeddings
import filters
import scan
import wordsuggest      # словарь ударений (660k, ruaccent) — уже в памяти процесса

СЛОВО = re.compile(r"[А-Яа-яЁёA-Za-z]+")
БУКВЫ = "абвгдежзи"

# Порог, с которого клаузула считается ПРИЗНАКОМ текста, а не совпадением.
# У пользователя 77/93/100% — с запасом выше; ниже 60% это уже смесь, и ворота
# по ней только обеднили бы пул без пользы.
КЛАУЗУЛА_ПОРОГ = 0.6

# Референтность, начиная с которой действуют крутилки с ОСОБОЙ ТОЧКОЙ — те, у
# которых дефолт лежит вне рабочего диапазона («Мат» и «Связность» выключены
# значением −1, клаузула — категориальна). Промежуточных положений у них нет:
# либо держим замеренное, либо не трогаем вовсе (см. `цепочка`).
ПОРОГ_ЖЁСТКОГО = 0.7


def _слоги(s: str) -> int:
    return sum(1 for ch in s.lower() if ch in scan.VOWELS)


def _хвосты(строка: str) -> tuple[str, str]:
    """Мужской и женский хвосты последнего слова — суррогат рифмо-ключа для
    ЧУЖОГО текста: ударений мы там не знаем (ruaccent живёт на сборке корпуса),
    но для сравнения окончаний между собой этого достаточно."""
    слова = СЛОВО.findall(строка.lower().replace("ё", "е"))
    if not слова:
        return "", ""
    w = слова[-1]
    гл = [i for i, ch in enumerate(w) if ch in scan.VOWELS]
    if not гл:
        return "", ""
    муж = w[гл[-1]:]
    жен = w[гл[-2]:] if len(гл) > 1 else муж
    return муж, жен


def _рифмуются(a, b, ярус: str) -> bool:
    am, aj = a
    bm, bj = b
    if not am or not bm:
        return False
    if ярус == "точная":
        return aj == bj and len(aj) >= 2
    if ярус == "усечённая":
        return am == bm
    return am[:1] == bm[:1]


def _клаузула(строка: str) -> int:
    """Клаузула последнего слова строки — по НАСТОЯЩЕМУ ударению.

    ПОЧИНКА Раунда 51. Здесь стояло собственное угадывание: хвост резался от
    предпоследней гласной, значит в нём ВСЕГДА ровно две гласных — и функция
    физически не могла вернуть 3, а для любого неодносложного слова
    возвращала 2. То есть это был детектор односложности, а не клаузула.
    Замер против ruaccent на 34 501 последнем слове строк корпуса: верна в
    58.1% случаев, при том что истина — 41.5% мужских и 37.0% женских.
    Вся «женская клаузула 77/93/100%» в замере референсов пользователя была
    артефактом этой ошибки.

    Настоящий ответ лежал в том же процессе: словарь 660k словоформ с
    ударениями от ruaccent поднят на старте сервера (wordsuggest.warm_caches).
    Слова нет в словаре — честный 0, и такая строка просто не участвует в
    замере (см. фильтр в `профиль`), а не портит его догадкой."""
    слова = СЛОВО.findall((строка or "").lower())
    if not слова:
        return 0
    return scan.clausula(wordsuggest.rhyme_key_of(слова[-1]))


def _центроид(строка: str):
    return embeddings.lemma_centroid(corpus_mod.lemmatize(строка))


def _cos(a, b):
    if a is None or b is None:
        return None
    na, nb = float(np.linalg.norm(a)), float(np.linalg.norm(b))
    if not na or not nb:
        return None
    return float(a @ b / (na * nb))


def _части(текст: str) -> list[list[str]]:
    out = []
    for блок in re.split(r"\n\s*\n", (текст or "").strip()):
        строки = [l.strip() for l in блок.split("\n") if l.strip()]
        if строки:
            out.append(строки)
    return out


def _схема(строки: list[str], ярус: str) -> str:
    """Буквы рифмовки части: первая непристроенная строка открывает новую
    букву, все рифмующиеся с ней получают ту же. Ярус задаёт, что считать
    рифмой — у пользователя точной почти нет, поэтому обычно 'усечённая'."""
    хв = [_хвосты(l) for l in строки]
    буквы = [""] * len(строки)
    сл = 0
    for i in range(len(строки)):
        if буквы[i]:
            continue
        буквы[i] = БУКВЫ[min(сл, len(БУКВЫ) - 1)]
        for j in range(i + 1, len(строки)):
            if not буквы[j] and _рифмуются(хв[i], хв[j], ярус):
                буквы[j] = буквы[i]
        сл += 1
    return "".join(буквы)


def _точность(доля_точных: float) -> float:
    """Ярус точности рифм из доли ТОЧНЫХ рифм в тексте. Шкала бэка обратная:
    0 = только точные, 1 = мягкие (см. clean.knobs rhyme_precision). Лесенка,
    а не формула: трёх точек калибровки на непрерывную кривую не хватает,
    и делать вид, что хватает, — хуже, чем признать ступени."""
    if доля_точных >= 0.4:
        return 0.25
    if доля_точных >= 0.2:
        return 0.5
    return 0.75


def профиль(текст: str) -> dict:
    """Полный профиль: общие числа плюс профиль КАЖДОЙ части.

    Части нужны отдельно не для красоты: требование: настраивать раздельно каждый кусок пайплайна — отдельно куплет, отдельно
    припев. Референс их и назначает."""
    embeddings.warm_caches()
    бл = _части(текст)
    if not бл:
        raise clean.BadInput("пустой референс")

    строки = [l for b in бл for l in b]
    n = len(строки)
    хв = [_хвосты(l) for l in строки]

    # доли ярусов рифмы по всему тексту: партнёр в пределах ±4 строк
    доли = {}
    for ярус in ("точная", "усечённая", "слабая"):
        есть = 0
        for i in range(n):
            for j in range(max(0, i - 4), min(n, i + 5)):
                if i != j and _рифмуются(хв[i], хв[j], ярус):
                    есть += 1
                    break
        доли[ярус] = есть / n
    ярус_схемы = "усечённая" if доли["усечённая"] >= 0.3 else "слабая"

    центры = [_центроид(l) for l in строки]
    части_проф = []
    поз = 0
    for b in бл:
        m = len(b)
        сл = [_слоги(l) for l in b]
        кл = [c for c in (_клаузула(l) for l in b) if c]
        частая = max(set(кл), key=кл.count) if кл else 0
        доля_кл = (кл.count(частая) / len(кл)) if кл else 0.0
        # связность внутри части
        внутри = [c for c in (_cos(центры[поз + i], центры[поз + i + 1]) for i in range(m - 1))
                  if c is not None]
        матных = sum(1 for l in b if filters.has_mat(l))
        части_проф.append({
            "строк": m,
            "схема": _схема(b, ярус_схемы),
            "слогов": round(st.mean(сл), 1),
            "разброс": round(st.pstdev(сл), 1) if m > 1 else 0.0,
            "клаузула": частая if доля_кл >= КЛАУЗУЛА_ПОРОГ else 0,
            "связность": round(st.mean(внутри), 3) if внутри else None,
            "мат": round(матных / m, 2),
        })
        поз += m

    # стыки: рифмуется ли конец части с началом следующей
    стыки = []
    поз = 0
    for i in range(len(бл) - 1):
        поз += len(бл[i])
        рифма = _рифмуются(хв[поз - 1], хв[поз], ярус_схемы)
        стыки.append("рифмовать стык" if рифма else "свободно")

    слова = [w.lower() for l in строки for w in СЛОВО.findall(l)]
    from wordfreq import zipf_frequency
    зипф = [z for z in (zipf_frequency(w, "ru") for w in слова) if z > 0]

    return {
        "частей": len(бл), "строк": n,
        "рифма": {k: round(v, 2) for k, v in доли.items()},
        "точность": _точность(доли["точная"]),
        "частотность": round(st.mean(зипф), 2) if зипф else 0.0,
        "мат": round(sum(1 for l in строки if filters.has_mat(l)) / n, 2),
        "части": части_проф,
        "стыки": стыки,
    }


def цепочка(проф: dict, референтность: float = 1.0) -> dict:
    """Профиль → готовый запрос пайплайна: цепочка со СВОЕЙ спекой строфы и
    своими кнобами на каждое звено плюс стыки.

    `референтность` 0..1 — насколько жёстко держаться замеров:
      1.0 — вилка слогов узкая (±полразброса), клаузула воротами, связность и
            мат ровно как в тексте;
      0.7 — последняя ступень, на которой всё это ещё держится;
      ниже — остаётся КАРКАС (сколько частей, какой длины, какая рифмовка,
            вилка слогов тем шире, чем ниже) и точность рифм, ползущая к
            дефолту; клаузула, связность и мат снимаются совсем.
      0.0 — только каркас, всё остальное по умолчанию.

    Линейно едет лишь то, у чего дефолт лежит ВНУТРИ шкалы: вилка слогов и
    точность рифм. Остальные крутилки выключаются значением вне диапазона
    (−1), и «полпути к выключено» на них не существует — см. ПОРОГ_ЖЁСТКОГО и
    разбор в теле функции.

    `обрезано` — сколько частей не влезло в предел цепочки. Отдаём число, а не
    молчим: длинный текст (кнопка «взять из листа» даёт цепочку сразу на весь
    лист) собрал бы 20 звеньев, интерфейс показал бы все 20, а прогон упал бы
    400-й «цепочка — список из 1..12 звеньев» — уже после того, как пользователь
    нажал «прогон» и подождал."""
    р = max(0.0, min(1.0, float(референтность)))
    части = проф["части"][:clean._PIPE_CHAIN_MAX]
    обрезано = len(проф["части"]) - len(части)
    звенья = []
    for ч in части:
        м = ч["слогов"]
        # чем ниже референтность, тем шире вилка: от ±0.5 разброса до ±3 слогов
        полу = max(1.0, ч["разброс"] * 0.5) * р + 3.0 * (1.0 - р)
        lo, hi = max(1, round(м - полу)), max(2, round(м + полу))
        схема = ч["схема"] or "".join(БУКВЫ[i % len(БУКВЫ)] for i in range(ч["строк"]))
        spec = [{"letter": схема[i % len(схема)], "min_syl": lo, "max_syl": hi}
                for i in range(ч["строк"])]
        # Крутилки в КООРДИНАТАХ ИНТЕРФЕЙСА (Раунд 51). Раньше здесь собирались
        # ядерные имена (clausula/flow/mat_share/rhyme_precision), а слепок
        # цепочки клал в то же поле русские — одно поле, две несовместимые
        # системы, и ядро молча выбрасывало чужие ключи, генеря на дефолтах.
        # Теперь формат ОДИН на всём пути: звено носит {mode, params}, а
        # переводит их единственный переводчик — clean.knobs_from_profile.
        # ПРАВИЛО (починка Раунда 51). Чего нет в params, то берёт дефолт
        # (clean.knob_params) — и только через отсутствие ключа обещание
        # докстринга «референтность 0 = остаётся один каркас» вообще
        # выполнимо. Поэтому: крутилка, у которой ДЕФОЛТ ЛЕЖИТ ВНЕ рабочего
        # диапазона, не интерполируется — она либо действует замеренной, либо
        # отсутствует. Интерполируется только та, чей дефолт лежит ВНУТРИ.
        #
        # Раньше на `р` умножалось всё подряд, а ноль на этих шкалах значит не
        # «не задано», а жёсткое требование, причём ПРОТИВОПОЛОЖНОЕ замеру:
        #   «Мат» 0 — это «без мата», сплошной фильтр (дефолт −1 «как есть»).
        #     Референс с 20% мата на нулевой референтности требовал выдачу без
        #     единого матерного слова.
        #   «Связность» 0 — это ВКЛЮЧЁННОЕ мнение с мишенью cos ≈ 0, то есть
        #     «соседние строки обязаны быть максимально не связаны» (filters:
        #     flow >= 0.0 включает, flow_target = _FLOW_MAX·flow). Выключено —
        #     это −1. Ослабить такую мишень умножением нельзя: множитель не
        #     уменьшает силу мнения, он меняет само требование.
        params = {}
        жёстко = р >= ПОРОГ_ЖЁСТКОГО
        if ч["клаузула"] and жёстко:
            params["Клаузула"] = ч["клаузула"]
        if ч["связность"] is not None and жёстко:
            # обратный перевод в шкалу ползунка (см. filters._FLOW_MAX)
            params["Связность"] = round(
                min(1.0, max(0.0, ч["связность"] / filters._FLOW_MAX)), 2)
        if жёстко:
            params["Мат"] = ч["мат"]
        # Точность рифм — обычная непрерывная шкала: её дефолт 0.25 лежит
        # ВНУТРИ диапазона, поэтому к нему и едем линейно, без порога.
        params["Точность рифм"] = round(проф["точность"] * р + 0.25 * (1.0 - р), 2)
        # `title` пустой (Раунд 50): референс задаёт КАРКАС и КРУТИЛКИ, а не
        # заголовки. Раньше сюда шло role="строфа" — и каждая часть текста
        # получала в документе строку-заголовок «строфа», которую пользователь не
        # просил и убрать не мог.
        звенья.append({"title": "", "spec": spec,
                       "mode": clean.MODE_ALGO, "params": params})
    # стыков ровно звеньев−1: обрезали цепочку — обрезаются и они
    return {"chain": звенья, "обрезано": обрезано,
            "junctions": list(проф["стыки"])[:max(0, len(звенья) - 1)]}
