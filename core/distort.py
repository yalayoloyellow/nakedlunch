# nakedlunch — ИСКАЖЕНИЕ КРУТИЛОК СЕРИИ (Раунд 55).
#
# Требование (2026-08-04): искажение живёт в серии и влияет на её пайплайны; на кривой
# пайплайны идут последовательно, а их параметры — по её высоте..
#
# И: «кривая похожа на RGB-кривую в редакторе, в этом смысл».
#
# ОТСЮДА ВСЁ УСТРОЙСТВО:
#
#   Ось X — МЕСТО В СЕРИИ. Целое число это трек, дробная часть — его звенья по
#   порядку. Трек занимает ровно одну клетку [k, k+1) независимо от того,
#   сколько звеньев в его цепочке, — поэтому смена цепочки у второго трека не
#   двигает третий. Это единственное, чем мы отличаемся от фотошопа, и это
#   надо помнить.
#
#   Ось Y — СДВИГ, а не значение. Нейтраль — горизонталь посередине: ровная
#   линия не делает ничего, выше — плюс к крутилке, ниже — минус. Поэтому
#   отдельного ползунка «сила кривой» нет и быть не должно: насколько отогнул,
#   настолько и подействовало.
#
#   Каналы — как в RGB: мастер плюс свои у каждого канала, и они СКЛАДЫВАЮТСЯ.
#   Гнёшь «все мнения» — едет всё; переключился на «Диссонанс» — гнёшь только
#   его, остальные держат своё.
#
# ЧТО ИСКАЖАЕТСЯ И ПОЧЕМУ ИМЕННО ЭТО.
#
# Только МНЕНИЯ — крутилки, которые переставляют порядок кандидатов. Ворота
# (Источники, Мат, Клаузула) режут насмерть: дёрнул клаузулу на бридже, и
# звено осталось без кандидатов, а пользователь увидел «пусто на звене» вместо
# интересной вариации. Мнения так сломаться не могут по построению — отсюда
# обещание в панели «пусто не станет», и оно должно оставаться правдой.
#
# «Повтор» не искажается тоже, хотя формально мнение: у него нет шкалы, есть
# барьер 0/1. Сдвинуть его на 0.3 — не «чуть иначе», а «как повезёт при
# округлении». «Связность» искажается ТОЛЬКО когда она включена: −1 у неё
# значит «выключено», а не «край шкалы», и сдвиг с −1 включал бы её молча.
#
# ШУМ — второй источник, работает вместе с кривой и складывается с ней.
# Кривая — характер МЕСТА в альбоме (один и тот же трек всегда звучит
# одинаково-своим), шум — разброс между ДУБЛЯМИ одного трека: своё случайное
# зерно на каждый прогон, десять вариантов — десять оттенков. Видеть его
# незачем, у него только сила.

from __future__ import annotations

import random

# Крутилки-мнения в координатах ИНТЕРФЕЙСА — те же имена, что едут в звене
# слепка цепочки. Порядок важен: он же порядок каналов в меню.
КАНАЛЫ = ("Точность рифм", "Мелодичность", "Банальность", "Диссонанс", "Связность")

# Канал «все мнения»: складывается с личным каналом каждой крутилки.
МАСТЕР = "все"

# «Связность» ведём, только если пользователь её включил. −1 у неё не край шкалы,
# а «выключено», и сдвиг оттуда включал бы её за спиной.
_ВЫКЛЮЧЕНА = -0.999


def _точка(v, лево=0.0, право=1.0):
    try:
        x = float(v)
    except (TypeError, ValueError):
        return None
    if x != x:                       # NaN
        return None
    return max(лево, min(право, x))


def кривая_канала(raw) -> list[tuple[float, float]]:
    """Сырые контрольные точки → отсортированный список (x, y).

    x — место в серии 0..1, y — сдвиг −1..+1. Кривая пустая или из одной точки
    — это не ошибка, а «ничего не гну»: рисование начинается с нуля точек, и
    падать на полпути было бы наказанием за начатое движение."""
    out = []
    for п in raw or ():
        if isinstance(п, dict):
            x, y = _точка(п.get("x")), _точка(п.get("y"), -1.0, 1.0)
        elif isinstance(п, (list, tuple)) and len(п) >= 2:
            x, y = _точка(п[0]), _точка(п[1], -1.0, 1.0)
        else:
            continue
        if x is None or y is None:
            continue
        out.append((x, y))
    out.sort(key=lambda т: т[0])
    return out


def кривая(raw) -> dict:
    """Все каналы разом. Чужие ключи выбрасываются молча: имя канала — это имя
    крутилки, а их канон живёт в clean, и второго списка тут нет."""
    if not isinstance(raw, dict):
        return {}
    ok = (МАСТЕР,) + КАНАЛЫ
    out = {}
    for имя in ok:
        точки = кривая_канала(raw.get(имя))
        if точки:
            out[имя] = [[x, y] for x, y in точки]
    return out


def _наклоны(точки) -> list[float]:
    """Наклоны в узлах по Фричу–Карлсону — монотонный кубический сплайн.

    Требование: кривая изгибается плавно, а не ступенькой.. Первая
    версия была ломаной, и он прав: излом в узле — это не кривая.

    Но обычный сплайн (Катмулл–Ром) между двумя близкими точками ВЫСКАКИВАЕТ
    за них: поставил 0.2 и 0.3, а посередине кривая уходит на 0.45 — и прогон
    делает то, чего на экране не нарисовано. Фрич–Карлсон гасит наклон там, где
    соседние отрезки идут в разные стороны, поэтому между двумя точками
    значение НИКОГДА не выходит за них. Гладко и без вранья."""
    n = len(точки)
    Δ = []
    for i in range(n - 1):
        dx = точки[i + 1][0] - точки[i][0]
        Δ.append((точки[i + 1][1] - точки[i][1]) / dx if dx > 0 else 0.0)
    m = [Δ[0]] + [(Δ[i - 1] + Δ[i]) / 2.0 for i in range(1, n - 1)] + [Δ[-1]]
    for i in range(n - 1):
        if Δ[i] == 0.0:                 # плоский участок — плоский и в узлах
            m[i] = m[i + 1] = 0.0
            continue
        a, b = m[i] / Δ[i], m[i + 1] / Δ[i]
        # круг Фрича–Карлсона: за ним начинается выброс
        s = a * a + b * b
        if s > 9.0:
            t = 3.0 / (s ** 0.5)
            m[i] = t * a * Δ[i]
            m[i + 1] = t * b * Δ[i]
    return m


def значение(точки, x: float) -> float:
    """Кривая в точке x. Гладкая между точками, за краями — крайняя точка.

    Продление краёв ровной линией — не лень, а то же правило «не делать того,
    чего не видно»: слева от первой точки пользователь ничего не рисовал."""
    if not точки:
        return 0.0
    if len(точки) == 1:
        return float(точки[0][1])
    if x <= точки[0][0]:
        return float(точки[0][1])
    if x >= точки[-1][0]:
        return float(точки[-1][1])
    m = _наклоны(точки)
    for i in range(1, len(точки)):
        x1, y1 = точки[i - 1]
        x2, y2 = точки[i]
        if x <= x2:
            h = x2 - x1
            if h <= 0:
                return float(y2)
            t = (x - x1) / h
            # эрмитов кубический кусок
            t2, t3 = t * t, t * t * t
            return float((2 * t3 - 3 * t2 + 1) * y1 + (t3 - 2 * t2 + t) * h * m[i - 1]
                         + (-2 * t3 + 3 * t2) * y2 + (t3 - t2) * h * m[i])
    return float(точки[-1][1])


def место(трек: int, треков: int, звено: int, звеньев: int) -> float:
    """Позиция крутилки звена на общей оси серии, 0..1.

    Трек занимает ровно одну клетку, звенья садятся ВНУТРИ неё по центрам
    своих долей — поэтому цепочка из двух звеньев и из восьми одинаково
    покрывают клетку, и смена цепочки у соседа ничего не двигает."""
    треков = max(1, int(треков))
    звеньев = max(1, int(звеньев))
    доля = (звено + 0.5) / звеньев
    return (max(0, трек) + доля) / треков


