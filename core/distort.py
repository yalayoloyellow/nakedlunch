# ТИПЫ ШУМА
#
# Требование: типы шумов разные, все известные, и разница между ними слышна.. Разница действительно должна быть слышна, иначе список типов — это
# украшение, а не выбор.
#
# Ось у нас одна — место в серии, и различает типы ровно одно: НАСКОЛЬКО
# ПОХОЖИ СОСЕДНИЕ ТОЧКИ. Отсюда и имена, взятые из спектральной классификации,
# и их поведение:
#
#   белый    соседи независимы — привычная ровная дрожь
#   синий    соседи НАРОЧНО разные: дребезг, противоположность розовому
#   розовый  1/f: соседи похожи, но есть медленный дрейф
#   перлин   плавные волны со случайной фазой — органика, а не дрожь
#
# ИХ ЧЕТЫРЕ, А НЕ ПЯТЬ. Пятым просился броуновский (случайное блуждание), и я
# его написала — но замерила и убрала. На нашем масштабе (серия это 6-160
# точек, обычно около тридцати) он неотличим от розового: связь соседей
# 0.79 против 0.82 на тридцати точках и 0.94 против 0.97 на ста двадцати,
# дрейф в пределах той же погрешности. Пробовала и другую нормировку — не
# помогло: разница между 1/f и 1/f² живёт на длинах, которых у нас нет.
#
# Требование: все известные типы., и соблазн поставить пятое имя был.
# Но имя, за которым стоит то же поведение, — это украшение, а не выбор, и
# ровно про это написано двумя абзацами выше.
#
# Нормируем ряд к ±1, чтобы «сила» у всех типов значила одно и то же.
ШУМЫ = ("белый", "синий", "розовый", "перлин")


def _ряд(r, тип: str, n: int) -> list[float]:
    """n значений шума в −1..+1. Ряд, а не независимые числа: у всех типов,
    кроме белого, смысл именно в связи между соседями."""
    n = max(1, int(n))
    сырьё = [r.random() * 2.0 - 1.0 for _ in range(n)]
    if тип == "белый":
        out = сырьё
    elif тип == "розовый":
        # 1/f — сумма октав, где КРУПНАЯ весит больше мелкой. Порядок тут
        # решает всё: сначала я шёл от мелкой октавы с весом 1, и «розовый»
        # получался почти белым (замерено связью соседей: 0.19 вместо
        # ожидаемых 0.3-0.5). Идём от крупной вниз, каждая следующая вдвое
        # тише — тогда получается дрейф с рябью, а не рябь с дрейфом.
        out = [0.0] * n
        шаг, вес = max(2, n // 2), 1.0
        while шаг >= 1:
            опоры = [r.random() * 2.0 - 1.0 for _ in range(n // шаг + 2)]
            for i in range(n):
                k = i / шаг
                a, b = опоры[int(k)], опоры[int(k) + 1]
                t = k - int(k)
                out[i] += вес * (a + (b - a) * t)
            шаг //= 2
            вес *= 0.5
    elif тип == "синий":
        # разность соседей: медленное уходит, быстрое остаётся
        out = [сырьё[i] - сырьё[i - 1] if i else сырьё[0] for i in range(n)]
    else:                                    # перлин — гладкие волны
        шаг = max(2, n // 3)
        опоры = [r.random() * 2.0 - 1.0 for _ in range(n // шаг + 2)]
        out = []
        for i in range(n):
            k = i / шаг
            a, b = опоры[int(k)], опоры[int(k) + 1]
            t = k - int(k)
            t = t * t * (3 - 2 * t)          # сглаживание, как у Перлина
            out.append(a + (b - a) * t)
    пик = max(abs(v) for v in out) or 1.0
    return [v / пик for v in out]


def ряды(r, тип: str, n: int) -> dict:
    """По ряду на каждый канал: мнения должны дрожать НЕ В УНИСОН, иначе шум
    сводится к той же одной оси, что и кривая, и различать их незачем."""
    т = тип if тип in ШУМЫ else ШУМЫ[0]
    return {имя: _ряд(r, т, n) for имя in КАНАЛЫ}


def сдвиги(x: float, крив: dict, шум: float, rnd=None, ряд: dict | None = None,
           i: int = 0) -> dict:
    """{крутилка: сдвиг} в точке x. Кривая и шум СКЛАДЫВАЮТСЯ.

    `ряд` — заранее посчитанные ряды шума (см. `ряды`), `i` — номер точки в
    них. Без ряда шум берётся независимыми числами, то есть белым: у одной
    точки соседей нет, и связывать не с чем."""
    крив = крив or {}
    мастер = значение(крив.get(МАСТЕР) or [], x)
    r = rnd or random
    out = {}
    for имя in КАНАЛЫ:
        d = мастер + значение(крив.get(имя) or [], x)
        if шум > 0:
            дрожь = ряд[имя][i % len(ряд[имя])] if ряд and ряд.get(имя) else (r.random() * 2.0 - 1.0)
            d += шум * дрожь
        out[имя] = d
    return out


def применить(params: dict, x: float, крив: dict, шум: float = 0.0, rnd=None,
              ряд: dict | None = None, i: int = 0) -> dict:
    """Крутилки звена + искажение в точке x → новые крутилки.

    Ворота не трогаются вовсе; «Повтор» не трогается тоже; выключенная
    «Связность» остаётся выключенной. Всё остальное клампится в 0..1 —
    значит искажение не может ни выключить связность, ни вывести крутилку за
    шкалу."""
    p = dict(params or {})
    if not крив and шум <= 0:
        return p
    d = сдвиги(x, крив, шум, rnd, ряд, i)
    for имя in КАНАЛЫ:
        if имя not in p:
            continue
        try:
            v = float(p[имя])
        except (TypeError, ValueError):
            continue
        if имя == "Связность" and v <= _ВЫКЛЮЧЕНА:
            continue                       # выключено — искажать нечего
        p[имя] = round(max(0.0, min(1.0, v + d[имя])), 3)
    return p
