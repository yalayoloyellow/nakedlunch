# nakedlunch — чёрный список слов и словосочетаний (Раунд 57).
#
# Требование: слово или словосочетание можно внести в чёрный список — такие фрагменты не
# показываются вовсе, а напротив правила в реальном времени видно, сколько строк оно
# убирает..
#
# СТАРЫЙ ЧЁРНЫЙ СПИСОК БЫЛ ВЫРЕЗАН, и не по глупости: он перебирал каждый из
# 1.7 млн фрагментов на КАЖДЫЙ запрос и стоил 1.2 с при нуле записей. Этот
# работает от обратного указателя индекса, поэтому дорог ровно настолько,
# сколько строк реально попало под правило.
#
# СЕМАНТИКА — ПО НАЧАЛЬНОЙ ФОРМЕ, ЦЕЛЫМИ СЛОВАМИ. Два требования правило «я» не должно задевать «явиться». По буквам «я»
#     зацепило бы «явиться», «ясный», «яблоко». Мы так не ищем.
#   · «госпожа и госпожи и госпожой — топ». Это ОДНО слово в падежах, и
#     начальная форма у них одна.
# Разбор даёт ровно это: «я» (местоимение) и «явиться» (глагол) — разные слова;
# «госпожа/госпожи/госпожой» — одно.
#
# Словосочетание — последовательность начальных форм ПОДРЯД и в том порядке,
# как написано.
#
# ХРАНЕНИЕ — свой файл рядом с корпусом, запись целиком или никак (tmp +
# подмена). Отдельный файл, а не общий с историей: цена ошибки при записи в
# corpus.json — избранное и история пользователя, и рисковать ими ради удобства
# незачем.

from __future__ import annotations

import json
import os
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent / "data"
СПИСОК = DATA_DIR / "blacklist.json"


def _канон(правило: str) -> str:
    """Правило как ключ: пробелы схлопнуты, регистр снят. Само правило хранится
    как написано — пользователь должен видеть свою запись, а не её обработку."""
    return " ".join(str(правило or "").split()).lower()


def читать() -> list[str]:
    """Правила в порядке добавления. Никогда не падает: сломанный файл — это
    потеря списка, а не отказ приложения открыться."""
    try:
        d = json.loads(СПИСОК.read_text("utf-8"))
    except (OSError, ValueError):
        return []
    if isinstance(d, list):
        return [str(x) for x in d if str(x).strip()]
    if isinstance(d, dict) and isinstance(d.get("rules"), list):
        return [str(x) for x in d["rules"] if str(x).strip()]
    return []


def _писать(правила: list[str]) -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    врем = СПИСОК.with_suffix(".json.новый")
    врем.write_text(json.dumps({"rules": правила}, ensure_ascii=False, indent=1), "utf-8")
    os.replace(врем, СПИСОК)


def добавить(правило: str) -> list[str]:
    """Добавить правило. Повтор — молча тот же список: пользователь нажал дважды,
    это не ошибка."""
    п = " ".join(str(правило or "").split())
    if not п:
        return читать()
    правила = читать()
    if _канон(п) in {_канон(x) for x in правила}:
        return правила
    правила.append(п)
    _писать(правила)
    return правила


def убрать(правило: str) -> list[str]:
    ключ = _канон(правило)
    правила = [x for x in читать() if _канон(x) != ключ]
    _писать(правила)
    return правила
