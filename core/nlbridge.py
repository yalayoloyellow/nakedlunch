ОПИСЬ = None            # заполняется при первом обращении, см. `опись_книг`


def _файл_описи():
    """Где лежит опись. В корне ЗАПИСИ, а не в складе: это НАШ производный
    файл, а склад — чужие данные (его пишет и читает ещё и CLI)."""
    return пути.ДАННЫЕ / "книги.json"


def опись_книг() -> list | None:
    """Список книг БЕЗ загрузки склада: id, имя, тип, число фрагментов.

    ЗАЧЕМ (замер 2026-09-03). Панель корпуса спрашивала `list_corpora()`, а тот
    требует разобранного `state.json` — 363 МБ и 5.3 секунды. Интерфейс зовёт
    эту панель при открытии окна, то есть склад грузился всегда и сразу; его
    `json.loads` — один непрерывный вызов, он держит GIL, и первая генерация
    ждала шесть секунд, хотя сама считается за 0.34.

    Опись — тот же приём, что `active.json`: маленький файл рядом, который
    пишется при каждом изменении состава книг. Флаги активности сюда НЕ
    кладутся: они меняются чаще всего и живут в своём файле; здесь только то,
    что меняется при заливке и удалении.

    None — файла нет или он битый: зовущий честно уходит к складу.
    """
    global ОПИСЬ
    if ОПИСЬ is not None:
        return ОПИСЬ or None
    try:
        д = json.loads(_файл_описи().read_text(encoding="utf-8"))
        книги = д["книги"]
        assert isinstance(книги, list) and книги
    except Exception:
        ОПИСЬ = []
        return None
    акт = активные_книги()
    for к in книги:
        к["active"] = bool(акт and к.get("id") in акт)
    ОПИСЬ = книги
    return книги


def записать_опись(store) -> None:
    """Переписать опись по загруженному складу. Зовётся, когда состав книг
    изменился, и один раз после фоновой загрузки склада.

    Молчит при любой ошибке: опись — ускорение, а не работа. Не записалась —
    следующий запуск просто подождёт склад, как раньше."""
    global ОПИСЬ
    try:
        книги = [{"id": к.get("id"), "name": к.get("name"),
                  "type": к.get("type"), "added_at": к.get("added_at"),
                  "fragment_count": к.get("fragment_count")}
                 for к in store.list_corpora()]
        всего = len(store.get_active_pool())
        ф = _файл_описи()
        ф.parent.mkdir(parents=True, exist_ok=True)
        врем = ф.with_suffix(".tmp")
        врем.write_text(json.dumps({"книги": книги, "пул": всего},
                                   ensure_ascii=False), encoding="utf-8")
        врем.replace(ф)                 # целиком или никак
        ОПИСЬ = None                    # перечитается с флагами активности
    except Exception:
        pass


def забыть_опись() -> None:
    """Сбросить память об описи — после переключения книги."""
    global ОПИСЬ
    ОПИСЬ = None


def пул_из_описи() -> int | None:
    """Сколько фрагментов в АКТИВНЫХ книгах, по описи. None — описи нет."""
    книги = опись_книг()
    if книги is None:
        return None
    return sum(int(к.get("fragment_count") or 0) for к in книги if к.get("active"))


def активные_книги() -> set | None:
    """Какие книги включены — БЕЗ загрузки склада (2026-09-03).

    ЗАЧЕМ. Отбору от склада нужно ровно одно: список включённых книг. Прежде
    ради него грузился весь `state.json` — 363 МБ и 5.3 секунды, — потому что
    активный пул отдавался СПИСКОМ ТЕКСТОВ. С переходом на колонку `src`
    (см. `nlindex.маска_книг`) тексты не нужны, а флаги активности лежат
    отдельным файлом на 1.4 КБ: склад пишет `active.json` при каждом
    переключении книги именно потому, что он мал и меняется часто.

    None — файла нет (свежая установка, книг ещё не заливали) или он битый:
    тогда зовущий честно уходит на прежний путь через склад. Молча считать,
    что «включено ничего», нельзя — это дало бы пустую выдачу без объяснения.
    """
    ф = NAKEDLUNCH_DATA / "active.json"
    try:
        флаги = json.loads(ф.read_text(encoding="utf-8"))
    except Exception:
        return None
    if not isinstance(флаги, dict) or not флаги:
        return None
    return {к for к, в in флаги.items() if в}


_TOKEN_RE = re.compile(r"[a-zа-яё0-9]+")


def _tokens(s: str) -> set[str]:
    return set(_TOKEN_RE.findall(s.lower()))


