# nakedlunch — СДВИГ ГРАНИЦЫ СТРОКИ: отрезать слово, не сломав ничего.
#
# ЗАМЫСЕЛ ВЛАДЕЛЬЦА (2026-09-01): «есть смысл нарезать и обозначать всё
# настолько оптимально, чтоб мы не потеряли, что уже есть, но чтоб это работало
# ещё лучше, и чтоб удлинение и укорачивание работало».
#
# ПОЧЕМУ СНАЧАЛА ТОЛЬКО УКОРАЧИВАНИЕ. Удлинить строку не из чего: в складе
# лежат нарезанные куски, а самих книг нет — замер 2026-09-01 показал в
# ~/Documents/nakedlunch ровно 2 307 826 фрагментов и ни одной книги. Значит
# расширение ждёт перезаливки книг с адресами (книга + границы), а сужение
# работает уже сегодня: строк длиннее двух слов 97.1%.
#
# ТЯНУТЬ ЗА ГОЛОВУ, А НЕ ЗА ХВОСТ — и это не вкус, а замер на 40 000 строк:
# отрезать ПЕРВОЕ слово меняет рифмо-ключ у 0.98% строк, ПОСЛЕДНЕЕ — у 73.1%.
# Ключ берётся с последнего знаменательного слова (build_nl_rhyme._ключ_и_span),
# поэтому голова почти всегда свободна, а хвост — почти никогда. Клаузула и
# ярус рифмы считаются из того же ключа и уезжают вместе с ним.
#
# ЧТО ПРОВЕРЯЕТСЯ ПОСЛЕ РЕЗА И ПОЧЕМУ ИМЕННО ЭТО. Ворота проекта делятся на два
# класса, и обходить нельзя только один:
#
#   · СОДЕРЖАТЕЛЬНЫЕ — «я не хочу этого видеть»: мат, внутренняя рифма,
#     перекличка, полосы редкости и плотности, тавтология, два знаменательных
#     слова, целостность краёв. Их рез нарушать не имеет права: строка,
#     отобранная при «без мата», не смеет стать матерной от нажатия ручки.
#   · ФОРМА — слоги. Их человек меняет НАРОЧНО, когда жмёт «короче»: в этом
#     весь смысл ручки. Запрещать было бы контрол-обманкой наоборот.
#
# ПОЛОСНЫЕ ОСИ — ОТДЕЛЬНЫЙ СЛУЧАЙ, И ЗДЕСЬ РУЧКА ЧЕСТНО ГАСНЕТ. Процентиль
# плотности назначен ЖРЕБИЕМ внутри групп равных (замер: на 2 130 766 строк со
# шкалой всего 155 разных сырых значений, а треть корпуса — один и тот же
# ноль). Пересчитать процентиль сдвинутой строки нельзя в принципе: он не
# свойство строки, а её место среди других. Врать числом хуже, чем не дать
# нажать, — поэтому при включённой полосе плотности или полосе редкости
# сочетаний ручка не работает вовсе. Ось «редкость слов» этим не больна
# (шкала почти непрерывна, крупнейшая связка 0.014%), но её пересчёт требует
# долей лемм по корпусу и книге — таблиц, которых в индексе пока нет.
from __future__ import annotations

import re

_СЛОВО = re.compile(r"\S+")
# Обрывок начала — та же тройка, что у ворот индекса (`nlindex._ОБРЫВОК_НАЧАЛО`):
# «нибудь», «либо», «таки» в начале строки значат, что резак разорвал слово.
_ОБРЫВОК = re.compile(r"^\s*(нибудь|либо|таки)\b", re.I)

СЛОВ_МИНИМУМ = 2          # «строка» из одного слова — не строка
ЗНАМЕНАТЕЛЬНЫХ_МИНИМУМ = 2   # тот же порог, что у ворот корпуса


_МОРФ = None


def _печкин_модуль():
    """`tools/build_nl_rhyme` — там живёт правило внутренней рифмы."""
    import importlib.util
    import sys
    from pathlib import Path
    if "build_nl_rhyme" in sys.modules:
        return sys.modules["build_nl_rhyme"]
    путь = Path(__file__).resolve().parent.parent / "tools" / "build_nl_rhyme.py"
    if not путь.exists():
        return None
    спец = importlib.util.spec_from_file_location("build_nl_rhyme", путь)
    мод = importlib.util.module_from_spec(спец)
    sys.modules["build_nl_rhyme"] = мод
    try:
        спец.loader.exec_module(мод)
    except Exception:
        sys.modules.pop("build_nl_rhyme", None)
        return None
    return мод


def _морфология():
    """(morph, acc) — поднимаются один раз на процесс и держатся."""
    global _МОРФ
    if _МОРФ is None:
        мод = _печкин_модуль()
        import pymorphy3
        _МОРФ = (pymorphy3.MorphAnalyzer(), мод.акцентуатор())
    return _МОРФ


class Отказ(Exception):
    """Рез невозможен. Причина — человеку, а не в лог: ручка объясняет, почему
    она погасла, иначе это молчащая кнопка."""


def короче(текст: str) -> str:
    """Строка без первого слова. Только текст, без проверок — их делает `рез`."""
    слова = _СЛОВО.findall(текст)
    if len(слова) < 2:
        raise Отказ("в строке одно слово — резать нечего")
    м = _СЛОВО.search(текст)
    хвост = текст[м.end():].lstrip()
    return хвост


def причина_отказа(было: str, стало: str, ворота: dict) -> str | None:
    """Почему рез нельзя сделать. None — можно.

    `ворота` — те же ключи, что у ядра (`clean.knobs`): no_mat, only_mat,
    inner_rhyme, echo, rare_word, rare_pair, dens. Проверяются ровно те, что
    ВКЛЮЧЕНЫ: выключенные ворота ничего не обещали и мешать не могут.
    """
    if len(_СЛОВО.findall(стало)) < СЛОВ_МИНИМУМ:
        return "осталось бы одно слово"
    if _ОБРЫВОК.match(стало):
        return "строка начиналась бы с обрывка слова"

    # ПОЛОСНЫЕ ОСИ: гасим, не считая. Разбор — в шапке модуля.
    if str(ворота.get("dens") or "").strip():
        return "при выбранной полосе плотности звука сдвиг не считается честно"
    if str(ворота.get("rare_pair") or "").strip():
        return "при выбранной полосе редкости сочетаний сдвиг не считается честно"
    if str(ворота.get("rare_word") or "").strip():
        return "при выбранной полосе редкости слов сдвиг пока не считается"

    import filters
    if ворота.get("no_mat") and filters.has_mat(стало):
        return "после реза строка стала бы матерной, а стоит «без мата»"
    if ворота.get("only_mat") and not filters.has_mat(стало):
        return "после реза в строке не осталось бы мата, а стоит «только мат»"

    import corpus as _corpus
    if _corpus.содержательных(стало) < ЗНАМЕНАТЕЛЬНЫХ_МИНИМУМ:
        return "осталось бы меньше двух знаменательных слов"

    if ворота.get("inner_rhyme") or ворота.get("echo"):
        причина = _звуковые_ворота(стало, ворота)
        if причина:
            return причина
    return None


def _звуковые_ворота(стало: str, ворота: dict) -> str | None:
    """Внутренняя рифма и перекличка — оба свойства текста, оба считаемы.

    Рез УБИРАЕТ слова, поэтому и пара внутренней рифмы, и перекличка могут
    только исчезнуть, но не появиться. Значит проверять надо лишь то, что
    включено, и лишь на пропажу.
    """
    if ворота.get("inner_rhyme"):
        # ПРАВИЛО ОДНО НА ВСЕХ: зовём тот же `_внутренняя_рифма`, которым флаг
        # считался при печке. Акцентуатор тяжёлый (словарь на 3.2 млн словоформ,
        # 1.5 ГБ), поэтому поднимается лениво и держится процессом; если его
        # нет — ворота не проверяем и МОЛЧИМ, а не выдумываем ответ.
        рифма = _печкин_модуль()
        if рифма is not None:
            morph, acc = _морфология()
            if not рифма._внутренняя_рифма(morph, acc, стало):
                return "после реза пропала бы внутренняя рифма"
    if ворота.get("echo"):
        import nlindex
        фон = nlindex.звук_фон()
        if фон is None:
            return None            # индекс без таблицы — ворота не проверить
        import звукопись as _звук
        слов = len(set(_звук._СЛОВО.findall(стало.lower())))
        R = _звук.перекличка(стало, фон)
        if _звук.сюрприз(R, слов, фон.get("доля_пар", 0.0)) < _звук.БАЛЛ_МИН:
            return "после реза пропала бы перекличка согласных"
    return None


def рез(текст: str, ворота: dict | None = None) -> dict:
    """«Короче на слово»: что выйдет и можно ли.

    Возвращает {"текст": ..., "слогов": ..., "можно": True} либо
    {"можно": False, "почему": "..."} — ручка гаснет с объяснением, а не молча.
    """
    ворота = ворота or {}
    try:
        стало = короче(текст)
    except Отказ as e:
        return {"можно": False, "почему": str(e)}
    почему = причина_отказа(текст, стало, ворота)
    if почему:
        return {"можно": False, "почему": почему}
    import scan
    слогов = sum(1 for ч in стало.lower() if ч in scan.VOWELS)
    return {"можно": True, "текст": стало, "слогов": слогов}
