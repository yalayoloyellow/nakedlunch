# nakedlunch — ЗВУКОПИСЬ: две шкалы строки, считаются при печати индекса.
#
# ЗАМЫСЕЛ ВЛАДЕЛЬЦА (2026-08-29), дословно: «было бы славно, если бы понимал
# такую концепцию как звукопись, потому что не только гласные, но и согласные
# могут иметь художественный эффект. То есть если там нету рифмы, но они все
# имеют сочетание звуковое ТРСК и прочие разные, любые — согласные, если везде
# там есть такое, перекликается — это тоже работает и делает фонетически
# осмысленным».
#
# ДВЕ ОСИ, И ЭТО НЕ ДУБЛИРОВАНИЕ. Замер на 40 000 живых строк: связь между
# ними r = +0.034, пересечение верхних ярусов 0.22% при 0.08% у независимых.
# Разные углы одного явления, и слить их в одну ручку нельзя — как нельзя
# слить две оси редкости.
#
#   · ПЕРЕКЛИЧКА (аллитерация) — два неродственных знаменательных слова делят
#     РЕДКОЕ сочетание согласных: «испытал головокружение и чуть не
#     споткнулся» (спт), «в коридоре продребезжал звонок» (рдр), «Скрывать —
#     значит искривлять» (скр). Это ворота: на боевом корпусе (2 307 826
#     строк) их проходят 0.32% — 7 331 строка. Полосами такое не крутится:
#     шкала была бы из одного нуля и хвоста.
#
#   · ПЛОТНОСТЬ — один согласный залил строку, встречаясь в трёх и более
#     РАЗНЫХ словах. Шкала сплошная — замер на 40 000 живых строк: p50 5.64,
#     p90 7.70, p99 9.75; без шкалы 7.6% (строки короче трёх слов). Поэтому
#     эта ось идёт полосами, как редкость.
#
# ЧТО ОТВЕРГНУТО ЗАМЕРОМ, а не вкусом:
#   · «просто считать повторы согласных биграмм между словами» — это
#     ИЗМЕРИТЕЛЬ ДЛИНЫ: связь с числом слов +0.52, разброс по корзинам длины в
#     262 раза (0.31% у коротких против 82% у длинных). Ровно та ловушка, на
#     которой проект уже горел с банальностью;
#   · z-балл плотности БУКВЫ без требования «в разных словах» — одна редкая
#     буква в короткой строке даёт z≈4-7, и наверх лезет «в вифсфагию к горе
#     елеонстей»;
#   · аллитерация по НАЧАЛАМ слов — разброс по длине в 47 раз.
from __future__ import annotations

import math
import re

import numpy as np

import редкость as _редкость

_СЛОВО = re.compile(r"[а-яё]{3,}")
# «й», «ъ» и «ь» из скелета выброшены: «й» даёт ложное эхо на -ый/-ой, а
# мягкий и твёрдый знаки звука не несут вовсе.
_СОГЛАСНЫЕ = set("бвгджзклмнпрстфхцчшщ")
# КЛАСТЕР — РОВНО ТРИ СОГЛАСНЫХ, и это замер, а не круглое число. Длины 4 и 5
# стояли здесь до 2026-08-30 и выброшены: на 40 000 живых строк они добавляли
# одиннадцать штук, и все одиннадцать — морфемный шум («посредством
# предоставления» — дств, «продолжаться… предложил» — рдлж). Причина в
# устройстве: длинный кусок редок ВСЕГДА, просто потому что длинный, и порогу
# редкости нечем отличить его от настоящей редкости сочетания.
ДЛИНА_КЛАСТЕРА = 3
# ГЛАВНАЯ КОНСТАНТА МОДУЛЯ, и она снята замером на том, что код считает
# СЕГОДНЯ, — на тройках согласных по всему корпусу (2 307 826 строк,
# 11 388 938 слов). Кластер редок, если его несёт не больше этой доли слов;
# 0.0028 — это 31 889 вхождений.
#
# ЧТО ПОКАЗАЛ ЗАМЕР. Суффиксы языка и звук разделяются сырой частотой:
#     морфемы: «ств» 281 751 · «стр» 165 330 · «нст» 159 210 · «прв» 124 689
#     звук:    «звд» 9 867 · «крб» 6 381 · «грх» 3 933 · «дрб» 2 909
# Развёртка порога на 400 000 строк (ворота · разброс по корзинам длины):
#     0.0014 — 0.15% · 36x     0.0028 — 0.31% · 14x     0.0056 — 0.30% · 11x
# Ширина ворот от порога почти не зависит, и это не случайность: чем больше
# троек считается редкими, тем выше ожидание — и сюрприз каждой пары падает,
# мера сама себя нормирует. Состав срабатываний тоже одинаков при любом
# пороге: больше половины дают тройки из верхней половины полосы. Значит выбор
# решается не шириной ворот, а СМЫСЛОМ оси: «редкое сочетание» — это 0.28%
# слов, а не 0.56%. Порог держит снаружи ровно те тройки, что оказались
# суффиксами: «ств», «стр», «нст».
ЧАСТОТА_МАКС = 0.0028
БАЛЛ_МИН = 2.0           # сюрприз: −log10 вероятности случайного совпадения
НЕТ_ШКАЛЫ = np.float32(-1.0)     # то же значение и смысл, что у редкости
РОДНЯ_ПРЕФИКС = 4        # общий буквенный зачин — однокоренные, не звукопись
МОРФЕМА = 4              # общая буквенная подстрока такой длины — морфема, не звук


def скелет(слово: str) -> str:
    """Согласный костяк слова: «пространство» → «прстрнств»."""
    return "".join(ч for ч in слово if ч in _СОГЛАСНЫЕ)


def кластеры(ске: str) -> set:
    """Тройки согласных подряд: «пространство» → прс, рст, стр, трн, рнс, нств.

    ПОЧЕМУ РЕДКОСТЬ МЕРЯЕТСЯ СЫРОЙ ЧАСТОТОЙ, А НЕ ЕЁ ЛОГАРИФМОМ. На одной
    длине это одно и то же, а на смешанных длинах логарифм ломался: «дств»
    реже любой тройки, хотя это суффикс. Сырая частота честна и проста — у
    морфемы она тысячная, у звука сотенная.
    """
    return {ске[i:i + ДЛИНА_КЛАСТЕРА]
            for i in range(len(ске) - ДЛИНА_КЛАСТЕРА + 1)}


def _общий_кусок(a: str, b: str, длина: int) -> bool:
    """Есть ли у двух слов общая буквенная подстрока такой длины."""
    if len(a) < длина or len(b) < длина:
        return False
    куски = {a[i:i + длина] for i in range(len(a) - длина + 1)}
    return any(b[i:i + длина] in куски for i in range(len(b) - длина + 1))


def _родня(a: str, b: str, кластер: str, ске_a: str, ске_b: str) -> bool:
    """Однокоренные или почти: «отвергнуть/низвергнуть» — не звукопись.

    ГЛАВНОЕ ПРАВИЛО — ОБЩАЯ БУКВЕННАЯ ПОДСТРОКА В ЧЕТЫРЕ ЗНАКА. Это морфема:
    корень, приставка или суффикс, — а повтор морфемы есть грамматика языка, а
    не звук, который слышно. Замер на живой пробе показал, чем платит его
    отсутствие: наверх лезли «окончательно… покончим» (общее «конч»), «в
    принципе воспринимаешь» («прин»), «пятнадцатого, шестнадцатого»
    («надцатого»), «с оскорбительной действительностью» («тельн»). Правило
    ловит их всех разом, чего не делали ни зачин, ни хвост по отдельности:
    морфема сидит в середине слова так же охотно, как по краям.

    Второе правило: кластер, закрывающий больше половины скелета У ОБОИХ слов —
    тогда слова просто похожи целиком, а не перекликаются куском.
    """
    if a[:РОДНЯ_ПРЕФИКС] == b[:РОДНЯ_ПРЕФИКС]:
        return True
    if _общий_кусок(a, b, МОРФЕМА):
        return True
    д = len(кластер)
    return д >= 0.6 * len(ске_a) and д >= 0.6 * len(ске_b)


def частоты_кластеров(тексты) -> dict:
    """Сколько ВХОЖДЕНИЙ слов корпуса несут каждую тройку — первый проход.

    По вхождениям, а не по разным словам, и порог `ЧАСТОТА_МАКС` делится на то
    же число: обе стороны в одних единицах. «Сколько разных слов» потребовало
    бы держать в памяти словарь корпуса ради того же самого отношения.

    Считается ОДИН РАЗ по всему корпусу, а не по книге: редкость сочетания
    звуков — свойство языка, и мерить её внутри одной книги значило бы
    объявлять редким то, что редко лишь у этого автора (то же правило, что у
    двусторонней редкости слов)."""
    счёт: dict = {}
    слов = 0
    for т in тексты:
        for w in _СЛОВО.findall(т.lower()):
            слов += 1
            for к in кластеры(скелет(w)):
                счёт[к] = счёт.get(к, 0) + 1
    return {"счёт": счёт, "слов": max(1, слов)}


def _редкий(к: str, фон: dict) -> bool:
    """Кластер редок, если его несут не больше ЧАСТОТА_МАКС доли слов корпуса."""
    return фон["счёт"].get(к, 0) <= ЧАСТОТА_МАКС * фон["слов"]


def редкие(слово: str, фон: dict):
    """(скелет, редкие кластеры слова).

    Редкие кластеры почти у всех слов пусты — и на этом держится скорость:
    пара отбрасывается, не доходя до пересечения множеств. Замер на 30 000
    строк — 0.6 с, то есть весь корпус в 2.3 млн строк проходится за минуту, и
    кэш по словам тут не нужен (с ним 0.5 с — разница не стоит лишней ручки).
    """
    ске = скелет(слово)
    return (ске, tuple(к for к in кластеры(ске) if _редкий(к, фон)))


def перекличка(текст: str, фон: dict) -> int:
    """Сколько пар слов строки перекликаются редким сочетанием согласных.

    ДВА ФИЛЬТРА, И КАЖДЫЙ СНЯТ С ШУМА:
      · не родня — без этого 43.3% верхнего яруса были однокоренными;
      · кластер не окончание у обоих — иначе звукопись подменяется
        грамматической рифмой («говорливых/деловых»), и доля строк с флагом
        внутренней рифмы в ярусе подскакивает вчетверо против фона.

    Пара засчитывается один раз, каким бы числом кластеров слова ни сошлись:
    ось отвечает на вопрос «перекликаются ли эти два слова», а не «сколькими
    способами сразу».

    ЛЕММ ЗДЕСЬ НЕТ, И ЭТО ЗАМЕР, А НЕ ЛЕНЬ. Отдельный фильтр «разные леммы»
    стоял против повтора слова («науке/науки») — но правило морфемы ловит его
    же и раньше: у таких пар общий буквенный кусок в четыре знака есть всегда.
    Прогон на 30 000 живых строк с настоящими леммами (pymorphy3, слово в
    слово, а не по номерам) и без них дал НОЛЬ расхождений. Значит поле было лишним —
    а лишнее поле в печке это ещё и стык, на котором номера лемм разъезжаются
    с номерами слов.
    """
    слова = list(dict.fromkeys(_СЛОВО.findall(текст.lower())))
    if len(слова) < 2:
        return 0
    свод = {w: редкие(w, фон) for w in слова}
    пар = 0
    for i, a in enumerate(слова):
        ске_a, ред_a = свод[a]
        if not ред_a:
            continue
        for b in слова[i + 1:]:
            ске_b, ред_b = свод[b]
            if not ред_b:
                continue
            for к in ред_a:
                if к not in ред_b:
                    continue
                if _родня(a, b, к, ске_a, ске_b):
                    continue
                if ске_a.endswith(к) and ске_b.endswith(к):
                    continue            # общее окончание — грамматика, не звук
                пар += 1
                break
    return пар


def сюрприз(R: int, слов: int, доля: float) -> float:
    """−log10 вероятности, что столько перекличек дал случай.

    ПОЧЕМУ НЕ ЧИСЛО ПАР И НЕ z-БАЛЛ. Голый счёт пар — измеритель ДЛИНЫ: пар в
    строке квадрат от числа слов, и наверх лезут длинные книжные периоды
    (разброс ворот по корзинам длины 70 раз). А z-балл (R−E)/√E — измеритель
    КОРОТКОСТИ: при ожидании в сотые доли пары одно совпадение в строке из
    четырёх слов даёт z≈30, и верхушку занимают обрывки. Сюрприз честен к
    обеим сторонам — разброс по длине падает до 7 раз: одно совпадение стоит
    ровно столько, сколько стоит его редкость, а чтобы подняться длинной
    строке, ей нужно СТОЛЬКО совпадений, сколько случай ей уже отсыпал.
    """
    пар = слов * (слов - 1) / 2
    if пар <= 0 or R <= 0:
        return 0.0
    E = доля * пар
    if E <= 0:
        return 0.0
    # P(X ≥ R) при пуассоне с ожиданием E — считаем через дополнение,
    # слагаемых мало: R редко больше трёх.
    хвост = 1.0
    член = math.exp(-E)
    for k in range(int(R)):
        хвост -= член
        член *= E / (k + 1)
    return round(-math.log10(max(хвост, 1e-12)), 3)


# НАДГРОБИЕ 2026-08-30: `балл(текст, фон)` — сюрприз одной строки одним
# вызовом. Заводился как удобный вход для живого счёта, и читателей у него не
# нашлось ни одного: печка зовёт `перекличка` и `сюрприз` порознь (иначе
# перекличка считалась бы дважды), а прогон запроса берёт готовую колонку.
# Вместе с ним ушла константа `ДОЛЯ_ПАР` — запасное ожидание «на случай счёта
# без индекса»: считать без индекса некому.


def плотность(текст: str) -> float:
    """z-балл самого «залившего» строку согласного, считая по РАЗНЫМ словам.

    Требование «в трёх и более разных словах» — то, что отличает плотность от
    случайной редкой буквы: без него «принцип его организации» лезет наверх на
    одной «ц». С ним разброс по длине строки падает с семикратного до
    четырёхкратного, то есть ось меряет звук, а не размер.
    """
    # РАЗНЫЕ СЛОВА — ЗНАЧИТ РАЗНЫЕ, И ЭТО НЕ ПРИДИРКА. Здесь стоял голый
    # `findall`, и «он шёл и шёл и шёл домой» получал плотность 6.4: одно слово
    # посчитано трижды. Ось обещает «согласный залил строку, встречаясь в трёх
    # РАЗНЫХ словах», а мерила повтор слова — то самое, что проект казнит
    # отдельно как тавтологию. Замер на 20 000 живых строк: правило меняет
    # шкалу у 2.63% строк.
    слова = list(dict.fromkeys(_СЛОВО.findall(текст.lower())))
    if len(слова) < 3:
        return float(НЕТ_ШКАЛЫ)     # в двух словах согласному нечего заливать
    в_словах: dict = {}
    for w in слова:
        for ч in set(скелет(w)):
            в_словах[ч] = в_словах.get(ч, 0) + 1
    if not в_словах:
        return float(НЕТ_ШКАЛЫ)
    n = len(слова)
    лучший = 0.0
    for ч, сколько in в_словах.items():
        if сколько < 3:
            continue
        p = 1.0 / len(_СОГЛАСНЫЕ)       # фон: равновероятный согласный
        ожид = n * p
        if ожид <= 0:
            continue
        z = (сколько - ожид) / math.sqrt(ожид * (1 - p))
        лучший = max(лучший, z)
    return round(лучший, 3)


def шкалы(тексты, фон: dict):
    """(перекличка uint8, плотность-процентиль float32) — по строке на запись.

    ОДИН ПРОХОД, И ЭТО ВАЖНО. Сюрприз нельзя посчитать раньше, чем известно
    ожидание — доля перекликающихся пар во всём корпусе, — а её саму даёт
    только полный обход. Поэтому обход один: сперва копим сырые счётчики, а
    ожидание и сюрприз выводим из них уже в памяти.

    Ожидание кладётся в `фон["доля_пар"]` и его ЧИТАЕТ ПЕЧКА — печатает в
    отчёте о выпечке. На боевом корпусе оно 0.000342, то есть перекликается
    одна пара слов из трёх тысяч; число стоит знать, потому что от него
    целиком зависит, где стоят ворота.

    ПЕРЕКЛИЧКА — ДЕСЯТЫМИ ДОЛЯМИ сюрприза (2.6 → 26): ворота стоят на 2.0, и
    целые баллы огрубили бы их до неразличимости соседних ярусов.

    ПЛОТНОСТЬ — ПРОЦЕНТИЛЕМ, как обе оси редкости, и ровно затем же: полосами
    крутится только ровная шкала, где полоса [a%, b%] даёт b−a процентов
    корпуса. 0 — самые пустые по звуку, 100 — самые залитые; −1 — шкалы нет
    (строка короче трёх слов, там мерить нечего).
    """
    R, слов, сырая = [], [], []
    for т in тексты:
        R.append(перекличка(т, фон))
        слов.append(len(set(_СЛОВО.findall(т.lower()))))
        сырая.append(плотность(т))
    R = np.asarray(R, dtype=np.int32)
    слов = np.asarray(слов, dtype=np.int32)
    пар = (слов.astype(np.float64) * (слов - 1) / 2).sum()
    фон["доля_пар"] = float(R.sum() / пар) if пар else 0.0
    пер = np.asarray(
        [min(255, round(сюрприз(r, с, фон["доля_пар"]) * 10)) for r, с in zip(R, слов)],
        dtype=np.uint8)

    # НОЛЬ — ЭТО ЗНАЧЕНИЕ, А НЕ ПРОПУСК. Строка, где ни один согласный не попал
    # в три разных слова, честно стоит в самом низу шкалы: звука в ней нет.
    # Свалить её в «нет шкалы» значило бы выкинуть треть корпуса из полос и
    # соврать про их ровность. Шкалы нет только там, где мерить нечем, — в
    # строке короче трёх слов.
    сырая = np.asarray(сырая, dtype=np.float64)
    пло = np.full(len(сырая), НЕТ_ШКАЛЫ, dtype=np.float32)
    есть = np.flatnonzero(сырая >= 0)
    if len(есть) > 1:
        # ФОРМУЛА ОДНА НА ВСЕ ПОЛОСНЫЕ ОСИ — та же, что у редкости, только без
        # переворота: у плотности сырое значение уже растёт в нужную сторону.
        # Своя копия здесь была вторым местом, где живёт правило ровности
        # шкалы; разойдись они — и полоса «90-100» значила бы на двух осях
        # разное.
        пло[есть] = _редкость.процентиль(сырая[есть], наоборот=False)
    elif len(есть):
        пло[есть] = 100.0
    return (пер, пло)
