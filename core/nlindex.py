def маска_книг(idx, активные) -> np.ndarray | None:
    """Маска активного пула ИЗ КОЛОНКИ `src`, а не из списка текстов.

    ЗАЧЕМ (замер 2026-09-03). Прежний путь один: склад отдаёт СПИСОК ТЕКСТОВ
    активных книг, а `mask_of` переводит их в номера строк через словарь
    «текст → номер» на 2.3 млн ключей. Цена этого пути:

        загрузка склада (state.json, 549 МБ)   5.3 с
        постройка словаря                      5.4 с
        сама маска                             1.5 с

    Двенадцать секунд из двенадцати с половиной, которые приложение тратит на
    прогрев. При том что номер книги у каждой строки ЛЕЖИТ В ИНДЕКСЕ колонкой
    `src` с Раунда 57, и та же маска из неё берётся за 0.01 с.

    СВЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО. Обе маски совпали побитово на четырёх
    раскладах — все книги включены, выключены 1, 5 и 20: ноль расходящихся
    строк при 2 299 472 / 2 113 358 / 1 017 270 живых.

    None — у индекса нет колонки `src` (испечён до Раунда 57) или список книг
    не передали: тогда зовущий честно уходит на прежний путь через тексты.
    """
    global _книги_кэш
    if активные is None or getattr(idx, "src", None) is None:
        return None
    ид = list(getattr(idx, "sources", []) or [])
    if not ид:
        return None
    ключ = (id(idx), frozenset(активные))
    if _книги_кэш is not None and _книги_кэш[0] == ключ:
        return _книги_кэш[1]
    номера = [i for i, x in enumerate(ид) if x in активные]
    if not номера:
        # НИ ОДНА КНИГА НЕ СОШЛАСЬ С ИНДЕКСОМ — значит спрашивали не про этот
        # индекс: он испечён из другого состава, или флаги активности пришли из
        # чужого хранилища (так вышло на тестовом стенде: синтетический индекс
        # против боевого active.json). Отдать здесь пустую маску значило бы
        # молча выдать ноль строк — тот самый молчаливый ноль, за который в
        # этом проекте казнят. Отдаём None: зовущий уйдёт на путь через тексты,
        # который сверяется с самим индексом.
        return None
    м = np.isin(np.asarray(idx.src), номера)
    _книги_кэш = (ключ, м)
    return м


