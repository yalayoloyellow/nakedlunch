# «БАНАЛЬНОСТЬ» — ОДНА ДВУСТОРОННЯЯ РУЧКА НА ДВЕ ОСИ (Раунд 58).
#
# Владелец, дословно: «по сути ручка банальность должна по обоим таким фронтам
# работать одна крутилка — на минимуме всё максимально стремится к банальности,
# на максимуме максимально неклишированно и не банально, посередине как будто
# не работает».
#
# ДВЕ ОСИ. Слова — частота самого редкого слова строки (как было). Сцепка —
# насколько затаскано сочетание соседей (новое, см. tools/build_nl_index.py).
#
# ПОЧЕМУ ДВУСТОРОННЯЯ. Прежняя ручка была ОДНОСТОРОННИМ потолком
# (`6.5 − 2.5·ручка`): она умела только отрезать банальный край, а сказать
# «хочу банального» было нельзя вовсе. Хуже: замер 2026-08-06 показал, что и
# отрезала она почти ничего — на САМОМ строгом положении доживал 81% пула, на
# положении владельца 94.6%. То есть ручка, которой он пользовался год, почти
# не двигала выдачу.
#
# ШКАЛА — ПО КВАНТИЛЯМ ЕГО КОРПУСА, а не по числам из головы: «оставить десятую
# часть самых обычных» осмысленно на любом корпусе, а «zipf ≥ 4.45» — только на
# этом. Кванты пекутся вместе с индексом.
#
# СЦЕПКА ВСТУПАЕТ СО ВТОРОЙ ПОЛОВИНЫ ХОДА. У 70% строк знакомых сцепок нет
# вовсе — любой порог по ней это обрыв, а не наклон. Поэтому первая половина
# хода в каждую сторону работает словами, вторая добавляет сцепку. Так у ручки
# нет мёртвой зоны и нет ступеньки.
#
# СТОРОНА НЕТРОНУТОГО ОСТАВЛЕНА В АБСОЛЮТНЫХ ЕДИНИЦАХ (6.5 − 2.5·ход), а не в
# квантилях, и это не непоследовательность, а замер: у 10% строк банальность
# ровно 0.00 — это строки, чьё самое редкое слово словарю НЕИЗВЕСТНО (опечатки,
# латиница, необнаруженные имена). Квантильный потолок на максимуме отобрал бы
# ровно их и выдал бы за нетронутый язык. Абсолютный потолок так не делает.
#
# КАК НАЗВАНЫ КОНЦЫ (Раунд 58). В интерфейсе стояло «банально · свежо», и оба
# слова врали. «Банально» — приговор строке, а ручка судит не строку, а ЯЗЫК:
# как часто эти слова и это сочетание ходят по рукам. «Свежо» обещало новизну,
# которой ручка не делает: справа она не выдумывает небывалое, а лишь убирает
# ношеное — и ровно поэтому туда лезли обрывки фраз, пока их не закрыли
# воротами целостности. Стало «затёрто · нетронуто»: про износ языка, а не про
# качество результата.
class Ворота(NamedTuple):
    """Полосы допуска по обеим осям. Бесконечность = ворот нет."""
    слова_низ: float = -math.inf
    слова_верх: float = math.inf
    сцепка_низ: float = -math.inf
    сцепка_верх: float = math.inf


def _квант(таблица, доля: float) -> float | None:
    """Точка распределения по проценту. None — таблицы нет (старый индекс)."""
    if not таблица:
        return None
    i = int(round(max(0.0, min(100.0, доля))))
    try:
        return float(таблица[i])
    except (IndexError, TypeError, ValueError):
        return None


def ворота_банальности(ручка: float, idx: "Index | None" = None) -> Ворота:
    """Положение ручки → полосы допуска. 0.5 — нейтраль (ворот нет), 0 —
    язык максимально ЗАТЁРТЫЙ (ходовые слова, готовые обороты), 1 —
    НЕТРОНУТЫЙ (редкие слова, ни одного заезженного сочетания).

    ЕДИНСТВЕННОЕ место перевода этой ручки в пороги: и быстрый путь по индексу,
    и путь по словарю, и карта воронки берут их отсюда. Дублировать формулу —
    ровно та ошибка, которой этот проект уже платил (см. RULES в сборщике)."""
    try:
        k = float(ручка)
    except (TypeError, ValueError):
        k = 0.5
    k = max(0.0, min(1.0, k))
    ход = abs(k - 0.5) * 2.0
    if ход <= 0.0:
        return Ворота()
    сц_ход = max(0.0, (ход - 0.5) * 2.0)       # сцепка — вторая половина хода
    if idx is None:
        idx = load()
    кв_сц = getattr(idx, "кванты_сцепки", None) if idx is not None else None
    кв_бн = getattr(idx, "кванты_банальности", None) if idx is not None else None

    if k > 0.5:                                 # нетронутое
        верх = _квант(кв_сц, 100.0 * (1.0 - сц_ход)) if сц_ход > 0 else None
        return Ворота(слова_верх=6.5 - 2.5 * ход,
                      сцепка_верх=math.inf if верх is None else верх)
    # 80, а не 90, и это ЗАМЕР, а не осторожность (2026-08-06). На квантиле 90
    # обе оси вместе оставляли 1861 строку из 2.4 млн — 383 рифмо-ключа, то
    # есть строфу с рифмовкой из этого уже не собрать, и край ручки честно
    # отвечал бы «нет материала». На 80 остаётся 21 497 строк и 2357 ключей:
    # край такой же крайний по смыслу (все слова обычные, в строке затасканная
    # связка), но выдача из него ещё собирается.
    низ = _квант(кв_бн, 80.0 * ход)             # затёртое
    сц = _квант(кв_сц, 80.0 * сц_ход) if сц_ход > 0 else None
    return Ворота(слова_низ=-math.inf if низ is None else низ,
                  сцепка_низ=-math.inf if сц is None else сц)


class Index:
    """Колонки корпуса. Массивы открыты через mmap: старт не платит разбор
    файла, а память растёт страницами по факту обращения — именно это снимает
    5.5 ГБ RSS и своп-налог на всё остальное."""

    def __init__(self, d: Path):
        meta = json.loads((d / "meta.json").read_text("utf-8"))
        self.n = int(meta["n"])
        self.rules = meta.get("rules", "")
        self.built_at = meta.get("built_at", "")
        self.keys = meta.get("keys") or []
        self.lemmas = meta.get("lemmas") or []
        self.tokens = meta.get("tokens") or []
        load = lambda name: np.load(d / f"{name}.npy", mmap_mode="r")  # noqa: E731
        self.banal = load("banal")
        self.taut = load("taut")
        self.mat = load("mat")
        self.syl = load("syl")
        self.key_id = load("key_id")
        self.span_a = load("span_a")
        self.span_b = load("span_b")
        self.lem_ids = load("lem_ids")
        self.lem_off = load("lem_off")
        self.lem2navec = load("lem2navec")
        self.tokpost = load("tokpost")
        self.tokoff = load("tokoff")
        self.text_off = load("text_off")
        # КОЛОНКА ИСТОЧНИКА (Раунд 57). Может отсутствовать у индекса, испечённого
        # до этого раунда — тогда None, и всё работает как раньше: источник это
        # новая возможность, а не новое требование.
        try:
            self.src = load("src")
        except Exception:
            self.src = None
        try:
            self.content = load("content")
        except Exception:
            self.content = None
        # СЦЕПКА СОСЕДНИХ СЛОВ (Раунд 58) — вторая ось ручки «Банальность»,
        # см. tools/build_nl_index.py: сцепка_колонка. Может отсутствовать у
        # индекса, испечённого раньше: тогда ручка работает одной осью, как
        # работала, и ничего не падает.
        try:
            self.bind = load("bind")
        except Exception:
            self.bind = None
        # 101 точка распределения каждой оси — шкала крутилки берётся отсюда,
        # а не из магических чисел. Считаются при сборке: это свойство корпуса.
        кв = meta.get("кванты") or {}
        self.кванты_банальности = кв.get("banal") or None
        self.кванты_сцепки = кв.get("bind") or None
        self.sources = meta.get("sources") or []
        self.blob = np.memmap(d / "text_blob.bin", dtype=np.uint8, mode="r")
        self._tok_id: dict[str, int] | None = None
        # производные, считаются один раз на процесс
        self._lem_len = np.diff(np.asarray(self.lem_off))
        nav = np.asarray(self.lem2navec)[np.asarray(self.lem_ids)]
        self._lem_valid = nav >= 0
        self._lem_navec = np.maximum(nav, 0)
        # Клаузула фрагмента (Раунд 44) — из его же рифмо-ключа, без новых
        # данных и без пересборки индекса: ключ начинается с ударной гласной,
        # значит число гласных в нём и есть слог от конца (см. scan.clausula).
        import scan as _scan
        по_ключу = np.array([_scan.clausula(k) for k in self.keys], dtype=np.int8) \
            if self.keys else np.zeros(0, dtype=np.int8)
        self.clau = по_ключу[np.asarray(self.key_id)] if len(по_ключу) else np.zeros(self.n, dtype=np.int8)

    # ---- тексты ----
    def text(self, i: int) -> str:
        a, b = int(self.text_off[i]), int(self.text_off[i + 1])
        return self.blob[a:b].tobytes().decode("utf-8")

    def texts(self, ids) -> list[str]:
        return [self.text(int(i)) for i in ids]

    def lemma_set(self, i: int) -> set:
        a, b = int(self.lem_off[i]), int(self.lem_off[i + 1])
        # tolist() одним куском: обход среза mmap поэлементно давал сотни тысяч
        # вызовов __getitem__ на запрос (замерено профайлером)
        return {self.lemmas[x] for x in self.lem_ids[a:b].tolist()}

    # ---- маски ----
    # Обрывки дефисных слов (Раунд 51). Нарезчик годами резал по обычному
    # дефису наравне с тире: «какая-нибудь» → «какая» + «нибудь», «из-за» →
    # «из» + «за». Регулярка в core/nlsrc/cutter.py починена, но 1.34% УЖЕ
    # нарезанного пула — обрывки: 26 263 фрагмента на 1.96 млн. По слогам и
    # клаузуле они безупречны, поэтому отбор их любит, а на слух это мусор
    # («нибудь гнусность скрывается» — реальная строка из документа владельца).
    #
    # Здесь ВОРОТА, а не удаление: данные владельца не трогаем, маска строится
    # один раз и живёт в памяти. Перенарезать источники — отдельное решение,
    # оно за ним.
    #
    # Списки закрытые и проверенные на ложные срабатывания: «мало» и «какой»
    # выброшены — ими фраза законно кончается («и все мало», «Воздух-то какой»).
    _ОБРЫВОК_НАЧАЛО = re.compile(r"^\s*(нибудь|либо|таки)\b", re.I)

    # ОБОРВАННАЯ ФРАЗА (Раунд 58). Владелец прислал выдачу на максимальной
    # свежести: «в этих сладостных битвах... В», «чтобы всё познать. Я не»,
    # «моих криков: О». Строка кончается словом, которое обязано что-то
    # присоединять, а присоединять нечего — нарезчик разрезал фразу пополам.
    #
    # ПОЧЕМУ ЭТО ЛЕЗЕТ ИМЕННО В СВЕЖУЮ ВЫДАЧУ. Целая русская фраза почти всегда
    # содержит хоть одно затасканное сочетание. Обрубок — нет: он и по редкости
    # слов, и по сцепке выглядит «свежим». То есть верхний край ручки
    # «Банальность» ОТБИРАЛ обрывки, а не терпел их.
    #
    # ЗАМЕР (2026-08-07, 2 434 632 строки): служебным словом кончается 384 255
    # строк — 15.8% корпуса, из них 223 095 доживали до свежей выдачи.
    #
    # СПИСОК ЗАКРЫТЫЙ И ПРОВЕРЕННЫЙ ВЫБОРКОЙ. Предлоги взяты целиком: русская
    # фраза не кончается предлогом никогда. Союзы и частицы — только те, по
    # которым просмотрены живые примеры, и среди них не нашлось ни одного
    # законного окончания: «а также то», «не такой уж», «Ну да», «малыш так»,
    # «имеет то же». Сомнительные («однако», «хотя», «словно») НЕ включены —
    # ими фраза кончиться может, а гадать здесь дороже, чем недобрать.
    # Правило Раунда 51 в силе: «мало» и «какой» остаются законными концами.
    _ХВОСТ = (
        # предлоги
        "в во на с со к ко за от ото до для без про через о об обо у при из изо "
        "по над надо под подо перед передо между среди около возле после ради "
        "вместо кроме сквозь вокруг против вдоль из-за из-под "
        # союзы и частицы — каждое проверено выборкой
        "и а но или либо ибо зато ни да не что чтобы чтоб как если ли бы же то "
        "так уж "
        # обрывки дефисных слов (Раунд 51)
        "кое давным"
    ).split()
    # МНОЖЕСТВОМ, А НЕ РЕГУЛЯРКОЙ. Альтернатива из шестидесяти слов гоняется по
    # 2.4 млн строк за 23 с — это платила бы первая генерация после запуска.
    # Отрезать хвост и сверить последнее слово со множеством — те же ворота за
    # 4 с: `rstrip`/`rfind` уходят в C, а перебор шестидесяти веток нет.
    _ХВОСТ_МНОЖЕСТВО = frozenset(_ХВОСТ)
    _ХВОСТ_МУСОР = " \t\n.,;:!?…\"»«()-–—'"

    @classmethod
    def _оборвана(cls, текст: str) -> bool:
        """Фраза кончается словом, которому нечего присоединять?"""
        хвост = текст.rstrip(cls._ХВОСТ_МУСОР)
        if not хвост:
            return False
        слово = хвост[хвост.rfind(" ") + 1:].lower()
        return слово in cls._ХВОСТ_МНОЖЕСТВО

    def whole_mask(self) -> np.ndarray:
        """True там, где фрагмент НЕ обрывок: ни разрезанного дефисного слова,
        ни оборванной фразы. Полный проход ~4 с на 2.4 млн, считается один раз
        за жизнь индекса и кэшируется; сервер делает это на прогреве, чтобы за
        него не платила первая генерация (см. api/server.py: этап «карты»)."""
        if getattr(self, "_whole", None) is None:
            бито = np.zeros(len(self.banal), dtype=bool)
            начало, оборвана = self._ОБРЫВОК_НАЧАЛО.match, self._оборвана
            for i in range(len(бито)):
                t = self.text(i)
                if оборвана(t) or начало(t):
                    бито[i] = True
            self._whole = ~бито
        return self._whole

    def gate_mask(self, ворота: "Ворота", no_mat: bool, only_mat: bool = False,
                  clausula: int = 0) -> np.ndarray:
        """Гейты строгого яруса: банальность (обе оси), тавтология, мат.
        Порядок и предикаты — дословно как в _score_strict_table.

        Раунд 58: ступень «клише» УБРАНА. Она была заглушкой на три зашитых
        выражения — то есть мнением автора кода о том, что затаскано, — а
        теперь то же самое меряется по корпусу владельца (см. `Ворота`)."""
        b = np.asarray(self.banal)
        m = (np.asarray(self.taut) == 0) & self.whole_mask()
        if ворота.слова_верх < math.inf:
            m &= b <= ворота.слова_верх
        if ворота.слова_низ > -math.inf:
            m &= b >= ворота.слова_низ
        if getattr(self, "bind", None) is not None:
            с = np.asarray(self.bind)
            if ворота.сцепка_верх < math.inf:
                m &= с <= ворота.сцепка_верх
            if ворота.сцепка_низ > -math.inf:
                m &= с >= ворота.сцепка_низ
        # СТРОКА ОБЯЗАНА ИМЕТЬ ХОТЯ БЫ ДВА ОБЫЧНЫХ СЛОВА (Раунд 57).
        #
        # «Г-ЖА ДЕ СЕНТ-АНЖ. — Я» проходит все прочие ворота честно: не клише,
        # не тавтология, не мат, слово целое, слоги в норме. Она не стих, а
        # ремарка пьесы, и признак у этого измеримый — знаменательных слов,
        # кроме имён, в ней меньше двух.
        #
        # Порог выбран по замеру, а не на глаз (2 276 166 доживших на
        # 2026-08-06): «меньше двух» отрезает 13.3% — ровно этот класс. «Меньше
        # трёх» срезало бы треть, включая нормальные короткие строки.
        if getattr(self, "content", None) is not None:
            m &= np.asarray(self.content) >= СЛОВ_МИН
        # ЧЁРНЫЙ СПИСОК (Раунд 57). Владелец: «если хоть где-то есть такое
        # сочетание слов — мне такие фрагменты вообще не показываются».
        # Маска кэшируется по самому списку, поэтому здесь это словарный поиск,
        # а не пересчёт: правила меняются редко, а ворота зовутся постоянно.
        з = запрет(_правила())
        if з["маска"] is not None:
            m &= ~з["маска"]
        if no_mat:
            m &= np.asarray(self.mat) == 0
        if only_mat:
            m &= np.asarray(self.mat) != 0
        if clausula:
            # 3 = «дактилическая и длиннее» (scan.clausula уже схлопывает)
            m &= np.asarray(self.clau) == clausula
        return m

    def token_hits(self, words) -> np.ndarray:
        """Номера фрагментов, где встречается хоть одно из слов, — обратный
        индекс вместо прохода по корпусу."""
        if self._tok_id is None:
            self._tok_id = {w: i for i, w in enumerate(self.tokens)}
        куски = []
        for w in words or ():
            t = self._tok_id.get(w)
            if t is None:
                continue
            куски.append(np.asarray(self.tokpost[self.tokoff[t]:self.tokoff[t + 1]]))
        if not куски:
            return np.empty(0, dtype=np.int64)
        return np.unique(np.concatenate(куски))

    # ---- релевантность теме ----
    def relevance(self, sims) -> np.ndarray:
        """Среднее косинуса по УНИКАЛЬНЫМ леммам фрагмента, что есть в словаре
        navec; 0.0 если таких лемм нет. Ровно то же, что embeddings.relevance
        на множестве лемм, только сразу по всему корпусу."""
        if sims is None:
            return np.zeros(self.n, dtype=np.float64)
        # двойная точность — НЕ перестраховка: на float32 среднее расходится с
        # поштучной embeddings.relevance на ~1e-7, а от порядка sem зависит РАНГ,
        # то есть перцентиль и оценка (поймано тестом при попытке ускорить)
        vals = np.asarray(sims, dtype=np.float64)[self._lem_navec]
        vals[~self._lem_valid] = 0.0
        off = np.asarray(self.lem_off)[:-1]
        sums = np.add.reduceat(vals, off)
        cnts = np.add.reduceat(self._lem_valid.astype(np.int64), off)
        # reduceat на ПУСТОМ сегменте возвращает соседний элемент, а не ноль
        пусто = self._lem_len == 0
        sums[пусто] = 0.0
        cnts[пусто] = 0
        return np.where(cnts > 0, sums / np.maximum(cnts, 1), 0.0)

    # ---- перцентиль и оценка ----
    def pctl(self, sem: np.ndarray, alive_idx: np.ndarray) -> np.ndarray:
        """Ранг релевантности среди ВЫЖИВШИХ, делённый на n−1. Сортировка
        стабильная: при равных значениях порядок остаётся корпусным — так же,
        как у sorted() в старом пути, и без темы (все sem нулевые) это в
        точности исходный порядок."""
        m = len(alive_idx)
        if m == 0:
            return np.empty(0, dtype=np.float64)
        if m == 1:
            return np.full(1, 0.5)
        order = np.argsort(sem[alive_idx], kind="stable")
        out = np.empty(m, dtype=np.float64)
        out[order] = np.arange(m, dtype=np.float64) / (m - 1)
        return out


def load(force: bool = False) -> "Index | None":
    """Индекс или None, если его нет либо он испечён по другим правилам.
    None — не ошибка: вызывающий честно уходит на старый путь."""
    global _idx, _tried
    if force:
        _idx, _tried = None, False
    if _tried:
        return _idx
    _tried = True
    try:
        if not (INDEX_DIR / "meta.json").exists():
            return None
        idx = Index(INDEX_DIR)
        if idx.rules != RULES:
            return None
        _idx = idx
    except Exception:
        _idx = None
    return _idx


def available() -> bool:
    return load() is not None


