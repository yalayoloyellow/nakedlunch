# КАРТА ВОРОНКИ (Раунд 57). Владелец: «нам в целом надо понимать, как именно
# что работает, чтоб потом этим управлять».
#
# Отвечает числом на вопрос «сколько народу отсекает каждая ступень» — по
# фрагментам И по книгам. До этого цена каждой ручки была известна только на
# словах, и три моих правки подряд били по симптомам именно потому, что
# посмотреть было некуда.
#
# Считается прямо по колонкам индекса, без похода в отбор: это карта ПУЛА, а не
# выдачи. Карта выдачи — отдельная работа (N прогонов), см.
# project-notes/PLAN-разнообразие.md.

def воронка(ручка: float = 0.5, no_mat: bool = False, only_mat: bool = False,
            clausula: int = 0, content_min: int = 0) -> dict | None:
    """Ступени отсева: сколько фрагментов и книг доживает до каждой.

    Возвращает None, если индекса нет — воронка это удобство, а не обязанность.
    """
    idx = load()
    if idx is None:
        return None
    import numpy as _np

    src = _np.asarray(idx.src) if getattr(idx, "src", None) is not None else None
    имена = getattr(idx, "sources", []) or []

    def книг(маска) -> int:
        if src is None:
            return 0
        s = src[маска]
        return int(len(_np.unique(s[s >= 0])))

    шаги = []
    маска = _np.ones(idx.n, dtype=bool)
    шаги.append(("весь индекс", маска.copy()))

    маска = маска & idx.whole_mask()
    шаги.append(("целые слова", маска.copy()))

    if no_mat:
        маска = маска & (~_np.asarray(idx.mat).astype(bool))
        шаги.append(("без мата", маска.copy()))
    elif only_mat:
        маска = маска & _np.asarray(idx.mat).astype(bool)
        шаги.append(("только мат", маска.copy()))

    # ЦЕНА РУЧКИ «БАНАЛЬНОСТЬ» — ПО КАЖДОЙ ОСИ ОТДЕЛЬНО (Раунд 58). Владелец
    # просил видеть, чем платит каждая ступень; у этой ручки ступеней две, и
    # смешать их в одну строку значило бы снова спрятать, что именно режет.
    в = ворота_банальности(ручка, idx)
    if в.слова_верх < math.inf:
        маска = маска & (_np.asarray(idx.banal) <= в.слова_верх)
        шаги.append((f"слова редкие ≤ {в.слова_верх:g}", маска.copy()))
    if в.слова_низ > -math.inf:
        маска = маска & (_np.asarray(idx.banal) >= в.слова_низ)
        шаги.append((f"слова ходовые ≥ {в.слова_низ:g}", маска.copy()))
    if getattr(idx, "bind", None) is not None:
        if в.сцепка_верх < math.inf:
            маска = маска & (_np.asarray(idx.bind) <= в.сцепка_верх)
            шаги.append((f"сцепка ≤ {в.сцепка_верх:.2f} · нетронутые", маска.copy()))
        if в.сцепка_низ > -math.inf:
            маска = маска & (_np.asarray(idx.bind) >= в.сцепка_низ)
            шаги.append((f"сцепка ≥ {в.сцепка_низ:.2f} · затёртые", маска.copy()))

    маска = маска & (~_np.asarray(idx.taut).astype(bool))
    шаги.append(("без тавтологии", маска.copy()))

    if clausula:
        # `clau`, а не `clausula`: колонка называется так везде (см. select).
        # Здесь стояло несуществующее имя — воронка падала на любом положении
        # клаузулы, кроме «любой», и молча возвращала пустоту.
        маска = маска & (_np.asarray(idx.clau) == clausula)
        шаги.append((f"клаузула {clausula}", маска.copy()))

    if content_min and getattr(idx, "content", None) is not None:
        маска = маска & (_np.asarray(idx.content) >= content_min)
        шаги.append((f"слов ≥ {content_min}", маска.copy()))

    всего = int(idx.n)
    ступени = [{"шаг": имя, "дожило": int(m.sum()),
                "доля": round(100.0 * int(m.sum()) / всего, 1) if всего else 0.0,
                "книг": книг(m)} for имя, m in шаги]

    # доли книг на ПОСЛЕДНЕЙ ступени — кто реально доходит до отбора
    доли = []
    if src is not None and шаги:
        s = src[шаги[-1][1]]
        s = s[s >= 0]
        if len(s):
            сч = _np.bincount(s, minlength=max(1, len(имена)))
            for i in _np.argsort(-сч)[:10]:
                if сч[i]:
                    доли.append({"источник": имена[i] if i < len(имена) else str(i),
                                 "строк": int(сч[i]),
                                 "доля": round(100.0 * int(сч[i]) / len(s), 1)})
    return {"всего": всего, "книг_всего": len(имена), "ступени": ступени, "источники": доли}


