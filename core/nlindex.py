# «БАНАЛЬНОСТЬ» — ОДНА ДВУСТОРОННЯЯ РУЧКА НА ДВЕ ОСИ (Раунд 58).
#
# Требование, дословно: одна крутилка на оба фронта — на минимуме язык максимально затёртый,
# на максимуме максимально нетронутый, посередине не влияет..
#
# ДВЕ ОСИ. Слова — частота самого редкого слова строки (как было). Сцепка —
# насколько затаскано сочетание соседей (новое, см. tools/build_nl_index.py).
#
# ПОЧЕМУ ДВУСТОРОННЯЯ. Прежняя ручка была ОДНОСТОРОННИМ потолком
# (`6.5 − 2.5·ручка`): она умела только отрезать банальный край, а сказать
# «хочу банального» было нельзя вовсе. Хуже: замер 2026-08-06 показал, что и
# отрезала она почти ничего — на САМОМ строгом положении доживал 81% пула, на
# положении пользователя 94.6%. То есть ручка, которой он пользовался год, почти
# не двигала выдачу.
#
# ШКАЛА — ПО КВАНТИЛЯМ ЕГО КОРПУСА, а не по числам из головы: «оставить десятую
# часть самых обычных» осмысленно на любом корпусе, а «zipf ≥ 4.45» — только на
# этом. Кванты пекутся вместе с индексом.
#
# СЦЕПКА ВСТУПАЕТ СО ВТОРОЙ ПОЛОВИНЫ ХОДА. У 70% строк знакомых сцепок нет
# вовсе — любой порог по ней это обрыв, а не наклон. Поэтому первая половина
# хода в каждую сторону работает словами, вторая добавляет сцепку. Так у ручки
# нет мёртвой зоны и нет ступеньки.
#
# СТОРОНА НЕТРОНУТОГО ОСТАВЛЕНА В АБСОЛЮТНЫХ ЕДИНИЦАХ (6.5 − 2.5·ход), а не в
# квантилях, и это не непоследовательность, а замер: у 10% строк банальность
# ровно 0.00 — это строки, чьё самое редкое слово словарю НЕИЗВЕСТНО (опечатки,
# латиница, необнаруженные имена). Квантильный потолок на максимуме отобрал бы
# ровно их и выдал бы за нетронутый язык. Абсолютный потолок так не делает.
#
# КАК НАЗВАНЫ КОНЦЫ (Раунд 58). В интерфейсе стояло «банально · свежо», и оба
# слова врали. «Банально» — приговор строке, а ручка судит не строку, а ЯЗЫК:
# как часто эти слова и это сочетание ходят по рукам. «Свежо» обещало новизну,
# которой ручка не делает: справа она не выдумывает небывалое, а лишь убирает
# ношеное — и ровно поэтому туда лезли обрывки фраз, пока их не закрыли
# воротами целостности. Стало «затёрто · нетронуто»: про износ языка, а не про
# качество результата.
class Ворота(NamedTuple):
    """Полосы допуска по обеим осям. Бесконечность = ворот нет."""
    слова_низ: float = -math.inf
    слова_верх: float = math.inf
    # ПОЛЕЙ СЦЕПКИ ЗДЕСЬ БОЛЬШЕ НЕТ (Раунд 62) — ось убрана по замеру, см.
    # `ворота_банальности`. Оставлять их «на всякий случай» значило бы держать
    # мёртвую половину ворот, которую следующий читатель примет за рабочую.


def _квант(таблица, доля: float) -> float | None:
    """Точка распределения по проценту. None — таблицы нет (старый индекс)."""
    if not таблица:
        return None
    i = int(round(max(0.0, min(100.0, доля))))
    try:
        return float(таблица[i])
    except (IndexError, TypeError, ValueError):
        return None


def ворота_банальности(ручка: float, idx: "Index | None" = None) -> Ворота:
    """Положение ручки → полосы допуска. 0.5 — нейтраль (ворот нет), 0 —
    язык максимально ЗАТЁРТЫЙ (ходовые слова, готовые обороты), 1 —
    НЕТРОНУТЫЙ (редкие слова, ни одного заезженного сочетания).

    ЕДИНСТВЕННОЕ место перевода этой ручки в пороги: и быстрый путь по индексу,
    и путь по словарю, и карта воронки берут их отсюда. Дублировать формулу —
    ровно та ошибка, которой этот проект уже платил (см. RULES в сборщике)."""
    try:
        k = float(ручка)
    except (TypeError, ValueError):
        k = 0.5
    k = max(0.0, min(1.0, k))
    ход = abs(k - 0.5) * 2.0
    if ход <= 0.0:
        return Ворота()
    # ОСЬ СЦЕПКИ УБРАНА (Раунд 62) — не упрощение, а починка по замеру.
    #
    # Она включалась со второй половины хода, и ровно она давала ОБЕ болезни
    # ручки: скачок пула в 3.65 раза на шаге 0.20→0.25 (момент её выключения) и
    # нищий край — 18 266 строк вместо 285 856. Без неё шаги ровные:
    # 1.50 · 1.34 · 1.26 · 1.20 · 1.18 вместо 3.39 и 3.65.
    #
    # А меряла она не то, что обещала. Верхушка «самых затёртых сочетаний» —
    # «Гуд бай», «летучая мышь», «Тверской бульвар», «Московский комсомолец»:
    # PMI по корпусу книг находит имена собственные, термины и транслитерации,
    # а не изношенный язык. Пример из докстринга самого сборщика — «сердечная
    # боль» — набирает 7 вхождений при пороге 30 и получает РОВНО НОЛЬ. У 70.1%
    # строк сцепка нулевая: для двух третей корпуса ось молчит вовсе. Слепое
    # чтение уравненных по длине и редкости строк её полосы не развело.
    #
    # Колонка `bind.npy` остаётся в индексе: перепечка не нужна, `RULES` не
    # меняется, её просто больше никто не спрашивает.
    if idx is None:
        idx = load()
    кв_бн = getattr(idx, "кванты_банальности", None) if idx is not None else None

    if k > 0.5:                                 # нетронутое
        # ПОТОЛОК ПОКА ОСТАЁТСЯ АБСОЛЮТНЫМ, И ЭТО ИЗВЕСТНЫЙ ДОЛГ (Раунд 62).
        #
        # Замерено: у 0.45/0.50/0.55 пул побуквенно одинаковый, а от 0.45 до
        # 0.75 — треть хода — уходит меньше процента корпуса. Порог 6.25 не
        # превышает ни одна строка, потому что редкость считается как МИНИМУМ
        # по знаменательным словам. Край 1.0 пропускает 84.9% корпуса, то есть
        # «нетронутое» не значит почти ничего.
        #
        # Квантильная шкала это чинит (замерено: мёртвых шагов 1 из 20 вместо
        # трёх подряд, край 15.6% вместо 84.9%), НО она молча переоценивает все
        # сохранённые профили пользователя: его умолчание 0.83 держит потолок
        # 4.875 и пропускает 84.9%, а тот же квантиль пустил бы 47%. Ручка
        # осталась бы на месте, а значить стала бы другое.
        # Поэтому перепечка шкалы — отдельное решение с пересчётом профилей,
        # а не тихая правка. См. план, этап 4.
        return Ворота(слова_верх=6.5 - 2.5 * ход)
    # 80, а не 90, и это ЗАМЕР, а не осторожность (2026-08-06). На квантиле 90
    # обе оси вместе оставляли 1861 строку из 2.4 млн — 383 рифмо-ключа, то
    # есть строфу с рифмовкой из этого уже не собрать, и край ручки честно
    # отвечал бы «нет материала». На 80 остаётся 21 497 строк и 2357 ключей:
    # край такой же крайний по смыслу (все слова обычные, в строке затасканная
    # связка), но выдача из него ещё собирается.
    низ = _квант(кв_бн, 80.0 * ход)             # затёртое
    return Ворота(слова_низ=-math.inf if низ is None else низ)


class Index:
    """Колонки корпуса. Массивы открыты через mmap: старт не платит разбор
    файла, а память растёт страницами по факту обращения — именно это снимает
    5.5 ГБ RSS и своп-налог на всё остальное."""

    def __init__(self, d: Path):
        meta = json.loads((d / "meta.json").read_text("utf-8"))
        self.n = int(meta["n"])
        self.rules = meta.get("rules", "")
        self.built_at = meta.get("built_at", "")
        self.keys = meta.get("keys") or []
        self.lemmas = meta.get("lemmas") or []
        self.tokens = meta.get("tokens") or []
        load = lambda name: np.load(d / f"{name}.npy", mmap_mode="r")  # noqa: E731
        self.banal = load("banal")
        self.taut = load("taut")
        self.mat = load("mat")
        self.syl = load("syl")
        self.key_id = load("key_id")
        self.span_a = load("span_a")
        self.span_b = load("span_b")
        self.lem_ids = load("lem_ids")
        self.lem_off = load("lem_off")
        self.lem2navec = load("lem2navec")
        self.tokpost = load("tokpost")
        self.tokoff = load("tokoff")
        self.text_off = load("text_off")
        # КОЛОНКА ИСТОЧНИКА (Раунд 57). Может отсутствовать у индекса, испечённого
        # до этого раунда — тогда None, и всё работает как раньше: источник это
        # новая возможность, а не новое требование.
        try:
            self.src = load("src")
        except Exception:
            self.src = None
        try:
            self.content = load("content")
        except Exception:
            self.content = None
        # СЦЕПКА СОСЕДНИХ СЛОВ (Раунд 58) — вторая ось ручки «Банальность»,
        # см. tools/build_nl_index.py: сцепка_колонка. Может отсутствовать у
        # индекса, испечённого раньше: тогда ручка работает одной осью, как
        # работала, и ничего не падает.
        try:
            self.bind = load("bind")
        except Exception:
            self.bind = None
        # 101 точка распределения каждой оси — шкала крутилки берётся отсюда,
        # а не из магических чисел. Считаются при сборке: это свойство корпуса.
        кв = meta.get("кванты") or {}
        self.кванты_банальности = кв.get("banal") or None
        # `кванты_сцепки` больше не читаются: ось убрана (Раунд 62, см.
        # `ворота_банальности`). В meta.json они остаются — индекс не
        # перепекается, и лишнее поле там никому не мешает.
        self.sources = meta.get("sources") or []
        self.blob = np.memmap(d / "text_blob.bin", dtype=np.uint8, mode="r")
        self._tok_id: dict[str, int] | None = None
        self._отпечаток: str | None = None
        # производные, считаются один раз на процесс
        self._lem_len = np.diff(np.asarray(self.lem_off))
        nav = np.asarray(self.lem2navec)[np.asarray(self.lem_ids)]
        self._lem_valid = nav >= 0
        self._lem_navec = np.maximum(nav, 0)
        # Клаузула фрагмента (Раунд 44) — из его же рифмо-ключа, без новых
        # данных и без пересборки индекса: ключ начинается с ударной гласной,
        # значит число гласных в нём и есть слог от конца (см. scan.clausula).
        import scan as _scan
        по_ключу = np.array([_scan.clausula(k) for k in self.keys], dtype=np.int8) \
            if self.keys else np.zeros(0, dtype=np.int8)
        self.clau = по_ключу[np.asarray(self.key_id)] if len(по_ключу) else np.zeros(self.n, dtype=np.int8)

    # ---- тексты ----
    def text(self, i: int) -> str:
        a, b = int(self.text_off[i]), int(self.text_off[i + 1])
        return self.blob[a:b].tobytes().decode("utf-8")

    def texts(self, ids) -> list[str]:
        return [self.text(int(i)) for i in ids]

    # ---- кто эти строки ----
    def отпечаток(self) -> str:
        """Отпечаток СОСТАВА, а не сборки.

        Семя воспроизводит прогон, пока строки те же и в том же порядке. Раньше
        это судилось по времени сборки (`built_at`), и любая перепечка объявляла
        ВСЕ записанные номера прогонов устаревшими — даже пересчёт одной
        колонки, при котором ни одна строка не сдвинулась. Врать в эту сторону
        не безобиднее, чем в другую: приложение зря говорило «номер снят с
        прежнего корпуса» и обесценивало то, что цело.

        Судим по самим строкам:
          • `n` — сколько их;
          • `text_off` целиком — длина КАЖДОЙ строки и её место в блобе. Любая
            вставка, удаление и перестановка сдвигают хвост смещений;
          • `key_id` целиком — рифмо-ключ каждой строки, то есть её последнее
            слово. Правка, меняющая текст, почти всегда трогает конец (ровно это
            делает ретро-подрезка обрывков), а конец здесь виден весь;
          • 64 текста через равные промежутки — выборочная сверка содержимого.

        ЧЕГО ЭТО НЕ ЛОВИТ, СКАЗАНО ПРЯМО: подмену строки на другую ТОЙ ЖЕ длины
        и с тем же рифмо-ключом, если она не попала в выборку из 64. Такой
        правки в конвейере нет ни одной, но отпечаток — [С], самоделка, и
        выдавать её за доказательство нельзя.

        Полный блоб (1.6 ГБ) нарочно не хешируется: он стоил бы секунду с
        лишним на первой же генерации — ровно тот налог, который в этом раунде
        сняли с прогрева. Цена нынешнего замерена на полном индексе
        (2 434 632 строки): **44.5 мс** первый раз, 0.002 дальше, и первый раз
        платит прогрев, а не пользователь."""
        if self._отпечаток is None:
            h = hashlib.blake2b(digest_size=8)
            h.update(f"{self.n}:".encode())
            h.update(np.asarray(self.text_off).tobytes())
            h.update(np.asarray(self.key_id).tobytes())
            шаг = max(1, self.n // 64)
            for i in range(0, self.n, шаг):
                h.update(self.text(int(i)).encode("utf-8"))
            self._отпечаток = h.hexdigest()
        return self._отпечаток

    def lemma_set(self, i: int) -> set:
        a, b = int(self.lem_off[i]), int(self.lem_off[i + 1])
        # tolist() одним куском: обход среза mmap поэлементно давал сотни тысяч
        # вызовов __getitem__ на запрос (замерено профайлером)
        return {self.lemmas[x] for x in self.lem_ids[a:b].tolist()}

    # ---- маски ----
    # Обрывки дефисных слов (Раунд 51). Нарезчик годами резал по обычному
    # дефису наравне с тире: «какая-нибудь» → «какая» + «нибудь», «из-за» →
    # «из» + «за». Регулярка в core/nlsrc/cutter.py починена, но 1.34% УЖЕ
    # нарезанного пула — обрывки: 26 263 фрагмента на 1.96 млн. По слогам и
    # клаузуле они безупречны, поэтому отбор их любит, а на слух это мусор
    # («нибудь гнусность скрывается» — реальная строка из документа пользователя).
    #
    # Здесь ВОРОТА, а не удаление: данные пользователя не трогаем, маска строится
    # один раз и живёт в памяти. Перенарезать источники — отдельное решение,
    # оно за ним.
    #
    # Списки закрытые и проверенные на ложные срабатывания: «мало» и «какой»
    # выброшены — ими фраза законно кончается («и все мало», «Воздух-то какой»).
    _ОБРЫВОК_НАЧАЛО = re.compile(r"^\s*(нибудь|либо|таки)\b", re.I)

    # ОБОРВАННАЯ ФРАЗА (Раунд 58). В выдаче на максимальной свежести встречалось: «в этих сладостных битвах... В», «чтобы всё познать. Я не»,
    # «моих криков: О». Строка кончается словом, которое обязано что-то
    # присоединять, а присоединять нечего — нарезчик разрезал фразу пополам.
    #
    # ПОЧЕМУ ЭТО ЛЕЗЕТ ИМЕННО В СВЕЖУЮ ВЫДАЧУ. Целая русская фраза почти всегда
    # содержит хоть одно затасканное сочетание. Обрубок — нет: он и по редкости
    # слов, и по сцепке выглядит «свежим». То есть верхний край ручки
    # «Банальность» ОТБИРАЛ обрывки, а не терпел их.
    #
    # ЗАМЕР (2026-08-07, 2 434 632 строки): служебным словом кончается 384 255
    # строк — 15.8% корпуса, из них 223 095 доживали до свежей выдачи.
    #
    # СПИСОК ЗАКРЫТЫЙ И ПРОВЕРЕННЫЙ ВЫБОРКОЙ. Предлоги взяты целиком: русская
    # фраза не кончается предлогом никогда. Союзы и частицы — только те, по
    # которым просмотрены живые примеры, и среди них не нашлось ни одного
    # законного окончания: «а также то», «не такой уж», «Ну да», «малыш так»,
