_ГЛАСНЫЕ = "аеёиоуыэюя"


def _подрезать(строка: str, вилка, ворота: dict):
    """Отрезать голову, пока строка не влезет в вилку слогов. None — не вышло.

    РЕЖЕТСЯ ПЕРВОЕ СЛОВО, А НЕ ПОСЛЕДНЕЕ: рифмо-ключ берётся с последнего
    знаменательного слова, поэтому голова свободна (замер: рез головы меняет
    ключ у 0.98% строк, хвоста — у 73.1%). Значит уже посчитанные корзины по
    рифме, клаузула и ярус остаются верными.

    Каждый шаг проверяется теми же воротами, что стоят у человека на панели
    (`сдвиг.причина_отказа`): подрезанная строка не имеет права нарушить то,
    по чему её отбирали. Не вышло — кандидат отбрасывается целиком.
    """
    низ, верх = вилка
    текущая = строка
    for _ in range(8):
        слогов = sum(1 for ч in текущая.lower() if ч in _ГЛАСНЫЕ)
        if слогов <= верх:
            return текущая if слогов >= низ else None
        try:
            следующая = _сдвиг.короче(текущая)
        except Exception:
            return None
        if _сдвиг.причина_отказа(текущая, следующая, ворота):
            return None
        текущая = следующая
    return None

