    def token_hits(self, words) -> np.ndarray:
        """Номера фрагментов, где встречается хоть одно из слов, — обратный
        индекс вместо прохода по корпусу."""
        if self._tok_id is None:
            self._tok_id = {w: i for i, w in enumerate(self.tokens)}
        куски = []
        for w in words or ():
            t = self._tok_id.get(w)
            if t is None:
                continue
            куски.append(np.asarray(self.tokpost[self.tokoff[t]:self.tokoff[t + 1]]))
        if not куски:
            return np.empty(0, dtype=np.int64)
        return np.unique(np.concatenate(куски))

    # ---- релевантность теме ----
    def relevance(self, sims) -> np.ndarray:
        """Среднее косинуса по УНИКАЛЬНЫМ леммам фрагмента, что есть в словаре
        navec; 0.0 если таких лемм нет. Ровно то же, что embeddings.relevance
        на множестве лемм, только сразу по всему корпусу."""
        if sims is None:
            return np.zeros(self.n, dtype=np.float64)
        # двойная точность — НЕ перестраховка: на float32 среднее расходится с
        # поштучной embeddings.relevance на ~1e-7, а от порядка sem зависит РАНГ,
        # то есть перцентиль и оценка (поймано тестом при попытке ускорить)
        vals = np.asarray(sims, dtype=np.float64)[self._lem_navec]
        vals[~self._lem_valid] = 0.0
        off = np.asarray(self.lem_off)[:-1]
        sums = np.add.reduceat(vals, off)
        cnts = np.add.reduceat(self._lem_valid.astype(np.int64), off)
        # reduceat на ПУСТОМ сегменте возвращает соседний элемент, а не ноль
        пусто = self._lem_len == 0
        sums[пусто] = 0.0
        cnts[пусто] = 0
        return np.where(cnts > 0, sums / np.maximum(cnts, 1), 0.0)

    # ---- перцентиль и оценка ----
    def pctl(self, sem: np.ndarray, alive_idx: np.ndarray) -> np.ndarray:
        """Ранг релевантности среди ВЫЖИВШИХ, делённый на n−1. Сортировка
        стабильная: при равных значениях порядок остаётся корпусным — так же,
        как у sorted() в старом пути, и без темы (все sem нулевые) это в
        точности исходный порядок."""
        m = len(alive_idx)
        if m == 0:
            return np.empty(0, dtype=np.float64)
        if m == 1:
            return np.full(1, 0.5)
        order = np.argsort(sem[alive_idx], kind="stable")
        out = np.empty(m, dtype=np.float64)
        out[order] = np.arange(m, dtype=np.float64) / (m - 1)
        return out


