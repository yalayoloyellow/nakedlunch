# в `api/server.py`; здесь она стоит на своём месте — у самого индекса.
#
#   `_ЗАМОК_ЗАГРУЗКИ` — крошечный, вокруг присваивания `_idx`/`_tried` и ничего
#       больше. Он чинит гонку `load()`: признак «пробовали» ставился ДО
#       постройки объекта, и второй вызывающий в эти 0.2 с получал None и верил
#       ему. Именно из-за неё перепривязка истории после КАЖДОЙ перепечки молча
#       не делала свою работу.
#
#   `ЗАМОК` — публичный, вокруг ЦЕЛОГО счёта по индексу (`filters.run`,
#       `воронка`, `форма_пула`) и вокруг `forget`/`reload`. Он чинит другое:
#       перепечка не имеет права влезть в середину запроса. Сбросом кэшей это
#       не лечится — запрос, начатый со старыми колонками, доходил бы до маски
#       уже с новыми.
#
# Разделять обязательно. Один общий замок означал бы, что опрос статуса (раз в
# 1.2 с, зовёт `load()`) встаёт за генерацией на все её 185–878 мс — то есть
# шапка отстаёт ровно тогда, когда пользователь смотрит на неё пристальнее
# всего. Порядок захвата всегда один: `ЗАМОК` → `_ЗАМОК_ЗАГРУЗКИ` → `_text_lock`;
# обратного нет нигде, поэтому взаимной блокировки быть не может.
#
# ЦЕНА. Незанятый `RLock` — **0.090 мкс** на пару acquire/release (замер
# 2026-08-18 на этой машине: 10⁶ пар за 0.090 с; прежняя запись говорила
# 0.109 мкс — тот же порядок). Против 185 мс прогона это 0.00005% запроса.
# Занятым он бывает только в конце перепечки: тогда одна генерация подождёт
# другую. Плата за то, что отказа нет вовсе.
_ЗАМОК_ЗАГРУЗКИ = threading.RLock()
ЗАМОК = threading.RLock()

