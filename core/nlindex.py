# 231 837 словоформ). `pymorphy3.parse` стоит 101.7 мкс на слово и НЕ кэширует
# ничего сам. Отсюда обе статьи расхода чёрного списка:
#
#   • карта форм — разбор всех 231 837 словоформ = 15.4 с. Сборка самого
#     словаря из готовых начальных форм при этом 0.30 с, то есть 98% времени
#     это pymorphy, а не структура данных;
#   • проверка «подряд» у словосочетания — разбор ВСЕХ слов каждой строки-
#     кандидата: 8 752 слова на 1 147 кандидатов = 0.89 с НА КАЖДОЕ правило.
#
# Пересечения постингов (0.012 с) и сама маска (0.0001 с) не стоят ничего —
