#   • резерв по перцентилю — чтобы тематический якорь не срезало усечением;
#   • резерв по слоговой вилке — по per_bucket на КАЖДЫЙ рифмо-ключ.
# Здесь они считаются по колонкам, а словари собираются только для объединения
# — тысячи строк вместо миллионов.
#
# ПОРЯДОК ВАЖЕН И ПОВТОРЁН ТОЧНО: перцентиль считается среди выживших ГЕЙТОВ по
# всей базе (так строилась строгая таблица — без пула, истории и чёрного
# списка), и только потом накладывается пул/история/чёрный список. Перепутать
# — значит тихо сдвинуть все ранги.
#
# Ничьи: старый путь мешал список и стабильно сортировал по убыванию оценки,
# то есть среди равных давал равномерно случайный порядок. Здесь то же самое
# даёт джиттер МЕНЬШЕ кванта округления (оценка округлена до 4 знаков, джиттер
# < 1e-5): порядок различных оценок он изменить не может, а равные
# перемешивает.

# Полуширина полосы темы в долях ранжира: «внутри ±этого от положения ручки все
# равны». Число ЗАМЕРЕНО, а не выбрано на глаз (2026-08-13, три темы, 25
# прогонов на каждую, два показателя — разнообразие и верность месту ранжира):
#
#   полоса   разных строк из 200        медиана |перцентиль − ручка|
#   ±0.000   72–75  (как было)          0.0000
#   ±0.002   142–148                    0.0013
#   ±0.005   147–153                    0.0033
#   ±0.020   154                        0.0140
#
# Колено ровно здесь: полоса ±0.002 УДВАИВАЕТ разнообразие, а выбранная строка
# остаётся в ближайших 0.13% ранжира (около 2 000 из 1.56 млн за воротами).
# Шире — покупаем ещё 5% разнообразия ценой десятикратного ухода от места,
# которое пользователь заказал ручкой. Потолок 154–158 из 200 ставит уже не
# полоса, а рифмо-схема и барьер повтора лемм.
ПОЛОСА_ТЕМЫ = 0.002

_JITTER = 1e-5

# ПОСТОЯННАЯ ПЛАТА ЗА ПОХОД — ОДИН РАЗ, А НЕ КАЖДЫЙ (Раунд 56).
#
# Замерено на машине пользователя, журналом из его окна: поход за ВОСЕМЬЮ строками
# стоит 45 секунд, за двумястами — 72. То есть почти вся цена не в строках, а в
# подготовке: ворота по 2.87 млн, релевантность по всем леммам корпуса,
# устойчивая сортировка перцентиля по 2.6 млн выживших. Это считалось ЗАНОВО на
# каждый вызов — а во фристайле тема и крутилки не меняются вовсе, и результат
# каждый раз выходил тот же самый.
#
# Кэшируем ровно то, что зависит ТОЛЬКО от корпуса и ручек. Пул и история в
# ключ не входят и не должны: они накладываются масками ПОСЛЕ, на каждый вызов
# свои, и именно поэтому кэш безопасен — показанное по-прежнему вычитается
# каждый раз.
#
# Одна запись: тема с крутилками меняется редко, а таблица весит десятки
# мегабайт, и держать историю значило бы менять секунды на своп (та же ловушка,
# что у _STRICT_SCORE_CACHE_MAX в filters.py).
_таблица_кэш: tuple | None = None


def _ключ_темы(tags, sims):
    """Тема в ключе — по её ПОСЛЕДСТВИЮ, а не по написанию: relevance зависит
    ровно от `sims`, и два разных набора слов с одинаковыми похожестями дают
    одну таблицу. `None` (темы нет) — свой отдельный случай."""
    if not tags or sims is None:
        return None
    a = np.asarray(sims)
    return (a.shape, float(a.sum()), float(a[0]) if a.size else 0.0)


# ТРИ КЭША, А НЕ ОДИН — ПОТОМУ ЧТО ТРИ РАЗНЫЕ ЗАВИСИМОСТИ (волна A, 2026-08-14).
#
# Кэш был один, с ключом «ворота + тема + связность», и любое движение любой из
# этих ручек пересчитывало ВСЁ. А зависимости у трёх величин разные, и на этом
# терялись сотни миллисекунд на каждом движении:
#
#   · `sem` — релевантность каждого фрагмента теме. От ворот не зависит ВООБЩЕ.
#     Замер: 137 мс, и они платились при каждом движении «Банальности»;
#   · `pctl` — ранг среди выживших ворот. От связности не зависит.
#     Замер: 289 мс, платились при каждом движении «Диссонанса»;
#   · `score` — от связности зависит, и это просто арифметика по готовому рангу.
#
# Ключи вложены: сменилась тема — недействительны все три; сменились ворота —
# два; сменилась связность — один.
_сем_кэш: tuple | None = None
_ранг_кэш: tuple | None = None


def _семантика(idx, tags, sims):
    """Релевантность темы по всему корпусу, с кэшем на одну тему."""
    global _сем_кэш
    ключ = (id(idx), _ключ_темы(tags, sims))
    if _сем_кэш is not None and _сем_кэш[0] == ключ:
        return _сем_кэш[1]
    _сем_кэш = (ключ, idx.relevance(sims))
    return _сем_кэш[1]


def _ранг(idx, sem, table_ids, tags):
    """Перцентиль релевантности среди выживших ворот, с кэшем на «ворота+тема».

    Ключ — по САМОМУ набору выживших, а не по положениям ручек: разные пороги
    банальности сплошь и рядом дают один и тот же набор (шкала дискретна), и
    считать ранг заново для того же множества незачем. Длина плюс концы — та же
    подпись, какой в этом файле ключуется маска пула."""
    global _ранг_кэш
    ключ = (id(idx), len(table_ids),
            int(table_ids[0]) if len(table_ids) else -1,
            int(table_ids[-1]) if len(table_ids) else -1,
            _ключ_темы(tags, None) if tags else None,
            id(sem))
    if _ранг_кэш is not None and _ранг_кэш[0] == ключ:
        return _ранг_кэш[1]
    _ранг_кэш = (ключ, idx.pctl(sem, table_ids))
    return _ранг_кэш[1]


def _таблица(idx, tags, sims, ворота, no_mat, only_mat, clausula, cohesion, pctl_scale):
    """(номера выживших ворот, перцентиль, оценка) — с кэшем на один набор."""
    global _таблица_кэш
    # Связность и её масштаб в ключе — только КОГДА ЕСТЬ ТЕМА: без темы от них
    # ничего не зависит (см. ниже), и держать их в ключе значило бы пересчитывать
    # ворота по 2.4 млн строк на каждое движение ползунка впустую.
    ключ = (id(idx), tuple(_правила()), tuple(ворота), bool(no_mat), bool(only_mat), int(clausula),
            float(cohesion) if tags else 0.0, float(pctl_scale) if tags else 0.0,
            _ключ_темы(tags, sims))
    if _таблица_кэш is not None and _таблица_кэш[0] == ключ:
        return _таблица_кэш[1]
    gate = idx.gate_mask(ворота, no_mat, only_mat, clausula)
    table_ids = np.flatnonzero(gate)                    # выжившие ГЕЙТОВ по всей базе
    if tags:
        sem = _семантика(idx, tags, sims)
        pctl_all = _ранг(idx, sem, table_ids, tags)
        # ПОЛОСА, А НЕ ОСТРИЁ (Раунд 62). Требование: «темы тоже равные шансы,
        # но после ранжирования по теме всего корпуса вообще».
        #
        # Ранжир по всему корпусу здесь и был: перцентиль считается по ВСЕМ
        # прошедшим ворота, а не по активному пулу. Не было второго — равных
        # шансов внутри выбранного места ранжира. Оценка убывала от центра, и
        # верхушка получалась всегда одна и та же: замерено 2026-08-13, 25
        # прогонов с РАЗНЫМИ семенами дали 75 разных строк из 200 — почти две
        # трети увиденного было повтором.
        #
        # Теперь внутри полосы оценка ОДНА, и кого взять решает случайная
        # добавка в `_topk_by`; за полосой оценка честно убывает — это запасной
        # ход, чтобы узкий активный пул не остался вовсе без кандидатов.
        d = np.abs(pctl_all - cohesion)
        score_all = np.round(np.where(d <= ПОЛОСА_ТЕМЫ, 0.6,
                                      0.6 - pctl_scale * (d - ПОЛОСА_ТЕМЫ)), 4)
    else:
        # БЕЗ ТЕМЫ НЕ РАНЖИРУЕМ ВОВСЕ (Раунд 62).
        #
        # Здесь стояло то же выражение, что и с темой, а `relevance(None)`
        # отдаёт нули. Тогда `pctl` — стабильная сортировка по нулям, то есть
        # РОВНО НОМЕР ФРАГМЕНТА В КОРПУСЕ, а оценка — «насколько этот номер
        # близок к положению ручки связности». Верхушка ранжира оказывалась
        # куском корпуса, а не выбором из него.
        #
        # ЗАМЕРЕНО (2026-08-13, 60 прогонов, пул 1 564 599 за воротами, 40 книг):
        # вся выдача — из ОДНОЙ книги (её доля в пуле 3.9%, перекос 25.8×),
        # номера фрагментов одного прогона укладывались в окно 293 подряд из
        # 2 434 632. `rng.sample` по тому же пулу давал 34 книги из 40 и
        # 9.4% у самой частой. То есть машина работала ХУЖЕ классического
        # рандома — ровно то, чего быть не должно.
        #
        # Ранжировать нечем — значит и не ранжируем: перцентиль нейтральный,
        # оценка одна на всех, а кого взять, решает случайная добавка в
        # `_topk_by`. Ручка связности без темы не действует ВООБЩЕ (не «слабо»,
        # а никак) — её и надо гасить в интерфейсе, а не подмешивать её
        # положение в уровень оценки.
        pctl_all = np.full(len(table_ids), 0.5, dtype=np.float64)
        score_all = np.full(len(table_ids), 0.6, dtype=np.float64)
    _таблица_кэш = (ключ, (table_ids, pctl_all, score_all))
    return _таблица_кэш[1]


def забыть_таблицу() -> None:
    """Сбросить кэши подготовки — зовётся вместе с `forget` при смене индекса.

    ВСЕ ТРИ, а не один: забыть внешний и оставить внутренние значило бы, что
    после перепечки индекса ранг считается по прежнему набору строк. Ровно так
    и живут ошибки этого рода — кэшей стало больше, а место сброса осталось
    одно."""
    global _таблица_кэш, _сем_кэш, _ранг_кэш
    _таблица_кэш = None
    _сем_кэш = None
    _ранг_кэш = None


def _topk_by(score, ids, k, rng):
    """k номеров с наибольшей оценкой; ничьи — случайно. Возвращает в порядке
    убывания оценки, как список после sort(reverse=True) у старого пути."""
    if k <= 0 or len(ids) == 0:
        return np.empty(0, dtype=np.int64)
    s = score + rng.random(len(score)) * _JITTER
    if len(ids) > k:
        part = np.argpartition(s, -k)[-k:]
    else:
        part = np.arange(len(ids))
    part = part[np.argsort(s[part])[::-1]]
    return ids[part]


def select(idx, *, pool_mask, hidden_mask, tags, forced, ворота,
           no_mat, only_mat, clausula, cohesion, pctl_scale, literal_cap, cap, reserve_n, use_theme_anchor,
           syllable_spec, per_bucket, sims, seed=None):
    """(строки, число_выживших, кандидаты_на_принудительное_слово, СЧЁТ).

    `счёт` — ступени отбора так, как они происходят на самом деле (Раунд 62).
    Четвёртым элементом, а не отдельными числами: ступеней будет прибавляться, и
    каждый раз менять подпись — значит каждый раз чинить всех вызывающих.

    Зачем понадобилось. Воронка показывала `nl_fetched → nl_survived → nl_used`,
    и в этой цепочке НЕ БЫЛО крупнейшей ступени: жребий из 1 564 599 в 300.
    Пользователь читал «из полутора миллионов выбрано восемь», а на деле —
    «из полутора миллионов СЛУЧАЙНО взято триста, и уже из трёхсот схема собрала
    восемь». Замер: буфер режет 99.98%, ворота — 35.7%."""
    rng = np.random.default_rng(seed)
    table_ids, pctl_all, score_all = _таблица(idx, tags, sims, ворота, no_mat,
                                              only_mat, clausula, cohesion, pctl_scale)

    keep = pool_mask[table_ids] & ~hidden_mask[table_ids]
    ids, pctl, score = table_ids[keep], pctl_all[keep], score_all[keep]
    # СЧИТАЕМ ЗДЕСЬ, А НЕ НИЖЕ. `n_survived` стоял ПОСЛЕ отсева повторов темы, и
    # с темой воронка врала на 3 528 строк: они прошли все ворота честно, а в
    # счётчике их не было, и потеря выглядела как ужесточение ворот.
    n_survived = int(len(ids))
    счёт = {"корпус": int(idx.n), "ворота": int(len(table_ids)), "пул": n_survived}

    # СРЕЗ БУКВАЛЬНЫХ УБРАН ОТСЮДА (волна B, 2026-08-14).
    #
    # Здесь стоял ограничитель `literal_cap`: из всего пула оставалось ровно
    # `cap` фрагментов со словом темы, остальные выбрасывались. Обещание было
    # «≈1 буквальная строка на строфу», а применялось оно КО ВСЕМУ ПУЛУ.
    # Замерено на реальном корпусе: тема «ночь» — срезано 728 из 730, «деньги»
    # — 1 185, оставалось 2. И выбирались эти двое по `score`, то есть по
    # близости к ПОЛОСЕ связности, а не по релевантности: при умолчании
    # (cohesion 0.3) выживали САМЫЕ ДАЛЁКИЕ от темы из буквальных, и до якоря
    # они уже не доходили. Отсюда «тема „деньги“ не появилась ни разу в 25
    # прогонах» при 4 670 подходящих строках в корпусе.
    #
    # Плюс сам признак был не тот: `token_hits` ловит ТОЧНУЮ СЛОВОФОРМУ.
    # «война» — есть, «войны», «войне», «войну» — нет; в корпусе таких форм
    # двенадцать. То есть срез бил мимо цели в обе стороны сразу.
    #
    # Обещание осталось, но переехало туда, где его можно сдержать: предел «не
    # больше одной буквальной на строфу» действует при сборке строфы
    # (filters._select_with_rhyme) и считает по ЛЕММЕ, а не по написанию.
    if tags:
        счёт["тема_буквально"] = int(np.isin(ids, idx.token_hits(tags)).sum())
    else:
        счёт["тема_буквально"] = 0
    порядок = np.arange(len(ids))

    отобрано = _topk_by(score, порядок, cap, rng)        # позиции внутри ids
    счёт["жребий"] = int(len(отобрано))
    взято = list(отобрано)
    есть = set(взято.copy())
    if use_theme_anchor and reserve_n > 0 and len(ids):
        # ВЕРХУШКА, А НЕ ВЕСЬ ПОРЯДОК (волна A, 2026-08-14). Нужны reserve_n
        # лучших по перцентилю — а считалась полная сортировка всего пула:
        # 73 мс из 295 на прогоне с темой при пуле в 800 000.
        #
        # Ответ ТОТ ЖЕ, и это не «почти»: перцентиль здесь — ранг, делённый на
        # n−1 (см. `Index.pctl`), то есть все значения РАЗНЫЕ по построению.
        # Ничьих нет, значит верхушка и её порядок определены однозначно, и
        # `argpartition` + сортировка только внутри верхушки дают ту же
        # последовательность, что полная сортировка. Порядок здесь важен: он
        # доезжает до порядка кандидатов, а от него зависит разброс равных.
        if reserve_n < len(pctl):
            верх = np.argpartition(pctl, -reserve_n)[-reserve_n:]
            рез = порядок[верх[np.argsort(pctl[верх])[::-1]]]
        else:
            рез = порядок[np.argsort(pctl)[::-1]]
        for j in рез:
            if int(j) not in есть:
                есть.add(int(j)); взято.append(j)
    if syllable_spec:
        _добрать_по_слогам(idx, ids, score, syllable_spec, per_bucket, взято, есть)

    взятые = np.asarray(взято, dtype=np.int64)
    строки = _строки(idx, ids[взятые], score[взятые], pctl[взятые]) if len(взятые) else []
    # ЖРЕБИЙ И РЕЗЕРВ — РАЗНЫЕ ЧИСЛА, и смешивать их нельзя. Первая версия
    # писала в «жребий» ИТОГ (`len(строки)`), и в интерфейсе выходило «жребий
    # 1 825» рядом с подписью «тянет случайные 300»: два числа об одном, и оба
    # правдивые. Поймано взглядом на нарисованную строку, не тестом.
    #
    # `жребий` — сколько вытянул `_topk_by` (без темы оценка у всех одна, значит
    # это буквально лотерея). `резерв` — сколько дописали сверху якорь темы и
    # добор по слоговой вилке. `в_сборку` — что в итоге ушло собирать схему.
    счёт["резерв"] = int(len(строки)) - счёт["жребий"]
    счёт["в_сборку"] = int(len(строки))
    счёт["предел_жребия"] = int(cap)
    кандидаты = {}
    for w in (forced or ()):
        попал = np.isin(ids, idx.token_hits([w]))
        кандидаты[w] = [_row(idx, int(ids[j]), float(score[j]), float(pctl[j]))
                        for j in np.flatnonzero(попал)]
    return строки, n_survived, кандидаты, счёт


def _добрать_по_слогам(idx, ids, score, syllable_spec, per_bucket, взято, есть):
    """Слоговой резерв: по per_bucket лучших на КАЖДЫЙ рифмо-ключ внутри
    вилки. Общий для строгого яруса и «классики» — правило одно, и разойтись
    им нельзя (иначе строфа с заданной длиной строки вела бы себя по-разному
    в зависимости от крутилки «классика»). Дописывает во `взято`/`есть`."""
    syl = np.asarray(idx.syl)[ids]
    key = np.asarray(idx.key_id)[ids]
    for lo, hi in {tuple(r) for r in syllable_spec}:
        в_вилке = np.flatnonzero((syl >= lo) & (syl <= hi) & (key != _пустой_ключ(idx)))
        if not len(в_вилке):
            continue
        # группируем по рифмо-ключу и берём по per_bucket лучших из каждой
        пор = в_вилке[np.lexsort((-score[в_вилке], key[в_вилке]))]
        k = key[пор]
        начала = np.flatnonzero(np.r_[True, k[1:] != k[:-1]])
        for a, b in zip(начала, np.r_[начала[1:], len(пор)]):
            for j in пор[a:min(a + per_bucket, b)]:
                if int(j) not in есть:
                    есть.add(int(j)); взято.append(j)


def _пустой_ключ(idx):
    """Номер пустого рифмо-ключа: фрагменты без ключа в слоговой резерв не
    берутся (старый путь требовал `key` истинным)."""
    if not hasattr(idx, "_empty_key"):
        try:
            idx._empty_key = idx.keys.index("")
        except ValueError:
            idx._empty_key = -1
    return idx._empty_key


def _строки(idx, номера, оценки, перцентили, light=False):
    """То же, что `_row` по одной, но КОЛОНКИ ЧИТАЮТСЯ ПАЧКОЙ (волна A).

    Замер на реальном пуле (800 000 фрагментов, умолчания приложения, тема):
    отбор отдаёт **12 616 строк за прогон**, и `_row` брал у mmap по одному
    элементу — семь скалярных обращений на строку плюс два среза. Это
    416 337 вызовов `memmap.__getitem__` за три прогона, 0.25 с из 1.5.

    Скалярное обращение к mmap стоит не чтения, а обёртки: numpy на каждое
    строит объект-массив и сразу его разбирает. Пачкой те же элементы читаются
    одним индексированием, а дальше идёт обычный питоновский список.

    Значения ТЕ ЖЕ до последнего бита: это те же элементы тех же колонок,
    прочитанные другим порядком вызовов."""
    n = len(номера)
    if n == 0:
        return []
    номера = np.asarray(номера, dtype=np.int64)
    span_a = np.asarray(idx.span_a)[номера].tolist()
    span_b = np.asarray(idx.span_b)[номера].tolist()
    key_id = np.asarray(idx.key_id)[номера].tolist()
    syl = np.asarray(idx.syl)[номера].tolist()
    mat = np.asarray(idx.mat)[номера].tolist()
    clau = np.asarray(idx.clau)[номера].tolist()
    t_off = np.asarray(idx.text_off)
    t_a, t_b = t_off[номера].tolist(), t_off[номера + 1].tolist()
    l_off = np.asarray(idx.lem_off)
    l_a, l_b = l_off[номера].tolist(), l_off[номера + 1].tolist()
    blob, lem_ids = idx.blob, idx.lem_ids
    ключи, леммы = idx.keys, idx.lemmas
    строки = []
    for k in range(n):
        a = span_a[k]
        row = {"text": blob[t_a[k]:t_b[k]].tobytes().decode("utf-8"),
               "template": "nakedlunch", "meter": None,
               "rhyme": ключи[key_id[k]],
               "rhyme_span": None if a < 0 else [a, span_b[k]],
               "syllables": syl[k], "score": float(оценки[k]),
               "_lem": {леммы[x] for x in lem_ids[l_a[k]:l_b[k]].tolist()},
               "mat": bool(mat[k]),
               "clausula": clau[k],
               "classic": light}
        if not light:
            row["_pctl"] = float(перцентили[k])
        строки.append(row)
    return строки


def _row(idx, i, score, pctl, light=False):
    """Строка выдачи ровно той формы, что собирал старый путь (после того как
    он удалял служебные _literal/_forced/_forced_hits).

    У «классики» поля `_pctl` нет СОЗНАТЕЛЬНО, а не по забывчивости: по его
    наличию `_select_with_rhyme` отличает строку алгоритмического яруса от
    классической (см. `if "_pctl" not in cand` там же). Появись он у
    классики — она попала бы в тематический якорь, которого у неё по
    определению нет."""
    a, b = int(idx.span_a[i]), int(idx.span_b[i])
    row = {"text": idx.text(i), "template": "nakedlunch", "meter": None,
           "rhyme": idx.keys[int(idx.key_id[i])],
           "rhyme_span": None if a < 0 else [a, b],
           "syllables": int(idx.syl[i]), "score": score, "_lem": idx.lemma_set(i),
           # Раунд 39: мат — доля, а не запрет, поэтому признак нужен КАЖДОЙ
           # строке, а не только воротам. Читаем из колонки индекса, считать
           # регуляркой заново незачем (см. filters._select_with_rhyme).
           "mat": bool(idx.mat[i]),
           "clausula": int(idx.clau[i]),
           "classic": light}
    if not light:
        row["_pctl"] = pctl
    return row


def select_light(idx, *, pool_mask, hidden_mask, no_mat, only_mat, clausula, cap, seed=None):
    """«Классика» = изначальный нейкедланч: случайные куски активного пула.

    РАУНД 35. Раньше она отключала только мнения extendo о качестве
    (банальность, тавтология, клише), но продолжала считать релевантность
    теме и подчиняться вилке слогов. Требование (2026-08-02): классика работает как изначальный nakedlunch — без фильтров и
    без настроек.. Изначальный (`nlsrc/generator.generate_four`)
    делает ровно `rng.sample(pool, 4)` — поэтому здесь нет ни темы, ни
    оценки: у всех строк оценка одна, и верхушка вырождается в равномерно
    случайную выборку. Аргументы `tags`/`sims`/`syllable_spec` убраны
    СОЗНАТЕЛЬНО — оставить их значило бы держать дверь, в которую по
    определению режима входить нельзя.

    Остаются ограничения, и ни одно из них не мнение о качестве: активный пул
    (какие книги включены), история (не показывать дважды), доля мата и чёрный
    список — явные запросы пользователя на содержание.

    ЧЁРНЫЙ СПИСОК ЗДЕСЬ ОБЯЗАН ДЕЙСТВОВАТЬ (Раунд 59). Он тут не применялся:
    старый список вырезали в Раунде 35 как бесполезный, новый (Раунд 57) в этот
    путь не дописали. Получалось, что слово, запрещённое навсегда, возвращалось
    в выдачу при переключении режима — и объяснить это пользователю нечем.
    Мат в классике применяется по той же логике, по какой должен применяться
    список: это не оценка качества, а сказанное вслух «мне такого не надо»."""
    rng = np.random.default_rng(seed)
    if no_mat:
        table_ids = np.flatnonzero(np.asarray(idx.mat) == 0)
    elif only_mat:
        table_ids = np.flatnonzero(np.asarray(idx.mat) != 0)
    else:
        table_ids = np.arange(idx.n, dtype=np.int64)
    if clausula:
        table_ids = table_ids[np.asarray(idx.clau)[table_ids] == clausula]
    # Обрывки дефисных слов отсеиваются и здесь (Раунд 51). Это не мнение о
    # качестве, а брак нарезки: «нибудь гнусность скрывается» — не сырьё, а
    # разорванное пополам слово. Классика подчиняется воротам, а это ворота.
    table_ids = table_ids[idx.whole_mask()[table_ids]]
    з = запрет(_правила())
    if з["маска"] is not None:
        table_ids = table_ids[~з["маска"][table_ids]]
    ids = table_ids[pool_mask[table_ids] & ~hidden_mask[table_ids]]
    n_survived = int(len(ids))
    # Ступени той же формы, что у `select` (Раунд 62): у ответа один вид на обеих
    # ветках, иначе разбирающему пришлось бы гадать, какой ярус перед ним. Здесь
    # «жребий» — не фигура речи: это буквально `rng.choice` ниже.
    счёт = {"корпус": int(idx.n), "ворота": int(len(table_ids)), "пул": n_survived,
            "тема_буквально": 0, "резерв": 0, "предел_жребия": int(cap)}
    if n_survived == 0:
        return [], 0, {**счёт, "жребий": 0, "в_сборку": 0}
    k = min(cap, n_survived)
    взято = rng.choice(n_survived, size=k, replace=False)
    return ([_row(idx, int(ids[j]), 0.6, 0.0, light=True) for j in взято],
            n_survived, {**счёт, "жребий": int(k), "в_сборку": int(k)})


# ---- маски пула и истории -------------------------------------------------
# Индекс знает корпус, но не знает, какие источники включены и что уже
# показывалось: и то и другое живёт снаружи и меняется между запросами.
# Переводим их в маски по номерам фрагментов.

_text_ids: dict | None = None
_text_lock = threading.Lock()
_pool_cache: tuple | None = None


def text_ids(idx) -> dict:
    """Карта «текст → номер». Строится один раз на процесс и живёт: без неё
    не перевести список активного пула в номера. Память — сотни МБ, против
    5.5 ГБ, которые снимает сам индекс.

    Замер 2026-08-02: на 2.87 млн записей это 9.8 с, и раньше их платил
    ПЕРВЫЙ запрос генерации в процессе — то есть пользователь, а не старт. Теперь
    старт греет её фоном (warm_background), а замок нужен, чтобы запрос,
    пришедший в разгар прогрева, встал в очередь, а не строил вторую такую
    же карту рядом."""
    global _text_ids
    with _text_lock:
        if _text_ids is None:
            _text_ids = {idx.text(i): i for i in range(idx.n)}
        return _text_ids


_lag_cache: tuple | None = None      # (сколько подали, ответ)


def lag(texts, total: int) -> int | None:
    """Сколько ТЕКСТОВ не попало в колоночный индекс.

    ПОЧИНКА ПОЧИНКИ. Первая версия считала разницей `фрагментов − строк
    индекса` — «дёшево и про то же». Оказалось не про то же и не дёшево по
    смыслу: на машине пользователя 2 874 175 фрагментов, но лишь 2 856 289
    РАЗНЫХ текстов (17 886 дублей), а строк в индексе 2 868 100 — там ещё
    живут тексты удалённых источников. Разница дала «6 075 строк вне индекса»
    при том, что вне его НОЛЬ. То есть строка, заведённая против вранья,
    начала врать сама.

    Точный ответ стоит 0.4 с (замер 2026-08-04) — карта «текст → номер» и так
    греется на старте, и по ней это просто 2.87 млн проверок в словаре.
    Дорогими были 13 с из первого замера: там я строил карту заново.

    None — карта ещё греется. Сказать «считаю» честнее, чем назвать число,
    которого не знаешь; ждать здесь нельзя — это поток HTTP-запроса."""
    global _lag_cache
    if _lag_cache is not None and _lag_cache[0] == total:
        return _lag_cache[1]
    idx = load()
    if idx is None:
        return total          # индекса нет — вне его всё; не кэшируем, он может появиться
    if _text_ids is None:
        return None           # греется
    ответ = sum(1 for t in texts if t not in _text_ids)
    _lag_cache = (total, ответ)
    return ответ


def forget() -> None:
    """Забыть загруженный индекс и все производные карты. Отдельно от
    `reload`, потому что это единственная СИНХРОННАЯ и проверяемая часть:
    `reload` следом пускает фоновый прогрев, и сразу после него состояние
    модуля уже меняется под руками."""
    global _idx, _tried, _text_ids, _pool_cache, _lag_cache
    with _text_lock:
        _idx = None
        _tried = False
        _text_ids = None
    _pool_cache = None
    _lag_cache = None
    забыть_таблицу()


def reload() -> None:
    """Забыть загруженный индекс и прогреть заново — зовётся ПОСЛЕ перепечи
    (Раунд 52).

    Без этого свежеиспечённый индекс не увидели бы до перезапуска: `_idx`
    живёт всю жизнь процесса, а карта «текст → номер» и подавно. Именно на
    этом ломалась загрузка книги: строки нового источника попадали в кэш
    рифм, но не в колонки, а `mask_of` молча пропускает всё, чего в индексе
    нет — то есть книга была в списке источников и не участвовала в выдаче.

    Старый mmap переживает перепечь: скрипт пишет во временный каталог и
    переименовывает, а отвязанные файлы живут, пока на них есть ссылки. То
    есть до этого вызова процесс честно читает ПРЕЖНИЙ индекс, а не мусор.

    Прогрев обязателен: карта «текст → номер» стоит 9.8 с, маска целостности
    ещё 9.2 с, и без фонового прогрева их заплатила бы ПЕРВАЯ генерация после
    перепечи — то есть пользователь."""
    forget()
    warm_background()


def форма_пула(idx, *, pool_mask, hidden_mask, ворота, no_mat=False, only_mat=False,
               clausula=0) -> dict:
    """Из ЧЕГО сейчас будет выбираться — до нажатия «сгенерировать».

    ЗАЧЕМ ИМЕННО ЭТО. Замер 3.7: живого предпросмотра выдачи нет и не будет —
    прогон стоит 185 мс без темы и 878 мс с темой, а подвыборка пула отвергнута
    (дорогие ступени считаются по всему корпусу, пул только маскирует потом).
    Значит осязание до нажатия несёт не выдача, а ФОРМА ПУЛА, и она дёшева.

    ЧТО ПОКАЗЫВАТЬ — ТОЖЕ ЗАМЕРЕНО, а не выбрано на глаз. Из восьми возможных
    форм живы три:
      · сколько строк осталось — размах 98× по ходу ручки (18 266 … 1 780 408);
      · рифмо-ключи — 2 257 … 37 653; это единственное, что предсказывает
        «соберётся ли рифмованная строфа вообще»;
      · категории редкости — узнаваемые куски корпуса (6 / 70 / 12 / 12%).
    Остальные пять мертвы и здесь их нет НАРОЧНО: гистограмма слогов на правой
    половине ручки двигает крупнейший столбец на 0.42 п.п., клаузула на 1.6,
    книги стоят на месте кроме крайнего левого положения, у сцепки 71.6% пула в
    одном столбце, а доля мата не превышает 0.8% и как полоска невидима.
    Показывать форму, которая не меняется, — врать движением.

    Числа считаются по ТОМУ ЖЕ пересечению, что и генерация (ворота ∩ активный
    пул ∩ не показанное): форма, посчитанная по другому множеству, обещала бы
    не то, что придёт."""
    gate = idx.gate_mask(ворота, no_mat, only_mat, clausula)
    живые = np.flatnonzero(gate & pool_mask & ~hidden_mask)
    n = int(len(живые))
    итог = {"строк": n}
    if n == 0:
        return {**итог, "ключей": 0, "крупнейшая_корзина": 0, "редкость": {}}

    ключи = np.asarray(idx.key_id)[живые]
    счёт = np.bincount(ключи[ключи >= 0])
    итог["ключей"] = int(np.count_nonzero(счёт))
    итог["крупнейшая_корзина"] = int(счёт.max()) if счёт.size else 0
    # ЗДЕСЬ СТОЯЛО «сколько строк могут с кем-то срифмоваться», и это оказалось
    # мёртвым числом: 95.5–99.6% при любом положении ручки. На пуле в полтора
    # миллиона почти у каждой строки есть однокорзинник — нехватка пар возникает
    # ПОСЛЕ жребия, когда из миллиона осталось триста. Значит и считать её надо
    # там: см. `ступени["в_парах"]` в filters.run.

    b = np.asarray(idx.banal)[живые]
    полосы = {
        "вне словаря": b == 0.0,
        "редкое": (b > 0.0) & (b <= 2.0),
        "обычное": (b > 2.0) & (b <= 4.5),
        "затёртое": b > 4.5,
    }
    итог["редкость"] = {имя: int(м.sum()) for имя, м in полосы.items()}
    # ПРИМЕРЫ — ЭТО И ЕСТЬ «РАЗНИЦА» (пункт плана 3.6, Раунд 62).
    #
    # Изначально разница задумывалась как «три ушедшие, три пришедшие» у края
    # ручки. Замер это закрыл: ворота монотонны по ходу ручки, поэтому каждый
    # шаг либо ТОЛЬКО убирает, либо ТОЛЬКО добавляет — двух колонок не бывает.
    # А одна колонка почти ничего не сообщает: слепой тест на ушедших и
    # оставшихся дал 28 из 44, то есть 64% при случайных 50%.
    #
    # Различимы не КРАЯ, а КАТЕГОРИИ: «Отвещаша ему иудее, глаголюще» против
    # «то есть тех, кто жив» видно с первого взгляда. Поэтому показываем не
    # рант ползунка, а содержимое полосы — по три строки, и пусть выбирает
    # глазами. Цена: три `idx.text` на полосу, доли миллисекунды.
    # Примеры ищем в ПОДВЫБОРКЕ, а не по всей полосе: материализовать четыре
    # массива по миллиону номеров стоило 10 мс из 19, а для трёх примеров это
    # незачем. Счётчики выше остаются точными — они одним проходом.
    # Выборка СЛУЧАЙНАЯ с закреплённым семенем, а не «каждый n-й»: номера идут
    # по книгам подряд, и равномерный шаг давал бы три строки одного автора.
    # `integers`, а не `choice(replace=False)`: второй строит перестановку на
    # весь пул и стоил 16 мс из 25. Для трёх примеров повторы безвредны.
    _rng = np.random.default_rng(20260813)
    сколько = min(6000, n)
    проба = живые if n <= сколько else живые[_rng.integers(0, n, сколько)]
    b_пробы = np.asarray(idx.banal)[проба]
    примеры: dict = {}
    for имя, _ in полосы.items():
        м = {"вне словаря": b_пробы == 0.0,
             "редкое": (b_пробы > 0.0) & (b_пробы <= 2.0),
             "обычное": (b_пробы > 2.0) & (b_пробы <= 4.5),
             "затёртое": b_пробы > 4.5}[имя]
        где = проба[м]
        примеры[имя] = [idx.text(int(i)) for i in где[:3]]
    итог["примеры"] = примеры
    return итог


def прогреть(idx) -> None:
    """Всё, что генерация считает ОДИН РАЗ и потом берёт из кэша.

    ОДНО МЕСТО НА ВСЕХ — И ЭТО НЕ АККУРАТНОСТЬ, А ПОЧИНКА. Список грелся в двух
    местах сразу (здесь и в api/server.py), и оба раза он отставал от того, что
    генерация на самом деле считает:

      · Раунд 51 — забыли маску целостности, 9.2 с платила первая генерация;
      · Раунд 62 — забыли МАСКУ ЧЁРНОГО СПИСКА, и это **17.4 секунды**
        (замерено 2026-08-13, четыре правила по 2.4 млн фрагментов). То есть
        каждый запуск приложения стоил пользователю семнадцати секунд ожидания
        на первой же генерации, при том что «прогрев завершён» уже написано.

    Поэтому греем НЕ список колонок, а `gate_mask` целиком — то самое, что
    зовёт генерация. Забыть отдельную ступень тут физически нечего: если
    появится новая, она попадёт сюда сама.

    Стоимость после прогрева: 2–6 мс на вызов."""
    text_ids(idx)
    idx.whole_mask()
    # Отпечаток состава — 44.5 мс замерено, дальше 0.002. Он идёт в каждый
    # ответ (штамп прогона), то есть его платила бы первая генерация: тот же
    # промах, что с маской чёрного списка, только в сорок раз дешевле.
    idx.отпечаток()
    # Ворота с самыми широкими порогами: маска чёрного списка и все колонки
    # ворот строятся здесь, а не у пользователя. Положение ручки не важно —
    # дорого именно первое касание, а не пороги.
    idx.gate_mask(ворота_банальности(0.5), False, False, 0)
    # КАРТА НАЧАЛЬНЫХ ФОРМ — ЗДЕСЬ, А НЕ У ПОЛЬЗОВАТЕЛЯ (2026-08-18).
    #
    # Она печётся на диск (`формы.bin`) и живёт ВНУТРИ каталога индекса —
    # нарочно: карта не имеет права пережить индекс, которому не соответствует.
    # Значит любая перепечка её сносит, и первый же процесс после перепечки
    # платит разбор 231 837 словоформ через pymorphy: **15.4 секунды**
    # (замерено). Без этой строки платил бы их человек — первым правилом
    # чёрного списка, которое он добавит.
    #
    # Ровно тот же промах, что с маской целостности (9.2 с) и маской чёрного
    # списка (17.4 с), и лечится он тем же: греем то, что зовёт работа, и
    # держим список в ОДНОМ месте — здесь, а не в роуте.
    try:
        _карта_форм(idx)
    except Exception:
        pass          # прогрев — удобство, а не работа: молча уступаем


def warm_background() -> None:
    """Прогреть индекс фоновым потоком (зовётся со старта сервера). Индекса нет
    или он чужой версии — молча выходим: генерация тогда идёт старым путём, и
    греть нечего."""
    def работа():
        try:
            idx = load()
            if idx is not None:
                прогреть(idx)
        except Exception:
            pass   # прогрев — удобство, а не обязанность: молчит и не мешает
    threading.Thread(target=работа, name="nlindex-warm", daemon=True).start()


def mask_of(idx, texts) -> np.ndarray:
    m = np.zeros(idx.n, dtype=bool)
    tid = text_ids(idx)
    for s in texts or ():
        i = tid.get(s)
        if i is not None:
            m[i] = True
    return m


def pool_mask(idx, pool) -> np.ndarray:
    """Маска активного пула с кэшем. Ключ — длина плюс первый и последний
    элемент: пул пересобирается на каждый запрос, но МЕНЯЕТСЯ только когда
    пользователь трогает источники, и любое такое изменение сдвигает длину.
    Совпадение всех трёх при разном содержимом теоретически возможно —
    поэтому это кэш, а не истина: ошибка стоила бы устаревшей маски до
    следующего изменения пула, не порчи данных."""
    global _pool_cache
    ключ = (len(pool or ()), (pool[0] if pool else ""), (pool[-1] if pool else ""))
    if _pool_cache is not None and _pool_cache[0] == ключ:
        return _pool_cache[1]
    m = mask_of(idx, pool)
    _pool_cache = (ключ, m)
    return m


def forget_pool() -> None:
    """Сбросить кэш маски пула — зовётся при добавлении/удалении источника."""
    global _pool_cache
    _pool_cache = None


