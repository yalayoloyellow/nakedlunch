# выключением соответствующей книги. См. план, часть 6.


class Index:
    """Колонки корпуса. Массивы открыты через mmap: старт не платит разбор
    файла, а память растёт страницами по факту обращения — именно это снимает
    5.5 ГБ RSS и своп-налог на всё остальное."""

    def __init__(self, d: Path):
        meta = json.loads((d / "meta.json").read_text("utf-8"))
        self.n = int(meta["n"])
        self.rules = meta.get("rules", "")
        self.built_at = meta.get("built_at", "")
        self.keys = meta.get("keys") or []
        self.lemmas = meta.get("lemmas") or []
        self.tokens = meta.get("tokens") or []
        load = lambda name: np.load(d / f"{name}.npy", mmap_mode="r")  # noqa: E731
        self.banal = load("banal")
        self.taut = load("taut")
        self.mat = load("mat")
        self.syl = load("syl")
        self.key_id = load("key_id")
        self.span_a = load("span_a")
        self.span_b = load("span_b")
        self.lem_ids = load("lem_ids")
        self.lem_off = load("lem_off")
        self.lem2navec = load("lem2navec")
        self.tokpost = load("tokpost")
        self.tokoff = load("tokoff")
        self.text_off = load("text_off")
        # КОЛОНКА ИСТОЧНИКА (Раунд 57). Может отсутствовать у индекса, испечённого
        # до этого раунда — тогда None, и всё работает как раньше: источник это
        # новая возможность, а не новое требование.
        try:
            self.src = load("src")
        except Exception:
            self.src = None
        try:
            self.content = load("content")
        except Exception:
            self.content = None
        # ДВЕ КОЛОНКИ РЕДКОСТИ (2026-08-26). Процентиль строки среди строк:
        # 0 — самые нередкие, 100 — самые редкие, −1 — шкалы у строки нет.
        # Формула и разбор — в `core/редкость.py`. Могут отсутствовать у
        # индекса, испечённого раньше: тогда ручка просто не отбирает, а всё
        # остальное работает как работало.
        try:
            self.rare_word = load("rare_word")
        except Exception:
            self.rare_word = None
        try:
            self.rare_pair = load("rare_pair")
        except Exception:
            self.rare_pair = None
        # СЦЕПКА СОСЕДНИХ СЛОВ (Раунд 58) — вторая ось ручки «Банальность»,
        # см. tools/build_nl_index.py: сцепка_колонка. Может отсутствовать у
        # индекса, испечённого раньше: тогда ручка работает одной осью, как
        # работала, и ничего не падает.
        try:
            self.bind = load("bind")
        except Exception:
            self.bind = None
        # НАДГРОБИЕ: `кванты_банальности` больше не читаются (2026-08-20).
        # Они задавали шкалу ручки «Банальность»; ручка удалена целиком — см.
        # надгробие выше. Как и `кванты_сцепки` (Раунд 62), в meta.json они
        # остаются: индекс не перепекается, лишнее поле там никому не мешает.
        self.sources = meta.get("sources") or []
        # ПУСТОЙ ИНДЕКС ЗАГРУЖАЕТСЯ (2026-08-18). `np.memmap` не умеет пустой
        # файл — «cannot mmap an empty file», проверено, — а индекс на ноль
        # строк это законный результат сборки на пустом корпусе. Раньше
        # исключение глотал `load()`, и n=0 становился неотличим от «индекса
        # нет вовсе»: та же тишина на два разных состояния. Пустой блоб —
        # пустой массив; остальные колонки пустыми грузятся сами (`np.load`
        # с mmap_mode на нулевом .npy отдаёт форму (0,), проверено).
        блоб = d / "text_blob.bin"
        self.blob = (np.memmap(блоб, dtype=np.uint8, mode="r")
                     if блоб.stat().st_size else np.zeros(0, dtype=np.uint8))
        self._tok_id: dict[str, int] | None = None
        self._отпечаток: str | None = None
        # производные, считаются один раз на процесс
        self._lem_len = np.diff(np.asarray(self.lem_off))
        nav = np.asarray(self.lem2navec)[np.asarray(self.lem_ids)]
        self._lem_valid = nav >= 0
        self._lem_navec = np.maximum(nav, 0)
        # Клаузула фрагмента (Раунд 44) — из его же рифмо-ключа, без новых
        # данных и без пересборки индекса: ключ начинается с ударной гласной,
        # значит число гласных в нём и есть слог от конца (см. scan.clausula).
        import scan as _scan
        по_ключу = np.array([_scan.clausula(k) for k in self.keys], dtype=np.int8) \
            if self.keys else np.zeros(0, dtype=np.int8)
        self.clau = по_ключу[np.asarray(self.key_id)] if len(по_ключу) else np.zeros(self.n, dtype=np.int8)

    # ---- тексты ----
    def text(self, i: int) -> str:
        a, b = int(self.text_off[i]), int(self.text_off[i + 1])
        return self.blob[a:b].tobytes().decode("utf-8")

    def texts(self, ids) -> list[str]:
        return [self.text(int(i)) for i in ids]

    # ---- кто эти строки ----
    def отпечаток(self) -> str:
        """Отпечаток СОСТАВА, а не сборки.

        Семя воспроизводит прогон, пока строки те же и в том же порядке. Раньше
        это судилось по времени сборки (`built_at`), и любая перепечка объявляла
        ВСЕ записанные номера прогонов устаревшими — даже пересчёт одной
        колонки, при котором ни одна строка не сдвинулась. Врать в эту сторону
        не безобиднее, чем в другую: приложение зря говорило «номер снят с
        прежнего корпуса» и обесценивало то, что цело.

        Судим по самим строкам:
          • `n` — сколько их;
          • `text_off` целиком — длина КАЖДОЙ строки и её место в блобе. Любая
            вставка, удаление и перестановка сдвигают хвост смещений;
          • `key_id` целиком — рифмо-ключ каждой строки, то есть её последнее
            слово. Правка, меняющая текст, почти всегда трогает конец (ровно это
            делает ретро-подрезка обрывков), а конец здесь виден весь;
          • 64 текста через равные промежутки — выборочная сверка содержимого.

        ЧЕГО ЭТО НЕ ЛОВИТ, СКАЗАНО ПРЯМО: подмену строки на другую ТОЙ ЖЕ длины
        и с тем же рифмо-ключом, если она не попала в выборку из 64. Такой
        правки в конвейере нет ни одной, но отпечаток — [С], самоделка, и
        выдавать её за доказательство нельзя.

        Полный блоб (1.6 ГБ) нарочно не хешируется: он стоил бы секунду с
        лишним на первой же генерации — ровно тот налог, который в этом раунде
        сняли с прогрева. Цена нынешнего замерена на полном индексе
        (2 434 632 строки): **44.5 мс** первый раз, 0.002 дальше, и первый раз
        платит прогрев, а не пользователь."""
        if self._отпечаток is None:
            h = hashlib.blake2b(digest_size=8)
            h.update(f"{self.n}:".encode())
            h.update(np.asarray(self.text_off).tobytes())
            h.update(np.asarray(self.key_id).tobytes())
            шаг = max(1, self.n // 64)
            for i in range(0, self.n, шаг):
                h.update(self.text(int(i)).encode("utf-8"))
            self._отпечаток = h.hexdigest()
        return self._отпечаток

    def lemma_set(self, i: int) -> set:
        a, b = int(self.lem_off[i]), int(self.lem_off[i + 1])
        # tolist() одним куском: обход среза mmap поэлементно давал сотни тысяч
        # вызовов __getitem__ на запрос (замерено профайлером)
        return {self.lemmas[x] for x in self.lem_ids[a:b].tolist()}

    # ---- маски ----
    # Обрывки дефисных слов (Раунд 51). Нарезчик годами резал по обычному
    # дефису наравне с тире: «какая-нибудь» → «какая» + «нибудь», «из-за» →
    # «из» + «за». Регулярка в core/nlsrc/cutter.py починена, но 1.34% УЖЕ
    # нарезанного пула — обрывки: 26 263 фрагмента на 1.96 млн. По слогам и
    # клаузуле они безупречны, поэтому отбор их любит, а на слух это мусор
    # («нибудь гнусность скрывается» — реальная строка из документа пользователя).
    #
    # Здесь ВОРОТА, а не удаление: данные пользователя не трогаем, маска строится
    # один раз и живёт в памяти. Перенарезать источники — отдельное решение,
    # оно за ним.
    #
    # Списки закрытые и проверенные на ложные срабатывания: «мало» и «какой»
    # выброшены — ими фраза законно кончается («и все мало», «Воздух-то какой»).
    _ОБРЫВОК_НАЧАЛО = re.compile(r"^\s*(нибудь|либо|таки)\b", re.I)

    # ОБОРВАННАЯ ФРАЗА (Раунд 58). В выдаче на максимальной свежести встречалось: «в этих сладостных битвах... В», «чтобы всё познать. Я не»,
    # «моих криков: О». Строка кончается словом, которое обязано что-то
    # присоединять, а присоединять нечего — нарезчик разрезал фразу пополам.
    #
    # ПОЧЕМУ ЭТО ЛЕЗЕТ ИМЕННО В СВЕЖУЮ ВЫДАЧУ. Целая русская фраза почти всегда
    # содержит хоть одно затасканное сочетание. Обрубок — нет: он и по редкости
