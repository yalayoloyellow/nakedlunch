#
# Обе статьи лечит ОДНА мысль: начальная форма каждой словоформы индекса уже
# посчитана при построении карты. Значит её надо (а) не считать заново в
# следующем процессе — кладём рядом с индексом, (б) не считать заново для слов
# строк — 100% слов строк есть в словаре индекса (замерено на всех кандидатах
# «ДЕ СЕНТ-АНЖ»: 8752 из 8752), значит памятка «слово → начальная форма»
# закрывает их целиком, а редкое непопадание честно уходит в тот же
# `морф.parse`. Тождество здесь не обещание, а свойство: памятка ОТДАЁТ РОВНО
# ТО, ЧТО В НЕЁ ПОЛОЖИЛ ТОТ ЖЕ ВЫЗОВ.

# (индекс, карта форм, памятка слово→начальная форма)
_ФОРМЫ_КЭШ: tuple | None = None

# Печёная карта форм лежит В КАТАЛОГЕ ИНДЕКСА, и это не случайность: сборщик
# пишет каталог целиком через временный и переставляет (tools/build_nl_index.py),
# поэтому перепечка индекса уносит и её — протухнуть физически негде.
ФОРМЫ_ФАЙЛ = "формы.bin"


def _формы_подпись(idx) -> str:
    """Чему обязана соответствовать печёная карта, чтобы её можно было взять.

    Индекс — свой (число строк, число словоформ, время сборки). Морфология —
    своя: обновление pymorphy или его словаря МЕНЯЕТ начальные формы, и молча
    отдать вчерашние значило бы, что чёрный список тихо работает по прежней
    морфологии. Версии берём из модулей, а не из разбора: `import` стоит 0.036 с,
    создание анализатора — 0.105 с, и платить их на попадании незачем."""
    try:
        import pymorphy3
        import pymorphy3_dicts_ru
        морфология = f"{pymorphy3.__version__}/{pymorphy3_dicts_ru.__version__}"
    except Exception:
        морфология = "?"
    return f"нф1\t{idx.n}\t{len(idx.tokens)}\t{idx.built_at}\t{морфология}"


def _формы_с_диска(idx) -> list[str] | None:
    """Начальные формы словаря индекса, испечённые прошлым процессом, или None.

    Замерено: чтение и разбор файла 0.018 с против 15.4 с разбора заново."""
    try:
        сырое = (INDEX_DIR / ФОРМЫ_ФАЙЛ).read_bytes().decode("utf-8")
    except (OSError, ValueError):
        return None
    подпись, _, тело = сырое.partition("\n")
    if подпись != _формы_подпись(idx):
        return None
    формы = тело.split("\n")
    # Длина — не украшение, а проверка целостности: обрыв записи или словоформа
    # с переводом строки внутри дадут другое число, и мы честно пересчитаем.
    return формы if len(формы) == len(idx.tokens) else None


def _формы_на_диск(idx, формы: list[str]) -> None:
    """Отложить карту следующему процессу. Молча не смогли — не беда: кэш это
    ускорение, а не условие работы (каталог может быть только для чтения)."""
    try:
        тело = _формы_подпись(idx) + "\n" + "\n".join(формы)
        врем = INDEX_DIR / (ФОРМЫ_ФАЙЛ + ".новый")
        врем.write_bytes(тело.encode("utf-8"))
        os.replace(врем, INDEX_DIR / ФОРМЫ_ФАЙЛ)   # целиком или никак
    except OSError:
        pass


def _карта_форм(idx) -> dict:
    """Начальная форма → номера ВСЕХ словоформ индекса, которые к ней приводятся.

    ПОЧЕМУ НЕ ПО КОЛОНКЕ ЛЕММ. Первая версия искала по ней и дала «с» → ноль:
    разбор оставляет в леммах только знаменательные слова, предлогов там нет
    вовсе. А требование: правило «с» убирает строки, где «с» стоит отдельным словом, и не трогает
    слова, внутри которых эта буква есть..

    Словарь словоформ индекса хранит слова как есть и ЦЕЛИКОМ — «с» там есть, а
    внутрь «список» оно не попадёт, потому что это другой токен. Приводим каждую
    словоформу к начальной форме один раз на процесс и получаем оба свойства
    сразу: склонения ловятся, подстроки — нет.
    """
    global _ФОРМЫ_КЭШ
    if _ФОРМЫ_КЭШ is not None and _ФОРМЫ_КЭШ[0] is idx:
        return _ФОРМЫ_КЭШ[1]
    _забыть_индекс(idx)
    формы = _формы_с_диска(idx)
    if формы is None:
        from corpus import _morph
        морф = _morph()
        формы = []
        for слово in idx.tokens:
            try:
                формы.append(морф.parse(слово)[0].normal_form)
            except Exception:
                формы.append(слово)
        _формы_на_диск(idx, формы)
    карта: dict[str, list[int]] = {}
    памятка: dict[str, str] = {}
    for i, (слово, нф) in enumerate(zip(idx.tokens, формы)):
        карта.setdefault(нф, []).append(i)
        if нф != слово:
            карта.setdefault(слово, []).append(i)
        памятка[слово] = нф
    _ФОРМЫ_КЭШ = (idx, карта, памятка)
    return карта


def _нф(idx, слово: str) -> str:
    """Начальная форма слова. Через памятку словаря индекса, а мимо неё — тем
    же самым `морф.parse`, каким памятка и набита."""
    _карта_форм(idx)
    нф = _ФОРМЫ_КЭШ[2].get(слово)
    if нф is not None:
        return нф
    from corpus import _morph
    try:
        return _morph().parse(слово)[0].normal_form
    except Exception:
        return слово


def _формы_слова(idx, слово: str) -> list[int]:
    """Номера словоформ индекса для одного слова правила: оно само и все его
    склонения."""
    низ = слово.lower()
    нф = _нф(idx, низ)
    карта = _карта_форм(idx)
    номера = set(карта.get(нф, ())) | set(карта.get(низ, ()))
    return sorted(номера)


def _строки_форм(idx, номера: list[int]) -> np.ndarray:
    """Строки, где встречается хоть одна из перечисленных словоформ."""
    куски = []
    for tid in номера:
        куски.append(np.asarray(idx.tokpost[idx.tokoff[tid]:idx.tokoff[tid + 1]]))
    if not куски:
        return np.empty(0, dtype=np.int64)
    return np.unique(np.concatenate(куски))


def строки_правила(idx, правило: str) -> np.ndarray:
    """Номера строк, попавших под одно правило.

    Слово — все его словоформы. Словосочетание — сперва пересечение по всем
    словам, и уже на коротком списке кандидатов проверка, что слова идут ПОДРЯД
    и в нужном порядке.
    """
    if idx is None:
        return np.empty(0, dtype=np.int64)
    слова = _подряд(правило)
    if not слова:
        return np.empty(0, dtype=np.int64)

    наборы = [_формы_слова(idx, w) for w in слова]
    if any(not н for н in наборы):
        return np.empty(0, dtype=np.int64)      # такого слова в корпусе нет вовсе

    кандидаты = _строки_форм(idx, наборы[0])
    for н in наборы[1:]:
        кандидаты = np.intersect1d(кандидаты, _строки_форм(idx, н), assume_unique=True)
        if not len(кандидаты):
            return кандидаты
    if len(слова) == 1:
        return кандидаты

    # ПОДРЯД И В ПОРЯДКЕ. Сверяем по НАЧАЛЬНЫМ ФОРМАМ, а не по написанию:
    # «госпожа де сент-анж» обязано ловить и «госпожи де сент-анж».
    #
    # Формы берём из памятки словаря индекса, а не разбором на месте: разбор
    # здесь стоил 0.89 с на правило (8 752 слова кандидатов по 101.7 мкс),
    # памятка — 0.0014 с при том же до последнего слова ответе. Слова строк —
    # это ровно словоформы индекса, поэтому промахов на живом корпусе нет
    # вовсе, а промах и не страшен: `_нф` уходит в тот же `морф.parse`.
    _карта_форм(idx)
    памятка = _ФОРМЫ_КЭШ[2]
    нф = [_нф(idx, w) for w in слова]
    подошли = []
    нет = object()          # не `or`: пустая строка — тоже законный ответ памятки
    for i in кандидаты.tolist():
        ряд = []
        for чист in _подряд(idx.text(int(i))):
            готово = памятка.get(чист, нет)
            ряд.append(_нф(idx, чист) if готово is нет else готово)
        for j in range(len(ряд) - len(нф) + 1):
            if ряд[j:j + len(нф)] == нф:
                подошли.append(i)
                break
    return np.asarray(подошли, dtype=np.int64)


def запрет(правила: list[str], idx=None) -> dict:
    """Маска запрещённых строк и счётчик на каждое правило.

    ИНДЕКС — АРГУМЕНТОМ, КАК У ВСЕХ СОСЕДЕЙ (2026-08-18). Раньше он брался
    здесь заново из `load()`, и это была половина отказа «operands could not be
    broadcast together»: `gate_mask` считала колонки по `self`, а маску
    запрета получала от ДРУГОГО индекса — того, что лежал в модуле на момент
    вызова. Стоило перепечь индекс на живом сервере, и длины переставали
    сходиться. Маска чёрного списка — это номера строк, то есть свойство
    КОНКРЕТНОГО индекса; спрашивать её «вообще» бессмысленно.

    `None` оставлен для вызывающих, у которых индекса под рукой нет (роут
    правки списка в api/server.py, тесты): им нужен счёт по текущему, и они
    берут его тем же `load()`, что и раньше.

    Кэш по самому списку: правила меняются редко, а спрашивают маску на каждой
    генерации. Пересчёт идёт только когда список действительно другой.

    ПРАВКА СПИСКА НЕ ПЕРЕСЧИТЫВАЕТ ОСТАЛЬНЫЕ ПРАВИЛА. Кэш был один на весь
    список, и добавление двадцатого правила заново считало девятнадцать
    посчитанных: замерено 9.3 с на одно нажатие. Держим строки КАЖДОГО правила
    отдельно — правило от списка не зависит, оно зависит только от индекса.
    Тогда добавление стоит одно новое правило, а маска складывается заново из
    готовых кусков (0.0001 с на правило, замерено).

    УДАЛЕНИЕ РАБОТАЕТ ТЕМ ЖЕ ХОДОМ, и это не совпадение, а причина так делать.
    Соблазн был наложить новое правило на прежнюю маску: добавление ведь только
    СУЖАЕТ выдачу. Но тогда удаление пришлось бы считать честно и целиком —
    убранное правило из объединённой маски не вычесть, строку могли запретить
    двое. Отдельные куски снимают вопрос: маска это объединение, и собрать его
    из другого набора кусков стоит столько же.
    """
    global _ЗАПРЕТ_КЭШ
    if idx is None:
        idx = load()
    if idx is None:
        return {"маска": None, "счёт": {п: 0 for п in (правила or [])}}
    _забыть_индекс(idx)
    ключ = (id(idx), tuple(правила or ()))
    if _ЗАПРЕТ_КЭШ is not None and _ЗАПРЕТ_КЭШ[0] == ключ:
        return _ЗАПРЕТ_КЭШ[1]
    маска = np.zeros(idx.n, dtype=bool)
    счёт = {}
    оставить = {}
    for п in (правила or []):
        строки = _ПРАВИЛО_КЭШ.get(п)
        if строки is None:
            строки = строки_правила(idx, п)
        оставить[п] = строки
        счёт[п] = int(len(строки))
        if len(строки):
            маска[строки] = True
    # Держим ровно нынешний список: иначе память копила бы строки всех правил,
    # какие пользователь когда-либо вводил и стёр.
    _ПРАВИЛО_КЭШ.clear()
    _ПРАВИЛО_КЭШ.update(оставить)
    итог = {"маска": маска, "счёт": счёт}
    _ЗАПРЕТ_КЭШ = (ключ, итог)
    return итог


def забыть_запрет() -> None:
    """Забыть МАСКУ — её зовут после каждой правки списка (api/server.py).

    Строки отдельных правил при этом остаются: они не про список, а про индекс,
    и пересчитывать их из-за соседа незачем — ровно в этом и была цена правки."""
    global _ЗАПРЕТ_КЭШ
    _ЗАПРЕТ_КЭШ = None
