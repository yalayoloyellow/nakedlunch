# ДВА ЗАМКА, И РАБОТА У НИХ РАЗНАЯ (2026-08-18, перенесено сюда из api/server.py).
#
# Горячая перепечка индекса роняла КАЖДЫЙ `POST /api/generate`:
#
#   ValueError: operands could not be broadcast together with shapes
#               (2392262,) (2450282,)
#
# Индексов в процессе оказывалось два, и оба живые: `filters` держал прежний
# объект (его кэш ключевался кэшем рифм, а не индексом), а `gate_mask` брал
# маску чёрного списка у `запрет()`, который загружал индекс заново — уже
