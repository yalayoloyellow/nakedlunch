def адреса():
    """(addr_book, addr_a, addr_b, тексты книг, смещения) — или None.

    Отдельный артефакт (`tools/build_nl_addr.py`), а не часть индекса, и это
    нарочно: он строится ПОСЛЕ индекса и по нему. Нет артефакта — удлинение
    просто не работает, всё остальное работает как работало.

    СПРАШИВАЕМ `пути.таблица`, А НЕ `пути.артефакт` (2026-09-02). Корней два, и
    в СОБРАННОМ приложении они разные: спека кладёт адреса рядом со встроенными
    таблицами (корень ЧТЕНИЯ), а `артефакт` смотрит только в корень ЗАПИСИ.
    Значит в бандле 77 МБ ехали мёртвым грузом, а удлинение было выключено
    НАВСЕГДА и молча. `таблица` делает ровно нужное: сперва корень записи —
    там лежит свежеиспечённое, — потом встроенное из бандла.

    ДЛИНА СВЕРЯЕТСЯ С ИНДЕКСОМ, И ЭТО НЕ ПЕДАНТИЗМ. Прежняя редакция обещала,
    что перепечка индекса адреса «не обесценивает», — неверно: перепечка меняет
    ЧИСЛО строк (залили книгу, почистили склад), и колонка адресов остаётся
    короче. Первое же обращение к строке с номером больше её длины роняло
    генерацию `IndexError` — то есть вместо обещанной тихой деградации
    пятисотая на ровном месте. Разошлись длины — отдаём None, как и обещано.
    """
    global _АДРЕСА
    if _АДРЕСА is not None:
        return _АДРЕСА or None
    д = пути.таблица("nl_addr")
    try:
        книга = np.load(д / "addr_book.npy", mmap_mode="r")
        a = np.load(д / "addr_a.npy", mmap_mode="r")
        b = np.load(д / "addr_b.npy", mmap_mode="r")
        оф = np.load(д / "book_off.npy")
        блоб = (д / "books_blob.bin").read_bytes()
    except Exception:
        _АДРЕСА = ()
        return None
    idx = load()
    if idx is None or len(книга) != idx.n or len(a) != idx.n or len(b) != idx.n:
        _АДРЕСА = ()
        return None
    _АДРЕСА = (книга, a, b, блоб, оф)
    return _АДРЕСА


def _тот_же_текст(срез: str, текст: str) -> bool:
    """Один ли это текст — с точностью до пробелов.

    ПОЧЕМУ НЕ ПОБУКВЕННО (замер 2026-09-02). Сверка стояла точным равенством и
    выбрасывала 13.7% строк с ВЕРНЫМ адресом: 307 621 строка корпуса. Причина
    не в порче, а в том, как адреса искались: резак сшивал переносы строк в
    пробелы, поэтому 17.4% строк находятся в книге только после схлопывания
    пробелов (см. `плоский` в tools/build_nl_addr.py) — и их срез отличается
    от текста строки ровно пробелом против переноса. То есть строгая сверка
    отвергала именно тот класс, ради которого схлопывание и заводили.

    Свою работу — поймать РАЗОШЕДШИЙСЯ адрес (перепечка корпуса другим
    резаком, подмена книги) — сверка при этом делает по-прежнему: другой текст
    остаётся другим и после схлопывания. На той же выборке в 40 000 строк
    таких не нашлось ни одной, то есть строгость ловила ноль порчи.

    СКОЛЬКО ЭТО ДАЁТ НА ДЕЛЕ — 2 252 строки, а не 307 621, и разница здесь
    важнее самого числа. Отвергнутых адресов действительно треть миллиона, но
    удлинение зовут только для КОРОТКИХ строк, а среди них большинство и так
    росло: замер на 6 000 строк с адресом дал 75.4% → 78.5% доросших. Правка
    честная — сверка наконец проверяет то, что обещает, — но выдавать за неё
    триста тысяч строк было бы враньём числом."""
    return " ".join(срез.split()) == " ".join(текст.split())


def _текст_книги(номер: int) -> str:
    св = адреса()
    if св is None:
        return ""
    _, _, _, блоб, оф = св
    if номер < 0 or номер + 1 >= len(оф):
        return ""
    return блоб[int(оф[номер]):int(оф[номер + 1])].decode("utf-8", "replace")


def _удлинить(idx, строка_ном: int, текст: str, вилка, ворота: dict):
    """Добавить слов СЛЕВА, пока строка не дорастёт до вилки. None — не вышло.

    ЗЕРКАЛО ПОДРЕЗКИ, И ПО ТОЙ ЖЕ ПРИЧИНЕ РАСТЁМ ВЛЕВО: рифмо-ключ берётся с
    последнего знаменательного слова, поэтому хвост трогать нельзя, а голова
    свободна (замер: сдвиг левой границы наружу меняет ключ в 0.0% случаев на
    четырёх шагах из 5 965).

    ЧЕРЕЗ АБЗАЦ НЕ ХОДИМ. Пустая строка в книге — граница мысли; сшить через
    неё значит получить ту самую «случайную связь», на которую и
    жаловался. Проверка дешёвая: ищем перенос строки в добавляемом куске.
    """
    св = адреса()
    if св is None:
        return None
    книга, a, b, _, _ = св
    ном_книги = int(книга[строка_ном])
    if ном_книги < 0:
        return None
    начало, конец = int(a[строка_ном]), int(b[строка_ном])
    книжный = _текст_книги(ном_книги)
    if not книжный or not _тот_же_текст(книжный[начало:конец], текст):
        return None                     # адрес разошёлся с текстом — молчим
    низ, верх = вилка
    поз = начало
    for _ in range(8):
        левее = книжный.rfind(" ", 0, поз - 1) if поз > 0 else -1
        if левее < 0:
            return None
        кусок = книжный[левее + 1:поз]
        if "\n" in кусок or "\n" in книжный[левее:поз]:
            return None                 # уперлись в конец абзаца
        поз = левее + 1
        # ПРОБЕЛЫ СХЛОПЫВАЮТСЯ ЗДЕСЬ, а не остаются как в книге: строка едет на
        # экран и в историю, а там перенос строки посреди фразы — мусор. Ровно
        # так же её однажды нарезал резак, поэтому вид совпадает с корпусным.
        новый = " ".join(книжный[поз:конец].split())
        слогов = sum(1 for ч in новый.lower() if ч in _ГЛАСНЫЕ)
        if слогов > верх:
            return None
        if слогов < низ:
            continue
        if _сдвиг.причина_добавления(новый, ворота):
            return None
        return новый
    return None


def звук_фон():
    """Фон переклички из индекса — для счёта ВНЕ печки (ручка «короче»).

    Печка кладёт в meta не весь словарь троек, а список ЧАСТЫХ — тех, что
    порог редкости не проходят (их девяносто против 6 038 редких, 540 байт).
    Здесь он разворачивается в тот же вид, какого ждёт `звукопись`: у частых
    счёт заведомо больше порога, у всех остальных ноль, то есть редкие. Так
    ворота после реза считаются ТОЙ ЖЕ функцией, что при печке, — второй
    формулы для одного правила в проекте быть не должно.

    None — у индекса, испечённого до этой волны: тогда ворота переклички после
    реза не проверяются, и ручка честно молчит вместо того, чтобы гадать.
    """
    idx = load()
    if idx is None:
        return None
    частые = getattr(idx, "звук_частые", None)
    if частые is None:
        return None
    большое = 1.0                      # заведомо больше порога при «слов» = 1
    return {"счёт": {к: большое for к in частые}, "слов": 1,
            "доля_пар": float(getattr(idx, "звук_доля_пар", 0.0) or 0.0)}


def pool_mask(idx, pool) -> np.ndarray:
    """Маска активного пула с кэшем. Ключ — длина плюс первый и последний
    элемент: пул пересобирается на каждый запрос, но МЕНЯЕТСЯ только когда
    пользователь трогает источники, и любое такое изменение сдвигает длину.
    Совпадение всех трёх при разном содержимом теоретически возможно —
    поэтому это кэш, а не истина: ошибка стоила бы устаревшей маски до
    следующего изменения пула, не порчи данных."""
    global _pool_cache
    ключ = (len(pool or ()), (pool[0] if pool else ""), (pool[-1] if pool else ""))
    if _pool_cache is not None and _pool_cache[0] == ключ:
        return _pool_cache[1]
    m = mask_of(idx, pool)
    _pool_cache = (ключ, m)
    return m


