# Ограниченный отбор: то, ради чего индекс и затевался.
#
# Старый путь материализовал словарь на каждый выживший фрагмент (~1.76 млн) и
# 99.8% из них селекция не видела вовсе. Читая run(), видно, что дальше идут
# ровно ТРИ ограниченных набора плюс само число выживших:
#   • верхушка по оценке (NL_SELECT_CAP), ничьи разбиты случайно;
#   • резерв по перцентилю — чтобы тематический якорь не срезало усечением;
#   • резерв по слоговой вилке — по per_bucket на КАЖДЫЙ рифмо-ключ.
# Здесь они считаются по колонкам, а словари собираются только для объединения
# — тысячи строк вместо миллионов.
#
# ПОРЯДОК ВАЖЕН И ПОВТОРЁН ТОЧНО: перцентиль считается среди выживших ГЕЙТОВ по
# всей базе (так строилась строгая таблица — без пула, истории и чёрного
# списка), и только потом накладывается пул/история/чёрный список. Перепутать
# — значит тихо сдвинуть все ранги.
#
# Ничьи: старый путь мешал список и стабильно сортировал по убыванию оценки,
# то есть среди равных давал равномерно случайный порядок. Здесь то же самое
# даёт джиттер МЕНЬШЕ кванта округления (оценка округлена до 4 знаков, джиттер
# < 1e-5): порядок различных оценок он изменить не может, а равные
# перемешивает.

_JITTER = 1e-5

# ПОСТОЯННАЯ ПЛАТА ЗА ПОХОД — ОДИН РАЗ, А НЕ КАЖДЫЙ (Раунд 56).
#
# Замерено на машине владельца, журналом из его окна: поход за ВОСЕМЬЮ строками
# стоит 45 секунд, за двумястами — 72. То есть почти вся цена не в строках, а в
# подготовке: ворота по 2.87 млн, релевантность по всем леммам корпуса,
# устойчивая сортировка перцентиля по 2.6 млн выживших. Это считалось ЗАНОВО на
# каждый вызов — а во фристайле тема и крутилки не меняются вовсе, и результат
# каждый раз выходил тот же самый.
#
# Кэшируем ровно то, что зависит ТОЛЬКО от корпуса и ручек. Пул и история в
# ключ не входят и не должны: они накладываются масками ПОСЛЕ, на каждый вызов
# свои, и именно поэтому кэш безопасен — показанное по-прежнему вычитается
# каждый раз.
#
# Одна запись: тема с крутилками меняется редко, а таблица весит десятки
# мегабайт, и держать историю значило бы менять секунды на своп (та же ловушка,
# что у _STRICT_SCORE_CACHE_MAX в filters.py).
_таблица_кэш: tuple | None = None


def _ключ_темы(tags, sims):
    """Тема в ключе — по её ПОСЛЕДСТВИЮ, а не по написанию: relevance зависит
    ровно от `sims`, и два разных набора слов с одинаковыми похожестями дают
    одну таблицу. `None` (темы нет) — свой отдельный случай."""
    if not tags or sims is None:
        return None
    a = np.asarray(sims)
    return (a.shape, float(a.sum()), float(a[0]) if a.size else 0.0)


def _таблица(idx, tags, sims, ворота, no_mat, only_mat, clausula, cohesion, pctl_scale):
    """(номера выживших ворот, перцентиль, оценка) — с кэшем на один набор."""
    global _таблица_кэш
    ключ = (id(idx), tuple(_правила()), tuple(ворота), bool(no_mat), bool(only_mat), int(clausula),
            float(cohesion), float(pctl_scale), _ключ_темы(tags, sims))
    if _таблица_кэш is not None and _таблица_кэш[0] == ключ:
        return _таблица_кэш[1]
    gate = idx.gate_mask(ворота, no_mat, only_mat, clausula)
    table_ids = np.flatnonzero(gate)                    # выжившие ГЕЙТОВ по всей базе
    sem = idx.relevance(sims if tags else None)
    pctl_all = idx.pctl(sem, table_ids)
    score_all = np.round(0.6 + pctl_scale * (0.5 - np.abs(pctl_all - cohesion)), 4)
    _таблица_кэш = (ключ, (table_ids, pctl_all, score_all))
    return _таблица_кэш[1]


def забыть_таблицу() -> None:
    """Сбросить кэш подготовки — зовётся вместе с `forget` при смене индекса."""
    global _таблица_кэш
    _таблица_кэш = None


def _topk_by(score, ids, k, rng):
    """k номеров с наибольшей оценкой; ничьи — случайно. Возвращает в порядке
    убывания оценки, как список после sort(reverse=True) у старого пути."""
    if k <= 0 or len(ids) == 0:
        return np.empty(0, dtype=np.int64)
    s = score + rng.random(len(score)) * _JITTER
    if len(ids) > k:
        part = np.argpartition(s, -k)[-k:]
    else:
        part = np.arange(len(ids))
    part = part[np.argsort(s[part])[::-1]]
    return ids[part]


def select(idx, *, pool_mask, hidden_mask, tags, forced, ворота,
           no_mat, only_mat, clausula, cohesion, pctl_scale, literal_cap, cap, reserve_n, use_theme_anchor,
           syllable_spec, per_bucket, sims, seed=None):
    """(строки, число_выживших, кандидаты_на_принудительное_слово) — ровно то,
    что run() получает от _nl_scored плюс своих усечений и резервов."""
    rng = np.random.default_rng(seed)
    table_ids, pctl_all, score_all = _таблица(idx, tags, sims, ворота, no_mat,
                                              only_mat, clausula, cohesion, pctl_scale)

    keep = pool_mask[table_ids] & ~hidden_mask[table_ids]
    ids, pctl, score = table_ids[keep], pctl_all[keep], score_all[keep]

    literal = np.zeros(len(ids), dtype=bool)
    forced_m = np.zeros(len(ids), dtype=bool)
    if tags:
        literal = np.isin(ids, idx.token_hits(tags))
    if forced:
        forced_m = np.isin(ids, idx.token_hits(forced))

    # ограничитель повторов темы: лишние литеральные (кроме принудительных)
    # выбрасываются СЛУЧАЙНОЙ выборкой — у них почти всегда равная оценка
    if literal_cap is not None and tags:
        cand = np.flatnonzero(literal & ~forced_m)
        if len(cand) > literal_cap:
            оставить = set(_topk_by(score[cand], cand, literal_cap, rng).tolist())
            drop = np.array([j for j in cand if j not in оставить], dtype=np.int64)
            маска = np.ones(len(ids), dtype=bool)
            маска[drop] = False
            ids, pctl, score, literal, forced_m = (ids[маска], pctl[маска], score[маска],
                                                   literal[маска], forced_m[маска])

    n_survived = int(len(ids))
    порядок = np.arange(len(ids))

    отобрано = _topk_by(score, порядок, cap, rng)        # позиции внутри ids
    взято = list(отобрано)
    есть = set(взято.copy())
    if use_theme_anchor and reserve_n > 0 and len(ids):
        рез = порядок[np.argsort(pctl)[::-1][:reserve_n]]
        for j in рез:
            if int(j) not in есть:
                есть.add(int(j)); взято.append(j)
    if syllable_spec:
        _добрать_по_слогам(idx, ids, score, syllable_spec, per_bucket, взято, есть)

    строки = [_row(idx, int(ids[j]), float(score[j]), float(pctl[j])) for j in взято]
    кандидаты = {}
    for w in (forced or ()):
        попал = np.isin(ids, idx.token_hits([w]))
        кандидаты[w] = [_row(idx, int(ids[j]), float(score[j]), float(pctl[j]))
                        for j in np.flatnonzero(попал)]
    return строки, n_survived, кандидаты


def _добрать_по_слогам(idx, ids, score, syllable_spec, per_bucket, взято, есть):
    """Слоговой резерв: по per_bucket лучших на КАЖДЫЙ рифмо-ключ внутри
    вилки. Общий для строгого яруса и «классики» — правило одно, и разойтись
    им нельзя (иначе строфа с заданной длиной строки вела бы себя по-разному
    в зависимости от крутилки «классика»). Дописывает во `взято`/`есть`."""
    syl = np.asarray(idx.syl)[ids]
    key = np.asarray(idx.key_id)[ids]
    for lo, hi in {tuple(r) for r in syllable_spec}:
        в_вилке = np.flatnonzero((syl >= lo) & (syl <= hi) & (key != _пустой_ключ(idx)))
        if not len(в_вилке):
            continue
        # группируем по рифмо-ключу и берём по per_bucket лучших из каждой
        пор = в_вилке[np.lexsort((-score[в_вилке], key[в_вилке]))]
        k = key[пор]
        начала = np.flatnonzero(np.r_[True, k[1:] != k[:-1]])
        for a, b in zip(начала, np.r_[начала[1:], len(пор)]):
            for j in пор[a:min(a + per_bucket, b)]:
                if int(j) not in есть:
                    есть.add(int(j)); взято.append(j)


def _пустой_ключ(idx):
    """Номер пустого рифмо-ключа: фрагменты без ключа в слоговой резерв не
    берутся (старый путь требовал `key` истинным)."""
    if not hasattr(idx, "_empty_key"):
        try:
            idx._empty_key = idx.keys.index("")
        except ValueError:
            idx._empty_key = -1
    return idx._empty_key


def _row(idx, i, score, pctl, light=False):
    """Строка выдачи ровно той формы, что собирал старый путь (после того как
    он удалял служебные _literal/_forced/_forced_hits).

    У «классики» поля `_pctl` нет СОЗНАТЕЛЬНО, а не по забывчивости: по его
    наличию `_select_with_rhyme` отличает строку алгоритмического яруса от
    классической (см. `if "_pctl" not in cand` там же). Появись он у
    классики — она попала бы в тематический якорь, которого у неё по
    определению нет."""
    a, b = int(idx.span_a[i]), int(idx.span_b[i])
    row = {"text": idx.text(i), "template": "nakedlunch", "meter": None,
           "rhyme": idx.keys[int(idx.key_id[i])],
           "rhyme_span": None if a < 0 else [a, b],
           "syllables": int(idx.syl[i]), "score": score, "_lem": idx.lemma_set(i),
           # Раунд 39: мат — доля, а не запрет, поэтому признак нужен КАЖДОЙ
           # строке, а не только воротам. Читаем из колонки индекса, считать
           # регуляркой заново незачем (см. filters._select_with_rhyme).
           "mat": bool(idx.mat[i]),
           "clausula": int(idx.clau[i]),
           "classic": light}
    if not light:
        row["_pctl"] = pctl
    return row


def select_light(idx, *, pool_mask, hidden_mask, no_mat, only_mat, clausula, cap, seed=None):
    """«Классика» = изначальный нейкедланч: случайные куски активного пула.

    РАУНД 35. Раньше она отключала только мнения extendo о качестве
    (банальность, тавтология, клише), но продолжала считать релевантность
    теме и подчиняться вилке слогов. Владелец 2026-08-02: «суть режима
    классика в том что работает как изначальный нейкедланч без фильтров без
    настроек без ничего». Изначальный (`nlsrc/generator.generate_four`)
    делает ровно `rng.sample(pool, 4)` — поэтому здесь нет ни темы, ни
    оценки: у всех строк оценка одна, и верхушка вырождается в равномерно
    случайную выборку. Аргументы `tags`/`sims`/`syllable_spec` убраны
    СОЗНАТЕЛЬНО — оставить их значило бы держать дверь, в которую по
    определению режима входить нельзя.

    Остаются ровно три ограничения, и ни одно из них не мнение о качестве:
    активный пул (какие книги включены), история (не показывать дважды) и
    доля мата — явный запрос владельца на содержание.

    Чёрного списка здесь тоже больше нет: он вырезан из проекта (Раунд 35,
    решение владельца — «пользы в нём вроде бы и нет»)."""
    rng = np.random.default_rng(seed)
    if no_mat:
        table_ids = np.flatnonzero(np.asarray(idx.mat) == 0)
    elif only_mat:
        table_ids = np.flatnonzero(np.asarray(idx.mat) != 0)
    else:
        table_ids = np.arange(idx.n, dtype=np.int64)
    if clausula:
        table_ids = table_ids[np.asarray(idx.clau)[table_ids] == clausula]
    # Обрывки дефисных слов отсеиваются и здесь (Раунд 51). Это не мнение о
    # качестве, а брак нарезки: «нибудь гнусность скрывается» — не сырьё, а
    # разорванное пополам слово. Классика подчиняется воротам, а это ворота.
    table_ids = table_ids[idx.whole_mask()[table_ids]]
    ids = table_ids[pool_mask[table_ids] & ~hidden_mask[table_ids]]
    n_survived = int(len(ids))
    if n_survived == 0:
        return [], 0
    k = min(cap, n_survived)
    взято = rng.choice(n_survived, size=k, replace=False)
    return [_row(idx, int(ids[j]), 0.6, 0.0, light=True) for j in взято], n_survived


# ---- маски пула и истории -------------------------------------------------
# Индекс знает корпус, но не знает, какие источники включены и что уже
# показывалось: и то и другое живёт снаружи и меняется между запросами.
# Переводим их в маски по номерам фрагментов.

_text_ids: dict | None = None
_text_lock = threading.Lock()
_pool_cache: tuple | None = None


def text_ids(idx) -> dict:
    """Карта «текст → номер». Строится один раз на процесс и живёт: без неё
    не перевести список активного пула в номера. Память — сотни МБ, против
    5.5 ГБ, которые снимает сам индекс.

    Замер 2026-08-02: на 2.87 млн записей это 9.8 с, и раньше их платил
    ПЕРВЫЙ запрос генерации в процессе — то есть владелец, а не старт. Теперь
    старт греет её фоном (warm_background), а замок нужен, чтобы запрос,
    пришедший в разгар прогрева, встал в очередь, а не строил вторую такую
    же карту рядом."""
    global _text_ids
    with _text_lock:
        if _text_ids is None:
            _text_ids = {idx.text(i): i for i in range(idx.n)}
        return _text_ids


_lag_cache: tuple | None = None      # (сколько подали, ответ)


def lag(texts, total: int) -> int | None:
    """Сколько ТЕКСТОВ не попало в колоночный индекс.

    ПОЧИНКА ПОЧИНКИ. Первая версия считала разницей `фрагментов − строк
    индекса` — «дёшево и про то же». Оказалось не про то же и не дёшево по
    смыслу: на машине владельца 2 874 175 фрагментов, но лишь 2 856 289
    РАЗНЫХ текстов (17 886 дублей), а строк в индексе 2 868 100 — там ещё
    живут тексты удалённых источников. Разница дала «6 075 строк вне индекса»
    при том, что вне его НОЛЬ. То есть строка, заведённая против вранья,
    начала врать сама.

    Точный ответ стоит 0.4 с (замер 2026-08-04) — карта «текст → номер» и так
    греется на старте, и по ней это просто 2.87 млн проверок в словаре.
    Дорогими были 13 с из первого замера: там я строил карту заново.

    None — карта ещё греется. Сказать «считаю» честнее, чем назвать число,
    которого не знаешь; ждать здесь нельзя — это поток HTTP-запроса."""
    global _lag_cache
    if _lag_cache is not None and _lag_cache[0] == total:
        return _lag_cache[1]
    idx = load()
    if idx is None:
        return total          # индекса нет — вне его всё; не кэшируем, он может появиться
    if _text_ids is None:
        return None           # греется
    ответ = sum(1 for t in texts if t not in _text_ids)
    _lag_cache = (total, ответ)
    return ответ


def forget() -> None:
    """Забыть загруженный индекс и все производные карты. Отдельно от
    `reload`, потому что это единственная СИНХРОННАЯ и проверяемая часть:
    `reload` следом пускает фоновый прогрев, и сразу после него состояние
    модуля уже меняется под руками."""
    global _idx, _tried, _text_ids, _pool_cache, _lag_cache
    with _text_lock:
        _idx = None
        _tried = False
        _text_ids = None
    _pool_cache = None
    _lag_cache = None
    забыть_таблицу()


def reload() -> None:
    """Забыть загруженный индекс и прогреть заново — зовётся ПОСЛЕ перепечи
    (Раунд 52).

    Без этого свежеиспечённый индекс не увидели бы до перезапуска: `_idx`
    живёт всю жизнь процесса, а карта «текст → номер» и подавно. Именно на
    этом ломалась загрузка книги: строки нового источника попадали в кэш
    рифм, но не в колонки, а `mask_of` молча пропускает всё, чего в индексе
    нет — то есть книга была в списке источников и не участвовала в выдаче.

    Старый mmap переживает перепечь: скрипт пишет во временный каталог и
    переименовывает, а отвязанные файлы живут, пока на них есть ссылки. То
    есть до этого вызова процесс честно читает ПРЕЖНИЙ индекс, а не мусор.

    Прогрев обязателен: карта «текст → номер» стоит 9.8 с, маска целостности
    ещё 9.2 с, и без фонового прогрева их заплатила бы ПЕРВАЯ генерация после
    перепечи — то есть владелец."""
    forget()
    warm_background()


def warm_background() -> None:
    """Прогреть карту «текст → номер» фоновым потоком (зовётся со старта
    сервера). Индекса нет или он чужой версии — молча выходим: генерация
    тогда идёт старым путём, и греть нечего."""
    def работа():
        try:
            idx = load()
            if idx is not None:
                text_ids(idx)
                # Раунд 51: маска целостности (обрывки дефисных слов) — 9.2 с
                # на 2.87 млн фрагментов. Без этой строки её платила ПЕРВАЯ
                # генерация владельца, хотя прогрев рядом уже был и грел не то.
                idx.whole_mask()
        except Exception:
            pass   # прогрев — удобство, а не обязанность: молчит и не мешает
    threading.Thread(target=работа, name="nlindex-warm", daemon=True).start()


def mask_of(idx, texts) -> np.ndarray:
    m = np.zeros(idx.n, dtype=bool)
    tid = text_ids(idx)
    for s in texts or ():
        i = tid.get(s)
        if i is not None:
            m[i] = True
    return m


def pool_mask(idx, pool) -> np.ndarray:
    """Маска активного пула с кэшем. Ключ — длина плюс первый и последний
    элемент: пул пересобирается на каждый запрос, но МЕНЯЕТСЯ только когда
    владелец трогает источники, и любое такое изменение сдвигает длину.
    Совпадение всех трёх при разном содержимом теоретически возможно —
    поэтому это кэш, а не истина: ошибка стоила бы устаревшей маски до
    следующего изменения пула, не порчи данных."""
    global _pool_cache
    ключ = (len(pool or ()), (pool[0] if pool else ""), (pool[-1] if pool else ""))
    if _pool_cache is not None and _pool_cache[0] == ключ:
        return _pool_cache[1]
    m = mask_of(idx, pool)
    _pool_cache = (ключ, m)
    return m


def forget_pool() -> None:
    """Сбросить кэш маски пула — зовётся при добавлении/удалении источника."""
    global _pool_cache
    _pool_cache = None


