def _skel_buckets() -> dict:
    """Вёдра «первая согласная скелета → слова» для вкладки «по звуку».

    Ленивое и точное, а не приблизительное: вкладка требует общего начала
    скелетов длиной ≥1 (при m == 0 кандидат отбрасывается безусловно),
    значит кандидат ОБЯЗАН делить первую согласную — вёдро отсекает ровно
    тех, кого отбросил бы полный проход, и ни одним словом больше. На 668k
    словах это разница между 20мс и секундой на каждый клик.

    Порядок внутри ведра — порядок _WORDS, то есть по убыванию частоты."""
    global _SKEL, _SKEL_BUCKET
    if _SKEL_BUCKET is None:
        _SKEL = {}
        buckets: dict = {}
        for w in _WORDS:
            s = _skeleton(w)
            _SKEL[w] = s
            if s:
                buckets.setdefault(s[0], []).append(w)
        _SKEL_BUCKET = buckets
    return _SKEL_BUCKET


def _yo_map() -> dict:
    """«еще» → «ещё»: у владельца это одна клавиша. Строим карту ТОЛЬКО по
    словам с ё (их проценты от словаря), лениво — раньше промах гонял
    линейный проход по всему индексу на каждое незнакомое слово."""
    global _YO
    if _YO is None:
        _YO = {w.replace("ё", "е"): w for w in _WORDS if "ё" in w}
    return _YO


def _канон(w: str) -> str:
    """Написание слова, под которым оно лежит в индексе.

    Ё ходит в обе стороны, и обе встречаются по-настоящему. Источник индекса
    — wordfreq, а там почти всё без ё («еще», «идет»), но в тексте владельца
    ё вполне может стоять («ещё», «идёт»), и раньше такой клик молча давал
    прочерк. Пробуем ровно два точных лукапа, без угадывания: слово как есть,
    затем противоположное написание. Рифмо-ключ при этом уже посчитан
    правильно на сборке (см. build_nl_rhyme._restore_yo), поэтому написание
    влияет только на попадание в словарь."""
    if not w or w in _WORDS:
        return w
    if "ё" in w:
        alt = w.replace("ё", "е")
        return alt if alt in _WORDS else w
    return _yo_map().get(w, w)


def rhyme_key_of(word: str) -> str:
    """Рифмо-ключ слова из словаря ударений (660k словоформ, ruaccent) — или
    пустая строка, если слова там нет.

    ЗАЧЕМ ПУБЛИЧНО (Раунд 51). Словарь уже поднят в память этого же процесса
    (warm_caches на старте сервера), но добраться до него можно было только
    через suggest(). Поэтому в проекте завелись СВОИ угадывания ударения —
    каждое со своим правилом и своей точностью: core/refprofile.py меряло
    клаузулу референса по числу гласных в срезе от предпоследней (58%),
    core/sheets.py — своим третьим способом (54%). Настоящий ответ всё это
    время лежал рядом.

    Пустая строка — честный отказ, а не догадка: слова нет в словаре, и
    вызывающий сам решает, что делать (в refprofile такая часть просто не
    участвует в замере клаузулы)."""
    if not _WORDS:
        warm_caches()
    entry = _WORDS.get(_канон((word or "").strip().lower()))
    return entry[0] if entry else ""


def _thesaurus() -> dict:
    """Ленивая загрузка data/thesaurus.json (см. комментарий у _THES).
    Возвращает {'syn': {...}, 'ant': {...}} или {} — отсутствие файла это
    нормальный режим (словарь не собран), не ошибка."""
    global _THES, _thes_attempted
    if not _thes_attempted:
        _thes_attempted = True
        if _THES_PATH.exists():
            data = json.loads(_THES_PATH.read_text(encoding="utf-8"))
            _THES = {"syn": data.get("syn") or {}, "ant": data.get("ant") or {}}
    return _THES


def thesaurus_status() -> dict:
    """Есть ли словарные слои — сырьё для /api/state.thesaurus. Только факт
    наличия данных; вердикт ворот качества (мусор → вкладка прячется)
    накладывает роут в api/server.py — решение о качестве живёт рядом с его
    документацией, а не в загрузчике."""
    th = _thesaurus()
    return {"syn": bool(th.get("syn")), "ant": bool(th.get("ant"))}


def _freq_label(zipf: float) -> str:
    """Частотная подпись справа: употреблений на миллиард слов (10^zipf —
    определение zipf-шкалы wordfreq), с тонким пробелом между тысячами
    («12 340») — формат из контракта API."""
    return format(int(round(10 ** zipf)), ",").replace(",", _THIN)


# Лемматизация — pymorphy3, он уже рантайм-зависимость (corpus.py). Нужна в
# двух местах, и оба нашлись живой проверкой 2026-08-01, а не рассуждением:
#   1) словарь Викисловаря ключуется леммами, а из текста приходит словоформа:
#      «холодная» давала пустые антонимы, хотя «холодный» → горячий/жаркий;
#   2) префиксный отсев однокоренных (≥5 букв) слишком груб для коротких
#      основ: «ночью» → «ночь»/«ночи» проходили фильтр (общих букв 4) и
#      векторный слой отдавал слову его же формы вместо синонимов.
_MORPH = None
_LEMMA_CACHE: dict[str, tuple] = {}
# Тот же порог веса разбора, что на сборке (tools/build_rhyme_index.py). Он
# обязан совпадать: иначе слово из индекса и слово из navec схлопывались бы
# по разным правилам, и одно и то же сравнение давало бы разный ответ.
_ПОРОГ_РАЗБОРА = 0.05
_МАКС_ЛЕММ = 4


def _леммы(word: str) -> tuple:
    """ВСЕ правдоподобные начальные формы слова (Раунд 32), первая — самая
    вероятная.

    Из индекса они уже испечены, и это не ускорение ради ускорения, а
    условие работоспособности: «по звуку» сверяет леммы у тысяч кандидатов
    на КАЖДЫЙ клик, а pymorphy стоит ~0.08мс на слово. Кэш — для всего,
    чего в индексе нет (слова из тезауруса и словаря navec)."""
    global _MORPH
    свой = _WORDS.get(word)
    if свой is not None:
        return tuple(свой[3])
    hit = _LEMMA_CACHE.get(word)
    if hit is not None:
        return hit
    out = (word,)
    try:
        if _MORPH is None:
            import pymorphy3
            _MORPH = pymorphy3.MorphAnalyzer()
        parsed = _MORPH.parse(word)
        if parsed:
            формы = list(dict.fromkeys(p.normal_form for p in parsed
                                       if p.score >= _ПОРОГ_РАЗБОРА))[:_МАКС_ЛЕММ]
            out = tuple(формы) or (parsed[0].normal_form,)
    except Exception:
        pass   # морфология — удобство, а не обязанность: молчит → работаем по форме
    _LEMMA_CACHE[word] = out
    return out


def _lemma(word: str) -> str:
    """Самая вероятная начальная форма — ею ключуется тезаурус (одна статья
    на слово, не набор). Для сравнения «то же самое слово?» нужен _леммы."""
    return _леммы(word)[0]


def _одно_слово(a: str, b: str) -> bool:
    """Две словоформы — одно и то же слово, если их наборы начальных форм
    пересеклись. Пересечение, а не равенство первых: у неоднозначных форм
    самый вероятный разбор pymorphy часто не тот («спал» → «спасть»,
    «утром» → «утром»), и равенство молча пропускало дубли — ровно те, на
    которые владелец и жаловался."""
    return bool(set(_леммы(a)) & set(_леммы(b)))


# Приставки для отсева однокоренных «через приставку» (Раунд 33). Только
# ДВУХбуквенные и длиннее: односложные «у-», «в-», «с-», «о-» дают ложные
# срабатывания на настоящих рифмах — «дар/удар», «раз/сраз» этимологически
# не родня, а правило их бы склеило. Порядок — от длинных к коротким, иначе
# «пере-» съелось бы как «пе-».
_ПРИСТАВКИ = ("через", "пред", "пере", "разо", "подо", "обо", "ото", "воз",
              "вос", "низ", "нис", "раз", "рас", "роз", "рос", "без", "бес",
              "при", "про", "пре", "под", "над", "изо", "из", "ис", "от",
              "об", "до", "за", "на", "по", "вы", "со")
_МИН_ОСНОВА = 3   # что останется после приставки; короче — уже совпадение, не корень


def _через_приставку(a: str, b: str) -> bool:
    """«любить» и «полюбить» — одно слово с приставкой, а значит рифма
    «любишь/полюбишь» самая дешёвая, какая бывает.

    Прежний отсев однокоренных сравнивал НАЧАЛА слов, и приставка их разводила
    насмерть: «л…» против «п…» — ноль общих букв. Поэтому пара проходила да
    ещё и как «богатая» (опорная согласная у них, конечно, совпадает).
    Найдено разбором собственной выдачи 2026-08-02."""
    длин, кор = (a, b) if len(a) > len(b) else (b, a)
    if len(кор) < _МИН_ОСНОВА or not длин.endswith(кор):
        return False
    приставка = длин[:len(длин) - len(кор)]
    return приставка in _ПРИСТАВКИ


def _same_root(a: str, b: str) -> bool:
    """Однокоренные: сначала честно по леммам (ночью/ночь — одно слово),
    потом через приставку (любить/полюбить), префикс остаётся запасным путём
    для того, чего морфология не знает."""
    if _одно_слово(a, b):
        return True
    for la in _леммы(a):
        for lb in _леммы(b):
            if _через_приставку(la, lb):
                return True
    x, y = a.replace("ё", "е"), b.replace("ё", "е")
    n = 0
    for p, q in zip(x, y):
        if p != q:
            break
        n += 1
    # короткое слово целиком лежит в начале длинного — «ночь» в «ночью»: лемма
    # тут не спасает (pymorphy считает «ночью» наречием, начальная форма своя),
    # а до префикса ≥5 общих букв не хватает одной
    if n >= 4 and n == min(len(x), len(y)):
        return True
    return n >= _ROOT_PREFIX


def _dict_lookup(layer: str, word: str) -> list[str]:
    """Словарный слой: статья ЛЕММЫ, следом статья самой словоформы.

    Раньше словоформа побеждала, а к лемме шли только при промахе. С приходом
    Абрамова (2026-08-02) это дало регресс: у него «холодная» — отдельная
    статья-существительное (арестантское «холодная» = острог), и клик по
    прилагательному «холодная» стал выдавать «острог, тюрьма» вместо
    «зябкий, ледяной, морозный». Лемма — почти всегда то, что человек имел в
    виду, кликая по словоформе; статью самой формы не выбрасываем, а
    дописываем следом: омоним остаётся доступен, но не вытесняет основное."""
    table = _thesaurus().get(layer) or {}
    lem = _lemma(word)
    из = list(table.get(lem) or ()) if lem != word else []
    for w in (table.get(word) or ()):
        if w not in из:
            из.append(w)
    return [w for w in из if w != word and w != lem]


def _нужна_опора(key: str) -> bool:
    """Ключ — ровно ОДИН гласный, то есть мужское открытое окончание:
    ударение на последнем слоге, и после ударного гласного не осталось
    ничего («рука», «окно», «моя»). Только здесь рифме нужна опорная
    согласная — см. _rhymes_tab.

    Первая версия правила (2026-08-02) звучала шире — «в ключе нет ни
    одной согласной» — и сгорела на сверке со старым индексом: под неё
    попало «минуя» (ключ «уя»), и настоящие рифмы «рискуя, образуя,
    поцелуя» отсеялись. Ключ «уя» — это ДВА слога, женское окончание, и
    рифму там несёт заударный хвост, ровно как в «мама/рама». Опору
    требует только случай, когда нести больше нечему."""
    return len(key) == 1 and key in scan.VOWELS


def _гласные(key: str) -> str:
    """Гласный скелет ключа — «ертвы» → «еы». По нему сгруппированы ключи
    для неточных ярусов: и замена одной согласной, и лишняя согласная на
    конце гласных не трогают, значит все неточные рифмы слова лежат в его
    собственном ведре, и перебирать 102 584 ключа на запрос не нужно."""
    return "".join(c for c in key if c in scan.VOWELS)


def _keys_by_vowels() -> dict:
    """ключ → ведро по гласному скелету; ленивое, греется в warm_caches."""
    global _KEYS_VOW
    if _KEYS_VOW is None:
        b: dict = {}
        for k in _KEYS:
            b.setdefault(_гласные(k), []).append(k)
        _KEYS_VOW = b
    return _KEYS_VOW


def _тип_рифмы(A: str, B: str) -> tuple[str, int] | None:
    """Тип неточной рифмы между ключом слова A и ключом кандидата B, плюс
    ВЕС (чем больше, тем ближе звучание — по нему ярус и упорядочен).
    Гласные у них уже совпали (вызывается только внутри одного ведра
    _keys_by_vowels), поэтому различаться могут только согласные.

    Возвращает None, если пара не дотягивает ни до одного честного типа —
    молчать здесь важнее, чем показать: см. отвергнутый «ассонанс» ниже."""
    if A == B:
        return None
    if len(A) == len(B):
        разн = [i for i in range(len(A)) if A[i] != B[i]]
        # ровно одна согласная разошлась: «ночь/плоть», «свет/затем»,
        # «любишь/клюнешь», «жертвы/смертны». Вес — сколько совпало ПОСЛЕ
        # расхождения: рифму несёт конец слова, поэтому чем раньше разошлось
        # и чем длиннее общий хвост, тем ближе звучание. Проверено на слух
        # по живым парам (сперва я взвесил наоборот): «безработицы/
        # богородицы» (разошлось на 1-й, хвост «ицы») сильнее, чем
        # «безработицы/блевотины» (разошлось на 3-й); «конфликтах/
        # мотоциклах» сильнее, чем «конфликтах/диктор»; «ночь/плоть»
        # сильнее, чем «ночь/почт».
        return ("неточная", len(A) - 1 - разн[0]) if len(разн) == 1 else None
    длин, кор = (A, B) if len(A) > len(B) else (B, A)
    if (len(длин) == len(кор) + 1 and длин.startswith(кор)
            and длин[-1] not in scan.VOWELS
            # у короткого ключа обязана быть своя согласная, иначе «свет»
            # (ключ «ет») усекается до «е» и рифмуется с «не, все, же, мне»
            and any(c not in scan.VOWELS for c in кор)):
        return "усечённая", len(кор)   # длиннее общий кусок — ближе рифма
    return None


# Порядок ярусов = порядок силы рифмы, он же порядок групп в попапе.
# «богатая» — точная рифма, у которой вдобавок совпала опорная согласная
# («мороз/матрос»); в русской традиции это сильнейший вид, и владелец
# просил «категоризировать и помечать разные типы».
# «однокоренная» идёт последней: «любишь/полюбишь» это точная рифма, но самая
# дешёвая, какая бывает. Раньше такие пары просто выбрасывались — и «любишь»
# оставался с четырьмя строками из одного слабого яруса. По той же логике, что
# и остальные типы: не прятать, а подписать и опустить вниз.
_ЯРУСЫ = ("богатая", "точная", "усечённая", "неточная", "однокоренная")
# Сколько показываем каждого. Точных — сколько есть (список скроллится),
# неточных — ограниченно: они добор, а не основа.
_КВОТА = {"богатая": TOP_RHYMES, "точная": TOP_RHYMES,
          "усечённая": 8, "неточная": 14, "однокоренная": 8}


def _rhymes_tab(word: str) -> list[dict]:
    """«Рифмы»: слова того же рифмо-ключа плюс размеченные неточные ярусы.

    ОПОРНАЯ СОГЛАСНАЯ. Если слово кончается ударным гласным, ключ — один
    гласный, и его делят тысячи слов: у «рука» ключ «а», а в ведре с ним
    «на», «за», «когда», «была». Русская рифма так не устроена — при
    мужском открытом окончании она требует совпадения согласной ПЕРЕД
    ударным гласным: «рука/река/строка/тоска», «окно/оно/давно/кино»,
    «моя/твоя/своя/края». Поэтому на таких ключах сверяем ещё и опору
    (поле индекса, печётся в tools/build_rhyme_index.py). Всем прочим
    ключам — и «очь», «ос», «ога», и двусложным «уя», «ою» — опора не
    нужна: там рифму несёт сам хвост (см. _нужна_опора).

    ОДНА ФОРМА НА ЛЕММУ. Внутри ведра остаётся самая частая форма слова —
    «утро/утра/утром» это одна рифма, а не три (жалоба владельца
    2026-08-02). Порядок ведра задан сборкой (обычные слова по убыванию
    частоты, потом подозрительные — фамилии, топонимы, незнакомое
    pymorphy), поэтому «лучшая форма» получается первой встреченной, без
    единой сортировки на запросе.

    НЕТОЧНЫЕ ЯРУСЫ (владелец, 2026-08-02: «я согласен ещё на такое явление
    как внутренняя рифма и прочее — можно просто категоризировать и
    помечать разные типы рифм»). Каждая строка несёт свой тип в поле `t`,
    и попап рисует группы заголовками — то есть неточное не выдаётся за
    точное, а честно подписано. Это же закрывает 6.4% словоформ, у которых
    точной рифмы в языке просто нет («жертвы», «безработицы»).
    Подозрительные в неточные ярусы НЕ пускаются вовсе: в списке слабых
    рифм фамилия или опечатка — чистый шум, а довода «с Москвой рифмуют»
    там уже нет.

    ЯРУС «АССОНАНС» ОТВЕРГНУТ ПОСЛЕ ПРОБЫ. Определение «гласные совпали,
    согласные какие угодно» на живом индексе дало «ночь → что, по, но,
    то», «жертвы → темы, схемы, проблемы», «маленькими → организациями,
    операциями». Два честных яруса лучше трёх, из которых один врёт."""
    entry = _WORDS.get(word)
    if entry is None or not entry[0]:
        return []   # не из словаря индекса / без ударения → честное «—»
    key, опора = entry[0], entry[2]
    строго = _нужна_опора(key)
    группы: dict = {t: [] for t in _ЯРУСЫ}
    видели_леммы = set(entry[3])

    def взять(c: str, ярус: str, только_чистые: bool) -> str | None:
        """Положить кандидата в ярус; вернуть ярус, куда он лёг, или None.

        Однокоренное слово в ТОЧНОМ ярусе не выбрасывается, а переезжает в
        ярус «однокоренная» (см. _ЯРУСЫ). В неточных ярусах выбрасывается:
        слабая рифма к тому же корню — уже ничего. То же слово в другой
        форме (пересечение начальных форм) не рифма нигде — его снимает
        дедуп по леммам: `видели_леммы` начинается с форм самого слова."""
        if c == word:
            return None
        c_z, c_леммы, c_подозр = _WORDS[c][1], _WORDS[c][3], _WORDS[c][4]
        if только_чистые and c_подозр:
            return None
        if видели_леммы.intersection(c_леммы):
            return None
        if _same_root(word, c):
            if только_чистые or len(группы["однокоренная"]) >= _КВОТА["однокоренная"]:
                return None
            ярус = "однокоренная"
        видели_леммы.update(c_леммы)
        группы[ярус].append({"w": c, "n": _freq_label(c_z), "t": ярус})
        return ярус

    # --- точные: ведро точного ключа --------------------------------------
    точных = 0
    for c in _KEYS.get(key, ()):
        c_опора = _WORDS[c][2]
        if строго and c_опора != опора:
            continue
        # «богатая» имеет смысл только там, где опора НЕ обязательна: где
        # обязательна, её совпадение — условие входа, а не достоинство
        ярус = "богатая" if (not строго and опора and c_опора == опора) else "точная"
        # однокоренные квоту точных не съедают — у них своя
        if взять(c, ярус, False) in ("богатая", "точная"):
            точных += 1
            if точных >= TOP_RHYMES:
                break

    # --- неточные: вёдра ключей того же гласного скелета -------------------
    # Ключи сортируем по весу ДО обхода: иначе порядок яруса задавался бы
    # тем, в каком порядке ключи попались в ведро, то есть ничем. Сортировка
    # устойчива, поэтому при равном весе сохраняется исходный порядок ведра —
    # а он идёт от самых частых слов (порядок сборки индекса).
    ключи: dict = {}
    for B in _keys_by_vowels().get(_гласные(key), ()):
        оценка = _тип_рифмы(key, B)
        if оценка is not None:
            ключи.setdefault(оценка[0], []).append((-оценка[1], B))
    for ярус in ("усечённая", "неточная"):
        for _вес, B in sorted(ключи.get(ярус, ()), key=lambda p: p[0]):
            if len(группы[ярус]) >= _КВОТА[ярус]:
                break
            for c in _KEYS.get(B, ()):
                if взять(c, ярус, True) is not None and len(группы[ярус]) >= _КВОТА[ярус]:
                    break

    return [строка for ярус in _ЯРУСЫ for строка in группы[ярус]]


def _sound_tab(word: str) -> list[dict]:
    """«По звуку» — НЕ рифма, а аллитерация/созвучие: балл = длина общего
    начала согласных скелетов (0..3) + совпадение ударного гласного (первый
    символ ключа — ключ всегда начинается с него) + близость длины. Рифмы
    точного ключа исключены — они на соседней вкладке, дублировать её тут
    значило бы показывать одно и то же дважды."""
    entry = _WORDS.get(word)
    if entry is None:
        return []
    key = entry[0]
    stressed = key[0] if key else ""
    ведра = _skel_buckets()
    skel = _SKEL.get(word) or _skeleton(word)
    if not skel:
        return []
    wlen = len(word)
    scored: list[tuple] = []
    for w in ведра.get(skel[0], ()):
        рек = _WORDS[w]
        k, z = рек[0], рек[1]
        if w == word or (key and k == key):
            continue
        # Подозрительное (фамилии, топонимы, транслит, незнакомое pymorphy)
        # ЗДЕСЬ выбрасывается, а не опускается, как на вкладке рифм. Разница
        # не в строгости, а в назначении вкладок: рифмуют и с «Москвой», а
        # созвучие с фамилией не даёт поэту ничего. Замер на живом индексе
        # 2026-08-02: без этого в верхушке «мороз» 22 слова из 30 были
        # «мирзо, морск, мерсо, морас, морза, моэрс, морсби, морстен».
        if рек[4]:
            continue
        s = _SKEL.get(w, "")
        m = 0
        for a, b in zip(skel, s):
            if a != b:
                break
            m += 1
        vow = 1.0 if (stressed and k and k[0] == stressed) else 0.0
        # Порог: одна общая согласная без общего ударного гласного — уже не
        # созвучие, а совпадение первой буквы; такой шум не показываем.
        if m < 2 and not vow:
            continue
        if m == 0:
            continue
        # Однокоренные режутся тем же порогом, что на вкладке рифм: без
        # этого топ по звуку — просто падежи самого слова («мороз → мороза,
        # морозы, морозов», проверено на живом индексе), а формы слова
        # владелец и так знает — слоты нужны настоящим созвучиям. Проверка
        # стоит ПОСЛЕ порога по баллу сознательно: она самая дорогая в
        # цикле, а порог отсеивает подавляющее большинство ведра.
        if _same_root(word, w):
            continue
        score = m + vow + max(0.0, 1.0 - abs(len(w) - wlen) / 4.0)
        scored.append((-score, -z, w))
    # Верхушку берём с запасом и схлопываем формы одного слова: «гроза,
    # грозы, грозе» звучат одинаково близко к «мороз» и займут три слота из
    # тридцати, показав одно слово (жалоба владельца 2026-08-02). Запас
    # нужен именно потому, что схлопывание идёт ПОСЛЕ отбора верхушки:
    # иначе на месте выброшенных форм остались бы дыры.
    top = heapq.nsmallest(TOP_RHYMES * 4, scored)
    out: list[dict] = []
    видели_леммы = set(_леммы(word))
    for _negs, negz, w in top:
        лем = _леммы(w)
        if видели_леммы.intersection(лем):
            continue
        видели_леммы.update(лем)
        out.append({"w": w, "n": _freq_label(-negz)})
        if len(out) >= TOP_RHYMES:
            break
    return out


def _lines_tab(word: str, line: str, corpus, no_mat: bool) -> list[dict]:
    """«Строкой»: фрагменты корпуса, подходящие к слову и к текущей строке.

    Баллы (решение прожарки): +2 точный токен слова, +1 подстрока в тексте,
    +2 рифмо-ключ фрагмента == ключу последнего слова строки (подпись
    «рифма»). Тайбрейкер — банальность: при равном балле выше идёт менее
    банальный фрагмент, это единственный предвычисленный сигнал качества
    (частоты у фрагмента нет).

    Кандидатов собирает либо колоночный индекс (быстро, обычный режим), либо
    проход по `filters._NL_RHYME` (когда индекса нет). Отбор, фильтры и
    подписи — общие, в `_pick_lines`: разъехаться этим двум путям нельзя."""
    if not word:
        return []
    строка = line.strip()
    последнее = _WORDS.get(_канон(filters._last_word(line))) if line else None
    line_key = последнее[0] if последнее else ""
    # Не `nlindex.load()`, а вердикт filters: индекс берётся только если он
    # испечён из ТОГО ЖЕ корпуса, что сейчас в работе. Тесты подменяют
    # `_NL_RHYME` синтетическим пулом, и без этой проверки вкладка отвечала бы
    # по настоящему корпусу вместо подменённого — ровно та ловушка, что уже
    # ловилась при подключении индекса к генерации (Раунд 31, шаг 3).
    idx = filters._index_for_current_cache()
    if idx is not None:
        matches = _lines_by_index(idx, word, line_key)
    else:
        matches = _lines_by_scan(filters._NL_RHYME, word, line_key)
    return _pick_lines(matches, строка, corpus, no_mat)


def _lines_by_index(idx, word: str, line_key: str) -> list:
    """Кандидаты через колонки: обратный индекс токенов и колонка рифмо-ключа.

    Подстрока ищется НЕ по сырому тексту, а по словарю токенов (253 516 слов
    против 2.87 млн текстов): токены, внутри которых есть искомое, дают те же
    фрагменты через тот же обратный индекс. Это и быстрее на два порядка, и
    честнее по смыслу — ловит «деньгами», «деньгах» как ЦЕЛЫЕ слова, а не
    случайное вхождение внутри чужого слова."""
    n = idx.n
    балл = np.zeros(n, dtype=np.int8)
    if line_key:
        kid = _key_id(idx, line_key)
        if kid is not None:
            балл[np.asarray(idx.key_id) == kid] = 2
    рифмует = балл == 2
    точные = idx.token_hits([word])
    балл[точные] += 2
    # подстрочный сигнал для коротких слов сработал бы почти везде — целое
    # токенное совпадение такие слова и так ловит
    if len(word) >= 4:
        похожие = [t for t in idx.tokens if word in t and t != word]
        if похожие:
            под = idx.token_hits(похожие)
            # +1 только тем, кто уже рифмует: у остальных это запасной ярус
            есть_рифма = под[рифмует[под]]
            балл[есть_рифма] += 1
            добор = под[~рифмует[под]]
        else:
            добор = np.empty(0, dtype=np.int64)
    else:
        добор = np.empty(0, dtype=np.int64)
    ids = np.flatnonzero(балл > 0)
    banal = np.asarray(idx.banal)
    out = [(-int(балл[i]), float(banal[i]), bool(рифмует[i]), idx.text(int(i)))
           for i in ids]
    # запасной ярус (балл 1) — только подстрочные, без рифмы и без токена
    добор = добор[балл[добор] == 0]
    out += [(-1, float(banal[i]), False, idx.text(int(i))) for i in добор]
    return out


def _lines_by_scan(nl: dict, word: str, line_key: str) -> list:
    """Тот же отбор проходом по `nl_rhyme.json` — путь без индекса.

    Скан двухпроходный: подстрочный сигнал (балл 1) НИКОГДА не обгоняет
    токенный/рифмо-ярус (балл ≥2), поэтому полный подстрочный проход нужен
    только когда верхних ярусов не хватило (замерено: одним проходом частое
    слово платило ~2-2.5с за C-поиск подстроки по 2.87 млн сырых текстов,
    двумя — ~0.3с). Подстрока ищется по СЫРОМУ тексту без lower(): 2.87 млн
    .lower() на запрос — ещё ~секунда одних аллокаций, а регистрозависимый
    промах покрыт токенами (они уже lowercase)."""
    if not nl:
        return []
    sub = word if len(word) >= 4 else None
    matches: list = []
    ap = matches.append
    for text, entry in nl.items():
        s = 0
        rhymed = False
        if line_key and entry.get("key") == line_key:
            s = 2
            rhymed = True
        toks = entry.get("tokens")
        if toks and word in toks:
            s += 2
        elif s and sub and sub in text:
            s += 1
        if s:
            ap((-s, entry.get("banal", 9.0), rhymed, text))
    if len(matches) < TOP_LINES * 4 and sub:
        have = {m[3] for m in matches}
        for text, entry in nl.items():
            if sub in text and text not in have:
                ap((-1, entry.get("banal", 9.0), False, text))
    return matches


def _key_id(idx, key: str):
    """Номер рифмо-ключа в индексе; None — такого ключа в корпусе нет."""
    if not hasattr(idx, "_key_id_map"):
        idx._key_id_map = {k: i for i, k in enumerate(idx.keys)}
    return idx._key_id_map.get(key)


def _pick_lines(matches: list, line_l: str, corpus, no_mat: bool) -> list[dict]:
    """Верхушка совпавших + честные фильтры. Дорогие проверки (hidden,
    has_mat) — только здесь, по совпавшим: их на порядки меньше пула.
    Частый ключ строки может совпасть у десятков тысяч фрагментов — полная
    сортировка не нужна, достаточно верхушки с запасом под фильтры."""
    if not matches:
        return []
    top = heapq.nsmallest(max(512, TOP_LINES * 4), matches)
    hidden = corpus.hidden_set() if corpus is not None else set()
    out: list[dict] = []
    for _negs, _banal, rhymed, text in top:
        if text == line_l or text in hidden:
            continue
        if no_mat and filters.has_mat(text):
            continue
        out.append({"w": text, "n": "рифма" if rhymed else ""})
        if len(out) >= TOP_LINES:
            break
    return out


def _navec_vocab() -> list:
    """Обратный словарь navec, лениво (см. _NAVEC_WORDS)."""
    global _NAVEC_WORDS
    if _NAVEC_WORDS is None and embeddings._index is not None:
        vocab = [""] * len(embeddings._index)
        for w, i in embeddings._index.items():
            vocab[i] = w
        _NAVEC_WORDS = vocab
    return _NAVEC_WORDS or []


def _navec_neighbors(word: str, top: int, exclude: set) -> list[str]:
    """Топ-N соседей слова по косинусу в navec — векторный слой «близкое».
    Исключаются: само слово, уже показанные словарные (exclude), однокоренные
    (_same_root, тот же порог ≥5, что у рифм — «деньги → деньгам» не
    ассоциация, а падеж), РАЗНЫЕ ФОРМЫ ОДНОГО слова между собой («вечер,
    вечера, вечером» — одна ассоциация, а не три; жалоба владельца
    2026-08-02) и не-кириллица (в словаре модели есть латиница и
    пунктуация). Один matmul по всему словарю + argpartition верхушки с
    запасом — та же дисциплина, что theme_similarities: не 500k питоновых
    сравнений, а одна векторная операция."""
    if top <= 0 or not embeddings._ensure_loaded():
        return []
    idx = embeddings._index.get(word)
    if idx is None:
        return []   # слова нет в словаре модели → слой честно пуст
    vocab = _navec_vocab()
    sims = embeddings._vectors @ embeddings._vectors[idx]
    # Запас x4+8: часть верхушки отсеется фильтрами; если не хватило — значит
    # рядом почти одни формы слова, добирать дальше нечестно (там уже чужое).
    k = min(len(sims), top * 4 + 8)
    cand = np.argpartition(-sims, k - 1)[:k]
    cand = cand[np.argsort(-sims[cand])]
    out: list[str] = []
    видели_леммы = set(_леммы(word))
    for x in exclude:
        видели_леммы.update(_леммы(x))
    for i in cand:
        w = vocab[int(i)]
        if w == word or w in exclude:
            continue
        if not _CYR_ONLY.fullmatch(w):
            continue
        if _same_root(word, w):
            continue
        лем = _леммы(w)
        if видели_леммы.intersection(лем):
            continue
        видели_леммы.update(лем)
        out.append(w)
        if len(out) >= top:
            break
    return out


def _syn_tab(word: str) -> list[dict]:
    """«Синонимы»: словарный слой (n='словарь') + добор векторным (n='близкое')
    до TOP_WORDS. Словарные строго выше векторных — проверенный людьми словарь
    доверия стоит больше, чем косинусная близость (решение прожарки). Вектора
    только ДОБИРАЮТ до общей длины вкладки, не удлиняют её: список попапа
    одного размера с рифмами, а не бездонная лента ассоциаций."""
    dict_words = [w for w in _dict_lookup("syn", word) if not _same_root(word, w)][:TOP_WORDS]
    items = [{"w": w, "n": "словарь"} for w in dict_words]
    room = TOP_WORDS - len(items)
    if room > 0:
        near = _navec_neighbors(word, room, set(dict_words))
        items += [{"w": w, "n": "близкое"} for w in near]
    return items


def _ant_tab(word: str) -> list[dict]:
    """«Антонимы»: ТОЛЬКО словарь. Векторного слоя нет сознательно (решение
    прожарки): у статических эмбеддингов противоположности — ближайшие соседи
    (общие контексты), топ по косинусу выдал бы синонимы под видом антонимов."""
    return [{"w": w, "n": "словарь"} for w in _dict_lookup("ant", word)[:TOP_WORDS]]


def suggest(word: str, tab: str, line: str = "", corpus=None, no_mat: bool = False) -> list[dict]:
    """Подсказки для попапа: список {w, n, t} по контракту /api/word/suggest.

    `t` — тип рифмы (богатая/точная/усечённая/неточная) на вкладке «рифмы»
    и пустая строка везде ещё: попап рисует заголовок группы при смене `t`,
    поэтому неточная рифма подписана неточной, а не выдана за точную.
    Валидация word/tab — забота роута (api/server.py); здесь word уже
    ожидается непустым. Пустой список — честный ответ («—» на фронте),
    никогда не догадки."""
    w = _канон(word.strip().lower())
    if tab == "рифмы":
        items = _rhymes_tab(w)
    elif tab == "по звуку":
        items = _sound_tab(w)
    elif tab == "строкой":
        items = _lines_tab(w, line or "", corpus, no_mat)
    elif tab == "синонимы":
        items = _syn_tab(w)
    elif tab == "антонимы":
        items = _ant_tab(w)
    else:
        return []
    # Поле `t` добираем ЗДЕСЬ, в одном месте, а не в каждой вкладке: контракт
    # ответа обязан быть одинаков у всех пяти, иначе фронт получал бы то
    # {w,n}, то {w,n,t} и раскладывал по-разному.
    for it in items:
        it.setdefault("t", "")
    return items
