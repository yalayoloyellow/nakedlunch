def _skeleton(word: str) -> str:
    """Согласный скелет начала слова (первые 3 согласных): lower, ё→е,
    оглушение той же таблицей _DEVOICE, что в rhyme_key — чтобы «сказка» и
    «глазки» сходились по звуку, а не по орфографии. ь/ъ и не-кириллица
    выпадают: они звука скелету не добавляют."""
    out = []
    for ch in word.lower().replace("ё", "е"):
        if ch in scan.VOWELS or ch in "ьъ" or not ("а" <= ch <= "я"):
            continue
        out.append(scan._DEVOICE.get(ch, ch))
        if len(out) == 3:
            break
    return "".join(out)


def _опорная(word: str, key: str) -> str:
    """Согласная перед ударным гласным — КОПИЯ логики сборки только для
    старого индекса (см. _activate). Настоящий источник —
    tools/build_rhyme_index.опорная, там она считается один раз на сборке;
    здесь нужна лишь чтобы двухполевой файл (или тестовая мини-фикстура) не
    падал, а честно доработал без перепечи."""
    if not key or len(key) > len(word):
        return ""
    j = len(word) - len(key) - 1
    while j >= 0 and word[j] in "ьъ":
        j -= 1
    if j < 0:
        return ""
    ch = word[j]
    return "" if ch in scan.VOWELS else ch


def _activate(data: dict) -> None:
    """Построить рантайм-структуры из содержимого rhyme_index.json.
    Отдельно от warm_caches, чтобы тесты подставляли МИНИ-индекс фикстурой,
    не таща словарь на 668k слов в тестовый прогон (та же дисциплина, что
    подмена filters._NL_RHYME в tests/test_realpath.py).

    Запись индекса — [ключ, zipf, опора, лемма, подозр] (Раунд 32). Файл
    старого формата [ключ, zipf] дополняем на лету: опору считаем сами,
    лемму подменяем самим словом, подозрительность обнуляем. Это НЕ второй
    формат про запас — это честная деградация до перепечи: дедуп по лемме
    тогда просто ничего не схлопнет, подозрительное ничего не опустит, а
    опорная согласная будет работать в полную силу."""
    global _WORDS, _KEYS, _SKEL, _SKEL_BUCKET, _KEYS_VOW, _YO
    words = data.get("words", {})
    if words and len(next(iter(words.values()))) < 5:
        words = {w: [e[0], e[1], _опорная(w, e[0]), [w], 0] for w, e in words.items()}
    _WORDS = words
    _KEYS = data.get("keys", {})
    _SKEL, _SKEL_BUCKET, _KEYS_VOW, _YO = {}, None, None, None


