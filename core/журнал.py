# nakedlunch — ОДИН журнал на всё приложение (Раунд 59).
#
# ЗАЧЕМ. Программу дают людям, которые пишут тексты, а не читают стеки. Значит
# работает правило: если что-то не работает, человек должен УВИДЕТЬ причину на
# экране и одним нажатием отправить её целиком. Лезть в папку за файлом он не
# должен и не будет.
#
# Журналов до этого было три, и все в разных местах: `data/интерфейс.log` от
# окна, `data/сборки.log` от сборок, вывод сервера — в никуда (из .app stdout
# уходит в системный лог, которого никто не видит). Собрать из этого картину
# мог только тот, кто знает, где что лежит. Теперь один файл и один отчёт.
#
# ДВА ХРАНИЛИЩА, И ЭТО НЕ ДУБЛИРОВАНИЕ:
#   · КОЛЬЦО В ПАМЯТИ — чтобы вкладка «Лог» открывалась мгновенно и не читала
#     мегабайты с диска на каждый показ;
#   · ФАЙЛ НА ДИСКЕ — чтобы журнал пережил падение процесса. Кольцо умирает
#     вместе с программой, а причина смерти нужна именно после неё.
#
# ПРОШЛАЯ СЕССИЯ СОХРАНЯЕТСЯ ЦЕЛИКОМ. При старте текущий файл переносится в
# `сессия-прошлая.log`, и если предыдущий запуск кончился аварийно, его журнал
# лежит нетронутым — а не затирается первой же строкой нового.
#
# ЖУРНАЛ НЕ ИМЕЕТ ПРАВА УРОНИТЬ ПРОГРАММУ. Любая ошибка записи глотается: не
# записать строку — неприятно, упасть из-за строки — недопустимо.

from __future__ import annotations

import json
import os
import platform
import sys
import threading
import time
import traceback
from collections import deque
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
ПАПКА = КОРЕНЬ / "data"
# АРХИВ ВСЕХ СЕССИЙ, А НЕ ДВУХ (Раунд 59). Ошибка редко видна в том же запуске,
# в котором родилась: человек замечает странность через день и присылает журнал
# уже другой сессии. Поэтому храним все — по файлу на запуск, с ограничением
# по числу и объёму, чтобы папка не росла без края.
АРХИВ = ПАПКА / "журнал"
ФАЙЛ = ПАПКА / "сессия.log"          # текущая сессия
ПРОШЛЫЙ = ПАПКА / "сессия-прошлая.log"
# Отметка чистого выхода. Есть — прошлый запуск закрылся сам; нет — упал или
# был убит, и это единственный способ отличить одно от другого после факта.
ОТМЕТКА = ПАПКА / "сессия.закрыта"
СЕССИЙ_ХРАНИМ = 40                    # запусков в архиве
АРХИВ_МАКС = 40 * 1024 * 1024         # и не больше сорока мегабайт суммарно

КОЛЬЦО_МАКС = 3000          # записей в памяти
ФАЙЛ_МАКС = 8 * 1024 * 1024  # больше — и копирование в буфер станет пыткой

_кольцо: deque = deque(maxlen=КОЛЬЦО_МАКС)
_замок = threading.Lock()
_начало = time.time()
_счёт = {"ошибок": 0, "всего": 0}


def _строка(з: dict) -> str:
    т = time.strftime("%H:%M:%S", time.localtime(з["t"]))
    у = {"ошибка": "ОШИБКА", "внимание": "ВНИМАНИЕ"}.get(з["уровень"], "")
    return f"{т} {з['откуда']:<8} {у + ' ' if у else ''}{з['текст']}"


def запись(откуда: str, текст: str, уровень: str = "инфо") -> None:
    """Одна строка журнала. `откуда` — сервер · окно · сборка · запуск."""
    з = {"t": time.time(), "откуда": str(откуда)[:12],
         "уровень": уровень, "текст": str(текст)[:4000]}
    try:
        with _замок:
            _кольцо.append(з)
            _счёт["всего"] += 1
            if уровень == "ошибка":
                _счёт["ошибок"] += 1
            try:
                ПАПКА.mkdir(parents=True, exist_ok=True)
                if ФАЙЛ.exists() and ФАЙЛ.stat().st_size > ФАЙЛ_МАКС:
                    ФАЙЛ.unlink()
                with open(ФАЙЛ, "a", encoding="utf-8") as f:
                    f.write(_строка(з) + "\n")
            except OSError:
                pass
    except Exception:
        pass                    # журнал не роняет программу. Никогда.


def ошибка(откуда: str, текст: str, искл: BaseException | None = None) -> None:
    """Ошибка со стеком. Стек — не украшение: без него причина «не удалось»
    ничем не отличается от «не знаю»."""
    if искл is not None:
        текст = f"{текст}: {type(искл).__name__}: {искл}\n" + \
                "".join(traceback.format_exception(type(искл), искл, искл.__traceback__))[-2500:]
    запись(откуда, текст, "ошибка")


def _подрезать_архив() -> None:
    """Оставить последние СЕССИЙ_ХРАНИМ файлов и не больше АРХИВ_МАКС байт.
    Старое уходит первым: свежая сессия объясняет больше, чем прошлогодняя."""
    try:
        файлы = sorted(АРХИВ.glob("*.log"), key=lambda p: p.stat().st_mtime, reverse=True)
        объём = 0
        for i, f in enumerate(файлы):
            объём += f.stat().st_size
            if i >= СЕССИЙ_ХРАНИМ or объём > АРХИВ_МАКС:
                f.unlink(missing_ok=True)
    except Exception:
        pass


def начать_сессию(кто: str = "запуск") -> None:
    """Новый запуск: прошлый журнал уходит в архив целиком, отметка чистого
    выхода снимается. Вызывается ОДИН раз, из launch.py."""
    try:
        ПАПКА.mkdir(parents=True, exist_ok=True)
        АРХИВ.mkdir(parents=True, exist_ok=True)
        if ФАЙЛ.exists():
            try:
                метка = time.strftime("%Y-%m-%d_%H-%M-%S",
                                      time.localtime(ФАЙЛ.stat().st_mtime))
                хвост = "-аварийно" if not ОТМЕТКА.exists() else ""
                import shutil
                shutil.copy2(ФАЙЛ, АРХИВ / f"{метка}{хвост}.log")
            except Exception:
                pass
            try:
                os.replace(ФАЙЛ, ПРОШЛЫЙ)
            except OSError:
                pass
        _подрезать_архив()
        аварийно = не_закрыто()
        if ОТМЕТКА.exists():
            ОТМЕТКА.unlink()
        запись(кто, f"сессия начата · {среда_строкой()}")
        if аварийно:
            запись(кто, "прошлый запуск закончился аварийно — его журнал в "
                        f"{ПРОШЛЫЙ.name}", "внимание")
    except Exception:
        pass


def закрыть_сессию(кто: str = "запуск") -> None:
    """Чистый выход. Отметка ставится ПОСЛЕДНИМ действием: если её нет —
    значит до конца не дошли."""
    try:
        запись(кто, "сессия закрыта штатно")
        ОТМЕТКА.write_text(str(time.time()), "utf-8")
    except Exception:
        pass


def не_закрыто() -> bool:
    """Прошлый запуск не поставил отметку — то есть упал или был убит."""
    try:
        return ПРОШЛЫЙ.exists() and not ОТМЕТКА.exists()
    except Exception:
        return False


def среда_строкой() -> str:
    return (f"{platform.system()} {platform.release()} · {platform.machine()} · "
            f"python {sys.version.split()[0]}")


def состояние() -> dict:
    """Что есть на диске прямо сейчас. Для отчёта: половина обращений
    объясняется не ошибкой, а тем, что артефакт не собран."""
    из_данных = КОРЕНЬ / "core" / "data"

    def мб(p: Path) -> str:
        try:
            if p.is_dir():
                n = sum(x.stat().st_size for x in p.iterdir() if x.is_file())
            else:
                n = p.stat().st_size
            return f"{n / 1024 / 1024:.0f} МБ"
        except Exception:
            return "нет"

    return {
        "словарь ударений (rhyme_index.json)": мб(из_данных / "rhyme_index.json"),
        "формы (forms.json)": мб(из_данных / "forms.json"),
        "векторы (navec.tar)": мб(из_данных / "navec.tar"),
        "кэш ударений (nl_rhyme.jsonl)": мб(из_данных / "nl_rhyme.jsonl"),
        "индекс корпуса (nl_index)": мб(из_данных / "nl_index"),
    }


def записи(сколько: int = 800) -> list[dict]:
    with _замок:
        return list(_кольцо)[-сколько:]


def отчёт(добавка: dict | None = None) -> str:
    """ВЕСЬ отчёт одним текстом — то, что человек копирует одной кнопкой.

    Порядок намеренный: сначала среда и состояние артефактов (по ним видно
    половину причин), потом счётчики, потом сами записи. Кто будет читать —
    прочтёт сверху вниз и остановится, как только поймёт."""
    части = ["=== nakedlunch · отчёт о сессии ===",
             f"время         {time.strftime('%Y-%m-%d %H:%M:%S')}",
             f"среда         {среда_строкой()}",
             f"в работе      {int(time.time() - _начало)} с",
             f"записей       {_счёт['всего']}, из них ошибок {_счёт['ошибок']}"]
    if не_закрыто():
        части.append("ВНИМАНИЕ      прошлый запуск закончился аварийно")
    части.append("")
    части.append("--- данные на диске ---")
    for k, v in состояние().items():
        части.append(f"{k:<38} {v}")
    if добавка:
        части.append("")
        части.append("--- состояние приложения ---")
        for k, v in добавка.items():
            части.append(f"{k:<38} {v}")
    части.append("")
    части.append("--- журнал сессии ---")
    for з in записи():
        части.append(_строка(з))
    прошлый = прошлый_журнал()
    if прошлый:
        части.append("")
        части.append("--- прошлая сессия (закончилась аварийно) ---")
        части.append(прошлый)
    return "\n".join(части)


def прошлый_журнал(хвост: int = 12000) -> str:
    """Хвост журнала прошлой сессии — если она закончилась аварийно. Именно он
    и нужен: причина падения записана в НЁМ, а не в текущем."""
    try:
        if не_закрыто() and ПРОШЛЫЙ.exists():
            return ПРОШЛЫЙ.read_text("utf-8", errors="replace")[-хвост:]
    except Exception:
        pass
    return ""


def как_json() -> str:
    return json.dumps({"записи": записи(), "счёт": dict(_счёт)}, ensure_ascii=False)


