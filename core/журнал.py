# ОТПРАВИТЬ, А НЕ ПРОЧИТАТЬ (Раунд 59).
#
# Тестер — не инженер. Ему нельзя давать задачу «найди папку, собери файлы,
# приложи». Задача должна быть одна: нажать кнопку и перетащить получившийся
# файл в переписку. Поэтому отчёт сохраняется НА РАБОЧИЙ СТОЛ под понятным
# именем и сразу показывается в проводнике.

def _рабочий_стол() -> Path:
    """Рабочий стол или, если его нет, домашняя папка. На Linux он бывает
    переименован по локали — тогда домашняя папка честнее, чем промах."""
    for имя in ("Desktop", "Рабочий стол"):
        p = Path.home() / имя
        if p.is_dir():
            return p
    return Path.home()


def архив_текстом(предел: int = 3_000_000) -> str:
    """ВСЕ сессии одним текстом, свежие сверху.

    Предел стоит не ради экономии, а ради адресата: файл на десятки мегабайт
    невозможно ни открыть, ни переслать, и вместо помощи он создаёт вторую
    проблему."""
    куски, объём = [], 0
    try:
        файлы = sorted(АРХИВ.glob("*.log"), key=lambda p: p.stat().st_mtime, reverse=True)
    except Exception:
        файлы = []
    for f in файлы:
        try:
            т = f.read_text("utf-8", errors="replace")
        except Exception:
            continue
        куски.append(f"\n===== сессия {f.stem} =====\n{т}")
        объём += len(т)
        if объём > предел:
            куски.append(f"\n[...ещё {len(файлы) - len(куски)} сессий не поместились]")
            break
    return "".join(куски) if куски else "(архив пуст — это первый запуск)"


def сохранить_отчёт(добавка: dict | None = None, всё: bool = True) -> Path:
    """Записать отчёт файлом на рабочий стол и вернуть путь.

    `всё=True` — вместе с архивом прошлых сессий: человек замечает странность
    через день, и журнал ТОГО запуска нужнее текущего."""
    т = отчёт(добавка)
    if всё:
        т += "\n\n=== ПРЕДЫДУЩИЕ СЕССИИ ===\n" + архив_текстом()
    имя = f"nakedlunch-отчёт-{time.strftime('%Y-%m-%d_%H-%M')}.txt"
    путь = _рабочий_стол() / имя
    путь.write_text(т, "utf-8")
    return путь


def показать_в_проводнике(путь: Path) -> bool:
    """Открыть папку с файлом и выделить его. Три системы — три команды; не
    получилось ни одной, значит человек найдёт файл сам, а путь ему покажут."""
    import subprocess
    try:
        if sys.platform == "darwin":
            subprocess.run(["open", "-R", str(путь)], timeout=10)
        elif os.name == "nt":
            subprocess.run(["explorer", "/select,", str(путь)], timeout=10)
        else:
            subprocess.run(["xdg-open", str(путь.parent)], timeout=10)
        return True
    except Exception:
        return False
