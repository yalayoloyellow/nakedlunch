# nakedlunch — цепочка фоновых сборок (Раунд 52).
#
# ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Живёт это в api/server.py по смыслу, но импорт
# сервера поднимает корпус и индекс — 69 секунд и правка настоящей истории
# владельца, в наборе тестов такому не место (см. tests/test_funnel_contract.py:
# ровно из-за этого 500-я на каждой генерации прожила день). Значит всё, что
# можно проверить, обязано жить там, где тест до него дотянется.
#
# ЧТО ЗДЕСЬ РЕШАЕТСЯ. У загруженной книги ДВА шага: кэш рифм и колоночный
# индекс, и второй печётся ИЗ первого. Запускать их параллельно бессмысленно —
# индекс испёк бы ровно то, что было до книги.

from __future__ import annotations

import threading


def then(proc, дальше, on_error=None) -> threading.Thread:
    """Дождаться процесса в фоне и сделать следующий шаг.

    Возвращает поток — чтобы тест мог дождаться, а не угадывать таймаутом.
    Исключение следующего шага не роняет поток молча: оно уходит в `on_error`,
    иначе цепочка обрывалась бы без единого признака."""
    def ждать():
        try:
            proc.wait()
        except Exception as e:
            if on_error:
                on_error(e)
            return
        try:
            дальше()
        except Exception as e:
            if on_error:
                on_error(e)

    t = threading.Thread(target=ждать, name="nl-chain", daemon=True)
    t.start()
    return t
