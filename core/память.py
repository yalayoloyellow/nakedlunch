"""Помещается ли работа в память ЭТОЙ машины — один расчёт на всю программу.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. У программы есть ровно один расход, который зависит не
от запроса, а от железа: без колоночного индекса запасной путь поднимает
словарь рифм ЦЕЛИКОМ. Замерено на рабочем корпусе — файл в 946 МБ на диске даёт
около 5.5 ГБ резидентной памяти на весь срок жизни процесса, то есть примерно
вшестеро. На машине с шестнадцатью гигабайтами это заметно; на восьми — своп, и
не «медленно», а намертво: система начинает выгружать сама себя, а человек
видит зависшее окно без единого слова о причине.

Спрашивают отсюда двое, и оба обязаны спрашивать ОДНО И ТО ЖЕ:
  · `core/filters.py` — прямо перед загрузкой, последний рубеж;
  · `launch.py` — до запуска ядра, чтобы отказ попал в окно, а не превратился
    в «ядро не ответило за отведённое время».

Второе и есть причина, по которой расчёт живёт не внутри filters: запускальщик
не может тянуть numpy и индекс ради одного деления.

Зависимостей нет: только stdlib.
"""

from __future__ import annotations

import os
from pathlib import Path

# Во столько раз словарь в памяти больше файла на диске. Число СНЯТО ЗАМЕРОМ на
# рабочем корпусе (946 МБ → ~5.5 ГБ), а не назначено с запасом.
РАЗБУХАНИЕ = 6

# Столько оставляем системе и движку окна — они живут в той же памяти.
ЗАПАС_ГБ = 3.0

# Ключ для того, кто знает, что делает, и готов к свопу.
КЛЮЧ = "NAKEDLUNCH_ПАМЯТЬ"
СНЯТЬ = "не_спрашивай"

ГБ = 1024 ** 3


class НеХватит(RuntimeError):
    """Загрузка не начата: она бы не поместилась. Отказ по расчёту, не сбой."""


def озу_байт() -> int:
    """Сколько всего оперативной памяти, в байтах. 0 — «система не ответила».

    Ноль обязан читаться как «не знаю», а не «нисколько»: отказать по незнанию
    значит сломать машину, на которой всё бы работало.
    """
    try:
        return os.sysconf("SC_PAGE_SIZE") * os.sysconf("SC_PHYS_PAGES")
    except (ValueError, OSError, AttributeError):
        return 0


def _гб(b: float) -> str:
    return f"{b / ГБ:.1f} ГБ"


def проверить_словарь(файл: Path | str) -> None:
    """Бросить `НеХватит`, если словарь рифм не поместится. Иначе молча выйти.

    Отказ называет ЧИСЛА и ВЫХОД. Отказ без выхода не лучше зависания: человек
    всё равно не знает, что делать дальше.
    """
    if os.environ.get(КЛЮЧ) == СНЯТЬ:
        return
    всего = озу_байт()
    if not всего:
        return
    try:
        размер = Path(файл).stat().st_size
    except OSError:
        return                       # файла нет — грузить нечего, не наше дело
    нужно = размер * РАЗБУХАНИЕ
    доступно = всего - int(ЗАПАС_ГБ * ГБ)
    if нужно <= доступно:
        return
    raise НеХватит(
        f"словарь рифм не поместится в память этой машины.\n\n"
        f"  файл на диске:   {_гб(размер)}\n"
        f"  нужно в памяти:  {_гб(нужно)} (примерно вшестеро, замерено)\n"
        f"  всего памяти:    {_гб(всего)}\n"
        f"  можно занять:    {_гб(доступно)} (остальное — системе и окну)\n\n"
        f"Этот путь включается только когда нет колоночного индекса.\n"
        f"Привези испечённый индекс (core/data/nl_index) с машины, где он есть:\n"
        f"с ним словарь целиком не читается вовсе, данные идут через mmap.\n"
        f"Либо испеки его здесь:\n"
        f"  .venv/bin/python tools/build_nl_index.py\n\n"
        f"Снять проверку и уйти в своп: {КЛЮЧ}={СНЯТЬ}")
