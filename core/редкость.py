# nakedlunch — РЕДКОСТЬ: две шкалы строки, считаются при печати индекса.
#
# ЗАМЫСЕЛ (2026-08-25), собранный из четырёх его поправок:
#
#   1. «редкость — мы замеряем по всему корпусу, а не по одной книге»
#   2. «если слово в самой книге очень частое, оно не может быть самым редким
#      по определению — это выборку объективнее делает»
#   3. «не либо-либо, а среднее арифметическое»
#   4. «мы перемножаем редкость каждого слова, а не какого-то одного»
#
# ФОРМУЛА ОСИ «СЛОВА»:
#
#     редкость слова  = ( доля в корпусе + доля в своей книге ) / 2
#     редкость строки = ( р₁ × р₂ × … × рₙ ) ^ 1/n        ← корень обязателен
#
# ПОЧЕМУ КОРЕНЬ. Без него произведение падает с каждым множителем, и крутилка
# превращается в измеритель длины: замер дал связь с числом слов −0.950, а в
# редкий конец шли не редкие строки, а длинные (медиана 8 слов против 4 по
# корпусу). Корень приводит к одному слову и связь с длиной убирает: −0.046.
# Замысел при этом цел — участвуют ВСЕ слова, каждое своим множителем.
#
# ФОРМУЛА ОСИ «ПАРА»: та же двусторонняя редкость, но у ПАРЫ соседних лемм, и
# по строке берётся САМАЯ РЕДКАЯ пара, а не средняя. Ось отвечает на вопрос
# «есть ли в строке дикое сочетание», а одного дикого достаточно.
#
# ДВЕ ОСИ, А НЕ ОДНА. Замер на боевом корпусе: связь между ними r = +0.298, то
# есть они правда разные. Слить их в одну крутилку нельзя — теряется целый угол
# «обычные слова в диком сочетании», который в единой шкале размазывается по
# середине и становится недостижим.
#
# ШКАЛА — ПРОЦЕНТИЛЬ СРЕДИ СТРОК, а не среди слов. По словарю она схлопывается:
# минимум даёт 51% строк в верхнем ярусе, среднее 79%, медиана 90%. Причина —
# в любой строке почти всегда есть хоть одно частое слово. Процентиль по
# строкам ровен по построению: полоса [a%, b%] всегда даёт b−a процентов.
#
# НАПРАВЛЕНИЕ: 0% — САМЫЕ НЕРЕДКИЕ, 100% — САМЫЕ РЕДКИЕ. Первая версия шла
# наоборот, и это поймалось сразу: «ведь 0 процентов редкости это самые
# нередкие должны быть». У ручки с именем «Редкость» ноль обязан значить
# «редкости нет», иначе имя врёт о шкале.
#
# ЧТО ЗНАЧИТ −1. Строка, у которой шкалы НЕТ: для оси «слова» это строка без
# единой леммы, для оси «пара» — строка, где лемма всего одна и пары не из
# чего составить. Такая строка не пройдёт ни одну полосу, и это честно: у неё
# нет того, что полоса отбирает. Замер по боевому корпусу: до ворот доживают
# 2 111 382 строки, из них без леммы 3 262 (0.15%), с одной леммой 58 329
# (2.8%). Ради этих 2.8% ось «слова» и считается от ОДНОЙ леммы, а не от пары:
# это короткие строки, а короткая строка в песне дорога.

from __future__ import annotations

import numpy as np

НЕТ_ШКАЛЫ = np.float32(-1.0)


def _лог(v):
    return np.log10(np.maximum(v, 1e-12))


def процентиль(v: np.ndarray, наоборот: bool = True) -> np.ndarray:
    """Место в ряду, шкалой 0..100.

    `наоборот=True` (редкость) — считаем по ЧАСТОТЕ: чем меньше, тем реже,
    поэтому переворачиваем и 100 достаётся самым редким. `наоборот=False`
    (плотность звука) — сырое значение УЖЕ растёт в нужную сторону, и 100
    достаётся самым залитым.

    ОДНА ФУНКЦИЯ НА ВСЕ ПОЛОСНЫЕ ОСИ (2026-08-30). Своя копия этой формулы
    лежала в `core/звукопись.py` и отличалась только знаком — то есть правило
    ровности шкалы держалось в двух местах сразу. Разойдись они, и полоса на
    одной оси перестала бы значить то же, что на другой.

    РАВНЫЕ РАЗВОДЯТСЯ, и это не небрежность, а условие ровности шкалы. Полоса
    [a%, b%] обязана давать ровно b−a процентов корпуса — иначе «топ 1 процент»
    перестанет быть одним процентом. Дать равным одно место значило бы копить
    их в одной ячейке и опустошать соседние. Место среди равных произвольно —
    честная цена за ровную шкалу; на плотности этот жребий особенно заметен,
    потому что там равных нулей треть корпуса (см. `звукопись.шкалы`)."""
    if len(v) < 2:
        return np.zeros(len(v), dtype=np.float32)
    место = np.argsort(np.argsort(v))
    доля = место / (len(v) - 1) * 100
    return ((100 - доля) if наоборот else доля).astype(np.float32)


def шкалы(lem_ids: np.ndarray, lem_off: np.ndarray, src: np.ndarray,
          n_лемм: int) -> tuple[np.ndarray, np.ndarray]:
    """Две колонки редкости по строкам индекса: («слова», «пара»).

    На вход — те же массивы, что уже собраны для индекса: леммы строк подряд,
    границы строк, номер книги строки. Ничего лишнего не читается: обе шкалы
    целиком выводятся из состава корпуса.
    """
    n = len(lem_off) - 1
    off = np.asarray(lem_off, dtype=np.int64)
    ids = np.asarray(lem_ids, dtype=np.int64)
    кн_строки = np.maximum(np.asarray(src, dtype=np.int64), 0)
    n_кн = int(кн_строки.max()) + 1 if n else 1
    лемм = np.diff(off)

    # ---- сколько раз лемма встречается: по корпусу и по своей книге ---------
    кн_вхожд = np.repeat(кн_строки, лемм)
    счёт = np.bincount(кн_вхожд * n_лемм + ids,
                       minlength=n_кн * n_лемм).reshape(n_кн, n_лемм).astype(np.float64)
    всего = счёт.sum()
    доля_корпус = счёт.sum(axis=0) / (всего or 1)
    размер = счёт.sum(axis=1)
    размер[размер == 0] = 1
    доля_книга = счёт / размер[:, None]

    # ---- ось «слова»: среднее логарифмов = корень из произведения -----------
    # log(∏xᵢ)/n = log(∏xᵢ^1/n) — то самое «корень обязателен», только без
    # переполнения, которым грозит произведение двух миллионов множителей.
    на_вхожд = (_лог(доля_корпус[ids]) + _лог(доля_книга[кн_вхожд, ids])) / 2
    строка_вхожд = np.repeat(np.arange(n, dtype=np.int64), лемм)
    сумма = np.bincount(строка_вхожд, weights=на_вхожд, minlength=n)
    есть_слово = лемм >= 1
    слова = np.full(n, НЕТ_ШКАЛЫ, dtype=np.float32)
    слова[есть_слово] = процентиль(сумма[есть_слово] / лемм[есть_слово])

    # ---- ось «пара»: та же двусторонняя редкость у соседних лемм ------------
    пар = np.maximum(0, лемм - 1)
    есть_пара = пар > 0
    ном = np.flatnonzero(есть_пара)
    пара = np.full(n, НЕТ_ШКАЛЫ, dtype=np.float32)
    if len(ном):
        лев = np.concatenate([ids[off[i]:off[i + 1] - 1] for i in ном])
        прав = np.concatenate([ids[off[i] + 1:off[i + 1]] for i in ном])
        код = лев * n_лемм + прав
        кн_пары = np.repeat(кн_строки[ном], пар[ном])
        _, обр_к, сч_к = np.unique(код, return_inverse=True, return_counts=True)
        доля_пара_корпус = сч_к[обр_к] / сч_к.sum()
        _, обр_б, сч_б = np.unique(кн_пары * (n_лемм * n_лемм) + код,
                                   return_inverse=True, return_counts=True)
        пар_книги = np.bincount(кн_пары, minlength=n_кн).astype(np.float64)
        пар_книги[пар_книги == 0] = 1
        доля_пара_книга = сч_б[обр_б] / пар_книги[кн_пары]
        границы = np.zeros(len(ном) + 1, dtype=np.int64)
        границы[1:] = np.cumsum(пар[ном])
        # МИНИМУМ, А НЕ СРЕДНЕЕ: ось отвечает на вопрос «есть ли в строке дикое
        # сочетание», и одного дикого достаточно. Среднее размывало бы его
        # остальными парами строки.
        сырое = (np.minimum.reduceat(_лог(доля_пара_корпус), границы[:-1])
                 + np.minimum.reduceat(_лог(доля_пара_книга), границы[:-1])) / 2
        пара[ном] = процентиль(сырое)

    return слова, пара


def маска_полос(колонка: np.ndarray, полосы) -> np.ndarray | None:
    """Маска строк, попавших ХОТЯ БЫ В ОДНУ из выбранных полос.

    ПОЛОСЫ, А НЕ ПОРОГ, — Требование: «я хочу мочь выбрать
    допустим диапазон с 5 по 10 процентов по редкости + диапазон с 17 по 18 +
    с 97 по 98, и все это в выдаче участвует и все это я выбрал руками, а
    остальное не участвует».

    Ползунок с порогом такого не умеет по устройству: он выражает «не ниже» и
    «не выше», то есть один отрезок. Отсюда и полоса из ста ячеек на экране.

    Строка без шкалы (−1) не попадает ни в одну полосу и отсеивается — у неё
    нет того, что полоса отбирает."""
    if not полосы:
        return None
    v = np.asarray(колонка)
    m = np.zeros(len(v), dtype=bool)
    for низ, верх in полосы:
        m |= (v >= низ) & (v < верх)
    return m


def разобрать_полосы(запись: str | None):
    """«5-10,17-18,97-98» → [(5,10), (17,18), (97,98)]. Пустое → [].

    Ноль-в-ноль («50-50») и перевёрнутое («10-5») отбрасываются: полоса нулевой
    ширины не отбирает ничего, а перевёрнутая — описка, и молча превращать её в
    прямую значит угадывать за пользователя.

    Верхняя граница 100 включительно: «97-100» обязано брать и самую последнюю
    строку, иначе сотая ячейка недостижима вовсе."""
    if not запись:
        return []
    полосы = []
    for кусок in str(запись).split(","):
        кусок = кусок.strip()
        if not кусок:
            continue
        а, _, б = кусок.partition("-")
        try:
            низ, верх = float(а), float(б)
        except ValueError:
            continue
        if верх <= низ:
            continue
        полосы.append((низ, 100.0001 if верх >= 100 else верх))
    return полосы
