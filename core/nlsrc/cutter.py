"""
Cutter: детерминированная нарезка текста на рваные фрагменты (cut-up стиль).

Правила:
- Однотипная обработка для поэзии и прозы.
- "Грязные" разрезы: обрывы посередине, мосты между предложениями, скользящие окна.
- Детерминировано (без random в основном пути).
- Фильтрация короткого мусора.
"""

from __future__ import annotations

import html
import re
from functools import lru_cache
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import List

import pymorphy3

_morph = pymorphy3.MorphAnalyzer()


_ПЕРЕНОС = re.compile(
    r"([а-яёa-zA-Z]+)-[ \t]*\r?\n[ \t]*([а-яёa-z]+)")
_СОЮЗЫ = frozenset(("и", "или", "иль", "да", "а", "но", "ни"))
# Как часто докладывать о ходе разметки имён. 20 000 слов — примерно
# полсекунды работы: чаще незачем, реже уже заметна неподвижность.
_ШАГ_ИМЁН = 20_000


@lru_cache(maxsize=1 << 16)
def _срастить(голова: str, хвост: str) -> str:
    """Как сшить «голова-\nхвост»: одним словом или через дефис.

    СПРАШИВАЕМ СЛОВАРЬ, А НЕ ГАДАЕМ (2026-08-21). Прежнее правило снимало
    дефис ВСЕГДА, и на самом частом месте переноса — на собственном дефисе
    слова — портило текст:

        где-\nто      → «гдето»       ✗
        из-\nза       → «изза»        ✗
        кто-\nнибудь  → «ктонибудь»   ✗

    Вёрстка рвёт строку по дефису охотнее всего: он уже там стоит. Значит
    случай не редкий, а частый.

    Правило: если слитная форма ЕСТЬ в словаре — это был перенос, дефис
    служебный. Если нет — дефис принадлежит слову, и его надо сохранить.
    Исключение на союзы («микро- и макрокосм») отпало само: «микрои» словарём
    не опознаётся, и дефис остаётся по общему правилу.
    """
    слитно = голова + хвост
    if _morph.word_is_known(слитно):
        return слитно
    # Дефис остаётся. Пробел после него — только перед СОЮЗОМ: это висячий
    # дефис сложного слова («микро- и макрокосм», «двух- или трёхлетний»), и
    # там пробел законный. В прочих случаях дефис принадлежит слову целиком
    # («где-то», «из-за»), и пробела в нём быть не должно.
    #
    # Замер: из 131 висячего дефиса в живом складе 58 (44%) стоят перед
    # союзом — то есть случай не редкий.
    if хвост in _СОЮЗЫ:
        return f"{голова}- {хвост}"
    return f"{голова}-{хвост}"


def _срастить_перенос(m: re.Match) -> str:
    return _срастить(m.group(1), m.group(2))


def clean_text(text: str, шаг=None) -> str:
    """СТАДИЯ 2 ЗАЛИВКИ: вся чистка текста, слепая к формату.

    Заливка книги — три стадии, и между ними один общий вид:

        `parse_source_file`   — достать текст (разметка fb2, кодировка txt)
        `clean_text`          — ЭТА: вычистить всё служебное
        `cut_into_fragments`  — резать уже чистое

    Про формат тут не знают ничего: сюда одинаково приходит и fb2, и txt, и md.
    Раньше часть правил жила в разборе fb2 (`_текст_абзаца`), часть тут, а
    снятие имён — третьим вызовом в `store.add_corpus`; форматы от этого
    расходились, и правило приходилось держать в двух местах.

    Порядок внутри не случаен и местами единственно возможный:
      · теги снимаются ПЕРВЫМИ — иначе `[<strong>322</strong>]` не опознать
        как ссылку (для снималки это скобка с буквами, то есть речь);
      · переносы и строки-номера — ПОКА ЕСТЬ ПЕРЕВОДЫ СТРОК, ниже они
        схлопнутся и «100» станет неотличим от числа внутри фразы;
      · имена — последними, по уже очищенному тексту.

    `шаг(этап)` — колбэк прогресса: разбор имён идёт pymorphy3 по всему тексту
    книги и занимает большую часть времени, молчать на нём нельзя.
    """
    if not text or not text.strip():
        return ""

    # Remove script and style blocks entirely (with content)
    text = re.sub(r'<script[^>]*>.*?</script>', ' ', text, flags=re.DOTALL | re.IGNORECASE)
    text = re.sub(r'<style[^>]*>.*?</style>', ' ', text, flags=re.DOTALL | re.IGNORECASE)

    # Remove HTML comments
    text = re.sub(r'<!--.*?-->', ' ', text, flags=re.DOTALL)

    # ТЕГИ СНИМАЮТСЯ ЗДЕСЬ, А НЕ ПОСЛЕ МАРКЕРОВ (2026-08-21).
    #
    # Порядок был обратный, и из-за него ссылка в разметке не опознавалась
    # вовсе: `[<strong>322</strong>]` для снималки маркеров — скобка с
    # БУКВАМИ, то есть речь, а не указатель. У Блаватской таких 268 из 1801.
    # Сняв теги первым делом, получаем «[322]» — обычный маркер.
    #
    # Тег заменяется ПРОБЕЛОМ, а не пустотой: в книгах пробел часто стоит
    # внутри тега (`<emphasis>постигай </emphasis>мир`), и склейка слов —
    # порча, которую потом уже не видно глазом.
    text = re.sub(r'</?\s*[^>\s]+(?:\s+[^>]*?)?\s*/?>', ' ', text,
                  flags=re.IGNORECASE)
    text = html.unescape(text)
    text = text.replace('\xa0', ' ').replace('&nbsp;', ' ')

    # СЛОВО, РАЗОРВАННОЕ ПЕРЕНОСОМ, СРАЩИВАЕТСЯ (2026-08-21).
    #
    # Вопрос владельца: «а вдруг это кривой какой-то перенос?» — и он прав.
    # В txt, снятом со скана или из вёрстки, слово рвётся дефисом на границе
    # строки: «пере-\nнос». Схлопывание пробелов ниже давало «пере- нос» —
    # висячий дефис и два обломка вместо слова. В fb2 такого нет (там абзац
    # цельный), а txt и md шли этим путём с самого начала.
    #
    # ДЕФИС БЫВАЕТ НЕ ТОЛЬКО ASCII (2026-08-21). Текст, снятый из вёрстки или
    # PDF, носит U+2010 HYPHEN и U+2011 NON-BREAKING HYPHEN вместо обычного
    # минуса. Правило ниже их не видело, и выходило ТИШЕ И ХУЖЕ ASCII-случая:
    # «пере‐\nнос» давало «пере нос» — два обломка БЕЗ висячего дефиса, то есть
    # порчу, которую потом уже ничем не опознать. Приводим к ASCII, дальше их
    # разбирает то же правило с тем же исключением на союзы.
    text = text.replace("\u2010", "-").replace("\u2011", "-")

    # МЯГКИЙ ПЕРЕНОС U+00AD — ОСОБЫЙ СЛУЧАЙ, ИСКЛЮЧЕНИЯ ЕМУ НЕ НУЖНО.
    # Этот знак невидим и означает РОВНО ОДНО: «здесь слово можно разорвать».
    # Оборотом «микро- и макрокосм» он не бывает никогда — сращиваем безусловно.
    #
    # Уцелевший ВНЕ переноса выбрасывается ЯВНО — и это не лишняя строка,
    # хотя выглядит ею. Утром 2026-08-21 она была снята как мёртвая: ломка не
    # покраснила ни одного теста, потому что U+00AD не проходил белый список
    # символов внизу и удалялся там. Вечером того же дня белый список стал
    # заменять чужой знак ПРОБЕЛОМ (иначе «км/ч» склеивалось в «кмч») — и
    # невидимый мягкий дефис начал рвать слово надвое: «сло<AD>во» → «сло во».
    #
    # То есть мёртвой она была не по существу, а потому что её работу делал
    # сосед. Сосед поменялся — работа вернулась.
    text = re.sub(r"\u00ad[ \t]*\r?\n[ \t]*", "", text)
    text = text.replace("\u00ad", "")

    # Только СТРОЧНАЯ буква после переноса: заглавная — начало новой мысли, а
    # не хвост слова. Тире («он сказал —\nи ушёл») это другой знак и под
    # шаблон не попадает. Как именно сшивать — решает `_срастить` по словарю.
    text = _ПЕРЕНОС.sub(_срастить_перенос, text)

    # КВАДРАТНЫЕ И ФИГУРНЫЕ СКОБКИ — ЗДЕСЬ, ДЛЯ ВСЕХ ФОРМАТОВ (2026-08-21).
    #
    # Снималка стояла в `_текст_абзаца`, то есть работала на fb2 и обходила
    # txt и md — а «[47]» и «{24}» попадаются в любом тексте, снятом с книги.
    # `clean_text` зовут ВСЕ пути заливки (см. store.add_corpus), значит правило
    # здесь накрывает все форматы разом.
    #
    # Обрубленные разрезом («…Едином»[709») тут НЕ ловятся нарочно: их СОЗДАЁТ
    # разрез, а не книга — в источнике скобка всегда целая. Обрубками
    # занимаются резак (`cut_into_fragments`) и чистка склада, оба через
    # `снять_маркеры`. Построчный проход по ним стоял и тут; ломка не
    # покраснила ни одного теста, девять живых книг побитово те же — снято.
    text = снять_ссылки(text)

    # СТРОКА ИЗ ОДНИХ ЦИФР — НОМЕР, А НЕ ТЕКСТ (2026-08-21).
    #
    # Номер страницы, номер раздела, номер сноски внизу полосы. Сам по себе он
    # не фрагмент (коротко), но окна протаскивают его В СЕРЕДИНУ соседней
    # фразы: «298 Описывая Птолемея и Гераклеона», «490 Бог Хептактис»,
    # «Раздел, обозначающий время. 239 Санхуниафон называет время».
    #
    # Замер по девяти живым книгам: у Блаватской таких строк 620, у Пелевина 1
    # («2022»), у остальных семи ноль. На её книге правило убирает 9 045 разных
    # порченых фрагментов; чистая убыль 340 — остальное просто сдвиг окон.
    #
    # ПОСЛЕДНИЙ МОМЕНТ, КОГДА ЭТО ВОЗМОЖНО: ниже пробелы схлопнутся, строки
    # исчезнут, и «100» станет неотличим от числа внутри фразы.
    #
    # ── ОТВЕРГНУТО ЗАМЕРОМ, НЕ ВОЗВРАЩАТЬ ───────────────────────────────────
    # Правило «короткая строка, повторённая 5+ раз, это колонтитул» на тех же
    # девяти книгах съедало не мусор, а ГОЛОС: у Паланика 243 строки («Я
    # говорю:», «Она говорит:», «И мама говорит:» — его фирменный повтор), у
    # Головина 24 («все наше навсегда», «мы убиваем друг друга» — припевы), у
    # Пелевина 26 («– Почему?», «Вбойщик!»). Настоящих колонтитулов не нашлось
    # ни одного. Правило снято до того, как попало в код.
    text = "\n".join(с for с in text.split("\n") if not _СТРОКА_НОМЕР.match(с))

    # Collapse all whitespace (newlines, tabs, multiple spaces) to single space
    text = re.sub(r'\s+', ' ', text).strip()

    # Remove other potential markup artifacts, keep letters, digits, basic punctuation for fragments
    # This is aggressive to kill any remaining < > / etc.
    # ЗАМЕНА НА ПРОБЕЛ, А НЕ НА ПУСТОТУ (2026-08-21).
    #
    # Знак вне списка стоит не только между словами, но и МЕЖДУ ними в
    # сокращениях, и выброс склеивал их в несуществующее слово:
    #
    #     «Скорость 60 км/ч была»  →  «Скорость 60 кмч была»   ✗
    #
    # Тот же класс, что склейка на краевом пробеле внутри тега: порча тихая,
    # глазом её потом уже не видно. С пробелом выходит «км ч» — два настоящих
    # токена, и рифма со счётом слогов считаются по ним верно.
    #
    # Прочие случаи от замены не страдают: «50%» → «50», «№ 5» → «5»,
    # «Иванов & Партнёры» → «Иванов Партнёры» — лишний пробел схлопнется ниже.
    # ЧТО В СПИСКЕ, А ЧТО НЕТ — ЗАМЕРЕНО ПО ДЕВЯТИ ЖИВЫМ КНИГАМ (2026-08-21).
    #
    # Пропускаем: кавычки всех начертаний („ “ ” ‘ ’ — «где взял „Псалтырь“»,
    # 286 мест) и обычную типографику № % ° § (43 места). Это законные знаки
    # русской прозы, и выбрасывать их значит менять текст автора.
    #
    # НЕ пропускаем: / (1004, почти всё библиография «// Tyndall»), & + = • ©
    # — технические знаки и выходные данные, в строке песни им делать нечего.
    text = re.sub(r'[<>]', ' ', text)
    text = re.sub(r'[^\w\s\.\,\!\?\;\:\-\—\–\'\"«»„“”‘’№%°§\(\)\[\]\{\}…]', ' ',
                  text, flags=re.UNICODE)

    # Final normalization
    text = re.sub(r'\s+', ' ', text).strip()

    # ИМЯ И ФАМИЛИЯ ВМЕСТЕ — ПОСЛЕДНИМ ШАГОМ (2026-08-21, переехало сюда из
    # `store.add_corpus`). Требование владельца от 2026-07-19: настоящее имя
    # человека целиком в нарезанной выдаче ему не нужно. Снимается ДО нарезки,
    # чтобы имя не попало даже в скользящие окна.
    #
    # Последним — потому что опознание идёт пословно, и знак, прилипший к
    # имени, его ломает («[Иисуса», «Молотова…»): к этому месту скобки и теги
    # уже сняты. Это самый долгий шаг чистки — pymorphy по всему тексту книги.
    if шаг:
        шаг("разбираю имена")
    return strip_full_names(text, шаг=шаг)


def _grammeme(word: str, grammeme: str) -> bool:
    """Is `word` tagged `grammeme` (Name/Surn/Patr) in pymorphy3's own
    dictionary, at real confidence — only ever checked on a CAPITALIZED
    word, so a common noun that happens to share a surname's spelling
    (e.g. "соловей" the bird vs "Соловьёв" the surname) never collides:
    real personal names are capitalized mid-sentence, common nouns aren't."""
    if not word[:1].isupper():
        return False
    for p in _morph.parse(word):
        if grammeme in p.tag and p.score > 0.1:
            return True
    return False


# ПАМЯТЬ НА СЛОВО (2026-08-21). Функция чистая — слово в тег, — а зовётся она
# на КАЖДОМ слове каждого фрагмента. Пока это был проход по одной книге при
# заливке, цена не считалась; с появлением повторяемой чистки склада
# (`NakedLunchStore.почистить`) тот же вызов идёт по 2 449 400 фрагментам, а
# слова в книгах повторяются десятками тысяч раз. Размер взят с запасом: в
# живом складе различных словоформ порядка миллиона, и держать их все дешевле,
# чем разбирать одно и то же морфологией.
@lru_cache(maxsize=1 << 20)
def _name_tag(word: str) -> str | None:
    # МНОГОТОЧИЕ И СКОБКИ ТОЖЕ ОБРЫВАЮТСЯ (2026-08-21). Их тут не было, и
    # знак, прилипший к имени, ломал опознание целиком:
    #
    #     «У Игоря Молотова… У Игоря Молотова убили брата»
    #      ^^^^^^^^^^^^^^^^^ уцелело      ^^^^^^^^^^^^^^^ снято
    #
    # То же с «[Иисуса Навин». Класс нашёлся сам: заливка переставала быть
    # самодостаточной ровно на этих двух местах из 584 000 фрагментов девяти
    # книг — резак обрывает знаки при нарезке, имя обнажается, и чистка
    # склада находила то, чего заливка не увидела. Одно правило, два ответа —
    # та самая болезнь, за которой тут охотятся отдельно.
    stripped = word.strip(".,!?;:—–-\"'«»()[]{}…")
    if not stripped:
        return None
    for grammeme in ("Name", "Surn", "Patr"):
        if _grammeme(stripped, grammeme):
            return grammeme
    return None


def strip_full_names(text: str, шаг=None) -> str:
    """Remove 'Имя [Отчество] Фамилия' (and the reverse 'Фамилия Имя')
    spans from raw book text — user's own explicit ask (2026-07-19): a real
    person's full name showing up whole in cut-up output isn't something he
    wants, however rarely a source text actually contains one. Deliberately
    narrow — a LONE first name or LONE surname is common (any character's
    given name, an author mentioned once) and stays; only the pair TOGETHER
    triggers removal, matching "имя и фамилию ВМЕСТЕ" exactly.

    Runs on raw text BEFORE fragmentation (see store.add_corpus) so a name
    never even reaches cut_into_fragments's sliding windows. For corpora
    already cut before this existed, see NakedLunchStore.strip_names — the
    same tagging logic, run directly over already-stored fragment text,
    since the raw source text isn't retained after a corpus is added once
    (see Fragment/Corpus in store.py — no source_text field)."""
    words = text.split(" ")
    # ПРОГРЕСС ВНУТРИ САМОГО ДОЛГОГО ШАГА (2026-08-21). Правило владельца: «если
    # что-то происходит где-то, это мне отображается». Разметка имён идёт
    # pymorphy по КАЖДОМУ слову книги — на большой книге это минута, и всё это
    # время в ленте работ висел один неподвижный ярлык «разбираю имена».
    # Теперь видно, сколько слов пройдено.
    if шаг is not None and len(words) > _ШАГ_ИМЁН:
        tags = []
        for н in range(0, len(words), _ШАГ_ИМЁН):
            шаг(f"разбираю имена · {н:,} из {len(words):,} слов".replace(",", " "))
            tags.extend(_name_tag(w) for w in words[н:н + _ШАГ_ИМЁН])
    else:
        tags = [_name_tag(w) for w in words]
    drop = [False] * len(words)
    i = 0
    while i < len(words):
        if tags[i] == "Name":
            j = i + 1
            if j < len(words) and tags[j] == "Patr":
                j += 1
            if j < len(words) and tags[j] == "Surn":
                for k in range(i, j + 1):
                    drop[k] = True
                i = j + 1
                continue
        elif tags[i] == "Surn" and i + 1 < len(words) and tags[i + 1] == "Name":
            drop[i] = True
            drop[i + 1] = True
            i += 2
            continue
        i += 1
    kept = [w for w, d in zip(words, drop) if not d]
    return re.sub(r"\s+", " ", " ".join(kept)).strip()


# --- индексно-цифровой мусор (2026-08-01, user's own ask) ------------------
# Живой пример, утёкший в выдачу extendo, дословно из пула:
#   «141, 573 Хазан В. II 468, 670 торн и контратака»
# — скользящее окно по именному указателю книги (собрание Мандельштама,
# сноски Блаватской и т.п.). Детекция ПО-ФРАГМЕНТНО, структурная, только
# regex (без pymorphy: фамилий из указателей часто нет в его словаре, а
# ретро-проход по 2.9М фрагментов должен оставаться быстрым).
# Контракт: ноль ложных срабатываний важнее полноты. Фрагмент с ОДНИМ
# числом («в 1970-ом») неприкосновенен, кроме единственного исключения —
# структурно однозначных входов указателя («573 Хазан В», «Лаврова К. Н.
# I 499»), которыми проза не бывает; все остальные правила требуют минимум
# двух числовых серий (и хотя бы одну многозначную) плюс независимую
# индексную улику. Полу-проза со ссылками («стр. 82)? Или же») сознательно
# выживает.

# «20 000» и «2,726,700» — одно число, не несколько; «141, 573» (запятая
# + пробел) — страничный список, НЕ склеивается.
_THOUSANDS = re.compile(r"(?<=\d)(?:\s+|,)(?=\d{3}(?:\D|$))")
_DIGIT_RUN = re.compile(r"\d+")
_ROMAN_PAGELIST = re.compile(r"\b[IVXLC]{1,5}\s+\d{1,4}\s*[,;]\s*\d{1,4}")
_INITIALS_ROMAN_PAGE = re.compile(
    r"[А-ЯЁ][а-яё]+\s+[А-ЯЁ]\.(?:\s*[А-ЯЁ]\.)?\s+[IVXLC]{1,5}\s+\d{1,4}"
)
_INITIALS_PAGELIST = re.compile(
    r"[А-ЯЁ][а-яё]+\s+[А-ЯЁ]\.(?:\s*[А-ЯЁ]\.)?\s+\d{1,4}\s*,\s*\d{1,4}"
)
_PAGELIST_SURNAME = re.compile(r"\d{1,4}\s*,\s*\d{1,4}\s+[А-ЯЁ][а-яё]+\s+[А-ЯЁ]\.")
_ANY_WORD = re.compile(r"[^\W\d_]+", re.UNICODE)
# Числа-НЕ-нумерация: «9)» — маркер перечисления в живом тексте
# («Скорпион; 9) Стрелец; 10) Козерог»), указатели так не нумеруют.
_RUN_NOT_ENUM = re.compile(r"\d+(?=[^)\d]|$)")
# Фрагмент ЦЕЛИКОМ — вход указателя «573 Хазан В» (страница + фамилия +
# инициал, возможно обрезанный без точки). Обнаружен живой проверкой:
# подрезы окна теряют второе число, и общий гейт «минимум два числа»
# такой обломок не видит.
_LONE_INDEX_ENTRY = re.compile(r"^\d{1,4}\s+[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?\s+[А-ЯЁ]\.?$")
# «Фамилия И. О.» (с необязательной скобкой: «Марджанов (Марджанишвили) К.»)
# — две такие группы подряд без единого слова в нижнем регистре бывают
# только в именном указателе, даже когда окно потеряло все страницы:
# «Моргулис А. О. Марджанов (Марджанишвили) К. А» (живая проверка).
_SURNAME_INITIALS_GROUP = re.compile(
    r"[А-ЯЁ][а-яё]+(?:\s*\([^)]{1,40}\))?\s+[А-ЯЁ]\.(?:\s*[А-ЯЁ]\.)?"
)


def is_index_junk(fragment: str) -> bool:
    """True, если фрагмент — обломок книжного указателя/оглавления/сносок,
    а не проза. Каждое правило проверено на живом пуле (2.89М фрагментов):
    библейские номера стихов, даты («ночь с 30 на 31 марта 2001»),
    биографические скобки («1877–1947) — английский писатель») и суммы
    («20,000 Quips») выживают; страничные списки и именные указатели — нет."""
    # Структурно однозначные входы указателя — до числовых гейтов: римский
    # том между инициалами и страницей («Лаврова К. Н. I 499») и целиком-
    # обломок «573 Хазан В» встречаются и с единственным числом.
    if _INITIALS_ROMAN_PAGE.search(fragment) or _LONE_INDEX_ENTRY.search(fragment):
        return True
    if (len(_SURNAME_INITIALS_GROUP.findall(fragment)) >= 2
            and not any(w[0].islower() for w in _ANY_WORD.findall(fragment))):
        return True  # именной указатель без страниц: «Моргулис А. О. Марджанов … К. А»
    merged = _THOUSANDS.sub("", fragment)
    runs = _DIGIT_RUN.findall(merged)
    if len(runs) < 2:
        return False  # одиночное число — неприкосновенно (кроме структурных входов выше)
    if not any(len(r) >= 2 for r in runs):
        # Одни однозначные числа — перечисления живого текста, не страницы:
        # «6… 5… 4… Нет» (Пелевин), «1. Восторг. 2. Разочарование» (афоризм),
        # «Навыки 1, 2, 3» (Кови). Указатель без многозначных номеров не бывает.
        return False
    if len(runs) >= 3:
        digits = sum(map(len, runs))
        nonspace = len(re.sub(r"\s+", "", merged)) or 1
        # Доминирование цифр — но минимум две КОРОТКИЕ серии (≤3 цифр,
        # страничные номера): годы 4-значные, и чисто годовые строки
        # («1911–1971) — поэт. В 1957», «27, 28 и 29 июля» на границе)
        # сюда не попадают. Порог 0.55, не 0.5 — прозаичные датировки
        # («17–31 мая 1912 г.») сидят на 0.50–0.53.
        if digits / nonspace >= 0.55 and sum(1 for r in runs if len(r) <= 3) >= 2:
            return True  # цифр больше, чем текста: «406, 456–458, 481, 486…»
        if (len(_RUN_NOT_ENUM.findall(merged)) >= 3
                and not any(w[0].islower() for w in _ANY_WORD.findall(merged))):
            return True  # числа вперемешку только с Именами: «118 Аполлодор II 502 Апулей I 516»
    if _ROMAN_PAGELIST.search(fragment):
        return True  # том + страницы: «II 468, 670»
    if _INITIALS_PAGELIST.search(fragment) or _PAGELIST_SURNAME.search(fragment):
        return True  # «Гаспаров Б. М. 188, 197» / «141, 573 Хазан В.»
    return False


NS = {"fb": "http://www.gribuser.ru/xml/fictionbook/2.0"}


def _имя(эл) -> str:
    """Имя тега БЕЗ пространства имён.

    ЗАЧЕМ (2026-08-21). Поиск шёл через `findall(".//fb:body", NS)`, где `fb`
    прибит к `fictionbook/2.0`. Книга в fb2 версии 2.1 или собранная небрежно,
    без объявления пространства имён вовсе, давала НОЛЬ абзацев — и молча: в
    итоге пользователь видел «текст есть, но нарезать из него нечего», то есть
    враньё о причине.

    Версия схемы к содержимому книги отношения не имеет; тег `<p>` он и в 2.1
    `<p>`. Ищем по имени, не по пространству."""
    return эл.tag.split("}")[-1] if isinstance(эл.tag, str) else ""


def _все(эл, имя: str):
    """Все потомки с таким именем тега, в порядке документа."""
    for ч in эл.iter():
        if _имя(ч) == имя:
            yield ч


# ССЫЛОЧНЫЙ МАРКЕР ЛИТЕРАЛОМ (2026-08-21, живые книги владельца).
#
# Часть сносок размечена не тегом, а прямо в тексте:
#     «В первом томе своих «Осколков» [47] профессор Мюллер…»   (скобки — текст,
#                                                                жирный только номер)
#     «…их легко победить {24} .»                               (Сунь-цзы)
# Тег `<a type="note">` их не ловит — там литерал. Скобка или фигурная скобка,
# внутри которой одни цифры, русской прозой не бывает НИКОГДА: это указатель.
# Замер на девяти книгах: 608 порченых фрагментов у Блаватской и 74 у Сунь-цзы,
# у остальных семи — ноль.
#
# Список номеров через запятую или тире («[166, 167]», «[12–14]») — тот же
# случай. Буквы внутри скобок НЕ трогаем: «[так в оригинале]» это речь.
_МАРКЕР_ССЫЛКИ = re.compile(r"[\[{]\s*\d+(?:\s*[-–—,]\s*\d+)*\s*[\]}]")

# Строка, в которой ничего кроме номера: «100», «— 47 —», «(3)», «298.».
# Разбор см. в `clean_text` — там же надгробие отвергнутому правилу про
# повторяющиеся строки. Не больше четырёх цифр: пятизначное на своей строке
# это уже не номер страницы, а данные.
_СТРОКА_НОМЕР = re.compile(r"^\s*[-—–\[({]*\s*\d{1,4}\s*[-—–\])}.]*\s*$")

# ОБРУБЛЕННЫЙ МАРКЕР — ТОТ ЖЕ МУСОР, НО УЖЕ В НАРЕЗАННОМ СКЛАДЕ (2026-08-21).
#
# Правила выше чинят разбор БУДУЩИХ книг. У владельца те же девять книг уже
# лежат в складе, нарезанные СТАРЫМ разбором, и скользящее окно режет маркер
# пополам:
#     «Атрибутами Непознаваемого Божества в Едином»[709     ← открылся, не закрыт
#     739] Но это «подобие» и сама Ogdoad'а есть лишь ширма  ← закрылся, не открыт
#
# Замер на живом индексе (проба 300 000 из 2 392 262): целых маркеров ≈ 8 501,
# обрубленных в конце ≈ 2 193, в начале ≈ 1 013 — итого ≈ 11 706 строк.
#
# Почему это безопасно. Скобка, открытая в КОНЦЕ фрагмента и не закрытая, либо
# закрытая в НАЧАЛЕ без открытия — след разреза, а не пунктуация: живая фраза
# не начинается с «739]» и не кончается на «[709».
# СОДЕРЖИМОЕ НЕ ПРОВЕРЯЕТСЯ — РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-08-21, ДОСЛОВНО:
# «я считаю, то что в квадратных скобках можно вырезать спокойно — это
# служебный же текст».
#
# Замер по живому складу подтвердил: целых квадратных скобок 7 772, из них
# 6 851 с цифрой (ссылки), а все 921 остальные — редакторские вставки:
# «[…]», «[.....]», «[Пракрити]», «[благочестием]», «[слуги]», «[Идеальная]».
# Речи автора внутри квадратных скобок нет ни одной.
#
# Круглых это НЕ касается: там 708 из 1111 — годы («(1773)»), обычная проза.
_МАРКЕР_ХВОСТ = re.compile(r"\s*[\[{][^\[\]{}]{0,80}$")
_МАРКЕР_ГОЛОВА = re.compile(r"^[^\[\]{}]{0,80}[\]}]\s*")


_СКОБКА = re.compile(r"[ \t]*[\[{][^\[\]{}]{0,80}[\]}][ \t]*")
_ЗНАК_ПОСЛЕ = re.compile(r"[,.;:!?…»)\]}]")


def снять_ссылки(текст: str) -> str:
    """Убрать ЦЕЛЫЕ ссылочные маркеры: «[47]», «{24}», «[166, 167]».

    ОДНА СНИМАЛКА НА ВСЕ МЕСТА: её зовёт чистка текста (`clean_text`, то есть
    заливка любого формата) и повторяемая чистка склада (через
    `снять_маркеры`). Два списка одного и того же расходятся всегда — в этом
    проекте на том обжигались трижды.

    ЩЕЛЬ ЗАКРЫВАЕТСЯ ТОЛЬКО ТАМ, ГДЕ МАРКЕР БЫЛ (2026-08-21). Раньше стояло
    «снять маркер → заменить пробелом → убрать ЛЮБОЙ пробел перед знаком по
    всему тексту». Второе правило било по живому:

        Как сказано в "Дифирамбах Дионису": …стоит артист
                                        → "Дионису":…стоит артист   ✗
        погас свет… …Ничего не видно    → погас свет……Ничего        ✗

    Пробел перед многоточием — законная речь, а не след маркера. Теперь
    решение принимается на месте снятия, по следующему знаку, и текста без
    маркеров правило не касается вовсе.

    Идемпотентна: снятое снимать нечего."""
    def чем(m: re.Match) -> str:
        # Впритык к знаку — уходит вместе со своими пробелами:
        #   «Субстанции-Матери[441]. Это» → «…Матери. Это»
        #   «Их легко победить {24} .»    → «Их легко победить.»
        if _ЗНАК_ПОСЛЕ.match(m.string[m.end():m.end() + 1]):
            return ""
        # Иначе — ПРОБЕЛ, а не пустота: «производят Софию[166]завершая» иначе
        # давало «Софиюзавершая», несуществующее слово, и порча становилась
        # тише, но хуже: её уже не видно глазом.
        return " "

    return _СКОБКА.sub(чем, текст)


def снять_маркеры(текст: str) -> str:
    """Целые маркеры И обрубленные разрезом. Зовёт чистка СКЛАДА.

    Обрубки («…Едином»[709», «166] завершая») создаёт нарезка, а не книга: в
    источнике маркер всегда целый. Поэтому в `clean_text` их не ищут вовсе —
    там достаточно `снять_ссылки`."""
    т = текст
    # ДО НЕПОДВИЖНОЙ ТОЧКИ: снятие одной скобки может обнажить следующую.
    for _ in range(4):
        было = т
        т = снять_ссылки(т)
        т = _МАРКЕР_ХВОСТ.sub("", т)
        т = _МАРКЕР_ГОЛОВА.sub("", т)
        if т == было:
            break
    return re.sub(r"[ \t]+", " ", т).strip()


def _текст_абзаца(эл) -> str:
    """Текст абзаца БЕЗ маркеров сносок.

    ЗАЧЕМ (2026-08-21, найдено на живых книгах владельца). В fb2 ссылка на
    сноску размечена так:

        производят Софию,<a l:href="#n_166" type="note">[166]</a> завершая

    Прежний `"".join(p.itertext())` тянул и текст ссылки, и в корпус попадало
    «в свою очередь производят Софию,[166» — обломок номера посреди фразы. На
    «Разоблачённой Изиде» таких ссылок 776, и все они портили соседний текст.

    Маркер сноски это УКАЗАТЕЛЬ, а не слово автора: выбрасываем его текст, а
    сам абзац сшиваем как был. `type="note"` проверяется явно — обычные ссылки
    внутри текста (их в fb2 почти не бывает, но бывают) остаются."""
    куски = []
    if эл.text:
        куски.append(эл.text)
    for ч in эл:
        имя = ч.tag.split("}")[-1]
        сноска = имя == "a" and (ч.get("type") or "").lower() == "note"
        if сноска:
            # ПРОБЕЛ ВМЕСТО СНОСКИ, А НЕ ПУСТОТА. Поймано собственным тестом:
            # «Софию<a type="note">[166]</a>завершая» без пробела склеивалось в
            # «Софиюзавершая» — несуществующее слово, и порча становилась тише,
            # но хуже: её уже не видно глазом. Лишний пробел безвреден —
            # `re.sub(r"\s+", " ")` в вызывающем схлопнет.
            куски.append(" ")
        else:
            куски.append(_текст_абзаца(ч))
        # хвост после ссылки нужен в любом случае — иначе фраза порвётся
        if ч.tail:
            куски.append(ч.tail)
    # ЧИСТКОЙ ТУТ НЕ ЗАНИМАЕМСЯ (2026-08-21). Раньше стояло
    # `снять_маркеры("".join(куски))` — то есть стадия 2 сидела внутри стадии 1
    # и работала ТОЛЬКО для fb2, а txt и md шли мимо неё. Разбор формата обязан
    # достать текст и больше ничего; вся чистка — одна, в `clean_text`, слепая
    # к тому, из какого формата текст пришёл.
    return "".join(куски)


# Тела, которые в fb2 держат НЕ текст книги. `notes` — сноски: библиография,
# примечания переводчика, ссылки на источники. У Блаватской это 1494 абзаца из
# 5231, то есть 28.6% книги, и всё это не проза автора, а аппарат издания.
_ТЕЛА_НЕ_КНИГА = {"notes", "footnotes", "comments"}


def _абзацы_по_порядку(эл):
    """`<p>` и `<v>` в порядке документа, без заголовков.

    ПОЧЕМУ НЕ `findall(".//fb:p") + findall(".//fb:v")` (2026-08-21). Так было,
    и это давало ДВА дефекта разом:

      · порядок ломался — сперва вся проза, потом ВСЕ стихи скопом. У Головина
        381 строка стиха уезжала в конец книги, отрываясь от своего контекста;
      · заголовки шли как текст: `<title>` в fb2 это глава или раздел, и
        «ГЛАВА ПЕРВАЯ», «Священный Лотос» попадали в корпус наравне с прозой,
        а окна протаскивали их в середину соседней фразы. У Блаватской таких
        абзацев 751, у Кови 149, у Паланика 80.

    Обход рекурсивный: `<title>` пропускается целым поддеревом, `<epigraph>`
    НЕ пропускается нарочно — эпиграф это цитата, то есть нормальный материал.
    """
    for ч in эл:
        имя = _имя(ч)
        if имя == "title":
            continue
        if имя in ("p", "v"):
            yield ч
        else:
            yield from _абзацы_по_порядку(ч)


def _fb2_to_text(path: Path) -> str:
    """Достать текст книги из fb2. Только `<p>` и `<v>`, в порядке документа.

    Картинки лежат в `<binary>` и сюда не попадают по построению — проверено
    на девяти живых книгах с 39 картинками: не пришло ни одной.

    ── СНЯТО 2026-08-21: «отрезать первые 25 абзацев» ──────────────────────
    Правило стояло тут как грубая замена разбору титульной части и обходилось
    дорого: 25 абзацев × 9 книг = 225 отрезанных, и у Сунь-цзы (417 абзацев
    всего) в них попадала аналитическая проза предисловия — «На протяжении
    всей книги Сунь-цзы обсуждает важнейшую проблему командования…».

    Нужды в нём больше нет: титульная часть в fb2 лежит в `<description>`,
    куда обход не заходит, а заголовки и сноски теперь отсекаются ПО
    РАЗМЕТКЕ. Замер на девяти книгах: без правила все девять начинаются
    живой прозой, мусора набирается три абзаца на всех — копирайт Лимонова
    и «Второе издание, исправленное» у Головина.
    """
    tree = ET.parse(path)
    root = tree.getroot()
    parts = []
    for тело in _все(root, "body"):
        if (тело.get("name") or "").lower() in _ТЕЛА_НЕ_КНИГА:
            continue
        for p in _абзацы_по_порядку(тело):
            t = _текст_абзаца(p)
            t = re.sub(r"\s+", " ", t).strip()
            if t and len(t) > 2:
                parts.append(t)
    text = "\n\n".join(parts)
    text = re.sub(r"\n{3,}", "\n\n", text).strip()
    return text


_БУКВА = re.compile(r"[а-яёА-ЯЁ]")
_КОДИРОВКИ = ("cp1251", "koi8-r", "cp866", "iso8859-5", "mac-cyrillic",
              "utf-16-le", "utf-16-be")
_BOM = ((b"\xef\xbb\xbf", "utf-8-sig"), (b"\xff\xfe\x00\x00", "utf-32"),
        (b"\x00\x00\xfe\xff", "utf-32"), (b"\xff\xfe", "utf-16"),
        (b"\xfe\xff", "utf-16"))

# Доли букв в русском языке. Ими РАЗЛИЧАЮТСЯ однобайтовые кириллические
# кодировки — больше ничем: все они сохраняют ASCII, то есть пробелы, знаки и
# длины слов у них одинаковы, и «похоже на текст» их не разводит вовсе.
# Прочитанный не тем кодеком текст даёт другое распределение букв, и это
# видно сразу: на «Керуаке» отрыв верного ответа от следующего 0.013–1.054.
_ЧАСТОТЫ = {"о":.1097,"е":.0845,"а":.0801,"и":.0735,"н":.0670,"т":.0626,"с":.0547,
            "р":.0473,"в":.0454,"л":.0440,"к":.0349,"м":.0321,"д":.0298,"п":.0281,
            "у":.0262,"я":.0201,"ы":.0190,"ь":.0174,"г":.0170,"з":.0165,"б":.0159,
            "ч":.0144,"й":.0121,"х":.0097,"ж":.0094,"ш":.0073,"ю":.0064,"ц":.0048,
            "щ":.0036,"э":.0032,"ф":.0026,"ё":.0004,"ъ":.0004}


def _похоже_на_текст(т: str) -> bool:
    """Текст ли это вообще — ДО вопроса о том, какой он кодировки.

    ЗАМЕРЕНО, А НЕ УГАДАНО (2026-08-21):

        настоящая проза  пробелов 16.7%,  среднее слово 5.0 знаков
        случайные байты  пробелов  0.0%,  «слово» 8000 знаков
        PNG              пробелов  0.0%,  «слово» 2668 знаков

    Доля букв тут бесполезна: любой однобайтовый кодек прочтёт что угодно и
    вернёт «кириллицу» — у случайных байтов в mac-cyrillic она 1.000."""
    if not т:
        return False
    слова = т.split()[:5000]
    if not слова:
        return False
    доля_пробелов = т.count(" ") / len(т)
    среднее_слово = sum(len(w) for w in слова) / len(слова)
    if not (0.03 <= доля_пробелов <= 0.40) or среднее_слово > 25:
        return False
    # УПРАВЛЯЮЩИЕ СИМВОЛЫ — ПРИЗНАК НЕ ТОЙ КОДИРОВКИ (2026-08-21).
    #
    # utf-16 БЕЗ метки порядка байтов декодируется как валидный utf-8: нулевые
    # байты и ASCII складываются в законные последовательности. Пробелы и длины
    # слов при этом выглядят прилично (0x20 0x00 → « » + «\x00»), и проверка
    # выше пропускала — а в склад ложилось «!\x04B\x04>\x04O\x04;\x040\x04».
    # Молча, как когда-то cp1251.
    #
    # В настоящем тексте управляющих нет вовсе, кроме переводов строк и
    # табуляций. Порог 1% — с большим запасом.
    управляющих = sum(1 for c in т[:20_000]
                      if ord(c) < 32 and c not in "\n\r\t")
    return управляющих <= 0.01 * min(len(т), 20_000)


_ЗАГЛАВНАЯ_В_СЕРЕДИНЕ = re.compile(r"(?<=[а-яёa-z])[А-ЯЁA-Z]")


def _отклонение_частот(т: str) -> float:
    """Насколько буквы текста расходятся с русским языком. Меньше — ближе.

    ПЛЮС ШТРАФ ЗА ЗАГЛАВНУЮ ПОСРЕДИ СЛОВА (2026-08-21). Одних частот не хватало
    на пару cp1251 / mac-cyrillic: их раскладки почти совпадают в строчных, и
    верный ответ отличался от неверного на 0.005 — то есть на шум. Из-за этого
    mac-cyrillic уходил в cp1251, и заглавные читались неверно («‘тоЯла зима»).

    А вот это и есть примета: в правильно прочитанном тексте заглавная стоит
    только в начале слова. Замер на пробе: верное чтение — 0 таких букв,
    mac-текст как cp1251 — 32, как cp866 — 40."""
    буквы = [c.lower() for c in _БУКВА.findall(т[:200_000])]
    if len(буквы) < 50:
        return 9.9
    счёт: dict[str, int] = {}
    for c in буквы:
        счёт[c] = счёт.get(c, 0) + 1
    n = len(буквы)
    отклонение = sum(abs(счёт.get(c, 0) / n - доля) for c, доля in _ЧАСТОТЫ.items())
    середина = len(_ЗАГЛАВНАЯ_В_СЕРЕДИНЕ.findall(т[:200_000]))
    return отклонение + 3.0 * середина / n


def определить_кодировку(данные: bytes) -> tuple[str, str]:
    """(кодировка, текст) для сырых байтов. ValueError, если это не текст.

    СТАДИЯ 1 ЗАЛИВКИ: достать текст, и только его. Читалось
    `read_text("utf-8", errors="replace")`, и русский txt в cp1251 — самой
    обычной для него кодировке — заливался МОЛЧА ИСПОРЧЕННЫМ: кириллица
    выбрасывалась как нечитаемая, белый список добивал остаток, и в склад
    ложилось «, , .». Ни ошибки, ни предупреждения; счётчик показывал
    фрагменты, книга числилась залитой.

    Порядок решений: метка порядка байтов → utf-8 (он сам себя проверяет) →
    однобайтовые по частотам букв. Не текст — честный отказ, а не догадка.

    Проверено: 8 кодировок из 8 на пробе, 5 из 5 на «Керуаке», 4 из 5 на
    «Селине». Единственный промах — mac-cyrillic, он уходит в cp1251 с
    отрывом 0.005 и деградирует мягко: строчные читаются верно, врут только
    заглавные. Русских книг в mac-cyrillic не бывает практически.

    Своё, а не зависимость: сверено с charset_normalizer как с эталоном и
    сошлось, а задача узкая — русская книга — и проверяема целиком."""
    for метка, код in _BOM:
        if данные.startswith(метка):
            return код, данные.decode(код, errors="replace")
    try:
        т = данные.decode("utf-8")          # utf-8 сам себя проверяет
        if not данные or _похоже_на_текст(т):
            return "utf-8", т
    except UnicodeDecodeError:
        pass
    проба = данные[:200_000]
    лучший, лучшее = None, 9.9
    for код in _КОДИРОВКИ:
        try:
            т = проба.decode(код)
        except (UnicodeDecodeError, LookupError):
            continue
        if not _похоже_на_текст(т):
            continue
        о = _отклонение_частот(т)
        if о < лучшее:
            лучший, лучшее = код, о
    if лучший is None:
        raise ValueError("unknown_encoding")
    return лучший, данные.decode(лучший, errors="replace")


def parse_source_file(path: str | Path) -> str:
    """СТАДИЯ 1 ЗАЛИВКИ: достать из файла текст. Только .fb2, .txt, .md.

    Заливка книги — три стадии, и между ними один общий вид:

        любой формат  →  ПРОСТО ТЕКСТ     (эта функция)
                              ↓
                         `clean_text`     — вся чистка, слепая к формату
                              ↓
                    `cut_into_fragments`  — режется уже чистое

    ЗДЕСЬ ЧИСТКИ НЕТ НАРОЧНО (2026-08-21). Раньше ветка txt звала `clean_text`
    прямо тут, а ветка fb2 не звала: то есть форматы расходились уже на первом
    шаге, и любое правило приходилось держать в двух местах. Ровно так и
    разъехались маркеры сносок — снимались у fb2, проходили насквозь у txt.

    Разбор формата знает про РАЗМЕТКУ (теги fb2) и про КОДИРОВКУ (байты txt).
    Про содержимое текста он не знает ничего — это дело `clean_text`."""
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"Source file not found: {p}")
    suffix = p.suffix.lower()
    if suffix == ".fb2":
        try:
            return _fb2_to_text(p)
        except ET.ParseError as e:
            # Свой код вместо «no element found: line 1, column 58». Разбор
            # обязан отвечать так, чтобы человек понял, что случилось с его
            # файлом; техническая позиция в XML ему ничего не говорит.
            raise ValueError("broken_fb2") from e
    elif suffix in (".txt", ".md"):
        # plain text or markdown — treat as plain text
        _, raw = определить_кодировку(p.read_bytes())
        return raw
    else:
        raise ValueError("unsupported_format")


def _normalize(text: str) -> str:
    # Схлопываем множественные пробелы, но сохраняем одиночные переносы строк
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    # Временно защитим одиночные \n
    text = re.sub(r"\n", " \n ", text)
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r" \n ", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def _split_sentences(p: str) -> List[str]:
    """Разбиваем параграф/блок на предложения, сохраняя базовые разделители."""
    if not p:
        return []
    # Разделители предложений + захват группы
    parts = re.split(r"([.!?])\s*", p)
    sents: List[str] = []
    i = 0
    while i < len(parts):
        chunk = parts[i].strip()
        if i + 1 < len(parts) and parts[i + 1] in ".!?":
            delim = parts[i + 1]
            s = (chunk + delim).strip()
            if s:
                sents.append(s)
            i += 2
        else:
            if chunk:
                sents.append(chunk)
            i += 1
    return sents


def _subsplit(sent: str) -> List[str]:
    """Дополнительные разрезы внутри предложения по запятым, тире и т.п."""
    if not sent:
        return []
    # Агрессивно режем по внутренним разделителям — но ТИРЕ только когда оно
    # стоит отдельным знаком, в окружении пробелов.
    #
    # Раньше в классе разделителей последним символом был обычный дефис-минус,
    # и он резал ЛЮБОЕ слово с дефисом пополам: «какая-нибудь» → «какая» +
    # «нибудь», «из-за» → «из» + «за», «по-русски» → «по» + «русски». Отсюда
    # в живой выдаче брались фрагменты вроде «нибудь гнусность скрывается» —
    # строка, безупречная по слогам и клаузуле и бессмысленная на слух.
    # Найдено аудитом Раунда 51 по этой самой строке из документа пользователя.
    subs = re.split(r"[,;]\s*|\s+[—–-]+\s*", sent)
    out = []
    for s in subs:
        s = s.strip()
        if s:
            out.append(s)
    return out


def _bridges(sents: List[str]) -> List[str]:
    """Мосты: хвост предыдущего + голова следующего."""
    bridges = []
    for i in range(len(sents) - 1):
        a = sents[i]
        b = sents[i + 1]
        aw = a.split()
        bw = b.split()
        if len(aw) >= 3 and len(bw) >= 2:
            bridge = " ".join(aw[-3:] + bw[:3])
            if len(bridge) >= 10:
                bridges.append(bridge)
        # ещё один вариант моста подлиннее
        if len(aw) >= 4 and len(bw) >= 3:
            bridge2 = " ".join(aw[-4:] + bw[:3])
            if len(bridge2) >= 12:
                bridges.append(bridge2)
    return bridges


def _sliding_windows(text: str) -> List[str]:
    """Систематические грязные окна по всему тексту (детерминировано)."""
    # Берём чистый текст без лишних переносов для окон
    clean = re.sub(r"\s+", " ", text)
    words = [w for w in clean.split() if w]
    windows: List[str] = []
    if len(words) < 4:
        return windows
    step = 3
    win = 7
    for i in range(0, len(words) - 3, step):
        chunk = " ".join(words[i : i + win])
        if len(chunk) >= 12:
            windows.append(chunk)
    # дополнительные чуть меньшие окна со сдвигом
    win2 = 5
    for i in range(1, len(words) - 3, step + 1):
        chunk = " ".join(words[i : i + win2])
        if len(chunk) >= 10:
            windows.append(chunk)
    return windows


def cut_into_fragments(text: str) -> List[str]:
    if not text or not text.strip():
        return []

    norm = _normalize(text)
    if not norm:
        return []

    fragments: List[str] = []

    # 1. Работаем по абзацам
    paras = [p.strip() for p in norm.split("\n\n") if p.strip()]
    if not paras:
        paras = [norm]

    for p in paras:
        # Учитываем также строки внутри (полезно для поэзии/рэпа)
        lines = [ln.strip() for ln in p.split("\n") if ln.strip()]
        for line in lines:
            if 8 <= len(line) <= 140:
                fragments.append(line)

        sents = _split_sentences(p)
        for s in sents:
            s = s.strip()
            if 8 <= len(s) <= 160:
                fragments.append(s)
            # подразрезы
            for sub in _subsplit(s):
                if 6 <= len(sub) <= 120:
                    fragments.append(sub)

        # мосты между предложениями этого параграфа
        for br in _bridges(sents):
            fragments.append(br)

    # 2. Глобальные скользящие окна (дают самые "дикие" обрывы)
    for w in _sliding_windows(norm):
        fragments.append(w)

    # 3. Финальная чистка + дедуп
    seen = set()
    result: List[str] = []
    for f in fragments:
        f = f.strip().strip(".,;:!?—–- \"'«»()[]{}")
        f = re.sub(r"\s+", " ", f).strip()
        if not f:
            continue
        # ОБОРВАННЫЙ ХВОСТ СНИМАЕТСЯ ЗДЕСЬ ЖЕ (2026-08-21).
        #
        # Раньше он снимался только кнопкой «почистить корпус», то есть ЗАДНИМ
        # ЧИСЛОМ. Значит каждая новая книга приносила свои 1.8% обрывков, и
        # владельцу пришлось бы жать чистку после КАЖДОЙ заливки. Его же
        # требование: «при заливе книги уже вся работа делается и не надо
        # второй раз прожимать».
        #
        # Дефект-то нарезки, а не чистки: скользящее окно режет фразу посреди и
        # оставляет висеть служебное слово («…И я бы не»). Чинить его надо там,
        # где он рождается.
        #
        # СПИСОК СЛУЖЕБНЫХ СЛОВ БЕРЁТСЯ ИЗ `nlindex`, А НЕ ЗАВОДИТСЯ СВОЙ.
        # Импорт ленивый и «снизу вверх» — некрасиво, но второй такой список
        # разошёлся бы с первым в первую же волну правок, и это не догадка: у
        # `подрезать_хвост` в докстринге ровно про то и написано, почему он
        # публичный. Одно правило дороже слоёв.
        #
        # ОБРУБЛЕННАЯ СКОБКА — ТОТ ЖЕ КЛАСС, И СНИМАЕТСЯ ТУТ ЖЕ (2026-08-21).
        # Целые скобки убирает `clean_text` ДО нарезки. Но окно режет прямо
        # СКВОЗЬ скобку, и получаются «…в тексте [Матфей,» и «III, 17] сказано».
        # Обрубок создаёт РАЗРЕЗ — значит и снимать его разрезу, иначе каждая
        # книга снова приносила бы работу для кнопки «почистить», а заливка
        # перестала бы быть самодостаточной.
        #
        # ДО НЕПОДВИЖНОЙ ТОЧКИ, и это не перестраховка: подрезка хвоста
        # ОБНАЖАЕТ следующий слой. Окно «…вечна? » [364, с.» после снятия
        # точки и подрезки предлога «с» превращается в «…вечна? » [364» —
        # обрубок, которого при первом проходе ещё не было. Один проход
        # оставлял на «Разоблачённой Изиде» восемь таких мест.
        пред = None
        while f and f != пред:
            пред = f
            f = снять_маркеры(f)
            f = _подрезать_хвост(f)
        if not f:
            continue
        # минимум 2 слова
        if len(f.split()) < 2:
            continue
        if len(f) < 7:
            continue
        # обломки указателей/оглавлений (2026-08-01) — см. is_index_junk
        if is_index_junk(f):
            continue
        # ДЕДУП ПО НОРМАЛИЗОВАННЫМ СЛОВАМ, А НЕ ПО ТОЧНОЙ СТРОКЕ (2026-08-21).
        #
        # Точное сравнение пропускало пары, различающиеся регистром или знаком:
        # «Во всяком случае» и «во всяком случае», «родилось бы вообще. )» и
        # «родилось бы вообще.)». `NakedLunchStore.почистить` сравнивает именно
        # по словам, и на живой пробе из 16 866 свежезалитых фрагментов кнопка
        # находила ровно эти три штуки. Разные правила в двух местах — та же
        # болезнь, что и разные разбивщики (см. `СЛОВО` ниже).
        ключ = tuple(СЛОВО.findall(f.lower()))
        if ключ and ключ not in seen:
            seen.add(ключ)
            result.append(f)

    # ДО НЕПОДВИЖНОЙ ТОЧКИ, как и в `NakedLunchStore.почистить`: снятый
    # обломок перестаёт быть контейнером для третьего окна, и один проход
    # оставляет остаток. Проверено: на пробной книге кнопка «почистить» после
    # заливки находила ещё два обломка — теперь ноль.
    while True:
        короче = _снять_обломки(result)
        if len(короче) == len(result):
            return короче
        result = короче


# ОДИН РАЗБИВЩИК НА СЛОВА НА ОБА МЕСТА, ГДЕ ИЩУТ БЛИЗНЕЦОВ (2026-08-21).
#
# Их два: здесь, при нарезке новой книги, и в `NakedLunchStore.почистить` для
# старого склада. Сперва у каждого был свой — тут `_ANY_WORD` (`[^\W\d_]+`,
# буквы без цифр), там `[а-яёa-z0-9]+` (буквы С цифрами). Разные разбивки дают
# разные 5-граммы, а значит разный ответ на «лежит ли эта строка внутри той»:
# на пробной книге кнопка «почистить» после свежей заливки находила ещё два
# обломка, хотя нарезчик уже отработал.
#
# Ровно та болезнь, за которой в этом проекте охотятся отдельно: два списка
# одного и того же расходятся всегда. Список теперь один, и `store.py` берёт
# его отсюда.
СЛОВО = re.compile(r"[а-яёa-z0-9]+")


def _подрезать_хвост(текст: str) -> str:
    """Тот же снимальщик служебного хвоста, что у индекса. Ленивый импорт:
    `nlindex` тянет numpy и mmap, а нарезчик зовут и там, где их нет."""
    from nlindex import Index
    х = Index.подрезать_хвост(текст)
    # Принимаем, ТОЛЬКО если ушло слово: `подрезать_хвост` начинается с
    # `rstrip` по знакам и сдирает авторское многоточие, даже когда резать
    # нечего. Та же оговорка и в `NakedLunchStore.почистить` — правило одно.
    return х if len(х.split()) < len(текст.split()) else текст


def _снять_обломки(фрагменты: List[str]) -> List[str]:
    """Убрать окна, целиком лежащие внутри другого окна той же книги.

    ЗАЧЕМ ЗДЕСЬ. `_sliding_windows` берёт окно в 7 слов с шагом 3 — соседние
    окна делят 4 слова из 7, и корпус ПО ПОСТРОЕНИЮ полон вложенных строк.
    Замер по живому складу 2026-08-21: 58.4% фрагментов целиком лежат внутри
    более длинного, а в каждой десятой малой рифмо-корзине из-за этого сидела
    пара близнецов, которые ещё и рифмуются между собой.

    Порог в два слога и выбор «остаётся длинная» — те же, что в
    `NakedLunchStore.почистить`, и по тем же замерам; там же разбор, почему
    сложное правило «по положению» отвергнуто.

    ВНУТРИ ОДНОЙ КНИГИ, а не по всему складу: близнецы рождаются из соседних
    окон ОДНОГО текста, и здесь их источник. Межкнижные совпадения ловит
    кнопка «почистить корпус» — но их единицы, и ради них незачем поднимать
    полмиллиона чужих фрагментов на каждой заливке."""
    гласные = set("аеёиоуыэюяАЕЁИОУЫЭЮЯ")
    слова = [tuple(СЛОВО.findall(f.lower())) for f in фрагменты]
    слогов = [sum(1 for c in f if c in гласные) for f in фрагменты]
    первая: dict = {}
    for i, w in enumerate(слова):
        if len(w) < 5:
            continue
        for k in range(len(w) - 4):
            первая.setdefault(w[k:k + 5], []).append(i)
    обломок = [False] * len(фрагменты)
    for i, w in enumerate(слова):
        if len(w) < 5:
            continue
        for j in первая.get(w[:5], ()):
            if j == i or обломок[j]:
                continue
            b = слова[j]
            if len(b) <= len(w) or abs(слогов[j] - слогов[i]) > 2:
                continue
            if any(b[s:s + len(w)] == w for s in range(len(b) - len(w) + 1)):
                обломок[i] = True
                break
    return [f for k, f in enumerate(фрагменты) if not обломок[k]]
