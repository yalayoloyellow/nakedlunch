# фристайла: в data/settings.json остался один ключ, записанный последним.
# Механизм был такой:
#   · чтение намеренно молчаливо — на битом файле возвращает пустоту, иначе
#     программа не откроется;
#   · запись сливала новые данные ИМЕННО В ЭТУ ПУСТОТУ и клала результат
#     поверх. Одно неудачное чтение — недописанный файл, гонка двух окон, что
#     угодно — стирало всё, чего в текущей записи не было;
#   · сама запись шла `write_text`, то есть с усечением на месте: прерваться
#     посреди неё значило оставить на диске ровно такой обрубок.
# Замкнутый круг: обрубок → «данных нет» → запись поверх → потеря навсегда.
#
# Настройки я тогда починила поимённо. Но ПОЛКИ — профили крутилок, цепочек,
# форм строфы — писались тем же `write_text` и такой защиты не получили: тот же
# сбой унёс бы и их, причём тихо. Заметил бы пользователь только открыв полку и не
# найдя своего.
#
# Здесь три правила, одинаковых для всех складов:
#   1. НЕ ПИСАТЬ ПОВЕРХ НЕПРОЧИТАННОГО. Файл есть, но не разбирается — отказ с
#      честной ошибкой. «Не смог прочитать» означает «не знаю, что там», а не
#      «там пусто»;
#   2. ЦЕЛИКОМ ИЛИ НИКАК. Пишем во временный файл рядом и подменяем одним
#      системным вызовом. Обрубков не бывает;
#   3. КОПИЯ ПРЕДЫДУЩЕГО. Один файл рядом, обновляется на каждой записи. То, из
#      чего можно вернуть потерянное, если беда придёт не с нашей стороны.

from __future__ import annotations

import json
import os
from pathlib import Path


def копия(путь: Path) -> Path:
    """Путь к копии предыдущего состояния склада."""
    return путь.with_suffix(путь.suffix + ".копия")


def читать(путь: Path, по_умолчанию):
    """Содержимое склада или `по_умолчанию`. Никогда не падает: сломанный склад
    — это потеря полки, а не отказ программы открыться."""
    try:
        return json.loads(путь.read_text("utf-8"))
    except (OSError, ValueError):
        return по_умолчанию


def писать(путь: Path, данные) -> None:
    """Записать склад по трём правилам выше. Единственное место, где эти правила
    живут: каждый склад, который заводит свою запись, рано или поздно забудет
    одно из них."""
    сырой = None
    try:
        сырой = путь.read_text("utf-8")
    except OSError:
        сырой = None

    есть_текст = сырой is not None and сырой.strip() != ""
    if есть_текст:
        try:
            json.loads(сырой)
        except ValueError:
            raise ValueError(
                f"склад {путь.name} есть, но не разбирается — запись отменена, "
                f"чтобы не стереть то, чего не видно. Почини или убери {путь}; "
                f"копия предыдущего состояния: {копия(путь)}")

    путь.parent.mkdir(parents=True, exist_ok=True)
    врем = путь.with_suffix(путь.suffix + ".новый")
    врем.write_text(json.dumps(данные, ensure_ascii=False, indent=1), "utf-8")
    if сырой:
        try:
            копия(путь).write_text(сырой, "utf-8")
        except OSError:
            pass            # копия — удобство, а не обязанность
    os.replace(врем, путь)
