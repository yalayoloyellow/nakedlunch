# nakedlunch — кэш ударений: чтение и запись без загрузки целиком (Раунд 57).
#
# ЗАЧЕМ. `core/data/nl_rhyme.json` — 832 МБ, 2.4 млн записей, и это ОДНА строка:
# `json.dumps` пишет без отступов. Значит построчного чтения не существует, и
# любой проход по кэшу обязан был поднять его в память целиком — около шести
# гигабайт. На 16-гигабайтной машине вместе с открытым приложением система
# такой процесс убивает молча: кнопка «пересчитать качество» падала, а в шапке
# висело «встало · 0%».
#
# РЕШЕНИЕ — ПОСТРОЧНЫЙ ФОРМАТ (JSONL): одна запись на строку,
# `{"t": текст, ...поля}`. Тогда любой проход читает строку, меняет что нужно,
# пишет строку — память постоянная, независимо от размера корпуса. Заодно это
# чинит две старые беды, записанные в шапке самого сборщика: загрузку кэша в
# `filters.warm_caches` и дописывание фрагментов при заливке книги (сейчас оно
# переписывает файл целиком, то есть «квадрат от числа заливок»).
#
# ПЕРЕХОД НЕ ОДНОСТОРОННЯЯ ДВЕРЬ. Читатель понимает ОБА формата и предпочитает
# построчный, если он есть. Миграция пишет НОВЫЙ файл рядом и старый не трогает:
# пока пользователь не убедился, что всё работает, откат — это удалить один файл.

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Iterator

DATA_DIR = Path(__file__).resolve().parent / "data"
СТАРЫЙ = DATA_DIR / "nl_rhyme.json"        # один огромный dict
СТРОЧНЫЙ = DATA_DIR / "nl_rhyme.jsonl"     # одна запись на строку


def есть_строчный() -> bool:
    return СТРОЧНЫЙ.exists() and СТРОЧНЫЙ.stat().st_size > 2


def поток() -> Iterator[tuple[str, dict]]:
    """Пары (текст, поля) по одной. На построчном файле память постоянная; на
    старом — деваться некуда, он читается целиком (последний раз, до миграции).
    """
    if есть_строчный():
        with СТРОЧНЫЙ.open(encoding="utf-8") as f:
            for строка in f:
                строка = строка.strip()
                if not строка:
                    continue
                try:
                    з = json.loads(строка)
                except ValueError:
                    continue          # битая строка — одна запись, а не весь кэш
                текст = з.pop("t", None)
                if текст is not None:
                    yield текст, з
        return
    if not СТАРЫЙ.exists():
        return
    for текст, поля in json.loads(СТАРЫЙ.read_text("utf-8")).items():
        yield текст, поля


def читать_всё() -> dict:
    """Весь кэш словарём — для тех, кому он нужен целиком (сборка индекса).
    Построчный формат читается тем же потоком, поэтому пик памяти тот же, что у
    результата, а не вдвое больше, как при разборе одной гигантской строки."""
    return dict(поток())


class Писатель:
    """Построчная запись с атомарной подменой.

    Целиком или никак: пишем во временный файл рядом и подменяем одним
    системным вызовом. Прерваться посреди прохода — значит оставить прежний
    файл нетронутым, а не обрубок, который следующее чтение примет за пустой
    кэш. Ровно этот круг стоил пользователю профилей сцены в этом же раунде.
    """

    def __init__(self, путь: Path | None = None):
        self.путь = путь or СТРОЧНЫЙ
        self.врем = self.путь.with_suffix(self.путь.suffix + ".новый")
        self._f = None
        self.записано = 0

    def __enter__(self):
        self.путь.parent.mkdir(parents=True, exist_ok=True)
        self._f = self.врем.open("w", encoding="utf-8")
        return self

    def запиши(self, текст: str, поля: dict) -> None:
        з = {"t": текст}
        з.update(поля)
        self._f.write(json.dumps(з, ensure_ascii=False) + "\n")
        self.записано += 1

    def __exit__(self, тип, знач, след):
        if self._f is not None:
            self._f.close()
            self._f = None
        if тип is not None:
            # проход упал — временный файл не подменяет ничего
            try:
                self.врем.unlink()
            except OSError:
                pass
            return False
        os.replace(self.врем, self.путь)
        return False
