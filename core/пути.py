# nakedlunch — где что лежит (Раунд 60).
#
# ЗАЧЕМ. Пока программа запускается из своей папки, вопроса нет: и таблицы, и
# данные пользователя, и испечённые индексы живут рядом с кодом. В собранном
# приложении так нельзя: бандл лежит в /Applications или в Program Files и на
# запись недоступен, а испечь индекс и сохранить историю программе надо.
#
# Отсюда РАЗДЕЛЕНИЕ НА ДВА КОРНЯ:
#
#   ЧТЕНИЕ — входные таблицы, которые едут вместе с программой и никогда не
#            меняются: словарь форм, лексикон, каркасы строф, модель векторов;
#   ЗАПИСЬ — всё, что программа создаёт: корпус пользователя, история,
#            избранное, настройки, полки, журнал, кэш ударений, индекс.
#
# В РАЗРАБОТКЕ ОБА КОРНЯ ПРЕЖНИЕ. Это не удобство, а требование: если пути
# разъедутся, половина тестов начнёт проверять пустоту, а вторая — чужие
# данные. Поэтому вне бандла всё остаётся ровно там, где было, и refactor
# доказуемо ничего не меняет — 556 тестов остаются зелёными.
#
# ИЗОЛЯЦИЯ ПРОВЕРОК: одна переменная на всё (Раунд 61). `NAKEDLUNCH_HOME`
# уводит В САМОМ ДЕЛЕ ВСЁ — корень записи, корпус, листы и записи. До Раунда 61
# это было ложным обещанием дважды: у переменной не было ни одного вызывающего,
# а корень записи не покрывал ни одно из трёх хранилищ (у каждого своя
# переменная). Живая проверка, доверившаяся документации, писала бы в
# настоящие данные пользователя.
#
# Порядок для каждого хранилища (см. `хранилище`): своя переменная →
# NAKEDLUNCH_HOME → умолчание. Точечный увод одного хранилища по-прежнему
# возможен своей переменной.
#
# ПОЧЕМУ НЕ «ПАПКА РЯДОМ С ПРОГРАММОЙ». Она недоступна на запись в macOS
# (/Applications) и в Windows (Program Files), а просить пользователя ставить
# программу в домашнюю папку — перекладывать на него нашу задачу.

from __future__ import annotations

import os
import sys
from pathlib import Path

# ВЫВОД ВСЕГДА В UTF-8 (Раунд 60).
#
# Консоль Windows по умолчанию живёт в cp1252, и любая русская строка в `print`
# роняет процесс с UnicodeEncodeError. Поймано первой же сборкой под Windows:
# загрузчик моделей успешно скачал файлы, но упал на строке отчёта об этом — и
# отчитался, что не смог скачать ни одного. Отказ, который врёт о причине,
# хуже отказа.
#
# Чиним в одном месте: этот модуль импортируют все части программы, значит
# перенастройка потоков случается ровно один раз и до первого вывода.
for _поток in (sys.stdout, sys.stderr):
    try:
        _поток.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass                        # поток может быть подменён или закрыт

КОРЕНЬ_КОДА = Path(__file__).resolve().parent.parent


def упаковано() -> bool:
    """Программа запущена из собранного бандла, а не из исходников."""
    return bool(getattr(sys, "frozen", False))


def _корень_чтения() -> Path:
    """Откуда читаются встроенные таблицы."""
    if упаковано():
        # PyInstaller распаковывает данные во временный каталог и кладёт путь
        # в sys._MEIPASS; onedir-сборка держит их рядом с исполняемым файлом.
        меипасс = getattr(sys, "_MEIPASS", None)
        return Path(меипасс) if меипасс else Path(sys.executable).resolve().parent
    return КОРЕНЬ_КОДА


def из_среды(имя: str) -> Path | None:
    """Путь из переменной среды. `None`, если переменная не задана.

    ПУСТАЯ СТРОКА — ОШИБКА, А НЕ «НЕ ЗАДАНО» (Раунд 61). Прежде пустое значение
    было неотличимо от отсутствия и молча уводило в боевой путь. Поймано на
    живой проверке: `ВРЕМ=...` в zsh не присвоилось (кириллическое имя),
    подстановка дала пустую строку, и проверка чуть не пошла по настоящему
    корпусу. Отказ, который врёт о причине, хуже отказа.
    """
    знач = os.environ.get(имя)
    if знач is None:
        return None
    знач = знач.strip()
    if not знач:
        raise RuntimeError(
            f"переменная среды {имя} задана пустой строкой. Это почти всегда "
            f"осечка подстановки в оболочке; пустое значение молча увело бы "
            f"программу к боевым данным. Уберите переменную или задайте путь.")
    return Path(знач).expanduser()


def хранилище(переменная: str, подпапка: str, по_умолчанию: Path) -> Path:
    """Корень ОДНОГО хранилища: корпуса, листов или записей.

    ЗАЧЕМ ОДНА ФУНКЦИЯ НА ТРИ МЕСТА (Раунд 61). Документация обещала, что
    `NAKEDLUNCH_HOME` уводит проверку от боевых данных. Обещание было ложным
    дважды: у переменной не было НИ ОДНОГО вызывающего, и корень записи не
    покрывает ни корпус (`NAKEDLUNCH_DATA`), ни листы (`NAKEDLUNCH_VAULT`), ни
    записи (`NAKEDLUNCH_RECORDINGS`). Изолировать проверку можно было только
    выставив все четыре разом — и об этом нигде не было сказано.

    Теперь порядок один для всех: своя переменная → `NAKEDLUNCH_HOME` →
    умолчание. Значит `NAKEDLUNCH_HOME` в одиночку уводит В САМОМ ДЕЛЕ ВСЁ, а
    отдельная переменная по-прежнему может увести одно хранилище точечно.
    """
    своё = из_среды(переменная)
    if своё is not None:
        return своё
    дом = из_среды("NAKEDLUNCH_HOME")
    if дом is not None:
        return дом / подпапка
    return по_умолчанию


def _корень_записи() -> Path:
    """Куда программа пишет. Переопределяется NAKEDLUNCH_HOME — этим же приёмом
    тесты и живые проверки уводятся во временную папку, не трогая настоящее."""
    свой = из_среды("NAKEDLUNCH_HOME")
    if свой is not None:
        return свой
    if not упаковано():
        return КОРЕНЬ_КОДА
    if sys.platform == "darwin":
        return Path.home() / "Library" / "Application Support" / "nakedlunch"
    if os.name == "nt":
        база = os.environ.get("APPDATA") or (Path.home() / "AppData" / "Roaming")
        return Path(база) / "nakedlunch"
    база = os.environ.get("XDG_DATA_HOME") or (Path.home() / ".local" / "share")
    return Path(база) / "nakedlunch"


ЧТЕНИЕ = _корень_чтения()
ЗАПИСЬ = _корень_записи()

# Встроенные таблицы: форм, лексикон, каркасы, векторы.
ТАБЛИЦЫ = ЧТЕНИЕ / "core" / "data"
# Испечённое: кэш ударений, колоночный индекс, словарь рифм, чёрный список.
АРТЕФАКТЫ = ЗАПИСЬ / "core" / "data"
# Данные пользователя: корпус, история, избранное, настройки, полки, журнал.
ДАННЫЕ = ЗАПИСЬ / "data"


def таблица(имя: str) -> Path:
    """Встроенная таблица. Если её положили в записываемый корень (так бывает
    при обновлении словаря на месте) — берём оттуда: свежее важнее."""
    свежая = АРТЕФАКТЫ / имя
    if свежая.exists():
        return свежая
    return ТАБЛИЦЫ / имя


def артефакт(имя: str) -> Path:
    return АРТЕФАКТЫ / имя


def данные(имя: str = "") -> Path:
    return ДАННЫЕ / имя if имя else ДАННЫЕ


def подготовить() -> None:
    """Создать каталоги записи. Зовётся один раз при старте: программа не
    должна падать на первом же сохранении из-за отсутствующей папки."""
    for p in (ДАННЫЕ, АРТЕФАКТЫ):
        try:
            p.mkdir(parents=True, exist_ok=True)
        except OSError:
            pass
