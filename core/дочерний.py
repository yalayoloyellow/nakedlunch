# nakedlunch — как программа запускает свои части (Раунд 60).
#
# ЗАЧЕМ. Приложение состоит из окна, сервера и сборщиков, и запускает их
# отдельными процессами: сборка индекса не должна ронять окно, а сервер обязан
# пережить долгий проход по корпусу. В исходниках это просто — берём питон и
# зовём нужный файл.
#
# В СОБРАННОМ ПРИЛОЖЕНИИ ПИТОНА НЕТ. `sys.executable` там — само приложение, а
# файлов `api/server.py` рядом не лежит. Поэтому собранная программа зовёт
# САМА СЕБЯ с именем роли первым аргументом, а точка входа разводит роли (см.
# main.py). Снаружи это тот же процесс-ребёнок, только команда другая.
#
# Один модуль на все три места, где ребёнок запускается: разъехавшиеся команды
# — это тот случай, когда в разработке работает, а у людей нет.
#
# ЗДЕСЬ ТОЛЬКО КОМАНДА, НО НЕ СРЕДА — И ЭТО НАРОЧНО (2026-08-18). Корни записи
# считает `core/пути.py` при импорте, из `NAKEDLUNCH_HOME`. У ребёнка импорт
# СВОЙ, значит корни он считает заново — и совпадут они с родительскими ровно
# потому, что `subprocess.Popen` без `env=` отдаёт ребёнку `os.environ` целиком.
# То есть изоляция переходит границу процесса сама, без единой строки кода, и
# отдельной «передачи корней» тут нет не по недосмотру.
#
# Плата за молчаливость — доброе намерение вида «почищу ребёнку среду»: один
# `env=` в любом `subprocess.Popen`, и сборщик начнёт писать кэш и сайдкар в
# БОЕВОЙ `core/data`, пока родитель считает, что работает в песочнице. Снаружи
# при этом всё работает, поэтому караулят это два сторожа в
# `tests/test_izolyatsiya.py`: один смотрит, где ребёнок считает свои корни,
# второй — на сами места запуска в `api/server.py` и `launch.py`.

from __future__ import annotations

import sys

import пути

РОЛИ = {
    "сервер": пути.КОРЕНЬ_КОДА / "api" / "server.py",
    "ударения": пути.КОРЕНЬ_КОДА / "tools" / "build_nl_rhyme.py",
    "индекс": пути.КОРЕНЬ_КОДА / "tools" / "build_nl_index.py",
}


def команда(роль: str) -> list[str]:
    """Начало командной строки для запуска роли отдельным процессом."""
    if роль not in РОЛИ:
        raise ValueError(f"неизвестная роль: {роль}")
    if пути.упаковано():
        return [sys.executable, роль]
    # В разработке предпочитаем питон окружения проекта: у системного может не
    # быть зависимостей, и ребёнок умрёт на первом же импорте.
    # ДВЕ РАСКЛАДКИ ВЕНВА (Раунд 61). На POSIX это `.venv/bin/python`, на
    # Windows — `.venv\Scripts\python.exe`. Проверялась только первая, значит на
    # Windows защита не срабатывала никогда: брался системный питон — ровно то,
    # чего комментарий выше обещает избежать.
    for отн in (("bin", "python"), ("Scripts", "python.exe")):
        свой = пути.КОРЕНЬ_КОДА / ".venv" / отн[0] / отн[1]
        if свой.exists():
            return [str(свой), str(РОЛИ[роль])]
    return [sys.executable, str(РОЛИ[роль])]
