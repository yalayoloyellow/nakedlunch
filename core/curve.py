#
# Владелец отложил её «после агента» и просил принять или отбросить на уровне
# размышления. Принята в той трактовке, которую мы разобрали: это НЕ второй
# движок компоновки, а ПОСТАВЩИК КРУТИЛОК ЗВЕНЬЕВ — тот же слот, куда садится
# референс. Референс берёт их из замеренного текста, кривая — из формы.
#
# Отсюда и цена: ноль изменений в ядре. `linkKnobs` на фронте уже умеет брать
# крутилки «снятые референсом», а `linkSpec` при отсутствии спеки честно
# падает на форму строфы звена — то есть кривая задаёт ЗВУЧАНИЕ, а каркас
# остаётся тот, что владелец выбрал сам. Это не экономия, а граница: длину
# строк и рифмовку он решает руками, машина ведёт только плотность.
#
# ПОЧЕМУ ОДНА ОСЬ, А НЕ ЧЕТЫРЕ. Кривая по каждой крутилке отдельно — это
# четыре независимых числа на звено, которые владелец не сможет ни услышать
# по отдельности, ни объяснить себе. Ось одна и называется ПЛОТНОСТЬ: к
# припеву плотнее (строки цепляются друг за друга, лексика обычнее), к бриджу
# реже. Это ровно то, чем песня отличается от цепочки независимых строф.
#
# ЧТО ПЛОТНОСТЬ ДВИГАЕТ:
#   «Связность»  — насколько соседние строки цепляются по смыслу;
#   «Банальность» — насколько лексика обычная (у припева она выше, и это не
#                   дефект, а жанр).
# Обе — крутилки ЗВЕНА, обе действуют уже сегодня, обе слышны. Слоги и рифмовка
# НЕ трогаются: они живут в каркасе, а каркас — решение владельца.

from __future__ import annotations

import math

import clean

# Формы названы тем, что слышно, а не математикой: владелец выбирает звучание,
# а не тип функции.
ФОРМЫ = ("нарастание", "спад", "волна", "провал")

# Плотность при нулевой силе — середина шкалы. Кривая качает ОТ неё, поэтому
# сила 0 даёт ровную цепочку, а не резкий сдвиг всего сразу.
СЕРЕДИНА = 0.5


def _форма(имя: str, t: float) -> float:
    """Значение формы в точке t (0..1) в пределах −1..+1.

    `провал` — это НЕ перевёрнутая волна: у волны один подъём и один спад, а у
    провала края высокие, а середина низкая. Для песни это разные вещи —
    «бридж проседает» и «второй куплет тише» звучат по-разному.

    Незнакомое имя (опечатка, старый сохранённый профиль) берёт «нарастание».
    Решение об этом принимается ЗДЕСЬ и только здесь: сначала такой же выбор
    стоял и в `плотность`, и мутационная проверка показала, что второй экземпляр
    ничего не сторожит — его можно снять, и ни один тест не заметит."""
    if имя == "спад":
        return 1.0 - 2.0 * t
    if имя == "волна":
        return math.sin(2.0 * math.pi * t)
    if имя == "провал":
        return math.cos(2.0 * math.pi * t)
    return 2.0 * t - 1.0        # нарастание — и оно же дефолт


def плотность(n: int, форма: str = "нарастание", сила: float = 1.0) -> list[float]:
    """Плотность на каждое из n звеньев, 0..1.

    Одно звено — это одиночная строфа, у неё формы нет по определению: вести
    нечего, и кривая честно отдаёт середину, а не край."""
    n = max(0, int(n))
    if n <= 0:
        return []
    if n == 1:
        return [СЕРЕДИНА]
    с = max(0.0, min(1.0, float(сила)))
    out = []
    for i in range(n):
        t = i / (n - 1)
        v = СЕРЕДИНА + 0.5 * с * _форма(форма, t)
        out.append(round(max(0.0, min(1.0, v)), 3))
    return out


# Края шкалы банальности — это уже не форма, а ВОРОТА: на нуле потолок самый
# строгий (banality 1.0 → потолок 4.0), и одно звено песни молча осталось бы
# без кандидатов, а владелец увидел бы «пусто на звене» вместо задуманной
# формы. Поэтому плотность ведёт её в рабочей полосе, а не до упора.
#
# Связность так НЕ жмётся намеренно: это цель ранжира, а не отсев. Ноль на ней
# значит «соседние строки максимально не связаны» — законное звучание для
# бриджа, и запрещать его было бы решением за владельца.
БАНАЛЬНОСТЬ_ПОЛОСА = (0.15, 0.85)


def _в_полосу(v: float, полоса: tuple[float, float]) -> float:
    низ, верх = полоса
    return round(низ + v * (верх - низ), 3)


def цепочка(n: int, форма: str = "нарастание", сила: float = 1.0) -> dict:
    """n звеньев → крутилки на каждое, в координатах ИНТЕРФЕЙСА.

    Форма ответа — та же, что у refprofile.цепочка, и это не совпадение:
    фронт кладёт её в тот же слот и разбирает тем же резолвером. Спеки здесь
    НЕТ намеренно — каркас остаётся тот, что выбран у звена.

    Стыки не назначаются вовсе: кривая ведёт звучание внутри строф, а чем
    строфы склеены — отдельное решение владельца, и молча его переписывать
    значило бы менять песню там, где просили менять плотность."""
    звенья = []
    for p in плотность(n, форма, сила):
        звенья.append({
            "title": "",
            "mode": clean.MODE_ALGO,
            "params": {
                # Связность: кривая её ВКЛЮЧАЕТ. Это осознанно — «собрать по
                # кривой» и есть просьба вести звучание, а выключенная
                # связность (−1) означала бы, что кривая ведёт половину того,
                # что обещает.
                "Связность": p,
                # Банальность: у припева лексика обычнее, и это жанр, а не
                # дефект. ПЛОТНОСТЬ ИДЁТ СЮДА НАОБОРОТ (Раунд 58): шкала стала
                # двусторонней, и теперь МЕНЬШЕ = банальнее. Правило («у припева
                # обычнее») не менялось — поменялось направление шкалы под ним,
                # и не перевернуть здесь значило бы молча начать вести припев в
                # обратную сторону. Полоса та же — см. БАНАЛЬНОСТЬ_ПОЛОСА.
                "Банальность": _в_полосу(1.0 - p, БАНАЛЬНОСТЬ_ПОЛОСА),
            },
        })
    return {"chain": звенья}
