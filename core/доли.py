# nakedlunch — ДОЛИ: многовыборность со ВЕСАМИ (2026-08-29).
#
# ЗАЧЕМ. требование: «ручки мы делаем многовыборными… может я хочу 20
# процентов где на первое слово рифма, 50 процентов в середине и 30 процентов в
# конце. В целом многовыборность это важный принцип».
#
# Маска (2026-08-28) отвечала на вопрос «какие сорта годятся». Доли отвечают на
# следующий: «в какой пропорции». Маска — частный случай долей с равными весами,
# и хранится тем же полем: пустая строка значит «поровну по маске».
#
# ПОЧЕМУ ПАМЯТЬ НЕДОБОРА, А НЕ ЧЕСТНЫЙ ЖРЕБИЙ. В строфе рифмопар одна-две, и
# 20% от двух пар — это 0.4 пары, а пара неделима. Чистый жребий по весам даёт
# нужную пропорцию только на длинной дистанции: на пяти строфах «20% начала»
# честно может выпасть нулём. Поэтому здесь не бросок монеты, а РАСПРЕДЕЛЕНИЕ
# ОСТАТКА (тот же приём, что у линии Брезенхэма и у дробного сглаживания):
# каждый сорт копит свой долг, и следующим берётся тот, кому недодали больше
# всех. На десяти подряд «20/50/30» даёт ровно 2/5/3, а не «примерно».
#
# ОДИН МЕХАНИЗМ НА ВСЕ РУЧКИ. Клаузула, ярусы рифмы, позиция рифмы, мат — у
# всех одна арифметика и один формат хранения. Двух реализаций одного понятия в
# этом проекте уже хватало (см. надгробия про «фильтра два»).
#
# ФОРМАТ ХРАНЕНИЯ — СТРОКА, РЯДОМ С ЧИСЛОВЫМИ КРУТИЛКАМИ, а не внутри них:
# «1:20,2:50,4:30» — бит сорта и его доля в процентах. Канон крутилок числовой
# (одно число на ручку), несколько долей в него не влезают — ровно та же
# причина, по которой полосы редкости живут отдельной строкой рядом с
# `params` (см. `core/редкость.py` и `settings._nl_params`).
from __future__ import annotations


def разобрать(строка: str | None, маска: int) -> dict[int, float]:
    """«1:20,4:80» → {1: 0.2, 4: 0.8}. Пустая строка — поровну по маске.

    Правила, и каждое снято с грабель этого проекта:
      · биты, погасшие в маске, отбрасываются: маска — источник правды о том,
        ЧТО выбрано, доли — только о пропорции. Иначе выключенный чипами сорт
        воскресал бы из сохранённой строки;
      · сумма нормируется к единице (человек введёт «20/50/40» — и это не
        повод отказывать);
      · сорт из маски, которого нет в строке, получает `МИНИМУМ`, а не ноль —
        см. разбор у самой константы: сто процентов одному сорту полоской не
        выражаются, это работа чипа;
      · мусор молча игнорируется — ручка не имеет права уронить прогон.
    """
    биты = [б for б in (1, 2, 4, 8) if маска & б]
    if not биты:
        return {}
    веса: dict[int, float] = {}
    for кусок in str(строка or "").split(","):
        кусок = кусок.strip()
        if not кусок or ":" not in кусок:
            continue
        сорт, _, доля = кусок.partition(":")
        try:
            б, в = int(сорт), float(доля)
        except (TypeError, ValueError):
            continue
        if б in биты and в > 0:
            веса[б] = веса.get(б, 0.0) + в
    if not веса:
        return {б: 1.0 / len(биты) for б in биты}
    итого = sum(веса.values())
    доли_ = {б: веса.get(б, 0.0) / итого for б in биты}
    return _минимум_каждому(доли_)


# ЕСЛИ ДЕЛИМ — ТО ДЕЛИМ (2026-08-30, требование: «естественно, заранее
# надо заложить ограничение: если мы вообще что-то делим на доли — мы нигде
# 100 процентов и не можем указать; а если хотим сто процентов, это чип»).
#
# Полоска отвечает на вопрос «в какой пропорции», и сто процентов одному —
# это не пропорция, а выключение остальных. Выключение живёт этажом выше и
# делается ЧИПОМ: погасил сорт — его нет в маске вовсе, и ворота исполняют это
# точно (замер: только внутренняя — 100% внутренних). Пустить сюда сотню
# значило бы дать два разных способа сделать одно, и второй — обманчивый:
# доли уступают рифме, и «100% середины» полоской даёт на деле около 64%.
#
# Поэтому каждому ВКЛЮЧЁННОМУ сорту гарантирован минимум. Два процента — не
# круглое число ради красоты: на выдаче в сорок строк это одна строка, то есть
# наименьшая различимая доля. Меньше — уже ноль, замаскированный под число.
МИНИМУМ = 0.02


def _минимум_каждому(доли_: dict) -> dict:
    """Поднять нули и крохи до МИНИМУМА, отняв разницу у крупных пропорционально."""
    if len(доли_) < 2:
        return доли_
    мало = {б: в for б, в in доли_.items() if в < МИНИМУМ}
    if not мало:
        return доли_
    добавка = sum(МИНИМУМ - в for в in мало.values())
    крупные = {б: в for б, в in доли_.items() if в >= МИНИМУМ}
    запас = sum(крупные.values())
    итог = {б: МИНИМУМ for б in мало}
    for б, в in крупные.items():
        итог[б] = в - добавка * (в / запас) if запас else МИНИМУМ
    return {б: итог[б] for б in доли_}


def записать(веса: dict[int, float]) -> str:
    """Обратно в строку, процентами. Для экрана и для сохранения."""
    if not веса:
        return ""
    return ",".join(f"{б}:{round(в * 100)}" for б, в in sorted(веса.items()) if в > 0)


class Жребий:
    """Кому дать следующий слот, чтобы доли сошлись на коротком отрезке.

    Держит долг каждого сорта: с каждой выдачей всем начисляется их доля, а
    получивший слот платит единицу. Следующим берётся самый должный — то есть
    тот, кому недодали больше всех. Это детерминированно и без накопления
    ошибки: на N слотах отклонение от заданных долей меньше одного слота.

    `пропустить` — для случая, когда сорт физически недоступен (в корпусе нет
    строк такой клаузулы в этой слоговой вилке): долг ему не гасится, и он
    получит слот, как только станет доступен, а не потеряет очередь навсегда.
    """

    def __init__(self, веса: dict[int, float]):
        self.веса = {б: в for б, в in (веса or {}).items() if в > 0}
        # ПЕРВОЕ НАЧИСЛЕНИЕ СРАЗУ, А НЕ С НУЛЯ. С нулевых долгов первый слот
        # доставался бы младшему БИТУ, а не самому весомому сорту: на строфе с
        # двумя парами «20/50/30» отдало бы слот двадцати процентам. Начальный
        # долг равен доле — то есть очередь сразу выстроена по весу.
        self.долг = dict(self.веса)

    def порядок(self) -> list[int]:
        """Сорта от самого должного к наименее — вызывающий берёт первый
        доступный, а не гадает, что делать с недоступным."""
        return sorted(self.долг, key=lambda б: (-self.долг[б], б))

    def взять(self, сорт: int) -> None:
        """Слот ушёл этому сорту: всем начислить долю, ему списать единицу."""
        if not self.веса:
            return
        for б, в in self.веса.items():
            self.долг[б] += в
        if сорт in self.долг:
            self.долг[сорт] -= 1.0

    def следующий(self, доступен=None) -> int | None:
        """Сорт для следующего слота. `доступен(сорт) -> bool` — проверка, что
        сорт вообще есть в материале; без неё берётся самый должный."""
        for б in self.порядок():
            if доступен is None or доступен(б):
                return б
        return None
