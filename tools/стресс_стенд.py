# -*- coding: utf-8 -*-
"""СТРЕСС-СТЕНД ЗАЛИВКИ КНИГ.

Кидает в заливку сорок разных входов — все кодировки, битые файлы, кривую
вёрстку, аппарат издания, вырожденное — и печатает, что дошло до склада, а что
отвергнуто и почему.

ЗАЧЕМ ОТДЕЛЬНО ОТ ТЕСТОВ. Тесты сторожат по одному правилу и отвечают «да/нет».
Стенд показывает КАРТИНУ ЦЕЛИКОМ и глазами: видно не только что отказ случился,
но и какой текст в итоге лёг в склад. Так нашлась порча эмодзи — валидный utf-8
уходил в перебор однобайтовых и превращался в «ЁЯФе ЁЯТА», а ни один тест этого
не спрашивал.

Прогон (боевые данные не трогает — своё хранилище во временном каталоге):

    NAKEDLUNCH_HOME=/tmp/стенд .venv/bin/python tools/стресс_стенд.py
"""
import os, sys, time, random, pathlib, shutil, traceback
sys.path.insert(0, "core")
from nlsrc.store import NakedLunchStore
from nlsrc.cutter import parse_source_file, clean_text, cut_into_fragments
import nlbridge

ШАПКА = ('<?xml version="1.0" encoding="{к}"?><FictionBook '
         'xmlns="http://www.gribuser.ru/xml/fictionbook/2.0" '
         'xmlns:l="http://www.w3.org/1999/xlink">')
ПРОЗА = ("Стояла зима, мороз был крепок, и снег скрипел под ногами прохожих. "
         "Он шёл вдоль набережной и думал о том, что всё когда-нибудь кончается. "
         "Ветер нёс запах гари, где-то далеко играла музыка и было очень тихо. ")

def фб2(тело, кодировка="utf-8"):
    return (ШАПКА.format(к=кодировка) + тело + "</FictionBook>").encode(кодировка)

def абз(n=40, текст=None):
    т = текст or ПРОЗА
    return "".join(f"<p>{т} Абзац {'первый' if i%2 else 'второй'} тут.</p>" for i in range(n))

ПРОБЫ = []
def проба(имя, имя_файла, байты, ждём):
    ПРОБЫ.append((имя, имя_файла, байты, ждём))

# ── 1. кодировки ────────────────────────────────────────────────────────────
for код in ("utf-8", "utf-8-sig", "cp1251", "koi8-r", "cp866", "iso8859-5",
            "mac-cyrillic", "utf-16", "utf-16-le", "utf-16-be"):
    проба(f"txt в {код}", "к.txt", (ПРОЗА * 12).encode(код), "прошло")

# ── 2. битое и не-текст ─────────────────────────────────────────────────────
_r = random.Random(1)
случ = bytes(_r.randrange(256) for _ in range(40_000))
проба("пустой файл",        "к.txt", b"", "отказ")
проба("случайные байты",    "к.txt", случ, "отказ")
проба("PNG под именем txt", "к.txt", b"\x89PNG\r\n\x1a\n" + случ, "отказ")
проба("ZIP под именем txt", "к.txt", b"PK\x03\x04" + случ, "отказ")
проба("PNG под именем fb2", "к.fb2", b"\x89PNG\r\n\x1a\n" + случ, "отказ")
проба("обрезанный fb2",     "к.fb2", '<?xml version="1.0"?><FictionBook><body><p>текст не'.encode(), "отказ")
проба("fb2 без тела",       "к.fb2", фб2("<description/>"), "отказ")
проба("формат .epub",       "к.epub", (ПРОЗА*12).encode(), "отказ")
проба("формат .docx",       "к.docx", (ПРОЗА*12).encode(), "отказ")

# ── 3. вырожденное ──────────────────────────────────────────────────────────
проба("одно слово",        "к.txt", "слово".encode(), "отказ")
проба("только цифры",      "к.txt", ("123 456 789 " * 400).encode(), "отказ")
проба("только знаки",      "к.txt", ("... --- ,,, !!! " * 400).encode(), "отказ")
проба("эмодзи",            "к.txt", ("🔥 💀 🌊 " * 800).encode(), "отказ")
проба("текст из одной буквы", "к.txt", b"A" * 8000, "отказ")
проба("латиница",          "к.txt", ("The quick brown fox jumps over the lazy dog again. "*40).encode(), "прошло")
проба("китайский",         "к.txt", ("我们都是中国人民的好朋友和同志们 " * 200).encode(), "отказ")
проба("одна строка 2 МБ",  "к.txt", (ПРОЗА * 8000).encode(), "прошло")
проба("слово в 50к букв",  "к.txt", ("я" * 50_000).encode(), "отказ")

# ── 4. кривая вёрстка ───────────────────────────────────────────────────────
проба("вложенные <p>", "к.fb2",
      фб2("<body><section>" + "".join(
          f"<p>снаружи {ПРОЗА}<p>внутри тоже текст идёт сюда</p> и хвост</p>"
          for _ in range(30)) + "</section></body>"), "прошло")
проба("пробел внутри тега", "к.fb2",
      фб2("<body><section>" + "".join(
          f"<p>как мы сейчас, и <emphasis>постигай </emphasis>мир до конца. {ПРОЗА}</p>"
          for _ in range(30)) + "</section></body>"), "прошло")
проба("глубокая вложенность", "к.fb2",
      фб2("<body><section>" + "<section>"*40 + абз(30) + "</section>"*40 + "</section></body>"), "прошло")
проба("fb2 версии 2.1", "к.fb2",
      ('<?xml version="1.0" encoding="utf-8"?><FictionBook '
       'xmlns="http://www.gribuser.ru/xml/fictionbook/2.1">'
       f"<body><section>{абз(30)}</section></body></FictionBook>").encode(), "прошло")
проба("fb2 без пространства имён", "к.fb2",
      ('<?xml version="1.0" encoding="utf-8"?><FictionBook>'
       f"<body><section>{абз(30)}</section></body></FictionBook>").encode(), "прошло")
проба("fb2 в windows-1251", "к.fb2", фб2(f"<body><section>{абз(30)}</section></body>", "cp1251"), "прошло")

# ── 5. аппарат издания ──────────────────────────────────────────────────────
сноски = "".join(f'<p>Софию,<a l:href="#n{i}" type="note">[{i}]</a> завершая. {ПРОЗА}</p>'
                 for i in range(30))
проба("30 сносок тегом", "к.fb2",
      фб2(f"<body><section>{сноски}</section></body>"
          f'<body name="notes"><section><p>Указ. соч., с. 122. Примечание.</p></section></body>'),
      "прошло")
летопись = "".join(f"<p>19{40+i} — {i+1} июня произошло важное событие тут.</p>" for i in range(12))
проба("летопись в конце", "к.fb2",
      фб2(f"<body><section>{абз(40)}{летопись}</section></body>"), "прошло")
проба("номера страниц", "к.fb2",
      фб2("<body><section>" + "".join(f"<p>{ПРОЗА}</p><p>{100+i}</p>" for i in range(30))
          + "</section></body>"), "прошло")
проба("оглавление заголовками", "к.fb2",
      фб2("<body><section>" + "".join(
          f"<title><p>Глава {i} про всякое</p></title><p>{ПРОЗА}</p>" for i in range(30))
          + "</section></body>"), "прошло")

# ── 6. переносы ─────────────────────────────────────────────────────────────
переносы = ("текст с пере-\nносом слова и менее тща-\nтельному разбору. "
            "он был где-\nто далеко, всё из-\nза тебя, пусть кто-\nнибудь придёт. "
            "полюса микро-\nи макрокосма, скорость 60 км/ч была большой. ")
проба("переносы всех видов", "к.txt", (переносы * 30).encode(), "прошло")
проба("юникодные дефисы", "к.txt",
      ((переносы.replace("-", "‐") + переносы.replace("-", "­")) * 20).encode(), "прошло")

def прогон():
    корень = pathlib.Path(os.environ["NAKEDLUNCH_HOME"])
    print(f"{'проба':<30} {'ждём':<8} {'исход':<10} {'фраг':>7}  что вышло / почему нет")
    print("─" * 118)
    сошлось = 0
    for имя, файл, байты, ждём in ПРОБЫ:
        дом = корень / f"д{len(имя)}{abs(hash(имя))%99999}"
        shutil.rmtree(дом, ignore_errors=True); (дом/"data").mkdir(parents=True)
        с = NakedLunchStore(дом/"data")
        t = time.time()
        try:
            к = nlbridge.add_source_from_bytes(с, файл, байты, save=False)
            исход, n = "прошло", к.fragment_count
            обр = next((f.text for f in с.state.fragments if len(f.text) > 25), "—")
            хвост = обр[:52]
        except ValueError as e:
            исход, n, хвост = "отказ", 0, str(e)
        except Exception as e:
            исход, n, хвост = "УПАЛО", 0, f"{type(e).__name__}: {str(e)[:44]}"
        ок = (исход == ждём); сошлось += ок
        print(f"{имя:<30} {ждём:<8} {('✓ ' if ок else '✗ ')+исход:<10} {n:>7}  {хвост}")
        shutil.rmtree(дом, ignore_errors=True)
    print("─" * 118)
    print(f"сошлось {сошлось} из {len(ПРОБЫ)}")

прогон()
