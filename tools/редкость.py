# nakedlunch — РЕДКОСТЬ: две шкалы и что на них лежит.
#
# ЗАМЫСЕЛ ВЛАДЕЛЬЦА (2026-08-25), собранный из четырёх его поправок:
#
#   1. «редкость — мы замеряем по всему корпусу, а не по одной книге»
#   2. «если слово в самой книге очень частое, оно не может быть самым редким
#      по определению — это выборку объективнее делает»
#   3. «не либо-либо, а среднее арифметическое»
#   4. «мы перемножаем редкость каждого слова, а не какого-то одного»
#
# ИТОГОВАЯ ФОРМУЛА:
#
#     редкость слова  = ( доля в корпусе + доля в своей книге ) / 2
#     редкость строки = ( р₁ × р₂ × … × рₙ ) ^ 1/n        ← корень обязателен
#
# ПОЧЕМУ КОРЕНЬ. Без него произведение падает с каждым множителем, и крутилка
# превращается в измеритель длины: замер дал связь с числом слов −0.950, а в
# редкий конец шли не редкие строки, а длинные (медиана 8 слов против 4 по
# корпусу). Корень приводит к одному слову и связь с длиной убирает: −0.046.
# Замысел при этом цел — участвуют ВСЕ слова, каждое своим множителем.
#
# ДВЕ ОСИ, А НЕ ОДНА. Замер: связь между ними r = +0.337, то есть они правда
# разные. Слить их в одну крутилку нельзя — теряется целый угол «обычные слова
# в диком сочетании» (62 460 строк: «Мир построен в эфирном флюиде», «Издатели
# всегда ищут новые таланты под старыми именами»). В единой шкале он
# размазывается по 31–68%, то есть недостижим.
#
# ШКАЛА — ПРОЦЕНТИЛЬ СРЕДИ СТРОК, а не среди слов. По словарю она схлопывается:
# минимум даёт 51% строк в верхнем ярусе, среднее 79%, медиана 90%. Причина —
# в любой строке почти всегда есть хоть одно частое слово. Процентиль по
# строкам ровен по построению: полоса [a%, b%] всегда даёт b−a процентов.
#
# Прогон (боевые данные только читает):
#     .venv/bin/python tools/редкость.py --ячейки
#
# ШКАЛА: 0% — самые нередкие (сплошь «быть, этот, тот»),
#        100% — самые редкие.
#     .venv/bin/python tools/редкость.py --выбор 5-10,17-18,97-98

from __future__ import annotations

import argparse
import json
import random
import pathlib
import sys
import tempfile
import time
from pathlib import Path

import numpy as np

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "core"))

import nlindex  # noqa: E402
import пути  # noqa: E402

# КЭШ — ВО ВРЕМЕННЫЙ КАТАЛОГ, А НЕ В ДАННЫЕ (2026-08-25). Первый прогон
# положил 36 МБ прямо в `core/data/` владельца. Инструмент исследовательский:
# он ничего не печёт и его кэш — расходник, которому в корпусе не место.
КЭШ = pathlib.Path(tempfile.gettempdir()) / "nakedlunch-редкость.npz"


def _посчитать():
    """Обе шкалы из колонок индекса. Ничего не печётся — только читается."""
    idx = nlindex.load()
    if idx is None:
        sys.exit("индекса нет — сперва tools/build_nl_index.py")
    мета = json.loads((пути.АРТЕФАКТЫ / "nl_index" / "meta.json").read_text("utf-8"))
    леммы = мета["lemmas"]
    n_л = len(леммы)
    off = np.asarray(idx.lem_off)
    ids = np.asarray(idx.lem_ids)
    src = np.asarray(idx.src)
    n_кн = int(src.max()) + 1

    # ---- слово: доля в корпусе и доля в своей книге -------------------------
    книга_вхождения = np.repeat(src, np.diff(off))
    годно = книга_вхождения >= 0
    счёт = np.bincount(
        книга_вхождения[годно].astype(np.int64) * n_л + ids[годно].astype(np.int64),
        minlength=n_кн * n_л,
    ).reshape(n_кн, n_л).astype(np.float64)
    размер = счёт.sum(axis=1)
    размер[размер == 0] = 1
    доля_корпус = счёт.sum(axis=0) / счёт.sum()
    доля_книга = счёт / размер[:, None]

    # ---- сочетание: пара соседних лемм, тоже с двух сторон ------------------
    пар = np.maximum(0, np.diff(off) - 1)
    есть = пар > 0
    ном = np.flatnonzero(есть)
    лев = np.concatenate([ids[off[i]:off[i + 1] - 1] for i in ном])
    прав = np.concatenate([ids[off[i] + 1:off[i + 1]] for i in ном])
    код = лев.astype(np.int64) * n_л + прав
    книга_пары = np.repeat(src[ном], пар[есть])
    _, обр_к, сч_к = np.unique(код, return_inverse=True, return_counts=True)
    доля_пара_корпус = сч_к[обр_к] / сч_к.sum()
    _, обр_б, сч_б = np.unique(
        книга_пары.astype(np.int64) * (n_л * n_л) + код,
        return_inverse=True, return_counts=True)
    пар_книги = np.bincount(книга_пары[книга_пары >= 0], minlength=n_кн).astype(np.float64)
    пар_книги[пар_книги == 0] = 1
    доля_пара_книга = сч_б[обр_б] / пар_книги[np.maximum(книга_пары, 0)]

    лог = lambda v: np.log10(np.maximum(v, 1e-12))  # noqa: E731
    # СРЕДНЕЕ ЛОГАРИФМОВ И ЕСТЬ КОРЕНЬ ИЗ ПРОИЗВЕДЕНИЯ: log(∏xᵢ)/n = log(∏xᵢ^1/n)
    слова = np.empty(len(ном), dtype=np.float64)
    for k, i in enumerate(ном):
        a, b = off[i], off[i + 1]
        кн = max(int(src[i]), 0)
        слова[k] = ((лог(доля_корпус[ids[a:b]]) + лог(доля_книга[кн, ids[a:b]])) / 2).mean()
    границы = np.zeros(len(ном) + 1, dtype=np.int64)
    границы[1:] = np.cumsum(пар[есть])
    пара = (np.minimum.reduceat(лог(доля_пара_корпус), границы[:-1])
            + np.minimum.reduceat(лог(доля_пара_книга), границы[:-1])) / 2

    # НАПРАВЛЕНИЕ: 0% — САМЫЕ НЕРЕДКИЕ, 100% — САМЫЕ РЕДКИЕ (2026-08-25).
    #
    # Первая версия шла наоборот, и владелец поймал это сразу: «ведь 0 процентов
    # редкости это самые нередкие должны быть». Он прав — у ручки с именем
    # «Редкость» ноль обязан значить «редкости нет», иначе имя врёт о шкале, а
    # это четвёртое правило допуска ручки на экран.
    #
    # Считаем по ЧАСТОТЕ (чем меньше — тем реже), поэтому переворачиваем.
    процентиль = lambda v: (100 - np.argsort(np.argsort(v)) / (len(v) - 1) * 100).astype(np.float32)  # noqa: E731
    return {"ном": ном, "слова": процентиль(слова), "пара": процентиль(пара),
            "штамп": idx.built_at}


def шкалы(заново: bool = False):
    if not заново and КЭШ.exists():
        д = np.load(КЭШ, allow_pickle=True)
        if str(д["штамп"]) == str(nlindex.load().built_at):
            return д["ном"], д["слова"], д["пара"]
    t = time.time()
    print("считаю шкалы (индекс не трогается, только читается)…", file=sys.stderr)
    д = _посчитать()
    np.savez(КЭШ, **д)
    print(f"готово за {time.time() - t:.0f} с", file=sys.stderr)
    return д["ном"], д["слова"], д["пара"]


def _слова_полосы(idx, где, мета_леммы, ids, off, сколько=8):
    if not len(где):
        return []
    из = np.concatenate([ids[off[i]:off[i + 1]] for i in где[:3000]])
    счёт = np.bincount(из, minlength=len(мета_леммы))
    return [мета_леммы[j] for j in np.argsort(-счёт)[:сколько]]


def показать_ячейки(ось: str):
    ном, слова, пара = шкалы()
    шкала = слова if ось == "слова" else пара
    idx = nlindex.load()
    мета = json.loads((пути.АРТЕФАКТЫ / "nl_index" / "meta.json").read_text("utf-8"))
    ids, off = np.asarray(idx.lem_ids), np.asarray(idx.lem_off)
    имя = "РЕДКОСТЬ СЛОВ" if ось == "слова" else "РЕДКОСТЬ СОЧЕТАНИЯ"
    print(f"\n{имя} — все сто ячеек, по 1% корпуса в каждой\n")
    рнд = random.Random(17)
    for п in range(100):
        м = (шкала >= п) & (шкала < п + 1)
        где = ном[м]
        if not len(где):
            continue
        сл = ", ".join(_слова_полосы(idx, где, мета["lemmas"], ids, off, 5))
        прим = idx.text(int(рнд.choice(где)))
        print(f"{п:>3}%  {сл[:46]:<48} {прим[:58]}")


def показать_выбор(выбор_слова, выбор_пара):
    ном, слова, пара = шкалы()
    idx = nlindex.load()
    мета = json.loads((пути.АРТЕФАКТЫ / "nl_index" / "meta.json").read_text("utf-8"))
    ids, off = np.asarray(idx.lem_ids), np.asarray(idx.lem_off)

    def маска(шкала, диапазоны):
        if not диапазоны:
            return np.ones(len(шкала), dtype=bool)
        м = np.zeros(len(шкала), dtype=bool)
        for a, b in диапазоны:
            м |= (шкала >= a) & (шкала < b)
        return м

    м = маска(слова, выбор_слова) & маска(пара, выбор_пара)
    где = ном[м]
    полоска = lambda д: "".join(  # noqa: E731
        "█" if any(a <= i < b for a, b in д) else "·" for i in range(100)) if д else "█" * 100
    Ш = 2 + 20 + 100 + 2          # отступ + подпись + сто ячеек + отступ
    доля = 100 * len(где) / len(ном) if len(ном) else 0
    print()
    print("┌" + "─" * Ш + "┐")
    # ВСЕ СТО ЯЧЕЕК ЦЕЛИКОМ. Полоска обрезалась на пятидесяти, и выбор «97–98»
    # в ней просто не был виден — орган управления, который не показывает
    # выбранное, хуже отсутствующего.
    print(f"│  {'РЕДКОСТЬ СЛОВ':<20}{полоска(выбор_слова)}  │")
    print(f"│  {'РЕДКОСТЬ СОЧЕТАНИЯ':<20}{полоска(выбор_пара)}  │")
    ось = "0" + "·".rjust(24)[:0] + " " * 23 + "25" + " " * 23 + "50" + " " * 23 + "75" + " " * 21 + "100"
    print(f"│  {'':<20}{ось[:100]:<100}  │")
    print("│" + " " * Ш + "│")
    строка = f"выбрано: {len(где)} строк · {доля:.2f}% корпуса"
    print(f"│  {строка:<{Ш - 4}}  │")
    print("└" + "─" * Ш + "┘")
    if not len(где):
        print("\n   пусто — полосы не пересекаются")
        return
    print("\nчастые слова выбранного:")
    print("   " + ", ".join(_слова_полосы(idx, где, мета["lemmas"], ids, off, 12)))
    print("\nчто пойдёт в выдачу:")
    for i in random.Random(5).sample(list(где), min(20, len(где))):
        print(f"   {idx.text(int(i))[:74]}")


def _разобрать(текст: str):
    if not текст:
        return []
    из = []
    for кусок in текст.split(","):
        a, _, b = кусок.partition("-")
        из.append((float(a), float(b or a) + (0 if b else 1)))
    return из


def main() -> int:
    р = argparse.ArgumentParser(description="Редкость: две шкалы и их содержимое")
    р.add_argument("--ячейки", choices=["слова", "пара"], nargs="?", const="слова",
                   help="показать все сто ячеек выбранной оси")
    р.add_argument("--выбор", default="", metavar="5-10,17-18",
                   help="диапазоны по оси СЛОВА")
    р.add_argument("--сочетание", default="", metavar="0-10",
                   help="диапазоны по оси СОЧЕТАНИЕ")
    р.add_argument("--заново", action="store_true", help="пересчитать, не читая кэш")
    а = р.parse_args()
    if а.заново:
        шкалы(заново=True)
    if а.ячейки:
        показать_ячейки(а.ячейки)
        return 0
    показать_выбор(_разобрать(а.выбор), _разобрать(а.сочетание))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
