#!/usr/bin/env python3
# nakedlunch — обратный индекс рифм для попапа по слову (ФАЗА 2, PLAN.md,
# решение прожарки №9: вкладка «рифмы» = предсобранный обратный индекс,
# ruaccent ТОЛЬКО на сборке). Тот же паттерн, что build_forms.py и
# build_nl_rhyme.py: акцентуатор гоняется один раз офлайн, рантайм
# (core/wordsuggest.py) читает плоский dict-кэш и никогда не трогает ruaccent.
#
# ПОЧЕМУ отдельный индекс, а не lexicon.json: лексикон — это ЛЕММЫ для
# генератора (NOUN/ADJF/INFN, без ударений); рифмуются же СЛОВОФОРМЫ
# («деньгами», не «деньга»), и попапу нужны именно они + ударение + обратная
# карта ключ→слова. Источник — wordfreq: тот же источник частот, что
# банальность в filters.py и частотная подпись в самом попапе, один источник
# правды на «насколько слово обычное».
#
# Ключ считается ФУНКЦИЕЙ scan.rhyme_key через build_nl_rhyme._word_rhyme_key
# — переиспользование, не копия: формат ключа обязан побайтово совпадать с
# ключами генератора и nl_rhyme.json, иначе вкладка «строкой» и рифмо-бонус
# по последнему слову строки никогда бы не сошлись (та же причина, по которой
# build_nl_rhyme.py сам зовёт scan.rhyme_key, см. его докстринг).
#
# РАУНД 32 (2026-08-02) — три правки по живой жалобе «рифм маловато», «одно и то же слово с разными окончаниями»):
#
#  1. ВЕСЬ кириллический словарь wordfreq (668 276 словоформ), а не первые
#     50 000. Причина прямая: рифмы берутся из ведра ТОЧНОГО ключа, и на
#     50k у половины ключей в ведре было 3-6 слов — остальное попап добирал
#     мусором. Цена честная: ruaccent ~0.01мс на частое слово и ~0.39мс на
#     редкое (в словаре ударений 98% / 55%), итого ≈4 мин сборки.
#
#  2. ОПОРНАЯ СОГЛАСНАЯ (поле `опора`). Ключ «рука» — это один гласный «а»,
#     и его делят 746 слов: «на», «за», «когда», «была». Так рифма не
#     работает: при мужском открытом окончании (слово кончается ударным
#     гласным) русская рифма требует совпадения согласной ПЕРЕД ударным
#     гласным — «рука/река/строка», а не «рука/на». Согласную считаем здесь,
#     потому что для неё нужна позиция ударения, а её знает только сборка.
#
#  3. ЛЕММЫ каждого слова (поле `леммы`, СПИСОК). Рантайму они нужны на
#     КАЖДОГО кандидата — схлопнуть «гроза/грозы/грозе» в одно слово на
#     вкладках «по звуку» и «синонимы». 668k разборов pymorphy на запрос
#     немыслимы, на сборке это ≈1 мин.
#
#     Почему СПИСОК, а не одна начальная форма: у неоднозначных словоформ
#     самый вероятный разбор pymorphy часто не тот. Живая проверка
#     2026-08-02: «спал» → «спасть» (а не «спать»), «утром» → «утром»
#     (ADVB, а не «утро»), «вечером» → «вечером», «ночью» → «ночью».
#     Из-за этого схлопывание форм не срабатывало ровно там, где пользователь
#     на него и жаловался: синонимы «ночь» показывали «утра, утром» и
#     «спать, спал» как разные слова. Берём все начальные формы разборов
#     весом ≥ _ПОРОГ_РАЗБОРА, и два слова считаем одним, если их наборы
#     пересеклись. Цена — редкие ложные склейки («мой» и «мыла» делят
#     «мыть»); она дешевле, чем дубли в каждой выдаче.
#
# ОТСЕВ МУСОРА (тоже Раунд 32) — два правила, оба проверены на живых данных:
#   • слово, у которого ВСЕ разборы pymorphy помечены Abbr и слово ему
#     известно → аббревиатура: «сша», «рф», «млн», «км», «цска», «гос».
#     Требование «все разборы» бережёт «сто» (Abbr + NUMR) и подобные.
#   • слово ≤3 букв, неизвестное pymorphy → обломок склейки, не слово:
#     «нью», «юго», «лос», «мск», «фк», «лнр». Настоящее двух-трёхбуквенное
#     русское слово в словаре pymorphy есть всегда.
#   Abbr у НЕизвестных слов не смотрим вовсе: там метку ставит гадатель, и
#   ставит наугад («чучундра», «грусто» — реальная выдача, не выдумка).
#
# ПОДОЗРИТЕЛЬНОЕ вместо удаления (поле `подозр`, 0/1). Остальной мусор в
# хвосте — фамилии, топонимы и опечатки: «огонь» → белоконь, сморгонь,
# булонь, гасконь, дордонь; «моя» → алия, дария, илия, бия. Их НЕ выбрасываем:
# те же признаки стоят на «москва», «путин», а с ними рифмуют по-настоящему,
# и на четверти словаря pymorphy просто не знает нормальных слов
# («еврокоммунизм», «культисты», «дракончика»). Поэтому признак не режет, а
# опускает: списки ключей сортируются (подозр, -zipf), и подозрительное
# честно живёт в конце выдачи, а не вытесняет настоящее.
# Подозрительно, если pymorphy слова не знает ИЛИ все его разборы помечены
# именем собственным (Name/Surn/Patr/Geox/Orgn). «Все разборы» — та же
# защита, что у Abbr: у «мороз» первый разбор Surn, но есть и обычный, и
# слово остаётся полноправным.
#
# Выход: core/data/rhyme_index.json =
#   {"meta": {…счётчики, дата…},
#    "words": {слово: [ключ, zipf, опора, [леммы], подозр]},  # порядок — по убыванию частоты
#    "keys":  {ключ: [слова, отсортированные по (подозр, -zipf)]}}
# Слово, которому ruaccent не дал ударения, остаётся в "words" с ключом ""
# (честное «рифм нет», не выдумка) и не попадает в "keys".
#
# Запуск: .venv/bin/python tools/build_rhyme_index.py        (~5 мин)
#         .venv/bin/python tools/build_rhyme_index.py --limit 20000   (проба)
# ruaccent — build-time зависимость (requirements.txt:
#   .venv/bin/pip install ruaccent "transformers<5").

import argparse
import json
import re
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "core"))
sys.path.insert(0, str(ROOT / "tools"))

from wordfreq import top_n_list, zipf_frequency  # noqa: E402

import scan  # noqa: E402  (VOWELS — та же таблица гласных, что в rhyme_key)
# _word_rhyme_key — единая механика «ударение (словарь → нейрофолбэк) →
# scan.rhyme_key»; см. его докстринг про то, почему без process_all().
import build_nl_rhyme  # noqa: E402

OUT = ROOT / "core" / "data" / "rhyme_index.json"
# Глубина чтения списка частот: кириллических словоформ ≥2 букв в нём
# 668 276, дальше wordfreq не отдаёт ничего.
SCAN_DEPTH = 1_000_000
_CYR = re.compile(r"^[а-яё]{2,}$")   # только кириллица, ≥2 букв — без цифр,
                                      # латиницы и дефисных склеек


def опорная(word: str, key: str) -> str:
    """Согласная перед ударным гласным («опорная» русской рифмы).

    Ключ — это хвост от ударного гласного, поэтому ударный гласный стоит
    ровно на позиции len(word) - len(key); идём от него влево, пропуская
    ь/ъ (звука не несут: «семья» опирается на «м»). Гласный слева или край
    слова → опоры нет (открытый слог: «моя», «твоя», «своя» — одна группа).

    Возвращаем букву как есть, без оглушения: перед гласным русские
    согласные не оглушаются, а «года/когда» опираются на одно и то же «д»
    и рифмуются по-настоящему.
    """
    if not key or len(key) > len(word):
        return ""
    j = len(word) - len(key) - 1
    while j >= 0 and word[j] in "ьъ":
        j -= 1
    if j < 0:
        return ""
    ch = word[j]
    return "" if ch in scan.VOWELS else ch


_ИМЯ_СОБСТВЕННОЕ = ("Name", "Surn", "Patr", "Geox", "Orgn")
# Вес разбора, ниже которого начальную форму не берём. 0.05 подобран по
# живым разборам: он держит «спал» → спасть+спать (0.5/0.5), «утром» →
# утром+утро (0.90/0.10), «ночью» → ночью+ночь (0.79/0.21) и отсекает
# «стекла» → стечь (0.010), где склейка была бы ложной.
_ПОРОГ_РАЗБОРА = 0.05
_МАКС_ЛЕММ = 4          # у гаданных слов разборов бывает десяток; хвост — шум


def разбор(morph, w: str) -> tuple[bool, bool, list]:
    """Один проход pymorphy на слово → (мусор, подозрительное, леммы).

    Одной функцией, потому что все три ответа стоят на одном и том же
    разборе, а разбор — это 0.08мс × 668k; звать его дважды значило бы
    подарить минуту сборки ни за что."""
    parses = morph.parse(w)
    # dict.fromkeys — множество С СОХРАНЕНИЕМ порядка: нулевой элемент
    # обязан остаться самым вероятным разбором, по нему рантайм ищет
    # статью в тезаурусе (он ключуется одной леммой, не набором).
    леммы = list(dict.fromkeys(p.normal_form for p in parses
                               if p.score >= _ПОРОГ_РАЗБОРА))[:_МАКС_ЛЕММ]
    if not леммы:
        леммы = [parses[0].normal_form]
    if not morph.word_is_known(w):
        return len(w) <= 3, True, леммы
    if all("Abbr" in p.tag for p in parses):
        return True, True, леммы
    собственное = all(any(g in p.tag for g in _ИМЯ_СОБСТВЕННОЕ) for p in parses)
    return False, собственное, леммы


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=0,
                    help="взять только первые N слов (проба сборки, не для боя)")
    args = ap.parse_args()

    import pymorphy3
    from ruaccent import RUAccent
    morph = pymorphy3.MorphAnalyzer()
    acc = RUAccent()
    # Та же конфигурация, что в build_nl_rhyme.build() — ключи двух кэшей
    # обязаны получаться из ОДИНАКОВОГО акцентуатора, не из двух похожих.
    acc.load(omograph_model_size="turbo2", use_dictionary=True, tiny_mode=False)

    сырьё = [w for w in top_n_list("ru", SCAN_DEPTH) if _CYR.match(w)]
    if args.limit:
        сырьё = сырьё[:args.limit]
    print(f"{len(сырьё)} кириллических словоформ wordfreq", flush=True)

    words_map: dict = {}
    keys_map: dict = {}
    n_empty = n_мусор = n_подозр = 0
    t0 = time.time()
    for i, w in enumerate(сырьё):
        мусор, подозр, леммы = разбор(morph, w)
        if мусор:
            n_мусор += 1
            continue
        n_подозр += подозр
        key = build_nl_rhyme._word_rhyme_key(acc, w, w)
        words_map[w] = [
            key,
            # zipf — для сортировок и частотной подписи попапа; round до 2
            # знаков, как везде в проекте (точнее wordfreq и сам не знает).
            round(zipf_frequency(w, "ru"), 2),
            опорная(w, key),
            леммы,
            int(подозр),
        ]
        if key:
            keys_map.setdefault(key, []).append(w)
        else:
            n_empty += 1
        if (i + 1) % 50_000 == 0:
            dt = time.time() - t0
            print(f"  {i + 1}/{len(сырьё)} ({dt:.0f}s, {(i + 1) / dt:.0f}/s)", flush=True)

    # Порядок внутри ключа: сперва не-подозрительные, внутри — по убыванию
    # частоты. Питоновская сортировка устойчива, а сырьё уже шло по частоте,
    # поэтому ключ сортировки — только флаг подозрительности.
    for k, lst in keys_map.items():
        lst.sort(key=lambda w: words_map[w][4])

    meta = {
        "built_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        "words": len(words_map),
        "keys": len(keys_map),
        "no_key": n_empty,
        "dropped": n_мусор,
        "suspect": n_подозр,
        "source": f"wordfreq top_n_list('ru', {SCAN_DEPTH}) → все кириллические ≥2 букв"
                  + (f", ОБРЕЗАНО --limit {args.limit}" if args.limit else ""),
        "fields": "words[слово] = [ключ, zipf, опора, [леммы], подозр]",
    }
    # Пишем во временный файл и переставляем: краш посреди записи не оставит
    # полуиндекс, который рантайм примет за целый (та же дисциплина, что в
    # tools/build_nl_index.py).
    tmp = OUT.with_suffix(".json.tmp")
    tmp.write_text(json.dumps({"meta": meta, "words": words_map, "keys": keys_map},
                              ensure_ascii=False), encoding="utf-8")
    tmp.replace(OUT)
    print(f"готово за {time.time() - t0:.0f}s: {meta['words']} слов "
          f"(отсеяно {meta['dropped']}, помечено подозрительными {meta['suspect']}), "
          f"{meta['keys']} ключей, без ударения {meta['no_key']} -> "
          f"{OUT} ({OUT.stat().st_size / 1024 / 1024:.0f} МБ)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
