// nakedlunch — ЛЕНТА: ЕДИНСТВЕННАЯ поверхность приложения (с 2026-08-18).
//
// ЗАЧЕМ. Требование владельца дословно: «жмёшь enter — тебе выдаёт… ты просто
// скроллишь и выделяешь, что нравится. И всё аккумулируется в избранном».
// И отдельно: «когда мы пытаемся сделать систему умнее, мы идём против самих
// принципов… надо довериться своему собственному мозгу на основе строчек,
// которые тебя уже вдохновили».
//
// НА ЭКРАНЕ ВСЕГДА ОДНА СТРОФА (переписано 2026-08-18, волна «экран»).
// Дословно: «Я жму интер — оно должно старое убирать, а показывать с
// центрированием по горизонтали и по вертикали. Но при этом я мог бы листать,
// если он за пределы экрана уходит». До этого `lenta` была накапливающимся
// списком, и он ругался: «ты мне в ленте показываешь подряд и старые не
// уходят». Поэтому `state.lenta` — НЕ история показов, а СТРОКИ ТЕКУЩЕЙ
// СТРОФЫ: каждая новая заменяет предыдущую целиком.
//
// ИМЯ КЛЮЧА ОСТАВЛЕНО ПРЕЖНИМ НАРОЧНО. `state.lenta` читает ещё и шапка
// (render.panels.jsx: строка «строк в ленте» в статистике). Переименовать
// значило бы либо править чужой файл, либо оставить в статистике вечный ноль —
// то есть завести показание, которое врёт.
//
// ПРОИЗВОДИТЕЛЬ ОДИН — строфа. Их задумывалось три (строфа, цепь, серия); цепь
// и серия вырезаны решением владельца («с практической точки зрения бесполезны;
// строфа единственным режимом и всё»), а одиночная генерация в документ
// (genStanza) — вместе с самим документом. Здесь единственный вход в генерацию
// на весь фронт.
//
// ПОЧЕМУ ЭТО НЕ ДОКУМЕНТ. Замер журнала событий (587 живых генераций за десять
// дней): в сессии на 453 минуты и 181 генерацию в избранное ушло **ноль**
// строк. Причина механическая, её нашла опись: во всём фронте ЧЕТЫРЕ входа в
// избранное, и все четыре внутри документа — звезда на строке, массовая
// кнопка, ★ в истории, ＋ в панели. Чтобы сохранить строку, надо было ПОПАСТЬ
// МЫШЬЮ в крошечную звезду. Звезда осталась единственным входом и сегодня, но
// уже как настоящая кнопка с областью нажатия в высоту строки — см.
// render.lenta.jsx.
//
// ЧЕГО ЗДЕСЬ НАРОЧНО НЕТ — «закрепить строку». Легенда обещала её с самого
// начала («кнопка — закрепить, строка не меняется генерацией»), и в коде её
// никогда не было. Сделать её честно нельзя: строфа связана рифмой, и если
// закрепить первую строку схемы «абба», то четвёртая обязана срифмоваться
// ИМЕННО с ней, а генератор не умеет принимать фиксированную строку.

import * as api from './api.js';

// РАЗМЕР ПАЧКИ ЗАМЕРЕН, А НЕ ВЫБРАН (2026-08-14, схема «абба», его настройки
// из журнала). Стоимость одной строфы:
//   1 строфа  — 53.4 мс      10 строф — 6.2 мс   ← в 8.6 раза дешевле
//   5 строф   — 10.4 мс      25 строф — 6.5 мс
//   50 строф  — 10.1 мс     100 строф — 18.7 мс  ← кривая разворачивается
// Сборка стоит O(строк × пул), поэтому «грузить сразу тысячу» ХУЖЕ, чем
// грузить десятками. Оптимум 10–25; берём нижний край — дозаказ дешевле, чем
// лишняя работа впрок.
//
// ПЕРЕХОД НА «ОДНУ НА ЭКРАНЕ» БУФЕР НЕ ОТМЕНЯЕТ. Наоборот: теперь пачка —
// единственное, что отделяет ↵ от ожидания в 53 мс, потому что показанное
// больше не копится и вернуться к нему прокруткой нельзя.
export const ПАЧКА = 10;
// Ниже этого запаса — дозаказ в фоне. Три строфы это несколько секунд чтения,
// а дозаказ стоит 62–90 мс, то есть успевает всегда.
export const ЗАПАС = 3;

export const lentaMethods = {

  // ---- подпись настроек ----
  // ЛОВУШКА, УЖЕ ПОЙМАННАЯ ОДНАЖДЫ ВО ФРИСТАЙЛЕ (см. methods.fs.js): пачка,
  // заказанная по СТАРЫМ крутилкам, приезжает уже ПОСЛЕ того, как буфер
  // очистили из-за смены настроек, и ложится в чистый буфер. Сцена потом
  // минуту показывает чужое. Лечится подписью: у буфера она своя, и приехавшая
  // пачка с другой подписью выбрасывается.
  // НОМЕР ПРОГОНА — ЧАСТЬ ПОДПИСИ (2026-08-18). Он приехал сюда из genStanza,
  // вырезанной вместе с редактором, и МЕНЯЕТ ВЫДАЧУ: не учесть его в подписи
  // значило бы отдать пачку, набранную по другому семени.
  //
  // НАДГРОБИЕ: ТЕМА И ЖЁСТКОЕ СЛОВО В ПОДПИСИ (сняты 2026-08-29). В подписи
  // стояли `this.keyFromSelection()` и `!!this._жёстко` — по той же причине,
  // по какой стоит семя: оба меняли выдачу. Обоих больше нет — решение
  // владельца «тему стоит вырезать как функцию она глупа и сложна»,
  // «вырезать всё вместе с темой».
  // ПОЛОСЫ И ДОЛИ — ТОЖЕ ЧАСТЬ ПОДПИСИ (2026-08-29). Закон подписи один:
  // в ней стоит всё, что меняет выдачу. Полос тут не было — и это была тихая
  // поломка ровно того сорта, от которой подпись и заводилась: полосу набрал,
  // а лента ещё десяток строф отдаёт из пачки, заказанной по старым воротам.
  // Доли ложатся туда же и по той же причине: без них полоску тянешь, а
  // ближайшие строфы приходят с прежней пропорцией — то есть ручка на глаз
  // не работает.
  lentaПодпись() {
    var st = this.state;
    return JSON.stringify([st.knobMode, st.params, this.curSpec(),
                           st.полосы || {}, st.доли || {},
                           String(st.seedDraft || '').trim()]);
  },

  // ЧТО НАПИСАНО ПОСРЕДИ ПУСТОГО ЭКРАНА. Одна строка, три состояния, и все три
  // — правда о том, что происходит ПРЯМО СЕЙЧАС.
  //
  // Порядок проверок не произволен: прогрев главнее занятости (пока корпус не
  // поднят, генерация и не начиналась), занятость главнее подсказки (иначе на
  // экране висело бы «↵ — строфа» ровно в тот момент, когда ↵ уже нажат и
  // работает).
  разогревИдёт() {
    return (this.state.jobs || []).some(function (j) {
      return j.id === 'warmup' && j.state === 'running';
    });
  },

  лентаЖдёт() {
    var разогрев = ((this.state.jobs || []).filter(function (j) {
      return j.id === 'warmup' && j.state === 'running';
    }))[0];
    if (разогрев) return '· ' + разогрев.detail + ' · ' + разогрев.pct + '%';
    if (this.state.genBusy) return '· ' + (this.state.genStatus || 'собираю строфу…');
    return '↵ — строфа';
  },

  lentaСброс() {
    this._буфер = [];
    this._буферПодпись = null;
    this._буферИдёт = false;
  },

  // ---- буфер ----
  async lentaНабрать() {
    if (this._буферИдёт) return;
    var подпись = this.lentaПодпись();
    var spec = this.curSpec(), n = spec ? spec.length : 4;
    // НАДГРОБИЕ: ТЕМА И ОБЯЗАТЕЛЬНОЕ СЛОВО «!слово» (сняты 2026-08-29).
    //
    // Здесь снималась тема (`keyFromSelection`) и, если строфу заказывали по
    // ⌥↵, каждому слову темы приписывался восклицательный знак — «!любовь,
    // !смерть», — что на бэке означало `clean.theme_forced`: слово обязано
    // войти в строку. Правило «знак КАЖДОМУ слову» само было починкой: стояло
    // `'!' + key`, и знак доставался только первому слову списка.
    //
    // Снято решением владельца: «тему стоит вырезать как функцию она глупа и
    // сложна» и «вырезать всё вместе с темой». Обязательное слово вырезано тем
    // же решением, вместе с клавишей ⌥↵. Запрос теперь без `theme` вовсе.
    this._буферИдёт = true;
    try {
      var payload = {
        source: 'lenta', shortlist: n * ПАЧКА,
        mode: this.state.knobMode, params: this.state.params || {},
        // Полосы редкости — не крутилка, а выбор: несколько несмежных
        // отрезков шкалы. Разбирает их `core/редкость.py`.
        полосы: this.state.полосы || {},
        // Доли — тем же путём и по той же причине: не число, а пропорция
        // между сортами маски («1:20,2:50,4:30»). Разбирает `core/доли.py`.
        доли: this.state.доли || {},
      };
      if (spec) payload.stanza = spec;
      // Номер прогона (Раунд 62): пусто — бэк снимает новое семя, вписанное
      // число — та же пачка повторяется в точности. Мусор здесь не проверяем
      // нарочно: clean.семя на бэке честно превращает его в новый прогон, а
      // ответ говорит, какой номер снялся, — ронять генерацию из-за опечатки в
      // поле было бы худшей сделкой.
      var семя = String(this.state.seedDraft || '').trim();
      if (семя) payload.seed = семя;
      var res = await api.generate(payload);
      // Подпись сменилась, пока пачка ехала — выбрасываем её целиком. Молча:
      // это не ошибка, а обычная гонка между пальцем и сетью.
      if (подпись !== this.lentaПодпись()) return;
      var rows = (res && res.shortlist) || [];
      var строфы = [];
      for (var i = 0; i + n <= rows.length; i += n) {
        строфы.push(rows.slice(i, i + n).map(function (r, j) {
          return { text: r.text, letter: spec ? spec[j].letter : 'а',
                   rk: r.rhyme || '', book: r.source || '', bookId: r.source_id || '' };
        }));
      }
      if (this._буферПодпись !== подпись) this._буфер = [];
      this._буферПодпись = подпись;
      this._буфер = (this._буфер || []).concat(строфы);
      // Семя и воронка последнего прогона — как у одиночной генерации: пустой
      // прогон тоже надо уметь повторить.
      if (res && res.seed) {
        this._lastSeed = res.seed.seed;
        this.setState({ seedLast: res.seed.seed, seedStamp: res.seed });
      }
      if (res && res.funnel) this.setState({ funnelLast: res.funnel });
    } catch (e) {
      this.flash(e && e.message ? e.message : String(e));
    } finally {
      this._буферИдёт = false;
    }
  },

  // Дозаказ в фоне: не ждём его и не блокируем нажатие.
  lentaДолить() {
    if ((this._буфер || []).length <= ЗАПАС) this.lentaНабрать();
  },

  // ---- строфа ----
  //
  // НАДГРОБИЕ: АРГУМЕНТ `жёстко` И ФЛАГ `_жёстко` (сняты 2026-08-29). Это была
  // ⌥ к ↵: слово темы становилось обязательным ('!слово', core/clean.py:
  // theme_forced). Флаг жил на экземпляре, а не в состоянии, потому что его
  // читала подпись буфера, и перерисовка ради него была бы ценой без покупки.
  // Снято вместе с темой — решение владельца: «вырезать всё вместе с темой».
  // Строфа теперь ровно одна и заказывается одинаково откуда угодно.
  async lentaСтрофа() {
    if (this._буферПодпись !== this.lentaПодпись()) this.lentaСброс();
    if (!(this._буфер || []).length) {
      // Холодный случай: буфер пуст (первое нажатие или смена настроек) —
      // ждём одну пачку. Дальше ожидания не будет вовсе.
      this.startGenClock('строфа');
      try { await this.lentaНабрать(); } finally { this.stopGenClock(); }
    }
    var строфа = (this._буфер || []).shift();
    if (!строфа || !строфа.length) { this.flash(this.почемуПусто(null)); this.setState({ genStatus: '' }); return; }
    this.lentaПоложить(строфа, { вид: 'строфа' });
    // СЕКУНДОМЕР ГАСИМ ЗДЕСЬ, И ЭТО ПОЧИНКА (2026-08-18). `stopGenClock` гасит
    // только флажок занятости — и в холодном случае в шапке НАВСЕГДА зависало
    // «строфа… 3с», то есть счётчик давно кончившегося прогона.
    //
    // НАДГРОБИЕ: СТАТУС ТЕМЫ (снят 2026-08-29). Здесь стояло
    // `genStatus: тема ? 'тема: «…»' : 'без темы'` — строка, которую писала ещё
    // genStanza. Темы больше нет, и «без темы» после каждой строфы стало бы
    // единственным, вечным и бессмысленным сообщением. Гашение осталось:
    // затирать секундомер по-прежнему обязано что-то, и это по-прежнему здесь.
    this.setState({ genStatus: '' });
    this.lentaДолить();
  },

  // ---- текущая строфа ----
  //
  // ЗАМЕНА, А НЕ ДОБАВЛЕНИЕ. Здесь стоял `setState(было => ({lenta: было.lenta
  // .concat(новые), lentaCur: …}))` — накопление, из-за которого «старые не
  // уходят». Теперь состояние новой строфы НЕ ЗАВИСИТ от прежнего, и
  // функциональная форма setState больше не нужна: последнее нажатие в круге
  // событий и должно выиграть — на экране всё равно одна строфа.
  //
  // ЧТО ЭТО СТОИЛО РАНЬШЕ. При накоплении ровно здесь дважды жил один и тот же
  // капкан: React группирует setState внутри одного круга событий, все вызовы
  // читали одну устаревшую ленту, и выживал последний — пять нажатий давали
  // одну строфу вместо пяти. Ловил его только живой браузер, не тесты. Замена
  // убирает сам капкан: зависимости от прежнего значения нет.
  //
  // ЗАПИСЬ В ИСТОРИЮ ОТСЮДА УШЛА — см. lentaОтметитьПоказ ниже.
  lentaПоложить(строки, мета) {
    var блок = (this._блокN = (this._блокN || 0) + 1);
    this.setState({
      lenta: строки.map(function (r) {
        return { text: r.text, letter: r.letter || '', rk: r.rk || '',
                 book: r.book || '', bookId: r.bookId || '',
                 блок: блок, вид: (мета && мета.вид) || 'строфа' };
      })
    });
    // Длинная строфа (ода в 14 строк) не влезает и прокручивается. Новая
    // обязана начинаться сверху: иначе она открывалась бы на том месте, до
    // которого домотали предыдущую. Флаг снимает componentDidUpdate.
    this._lentaВверх = true;
  },

  // ---- история пишется ПО ФАКТУ ПОКАЗА ----
  //
  // Владелец дословно: «мы показываем то, что показываем, добавляется в
  // историю, а то, чего нет на экране, не добавляется».
  //
  // ПОЧЕМУ НЕ В `lentaПоложить`, ГДЕ ЭТО СТОЯЛО РАНЬШЕ. Пока лента копилась,
  // «положить» и «показать» совпадали: положенное оставалось на экране навсегда.
  // При замене это разошлось — два нажатия в одном круге событий берут из
  // буфера ДВЕ строфы, а перерисовка случается одна, и первая строфа не
  // появляется на экране ни на кадр. Записать её в историю значило бы навсегда
  // вычеркнуть из выдачи строки, которых он не видел.
  //
  // Отсюда: отмечаем ПОСЛЕ отрисовки (componentDidUpdate в Nakedlunch.jsx) и по
  // номеру блока — тот же блок второй раз не отмечается, а пропущенный не
  // отмечается вовсе.
  lentaОтметитьПоказ() {
    var л = this.state.lenta || [];
    var блок = л.length ? л[0].блок : null;
    if (блок == null || блок === this._показанБлок) return;
    this._показанБлок = блок;
    if (this.markShownQueue) {
      this.markShownQueue(л.map(function (r) { return { text: r.text, template: '' }; }));
    }
  },

  // ---- в копилку ----
  //
  // ЕДИНСТВЕННЫЙ ВХОД В ИЗБРАННОЕ ИЗ ЛЕНТЫ. Нарочно одна функция без единого
  // знания о мыши, клавишах и разметке: способ вызова ещё будет меняться
  // (владелец уже передумал один раз), и цена смены должна быть в одну строку
  // разметки, а не в переписывание сохранения.
  //
  // Сейчас её зовёт звезда слева от строки (render.lenta.jsx) — настоящая
  // кнопка, а не значок: «уже есть реализованный механизм со звездочками — мне
  // не нравилась лишь подсветка строки при нажатии».
  //
  // ОДНА СТРОКА — ОДИН ВЫЗОВ, поэтому здесь нет капкана группировки setState,
  // из-за которого прежнее «сохранить выделение» цикла по строкам сохраняло
  // одну из трёх. И поэтому же складываем через `addFavText`
  // (methods.corpus.js): второго источника правды о том, как строка попадает в
  // копилку, в программе быть не должно — он и проверяет дубль, и шлёт на бэк,
  // и говорит вслух.
  сохранитьСтроку(i) {
    var r = (this.state.lenta || [])[i];
    if (!r || !r.text) return;
    this.addFavText(r.text);
  },

  // Уже сохранена? Читает та же звезда — залитая означает «эта строка больше
  // не вернётся в выдачу», и ответ нужен постоянно.
  строкаВИзбранном(text) {
    return (this.state.favs || []).some(function (f) { return f.t === text; });
  },

  // ---------------------------------------------------------------------------
  // ЗДЕСЬ БЫЛО ВЫДЕЛЕНИЕ СТРОК И ВСЁ, ЧТО НА НЁМ СТОЯЛО (вырезано 2026-08-18,
  // волна «экран»):
  //   lentaШаг(куда, тянуть) — курсор по строкам стрелками, Shift тянул
  //     диапазон от якоря;
  //   lentaВыбор()           — «строки под курсором или под выделением»;
  //   lentaСохранить()       — пробел: всё выделение в избранное ОДНИМ setState;
  //   lentaКопировать()      — ⌘C: выделенные строки в буфер обмена;
  //   sel_hit / lentaCur / lentaSel — само состояние выделения и его подсветка.
  //
  // ПОЧЕМУ. Дословно: «там сейчас можно бессмысленно выделить строку одну, и с
  // этим ни хуя не делается. Это просто графическое выражение, это бред»; и
  // после — «уже есть реализованный механизм со звездочками, мне не нравилась
  // лишь подсветка строки при нажатии». Выдача не редактируется, курсору в ней
  // нечего обозначать, а серая заливка строки была ровно тем «графическим
  // выражением», которое ничего не значит.
  //
  // КОПИРОВАНИЕ НЕ ПОТЕРЯНО, А ВЕРНУЛОСЬ К БРАУЗЕРУ: текст строк обычный,
  // мышью он выделяется и копируется ⌘C как везде. Свой ⌘C был нужен только
  // потому, что своё выделение браузер не видел.
  //
  // ПРОБЕЛ НЕ ПЕРЕЕХАЛ НА ЗВЕЗДУ. Без курсора по строкам он неоднозначен:
  // «в избранное» — какую из четырёх? Клавиша, которой нельзя назвать
  // предмет, — это или молчаливое действие не над тем, или обещание в
  // подсказке, которое не выполняется.
  //
  // ПЕРЕКАТ (R, lentaПерекатить) ВЫРЕЗАН ТОЙ ЖЕ ПРАВКОЙ. Он менял строфу под
  // курсором на свежую из буфера — то есть ровно то, что теперь делает ↵:
  // старая уходит, новая встаёт на её место. Две клавиши для одного действия —
  // это не выбор, а лишнее знание.
  // ---------------------------------------------------------------------------

  // ---- клавиши ленты ----
  // Возвращает true, если событие обработано: вызывающий тогда гасит его.
  //
  // ВСЯ КЛАВИАТУРА ЛЕНТЫ ЖИВЁТ ЗДЕСЬ, включая ↵. Раньше ↵ разбирался в
  // onGlobalKey (Nakedlunch.jsx), и там же стояло `if (!mod) return;` РАНЬШЕ
  // проверки Enter — из-за чего работал только ⌘↵: «я сказал нажатие на интер
  // даёт строфу, а у тебя строфа на комманд интер». Пока правда о клавише
  // лежала в двух файлах, такую ошибку и нельзя было увидеть, читая один.
  lentaКлавиша(e) {
    if (this.state.tab !== 'lenta') return false;
    if (e.key !== 'Enter') return false;
    // ↵ В ПОЛЕ ВВОДА — ЭТО ВВОД. Поля есть у поиска по избранному и истории,
    // чёрного списка, номера прогона, имён профилей; часть из них разбирает
    // Enter сама (добавить правило, сохранить профиль). Окно слушает клавиши
    // мимо React, поэтому без этой проверки одно нажатие делало бы ДВА дела
    // разом. (Поле «темы» стояло в этом списке первым — снято 2026-08-29.)
    var t = e.target, тег = (t && t.tagName ? String(t.tagName) : '').toUpperCase();
    if (тег === 'INPUT' || тег === 'TEXTAREA' || тег === 'SELECT' || (t && t.isContentEditable)) return false;
    e.preventDefault();
    // МОДИФИКАТОРЫ НЕ ПРОВЕРЯЮТСЯ ВОВСЕ: голый ↵ — основной путь, ⌘↵ обязан
    // продолжать работать ради мышечной памяти, и оба означают одно и то же.
    //
    // НАДГРОБИЕ: ВЕТКА ⌥ (снята 2026-08-29). Здесь стояло
    // `this.lentaСтрофа(e.altKey)` — ⌥ был единственным модификатором со
    // смыслом: строфа с обязательным словом темы. Тема вырезана целиком
    // решением владельца («вырезать всё вместе с темой»), и ⌥↵ ушла вместе с
    // ней — из обработчика, из легенды и из подсказки внизу (render.panels.jsx).
    // Клавиша, которая молча делает то же самое, что ↵, — это не выбор, а
    // лишнее знание; ровно за это здесь уже вырезали перекат.
    // Строфа берётся ИЗ БУФЕРА — 6.2 мс против 53.4 у одиночного прогона.
    this.lentaСтрофа();
    return true;
  },
};
