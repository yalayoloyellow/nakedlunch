// Клаузула — тоже МАСКА (2026-08-28, владелец: «может я хочу только мужскую
// и дактилическую»): 1 мужская · 2 женская · 4 дактилическая; 7 — любая.
export const КЛАУЗУЛЫ_МАСКА = [['мужская', 1], ['женская', 2], ['дактилическая', 4]];

export function имяМаскиКлаузул(м) {
  var x = Number(м) || 7;
  if ((x & 7) === 7) return 'любая';
  return КЛАУЗУЛЫ_МАСКА.filter(function (к) { return x & к[1]; })
    .map(function (к) { return к[0]; }).join('+') || 'любая';
}
// Внутренняя рифма — переключатель, как клаузула: два слова с разными
// леммами рифмуются внутри строки (правило — build_nl_rhyme, 2.9% корпуса).
export const ВНУТР_РИФМА = ['неважно', 'только с ней'];
// ПЕРЕКЛИЧКА СОГЛАСНЫХ — переключатель того же класса (2026-08-30): два
// неродственных слова строки делят редкое сочетание согласных («испытал… не
// споткнулся»). Ворота, а не полоса: их проходят 0.32% корпуса, крутить такое
// полосами нечем. Устройство и пороги — core/звукопись.py.
export const ПЕРЕКЛИЧКА = ['неважно', 'только с ней'];
// ПОЗИЦИЯ РИФМЫ — МАСКА СОРТОВ (2026-08-30, слово владельца: «рифма так-то не
// только в конце существует… может быть и первым, и вторым, и третьим любым
// словом»). Биты и границы — канон ядра (nlindex.бит_позиции): конечная это
// последнее слово, внутренняя — 1-2 слова от конца, начальная — дальше.
// Граница взята замером: при рифме «где угодно» 7.6% пар физически не слышны,
// при последних трёх словах мусора ноль.
export const ПОЗИЦИИ_РИФМЫ = [['конечная', 1], ['внутренняя', 2], ['начальная', 4]];

export function имяМаскиПозиций(м) {
  var x = Number(м) || 1;
  if ((x & 7) === 7) return 'любая';
  return ПОЗИЦИИ_РИФМЫ.filter(function (п) { return x & п[1]; })
    .map(function (п) { return п[0]; }).join('+') || 'конечная';
}

/** Защёлкивание к осмысленным положениям (Раунд 51).
 *
 *  У «Мата» промежуток между −1 и 0 не значит НИЧЕГО: ядро понимает −1 («как
 *  есть»), 0 («без мата») и долю 0..1. Ползунок при этом ходил по всему
 *  отрезку, и −0.4 подписывалось «без мата», а вело себя как «как есть».
 *  Защёлкивание было описано в комментарии ядра и не написано в интерфейсе —
 *  то есть код обещал то, чего не делал.
 *
 *  Так же была устроена «Связность» — удалена 2026-08-21.  */
export function защёлкнуть(имя, v) {
  var x = parseFloat(v);
  if (isNaN(x)) return v;
  if (имя === 'Мат') {
    if (x < 0) return x <= -0.5 ? -1 : 0;   // мёртвая зона — к ближнему концу
  }
  if (имя === 'Клаузула') return Math.max(1, Math.min(7, Math.round(x)));
  if (имя === 'Позиция рифмы') return Math.max(1, Math.min(7, Math.round(x)));
  if (имя === 'Ярусы рифмы') return Math.max(1, Math.min(15, Math.round(x)));
  if (имя === 'Повтор') return Math.max(0, Math.min(1, Math.round(x)));
  if (имя === 'Внутренняя рифма') return Math.max(0, Math.min(1, Math.round(x)));
  if (имя === 'Перекличка') return Math.max(0, Math.min(1, Math.round(x)));
  return x;
}

/** Читаемая подпись значения — то, что стоит справа от ползунка. */
export function подпись(имя, v) {
  if (имя === 'Клаузула') return имяМаскиКлаузул(v);
  if (имя === 'Позиция рифмы') return имяМаскиПозиций(v);
  if (имя === 'Ярусы рифмы') return имяМаскиРифмы(v);
  if (имя === 'Повтор') return ПОВТОРЫ[Math.round(v)] || ПОВТОРЫ[0];
  if (имя === 'Внутренняя рифма') return ВНУТР_РИФМА[Math.round(v)] || ВНУТР_РИФМА[0];
  if (имя === 'Перекличка') return ПЕРЕКЛИЧКА[Math.round(v)] || ПЕРЕКЛИЧКА[0];
  if (имя === 'Мат') {
    if (v <= -0.999) return 'как есть';
    if (v <= 0.0005) return 'без мата';
    if (v >= 0.9995) return 'только мат';
    return Math.round(v * 100) + '%';
  }
  return v.toFixed(2);
}

