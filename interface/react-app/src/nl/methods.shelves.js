/** Имя пресета, которому ТОЧНО отвечают текущие положения, или '' .
 *
 *  Считается, а не хранится. Хранимое «выбран такой-то» рано или поздно
 *  разъезжается с тем, что реально уедет на бэк, — а тут подсветка обязана
 *  означать «нажмёшь ↵ и получишь ровно это». Не совпало ни с одним — честно
 *  не подсвечиваем ничего (так будет у старых `settings.json`, где лежат
 *  положения годичной давности; §9.4: «молча не подменять»). */
export function имяПресета(params, mode) {
  var p = params || {};
  for (var i = 0; i < ПРЕСЕТЫ.length; i++) {
    var пр = ПРЕСЕТЫ[i];
    if ((mode || РЕЖИМ_АЛГО) !== пр.mode) continue;
    // Классика узнаётся одним режимом: её набор пуст, сверять нечего.
    if (пр.mode === РЕЖИМ_КЛАССИКА) return пр.name;
    var сошлось = true;
    for (var j = 0; j < КЛЮЧИ_ПРЕСЕТА.length; j++) {
      var к = КЛЮЧИ_ПРЕСЕТА[j];
      var было = parseFloat(p[к]), надо = пр.params[к];
      if (надо == null) continue;
      // 1e-6, а не ===: числа ходят через JSON и через value ползунка строкой.
      if (isNaN(было) || Math.abs(было - надо) > 1e-6) { сошлось = false; break; }
    }
    if (сошлось) return пр.name;
  }
  return '';
}

