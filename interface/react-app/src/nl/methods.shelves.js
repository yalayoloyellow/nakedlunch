/** Номер яруса по значению крутилки. Зеркалит `filters._rhyme_prefix_len` —
 *  разойтись этим двум нельзя, иначе кнопка горела бы не та, что действует. */
export function ярусТочности(v) {
  var x = Number(v);
  if (isNaN(x) || x <= 0.0) return 0;
  if (x <= 0.34) return 1;
  if (x <= 0.67) return 2;
  return 3;
}

