/** Защёлкивание к осмысленным положениям (Раунд 51).
 *
 *  У «Мата» промежуток между −1 и 0 не значит НИЧЕГО: ядро понимает −1 («как
 *  есть»), 0 («без мата») и долю 0..1. Ползунок при этом ходил по всему
 *  отрезку, и −0.4 подписывалось «без мата», а вело себя как «как есть».
 *  Защёлкивание было описано в комментарии ядра и не написано в интерфейсе —
 *  то есть код обещал то, чего не делал.
 *
 *  «Связность» устроена так же: −1 «выключено», дальше 0..1.  */
export function защёлкнуть(имя, v) {
  var x = parseFloat(v);
  if (isNaN(x)) return v;
  if (имя === 'Мат' || имя === 'Связность') {
    if (x < 0) return x <= -0.5 ? -1 : 0;   // мёртвая зона — к ближнему концу
  }
  if (имя === 'Клаузула') return Math.max(0, Math.min(3, Math.round(x)));
  if (имя === 'Повтор') return Math.max(0, Math.min(1, Math.round(x)));
  return x;
}

/** Читаемая подпись значения — то, что стоит справа от ползунка. */
export function подпись(имя, v) {
  if (имя === 'Клаузула') return КЛАУЗУЛЫ[Math.round(v)] || 'любая';
  if (имя === 'Повтор') return ПОВТОРЫ[Math.round(v)] || ПОВТОРЫ[0];
  if (имя === 'Связность') return v <= -0.999 ? 'выкл' : Math.round(v * 100) + '%';
  if (имя === 'Мат') {
    if (v <= -0.999) return 'как есть';
    if (v <= 0.0005) return 'без мата';
    if (v >= 0.9995) return 'только мат';
    return Math.round(v * 100) + '%';
  }
  // Банальность ДВУСТОРОННЯЯ (Раунд 58): у неё середина — это «выключено», а
  // «0.50» об этом не говорит ничего. Считаем от середины и называем сторону —
  // иначе единственный способ понять, где ноль действия, это подёргать ползунок.
  if (имя === 'Банальность') {
    var от = Math.round(Math.abs(v - 0.5) * 200);
    if (от < 3) return 'не влияет';
    return (v < 0.5 ? 'затёрто ' : 'нетронуто ') + от + '%';
  }
  return v.toFixed(2);
}

