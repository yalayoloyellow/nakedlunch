  // ЗДЕСЬ БЫЛО ЗВЕНО, ХУК, РЕФЕРЕНС И ПОЛКА ЦЕПОЧЕК (вырезано 2026-08-18, 205 строк).
  //
  //   setLinkKnobs / linkKnobPayload / linkKnobs — профиль настроек звена и
  //     резолвер «свой профиль → снятое референсом → мастерская».
  //   linkSpec — тот же резолвер для каркаса.
  //   setLinkRepeat / linkRepeat / чинитьПовторы — хук: звено-повтор и пересчёт
  //     ссылок после перестановки цепочки.
  //   docAsReference / refFromDoc / refPatch — открытый лист как референс и
