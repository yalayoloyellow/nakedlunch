  // ---- хук: звено-повтор (Раунд 52) --------------------------------------
  /** Пересчёт ссылок повтора после правки цепочки.
   *
   *  `перевод[старый] = новый индекс` или null, если звено удалено. Ссылка
   *  хранится ИНДЕКСОМ, а индексы едут при любой перестановке и удалении —
   *  ровно та порода ошибок, на которой проект уже обжёгся: chainKnobs
   *  забыли переставлять вместе со звеном, и профили молча съезжали на чужие.
   *  Поэтому пересчёт один и чистый, а не по копии в каждом обработчике.
   *
   *  Ссылка обязана смотреть НАЗАД. Развернулась после перестановки — не
   *  «поджимаем» её к соседу (это была бы другая песня, собранная молча), а
   *  снимаем: звено становится обычным, и это видно в цепочке. */
  чинитьПовторы(rep, перевод, длина) {
    var out = [];
    var i;
    for (i = 0; i < длина; i++) out.push(null);
    (rep || []).forEach(function (цель, старый) {
      var новый = перевод[старый];
      if (новый == null || новый >= длина) return;
      out[новый] = (цель == null) ? null : перевод[цель];
      if (out[новый] == null) return;
      if (!(out[новый] < новый)) out[новый] = null;   // вперёд или на себя — не ссылка
    });
    return out;
  },

  /** Назначить/снять повтор у звена. */
  setLinkRepeat(i, цель) {
    var rep = this._параллельно('chainRepeat', (this.state.chain || []).length);
    var n = (цель === '' || цель == null) ? null : parseInt(цель, 10);
    rep[i] = (n != null && n >= 0 && n < i) ? n : null;
    this.setState({ chainRepeat: rep });
  },

  /** Повторяет ли звено другое (и какое). */
  linkRepeat(i) {
    var v = (this.state.chainRepeat || [])[i];
    return (v == null || v >= i) ? null : v;
  },

  /** Открытый лист → текст референса. Заголовки («куплет», «припев») выкидываем
   *  и ставим на их место пустую строку: для измерителя пустая строка и есть
   *  граница части (refprofile._части), а заголовок он бы посчитал строкой —
   *  и приписал каждому куплету лишнюю односложную строку в схеме рифмовки.
   *
   *  Берём СОСТОЯНИЕ документа, а не файл с диска: несохранённая правка обязана
   *  попасть в референс, иначе кнопка молча даёт вчерашний текст.
   *
   *  Чистая функция — проверяется в node (tests/test_reference_knobs.py). */
  docAsReference(rows) {
    var части = [[]];
    (rows || []).forEach(function (r) {
      if (r.type === 'role') { if (части[части.length - 1].length) части.push([]); return; }
      var t = String(r.text || '').trim();
      if (!t) { if (части[части.length - 1].length) части.push([]); return; }
      части[части.length - 1].push(t);
    });
    return части.filter(function (ч) { return ч.length; })
                .map(function (ч) { return ч.join('\n'); }).join('\n\n');
  },

  /** Кнопка «взять из листа»: открытый лист становится референсом. */
  refFromDoc() {
    var текст = this.docAsReference(this.cur());
    if (!текст) { this.flash('в листе нет строк — референс брать не из чего'); return; }
    this.refSoon({ refText: текст });
  },

