  //   paramsOf / modeOf — «профиль → положения ползунков» с добивкой дефолтами;
  //   pickKnobProfile — выбор записи полки;
  //   saveKnobProfile / deleteKnobProfile — запись и удаление своих профилей
  //     через /api/knobs/profiles;
  //   setKnobMode — бинарный переключатель «алгоритм · классика».
  // Своих профилей не было ни одного (`data/knob_profiles.json` = `[]` с
  // 2026-08-03), встроенных было два, и оба теперь пресеты: «Обычный» → «Как
  // всегда», «Классика» → она же.
  // Переключатель режима стал четвёртым пресетом: отдельная кнопка «классика»
  // рядом с четырьмя кнопками, одна из которых И ЕСТЬ классика, — второе имя
  // одного решения.

  /** Текущее имя пресета или '' — считается по положениям, не хранится. */
  текущийПресет() {
    return имяПресета(this.state.params, this.state.knobMode);
  },

  /** Нажат пресет. Ворота (Мат, Клаузула) и Диссонанс НЕ ТРОГАЕМ — их в наборе
   *  пресета нет, и это единственный механизм, которым «переключатели не
   *  сбрасываются при смене пресета» держится. Никаких «сохранить поверх»:
   *  пресет — не запись на полке, а решение, у него нет состояния «изменён». */
  pickПресет(имя) {
    var пр = null;
    for (var i = 0; i < ПРЕСЕТЫ.length; i++) if (ПРЕСЕТЫ[i].name === имя) пр = ПРЕСЕТЫ[i];
    if (!пр) return;
    // Базой берём PARAM_DEFAULTS, а не пустоту: у `params` девять ключей, их
    // читает фристайл (methods.fs.js: fsGenKey ← knobsOfProfile) и бэк
    // (clean.knob_params). Половина набора здесь стала бы тихим разнобоем.
    var p = Object.assign({}, PARAM_DEFAULTS, this.state.params || {}, пр.params);
    // ЗАПИСЬ НА ДИСК — ЗДЕСЬ, И ЭТО ПОЧИНКА (2026-08-18). Комментарий в
    // componentDidUpdate обещал, что «крутилки пишет saveGenProfileSoon со
    // своих обработчиков», а после сноса цепочки её не звал НИ ОДИН из них:
    // единственными звавшими остались обработчики каркаса строфы. Положения
    // ползунков переживали перезапуск только если заодно тронуть форму.
    this.setState({ params: p, knobMode: пр.mode }, this.saveGenProfileSoon.bind(this));
    this.спроситьФормуПула();
  },

  /** Правка одной крутилки. Живых на экране ленты осталось три: два воротных
   *  переключателя и Диссонанс при заданной теме. Панель фристайла зовёт то же
   *  самое через setParam — там крутилок по-прежнему девять, и это его дело. */
  setKnob(имя, v) {
    var p = Object.assign({}, this.state.params);
    p[имя] = защёлкнуть(имя, v);
    this.setState({ params: p }, this.saveGenProfileSoon.bind(this));
    this.спроситьФормуПула();
  },

  // ФОРМА ПУЛА ПРИ ДВИЖЕНИИ РУЧКИ (Раунд 62).
  //
  // Дебаунс 140 мс — не «на всякий случай», а по замеру: сам запрос стоит
  // 2.3–9.7 мс, но ползунок сыплет событиями на каждый пиксель, и без склейки
  // мы бы слали сотню запросов на один жест. Живого предпросмотра ВЫДАЧИ нет и
  // не будет (прогон 185 мс без темы, 878 с темой — замер 3.7); форма пула
  // умещается, и она же несёт «осязать до нажатия».
  спроситьФормуПула() {
    var self = this;
    clearTimeout(this._формаT);
    this._формаT = setTimeout(function () {
      // СЧЁТЧИК ИНИЦИАЛИЗИРУЕТСЯ ЯВНО. Здесь стояло просто `++self._формаN`, а
      // это на неинициализированном поле даёт NaN — и `NaN === NaN` ложь, то
      // есть сторож устаревших ответов отбрасывал ВСЕ ответы, включая свежий.
      // Запрос уходил, отвечал 200, и ничего не появлялось.
      self._формаN = (self._формаN || 0) + 1;
      var н = self._формаN;
      api.poolShape({ mode: self.state.knobMode, params: self.state.params || {} })
        .then(function (res) {
          // ответ на УСТАРЕВШИЙ запрос выбрасываем: пользователь уже увёл
          // ручку дальше, и показать старое число хуже, чем не показать
          if (н === self._формаN) self.setState({ poolShape: res && res.готово ? res : null });
        })
        .catch(function () { /* форма — удобство, а не обязанность */ });
    }, 140);
  },

