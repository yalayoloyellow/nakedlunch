//   почемуПусто           — честная причина пустой выдачи по воронке бэка;
//   markShownQueue        — история = только показанное на экране, построчно.
// Все четыре зовёт лента (methods.lenta.js) и три из четырёх — фристайл.
//
// ЧЕГО ЗДЕСЬ БОЛЬШЕ НЕТ: прогона цепи (вырезан вместе с пайплайном — «строфа
// единственным режимом и всё») и одиночной генерации в документ genStanza с её
// insertAt и снятьКаретку (вырезаны вместе с редактором). Надгробия — по
