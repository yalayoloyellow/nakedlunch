// Editor First.dc.html, строки 2105..2158) — миксин: интегратор делает
// Object.assign(Nakedlunch.prototype, genMethods). Каркас вставки блоков
// (genStanza/runPipe/rowsFromVariant/insertAt)
// перенесён дословно; мок-генерация дизайна (buildSong/allLines/runTitles)
// заменена реальным POST /api/generate (api/server.py: api_generate).
// Отличия от дизайна — только решения прожарки (PLAN.md):
//   2) тема = выделение: ключ снимается строго в момент вызова
//      (keyFromSelection), обратная связь — статусная строка state.genStatus
//      («генерация…» / «тема: „…“» / «без темы»; интегратор её рендерит);
//      ⌥↵ — принудительный показ ключа ('!слово', core/clean.py: theme_forced);
//   5) крутилки панелей → knobs бэка (genKnobs);
//   7) история = только показанное на экране, построчно (markShownQueue);
//   4) склейка пайплайна: runPipe — настоящий POST /api/pipeline/run (пулы по
//      звеньям + комбинаторная склейка на бэке). Прогон отдаёт ОДИН вариант и
//      кладёт его строфы в документ как обычный текст: механизма вариантов
//      (state.runs, листалка, «оставить»/«убрать блок») больше нет — Раунд 49,
//      требование: выдача одна, механизм вариантов не нужен..

import * as api from './api.js';

// значение ползунка 0..1 с фолбэком — дефолты зеркалят core/clean.py: knobs()
function num(v, dflt) { var n = parseFloat(v); return isNaN(n) ? dflt : Math.max(0, Math.min(1, n)); }

export const genMethods = {
  // ---- ключ темы: решение прожарки 2 — тема = выделение ----
  // Снимок ключа В МОМЕНТ вызова (до потери фокуса): выделенный текст,
  // обрезанный до слова/строки → иначе слово под кареткой (wordAt) → иначе
  // строка каретки, если она выделена целиком (гутер-отметка или ⌘A).
  // Ключ запоминается в _lastKey.
  // ТЕМА — ТОЛЬКО ПОЛЕ «ТЕМЫ» В НАСТРОЙКАХ СТРОФЫ (Раунд 57).
  //
  // Источников было три, и два из них не были видны глазами: нативное
  // выделение, слово под кареткой, отмеченная ярлыком строка. Отсюда и
  // «генерит не про то». Все три вырезаны по его словам: сперва «если я в конце
  // строки ставлю каретку и жму генерацию, последнее слово подхватывается —
  // пусть больше не подхватывается», потом «убрать это усложнение и добавить
  // выбор тем в настройки строфы через запятую, как кейворды», потом «выбор
  // строки никак не влияет на тему — это тоже можно вырезать».
  //
  // Осталось одно поле, которое видно, не наводя мышь. Пусто — значит без темы.
  // Ключ запоминается в _lastKey (его читает фристайл — продолжает начатую
  // мысль, а не начинает свою).
  keyFromSelection() {
    // ЗАПЯТЫЕ СОХРАНЯЮТСЯ. Здесь стояло `join(' ')` — слова склеивались в ОДИН
    // тег, и «любовь, смерть» уезжало на бэк как одно понятие. А `clean.theme`
    // (core/clean.py) режет тему ровно по запятым и переводам строки: каждое
    // слово — свой тег. Отчёт: слова через запятую склеивались в одну тему.. Чистим пробелы и пустые куски, разделитель оставляем.
    var key = String(this.state.themeKeys || '')
      .split(',').map(function (s) { return s.replace(/\s+/g, ' ').trim(); })
      .filter(Boolean).join(', ');
    this._lastKey = key;
    return key;
  },

  // ЗДЕСЬ БЫЛИ stanzaSpec() и genKnobs() — «каркас с панели» и «крутилки с
  // панели». Обе умерли в Раунде 51 вместе с самим понятием «настройки
  // панели как источник запроса»: и каркас, и крутилки берутся у ЗВЕНА
  // (methods.shelves.js: linkSpec / linkKnobs), а панель в них — только
  // последняя из трёх ступеней. Последним читателем обеих был fsGenKey, и
  // читал он не то, что уезжало в запросе, — из-за чего подпись буфера
  // фристайла не менялась там, где выдача менялась.
  //
  // Заодно ушли и три флажка «фильтры»: «фильтр банальности» не был подключён
  // никуда, «слоги 8–9» молча переписывал конструктор строфы и в пайплайне не
  // работал вовсе, «только точные рифмы» ставил rhyme_precision в 1, что по
  // шкале ядра означает САМЫЕ МЯГКИЕ — то есть делал обратное своему названию.

  // ---- генерация ----
  // ⌘↵ — строфа в каретку; вставка блока дословно из дизайна (genStanza),
  // мок buildSong заменён на POST /api/generate
  // Секундомер в статусе (2026-08-02). Прогон по строфе на 14 строк идёт 21
  // секунду на тёплом сервере и 43 на холодном — молчаливое «генерация…»
  // мелким серым в углу читалось как «клавиша не сработала». Теперь счётчик
  // идёт вслух, а статус на время работы становится цветом чернил.
  // НА ВРЕМЯ ПРОГОНА КАРЕТКИ В РЕДАКТОРЕ НЕТ (Раунд 57).
  //
  // Вставка строки-заполнителя перестраивает контейнер, узел под кареткой
  // умирает вместе с выделением, а фокус остаётся — и браузер рисует палку в
  // начале координат контейнера, у левого края. отчёт: на время генерации каретка появляется не на своём месте..
  //
  // Печатать во время прогона всё равно некуда — место вставки заморожено
  // (`_genКуда`), и текст под каретку не пойдёт. Поэтому снимаем выделение и
  // уводим фокус; вернёт каретку в строку сам прогон, когда закончит.
  снятьКаретку() {
    try {
      var sel = typeof window !== 'undefined' && window.getSelection && window.getSelection();
      if (sel && sel.removeAllRanges) sel.removeAllRanges();
    } catch (e) { /* нет выделения — тем лучше */ }
    if (this._lines && this._lines.blur) this._lines.blur();
  },

  startGenClock(label) {
    var self = this, t0 = Date.now();
    clearInterval(this._genClock);
    this.setState({ genStatus: label + '…', genBusy: true });
    this._genClock = setInterval(function () {
      var s = label + '… ' + Math.round((Date.now() - t0) / 1000) + 'с';
      // секунды пишем ПРЯМО в узел заполнителя, минуя setState: иначе каждая
      // секунда перестраивала бы весь контейнер строк документа
      var el = document.getElementById('nlGenSecs');
      if (el) el.textContent = s;
      self.setState({ genStatus: s });
    }, 1000);
  },
  stopGenClock() {
    clearInterval(this._genClock);
    this._genClock = null;
    this.setState({ genBusy: false });
  },

  // Честная причина пустой выдачи (Раунд 51). Раньше на любой пустой ответ
  // печаталось «генератор не вернул строк» — а бэк в этот момент присылал
  // воронку, по которой видно, ЧТО именно всё вырезало. При дефолтных
  // настройках («Источники» на корпусе) грамматический генератор вообще не
  // запускается, и «генератор не вернул строк» — враньё о причине.
  //
  // ПОЧИНКА: воронка ПЛОСКАЯ. Написано это было под вложенный вид
  // (funnel.nl.active, funnel.gen.survived), которого не существует: его давал
  // `_rich_funnel`, вырезанный тем же раундом из горячего пути. Все проверки
  // читали undefined, и «честная причина» всегда сваливалась в последнюю
  // общую фразу — то самое безадресное сообщение, ради устранения которого
  // функция и писалась.
  почемуПусто(res) {
    var f = (res && res.funnel) || {};
    var nl = { active: f.nl_fetched > 0, pool_available: f.pool_available,
               algo_survived: f.nl_survived, classic_survived: f.nl_classic_survived };
    // generated — сколько сырых строк дал грамматический генератор, banality —
    // сколько их дожило до конца каскада (последняя ступень)
    var gen = { active: f.generated > 0, survived: f.banality };
    if (nl.active && !nl.pool_available) return 'в активном пуле не осталось непоказанных строк — верни что-нибудь из истории';
    if (nl.active && !(nl.algo_survived || nl.classic_survived)) {
      var к = this.state.params || {};
      if (Number(к['Клаузула']) > 0) return 'ни одна строка не подошла под выбранную клаузулу — ослабь её';
      if (Number(к['Мат']) >= 0.9995) return 'в пуле не нашлось матерных строк под эти ворота';
      if (Number(к['Мат']) === 0) return 'фильтр «без мата» вырезал всё, что подошло по остальным условиям';
      return 'ворота вырезали весь пул — ослабь клаузулу, мат или банальность';
    }
    if (gen.active && !gen.survived) return 'генератор собрал строки, но их вырезали банальность или метр';
    if (!nl.active && !gen.active) return 'нет источника: «Источники» на нуле, а корпус выключен';
    return 'ни одна строка не прошла отбор — ослабь условия';
  },

  async genStanza(opts) {
    opts = opts || {};
    // раньше здесь был молчаливый return: второе нажатие во время прогона не
    // давало вообще никакого признака жизни
    if (this._busy) { this.flash('прогон уже идёт — дождись или Esc'); return; }
    var self = this;
    var key = this.keyFromSelection();
    // ⌥↵ — принудительный показ ключа: '!слово' (PLAN.md 0.2b, clean.theme_forced)
    // ВОСКЛИЦАТЕЛЬНЫЙ ЗНАК — КАЖДОМУ СЛОВУ (Раунд 57). Стояло `'!' + key`, и
    // пока тема была ОДНИМ словом, это работало. С полем «темы» через запятую
    // ключ стал списком, и знак доставался только первому: `!любовь, смерть` —
    // первое слово жёстко обязательное, остальные обычные темы. Отсюда и
    // одинаковая первая строка в трёх строфах подряд у пользователя.
    var theme = key;
    if (opts.forced && key) {
      theme = key.split(',').map(function (s) {
        var w = s.trim();
        return w ? (w.charAt(0) === '!' ? w : '!' + w) : '';
      }).filter(Boolean).join(', ');
    }
    this._busy = true;
    // МЕСТО ВСТАВКИ ЗАМОРОЖЕНО (Раунд 57). Оно считалось ДВАЖДЫ: здесь, при
    // показе заполнителя (renderRows звал insertAt на каждом рендере, нарочно —
    // «заполнитель должен уехать за кареткой»), и ещё раз при вставке готового
    // блока. Пока каретка стояла смирно, оба ответа совпадали. Стоило её
    // сдвинуть — своей рукой или сторожем каретки, — и надпись «генерация»
    // переезжала на другую строку, а блок ложился в третью.
    //
    // Отчёт: надпись «генерация» перескакивала на строку выше..
    //
    // Одно решение на один прогон: куда нажал — туда и ляжет. Заполнитель и
    // блок читают ОДНО И ТО ЖЕ значение, пересчёта нет нигде.
    this._genКуда = this.insertAt();
    this.снятьКаретку();
    this.startGenClock('генерация');
    try {
      // МАСТЕРСКАЯ, а не звено (Раунд 55). Строфа — самостоятельное занятие со
      // своим меню, своей формой и своим профилем настроек; цепочка к ней
      // отношения не имеет.
      //
      // В Раунде 51 здесь стояли linkSpec(0)/linkKnobs(0) — и это было верно
      // ровно до тех пор, пока строфа и пайплайн жили в одном попапе: тогда
      // «цепочка из одного звена» и «одиночная строфа» обязаны были совпадать,
      // иначе один и тот же экран звучал по-разному в зависимости от длины
      // цепочки. Теперь это два разных занятия за двумя кнопками, совпадать им
      // незачем, и чтение чужого этажа было бы ровно той связью, ради разрыва
      // которой попап и разделили.
      var spec = this.curSpec(), n = spec ? spec.length : 4;
      var payload = { source: 'editor', shortlist: n,
                      mode: this.state.knobMode, params: this.state.params || {} };
      if (theme) payload.theme = theme;
      if (spec) payload.stanza = spec;
      var res = await api.generate(payload);
      var rows = ((res && res.shortlist) || []).slice(0, n);
      if (!rows.length) { this.flash(this.почемуПусто(res)); this.setState({ genStatus: '' }); return; }
      var fresh = rows.map(function (r, i) {
        // буква — из схемы профиля по позиции; rk — рифмо-ключ бэка (scheme() в
        // methods.doc.js берёт его главнее клиентского rkey)
        return { type: 'line', text: r.text, letter: spec ? spec[i % spec.length].letter : 'а', src: 'nl',
                 rk: r.rhyme || '',
                 // книга, откуда строка (Раунд 57) — чтобы её было видно при
                 // выделении и можно было отключить прямо оттуда
                 book: r.source || '', bookId: r.source_id || '' };
      });
      var prev = this.cur(), doc = prev.slice(), куда = this._genКуда || this.insertAt(), at = куда.at;
      // Заголовок вставляем, только если он выбран (Раунд 50). Раньше здесь
      // всегда появлялась строка «строфа» — мусорный заголовок, которого
      // пользователь не просил и убрать не мог. Раунд 55: заголовок свой, из меню
      // «Строфа», а не первого звена чужой цепочки.
      var секция = String(this.state.stanzaSection || '').trim();
      var block = (секция ? [{ type: 'role', text: секция.toLowerCase() }] : []).concat(fresh);
      doc.splice.apply(doc, [at, куда.съесть].concat(block));
      // КАРЕТКА ПОСЛЕ ВСТАВКИ — ШТАТНЫМ ПУТЁМ (Раунд 57). У переноса строки на
      // Enter он есть с самого начала: `_restore = {строка, смещение}`, и
      // `restoreCaret` ставит каретку после перерисовки. У генерации его не
      // было — каретке было некуда встать, она оставалась в контейнере и
      // рисовалась палкой у левого края. Три сторожа ловили это задним числом;
      // теперь генерация просто говорит, где встать, как и все остальные.
      var последняя = block[block.length - 1];
      this._restore = { row: at + block.length - 1,
                        off: последняя && последняя.text ? String(последняя.text).length : 0 };
      this.setState({
        caret: at + block.length - 1, genStatus: key ? 'тема: «' + key + '»' : 'без темы',
        // lastFunnel/lastInsertN вырезаны (Раунд 51): их единственным читателем
        // была инфографика воронки, которая ушла с экрана ещё в Раунде 50.
      });
      this.push(doc, prev);
      if (at >= prev.length) setTimeout(function () { if (self._doc) self._doc.scrollTop = self._doc.scrollHeight; }, 60);
      // честный отчёт о принудительном слове: missing/unrhymed —
      // см. core/filters.py: _ensure_forced
      var fn = (res && res.forced_notice) || {};
      var bad = Object.keys(fn).filter(function (w) { return fn[w] !== 'ok'; });
      if (bad.length) {
        var почему = {
          unrhymed: 'есть в базе, но не рифмуется со схемой',
          // Раунд 57: «всё показано» — отдельный ответ. Железное правило
          // пользователя: показанное не возвращается никогда, поэтому здесь не
          // отказ движка, а подсказка, что делать: чистить историю.
          shown: 'всё, что было с этим словом, уже показано — очисти историю или залей новые источники',
          // Раунд 51: вердикт классики печатался как «нет строки в базе» —
          // ровно то враньё о причине, которое Раунд 50 объявил вырезанным.
          // Тема в классике не действует по определению режима.
          classic: 'в режиме «классика» тема не действует вовсе',
        };
        this.flash('«' + bad[0] + '» — ' + (почему[fn[bad[0]]] || 'нет подходящей строки в базе'));
      }
      // решение прожарки 7: показано = вставлено на экран
      this.markShownQueue(rows.map(function (r) { return { text: r.text, template: r.template || '' }; }));
    } catch (e) {
      this.flash(e && e.message ? e.message : String(e));
      this.setState({ genStatus: '' });
    } finally {
      this._busy = false;
      this._genКуда = null;
      this.stopGenClock();
    }
  },

  // решение прожарки 7: история = только показанное на экране, построчно.
  // Очередь с дебаунсом 300 мс → POST /api/history/mark_shown
  // (api/server.py: {items: [{text, template}], theme?}). Тема снимается при
  // постановке в очередь (_lastKey), при отправке группируем по теме — быстрые
  // генерации с разными ключами не смешиваются под одной темой.
  markShownQueue(texts) {
    var self = this;
    if (!this._shownQ) this._shownQ = [];
    var theme = this._lastKey || '';
    (texts || []).forEach(function (t) {
      var it = typeof t === 'string' ? { text: t, template: '' } : { text: t.text || '', template: t.template || '' };
      if (it.text) self._shownQ.push({ text: it.text, template: it.template, theme: theme });
    });
    clearTimeout(this._shownT);
    this._shownT = setTimeout(function () {
      var q = self._shownQ; self._shownQ = [];
      if (!q || !q.length) return;
      var groups = {};
      q.forEach(function (it) { (groups[it.theme] = groups[it.theme] || []).push({ text: it.text, template: it.template }); });
      Object.keys(groups).forEach(function (th) {
        api.markShown(th ? { items: groups[th], theme: th } : { items: groups[th] }).then(function () {
          // Список истории в состоянии подтягиваем ПОСЛЕ записи (Раунд 41).
          // Отчёт: история фристайла и генерации не была единой — строки фристайла не
          // находились поиском.. Записывалось-то всё правильно, а вот клиентский список
          // грузился один раз в boot и с тех пор не обновлялся — поиск шёл по
          // вчерашнему снимку. Дозагрузка отложенная и одна на пачку: фристайл
          // помечает строки каждые несколько секунд.
          clearTimeout(self._histReloadT);
          self._histReloadT = setTimeout(function () { if (self.reloadHistory) self.reloadHistory(); }, 1500);
        }).catch(function (e) {
          // запись истории не мешает потоку: молча в консоль, но первый раз
          // за сессию — честный flash, чтобы потеря не была тихой
          console.error('mark_shown:', e);
          if (!self._shownErrFlashed) { self._shownErrFlashed = true; self.flash('история не записалась: ' + (e && e.message ? e.message : e)); }
        });
      });
    }, 300);
  },

  // решение прожарки 4: пайплайн = пулы по звеньям + комбинаторная склейка
  // (core/pipeline.py, POST /api/pipeline/run). Каркас вставки блока — дословно
  // из runPipe дизайна (строки 2114..2125), мок buildSong заменён ответом бэка;
  // 409 «прогон уже идёт» и таймаут приходят честным throw из api.js
  async runPipe() {
    // общий замок с genStanza: один прогон/генерация за раз — но не молча
    if (this._busy) { this.flash('прогон уже идёт — дождись или Esc'); return; }
    var self = this;
    var key = this.keyFromSelection();
    var st = this.state;
    this._busy = true;
    // То же замораживание, что у строфы: прогон идёт дольше, и шанс, что
    // каретка уедет за это время, только выше.
    this._genКуда = this.insertAt();
    this.снятьКаретку();
    this.startGenClock('прогон');
    try {
      var изРеференса = st.refChain || [];
      // Звено = каркас + профиль настроек + необязательный заголовок секции.
      //
      // Раунд 51: крутилки уезжают в КООРДИНАТАХ ИНТЕРФЕЙСА ({mode, params}),
      // а переводит их бэк — clean.knobs_from_profile. До этого фронт слал
      // ядерные имена, и в то же поле восстановление слепка клало русские;
      // ядро русских не знало и молча ставило дефолты, которые вдобавок
      // перебивали глобальные. Одно поле, один формат — и переводчик один.
      //
      // Порядок источников крутилок: свой профиль звена → снятое с референса
      // → то, что стоит в панели. Каркас — теми же тремя ступенями (linkSpec).
      var chain = (st.chain || []).map(function (секция, i) {
        var повтор = self.linkRepeat(i);
        // Звено-повтор (хук) не несёт НИЧЕГО своего, кроме заголовка: каркас,
        // крутилки и саму строфу оно берёт у двойника. Прислать ему свою спеку
        // значило бы дать бэку два несогласных источника правды об одном
        // звене — и он молча выбрал бы один.
        if (повтор != null) return { title: секция || '', repeat_of: повтор };
        var реф = изРеференса[i];
        var звено = { title: секция || '', form: (st.chainForms || [])[i] || null };
        if (реф && реф.spec) звено.spec = реф.spec;
        // тот же резолвер, что у одиночной генерации и фристайла; панель в
        // звено не кладём — она уже едет глобально (см. linkKnobs)
        var проф = self.linkKnobs(i);
        if (проф.source !== 'мастерская') { звено.mode = проф.mode; звено.params = проф.params; }
        return звено;
      });
      // стыков ровно звеньев−1; дырки массива (setJunc пишет по индексу) — дефолт контракта
      var junctions = (st.chain || []).slice(1).map(function (_, i) { return (st.junctions || [])[i] || 'рифмовать стык'; });
      var res = await api.pipelineRun({
        theme: key || '',
        chain: chain,
        junctions: junctions,
        // глобальные крутилки прогона — фолбэк для звена без своего профиля;
        // формат тот же, что у звена, и переводит их тот же переводчик
        mode: st.knobMode, params: st.params,
        // Раунд 47. Требование: убрать настройки, где «больше» не значит «лучше», оставив оптимальное
        // соотношение..
        // Обе величины производные: пул — сколько готовых строф просить у
        // генератора (дальше по ранжиру идёт заведомо худшее), ширина перебора
        // — сколько частичных цепочек держать. Обе выведены из длины цепочки,
        // решения пользователя не требуют и с глаз убраны.
        runs: Math.max(2000, Math.min(20000, 1200 * Math.max(1, (st.chain || []).length))),
        pool_per_link: 50,
        // Порога отсева больше нет (Раунд 39). требование: прогонять всё, оценивать по признакам и выдавать лучшее — десять штук
        // по умолчанию..
        // Порог решал ту же задачу вслепую: при 0.6 живые пулы резались почти
        // в ноль, при 0.35 не резал почти ничего. Отбираем ЛУЧШИЕ N, а не всё
        // выше выдуманного числа; на бэке threshold по умолчанию 0.0.
        // Раунд 48. требование: один вариант вместо десяти вариаций, без повторов, с записью в
        // историю.. Десять вариантов были попыткой дать выбор
        // ДО просмотра; выбор оказался не нужен, а нужна невозвратность:
        // показанное уходит в историю и в следующий прогон не попадёт
        // (filters.run вычитает corpus.hidden_set из пула).
        best: 1,
      });
      var variants = (res && res.variants) || [];
      if (!variants.length) {
        // Причина у бэка есть — воронка говорит, на каком звене кончились
        // строфы. Раньше печаталось безадресное «не собрал ни одного
        // варианта», и пользователь не знал, какое звено ослаблять.
        var пусто = ((res && res.funnel && res.funnel.pools) || [])
          .filter(function (p) { return !p.stanzas; })
          .map(function (p) { return p.title || p.form || 'звено'; });
        this.flash(пусто.length
          ? 'пусто на звене: ' + пусто.join(', ') + ' — ослабь его условия'
          : 'строфы набрались, но ни одно сочетание не прошло по стыкам');
        this.setState({ genStatus: '' });
        return;
      }
      // Раунд 49: блок вставляется как обычный текст. требование: «оставить/убрать блок» — лишняя функция, выдача одна.. Механизма вариантов больше
      // нет вовсе: ни state.runs, ни листалки, ни ✓/✕ — прогон кладёт строфы
      // в документ ровно так же, как одиночная генерация кладёт одну.
      var block = this.rowsFromVariant(variants[0]);
      var prev = this.cur(), doc = prev.slice(), куда = this._genКуда || this.insertAt(), at = куда.at;
      doc.splice.apply(doc, [at, куда.съесть].concat(block));
      // КАРЕТКА ПОСЛЕ ВСТАВКИ — ШТАТНЫМ ПУТЁМ (Раунд 57). У переноса строки на
      // Enter он есть с самого начала: `_restore = {строка, смещение}`, и
      // `restoreCaret` ставит каретку после перерисовки. У генерации его не
      // было — каретке было некуда встать, она оставалась в контейнере и
      // рисовалась палкой у левого края. Три сторожа ловили это задним числом;
      // теперь генерация просто говорит, где встать, как и все остальные.
      var последняя = block[block.length - 1];
      this._restore = { row: at + block.length - 1,
                        off: последняя && последняя.text ? String(последняя.text).length : 0 };
      this.setState({
        caret: at + block.length - 1,
        genStatus: key ? 'тема: «' + key + '»' : 'без темы',
        // итог склейки — отдельным ключом: форма funnel пайплайна не совпадает
        // с _rich_funnel генерации, и funnelData её бы не пережил
        lastPipeFunnel: (res && res.funnel) || null,
      });
      this.push(doc, prev);
      if (at >= prev.length) setTimeout(function () { if (self._doc) self._doc.scrollTop = self._doc.scrollHeight; }, 60);
      this.markShownQueue(block.filter(function (r) { return r.type === 'line'; }).map(function (r) { return { text: r.text, template: '' }; }));
    } catch (e) {
      this.flash(e && e.message ? e.message : String(e));
      this.setState({ genStatus: '' });
    } finally {
      this._busy = false;
      this._genКуда = null;
      this.stopGenClock();
    }
  },

  // ---- референс как вход пайплайна (Раунд 45) ----
  // Требование: пайплайн принимает референтный текст и процент референтности и сам
  // назначает структуру.. Снятая цепочка кладётся в state целиком: длина, спеки строф и
  // кнобы на каждое звено. Дальше её можно править руками как обычную.
  // Референс применяется САМ, как только вставлен текст или сдвинут ползунок
  // (Раунд 46). Требование: структура принимается сразу при вставке текста..
  // Кнопки «снять» больше нет: лишний шаг между «вставил» и «увидел».
  refSoon(patch) {
    var self = this;
    this.setState(patch || {}, function () {
      clearTimeout(self._refT);
      if (!(self.state.refText || '').trim()) {
        self.setState({ refChain: null, refProfile: null });
        return;
      }
      self._refT = setTimeout(function () { self.applyRef(true); }, 500);
    });
  },

  // applyCurve ВЫРЕЗАН (Раунд 55). Кривая была вторым поставщиком того же
  // слота, что и референс, — и они стирали друг друга: выбрал одно, молча
  // потерял другое. Требование: искажение живёт в серии, а не в пайплайне, и влияет на её пайплайны..
  //
  // Он прав дважды. Во-первых, искажение — это про то, чем тексты отличаются
  // ДРУГ ОТ ДРУГА, а в одном ручном прогоне отличаться не от чего. Во-вторых,
  // форму одного текста и так задают профили звеньев: «Плотная» на припев,
  // «Рваная» на бридж — руками, видно, и никакой второй машинки для того же
  // самого не нужно. Кривая переехала в серию (core/distort.py) и стала не
  // заменой крутилок, а сдвигом поверх них.

  async applyRef(тихо) {
    var текст = (this.state.refText || '').trim();
    if (!текст) { if (!тихо) this.flash('вставь текст референса'); return; }
    this.setState({ refBusy: true });
    try {
      var res = await api.pipelineProfile(текст, this.state.refPct != null ? this.state.refPct : 1);
      var звенья = (res && res.chain) || [];
      if (!звенья.length) { this.flash('из референса не вышло ни одного звена'); return; }
      // вся перекладка модели — в methods.shelves.js: refPatch (чистая, и
      // потому проверяемая без сервера)
      this.setState(this.refPatch(звенья, res.junctions, res.profile));
      // Обрезку говорим ВСЛУХ и даже в тихом режиме: молча показать 12 звеньев
      // вместо двадцати — это соврать о том, что взято из текста. Тихий режим
      // молчит про удачу, а не про потерю.
      if (res['обрезано']) {
        this.flash('в тексте ' + (звенья.length + res['обрезано']) + ' частей, а в цепочку влезает '
                   + звенья.length + ' — взяты первые; лишнее разнеси по отдельным прогонам');
      } else if (!тихо) {
        var p = res.profile || {};
        this.flash('снято: ' + (p.частей || звенья.length) + ' частей, ' + (p.строк || '?') + ' строк');
      }
    } catch (e) {
      this.flash(e && e.message ? e.message : String(e));
    } finally {
      this.setState({ refBusy: false });
    }
  },

  // Вариант бэка → строки документа: секция становится обычным заголовком, её
  // строки — обычными строками. Ни `run`, ни `sub` больше нет: механизм
  // вариантов вырезан целиком (Раунд 49), блок ничем не отличается от того,
  // что кладёт одиночная генерация. Буква — из схемы профиля формы звена по
  // позиции; без формы фолбэк 'а', scheme() всё равно считает буквы показа от
  // rk бэка (решение прожарки 2).
  rowsFromVariant(v) {
    var self = this, forms = this.state.chainForms || [], rows = [];
    ((v && v.sections) || []).forEach(function (sec, si) {
      // Заголовок — только если он есть (Раунд 50). Раньше строка-заголовок
      // вставлялась ВСЕГДА, а текст брался из роли, которую фронт при пустой
      // секции сам подменял на имя формы или на слово «строфа» — то есть
      // «без заголовка» в панели давало в документе заголовок «строфа».
      var заголовок = String(sec.title || '').trim();
      if (заголовок) rows.push({ type: 'role', text: заголовок.toLowerCase() });
      var lines = self.formLines(forms[si]);
      ((sec && sec.lines) || []).forEach(function (ln, li) {
        rows.push({ type: 'line', text: ln.text,
                    letter: lines && lines[li % lines.length] ? lines[li % lines.length].letter : 'а',
                    src: 'nl', rk: ln.rhyme || '' });
      });
    });
    return rows;
  },

  // профиль строфы по имени из state.stanzaForms (boot) — для букв рифмовки строк варианта
  formLines(name) {
    if (!name) return null;
    var f = this.state.stanzaForms || {};
    var all = (f.builtin || []).concat(f.custom || []);
    for (var i = 0; i < all.length; i++) if (all[i].name === name) return all[i].lines || null;
    return null;
  },
  // куда вставлять: после строки с курсором, иначе в конец
  // КУДА ЛЯЖЕТ ГЕНЕРАЦИЯ (Раунд 56).
  //
  // Читалось `state.caret`, а он ставится ТОЛЬКО кликом по строке. Подвигал
  // каретку стрелками, напечатал в другом месте, вернулся с другой вкладки —
  // и значение устарело: строфа уходила туда, где отчёт: место генерации определялось криво и попадало туда, где начинать её не хотели..
  //
  // Спрашиваем ЖИВУЮ каретку у самого документа (`caretSnap` читает
  // выделение), и только если её нет — падаем на `state.caret`, а потом на
  // конец листа. Вставка всегда ПОСЛЕ текущей строки, то есть с новой.
  // РОВНО ТУДА, ГДЕ КАРЕТКА (Раунд 57). Здесь стояло `c + 1` — генерация
  // всегда уходила на строку НИЖЕ. требование: генерация начинается ровно в позиции каретки — без переносов и без поиска
  // другой строки..
  //
  // Стоит на пустой строке — блок занимает ЕЁ, а не следующую: пустую съедаем,
  // иначе над выдачей оставался бы осиротевший отступ, который он и видел как
  // «вылезает не туда». Стоит на строке с текстом — блок встаёт на её место, а
  // текст уезжает вниз целым: рвать его посередине он запретил отдельно.
  insertAt() {
    var живая = this.caretSnap ? this.caretSnap() : null;
    var c = живая ? живая.row : this.state.caret;
    var doc = this.cur();
    if (!(c >= 0 && c < doc.length)) return { at: doc.length, съесть: 0 };
    var r = doc[c];
    var пусто = r && r.type === 'line' && !String(r.text || '').trim();
    return { at: c, съесть: пусто ? 1 : 0 };
  },
};
