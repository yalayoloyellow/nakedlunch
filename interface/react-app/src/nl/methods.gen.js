import * as api from './api.js';

// `num()` (значение ползунка 0..1 с фолбэком) вырезан 2026-08-18: его читал
// только genKnobs, умерший ещё в Раунде 51. Перевод крутилок в координаты ядра
// живёт ОДИН — methods.shelves.js: knobsOfProfile.

export const genMethods = {
  // ---- ключ темы ----
  // ТЕМА — ТОЛЬКО ПОЛЕ «ТЕМЫ» В НАСТРОЙКАХ СТРОФЫ (Раунд 57).
  //
  // Источников было три, и два из них не были видны глазами: нативное
  // выделение, слово под кареткой, отмеченная ярлыком строка. Отсюда и
  // «генерит не про то». Все три вырезаны по его словам: сперва «если я в конце
  // строки ставлю каретку и жму генерацию, последнее слово подхватывается —
  // пусть больше не подхватывается», потом «убрать это усложнение и добавить
  // выбор тем в настройки строфы через запятую, как кейворды», потом «выбор
  // строки никак не влияет на тему — это тоже можно вырезать».
  //
  // Осталось одно поле, которое видно, не наводя мышь. Пусто — значит без темы.
  // Ключ запоминается в _lastKey (его читает фристайл — продолжает начатую
  // мысль, а не начинает свою).
  keyFromSelection() {
    // ЗАПЯТЫЕ СОХРАНЯЮТСЯ. Здесь стояло `join(' ')` — слова склеивались в ОДИН
    // тег, и «любовь, смерть» уезжало на бэк как одно понятие. А `clean.theme`
    // (core/clean.py) режет тему ровно по запятым и переводам строки: каждое
    // слово — свой тег. Отчёт: слова через запятую склеивались в одну тему.. Чистим пробелы и пустые куски, разделитель оставляем.
    var key = String(this.state.themeKeys || '')
      .split(',').map(function (s) { return s.replace(/\s+/g, ' ').trim(); })
      .filter(Boolean).join(', ');
    this._lastKey = key;
    return key;
  },

  // ЗДЕСЬ БЫЛИ stanzaSpec() и genKnobs() — «каркас с панели» и «крутилки с
  // панели». Обе умерли в Раунде 51 вместе с самим понятием «настройки
  // панели как источник запроса»: и каркас, и крутилки брались у ЗВЕНА
  // (methods.shelves.js: linkSpec / linkKnobs), а панель в них была только
  // последней из трёх ступеней. Последним читателем обеих был fsGenKey, и
  // читал он не то, что уезжало в запросе, — из-за чего подпись буфера
  // фристайла не менялась там, где выдача менялась.
  // 2026-08-18: звеньев больше нет, и трёх ступеней тоже — каркас берётся
  // прямо из мастерской (curSpec), крутилки из state.params.
  //
  // Заодно ушли и три флажка «фильтры»: «фильтр банальности» не был подключён
  // никуда, «слоги 8–9» молча переписывал конструктор строфы и в пайплайне не
  // работал вовсе, «только точные рифмы» ставил rhyme_precision в 1, что по
  // шкале ядра означает САМЫЕ МЯГКИЕ — то есть делал обратное своему названию.

  // ---- генерация ----
  // Секундомер в статусе (2026-08-02). Прогон по строфе на 14 строк идёт 21
  // секунду на тёплом сервере и 43 на холодном — молчаливое «генерация…»
  // мелким серым в углу читалось как «клавиша не сработала». Теперь счётчик
  // идёт вслух, а статус на время работы становится цветом чернил.
  // Ленте он нужен ровно в холодном случае: пустой буфер на первом нажатии или
  // после смены настроек. Дальше ожидания нет вовсе.
  // ЗДЕСЬ БЫЛА `снятьКаретку()` (вырезано 2026-08-18). Она гасила выделение и
  // уводила фокус из контейнера строк на время прогона, чтобы браузер не рисовал
  // палку каретки у левого края. Каретки нет — редактор вырезан целиком.

  startGenClock(label) {
    var self = this, t0 = Date.now();
    clearInterval(this._genClock);
    this.setState({ genStatus: label + '…', genBusy: true });
    this._genClock = setInterval(function () {
      // Заполнитель в строке документа (#nlGenSecs), которому секунды писались
      // напрямую, минуя setState, вырезан 2026-08-18 вместе с редактором.
      // Секундомер остался один — в статусной строке шапки.
      self.setState({ genStatus: label + '… ' + Math.round((Date.now() - t0) / 1000) + 'с' });
    }, 1000);
  },
  stopGenClock() {
    clearInterval(this._genClock);
    this._genClock = null;
    this.setState({ genBusy: false });
  },

  // Честная причина пустой выдачи (Раунд 51). Раньше на любой пустой ответ
  // печаталось «генератор не вернул строк» — а бэк в этот момент присылал
  // воронку, по которой видно, ЧТО именно всё вырезало. При дефолтных
  // настройках («Источники» на корпусе) грамматический генератор вообще не
  // запускается, и «генератор не вернул строк» — враньё о причине.
  //
  // ПОЧИНКА: воронка ПЛОСКАЯ. Написано это было под вложенный вид
  // (funnel.nl.active, funnel.gen.survived), которого не существует: его давал
  // `_rich_funnel`, вырезанный тем же раундом из горячего пути. Все проверки
  // читали undefined, и «честная причина» всегда сваливалась в последнюю
  // общую фразу — то самое безадресное сообщение, ради устранения которого
  // функция и писалась.
  почемуПусто(res) {
    var f = (res && res.funnel) || {};
    var nl = { active: f.nl_fetched > 0, pool_available: f.pool_available,
               algo_survived: f.nl_survived, classic_survived: f.nl_classic_survived };
    // generated — сколько сырых строк дал грамматический генератор, banality —
    // сколько их дожило до конца каскада (последняя ступень)
    var gen = { active: f.generated > 0, survived: f.banality };
    if (nl.active && !nl.pool_available) return 'в активном пуле не осталось непоказанных строк — верни что-нибудь из истории';
    if (nl.active && !(nl.algo_survived || nl.classic_survived)) {
      var к = this.state.params || {};
      if (Number(к['Клаузула']) > 0) return 'ни одна строка не подошла под выбранную клаузулу — ослабь её';
      if (Number(к['Мат']) >= 0.9995) return 'в пуле не нашлось матерных строк под эти ворота';
      if (Number(к['Мат']) === 0) return 'фильтр «без мата» вырезал всё, что подошло по остальным условиям';
      return 'ворота вырезали весь пул — ослабь клаузулу, мат или банальность';
    }
    if (gen.active && !gen.survived) return 'генератор собрал строки, но их вырезали банальность или метр';
    if (!nl.active && !gen.active) return 'нет источника: «Источники» на нуле, а корпус выключен';
    return 'ни одна строка не прошла отбор — ослабь условия';
  },

  // ---------------------------------------------------------------------------
  // ЗДЕСЬ БЫЛА ОДИНОЧНАЯ ГЕНЕРАЦИЯ В ДОКУМЕНТ — genStanza (вырезано
  // 2026-08-18, 130 строк).
  //
  // Она делала POST /api/generate на ОДНУ строфу и вставляла её в лист по месту
  // каретки: замораживала место вставки (_genКуда), показывала заполнитель,
  // клала заголовок секции над блоком, возвращала каретку в последнюю строку и
  // прокручивала лист вниз. Всё это — работа с документом, а документа нет.
  //
  // ПРОИЗВОДИТЕЛЬ ТЕПЕРЬ ОДИН: lentaСтрофа (methods.lenta.js). Он не хуже, а
  // дешевле — берёт готовую строфу из пачки: 6.2 мс против 53.4 у одиночного
  // прогона (замер 2026-08-14). Всё, что у genStanza было своего и живого, туда
  // и переехало: обязательное слово темы (⌥), номер прогона и его штамп,
  // воронка последнего прогона, честная причина пустой выдачи, запись
  // показанного в историю.
  //
  // Что НЕ переехало и почему: заголовок секции (stanzaSection). Он был строкой
  // `## куплет`, которую генерация клала НАД строфой В ЛИСТ. В ленте строк
  // разметки нет и быть не может — она выдача, а не текст.
  // ---------------------------------------------------------------------------

  // решение прожарки 7: история = только показанное на экране, построчно.
  // Очередь с дебаунсом 300 мс → POST /api/history/mark_shown
  // (api/server.py: {items: [{text, template}], theme?}). Тема снимается при
  // постановке в очередь (_lastKey), при отправке группируем по теме — быстрые
  // генерации с разными ключами не смешиваются под одной темой.
  markShownQueue(texts) {
    var self = this;
    if (!this._shownQ) this._shownQ = [];
    var theme = this._lastKey || '';
    // Номер прогона снимается ЗДЕСЬ, при постановке в очередь, по той же
    // причине, что и тема: пока пачка ждёт отправки, успевает пройти следующая
    // генерация, и группировка по паре (тема, номер) не даёт смешать чужие
    // строки под одним номером. Фристайл номера не ведёт — там он пустой, и
    // запись ведёт себя как раньше.
    var семя = this._lastSeed != null ? this._lastSeed : '';
    (texts || []).forEach(function (t) {
      var it = typeof t === 'string' ? { text: t, template: '' } : { text: t.text || '', template: t.template || '' };
      if (it.text) self._shownQ.push({ text: it.text, template: it.template, theme: theme, seed: семя });
    });
    clearTimeout(this._shownT);
    this._shownT = setTimeout(function () {
      var q = self._shownQ; self._shownQ = [];
      if (!q || !q.length) return;
      var groups = {};
      q.forEach(function (it) {
        // Разделитель \u0000, а не пробел: тема бывает из нескольких слов, и
        // на пробеле обратный разбор ключа разъехался бы.
        var k = it.theme + '\u0000' + (it.seed == null ? '' : it.seed);
        (groups[k] = groups[k] || []).push({ text: it.text, template: it.template });
      });
      Object.keys(groups).forEach(function (k) {
        var части = k.split('\u0000'), th = части[0], семя = части[1];
        var payload = { items: groups[k] };
        if (th) payload.theme = th;
        if (семя) payload.seed = семя;
        api.markShown(payload).then(function () {
          // Список истории в состоянии подтягиваем ПОСЛЕ записи (Раунд 41).
          // Отчёт: история фристайла и генерации не была единой — строки фристайла не
          // находились поиском.. Записывалось-то всё правильно, а вот клиентский список
          // грузился один раз в boot и с тех пор не обновлялся — поиск шёл по
          // вчерашнему снимку. Дозагрузка отложенная и одна на пачку: фристайл
          // помечает строки каждые несколько секунд.
          clearTimeout(self._histReloadT);
          self._histReloadT = setTimeout(function () { if (self.reloadHistory) self.reloadHistory(); }, 1500);
        }).catch(function (e) {
          // запись истории не мешает потоку: молча в консоль, но первый раз
          // за сессию — честный flash, чтобы потеря не была тихой
          console.error('mark_shown:', e);
          if (!self._shownErrFlashed) { self._shownErrFlashed = true; self.flash('история не записалась: ' + (e && e.message ? e.message : e)); }
        });
      });
    }, 300);
  },

  // ---------------------------------------------------------------------------
  // ЗДЕСЬ БЫЛ ПРОГОН ЦЕПИ И ВСЁ, ЧТО ЕГО КОРМИЛО (вырезано 2026-08-18, 224 строки).
  //
  // runPipe — POST /api/pipeline/run: пулы по звеньям, комбинаторная склейка на
  //   бэке, вставка готового текста в документ, а с волны Л5 — ещё и ветка
  //   «цепь в ленту» одним блоком.
  // stopPipe — останов прогона по Escape (POST /api/pipeline/stop).
  // refSoon / applyRef — референс: чужой текст меряется и превращается в
  //   цепочку (POST /api/pipeline/profile).
  // rowsFromVariant — вариант бэка в строки документа.
  // formLines — схема формы строфы по имени с полки; жила только ради трёх
  //   читателей выше (rowsFromVariant, linkSpec, chainSnapshot) и ушла с ними.
  //
  // ПОЧЕМУ. Решение владельца дословно: «pipeline и серия это бесполезные режимы
  // на самом деле… с практической точки зрения бесполезны, их можно вырезать.
  // Строфа единственным режимом и всё». Замер журнала за десять живых дней: 29
  // прогонов цепи против 587 одиночных строф, медиана цепи 24.2 с — впрок такое
  // и не набьёшь, и ради этого держать второй путь генерации незачем.
  // ---------------------------------------------------------------------------

  // ЗДЕСЬ БЫЛ insertAt() (вырезано 2026-08-18) — «куда лечь блоку»: живая
  // каретка документа, иначе state.caret, иначе конец листа, плюс правило
  // «стоишь на пустой строке — блок занимает ЕЁ». Класть некуда: лента всегда
  // растёт вниз, и вопроса о месте вставки в ней не существует.
};
