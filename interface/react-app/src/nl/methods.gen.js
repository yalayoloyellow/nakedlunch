  // ЗДЕСЬ БЫЛИ stanzaSpec() и genKnobs() — «каркас с панели» и «крутилки с
  // панели». Обе умерли в Раунде 51 вместе с самим понятием «настройки
  // панели как источник запроса»: и каркас, и крутилки брались у ЗВЕНА
  // (methods.shelves.js: linkSpec / linkKnobs), а панель в них была только
  // последней из трёх ступеней. Последним читателем обеих был fsGenKey, и
  // читал он не то, что уезжало в запросе, — из-за чего подпись буфера
  // фристайла не менялась там, где выдача менялась.
  // 2026-08-18: звеньев больше нет, и трёх ступеней тоже — каркас берётся
  // прямо из мастерской (curSpec), крутилки из state.params.
  //
  // Заодно ушли и три флажка «фильтры»: «фильтр банальности» не был подключён
  // никуда, «слоги 8–9» молча переписывал конструктор строфы и в пайплайне не
