// ============================================================
// «ИЗ ЧЕГО ВЫБИРАЕТСЯ» — ОДНА СТРОКА (было два блока на девять строк)
// ============================================================
//
// ЗАЧЕМ ВООБЩЕ ОСТАВЛЕНО. Владелец про меню: «дохуя много лишней информации», и
// первый порыв — выбросить оба блока. Нельзя выбросить второй: замер показал,
// что крупнейшая ступень каскада — ЖРЕБИЙ, случайные триста строк из полутора
// миллионов (99.98% отсева). Пока его не видно, кажется, что выдачу решают
// настройки; убери — и вернётся ощущение, что пресеты всесильны. Это ровно та
// болезнь, которую замер и лечит.
//
// ЧТО ИЗ БЛОКА ПУЛА УШЛО (2026-08-18): четыре строки полос редкости
// («затёртое · обычное · редкое · вне словаря») с примером и процентом. Они
// стояли затем, чтобы ОСЯЗАТЬ КРАЙ ПОЛЗУНКА до нажатия — а ползунков больше
// нет: «затёрто или нет» теперь называется словом «Разговор» на кнопке. Числа
// строк и рифмо-ключей остались: это единственное, чем видно, что пресеты дают
// РАЗНЫЕ пулы (П1 2 043 349 строк против П3 1 361 802 — 85.4% корпуса против
// 56.9%) [Э].
// НА СКОЛЬКО ХВАТИТ — ПРЕДУПРЕЖДЕНИЕ ЗАРАНЕЕ (2026-08-31)
//
// Слово владельца: «пусть говорит заранее и рекомендует увеличить количество
// источников и т.д.». Повод — замер: катрен 8-9 слогов с воротами переклички
// выбирает из ШЕСТИДЕСЯТИ строк на весь корпус, то есть кончается за пятнадцать
// нажатий. Показанное не возвращается 180 дней, поэтому кончится оно НАСОВСЕМ
// на этот срок, а не пойдёт по кругу; человек имеет право знать об этом ДО
// того, как упрётся, а не после.
//
// ПОРОГИ ВЗЯТЫ ОТ ЖИЗНИ, А НЕ ОТ КРУГЛЫХ ЧИСЕЛ. На дефолтном катрене запас
// 54 000 строф — писать о нём незачем, это шум. Ниже 300 строф запас перестаёт
// быть бесконечным (вечер работы), ниже 30 — это минуты, и тогда к числу
// добавляется совет, что именно расширить.
//
// «НЕ БОЛЬШЕ ЧЕМ» — потому что рифма сузит ещё: строке нужен партнёр по ключу,
// и он может не найтись. Обещать точное число значило бы обещать то, чего до
// отбора никто не знает.
function запас(ф) {
  var н = ф['хватит_строф'];
  if (н == null || н >= 300) return null;
  var выкл = ф['книг_выключено'] || 0;
  var совет = н >= 30 ? ''
    : (выкл > 0
        ? ' — включи ещё книги (выключено ' + выкл + ') или расширь вилку слогов'
        : ' — расширь вилку слогов, ослабь ворота или залей ещё книг');
  // СКЛОНЕНИЕ ПО-РУССКИ, А НЕ «0 СТРОФЫ». Правило целиком: 1, 21, 31 — строфу;
  // 2-4, 22-24 — строфы; всё остальное, включая 0 и 11-14, — строф.
  var д = н % 10, с = н % 100;
  var слово = (д === 1 && с !== 11) ? 'строфу'
            : (д >= 2 && д <= 4 && !(с >= 12 && с <= 14)) ? 'строфы' : 'строф';
  return (
    <div style={s('margin-top: 3px; font-size: 9px; line-height: 1.5; color: '
                  + (н < 30 ? 'var(--ink)' : 'var(--muted-soft)') + ';')}>
      {/* ДВА ЧИСЛА РЯДОМ, ИНАЧЕ ЧИТАЕТСЯ КАК ПОЛОМКА. Выше стоит «190 строк» —
          это то, что прошло ВОРОТА. Здесь — сколько из них влезает в вилку
          слогов ЭТОЙ формы, и разойтись они могут на два порядка. Без второго
          числа строка «на целую строфу не хватит» под числом 190 выглядит
          враньём одного из двух. */}
      {'в вилку слогов попадают ' + Number(ф['под_форму'] || 0).toLocaleString('ru-RU') + ': '}
      {н === 0 ? 'на целую строфу не хватит' : ('хватит не больше чем на ' + н + ' ' + слово)}
      {совет}
    </div>
  );
}

function пул_и_воронка(ф, f, ярус) {
  var готов = !!(ф && ф['готово']);
  var ст = (f && f.ступени) || null;
  var естьВоронка = !!(ст && ст['корпус']);
  if (!готов && !естьВоронка) return null;   // «ещё не спрашивали» ≠ «пусто»
  var ч = function (n) { return Number(n || 0).toLocaleString('ru-RU'); };
  // ПОРЯДОК — ОТ СВОЕГО К ОТСЕВУ (2026-08-20). Стояло «корпус → ворота → пул»,
  // и число ворот считало строки из книг, которые он ВЫКЛЮЧИЛ: честное про
  // ворота, бессмысленное про его корпус. Теперь сперва «моё», потом отсев, и
  // последнее число читается как доля от своего.
  // Считает бэк по-прежнему воротами вперёд — маска ворот кэшируется (холодная
  // 5.8 с против тёплых 1.7 мс), а «показанное» меняется каждый прогон.
  var шаги = естьВоронка
    ? [['всего', ст['корпус']],
       ['мои книги', ст['твои_книги']],
       ['минус показанное', ст['показано']],
       ['прошло ворота', ст['пул']],
       ['выдано', ст['тяга'] != null ? ст['тяга'] : ст['в_сборку']]].filter(function (ш) { return ш[1] != null; })
    : [];
  return (
    <div style={s('margin-top: 12px;')}>
      <div style={s(ЗАГОЛОВОК)}>из чего выбирается</div>
      {готов ? (
        /* КОРЗИНЫ СЧИТАЮТСЯ ПО ЯРУСУ ТОЧНОСТИ (2026-08-28, владелец: «выбор
           типа рифмы не отражается в показателях»). Бэк режет ключи тем же
           префиксом, каким отбор ищет пары (nlindex._префиксы_ключей), поэтому
           число дышит вместе с ручкой: шире ярус — корзин меньше и каждая
           толще. На «точной» корзина = целый ключ, подпись остаётся прежней. */
        <div style={s('font-size: 11px; color: var(--ink); font-variant-numeric: tabular-nums;')}
             title={ярус == null
                    ? 'в классике рифмовки нет — корзины по целым ключам, для справки'
                    : 'корзина — строки, среди которых маска «' + имяМаскиРифмы(ярус)
                    + '» ищет пары; ярусы исключающие: «созвучие» даёт созвучные, но не точные'
                      + (ф['крупнейшая_корзина'] ? ' · крупнейшая сейчас: ' + ч(ф['крупнейшая_корзина']) + ' строк' : '')}>
          {ч(ф['строк'])} строк <span style={s(ПОЯС)}>· {ч(ф['ключей'])}{' '}
          {ярус == null ? 'разных рифм' : 'рифмо-корзин (' + имяМаскиРифмы(ярус) + ')'}</span>
        </div>
      ) : null}
      {готов ? запас(ф) : null}
      {естьВоронка ? (
        <div style={s('display: flex; flex-wrap: wrap; align-items: baseline; gap: 3px 7px; margin-top: 3px; font-size: 9px; color: var(--muted-soft); font-variant-numeric: tabular-nums;')}
             /* ПОДПИСЬ ГОВОРИТ ТО, ЧТО ПРОИСХОДИТ СЕЙЧАС. Стояло «жребий берёт
                случайные N из M» — жребия больше нет: при прямой тяге строки
                тянутся по одной прямо из подходящих форме, и разворачивается
                только выбранная. Жребий остаётся лишь на пути со сборщиком
                НАДГРОБИЕ 2026-08-29: вторым путём был сборщик — он включался
                темой, обязательным словом или связностью. Все три вырезаны,
                путь остался один. */
             /* ХВОСТЫ ВЫРЕЗАННОГО УБРАНЫ ОТСЮДА 2026-08-30. Подпись
                дописывала «плюс якорь темы», «полоса темы» и «генератор не
                запускался» — ни темы, ни генератора в проекте нет с
                2026-08-29, а ключи `резерв`/`полоса_темы` ядро больше не
                кладёт вовсе. Экран обещал механизмы, которых нет. */
             title={ст['тяга'] != null
                       ? 'строки тянутся по одной из ' + ч(ст['пул']) + ' подходящих'
                         + (ст['перетяжек'] ? ' · перетяжек ' + ч(ст['перетяжек']) : '')
                       : 'жребий берёт случайные ' + ч(ст['жребий']) + ' из ' + ч(ст['пул'])}>
          {шаги.map(function (ш, i) {
            // жребий выделен нарочно: это 99.98% отсева и настоящая развилка
            var сам = ш[0] === 'жребий';
            return (
              <Fragment key={ш[0]}>
                {i ? <span style={s('opacity: 0.5;')}>→</span> : null}
                <span style={s(сам ? 'color: var(--ink);' : '')}>{ш[0]} {ч(ш[1])}</span>
              </Fragment>
            );
          })}
        </div>
      ) : null}
    </div>
  );
}


