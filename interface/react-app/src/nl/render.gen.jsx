// Рифмовке нужны ПОВТОРЫ букв в форме: «аа» — пара, «абв» — все вольные.
// Когда повторов нет, ярус точности на отбор не влияет вовсе — и подпись
// обязана это сказать (2026-08-28, владелец: «выбор рифмы не совсем корректно
// работает» — его форма и была Хайку «абв», ярус молча спал). Ручка, которая
// выглядит действующей и не действует, — контрол-обманка, худший класс.
function формаБезРифмовки(st) {
  var буквы = (st.stanzaSpec || []).map(function (l) { return l && l.letter; }).filter(Boolean);
  return буквы.length > 0 && new Set(буквы).size === буквы.length;
}


