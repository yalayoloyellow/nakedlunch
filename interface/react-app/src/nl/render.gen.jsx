// «ИЗ ЧЕГО ВЫБИРАЕТСЯ» — ОДНА СТРОКА (было два блока на девять строк)
// ============================================================
//
// ЗАЧЕМ ВООБЩЕ ОСТАВЛЕНО. Владелец про меню: «дохуя много лишней информации», и
// первый порыв — выбросить оба блока. Нельзя выбросить второй: замер показал,
