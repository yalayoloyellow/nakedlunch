// остальное не участвует». Ползунок выражает «не ниже» и «не выше», то есть
// ОДИН отрезок; несколько несмежных полос им не выразимы никак.
//
// ПОЧЕМУ СТО. Шкала — процентиль среди строк (см. core/редкость.py), и ячейка
// в один процент это ровно один процент корпуса. Полоса [a, b] всегда даёт
// b−a процентов — свойство построения, а не совпадение на этом корпусе.
//
// ПУСТО = ВОРОТА НЕ ЗАКРЫТЫ. Ни одна ячейка не выбрана — редкость не отбирает
// ничего, и это дефолт. «Выбрано всё» и «не выбрано ничего» дают один и тот же
// пул, но означают разное, поэтому пустое состояние подписано словами.

function ячейкиИзСтроки(строка) {
  var я = new Array(100).fill(false);
  String(строка || '').split(',').forEach(function (кус) {
    var ч = кус.trim().split('-');
    if (ч.length !== 2) return;
    var a = parseFloat(ч[0]), b = parseFloat(ч[1]);
    if (!(b > a)) return;
    for (var i = Math.max(0, Math.floor(a)); i < Math.min(100, Math.ceil(b)); i++) я[i] = true;
  });
  return я;
}

function строкаИзЯчеек(я) {
  var куски = [], i = 0;
  while (i < 100) {
    if (!я[i]) { i++; continue; }
    var a = i;
    while (i < 100 && я[i]) i++;
    куски.push(a + '-' + i);
  }
  return куски.join(',');
}

