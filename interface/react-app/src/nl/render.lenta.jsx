// С 2026-08-18 это ЕДИНСТВЕННАЯ поверхность приложения: редактор документа и
// листы вырезаны целиком (см. надгробия в Nakedlunch.jsx и render.panels.jsx).
//
// ОДНА СТРОФА ПО ЦЕНТРУ ОБЕИХ ОСЕЙ (переписано 2026-08-18, волна «экран»).
// Дословно: «Я жму интер — оно должно старое убирать, а показывать с
// центрированием по горизонтали и по вертикали. Но при этом я мог бы листать,
// если он за пределы экрана уходит». Раньше здесь стоял `лента.map(...)` по
// накапливающемуся списку — отсюда «ты мне в ленте показываешь подряд и старые
// не уходят».
//
// ПОЧЕМУ ЦЕНТРИРОВАНИЕ СДЕЛАНО `margin: auto`, А НЕ `justify-content: center`.
// У центрирования флексом есть известная беда: когда содержимое ВЫШЕ окна,
// переполнение уходит в обе стороны, и верх строфы становится недостижим —
// прокрутка вверх упирается в ноль, а текст начался выше. `margin: auto`
// съедает только ПОЛОЖИТЕЛЬНЫЙ свободный зазор: влезло — стоит по центру, не
// влезло (ода в 14 строк) — поля схлопываются в ноль, и строфа честно
// листается с самого верха. То есть центрирование пропадает ровно тогда, когда
// физически невозможно, и ни секундой раньше.
//
// ЧТО ЗДЕСЬ НАРОЧНО ПРОСТО. У строки одна-единственная кнопка — звезда, и
// текст на мышь не отвечает вовсе. Владелец дословно: «уже есть реализованный
// механизм со звездочками — мне не нравилась лишь подсветка строки при
// нажатии», и раньше: «там сейчас можно бессмысленно выделить строку одну, и с
// этим ни хуя не делается. Это просто графическое выражение, это бред».
// Поэтому серой заливки строки нет ни при наведении, ни при нажатии: текст —
// это текст, мышью он выделяется и копируется как везде.
//
// ЗВЕЗДА — КНОПКА, А НЕ ЗНАЧОК, И ОДНОВРЕМЕННО ПРИЗНАК. Она отвечает на вопрос
// «эта уже сохранена?» (ответ нужен постоянно: сохранённое больше не вернётся
// в выдачу) и она же сохраняет. Область нажатия — не меньше высоты строки, и
// это не вкусовщина: замер журнала показал, что копилка не наполнялась именно
// из-за промахов мимо крохотной звезды (453 минуты, 181 генерация, НОЛЬ
// сохранений). Повторять этот промах нельзя.
//
// ЗДЕСЬ БЫЛ ПОПАП СЛОВА — рифмы, «по звуку», синонимы, антонимы, «строкой»
// (renderПопапСлова, ~75 строк; данные — methods.слово.js, вырезан целиком).
// Клик по слову открывал список и ничего им не делал: строки ленты не
// редактируются, заменять нечего. Владелец: «попап с кликом по тексту не
// нужен». Роут бэка /api/word/suggest НЕ тронут — см. надгробие в api.js.

import { s, hov } from './style.js';

// РАЗДЕЛИТЕЛЯ БЛОКОВ БОЛЬШЕ НЕТ (2026-08-18). Он был нужен, пока в ленту
// падали три разных производителя — строфа, цепь и серия. Цепь и серия
// вырезаны решением владельца («с практической точки зрения бесполезны»;
// журнал: 29 прогонов цепи против 587 строф), а с 2026-08-18 на экране и вовсе
// одна строфа — отделять её не от чего.

// НАДГРОБИЕ: подсветка внутренней рифмы жила здесь один день
// (2026-08-27). Владелец посмотрел живьём и снял: «без спанов — с ними
// наоборот читать сложнее». Вырезана вся цепочка данных (кэш → индекс →
// строки → сюда), а не только рендер: поле без читателя — мёртвый груз.
// Флаг и ворота «внутр. рифма» живут — претензия была к чтению, не к отбору.

export function renderLenta(c) {
  var st = c.state;
  if (st.tab !== 'lenta') return null;
  // `state.lenta` — строки ТЕКУЩЕЙ строфы, а не список показанного: имя ключа
  // оставлено прежним, потому что его читает статистика в шапке (см. шапку
  // methods.lenta.js).
  var строфа = st.lenta || [];
  var C = c.cfg();
  // РАЗМЕР И ИНТЕРЛИНЬЯЖ — ТЕ ЖЕ НАСТРОЙКИ, ЧТО БЫЛИ У ДОКУМЕНТА (2026-08-18).
  // Они управляли строками редактора; редактора нет, а строки остались — здесь.
  // Выбросить их значило бы отнять у него единственную ручку размера текста,
  // оставить в настройках без потребителя — соврать. Ширина колонки приходит
  // тем же путём, что и раньше: --content-max-width (applyTheme).
  var кегль = Math.max(11, Math.min(40, parseFloat(C.textSize) || 15));
  var интер = Math.max(1.2, Math.min(2.4, parseFloat(C.lineGap) || 1.5));
  var шрифт = (C.docFont && C.docFont !== 'как интерфейс')
    ? "'" + C.docFont + "', ui-monospace, Menlo, monospace" : 'inherit';
  // Область нажатия звезды = высота строки (нижний порог — на случай мелкого
  // кегля: 20 px это всё ещё промахиваемо, но уже не мишень в 8 px).
  var H = Math.max(20, Math.round(кегль * интер));

  // Блок строфы: шире --content-max-width не растёт, уже — по самой длинной
  // строке. `margin: auto` центрирует его и по горизонтали, и по вертикали.
  var блокStyle = 'margin: auto; max-width: min(var(--content-max-width), 100%); '
    + 'padding: 24px 28px; font-size: ' + кегль + 'px; line-height: ' + интер
    + '; font-family: ' + шрифт + ';';

  return (
    <div style={s('position: relative; z-index: 1; flex: 1; min-width: 0; display: flex; '
                + 'flex-direction: column; min-height: 0;')}>
      {/* ГРАНИЦЫ КОЛОНКИ ВИДНЫ, ПОКА ОТКРЫТА ПАНЕЛЬ С РУЧКОЙ (2026-08-28).
          Владелец: «сломана концепция ширины колонки». Ручка работала всю
          дорогу (кнопка → --content-max-width → перенос длинных строк), но на
          коротких строках стиха эффект невидим: блок сжимается по самой
          длинной строке, и клик выглядел пустым. Волосяные края показывают
          колонку в момент настройки и уходят вместе с панелью — ручка больше
          не молчит о том, чем управляет. */}
      {st.openPill === 'cfg' ? (
        <div style={s('position: absolute; top: 0; bottom: 0; left: 0; right: 0; margin: 0 auto; '
                    + 'max-width: min(var(--content-max-width), 100%); pointer-events: none; '
                    + 'border-left: 1px solid var(--border-soft); '
                    + 'border-right: 1px solid var(--border-soft); opacity: .45;')} />
      ) : null}
      <section ref={c.lentaRef} data-noscrollbar="1"
               style={s('flex: 1; min-height: 0; overflow-y: auto; overflow-x: hidden; display: flex;')}>
        <div style={s(блокStyle)}>
        {!строфа.length ? (
          /* ПУСТОЙ ЭКРАН ГОВОРИТ ОДНУ ВЕЩЬ — но не тогда, когда работа ИДЁТ.
             Здесь стояли три строки подсказок, и две из них врали: «стрелки —
             по строкам» и «клик по слову — рифмы и синонимы». Остальное живёт
             в подсказке внизу (render.panels.jsx), дублировать её незачем.

             СОСТОЯНИЕ РАБОТЫ ДОБАВЛЕНО 2026-08-21 по требованию владельца:
             «на главном экране написано нажми интер и получишь результат, но я
             жму и опять ничего не происходит, а данные о том, что строфа
             готовится, только в верхней панели, которая в этот момент невидима,
             так как мышка не наведена — это не ок».
             Правило то же, что у чистки: если работа идёт, её видно ТАМ, КУДА
             СМОТРЯТ, а не там, где удобно нарисовать. */
          <div style={s('opacity: .35; white-space: nowrap;')}>{c.лентаЖдёт()}</div>
        ) : строфа.map(function (r, i) {
          var есть = c.строкаВИзбранном(r.text);
          return (
            <div key={i} style={s('display: flex; gap: 8px; align-items: flex-start;')}>
              {/* ЗВЕЗДА СПРАВА ОТ СТРОКИ (2026-08-28, владелец: «значки
                  звёздочки… справа должен быть, а не слева»). Текст первым,
                  звезда после: строки читаются с левого края без частокола
                  кнопок перед ними, а звёзды выстраиваются рейкой по правому
                  краю блока. */}
              <span style={s('flex: 1 1 auto; min-width: 0;')}>{r.text}</span>
              {/* ЕДИНСТВЕННЫЙ ОБРАБОТЧИК СОХРАНЕНИЯ на весь экран. Способ
                  вызова уже менялся (пробел → клик по строке → звезда), и
                  менять его снова должно стоить одной строки здесь: вся
                  работа — в `сохранитьСтроку` (methods.lenta.js).
                  onMouseDown гасит фокус: иначе после клика кнопка остаётся
                  сфокусированной, и следующий ↵ сделал бы ДВА дела разом —
                  нажал звезду и выдал строфу.
                  tabIndex=-1 — потому что клавиатурного пути в избранное нет
                  вовсе (пробел вырезан как неоднозначный без курсора по
                  строкам), а фокус, который никуда не ведёт, — обещание. */}
              <button type="button" tabIndex={-1}
                      onMouseDown={function (e) { e.preventDefault(); }}
                      onClick={function () { c.сохранитьСтроку(i); }}
                      title={есть ? 'уже в избранном' : 'в избранное'}
                      aria-label={есть ? 'уже в избранном' : 'в избранное'}
                      /* !important обязателен: инлайновый стиль перебивает
                         правило класса, и без него наведение было бы немым. */
                      className={hov('opacity: 1 !important;')}
                      style={s('appearance: none; border: none; background: none; padding: 0; '
                             + 'flex: 0 0 auto; width: ' + H + 'px; height: ' + H + 'px; '
                             + 'display: flex; align-items: center; justify-content: center; '
                             + 'font-family: inherit; font-size: .85em; line-height: 1; '
                             + 'color: var(--ink); cursor: pointer; '
                             + 'transition: opacity 140ms var(--ease); '
                             + 'opacity: ' + (есть ? '.8' : '.16') + ';')}>★</button>
            </div>
          );
        })}
        {/* СТРОФА УЖЕ ЕСТЬ, А РАБОТА ИДЁТ — второй случай того же требования.
            В тёплом прогоне это 53 мс и строка мелькнёт незаметно; в холодном
            (буфер пуст после смены настроек) это секунды, и без неё экран снова
            выглядел бы так, будто ↵ не нажимался. Тот же кегль и та же
            прозрачность, что у пустого экрана: это не украшение, а тот же
            единственный признак работы, только на своём месте. */}
        {строфа.length && (st.genBusy || c.разогревИдёт()) ? (
          <div style={s('opacity: .35; white-space: nowrap; padding-top: 6px;')}>
            {c.лентаЖдёт()}
          </div>
        ) : null}
        </div>
      </section>
    </div>
  );
}
