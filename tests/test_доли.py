@нужен_большой_индекс
def test_доли_клаузул_доезжают_до_выдачи():
    """Заказ «мужская 20 · женская 50 · дактилическая 30» на сорока строках.

    Допуск ±5 процентных пунктов. Он был бы вдвое шире, если бы партнёр по
    рифме не предпочитал концовку первой строки группы: на широких ярусах
    ключи разной длины дают разные концовки, и заказ «только дактилическая»
    размывался до 75%. Теперь партнёр берёт ту же концовку, когда такая пара
    есть, и живой замер держит ровно заказанное (20/50/30 → 20/50/30,
    «4:100» → 100% дактилических)."""
    idx = nlindex.load()
    table_ids, _ = nlindex._таблица(idx, False, False, 7)
    веса = доли.разобрать("1:20,2:50,4:30", 7)
    строки = nlindex.тянуть_строфы(idx, table_ids, [(5, 9), (5, 9)], "аа", 40,
                                   np.random.default_rng(7),
                                   ярусы_рифмы=3, доли_клаузул=веса)
    assert len(строки) == 40, "тяга не собрала выдачу — замер бессмыслен"
    счёт = {1: 0, 2: 0, 3: 0}
    for r in строки:
        к = scan.clausula(r.get("rhyme", ""))
        if к in счёт:
            счёт[к] += 1
    всего = sum(счёт.values())
    доля = {к: 100 * v / всего for к, v in счёт.items()}
    for к, ждём in ((1, 20), (2, 50), (3, 30)):
        assert abs(доля[к] - ждём) <= 5, \
            f"клаузула {к}: {доля[к]:.0f}% против заказанных {ждём}% ({счёт})"


@нужен_большой_индекс
def test_без_долей_пропорция_своя():
    """Обратная сторона: без долей тяга НЕ обязана держать пропорцию — она
    берёт равновероятно по форме. Иначе сторож выше зеленел бы и на коде,
    который доли игнорирует."""
    idx = nlindex.load()
    table_ids, _ = nlindex._таблица(idx, False, False, 7)
    строки = nlindex.тянуть_строфы(idx, table_ids, [(5, 9), (5, 9)], "аа", 40,
                                   np.random.default_rng(7), ярусы_рифмы=3)
    счёт = {1: 0, 2: 0, 3: 0}
    for r in строки:
        к = scan.clausula(r.get("rhyme", ""))
        if к in счёт:
            счёт[к] += 1
    доля_муж = 100 * счёт[1] / max(1, sum(счёт.values()))
    assert abs(доля_муж - 20) > 5, \
        f"без долей вышло ровно заказанное — значит доли не при чём ({счёт})"


@нужен_большой_индекс
def test_одна_доля_берёт_всё():
    """«Только дактилическая» — сто процентов, а не «в основном». Именно здесь
    видно, держит ли партнёр по рифме концовку первой строки группы."""
    idx = nlindex.load()
    table_ids, _ = nlindex._таблица(idx, False, False, 7)
    строки = nlindex.тянуть_строфы(idx, table_ids, [(5, 9), (5, 9)], "аа", 30,
                                   np.random.default_rng(3), ярусы_рифмы=3,
                                   доли_клаузул=доли.разобрать("4:100", 7))
    концовки = {scan.clausula(r.get("rhyme", "")) for r in строки}
    assert концовки == {3}, f"заказана только дактилическая, вышли {концовки}"
