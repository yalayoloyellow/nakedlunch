# ДОЛИ: многовыборность со весами (2026-08-29).
#
# Слово владельца: «может я хочу 20 процентов где на первое слово рифма,
# 50 процентов в середине и 30 процентов в конце… многовыборность это важный
# принцип». В строфе рифмопар одна-две, и 20% от двух пар — 0.4 пары; поэтому
# доли держатся не броском монеты, а распределением остатка (память недобора).
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))
import доли  # noqa: E402


def test_пустая_строка_это_поровну_по_маске():
    assert доли.разобрать("", 1 | 4) == {1: 0.5, 4: 0.5}
    assert доли.разобрать(None, 1) == {1: 1.0}
    assert доли.разобрать("", 0) == {}


def test_проценты_нормируются():
    в = доли.разобрать("1:20,2:50,4:30", 1 | 2 | 4)
    assert (round(в[1], 3), round(в[2], 3), round(в[4], 3)) == (0.2, 0.5, 0.3)
    # человек ввёл сумму не сто — это не повод отказывать
    в2 = доли.разобрать("1:20,2:50,4:40", 1 | 2 | 4)
    assert round(sum(в2.values()), 6) == 1.0
    assert в2[4] > в2[1]


def test_маска_главнее_строки():
    """Сорт, выключенный чипом, не воскресает из сохранённых долей."""
    в = доли.разобрать("1:50,8:50", 1)
    assert в == {1: 1.0}, "погасший бит вернулся из строки"


def test_мусор_не_роняет():
    assert доли.разобрать("чушь", 1 | 2) == {1: 0.5, 2: 0.5}
    assert доли.разобрать("1:abc,2:", 1 | 2) == {1: 0.5, 2: 0.5}
    assert доли.разобрать("1:-5,2:10", 1 | 2) == {1: 0.0, 2: 1.0}


def test_доли_сходятся_на_коротком_отрезке():
    """Главное свойство: 20/50/30 обязаны дать ровно 2/5/3 на десяти слотах,
    а не «в среднем когда-нибудь». Чистый жребий этого не гарантирует."""
    ж = доли.Жребий(доли.разобрать("1:20,2:50,4:30", 1 | 2 | 4))
    счёт = {1: 0, 2: 0, 4: 0}
    for _ in range(10):
        с = ж.следующий()
        счёт[с] += 1
        ж.взять(с)
    assert счёт == {1: 2, 2: 5, 4: 3}, счёт


def test_на_двух_слотах_берётся_крупнейшая_доля():
    """Строфа с двумя парами: 20/50/30 в неё не влезают, и жребий обязан
    отдать слоты самым весомым сортам, а не случайным."""
    ж = доли.Жребий(доли.разобрать("1:20,2:50,4:30", 1 | 2 | 4))
    взято = []
    for _ in range(2):
        с = ж.следующий()
        взято.append(с)
        ж.взять(с)
    assert взято == [2, 4], взято


def test_недоступный_сорт_не_теряет_очередь():
    """Сорта нет в материале — слот уходит следующему, но долг сохраняется,
    и как только сорт появится, он своё возьмёт."""
    ж = доли.Жребий(доли.разобрать("1:50,2:50", 1 | 2))
    нет_единицы = {2}
    for _ in range(4):
        с = ж.следующий(доступен=lambda б: б in нет_единицы)
        assert с == 2
        ж.взять(с)
    # долг первого копился всё это время — теперь он первый в очереди
    assert ж.следующий() == 1


def test_запись_читается_обратно():
    в = доли.разобрать("1:25,8:75", 1 | 8)
    строка = доли.записать(в)
    assert строка == "1:25,8:75"
    assert доли.разобрать(строка, 1 | 8) == в


