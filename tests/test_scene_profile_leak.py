# nakedlunch — профиль СЦЕНЫ не должен хранить модель генерации (Раунд 50/51).
#
# ЭТОТ БАГ СЛУЧАЛСЯ ДВАЖДЫ, второй раз — в тот же день, что и починка.
#
# Профиль сцены фристайла снимает состояние по принципу «всё, кроме
# перечисленного». Такой запрет надо ПОМНИТЬ, и его дважды забыли:
#   1. Не были исключены chain/params/junctions/threshold — и на диске
#      владельца осел «профиль 1» с чужой цепочкой из шести ролей,
#      «Источники 0.9» при живом значении 1.0 и полями limit:10 /
#      pipeRuns:5000 / threshold:0.35, удалёнными ещё в Раундах 47-49.
#      Применение такого профиля молча перезаписывало цепочку и воскрешало
#      порог, который в первом живом прогоне резал выдачу почти в ноль.
#   2. Через несколько часов три новые полки добавили десять ключей — и ни
#      один снова не попал в запрет.
#
# Структурная починка: список ключей модели живёт РЯДОМ С МОДЕЛЬЮ
# (methods.shelves.js: КЛЮЧИ_МОДЕЛИ) и подмешивается в запрет автоматически.
# Тест сторожит то, что автоматикой не закрыть: что новый ключ модели вообще
# попал в этот список.
#
# Тест читает исходники фронта текстом — сборка тут не поможет: она зелёная и
# при утечке, потому что синтаксически всё в порядке. Ровно тот случай, о
# котором в проекте уже записано: зелёный build не значит рабочий код.
#
# Прогон: .venv/bin/python -m pytest tests/test_scene_profile_leak.py -q

import re
from pathlib import Path

import pytest

NL = Path(__file__).resolve().parent.parent / "interface" / "react-app" / "src" / "nl"
СОСТОЯНИЕ = NL / "Nakedlunch.jsx"
ПОЛКИ = NL / "methods.shelves.js"
ПРОФИЛИ = NL / "methods.fsprofiles.js"

# Приставки ключей, которые ПО ОПРЕДЕЛЕНИЮ принадлежат модели генерации, а не
# сцене. Любой такой ключ обязан быть в КЛЮЧИ_МОДЕЛИ.
ПРИСТАВКИ = ("chain", "knob", "ref", "stanza", "junction", "param", "series", "curve")

# Ключи с этими приставками, которые к модели НЕ относятся — исключения
# перечислены поимённо, чтобы новое исключение требовало осознанного решения.
НЕ_МОДЕЛЬ = {
    "refresh",          # если появится: обновление, не референс
}


def ключи_модели() -> set[str]:
    текст = ПОЛКИ.read_text("utf-8")
    m = re.search(r"export const КЛЮЧИ_МОДЕЛИ = \[(.*?)\];", текст, re.S)
    assert m, "КЛЮЧИ_МОДЕЛИ не найден — список ключей модели переименовали или удалили"
    return set(re.findall(r"'([^']+)'", m.group(1)))


def ключи_состояния() -> set[str]:
    """Имена полей из литерала `state = {…}`. Разбор грубый (регулярка по
    идентификаторам перед двоеточием) и намеренно СКЛОНЕН К ПЕРЕБОРУ: лишнее
    имя в выборке даст лишнюю проверку, пропущенное — дыру. Лучше первое."""
    текст = СОСТОЯНИЕ.read_text("utf-8")
    i = текст.index("state = {")
    # литерал состояния кончается первым `};` на отступе метода класса
    j = текст.index("\n  };", i)
    блок = текст[i:j]
    # комментарии выкусываем ДО разбора: ключ, за которым стоит поясняющий
    # комментарий, иначе не находится — и дыра появляется ровно там, где
    # разработчик потрудился объяснить, что делает поле
    блок = re.sub(r"/\*.*?\*/", ",", блок, flags=re.S)
    блок = re.sub(r"//[^\n]*", "", блок)
    # ключи литерала — те, что идут после `{` или `,`; вложенные объекты сюда
    # тоже попадут, и это СОЗНАТЕЛЬНО: лишнее имя даст лишнюю проверку,
    # пропущенное — дыру
    return set(re.findall(r"[{,]\s*([A-Za-zА-Яа-я_][\w]*)\s*:", блок))


def test_klyuchi_modeli_ne_pusty():
    """Опора всего файла: если список пуст или не разобрался, остальные тесты
    зелёные и бессмысленные."""
    к = ключи_модели()
    assert len(к) > 20, f"разобралось подозрительно мало ключей: {len(к)}"
    assert {"chain", "params", "knobMode", "refText"} <= к


def test_sostoyanie_razobralos():
    с = ключи_состояния()
    assert len(с) > 50, f"разобралось подозрительно мало полей состояния: {len(с)}"
    assert {"doc", "chain", "params"} <= с


def test_kazhdyy_klyuch_modeli_v_spiske():
    """ГЛАВНЫЙ. Любое поле состояния с приставкой модели обязано быть в
    КЛЮЧИ_МОДЕЛИ — иначе профиль сцены снимет его и станет вторым, невидимым
    хранилищем настроек генерации."""
    модель, состояние = ключи_модели(), ключи_состояния()
    подозрительные = {
        k for k in состояние
        if k.lower().startswith(ПРИСТАВКИ) and k not in НЕ_МОДЕЛЬ
    }
    забытые = подозрительные - модель
    assert not забытые, (
        "поля состояния относятся к модели генерации, но не внесены в "
        f"КЛЮЧИ_МОДЕЛИ (methods.shelves.js): {sorted(забытые)}. "
        "Без этого профиль сцены фристайла снимет их в свой снимок и при "
        "применении перезапишет живые настройки — это уже случалось дважды."
    )


def test_zapret_podmeshivaetsya_avtomaticheski():
    """Список не должен переписываться руками во второй раз: подмешивание
    обязано быть в коде, а не в комментарии."""
    текст = ПРОФИЛИ.read_text("utf-8")
    assert "КЛЮЧИ_МОДЕЛИ" in текст, "профиль сцены не импортирует список ключей модели"
    assert re.search(r"КЛЮЧИ_МОДЕЛИ\.forEach\(.*?PROF_SKIP_STATE", текст, re.S), \
        "ключи модели не подмешиваются в PROF_SKIP_STATE — запрет снова ручной"


@pytest.mark.parametrize("ключ", [
    "chain", "chainForms", "chainKnobs", "junctions", "params",
    "knobProfile", "knobMode", "refText", "refPct", "refChain",
    # поля, вырезанные в Раундах 47-50: в живом состоянии их нет, но в СТАРОМ
    # файле профиля сцены на диске они лежат и без запрета вернулись бы
    "threshold", "limit", "pipeRuns", "poolPer", "pipeW", "runs", "filters",
])
def test_izvestnye_utechki_zakryty(ключ):
    """Поимённо — те ключи, что реально утекли в data/settings.json владельца."""
    assert ключ in ключи_модели(), f"ключ {ключ!r} снова не под запретом"
