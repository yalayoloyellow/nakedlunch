# ── СЦЕНА ФРИСТАЙЛА ВЕЗЁТ ВСЕ ОСИ НАСТРОЕК, А НЕ ЧАСТЬ ──────────────────────
#
# ЧТО БЫЛО (найдено разбором 2026-09-02). `fsНастройки` собирала для сцены
# режим, крутилки, каркас и ПОЛОСЫ — а ДОЛИ не собирала вовсе. Из-за этого:
#
#   · сцена генерировала без долей клаузул, позиции и ярусов рифмы, хотя ядро
#     их читает и они правят выдачу (замер: 21/19 → 35/5 → 5/35);
#   · кнопка «взять настройки строфы из редактора» их МОЛЧА ТЕРЯЛА. Человек
#     выставлял «20 процентов на первое слово, 50 в середине, 30 в конце»,
#     нажимал перенос — и во фристайле стояла пропорция, которую он не заказывал.
#
# Болезнь та же, что у профиля сцены выше: набор полей перечислен руками, и
# новую ось в него забыли. Здесь автоматикой это не закрыть — поля разные по
# смыслу, — поэтому сторожит тест: каждая ось настроек строфы обязана быть во
# ВСЕХ четырёх местах пути.

ОСИ_СЦЕНЫ = ("fsParams", "fsSpec", "fsПолосы", "fsДоли")


def _fs_js() -> str:
    return (NL / "methods.fs.js").read_text("utf-8")


def _кусок(текст: str, имя: str) -> str:
    """Тело метода `имя` — от его объявления до следующего на том же уровне."""
    н = текст.index(f"  {имя}(")
    к = текст.find("\n  },", н)
    assert к > н, f"не найден конец метода {имя}"
    return текст[н:к]


def test_отделение_сцены_везёт_все_оси():
    """`fsНастройки` — место, где сцена отделяется от редактора. Пропущенная
    здесь ось означает, что сцена генерирует по чужой настройке и молчит."""
    тело = _кусок(_fs_js(), "fsНастройки")
    for ось in ОСИ_СЦЕНЫ:
        assert ось in тело, (
            f"{ось} нет в fsНастройки — сцена не получит эту ось настроек и "
            f"будет генерировать по умолчанию, не сказав об этом")
    # и отдаёт их наружу, а не только кладёт в состояние
    for ключ in ("полосы:", "доли:"):
        assert ключ in тело, f"fsНастройки не отдаёт {ключ} вызывающему"


def test_перенос_из_редактора_везёт_все_оси():
    """Кнопка «взять настройки строфы из редактора» обязана взять ВСЁ.
    Половина перенесённых настроек хуже неперенесённых: человек уверен, что
    сцена крутится по его строфе, а она крутится по половине его строфы."""
    тело = _кусок(_fs_js(), "fsВзятьИзРедактора")
    for ось in ОСИ_СЦЕНЫ:
        assert ось in тело, (
            f"{ось} не переносится кнопкой «взять настройки строфы из редактора» "
            f"— перенос теряет эту ось молча")


def test_подпись_буфера_учитывает_все_оси():
    """`fsGenKey` — подпись, по которой выбрасывается буфер при смене настроек.
    Ось, забытая здесь, означает: настройку сменили, а сцена ещё десятки строк
    крутит выдачу, набранную по старой. Это уже случалось с крутилками звена —
    разбор в комментарии над `fsGenKey`."""
    тело = _кусок(_fs_js(), "fsGenKey")
    for ключ in ("проф.spec", "проф.полосы", "проф.доли"):
        assert ключ in тело, f"{ключ} не входит в подпись буфера сцены"


def test_запрос_фристайла_несёт_все_оси():
    """Последнее звено: то, что реально уходит на сервер."""
    js = _fs_js()
    н = js.index("source: 'freestyle'")
    payload = js[н:js.index("};", н)]
    for ключ in ("mode:", "params:", "полосы:", "доли:"):
        assert ключ in payload, f"{ключ} не уходит в запрос генерации фристайла"
