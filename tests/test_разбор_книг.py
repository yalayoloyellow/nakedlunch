# ---- txt и md: те же беды, другой путь -------------------------------------
#
# Вопрос владельца: «а почему не работает на txt и md? вдруг там такое
# встретится? вдруг это кривой какой-то перенос?»
#
# Он был прав дважды. Снималка маркеров стояла в разборе fb2 и обходила txt и
# md стороной, а перенос слова через строку не сращивался вовсе. Обе правки
# переехали в `clean_text` — через него проходит текст ВСЕХ форматов
# (`store.add_corpus` зовёт его первым делом).

def тхт(tmp_path, текст: str, имя="книга.txt") -> Path:
    p = tmp_path / имя
    p.write_text(текст, "utf-8")
    return p


def test_маркеры_снимаются_и_в_txt(tmp_path):
    """Снималка жила в `_текст_абзаца`, то есть работала только на fb2. А
    «[47]» и «{24}» попадаются в любом тексте, снятом с книги."""
    т = разобрать(тхт(tmp_path,
        "В первом томе своих «Осколков» [47] профессор Мюллер клеймит Веды.\n"
        "Их легко победить {24} . Противник не знает, где он будет сражаться.\n"))
    assert "[47]" not in т and "{24}" not in т, т
    assert "профессор Мюллер клеймит" in т and "Противник не знает" in т


def test_маркеры_снимаются_и_в_md(tmp_path):
    """md идёт тем же путём, что txt, — но проверяется отдельно: «идёт тем же
    путём» это утверждение о коде, а тест обязан проверять исход."""
    т = разобрать(тхт(tmp_path, "## Глава\n\nтекст со ссылкой [12] внутри строки\n",
                              имя="книга.md"))
    assert "[12]" not in т and "текст со ссылкой" in т, т


def test_перенос_слова_сращивается(tmp_path):
    """В txt, снятом со скана или из вёрстки, слово рвётся дефисом на границе
    строки: «пере-\nнос». Схлопывание пробелов давало «пере- нос» — висячий
    дефис и два обломка вместо слова. В fb2 такого нет: там абзац цельный."""
    т = разобрать(тхт(tmp_path,
        "А это обычный текст с пере-\nносом слова через строку.\n"))
    assert "пере- нос" not in т, f"висячий дефис остался: {т!r}"
    assert "переносом слова" in т, f"слово не срослось: {т!r}"


def test_тире_на_конце_строки_не_сращивается(tmp_path):
    """ГРАНИЦА ПРАВИЛА. Тире — это знак речи, а не перенос:
    «Он сказал —\nИ замолчал» обязано остаться двумя мыслями."""
    т = разобрать(тхт(tmp_path, "Он сказал —\nИ замолчал надолго.\n"))
    assert "сказал — И замолчал" in т, f"тире съедено как перенос: {т!r}"


def test_заглавная_после_переноса_не_сращивается(tmp_path):
    """Заглавная буква после дефиса и перевода строки — начало новой мысли, а
    не хвост разорванного слова. Сращивать её значило бы склеить два
    предложения в одно несуществующее слово."""
    т = разобрать(тхт(tmp_path, "какой-то список чего-\nНовая строка тут.\n"))
    assert "чегоНовая" not in т, f"склеены разные мысли: {т!r}"


def test_дефис_внутри_строки_цел(tmp_path):
    """«какой-то», «что-нибудь» — обычные слова. Правило срабатывает ТОЛЬКО на
    границе строки, и это надо сторожить: дефис в русском тексте частый."""
    т = разобрать(тхт(tmp_path, "он взял какой-то предмет и что-нибудь ещё\n"))
    assert "какой-то" in т and "что-нибудь" in т, т


def test_союз_после_дефиса_не_склеивается(tmp_path):
    """ГРАНИЦА, ЗАМЕРЕННАЯ ПО ЖИВОМУ КОРПУСУ. «микро- и макрокосм» — законный
    висячий дефис, а не разорванное слово: из 131 висячего дефиса в складе
    владельца 58 (44%) стоят перед союзом. Ляг такой оборот на границу строки —
    и наивное правило дало бы «микроимакрокосм»."""
    т = разобрать(тхт(tmp_path, "полюса микро-\nи макрокосма, можно назвать\n"))
    assert "микроимакрокосма" not in т, f"союз склеен: {т!r}"
    assert "микро- и макрокосма" in т, т


def test_двух_или_трехлетнего_цело(tmp_path):
    """Второй по частоте союз в этой позиции — «или» (11 случаев)."""
    т = разобрать(тхт(tmp_path, "признаки двух-\nили трехлетнего периода\n"))
    assert "двух- или трехлетнего" in т, т


# ---- дефис бывает не только ASCII ------------------------------------------
#
# Вопрос владельца: «вдруг это кривой какой-то перенос?» Кривой он ровно в этом:
# текст из вёрстки или PDF носит юникодные дефисы, и правило по ASCII их не
# видело. Порча выходила ТИШЕ ASCII-случая — без висячего дефиса, а значит и
# без единой приметы, по которой её потом опознать.

def test_юникодный_дефис_U2010_сращивается(tmp_path):
    т = разобрать(тхт(tmp_path, "текст с пере\u2010\nносом слова тут\n"))
    assert "переносом слова" in т, f"U+2010 не сросся: {т!r}"


def test_неразрывный_дефис_U2011_сращивается(tmp_path):
    т = разобрать(тхт(tmp_path, "текст с пере\u2011\nносом слова тут\n"))
    assert "переносом слова" in т, f"U+2011 не сросся: {т!r}"


def test_мягкий_перенос_сращивается(tmp_path):
    """U+00AD невидим и значит РОВНО «здесь можно разорвать» — самый частый
    след вёрстки. Сращивается безусловно: оборотом «микро- и» он не бывает."""
    т = разобрать(тхт(tmp_path, "текст с пере\u00ad\nносом слова тут\n"))
    assert "переносом слова" in т, f"мягкий перенос не сросся: {т!r}"


def test_мягкий_перенос_вне_переноса_выброшен(tmp_path):
    """Уцелевший внутри строки он невидим, но рвёт слово надвое при разбивке
    на токены — то есть портит и рифму, и счёт знаменательных слов.

    Сторожит ИСХОД, а не строку: снимает его белый список символов в конце
    `clean_text`, а не отдельное правило (отдельное правило тут стояло и снято
    как мёртвое). Доказан ломкой именно белого списка."""
    т = разобрать(тхт(tmp_path, "обычное сло\u00adво в середине строки\n"))
    assert "\u00ad" not in т and "слово в середине" in т, repr(т)


def test_юникодный_дефис_тоже_щадит_союз(tmp_path):
    """Исключение на союзы обязано работать и после приведения к ASCII —
    иначе правило чинило бы один формат и ломало другой."""
    т = разобрать(тхт(tmp_path, "полюса микро\u2010\nи макрокосма тут\n"))
    assert "микроимакрокосма" not in т, f"союз склеен: {т!r}"


# ---- стадия 1: кодировка ---------------------------------------------------
#
# Замысел владельца: «какой бы формат я ни залил, он должен становиться txt без
# проблем, спокойно вообще». Читалось `read_text("utf-8", errors="replace")`, и
# русский txt в cp1251 заливался МОЛЧА ИСПОРЧЕННЫМ: кириллица выбрасывалась
# как нечитаемая, белый список добивал остаток, в склад ложилось «, , .».
