# nakedlunch — РАЗБОР КНИГ: что приходит из fb2 в корпус (2026-08-21).
#
# ЗАЧЕМ ЭТОТ ФАЙЛ. Владелец спросил прямо: «проблема ещё в том, чтобы ты
# понимал, как работает, когда заливаешь книгу, в которой есть картинки, есть
# какая-то разметка и прочая хуйня, оглавления и прочие залупы» — и приложил
# девять настоящих книг.
#
# Проверка по ним нашла две настоящие порчи текста, обе про сноски. Здесь они
# зафиксированы на маленьких fb2, собранных руками: настоящих книг в
# репозитории нет и быть не должно (они лежат в `тест-книги/`, под gitignore),
# а сторож обязан работать на любой машине.
#
# ЧТО ПРОВЕРЕНО НА ЖИВЫХ КНИГАХ И НЕ ПОВТОРЯЕТСЯ ЗДЕСЬ:
#   · картинки (`<binary>`, base64) в текст не попадают — разбор берёт только
#     `<p>` и `<v>`, и на девяти книгах с 39 картинками не пришло ни одной;
#   · титульная часть и оглавления не протекли ни в одной из девяти: грубое
#     «отрезать первые 25 абзацев» на этом наборе отрабатывает;
#   · после заливки кнопке «почистить» делать нечего (0 у семи книг, 2 у двух).
#
# Прогон: .venv/bin/python -m pytest tests/test_разбор_книг.py -q

import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "core"))

from nlsrc.cutter import parse_source_file  # noqa: E402

ШАПКА = ('<?xml version="1.0" encoding="utf-8"?>\n'
         '<FictionBook xmlns="http://www.gribuser.ru/xml/fictionbook/2.0" '
         'xmlns:l="http://www.w3.org/1999/xlink">')


def книга(tmp_path, абзацы: list[str], лишние: bool = True) -> Path:
    """Маленький fb2. `лишние` добивает начало до 25 абзацев — их разбор
    отрезает как титульную часть, и без добивки проверяемое исчезло бы."""
    вступление = [f"<p>служебная строка {i}</p>" for i in range(25)] if лишние else []
    тело = "".join(вступление) + "".join(абзацы)
    p = tmp_path / "проба.fb2"
    p.write_text(f"{ШАПКА}<body>{тело}</body></FictionBook>", "utf-8")
    return p


# ---- сноски тегом ----------------------------------------------------------

def test_маркер_сноски_тегом_не_попадает_в_текст(tmp_path):
    """НАЙДЕНО НА «РАЗОБЛАЧЁННОЙ ИЗИДЕ». В fb2 ссылка на сноску размечена так:

        производят Софию,<a l:href="#n_166" type="note">[166]</a> завершая

    Прежний разбор тянул и текст ссылки, и в корпус попадало «в свою очередь
    производят Софию,[166» — обломок номера посреди фразы. Таких ссылок в той
    книге 776, и каждая портила соседний текст."""
    ф = книга(tmp_path, ['<p>производят Софию,'
                         '<a l:href="#n_166" type="note">[166]</a>'
                         ' завершая этим Тетрактис</p>'])
    т = parse_source_file(ф)
    assert "166" not in т, f"маркер сноски остался: {т!r}"
    assert "производят Софию" in т and "завершая этим Тетрактис" in т, (
        f"фраза порвалась вместе с маркером: {т!r}")


def test_маркер_сноски_БЕЗ_скобок_тоже_снимается(tmp_path):
    """ЭТОТ СЛУЧАЙ ЛОВИТ ТОЛЬКО ТЕГ, И БЕЗ НЕГО ТЕСТ ВЫШЕ ОБМАНЫВАЛ.

    Поймано ломкой: первый вариант проверки использовал маркер «[166]», а его
    подхватывала ВТОРАЯ защита — снималка литеральных скобок. Отключаешь
    обработку тега — тест всё равно зелёный, потому что скобки съедает regex.
    Два механизма прикрывали друг друга, и ни один по-настоящему не сторожился.

    Маркер без скобок — надстрочный номер или звёздочка — есть только у тега, и
    regex его не видит."""
    ф = книга(tmp_path, ['<p>производят Софию'
                         '<a l:href="#n_166" type="note">166</a>'
                         ' завершая этим Тетрактис</p>',
                         '<p>и добавил<a l:href="#n_1" type="note">*</a> к сказанному</p>'])
    т = parse_source_file(ф)
    assert "166" not in т, f"маркер без скобок остался: {т!r}"
    assert "*" not in т, f"звёздочка-сноска осталась: {т!r}"
    assert "производят Софию" in т and "завершая этим Тетрактис" in т
    assert "и добавил" in т and "к сказанному" in т


def test_обычная_ссылка_остаётся(tmp_path):
    """Выбрасываем ТОЛЬКО `type="note"`. Обычная ссылка внутри текста в fb2
    почти не встречается, но её текст — слова автора, а не указатель."""
    ф = книга(tmp_path, ['<p>смотри <a l:href="#gl2">вторую главу</a> внимательно</p>'])
    т = parse_source_file(ф)
    assert "вторую главу" in т, f"съеден текст обычной ссылки: {т!r}"


# ---- сноски литералом ------------------------------------------------------

def test_маркер_литералом_снимается(tmp_path):
    """ВТОРАЯ ПОРЧА, И ТЕГ ЕЁ НЕ ЛОВИТ. Часть сносок в живых книгах размечена
    прямо текстом:

        «В первом томе своих «Осколков» [<strong>47</strong>] профессор Мюллер»
        «…их легко победить {24} .»                            (Сунь-цзы)

    Скобка, внутри которой одни цифры, русской прозой не бывает никогда.
    Замер: 608 порченых фрагментов у Блаватской и 74 у Сунь-цзы; после
    правки 18 и 0."""
    ф = книга(tmp_path, ['<p>своих «Осколков» [<strong>47</strong>] профессор Мюллер клеймит</p>',
                         '<p>их легко победить {24} . Противник не знает</p>',
                         '<p>смотри примечания [166, 167] и далее по тексту</p>'])
    т = parse_source_file(ф)
    for мусор in ("[47]", "{24}", "[166, 167]", "47]", "{24"):
        assert мусор not in т, f"остался маркер {мусор!r}: {т!r}"
    assert "профессор Мюллер клеймит" in т and "Противник не знает" in т


def test_скобка_с_буквами_не_трогается(tmp_path):
    """ГРАНИЦА ПРАВИЛА. «[так в оригинале]», «(и это правда)» — это речь, а не
    указатель. Режем только скобки, внутри которых НЕТ ни одной буквы."""
    ф = книга(tmp_path, ['<p>он сказал [так в оригинале] и вышел вон</p>',
                         '<p>она молчала (и это было страшно) целый вечер</p>'])
    т = parse_source_file(ф)
    assert "[так в оригинале]" in т and "(и это было страшно)" in т, т


def test_маркер_заменяется_пробелом_а_не_пустотой(tmp_path):
    """Иначе «Софию[166]завершая» склеилось бы в одно несуществующее слово, и
    порча стала бы тише, но хуже: её уже не видно глазом."""
    ф = книга(tmp_path, ['<p>Софию<a l:href="#n" type="note">[166]</a>завершая</p>'])
    т = parse_source_file(ф)
    assert "Софиюзавершая" not in т, f"слова склеились: {т!r}"
    assert "Софию" in т and "завершая" in т


# ---- картинки и прочая разметка --------------------------------------------

def test_картинки_в_текст_не_попадают(tmp_path):
    """На девяти живых книгах 39 картинок, и ни одна не пришла текстом: разбор
    берёт только `<p>` и `<v>`, а base64 лежит в `<binary>`. Сторож нужен на
    случай, если поиск однажды расширят до «всего текста тела»."""
    p = tmp_path / "с_картинкой.fb2"
    вступление = "".join(f"<p>служебная строка {i}</p>" for i in range(25))
    p.write_text(
        f'{ШАПКА}<body>{вступление}'
        '<p>обычный абзац с живым текстом внутри книги</p>'
        '<image l:href="#pic1"/></body>'
        '<binary id="pic1" content-type="image/jpeg">iVBORw0KGgoAAAANSUhEUg</binary>'
        '</FictionBook>', "utf-8")
    т = parse_source_file(p)
    assert "iVBORw0KGgo" not in т, "base64 картинки утёк в текст"
    assert "обычный абзац" in т


def test_стихи_берутся_наравне_с_прозой(tmp_path):
    """`<v>` — строка стиха. У Головина их 381, и это ровно тот материал, ради
    которого программа существует."""
    ф = книга(tmp_path, ['<poem><stanza>'
                         '<v>и падал снег на чёрные заборы</v>'
                         '<v>а мы стояли молча у ворот</v>'
                         '</stanza></poem>'])
    т = parse_source_file(ф)
    assert "падал снег на чёрные заборы" in т and "стояли молча у ворот" in т


# ---- отказы --------------------------------------------------------------

def test_чужой_формат_отвергается_понятно(tmp_path):
    """Окно выбора файла предлагает ровно fb2/txt/md (сторож совпадения — в
    test_чистка_склада.py). Если файл всё же придёт другой, отказ обязан быть
    называемым, а не падением разбора."""
    p = tmp_path / "книга.epub"
    p.write_text("что угодно", "utf-8")
    with pytest.raises(ValueError, match="unsupported_format"):
        parse_source_file(p)


def test_пустая_книга_не_роняет_разбор(tmp_path):
    """fb2 без единого абзаца — законный вход (битый файл, чужая разметка).
    Разбор обязан вернуть пусто, а заливка сказать «empty_source»."""
    p = tmp_path / "пустая.fb2"
    p.write_text(f"{ШАПКА}<body></body></FictionBook>", "utf-8")
    assert parse_source_file(p).strip() == ""


# ---- txt и md: те же беды, другой путь -------------------------------------
#
# Вопрос владельца: «а почему не работает на txt и md? вдруг там такое
# встретится? вдруг это кривой какой-то перенос?»
#
# Он был прав дважды. Снималка маркеров стояла в разборе fb2 и обходила txt и
# md стороной, а перенос слова через строку не сращивался вовсе. Обе правки
# переехали в `clean_text` — через него проходит текст ВСЕХ форматов
# (`store.add_corpus` зовёт его первым делом).

def тхт(tmp_path, текст: str, имя="книга.txt") -> Path:
    p = tmp_path / имя
    p.write_text(текст, "utf-8")
    return p


def test_маркеры_снимаются_и_в_txt(tmp_path):
    """Снималка жила в `_текст_абзаца`, то есть работала только на fb2. А
    «[47]» и «{24}» попадаются в любом тексте, снятом с книги."""
    т = parse_source_file(тхт(tmp_path,
        "В первом томе своих «Осколков» [47] профессор Мюллер клеймит Веды.\n"
        "Их легко победить {24} . Противник не знает, где он будет сражаться.\n"))
    assert "[47]" not in т and "{24}" not in т, т
    assert "профессор Мюллер клеймит" in т and "Противник не знает" in т


def test_маркеры_снимаются_и_в_md(tmp_path):
    """md идёт тем же путём, что txt, — но проверяется отдельно: «идёт тем же
    путём» это утверждение о коде, а тест обязан проверять исход."""
    т = parse_source_file(тхт(tmp_path, "## Глава\n\nтекст со ссылкой [12] внутри строки\n",
                              имя="книга.md"))
    assert "[12]" not in т and "текст со ссылкой" in т, т


def test_перенос_слова_сращивается(tmp_path):
    """В txt, снятом со скана или из вёрстки, слово рвётся дефисом на границе
    строки: «пере-\nнос». Схлопывание пробелов давало «пере- нос» — висячий
    дефис и два обломка вместо слова. В fb2 такого нет: там абзац цельный."""
    т = parse_source_file(тхт(tmp_path,
        "А это обычный текст с пере-\nносом слова через строку.\n"))
    assert "пере- нос" not in т, f"висячий дефис остался: {т!r}"
    assert "переносом слова" in т, f"слово не срослось: {т!r}"


def test_тире_на_конце_строки_не_сращивается(tmp_path):
    """ГРАНИЦА ПРАВИЛА. Тире — это знак речи, а не перенос:
    «Он сказал —\nИ замолчал» обязано остаться двумя мыслями."""
    т = parse_source_file(тхт(tmp_path, "Он сказал —\nИ замолчал надолго.\n"))
    assert "сказал — И замолчал" in т, f"тире съедено как перенос: {т!r}"


def test_заглавная_после_переноса_не_сращивается(tmp_path):
    """Заглавная буква после дефиса и перевода строки — начало новой мысли, а
    не хвост разорванного слова. Сращивать её значило бы склеить два
    предложения в одно несуществующее слово."""
    т = parse_source_file(тхт(tmp_path, "какой-то список чего-\nНовая строка тут.\n"))
    assert "чегоНовая" not in т, f"склеены разные мысли: {т!r}"


def test_дефис_внутри_строки_цел(tmp_path):
    """«какой-то», «что-нибудь» — обычные слова. Правило срабатывает ТОЛЬКО на
    границе строки, и это надо сторожить: дефис в русском тексте частый."""
    т = parse_source_file(тхт(tmp_path, "он взял какой-то предмет и что-нибудь ещё\n"))
    assert "какой-то" in т and "что-нибудь" in т, т


def test_союз_после_дефиса_не_склеивается(tmp_path):
    """ГРАНИЦА, ЗАМЕРЕННАЯ ПО ЖИВОМУ КОРПУСУ. «микро- и макрокосм» — законный
    висячий дефис, а не разорванное слово: из 131 висячего дефиса в складе
    владельца 58 (44%) стоят перед союзом. Ляг такой оборот на границу строки —
    и наивное правило дало бы «микроимакрокосм»."""
    т = parse_source_file(тхт(tmp_path, "полюса микро-\nи макрокосма, можно назвать\n"))
    assert "микроимакрокосма" not in т, f"союз склеен: {т!r}"
    assert "микро- и макрокосма" in т, т


def test_двух_или_трехлетнего_цело(tmp_path):
    """Второй по частоте союз в этой позиции — «или» (11 случаев)."""
    т = parse_source_file(тхт(tmp_path, "признаки двух-\nили трехлетнего периода\n"))
    assert "двух- или трехлетнего" in т, т


# ---- дефис бывает не только ASCII ------------------------------------------
#
# Вопрос владельца: «вдруг это кривой какой-то перенос?» Кривой он ровно в этом:
# текст из вёрстки или PDF носит юникодные дефисы, и правило по ASCII их не
# видело. Порча выходила ТИШЕ ASCII-случая — без висячего дефиса, а значит и
# без единой приметы, по которой её потом опознать.

def test_юникодный_дефис_U2010_сращивается(tmp_path):
    т = parse_source_file(тхт(tmp_path, "текст с пере\u2010\nносом слова тут\n"))
    assert "переносом слова" in т, f"U+2010 не сросся: {т!r}"


def test_неразрывный_дефис_U2011_сращивается(tmp_path):
    т = parse_source_file(тхт(tmp_path, "текст с пере\u2011\nносом слова тут\n"))
    assert "переносом слова" in т, f"U+2011 не сросся: {т!r}"


def test_мягкий_перенос_сращивается(tmp_path):
    """U+00AD невидим и значит РОВНО «здесь можно разорвать» — самый частый
    след вёрстки. Сращивается безусловно: оборотом «микро- и» он не бывает."""
    т = parse_source_file(тхт(tmp_path, "текст с пере\u00ad\nносом слова тут\n"))
    assert "переносом слова" in т, f"мягкий перенос не сросся: {т!r}"


def test_мягкий_перенос_вне_переноса_выброшен(tmp_path):
    """Уцелевший внутри строки он невидим, но рвёт слово надвое при разбивке
    на токены — то есть портит и рифму, и счёт знаменательных слов.

    Сторожит ИСХОД, а не строку: снимает его белый список символов в конце
    `clean_text`, а не отдельное правило (отдельное правило тут стояло и снято
    как мёртвое). Доказан ломкой именно белого списка."""
    т = parse_source_file(тхт(tmp_path, "обычное сло\u00adво в середине строки\n"))
    assert "\u00ad" not in т and "слово в середине" in т, repr(т)


def test_юникодный_дефис_тоже_щадит_союз(tmp_path):
    """Исключение на союзы обязано работать и после приведения к ASCII —
    иначе правило чинило бы один формат и ломало другой."""
    т = parse_source_file(тхт(tmp_path, "полюса микро\u2010\nи макрокосма тут\n"))
    assert "микроимакрокосма" not in т, f"союз склеен: {т!r}"
