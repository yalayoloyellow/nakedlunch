def test_mac_cyrillic_читается_верно(tmp_path):
    """ПУНКТ, КОТОРЫЙ ДОЛГО СТОЯЛ ОТКРЫТЫМ. cp1251 и mac-cyrillic почти
    совпадают в строчных, и одних частот букв не хватало: верный ответ
    отличался от неверного на 0.005, то есть на шум.

    Примета нашлась: в правильно прочитанном тексте ЗАГЛАВНАЯ стоит только в
    начале слова. Замер на пробе — верное чтение 0 таких букв, mac-текст,
    прочитанный как cp1251, даёт 32 («‘тоЯла зима»)."""
    p = tmp_path / "книга.txt"
    p.write_bytes(ОБРАЗЕЦ.encode("mac-cyrillic"))
    assert "Стояла зима, мороз был крепок" in разобрать(p)


def test_кавычки_и_типографика_остаются(tmp_path):
    """Белый список выбрасывал „ “ ’ № % ° § — законные знаки русской прозы.
    Замер по девяти книгам: кавычек 286 мест («где взял „Псалтырь“»),
    типографики 43. А вот / (1004, почти всё библиография «// Tyndall»), &, +,
    = не пускаем — в строке песни им делать нечего."""
    т = разобрать(тхт(tmp_path, "где взял „Псалтырь“ и дом № 5, где 90% людей\n"))
    assert "„Псалтырь“" in т, т
    assert "№ 5" in т and "90%" in т, т


