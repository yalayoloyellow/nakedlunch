# ---- летопись в конце книги ------------------------------------------------
#
# Владелец указал на выдачу и сказал прямо: «вот подобного рода мусор мне не
# нужен» — «1947 — 24 июня Селин освобожден», «книгу «Жизнь Земмельвайса».
# 1929 — В январе». Это справочное приложение в конце книги, летопись жизни
# автора; разметка её от прозы не отличает.

ЛЕТОПИСЬ = ["1894 — 27 мая в Курбевуа родился Луи-Фердинанд-Огюст Детуш.",
            "В сентябре семья переезжает в Париж на улицу Мадлен.",
            "1912 — 28 сентября Детуш поступает на военную службу в полк.",
            "1914 — 25 октября он ранен в правую руку под Пуркуа-Па.",
            "1915 — В мае получает военную медаль и отправлен в Лондон.",
            "1924 — Защищает диссертацию о жизни доктора Земмельвайса.",
            "1932 — В октябре выходит «Путешествие на край ночи».",
            "1961 — 1 июля Луи-Фердинанд Селин скончался в Медоне."]
ПРОЗА = ["Он никогда не учился в лицее, и это было заметно по речи его.",
         "В 1914 году двадцатилетний Детуш очень скоро получил награду.",
         "Того, что от нее оставалось в 1914 году, теперь уже стыдились.",
         "Около 1913 года еще один сверхштатный приказчик служил тут.",
         "И можно быть уверенным, что этот шедевр сегодня уже не забыт."] * 4


def test_летопись_в_конце_срезается(tmp_path):
    """Признак СТРУКТУРНЫЙ, а не смысловой: проза год упоминает, но никогда не
    НАЧИНАЕТСЯ с голого года. Замер на «Путешествии на край ночи»: все 51
    абзац, начинающийся с года, лежат в последних 4% книги (2496–2597 из
    2601), в прозе таких нет ни одного.

    Режется БЛОКОМ: внутри летописи полно строк без года («В сентябре семья
    переезжает»), поодиночке их от прозы не отличить."""
    т = разобрать(тхт(tmp_path, "\n\n".join(ПРОЗА + ЛЕТОПИСЬ)))
    assert "1894 — 27 мая" not in т, f"летопись уцелела: {т[-200:]!r}"
    assert "В сентябре семья переезжает" not in т, "строка летописи без года уцелела"
    assert "этот шедевр сегодня уже не забыт" in т, "срезано лишнее"


def test_проза_с_годами_не_трогается(tmp_path):
    """ГЛАВНАЯ ГРАНИЦА. Без летописи в хвосте правило не срабатывает вовсе —
    иначе оно резало бы обычный текст, где годы поминают часто."""
    т = разобрать(тхт(tmp_path, "\n\n".join(ПРОЗА)))
    for кусок in ("В 1914 году двадцатилетний", "Около 1913 года еще"):
        assert кусок in т, f"проза с годом срезана: {кусок}"


def test_несколько_дат_подряд_не_считаются_летописью(tmp_path):
    """Порог в пять записей — с запасом. Три абзаца с года это ещё не
    приложение, а, например, врезка в тексте."""
    т = разобрать(тхт(tmp_path, "\n\n".join(ПРОЗА + ЛЕТОПИСЬ[:3])))
    assert "1894 — 27 мая" in т, "срезано по трём записям"


def test_летопись_в_НАЧАЛЕ_не_трогается(tmp_path):
    """ОСОЗНАННАЯ ГРАНИЦА. Правило смотрит только вторую половину книги —
    потому что только там летопись и нашлась. В начале она бывает, но в девяти
    живых книгах её нет, и правило на неё было бы догадкой, а не замером."""
    т = разобрать(тхт(tmp_path, "\n\n".join(ЛЕТОПИСЬ + ПРОЗА)))
    assert "1894 — 27 мая" in т, "срезан блок в начале — правило вышло за замер"


def test_строка_с_цифрой_не_доходит_до_склада(tmp_path):
    """РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-08-21, дословно: «В 1914 году двадцатилетний»,
    «перевалил за 39, потом 40 градусов», «Шуазель в 1896–1912 годах?» — «мне
    это тоже нахуй не нужно».

    СУДЬЯ — ЕГО СОБСТВЕННОЕ ИЗБРАННОЕ, и приговор единогласный: из 62
    сохранённых им строк цифра есть в НУЛЕ. Числа, которые он уносит, всегда
    записаны словами — «два часа как четверг», «субстантивированные двое суток».

    Цена по девяти живым книгам: 8 553 фрагмента из 569 480 (1.50%)."""
    from nlsrc.cutter import cut_into_fragments
    ф = cut_into_fragments(разобрать(тхт(tmp_path,
        "В 1914 году двадцатилетний Детуш очень скоро получил боевую награду свою.\n"
        "Он шёл вдоль набережной и думал о том, что всё когда-нибудь кончается.\n")))
    assert ф, "нарезка пуста"
    assert not any(any(c.isdigit() for c in x) for x in ф), \
        [x for x in ф if any(c.isdigit() for c in x)][:3]
    assert any("вдоль набережной" in x for x in ф), "срезано лишнее"


def test_число_словами_остаётся(tmp_path):
    """ГРАНИЦА. Режется ЦИФРА, а не число. «два часа как четверг» и
    «субстантивированные двое суток» — это его же сохранённые строки."""
    from nlsrc.cutter import cut_into_fragments
    ф = cut_into_fragments(разобрать(тхт(tmp_path,
        "два часа как четверг и потом еще уйти хоть под утро совсем\n")))
    assert any("два часа" in x for x in ф), ф[:5]
