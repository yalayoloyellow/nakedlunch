@pytest.mark.parametrize("ns", [
    'xmlns="http://www.gribuser.ru/xml/fictionbook/2.0"',
    'xmlns="http://www.gribuser.ru/xml/fictionbook/2.1"',
    '',
])
def test_версия_схемы_fb2_не_решает(tmp_path, ns):
    """Поиск шёл через `findall(".//fb:body", NS)`, где `fb` прибит к
    `fictionbook/2.0`. Книга в 2.1 или собранная без объявления пространства
    имён давала НОЛЬ абзацев — и молча: человек видел «нарезать нечего,
    слишком короткий», то есть враньё о причине.

    Версия схемы к содержимому книги отношения не имеет."""
    p = tmp_path / "книга.fb2"
    p.write_text(f'<?xml version="1.0" encoding="utf-8"?><FictionBook {ns}>'
                 "<body><section><p>Стояла зима и мороз был крепок совсем.</p>"
                 "</section></body></FictionBook>", "utf-8")
    assert "Стояла зима и мороз" in разобрать(p), ns


def test_битый_fb2_отвечает_понятно(tmp_path):
    """Вместо «no element found: line 1, column 58» — свой код, который лента
    работ покажет как «файл повреждён — это не читается как fb2»."""
    p = tmp_path / "книга.fb2"
    p.write_text('<?xml version="1.0"?><FictionBook><body><p>текст не закрыт', "utf-8")
    with pytest.raises(ValueError, match="broken_fb2"):
        разобрать(p)


