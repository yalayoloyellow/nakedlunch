# КЛАССИКА И МАСКА КЛАУЗУЛЫ — ИСТОРИЯ ОДНОГО ДОГОВОРА И ЕГО ОТМЕНЫ.
#
# ЧТО БЫЛО СНАЧАЛА (2026-08-28). Клаузула стала МАСКОЙ концовок (1 мужская ·
# 2 женская · 4 дактилическая, 7 «любая») — по требованию «может я хочу
# только мужскую и дактилическую». Алгоритм переучили, а классику забыли:
# `nlindex.select_light` продолжал сравнивать `clau == clausula`, а колонка
# держит номера 1..3, и семёрки в ней не бывает вовсе.
#
# ИТОГ БЫЛ ХУДШИМ ИЗ ВОЗМОЖНЫХ: КЛАССИКА ОТДАВАЛА НОЛЬ СТРОК при любом
# положении ручки — и молча, без ошибки. Поймано не тестом, а живым прогоном в
# браузере: экран не обновлялся, запрос отвечал 200, «ворота: 0». Тесты
# молчали, потому что `test_classic_binary` звал классику на стенде БЕЗ
# колоночного индекса, где работает другой путь и маску понимает. Тогда и
# завёлся этот файл — сторож по индексному пути.
#
# ЧТО СТАЛО (2026-09-02). Договор отменён целиком: клаузулы в классике больше
# нет. требование — «классика вообще все настройки отключает и просто даёт
# равную выдачу». Вместе с клаузулой сняты внутренняя рифма, перекличка и три
# полосы редкости; остались мат, чёрный список, история и активный пул —
# сказанное вслух про СОДЕРЖАНИЕ, а не про форму. Разбор и замер — в надгробии
# внутри `nlindex.select_light`, на экране ручки гаснут подписью «классика
# этого не читает» (`render.gen.jsx`, `классикаНеЧитает`).
#
# ФАЙЛ ОСТАЁТСЯ, И ЭТО НЕ СЕНТИМЕНТАЛЬНОСТЬ. Урок здесь не про клаузулу, а про
# МОЛЧАЛИВЫЙ НОЛЬ: ручка, из-за которой режим отдаёт пустоту без единого слова,
# — худший вид поломки, и сторож против неё нужен при любом договоре. Он ниже,
# только перевёрнут: теперь проверяется, что положение ручки на выдачу НЕ
# влияет и пустоты не делает.
import sys
from pathlib import Path

import numpy as np
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))
import nlindex  # noqa: E402


class _Идх:
    """Минимальный индекс: только то, что читает select_light."""
    n = 6
    #                мужская, женская, дактиль, мужская, женская, дактиль
    clau = np.array([1, 2, 3, 1, 2, 3], dtype=np.int8)
    mat = np.zeros(6, dtype=np.int8)
    whole = np.ones(6, dtype=np.uint8)

    def whole_mask(self):
        return np.asarray(self.whole) != 0

    def text(self, i):
        return f"строка {i}"


@pytest.fixture
def стенд(monkeypatch):
    monkeypatch.setattr(nlindex, "_правила", lambda: [])
    monkeypatch.setattr(nlindex, "_row",
                        lambda idx, i, *a, **k: {"text": idx.text(i),
                                                 "clausula": int(idx.clau[i])})
    return _Идх()


def _классика(идх):
    пул = np.ones(идх.n, dtype=bool)
    скрыт = np.zeros(идх.n, dtype=bool)
    строки, выжило, _ = nlindex.select_light(
        идх, pool_mask=пул, hidden_mask=скрыт, no_mat=False, only_mat=False,
        cap=10, seed=1)
    return строки, выжило


def test_классика_не_принимает_клаузулу():
    """Ворота формы сняты с режима, который форму не судит."""
    import inspect
    подпись = inspect.signature(nlindex.select_light).parameters
    for снято in ("clausula", "внутр_рифма", "перекличка",
                  "редкость_слова", "редкость_пары", "плотность"):
        assert снято not in подпись, (
            f"классика снова принимает «{снято}» — ворота формы вернулись в "
            f"режим, который по определению работает как изначальный nakedlunch")


def test_мат_и_история_остались():
    """А это — не форма, а содержание, и оно остаётся по решению."""
    import inspect
    подпись = inspect.signature(nlindex.select_light).parameters
    for оставлено in ("no_mat", "only_mat", "mat_share", "hidden_mask", "pool_mask"):
        assert оставлено in подпись, f"из классики пропало «{оставлено}»"


def test_классика_отдаёт_всё_и_никогда_не_ноль(стенд):
    """ГЛАВНЫЙ СТОРОЖ, ПЕРЕЖИВШИЙ СМЕНУ ДОГОВОРА.

    Урок молчаливого нуля 2026-08-29: режим, отдающий пустоту без единого
    слова, — худшая поломка из возможных. При нынешнем договоре классика обязана
    отдавать ВЕСЬ пул: резать ей нечем."""
    строки, выжило = _классика(стенд)
    assert выжило == 6, "классика потеряла строки — а резать ей теперь нечем"
    assert len(строки) == 6
    assert {r["clausula"] for r in строки} == {1, 2, 3}, (
        "в выдаче не все концовки — где-то остались ворота формы")
