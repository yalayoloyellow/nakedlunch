# nakedlunch — правило рифмо-ключа (core/scan.rhyme_key), Раунд 33.
#
# Ключ считается ТРЕМЯ путями (лексикон генератора, nl_rhyme.json, индекс слов
# попапа) и обязан совпадать побайтово, иначе строки генератора и фрагменты
# корпуса не срифмуются никогда. Здесь проверяется само правило — на парах,
# которые слышно ухом.
#
# Прогон: .venv/bin/python -m pytest tests/test_rhyme_key.py -q

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "core"))

import scan


def ключ(слово, ударный_гласный):
    return scan.rhyme_key(слово, ударный_гласный)


def test_ударная_ё_сводится_к_о():
    """До Раунда 33 ударная ё оставалась в ключе как есть, и он врал в обе
    стороны: «свет»/«идёт» получали один ключ «ет» и выдавались рифмой, а
    «идёт»/«поворот» рифмой НЕ считались."""
    assert ключ("идёт", 1) == ключ("поворот", 2) == "от"
    assert ключ("мёд", 0) == ключ("год", 0) == "от"
    assert ключ("лёд", 0) == ключ("идёт", 1)
    assert ключ("свет", 0) != ключ("идёт", 1)
    assert ключ("нёс", 0) != ключ("лес", 0)


def test_ключ_никогда_не_содержит_ё():
    """Инвариант правила: ё в ключе не остаётся ни в ударной позиции, ни в
    заударной (там её давно сводит _REDUCE)."""
    for слово, i in [("ёлка", 0), ("тётя", 0), ("идёт", 1), ("нёс", 0),
                     ("шёпот", 0), ("ружьё", 1)]:
        assert "ё" not in ключ(слово, i), слово


def test_старые_свойства_ключа_на_месте():
    """Правка ё не должна была тронуть остальное: заударная редукция и
    оглушение конца."""
    assert ключ("дом", 0) == ключ("том", 0) == "ом"       # оглушения нет, но пара равна
    assert ключ("сад", 0) == "ат"                          # д → т на конце
    assert ключ("ночь", 0) == "очь"
    assert ключ("дорога", 1) == "ога"                      # заударная а остаётся а
    assert ключ("много", 0) == "ога"                       # заударная о → а
