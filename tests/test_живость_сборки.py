ЖИВОЙ = 10 ** 9          # такого номера процесса не бывает — os.kill скажет «нет»


def сайдкар(*, молчит: float, pid=None, state="running") -> dict:
    s = {"state": state, "cached": 1, "mode": "incremental",
         "updated_at": time.time() - молчит}
    if pid is not None:
        s["pid"] = pid
    return s


