# nakedlunch — панель настроек не имеет права открываться пустой.
#
# ЧТО СЛУЧИЛОСЬ (найдено живой проверкой 2026-08-18 на КОПИИ настоящего
# живой settings.json). Панель настроек открывалась пустой: вкладки «лента
# вид корпус лог» сверху есть, под ними — ничего. Без ошибки в консоли, без
# красной плашки, без единого следа в журнале. Молчаливый отказ.
#
# ПОЧЕМУ. В сохранённых сохранённых профилях сцены лежит `cfgTab: "документ"` —
# имя вкладки настроек РЕДАКТОРА, вырезанного вместе с документом 2026-08-18.
# Профиль сцены снимает состояние по принципу «всё, кроме перечисленного»
# (methods.fsprofiles.js: PROF_SKIP_STATE), и cfgTab в запрет не попал. При
# загрузке профиль возвращал «документ» в живое состояние, а render.settings.jsx
# знает только CFG_TABS — ни одна ветка `tab === '…'` не совпадала, и тело
# панели не рисовалось вовсе.
#
# ПОЧИНКА ИЗ ДВУХ ПОЛОВИН, И ВТОРАЯ ВАЖНЕЕ ПЕРВОЙ:
#   1) cfgTab внесён в PROF_SKIP_STATE — закрыт известный путь;
#   2) выбор вкладки падает на первую из CFG_TABS, если имя незнакомо, — закрыты
#      все остальные пути, включая те, которых мы ещё не видели.
# Второе важнее потому, что старые профили на диске останутся с
# «документом» НАВСЕГДА, и потому, что источник незнакомого имени может быть
# любым: ключ из будущей версии, правка файла руками, вкладка, которую вырежут
# следующей. Запрет чинит причину, зажим — последствие; без зажима любая новая
# причина снова даст пустой экран.
#
# Тест читает исходники фронта ТЕКСТОМ, как и tests/test_scene_profile_leak.py:
# сборка тут не помощник — она зелёная и при этом баге, синтаксически всё
# в порядке. Записано в правилах проекта: зелёный build не значит рабочий код.
#
# Прогон: .venv/bin/python -m pytest tests/test_вкладка_настроек.py -q

import re
from pathlib import Path

NL = Path(__file__).resolve().parent.parent / "interface" / "react-app" / "src" / "nl"
ПРОФИЛИ = NL / "methods.fsprofiles.js"
НАСТРОЙКИ = NL / "render.settings.jsx"


def _запрет() -> set[str]:
    """Имена из литерала PROF_SKIP_STATE. Разбор грубый и намеренно склонён
    к перебору: лишнее имя даст лишнюю проверку, пропущенное — дыру."""
    текст = ПРОФИЛИ.read_text("utf-8")
    i = текст.index("PROF_SKIP_STATE: {")
    j = текст.index("\n  },", i)
    тело = текст[i:j]
    # комментарии выбрасываем: в них перечислены имена, которых в запрете нет
    тело = re.sub(r"//[^\n]*", "", тело)
    return set(re.findall(r"([A-Za-zА-Яа-я_$][\w$]*)\s*:", тело))


def _вкладки() -> list[str]:
    текст = НАСТРОЙКИ.read_text("utf-8")
    m = re.search(r"export const CFG_TABS = \[(.*?)\];", текст, re.S)
    assert m, "CFG_TABS не найден — список вкладок переименовали или удалили"
    return re.findall(r"'([^']+)'", m.group(1))


def test_профиль_сцены_не_решает_за_вкладку_настроек():
    """Первая половина починки: известный путь закрыт.

    Профилю сцены нечего решать за вкладку панели настроек — она не часть
    сцены. Если этот тест покраснел, значит cfgTab убрали из запрета, и у
    снова откроется пустая панель: его профили на диске несут
    «документ» и будут нести всегда."""
    assert "cfgTab" in _запрет(), (
        "cfgTab пропал из PROF_SKIP_STATE. В сохранённых профилях сцены "
        "лежит cfgTab: «документ» — вкладка вырезанного редактора; "
        "без запрета applyProfile вернёт её в живое состояние и панель "
        "настроек откроется пустой."
    )


def test_незнакомое_имя_вкладки_даёт_вкладку_а_не_пустоту():
    """Вторая половина, и она важнее первой: закрыты ВСЕ пути.

    Сторожим свойство, а не строчку: имя вкладки, которого нет в CFG_TABS,
    обязано приводить к вкладке из списка. Проверяем, что выбор сверяется со
    списком, а не берёт значение состояния как есть с запасным вариантом
    (`st.cfgTab || 'вид'` — именно так и было, и именно поэтому «документ»
    доезжал до отрисовки нетронутым)."""
    текст = НАСТРОЙКИ.read_text("utf-8")
    m = re.search(r"^\s*var tab = (.+?);\s*$", текст, re.M)
    assert m, "строка выбора вкладки не найдена — её переименовали"
    выбор = m.group(1)

    assert "CFG_TABS" in выбор, (
        f"выбор вкладки не сверяется со списком живых: `{выбор}`. Любое имя, "
        "которого нет в CFG_TABS, доедет до отрисовки и даст ПУСТУЮ панель "
        "без единой ошибки — так и получались пустые настройки."
    )

    вкладки = _вкладки()
    запасная = re.findall(r"'([^']+)'", выбор)
    assert запасная, f"у выбора вкладки нет запасного имени: `{выбор}`"
    for имя in запасная:
        assert имя in вкладки, (
            f"запасная вкладка «{имя}» отсутствует в CFG_TABS {вкладки} — "
            "запасной путь ведёт в ту же пустоту, от которой защищает."
        )


def test_вкладки_не_пусты_и_вырезанной_среди_них_нет():
    """Вырожденные данные: список вкладок обязан быть непустым, а вкладки
    вырезанного редактора в нём быть не должно — иначе панель обещала бы
    настройки того, чего в программе нет."""
    вкладки = _вкладки()
    assert вкладки, "CFG_TABS пуст — панель настроек не может открыться ничем"
    assert "документ" not in вкладки, (
        "вкладка «документ» вернулась в CFG_TABS. Редактор документа вырезан "
        "2026-08-18; вкладка его настроек обещала бы то, чего нет."
    )
