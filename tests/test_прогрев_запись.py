# ЗАПИСЬ ПРОГРЕВА В ЛЕНТЕ РАБОТ: два индикатора об одном событии обязаны
# называть одно число, а оценка «осталось ~N с» — не протухать вместе с корпусом.
#
# ЧТО БЫЛО (найдено разбором 2026-09-02). Запись отдавала `done` в СЕКУНДАХ на
# часах, а `total` — суммой ВЕСОВ этапов. Кольцо в шапке считает свой процент
# как done/total (`methods.corpus.js`), поэтому оно упиралось в 100% раньше
# готовности и спорило с процентом из этой же записи: кольцо 100%, строка
# ленты 88%, и ↵ в этот момент ещё ничего не делал. Сами веса были замером
# 2026-08-21 и к сентябрю разошлись вдвое — оценка «осталось ~9 с» врала при
# реальных ~23 с.
import json
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "core"))
sys.path.insert(0, str(КОРЕНЬ / "api"))


@pytest.fixture
def сервер():
    import server
    return server


def _запись(server, готов: bool, этапы: list, этап: str, начат_назад: float):
    import time
    server._ПРОГРЕВ["готов"] = готов
    server._ПРОГРЕВ["этапы"] = list(этапы)
    server._ПРОГРЕВ["этап"] = этап
    server._ПРОГРЕВ["начат"] = time.time() - начат_назад
    server._ПРОГРЕВ["кончен"] = time.time()
    return server._прогрев_статус()


def test_кольцо_и_строка_называют_одно_число(сервер):
    """`done/total` — то же, что `pct`. Разные единицы в одной записи означали
    бы два индикатора, спорящих об одном событии."""
    сохр = dict(сервер._ПРОГРЕВ)
    try:
        # середина прогрева: первый этап позади, идёт второй
        з = _запись(сервер, False, [["корпус", 5.0]], "карты индекса", 8.0)
        кольцо = round(100 * з["done"] / з["total"]) if з["total"] else 0
        assert abs(кольцо - з["pct"]) <= 5, (
            f"кольцо {кольцо}% против строки {з['pct']}% — разные единицы")
        assert з["pct"] < 100, "процент дошёл до ста, а прогрев ещё идёт"
        assert кольцо < 100, "кольцо дошло до ста, а прогрев ещё идёт"
    finally:
        сервер._ПРОГРЕВ.clear(); сервер._ПРОГРЕВ.update(сохр)


def test_долгий_прогрев_не_упирается_в_сто(сервер):
    """ГЛАВНЫЙ СТОРОЖ. Прогрев идёт ВДВОЕ дольше суммы весов — ровно случай
    выросшего корпуса, на котором всё и сломалось. Ни один из двух индикаторов
    не смеет показать сто, пока `готов` не выставлен."""
    сохр = dict(сервер._ПРОГРЕВ)
    try:
        всего = sum(сервер._ВЕС_ЭТАПА.values())
        з = _запись(сервер, False, [["корпус", 5.0]], "карты индекса", всего * 2)
        кольцо = round(100 * з["done"] / з["total"]) if з["total"] else 0
        assert з["pct"] < 100, f"строка показала {з['pct']}% при неготовом прогреве"
        assert кольцо < 100, f"кольцо показало {кольцо}% при неготовом прогреве"
        assert з["state"] == "running"
    finally:
        сервер._ПРОГРЕВ.clear(); сервер._ПРОГРЕВ.update(сохр)


def test_веса_берутся_с_прошлого_запуска(сервер, tmp_path, monkeypatch):
    """Зашитые числа протухают вместе с ростом корпуса — поэтому вес этапа
    берётся с прошлого запуска, а зашитое остаётся умолчанием для первого."""
    файл = tmp_path / "прогрев.json"
    monkeypatch.setattr(сервер, "_ВЕС_ФАЙЛ", файл)

    # файла нет — идём на умолчаниях, а не падаем и не обнуляемся
    assert сервер._веса() == сервер._ВЕС_УМОЛЧАНИЕ

    файл.write_text(json.dumps({"корпус": 13.0, "карты индекса": 12.5,
                                "перепривязка истории": 0.0}), "utf-8")
    веса = сервер._веса()
    assert веса["корпус"] == 13.0
    assert веса["карты индекса"] == 12.5
    # НОЛЬ НЕ ПЕРЕЗАПИСЫВАЕТ УМОЛЧАНИЕ: этап, уложившийся в 0.0 с, сделал бы
    # знаменатель меньше и вернул бы ту же болезнь — сто процентов раньше срока.
    assert веса["перепривязка истории"] == сервер._ВЕС_УМОЛЧАНИЕ["перепривязка истории"]


def test_битый_файл_весов_не_роняет_прогрев(сервер, tmp_path, monkeypatch):
    """Замер — удобство, а не работа. Мусор в файле обязан дать умолчания."""
    файл = tmp_path / "прогрев.json"
    monkeypatch.setattr(сервер, "_ВЕС_ФАЙЛ", файл)
    for мусор in ("не json вовсе", "[]", '{"корпус": "долго"}', ""):
        файл.write_text(мусор, "utf-8")
        assert сервер._веса()["корпус"] == сервер._ВЕС_УМОЛЧАНИЕ["корпус"]
