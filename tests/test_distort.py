# ---- 7. кривая действительно кривая ----------------------------------------

def test_krivaya_gladkaya_a_ne_lomanaya():
    """Пользователь: «пусть кривая реально изгибается как кривая, а не резко».
    Ломаная даёт в узле излом — в середине отрезка значение ровно среднее.
    Сплайн отходит от него: это и есть изгиб."""
    точки = [(0.0, -1.0), (0.5, 0.0), (1.0, 1.0)]
    прямая = [(0.0, -1.0), (1.0, 1.0)]
    # на прямой линии сплайн обязан совпадать с прямой — иначе он врёт
    assert distort.значение(прямая, 0.25) == pytest.approx(-0.5, abs=0.02)
    # а на изогнутой — идти плавно, без излома в узле
    слева = distort.значение([(0.0, 0.0), (0.5, 1.0), (1.0, 1.0)], 0.45)
    справа = distort.значение([(0.0, 0.0), (0.5, 1.0), (1.0, 1.0)], 0.55)
    assert 0.9 < слева < 1.0 and 0.99 <= справа <= 1.0, (слева, справа)


def test_splayn_ne_vyskakivaet_za_tochki():
    """ГЛАВНОЕ ОГРАНИЧЕНИЕ. Обычный сплайн между 0.2 и 0.3 может уйти на 0.45 —
    и прогон сделал бы то, чего на экране не нарисовано. Фрич–Карлсон гасит
    наклон там, где соседние отрезки идут в разные стороны."""
    # Случай, на котором ограничитель и нужен: крутой короткий отрезок рядом с
    # пологим длинным. Без гашения наклон, унаследованный от крутого куска,
    # выносит кривую на пологом далеко за верхнюю точку. Мягкая волна такого
    # не показывает — первая версия теста брала именно её и мутацию не поймала.
    for точки in ([(0.0, 0.0), (0.1, 0.9), (1.0, 1.0)],
                  [(0.0, 1.0), (0.9, 0.9), (1.0, 0.0)],
                  [(0.0, 0.0), (0.3, 0.8), (0.6, 0.1), (1.0, 0.9)]):
        _без_выброса(точки)


def _без_выброса(точки):
    for i in range(1, len(точки)):
        низ = min(точки[i - 1][1], точки[i][1])
        верх = max(точки[i - 1][1], точки[i][1])
        for k in range(11):
            x = точки[i - 1][0] + (точки[i][0] - точки[i - 1][0]) * k / 10
            v = distort.значение(точки, x)
            assert низ - 1e-9 <= v <= верх + 1e-9, f"выброс в x={x}: {v} вне [{низ}, {верх}]"


# ---- 8. типы шума действительно разные -------------------------------------

def подпись_шума(тип, n=40, зёрен=24):
    """Двумерная подпись типа: СВЯЗЬ соседей и РЯБЬ (мелкая деталь).

    Одной мало, и это выяснилось на живом замере. Связь насыщается: на четырёх
    сотнях точек всё гладкое даёт 0.99, и розовый с перлином становятся
    неотличимы — хотя на глаз у розового рябь на волне, а у перлина чистая
    волна. Рябь ловит ровно это, а связь ловит белый и синий, которые по ряби
    близки. Вместе они разводят все четыре."""
    св, ря = [], []
    for з in range(зёрен):
        р = distort._ряд(random.Random(з), тип, n)
        m = sum(р) / len(р)
        ц = [v - m for v in р]
        низ = sum(v * v for v in ц) or 1e-12
        св.append(sum(ц[i] * ц[i - 1] for i in range(1, len(ц))) / низ)
        ря.append(sum((ц[i] - 2 * ц[i - 1] + ц[i - 2]) ** 2 for i in range(2, len(ц))) / низ)
    return sum(св) / зёрен, sum(ря) / зёрен


def test_tipy_shuma_otlichayutsya_drug_ot_druga():
    """Пользователь: «разница в шумах должна быть». Проверяем не имена, а
    ПОВЕДЕНИЕ — и ровно то, чем типы подписаны в панели:

        белый    связь около нуля, средняя рябь — независимая дрожь
        синий    связь отрицательная, рябь наибольшая — дребезг
        розовый  связь высокая, рябь есть — волна с рябью
        перлин   связь высокая, ряби нет — чистая волна
    """
    б = подпись_шума("белый")
    син = подпись_шума("синий")
    роз = подпись_шума("розовый")
    пер = подпись_шума("перлин")
    assert abs(б[0]) < 0.15, f"белый обязан быть независимым: {б}"
    assert син[0] < -0.25, f"синий обязан быть антикоррелированным: {син}"
    assert роз[0] > 0.6 and пер[0] > 0.6, f"розовый и перлин обязаны быть связными: {роз} {пер}"
    assert син[1] > б[1] > роз[1], f"по ряби: синий > белый > розовый, а вышло {син} {б} {роз}"
    assert роз[1] > пер[1] * 5 + 0.02, f"у перлина ряби быть не должно: {роз} vs {пер}"


