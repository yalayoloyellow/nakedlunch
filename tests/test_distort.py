# ---- 4. ось X: трек занимает свою клетку -----------------------------------

def test_trek_zanimaet_svoyu_kletku():
    """Целое число это трек, дробная часть — его звенья. Клетка одна на трек
    независимо от длины цепочки."""
    for звеньев in (1, 2, 8):
        for j in range(звеньев):
            x = distort.место(1, 4, j, звеньев)
            assert 0.25 <= x < 0.5, f"звено {j}/{звеньев} вылезло из клетки трека"


def test_smena_cepochki_ne_dvigaet_sosedey():
    """РЕГРЕССИЯ ПО ЗАМЫСЛУ. Если бы звенья нумеровались сквозь всю серию,
    добавление звена во второй трек сдвинуло бы третий и четвёртый — и вся
    выстроенная кривая поехала бы от правки чужой цепочки.

    Внутри своей клетки звенья, конечно, перераспределяются: их стало больше.
    Проверяем именно ГРАНИЦЫ — что чужие клетки стоят на месте."""
    for звеньев in (2, 4, 9):
        for k in range(3):
            места = [distort.место(k, 3, j, звеньев) for j in range(звеньев)]
            assert min(места) >= k / 3, f"трек {k} залез в предыдущий"
            assert max(места) < (k + 1) / 3, f"трек {k} залез в следующий"


