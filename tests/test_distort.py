# ---- 1. кривая: нейтраль, края, ломаная ------------------------------------

def test_rovnaya_liniya_nichego_ne_delaet():
    """Нейтраль — горизонталь посередине. Именно поэтому отдельного ползунка
    «сила кривой» нет: насколько отогнул, настолько и подействовало."""
    крив = {distort.МАСТЕР: [[0.0, 0.0], [1.0, 0.0]]}
    assert distort.применить(ПОЛНЫЕ, 0.5, крив) == ПОЛНЫЕ


def test_pustaya_krivaya_ne_oshibka():
    """Рисование начинается с нуля точек. Падать на полпути — наказание за
    начатое движение."""
    assert distort.кривая_канала(None) == []
    assert distort.кривая_канала([{"x": "чушь", "y": 0.5}]) == []
    assert distort.применить(ПОЛНЫЕ, 0.3, {}) == ПОЛНЫЕ


def test_za_krayami_derzhitsya_krayanaya_tochka():
    """Так же рисует и виджет (хвосты на холсте). Разойдись они — картинка
    обещала бы одно, а прогон делал другое."""
    точки = [(0.3, 0.4), (0.7, -0.2)]
    assert distort.значение(точки, 0.0) == pytest.approx(0.4)
    assert distort.значение(точки, 1.0) == pytest.approx(-0.2)
    assert distort.значение(точки, 0.5) == pytest.approx(0.1)


def test_odna_tochka_eto_rovnyy_sdvig():
    assert distort.значение([(0.5, 0.3)], 0.0) == pytest.approx(0.3)
    assert distort.значение([(0.5, 0.3)], 1.0) == pytest.approx(0.3)


# ---- 2. ГЛАВНОЕ: ворота не трогаются ---------------------------------------

@pytest.mark.parametrize("ворота", ["Источники", "Мат", "Клаузула"])
def test_vorota_ne_trogayutsya(ворота):
    """Ворота режут насмерть: дёрнул клаузулу — звено осталось без кандидатов.
    Обещание панели «пусто не станет» держится ровно этим."""
    крив = {distort.МАСТЕР: [[0.0, 1.0], [1.0, 1.0]]}
    из = distort.применить(ПОЛНЫЕ, 0.5, крив, шум=1.0, rnd=random.Random(1))
    assert из[ворота] == ПОЛНЫЕ[ворота]


def test_povtor_ne_trogaetsya():
    """У «Повтора» нет шкалы, есть барьер 0/1. Сдвиг на 0.3 — не «чуть иначе»,
    а «как повезёт при округлении»."""
    крив = {distort.МАСТЕР: [[0.0, 0.9], [1.0, 0.9]]}
    assert distort.применить(ПОЛНЫЕ, 0.5, крив)["Повтор"] == 0


def test_vyklyuchennaya_svyaznost_ostayotsya_vyklyuchennoy():
    """−1 у связности значит «выключено», а не «край шкалы». Сдвиг оттуда
    включал бы её за спиной пользователя."""
    p = dict(ПОЛНЫЕ, **{"Связность": -1.0})
    крив = {distort.МАСТЕР: [[0.0, 1.0], [1.0, 1.0]]}
    assert distort.применить(p, 0.5, крив)["Связность"] == -1.0


def test_vklyuchennaya_svyaznost_vedyotsya():
    p = dict(ПОЛНЫЕ, **{"Связность": 0.2})
    крив = {distort.МАСТЕР: [[0.0, 0.5], [1.0, 0.5]]}
    assert distort.применить(p, 0.5, крив)["Связность"] == pytest.approx(0.7)


def test_sdvig_ne_vyvodit_za_shkalu():
    крив = {distort.МАСТЕР: [[0.0, 5.0], [1.0, -5.0]]}   # за пределами -1..1
    из = distort.применить(ПОЛНЫЕ, 0.0, крив)
    assert 0.0 <= из["Банальность"] <= 1.0
    из2 = distort.применить(ПОЛНЫЕ, 1.0, крив)
    assert 0.0 <= из2["Банальность"] <= 1.0


