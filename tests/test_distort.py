def test_brounovskiy_ne_stavim():
    """Пятым просился броуновский (случайное блуждание) — я его написала и
    убрала. На нашем масштабе он замерился неотличимым от розового: связь
    соседей 0.79 против 0.82 на тридцати точках, 0.94 против 0.97 на ста
    двадцати; другая нормировка не помогла. Разница между 1/f и 1/f² живёт на
    длинах, которых у серии нет.

    Пользователь просил «все известные типы», и соблазн поставить пятое имя был.
    Но имя, за которым стоит то же поведение, — украшение, а не выбор.

    Тест сторожит не отсутствие слова, а ОБЕЩАНИЕ: любые два типа обязаны
    отличаться хоть чем-то."""
    assert "броуновский" not in distort.ШУМЫ
    подписи = {т: подпись_шума(т) for т in distort.ШУМЫ}
    имена = list(distort.ШУМЫ)
    for i, a in enumerate(имена):
        for b in имена[i + 1:]:
            сa, ра = подписи[a]
            сb, рб = подписи[b]
            разошлись = abs(сa - сb) > 0.2 or abs(ра - рб) > 0.1
            assert разошлись, f"«{a}» и «{b}» ведут себя одинаково: {подписи[a]} vs {подписи[b]}"


