# «БАНАЛЬНОСТЬ» — ДВУСТОРОННЯЯ РУЧКА (Раунд 58, пункт 7 плана).
#
# Пользователь: «на минимуме всё максимально стремится к банальности, на максимуме
# максимально неклишированно и не банально, посередине как будто не работает».
#
# Три числа, а не выдача: на минимуме средняя сцепка выбранных ВЫШЕ средней по
# пулу, на максимуме НИЖЕ, в середине совпадает. Ровно так эту ручку и можно
# сломать незаметно — она продолжит двигаться и перестанет что-либо значить.

def test_ruchka_banalnosti_dvustoronnyaya():
    """Перевод положения в пороги: середина пустая, края противоположные."""
    class Индекс:                      # кванты ровные — проверяем НАПРАВЛЕНИЕ
        кванты_банальности = [i / 10.0 for i in range(101)]
        кванты_сцепки = [0.0] + [i / 10.0 for i in range(1, 101)]
    и = Индекс()
    import math

    середина = nlindex.ворота_банальности(0.5, и)
    assert середина == nlindex.Ворота(), "в середине ручка обязана не работать"

    свежо = nlindex.ворота_банальности(1.0, и)
    assert свежо.слова_верх < math.inf and свежо.слова_низ == -math.inf
    assert свежо.сцепка_верх == 0.0, "на максимуме сцепленные строки не проходят"

    банально = nlindex.ворота_банальности(0.0, и)
    assert банально.слова_низ > -math.inf and банально.слова_верх == math.inf
    assert банально.сцепка_низ > 0, "на минимуме требуется затасканная сцепка"

    # монотонность: чем дальше от середины, тем строже
    assert (nlindex.ворота_банальности(0.9, и).слова_верх
            > nlindex.ворота_банальности(1.0, и).слова_верх)
    assert (nlindex.ворота_банальности(0.1, и).слова_низ
            < nlindex.ворота_банальности(0.0, и).слова_низ)
    # сцепка вступает ТОЛЬКО во второй половине хода — у 70% строк её нет
    # вовсе, и раньше она была бы обрывом, а не наклоном
    assert nlindex.ворота_банальности(0.7, и).сцепка_верх == math.inf
    assert nlindex.ворота_банальности(0.3, и).сцепка_низ == -math.inf


@нет_индекса
def test_scepka_smeshchaet_vybor_v_obe_storony():
    """Три числа на живом корпусе: минимум выше среднего, максимум ниже.

    Это и есть обещание ручки. Если однажды колонка сцепки перестанет
    попадать в ворота (переименовали, забыли испечь, перепутали знак), тест
    упадёт здесь, а не через месяц на глазах у пользователя."""
    import numpy as np
    idx = nlindex.load()
    if getattr(idx, "bind", None) is None:
        pytest.skip("индекс испечён без колонки сцепки")
    сцепка = np.asarray(idx.bind)
    среднее_пула = float(сцепка.mean())

    def среднее(ручка):
        m = idx.gate_mask(nlindex.ворота_банальности(ручка, idx), no_mat=False)
        assert m.sum() > 1000, f"на ручке {ручка} доживает {int(m.sum())} строк — пул выжжен"
        return float(сцепка[m].mean())

    банально, середина, свежо = среднее(0.0), среднее(0.5), среднее(1.0)
    assert банально > середина, "на минимуме сцепка обязана быть ВЫШЕ средней"
    assert свежо < середина, "на максимуме сцепка обязана быть НИЖЕ средней"
    # «Посередине как будто не работает» — это про САМУ РУЧКУ, а не про весь
    # отбор: остальные ворота (тавтология, целые слова, два знаменательных
    # слова, чёрный список) стоят всегда и своё смещение вносят законно.
    # Поэтому сверяем маску в середине с маской вообще без ворот, а не
    # среднее по сырому пулу — первая версия теста сравнивала именно с ним и
    # ловила чужую работу.
    пустые = idx.gate_mask(nlindex.Ворота(), no_mat=False)
    в_середине = idx.gate_mask(nlindex.ворота_банальности(0.5, idx), no_mat=False)
    assert np.array_equal(пустые, в_середине), "в середине ручка что-то режет"
    assert среднее_пула > 0, "колонка сцепки пуста — мерить нечего"


