@нет_индекса
def test_seyanie_reshaet_vybor(книги):
    """Разные сёмена дают РАЗНЫЕ строфы, одно и то же — побитово ту же.

    Половина сторожа переехала сюда из tests/test_select_speed.py: там она
    называлась «ничьи не зависят от номера» и проверяла разведение равных
    кандидатов внутри сборщика. Сборщика нет, а свойство осталось и стало
    важнее: РАНЖИРОВАТЬ БОЛЬШЕ НЕЧЕМ (оценка у всех ровно 0.6, см. надгробие
    `nlindex._таблица`), то есть весь выбор держится на одном жребии. Умри
    случайность — и выдача при одних настройках повторялась бы дословно, ровно
    та жалоба, с которой всё началось."""
    тексты, _ = книги
    knobs = clean.knobs({"shortlist": 4, "classic": 0.0})

    def строфа(семя):
        res = filters.run([], knobs, Corpus(), nl_fragments=тексты,
                          rhyme="none", семя=семя)
        return tuple(r["text"] for r in res["shortlist"])

    видели = {строфа(с) for с in range(20)}
    assert len(видели) > 1, "разные сёмена дали одну строфу — случайность мертва"
    assert строфа(7) == строфа(7), "одно семя дало разные строфы — прогон не повторить"


