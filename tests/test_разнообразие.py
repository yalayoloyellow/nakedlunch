@нет_индекса
def test_chs_lovit_sklonenia_no_ne_sosedey():
    idx = nlindex.load()
    госпожа = set(nlindex.строки_правила(idx, "госпожа").tolist())
    assert госпожа, "в корпусе нет «госпожи» — тест бессмыслен"
    тексты = " ".join(idx.text(int(i)).lower() for i in list(госпожа)[:400])
