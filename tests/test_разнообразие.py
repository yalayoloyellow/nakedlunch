import pytest

import nlindex

нет_индекса = pytest.mark.skipif(nlindex.load() is None, reason="индекс не испечён")


@нет_индекса
def test_chs_ishchet_slovami_a_ne_podstrokoy():
    idx = nlindex.load()
    с = nlindex.строки_правила(idx, "с")
    список = nlindex.строки_правила(idx, "список")
    assert len(с) and len(список), "на этом корпусе нечего проверять"
    # «список» содержит «с» как подстроку — но не как СЛОВО, значит правило «с»
    # не смеет уносить строки, попавшие только под «список»
    только_список = set(список.tolist()) - set(с.tolist())
    assert только_список, "правило «с» съело все строки со «списком» — ищет подстрокой"


@нет_индекса
def test_chs_lovit_sklonenia_no_ne_sosedey():
    idx = nlindex.load()
    госпожа = set(nlindex.строки_правила(idx, "госпожа").tolist())
    assert госпожа, "в корпусе нет «госпожи» — тест бессмыслен"
    тексты = " ".join(idx.text(int(i)).lower() for i in list(госпожа)[:400])
    assert "госпож" in тексты
    # склонения обязаны попасть: ищем в выдаче форму, отличную от начальной
    assert any(ф in тексты for ф in ("госпожи", "госпожой", "госпожу", "госпоже")), (
        "правило поймало только начальную форму — склонения не ловятся")
    # А СОСЕД ПО НАЧАЛУ СЛОВА НЕ ЛОВИТСЯ. Пересечение множеств здесь ничего не
    # доказывает: строка может содержать оба слова разом, и это законно (первая
    # версия теста на этом и упала). Проверяем ровно нужное: строка, где есть
    # «господин» и НЕТ «госпож», под правило «госпожа» попадать не смеет.
    господин = nlindex.строки_правила(idx, "господин").tolist()
    чистые = [i for i in господин if "госпож" not in idx.text(int(i)).lower()]
    assert чистые, "в корпусе нет строк только с «господином» — проверять нечего"
    assert not (госпожа & set(чистые)), (
        "«господин» попал под правило «госпожа» — поиск идёт по началу слова")


