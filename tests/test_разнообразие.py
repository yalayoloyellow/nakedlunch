    assert any(ф in тексты for ф in ("госпожи", "госпожой", "госпожу", "госпоже")), (
        "правило поймало только начальную форму — склонения не ловятся")
    # А СОСЕД ПО НАЧАЛУ СЛОВА НЕ ЛОВИТСЯ. Пересечение множеств здесь ничего не
    # доказывает: строка может содержать оба слова разом, и это законно (первая
