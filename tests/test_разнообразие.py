def test_tema_suzhaet_namerenno():
    """С темой выбор обязан СМЕЩАТЬСЯ к релевантным. Проверяется по перцентилю:
    средний у выбранных выше среднего по пулу. Если не выше — тема не работает,
    и мы бы этого не заметили: выдача выглядела бы нормально."""
    строки = пул({"альфа": 300})
    for i, r in enumerate(строки):
        r["_pctl"] = i / (len(строки) - 1)          # ровная лесенка от 0 до 1
    средний_пул = sum(r["_pctl"] for r in строки) / len(строки)
    # Мерим ЯКОРЬ, а не всю строфу: тема обещает «строка точно в тему» ровно про
    # него, остальные слоты подбираются к нему по рифме и обязаны оставаться
    # разнообразными. Средний по строфе поэтому и равен среднему по пулу — это
    # не поломка, а устройство, и первая версия теста этого не учла.
    выбранные = []
    for семя in range(40):
        filters.закрепить_разброс(семя)
        выдача = filters._select_with_rhyme([dict(c) for c in строки], "аа", 2,
                                            set(range(2)), precision=0.0, theme_anchor=True)
        выбранные += [r.get("_pctl", 0.0) for r in выдача if r.get("anchor")]
    filters.закрепить_разброс(20260806)
    assert выбранные, "якоря темы не было ни в одной выдаче"
    средний_выбор = sum(выбранные) / len(выбранные)
    assert средний_выбор > средний_пул, (
        f"тема не сузила: средний перцентиль выбранных {средний_выбор:.3f} "
        f"против {средний_пул:.3f} по пулу")


