# КЭШ УДАРЕНИЙ: построчный формат (Раунд 57). Кнопка «пересчитать качество»
# падала молча, потому что проход поднимал 832 МБ JSON в память (~6 ГБ) и его
# убивала система. Формат сменён на построчный — память стала постоянной
# (замер: 292 МБ пика вместо шести гигабайт).
#
# Сторож на главное свойство перехода: читатель обязан ОДИНАКОВО отвечать на
# обоих форматах. Иначе миграция становится односторонней дверью, а откат —
# восстановлением часа работы модели ударений.

def test_kesh_chitaet_oba_formata(tmp_path, monkeypatch):
    import json as _j
    import кэш

    записи = {"строка раз": {"key": "аз", "banal": 3.1, "content": 2},
              "строка два": {"key": "ва", "banal": 4.2, "content": 2}}

    старый = tmp_path / "nl_rhyme.json"
    строчный = tmp_path / "nl_rhyme.jsonl"
    monkeypatch.setattr(кэш, "СТАРЫЙ", старый)
    monkeypatch.setattr(кэш, "СТРОЧНЫЙ", строчный)

    старый.write_text(_j.dumps(записи, ensure_ascii=False), "utf-8")
    assert not кэш.есть_строчный()
    assert кэш.читать_всё() == записи, "старый формат читается неверно"

    with кэш.Писатель(строчный) as п:
        for т, поля in записи.items():
            п.запиши(т, поля)
    assert кэш.есть_строчный()
    assert кэш.читать_всё() == записи, "построчный формат разошёлся со старым"


def test_kesh_pishet_celikom_ili_nikak(tmp_path, monkeypatch):
    """Проход упал посреди — прежний файл остаётся нетронутым.

    Именно круг «обрубок → читается как пустое → пишем поверх» стоил пользователю
    профилей сцены в этом же раунде. Здесь он закрыт на уровне записи."""
    import кэш
    строчный = tmp_path / "nl_rhyme.jsonl"
    monkeypatch.setattr(кэш, "СТРОЧНЫЙ", строчный)
    with кэш.Писатель(строчный) as п:
        п.запиши("целая", {"banal": 1.0})
    было = строчный.read_text("utf-8")

    try:
        with кэш.Писатель(строчный) as п:
            п.запиши("новая", {"banal": 2.0})
            raise RuntimeError("проход упал")
    except RuntimeError:
        pass
    assert строчный.read_text("utf-8") == было, "упавший проход испортил кэш"
    assert not list(tmp_path.glob("*.новый")), "обрубок остался на диске"


