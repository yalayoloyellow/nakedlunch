@pytest.fixture(scope="module")
def книги():
    """Три «книги» из настоящего корпуса — три несмежных участка по номерам.

    Берутся только строки, доживающие до выдачи (целые, не тавтология, со
    знаменательными словами, не под чёрным списком): иначе доля в пуле,
    которую тест считает, расходилась бы с долей, которую видит отбор."""
    idx = nlindex.load()
    if idx is None:
        pytest.skip("индекс не испечён")
    м = idx.whole_mask().copy()
    м &= np.asarray(idx.taut) == 0
    if getattr(idx, "content", None) is not None:
        м &= np.asarray(idx.content) >= nlindex.СЛОВ_МИН
    з = nlindex.запрет(nlindex._правила(), idx)
    if з["маска"] is not None:
        м &= ~з["маска"]
    годные = np.flatnonzero(м)
    шаг = len(годные) // 4
    участки = {"альфа": годные[:ДОЛИ["альфа"]],
               "бета": годные[шаг:шаг + ДОЛИ["бета"]],
               "гамма": годные[2 * шаг:2 * шаг + ДОЛИ["гамма"]]}
    чья, тексты = {}, []
    for имя, номера in участки.items():
        assert len(номера) == ДОЛИ[имя], "в корпусе не хватило строк на стенд"
        for i in номера:
            т = idx.text(int(i))
            чья[т] = имя
            тексты.append(т)
    assert len(set(тексты)) == len(тексты), "участки пересеклись — доли соврут"
    return тексты, чья


@pytest.fixture(scope="module")
def карта(книги):
    """Сколько строк каждой книги выпало за ПРОГОНОВ прогонов.

    Прогоны идут через весь каскад (`filters.run` без схемы), а не через
    внутренний хелпер: сторож на хелпере остался бы зелёным, если хелпер
    перестанут звать, — а именно так и вышло с долей мата (bug_002)."""
    тексты, чья = книги
    knobs = clean.knobs({"shortlist": 2, "classic": 0.0})
    счёт = Counter()
    for семя in range(ПРОГОНОВ):
        res = filters.run([], knobs, Corpus(), nl_fragments=тексты,
                          rhyme="none", семя=семя)
        for r in res["shortlist"]:
            счёт[чья[r["text"]]] += 1
    return счёт


