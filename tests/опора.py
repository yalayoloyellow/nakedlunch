# nakedlunch — общие условия пропуска для тестов, которым нужен НАСТОЯЩИЙ корпус.
#
# ЗАЧЕМ ЭТО ЗАВЕЛОСЬ. Три файла тестов писали пропуск так:
#
#     нет_индекса = pytest.mark.skipif(nlindex.load() is None, reason="индекс не испечён")
#
# Условие спрашивает «индекс вообще есть?», а тесту нужно другое — «индекс
# БОЛЬШОЙ». На стенде с индексом из восьми строк они не пропускались, а падали
# с чужой причиной: «корпус слишком мал, чтобы набрать правила». Поймано, когда
# после живой проверки в изолированном доме остался маленький индекс.
#
# Красный тест, который врёт о причине, хуже пропущенного: человек идёт чинить
# то, что не ломалось. Это тот же класс, что и вылеченные сегодня сторожа,
# спрашивавшие про существование конкретного файла вместо того, что реально
# будет прочитано.
#
# Список здесь ОДИН на всех потребителей нарочно: три копии одного условия в
# этом проекте разошлись бы с гарантией — так уже было и с прогревом, и с
# кэшем ударений, и с ключами профиля сцены.

from __future__ import annotations

import pytest

import nlindex

# Сколько строк считается «настоящим корпусом». Порог не выведен формулой, а
# взят с запасом от того, чего требуют сами тесты: `test_чс_скорость` набирает
# правила из корпуса и падает, если их не хватает, `test_разнообразие` считает
# доли по выдаче. Боевой индекс — 2.4 млн строк, стенды живых проверок — от
# пяти до нескольких тысяч. Любое число в этом промежутке разделяет их одинаково;
# взято круглое, и оно названо здесь, а не спрятано в трёх файлах.
МАЛО_СТРОК = 100_000


def _размер() -> int:
    idx = nlindex.load()
    return 0 if idx is None else int(idx.n)


def мал_или_нет_индекса() -> bool:
    return _размер() < МАЛО_СТРОК


нужен_большой_индекс = pytest.mark.skipif(
    мал_или_нет_индекса(),
    reason=f"нужен настоящий корпус (в индексе меньше {МАЛО_СТРОК:_} строк)".replace("_", " "),
)
