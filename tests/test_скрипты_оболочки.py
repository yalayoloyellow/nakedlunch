# nakedlunch — скрипты оболочки в репозитории: разбор и имена переменных.
#
# ЗАЧЕМ. Сторож на кириллические имена переменных уже был, но смотрел ТОЛЬКО в
# .github/workflows (tests/test_workflows.py). Скрипты, которые запускает
# человек, — ярлык, run.command, перенос — не проверял никто, и первый же из
# них, написанный с `КОРЕНЬ=`, лёг: zsh на macOS не берёт кириллицу в именах
# переменных вовсе и отвечает «bad substitution» без указания, что именно
# плохо. Ошибка воспроизводилась ровно там, где её меньше всего ждут: у
# человека на чужой машине, при первом запуске.
#
# Здесь проверяется то же правило и разбор без выполнения (`zsh -n`).
#
# Прогон: .venv/bin/python -m pytest tests/test_скрипты_оболочки.py -q

import re
import subprocess
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent

# Имя переменной оболочки по POSIX: буква или подчёркивание, дальше буквы,
# цифры, подчёркивания. Кириллица сюда не входит ни в каком виде.
ПРИСВОЕНИЕ = re.compile(r"^[ \t]*(?:local[ \t]+|export[ \t]+)?([А-Яа-яЁё_][А-Яа-яЁё0-9_]*)=", re.M)
# Подстановка: $имя, ${имя}, ${#имя}, ${имя[...]}
ПОДСТАНОВКА = re.compile(r"\$\{?#?([А-Яа-яЁё][А-Яа-яЁё0-9_]*)")


def скрипты() -> list[Path]:
    """Все скрипты оболочки репозитория, кроме чужих (.venv, node_modules)."""
    найдено = []
    for шаблон in ("*.sh", "*.command"):
        найдено += [p for p in КОРЕНЬ.rglob(шаблон)
                    if not any(ч in p.parts for ч in (".venv", "node_modules", "dist", "build"))]
    # ярлык — файл без расширения, но это тоже скрипт оболочки
    ярлык = КОРЕНЬ / "nakedlunch.app" / "Contents" / "MacOS" / "nakedlunch"
    if ярлык.is_file():
        найдено.append(ярлык)
    return sorted(найдено)


def test_скрипты_вообще_нашлись():
    """Пустой список тестов — зелёный тест ни о чём."""
    assert скрипты(), "не нашлось ни одного скрипта оболочки — сторож смотрит не туда"


@pytest.mark.parametrize("файл", скрипты(), ids=lambda p: p.name)
def test_имена_переменных_только_латиницей(файл):
    """zsh не берёт кириллицу в именах переменных и говорит «bad substitution».

    Сообщение не называет ни файла, ни строки. Поймать это глазами нельзя —
    только сторожем."""
    текст = файл.read_text(encoding="utf-8")
    # комментарии выкидываем: в них кириллица уместна и обязательна
    без_комментариев = "\n".join(
        ("" if с.lstrip().startswith("#") else с) for с in текст.splitlines())
    беда = ПРИСВОЕНИЕ.findall(без_комментариев) + ПОДСТАНОВКА.findall(без_комментариев)
    assert not беда, (
        f"{файл.relative_to(КОРЕНЬ)}: кириллические имена переменных "
        f"{sorted(set(беда))} — zsh ответит «bad substitution» без указания места")


@pytest.mark.parametrize("файл", скрипты(), ids=lambda p: p.name)
def test_скрипт_разбирается(файл):
    """`zsh -n` — разбор без выполнения. Ловит то, что переживает беглый взгляд."""
    if not (КОРЕНЬ / ".git").exists():
        pytest.skip("не репозиторий")
    п = subprocess.run(["zsh", "-n", str(файл)], capture_output=True, text=True)
    assert п.returncode == 0, (
        f"{файл.relative_to(КОРЕНЬ)} не разбирается:\n{п.stderr.strip()}")
