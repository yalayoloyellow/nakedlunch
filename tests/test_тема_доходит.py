# nakedlunch — ТЕМА ДОХОДИТ ДО ВЫДАЧИ (Раунд 62, волна B: B2 и B3).
#
# ЧТО БЫЛО ЗАМЕРЕНО НА НАСТОЯЩЕМ КОРПУСЕ (2026-08-14, пул 800 000, умолчания
# приложения, 25 прогонов с РАЗНЫМИ семенами на каждую тему):
#
#   тема «ночь»   — 25 строк с темой, и все двадцать пять ОДНА И ТА ЖЕ строка;
#   тема «война»  — то же, одна строка на 25 прогонов;
#   тема «деньги» — НОЛЬ строк с темой при 4 670 подходящих в корпусе.
#
# Три причины, все три чинятся здесь:
#
# 1. ЯКОРЬ ДЕТЕРМИНИРОВАН. Он брал argmax перцентиля, а перцентиль — это ранг:
#    значения разные по построению, ничьих нет, и случайный тай-брейк не
#    срабатывает никогда. Один и тот же фрагмент корпуса, сколько семян ни меняй.
#
# 2. СРЕЗ БУКВАЛЬНЫХ БИЛ ПО ПУЛУ. `literal_cap` обещал «≈1 на строфу», а
#    применялся ко всему пулу: срезано 728 из 730 на «ночи», 1 185 на «деньгах».
#    Причём выбирались выжившие по `score` — то есть по близости к полосе
#    связности, а не по релевантности, и при умолчании выживали САМЫЕ ДАЛЁКИЕ
#    от темы из буквальных.
#
# 3. ПРИЗНАК БЫЛ НЕ ТОТ. `token_hits` ловит точную словоформу: «война» — да,
#    «войны», «войне», «войну» — нет, а таких форм в корпусе двенадцать.
#
# Стало: якорь берёт случайного из полосы близких к лучшему; предел «не больше
# одной буквальной на строфу» стоит при сборке, где строфа и есть, и считает по
# ЛЕММЕ; якорь предпочитает буквальные, потому что предел делает это безопасным.
#
# Замер после: 25/25 строф с темой на всех трёх темах, разных строк 15 / 9 / 11,
# строф с двумя буквальными — НИ ОДНОЙ (99.2% ровно с одной, 0.8% без).
#
# Прогон: .venv/bin/python -m pytest tests/test_тема_доходит.py -q

import sys
from pathlib import Path

import pytest
from conftest import нет_векторов  # noqa: F401

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "core"))

import clean
import filters
import nlbridge
from corpus import Corpus, lemmatize

# Пул НАРОЧНО крупный и однородный: на десятке строк любой отбор сойдётся сам,
# и тест был бы зелёным при полностью сломанном якоре.
С_ТЕМОЙ = [f"деньги кончились в среду {i}" for i in range(40)]
ФОРМЫ = [f"платил деньгами за проезд {i}" for i in range(20)]   # другая словоформа
БЕЗ_ТЕМЫ = [f"снег лежал на крыше дома {i}" for i in range(200)]
ВСЕ = С_ТЕМОЙ + ФОРМЫ + БЕЗ_ТЕМЫ
ЛЕММЫ_ТЕМЫ = set(lemmatize("деньги"))


@pytest.fixture()
def словарь(monkeypatch):
    fake = {t: {"banal": 3.0, "taut": False, "lemmas": lemmatize(t),
                "tokens": list(nlbridge._tokens(t)), "key": "еды" if "среду" in t else "оме",
                "span": None}
            for t in ВСЕ}
    monkeypatch.setattr(filters, "_NL_RHYME", fake)
    # Колоночный путь НАРОЧНО выключен: он проверяется на живом индексе
    # отдельно, а смешивать два пути в одном тесте значит не знать, какой из
    # них проверен.
    monkeypatch.setattr(filters, "_index_for_current_cache", lambda *a, **k: None)


def прогон(семя, тема="деньги", схема="аабб", size=8):
    knobs = clean.knobs({"shortlist": size, "real_text": 1.0, "cohesion": 0.5})
    r = filters.run([], knobs, Corpus(), nl_fragments=ВСЕ, rhyme=схема,
                    tags=clean.theme(тема), семя=семя)
    return r["shortlist"]


def буквальных(строки) -> int:
    return sum(1 for s in строки if ЛЕММЫ_ТЕМЫ & set(lemmatize(s["text"])))


@нет_векторов
def test_yakor_ne_odna_i_ta_zhe_stroka(словарь):
    """ГЛАВНОЕ B2: разные семена дают РАЗНЫЕ тематические строки.

    Сторож именно на поломку: до правки здесь была бы ровно одна строка на все
    двадцать прогонов, потому что перцентиль не даёт ничьих."""
    якоря = set()
    for семя in range(20):
        якоря |= {s["text"] for s in прогон(семя) if s.get("anchor")}
    assert len(якоря) >= 5, f"якорь почти не разбрасывается: {len(якоря)} разных на 20 семян"


@нет_векторов
def test_ne_bolshe_odnoy_bukvalnoy_na_strofu(словарь):
    """ГЛАВНОЕ B3, и это ЖИВАЯ жалоба 2026-07-17: тема «деньги» дала слово
    буквально в 19 строках из 20. Предел обязан держаться на КАЖДОЙ строфе, а
    не в среднем по выдаче."""
    for семя in range(15):
        строки = прогон(семя, схема="аабб", size=8)
        for н in range(0, len(строки) - 3, 4):
            строфа = строки[н:н + 4]
            assert буквальных(строфа) <= 1, \
                f"в строфе {буквальных(строфа)} буквальных: {[s['text'] for s in строфа]}"


@нет_векторов
def test_tema_voobshche_dohodit(словарь):
    """Обратная сторона предела: он не должен превратиться в запрет. Тема
    обязана появляться, иначе «не больше одной» вырождается в «ни одной»."""
    было = sum(1 for семя in range(15) if буквальных(прогон(семя)) > 0)
    assert было >= 12, f"тема дошла лишь в {было} прогонах из 15"


@нет_векторов
def test_bukvalnost_schitaetsya_po_lemme(словарь):
    """Третья причина: признак «буквально» ловил точную словоформу. Для
    человека «деньги» и «деньгами» — одно слово, и предел обязан считать их
    вместе, иначе строфа получит обе."""
    формы = set(ФОРМЫ)
    for семя in range(15):
        строки = прогон(семя)
        for н in range(0, len(строки) - 3, 4):
            строфа = [s["text"] for s in строки[н:н + 4]]
            вместе = sum(1 for т in строфа if т in формы) + \
                     sum(1 for т in строфа if т in set(С_ТЕМОЙ))
            assert вместе <= 1, f"разные формы одного слова прошли вдвоём: {строфа}"


@нет_векторов
def test_yakor_predpochitaet_bukvalnuyu(словарь):
    """Якорь — это обещание «строка точно в тему», то есть слово ВИДНО.
    Релевантность его не даёт: она среднее по леммам и разбавляется длиной —
    у темы «деньги» лучший буквальный фрагмент стоял по перцентилю 34-м."""
    попал = 0
    for семя in range(15):
        якоря = [s for s in прогон(семя) if s.get("anchor")]
        попал += sum(1 for s in якоря if ЛЕММЫ_ТЕМЫ & set(lemmatize(s["text"])))
    assert попал >= 12, f"якорь берёт буквальную лишь {попал} раз на 15 прогонов"
