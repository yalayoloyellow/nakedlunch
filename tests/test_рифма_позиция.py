# РИФМА ЛЮБЫМ СЛОВОМ И ОСЬ ПОЗИЦИИ (2026-08-30).
#
# Слово владельца: «рифма так-то не только в конце существует. Может быть и
# первым, и вторым, и третьим любым словом. В этом и суть».
#
# ЧТО ПОЯВИЛОСЬ. У строки теперь не один рифмо-ключ (последнего слова), а
# ключи ВСЕХ знаменательных слов с позицией от конца — колонки wk_ids/wk_pos/
# wk_off. Ось «позиция рифмы» — маска сортов: 1 конечная (последнее слово),
# 2 внутренняя (1-2 слова от конца), 4 начальная (дальше).
#
# ГРАНИЦА ВЗЯТА ЗАМЕРОМ: проба 200 000 живых пар показала, что при рифме «где
# угодно» 7.6% пар физически не слышны (оба слова в середине длинных строк), а
# при ограничении последними тремя словами мусора ноль. Отсюда «внутренняя»
# кончается на второй позиции.
import sys
