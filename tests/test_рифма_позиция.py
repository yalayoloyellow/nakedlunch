# дословно: «может я хочу 20 процентов где на первое слово рифма, 50 процентов
# в середине и 30 процентов в конце».
import доли  # noqa: E402

from опора import нужен_большой_индекс  # noqa: E402


def _расклад(заказ, n=40, семя=5):
    """Фактические доли позиций в выдаче тяги на ЖИВОМ корпусе."""
    idx = nlindex.load()
    таб, _ = nlindex._таблица(idx, False, False, 7)
    счёт = {}
    nlindex.тянуть_строфы(idx, таб, [(5, 9), (5, 9)], "аа", n,
                          np.random.default_rng(семя),
                          ярусы_рифмы=nlindex.ЯРУС_ТОЧНАЯ, позиции_рифмы=7,
                          доли_позиций=доли.разобрать(заказ, 7), счёт=счёт)
    к = счёт.get("поз_конечных", 0)
    в = счёт.get("поз_внутренних", 0)
    н = счёт.get("поз_начальных", 0)
    всего = к + в + н
    assert всего, "тяга ничего не собрала — замер бессмыслен"
    return (100 * к / всего, 100 * в / всего, 100 * н / всего)


@нужен_большой_индекс
def test_двадцать_пятьдесят_тридцать():
    """Заказ владельца слово в слово. Допуск ±6 п.п.: на сорока строках одна
    строка весит 2.5 пункта, и требовать точности до процента значило бы
    сторожить округление, а не механизм."""
    конец, середина, начало = _расклад("1:20,2:50,4:30")
    for имя, факт, ждём in (("конец", конец, 20), ("середина", середина, 50),
                            ("начало", начало, 30)):
        assert abs(факт - ждём) <= 6, \
            f"{имя}: {факт:.0f}% против заказанных {ждём}%"


@нужен_большой_индекс
def test_сто_процентов_полоской_не_берутся_а_маской_берутся():
    """Полоска долей не даёт ста процентов — их даёт ЧИП, и это правило.

    Слово владельца дословно: «если мы вообще что-то делим на доли — мы нигде
    100 процентов и не можем указать; а если хотим сто процентов, это чип».
    Поэтому каждому ВКЛЮЧЁННОМУ сорту достаётся минимум (`доли.МИНИМУМ` = 2%),
    и заказ «4:100» честно отдаёт началу около 96, а не все сто: два процента
    остаются конечной и два внутренней. Чистые сто берутся выключением сортов
    в маске — вот вторая половина сторожа."""
    конец, середина, начало = _расклад("4:100")
    assert начало > 90, f"начало забрало лишь {начало:.0f}%"
    assert начало < 100, "полоска отдала все сто — значит МИНИМУМ не работает"
    assert конец + середина > 0, "остальным сортам не досталось даже минимума"

    # А теперь — чип: в маске один сорт, и он берёт всё без всяких долей.
    idx = nlindex.load()
    таб, _ = nlindex._таблица(idx, False, False, 7)
    счёт = {}
    nlindex.тянуть_строфы(idx, таб, [(5, 9), (5, 9)], "аа", 40,
                          np.random.default_rng(5),
                          ярусы_рифмы=nlindex.ЯРУС_ТОЧНАЯ,
                          позиции_рифмы=nlindex.ПОЗ_НАЧАЛЬНАЯ, счёт=счёт)
    всего = (счёт.get("поз_конечных", 0) + счёт.get("поз_внутренних", 0)
             + счёт.get("поз_начальных", 0))
    assert всего, "тяга ничего не собрала — замер бессмыслен"
    assert счёт.get("поз_начальных", 0) == всего, \
        "чип обязан давать ровно сто процентов, иначе он не чип"


