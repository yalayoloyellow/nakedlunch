# ── СТРОФА ПРИЕЗЖАЕТ ЦЕЛОЙ: ГРАНИЦЫ И МЕСТА В СХЕМЕ ─────────────────────────
#
# ЧТО БЫЛО (найдено разбором 2026-09-02, подтверждено замером). Позиция, которую
# не удалось заполнить, выпадала из ответа, а ответ уходил ПЛОСКИМ списком без
# единого признака, где кончается одна строфа. Лента резала его строго по длине
# схемы, и один короткий блок сдвигал всё, что идёт после него.
#
# Замер на боевом корпусе (вилка 8-9, абаб, заказ 20 строк, три семени;
# считались пары строк, которым ДОСТАЛАСЬ ОДНА БУКВА, и проверялось, рифмуют ли
# они по канону движка `nlindex.ярус_пары`):
#
#   ворота          пар одной буквы   НЕ рифмуют — было → стало
#   умолчание             30            0 (0%)   →   0 (0%)
#   только точные         28            4 (14%)  →   0 (0%)
#   близкая               24           22 (91%)  →   0 (0%)
#   перекличка            16           13 (81%)  →   0 (0%)
#
# Отбрасывать неполный блок целиком было первой мыслью и оказалось слишком
# дорого: заказ в 12 строк отдавал 4, а «перекличка» — то 4, то 0.

_ИДХ = nlindex.load()
нет_боевого = pytest.mark.skipif(_ИДХ is None, reason="индекс не испечён")
# Прорежённый корпус, как в tests/test_семя.py: на синтетике блоки не бывают
# неполными, а весь корпус стоил бы минуты на прогон.
_ПУЛ = ([_ИДХ.text(i) for i in range(0, _ИДХ.n, max(1, _ИДХ.n // 20_000))]
        if _ИДХ is not None else [])


@нет_боевого
def test_строка_знает_свою_строфу_и_своё_место():
    """`_блок` и `_поз` есть у КАЖДОЙ строки, и по ним собирается строфа.

    Без `_блок` показывающий не знает границ строф; без `_поз` он не знает,
    какая буква схемы досталась строке, — блок «а б а б», потерявший вторую
    строку, приезжает тройкой, и по порядку она читалась бы как «а б а»."""
    строфа = clean.stanza_spec([{"letter": б, "min_syl": 8, "max_syl": 9} for б in "абаб"])
    схема = clean.stanza_letters(строфа)
    строки = filters.run([], clean.knobs({"shortlist": 12, "rhyme_tiers": 2}), Corpus(),
                         nl_fragments=_ПУЛ, rhyme=схема, stanza=строфа,
                         семя=1)["shortlist"]
    assert строки, "прогон пуст — тест ни о чём"
    for r in строки:
        assert "_блок" in r, f"у строки нет номера строфы: {r.get('text')!r}"
        assert "_поз" in r, f"у строки нет места в схеме: {r.get('text')!r}"
        assert 0 <= r["_поз"] < len(схема), f"место вне схемы: {r['_поз']}"
    # блоки идут подряд и не перемешаны: группировка «пока номер тот же» верна
    номера = [r["_блок"] for r in строки]
    assert номера == sorted(номера), f"блоки перемешаны: {номера}"


@нет_боевого
def test_у_строк_одной_буквы_рифма_есть():
    """ГЛАВНЫЙ СТОРОЖ. Две строки, которым досталась одна буква схемы, обязаны
    рифмовать по тому же правилу, каким движок их и подбирал.

    Проверяется на УЗКИХ воротах — «близкая» и «перекличка»: именно там блоки
    приходят неполными, и именно там строфа разъезжалась почти всегда."""
    строфа = clean.stanza_spec([{"letter": б, "min_syl": 8, "max_syl": 9} for б in "абаб"])
    схема = clean.stanza_letters(строфа)
    # ПАР ТРЕБУЕМ НЕ С КАЖДЫХ ВОРОТ. Пул здесь прорежён до двадцати тысяч, и
    # «перекличка» на нём пар одной буквы не даёт вовсе — блоки приходят по
    # одной-две строки. Это честное свойство узких ворот на бедном пуле, а не
    # поломка; поэтому непустоту спрашиваем со ВСЕГО теста, а строгость рифмы —
    # с каждой найденной пары, на любых воротах.
    всего_пар = 0
    for доп, ярусы in (({"rhyme_tiers": 2}, 2), ({"echo": 1}, 3)):
        пар = 0
        for семя in (1, 2, 3):
            строки = filters.run([], clean.knobs(dict({"shortlist": 20}, **доп)), Corpus(),
                                 nl_fragments=_ПУЛ, rhyme=схема, stanza=строфа,
                                 семя=семя)["shortlist"]
            группы: dict = {}
            for r in строки:
                группы.setdefault(r["_блок"], []).append(r)
            for блок in группы.values():
                for i in range(len(блок)):
                    for j in range(i + 1, len(блок)):
                        if схема[блок[i]["_поз"]] != схема[блок[j]["_поз"]]:
                            continue
                        пар += 1
                        к1 = блок[i].get("rhyme") or ""
                        к2 = блок[j].get("rhyme") or ""
                        assert к1 and к2 and (nlindex.ярус_пары(к1, к2) & ярусы), (
                            f"строки одной буквы не рифмуют при {доп}:\n"
                            f"  {блок[i]['text']!r} (ключ {к1!r})\n"
                            f"  {блок[j]['text']!r} (ключ {к2!r})")
        всего_пар += пар
    assert всего_пар, "не набралось ни одной пары одной буквы — тест ни о чём"
