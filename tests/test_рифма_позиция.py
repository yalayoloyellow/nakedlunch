def test_биты_позиции_по_замеру():
    assert nlindex.бит_позиции(0) == nlindex.ПОЗ_КОНЕЧНАЯ
    assert nlindex.бит_позиции(1) == nlindex.ПОЗ_ВНУТРЕННЯЯ
    assert nlindex.бит_позиции(2) == nlindex.ПОЗ_ВНУТРЕННЯЯ
    assert nlindex.бит_позиции(3) == nlindex.ПОЗ_НАЧАЛЬНАЯ
    assert nlindex.бит_позиции(9) == nlindex.ПОЗ_НАЧАЛЬНАЯ


class _Идх:
    """Четыре строки. Пара «олу» сходится ВНУТРЕННИМ словом одной строки и
    последним другой — ровно тот случай, ради которого ось заведена
    (живой пример из замера: «исполнявших волю начальства» / «Бросил школу»)."""
    keys = ["", "олу", "альства", "ачник", "ыло"]
    #        текст                          ключи (id, позиция от конца)
    строки = [
        ("исполнявших волю начальства", [(1, 1), (2, 0)]),
        ("неудачник бросил школу",      [(3, 2), (1, 0)]),
        # обе позиции 3+ — это НАЧАЛЬНАЯ у обеих: пара, достижимая только
        # когда владелец включил третий сорт сознательно
        ("это было очень давно тому",   [(4, 3)]),
        ("а тут совсем другое дело",    [(4, 4)]),
    ]

    def __init__(self):
        n = len(self.строки)
        self.n = n
        self.syl = np.full(n, 7, dtype=np.uint16)
        self.mat = np.zeros(n, dtype=np.uint8)
        self.clau = np.ones(n, dtype=np.int8)
        self.lem_off = np.arange(n + 1)
        self.lem_ids = np.arange(n)
        # рифмо-хвост строки — последний ключ (как в боевом индексе)
        self.key_id = np.array([пары[-1][0] for _т, пары in self.строки])
        плоские, позы, оф = [], [], [0]
        for _т, пары in self.строки:
            for k, п in пары:
                плоские.append(k)
                позы.append(п)
            оф.append(len(плоские))
        self.wk_ids = np.array(плоские, dtype=np.int32)
        self.wk_pos = np.array(позы, dtype=np.uint8)
        self.wk_off = np.array(оф, dtype=np.int64)

    def text(self, i):
        return self.строки[int(i)][0]


@pytest.fixture
def стенд(monkeypatch):
    monkeypatch.setattr(nlindex, "_строки", lambda idx, ids, оц, пц: [
        {"text": idx.text(int(i)), "rhyme": idx.keys[int(idx.key_id[int(i)])]}
        for i in ids])
    monkeypatch.setattr(nlindex, "_пустой_ключ", lambda idx: 0)
    return _Идх()


def _строфа(идх, позиции, семя=0):
    return nlindex.тянуть_строфы(идх, np.arange(идх.n), [(1, 30), (1, 30)], "аа", 2,
                                 np.random.default_rng(семя),
                                 ярусы_рифмы=nlindex.ЯРУС_ТОЧНАЯ,
                                 позиции_рифмы=позиции)


def test_только_конечная_не_видит_внутренней_пары(стенд):
    """Прежнее поведение: рифмуется только последнее слово. Пара «волю/школу»
    не собирается — у первой строки «олу» стоит вторым с конца."""
    for семя in range(8):
        строфа = _строфа(стенд, nlindex.ПОЗ_КОНЕЧНАЯ, семя)
        тексты = {r["text"] for r in строфа}
        assert "исполнявших волю начальства" not in тексты or len(строфа) < 2, \
            "конечная рифма не должна ловить внутреннее слово"


def test_внутренняя_позиция_даёт_новую_пару(стенд):
    """Разрешили внутреннюю — пара «волю/школу» становится достижимой.
    Это и есть выгода: у строк, у которых конец не рифмует, появляется партнёр."""
    нашлась = False
    for семя in range(12):
        тексты = {r["text"] for r in _строфа(стенд, nlindex.ПОЗ_КОНЕЧНАЯ | nlindex.ПОЗ_ВНУТРЕННЯЯ, семя)}
        if тексты == {"исполнявших волю начальства", "неудачник бросил школу"}:
            нашлась = True
            break
    assert нашлась, "пара по внутреннему слову не собралась ни на одном семени"


def test_начальная_отдельным_сортом(стенд):
    """Третья и дальше позиция — отдельный сорт: включать её приходится
    сознательно, потому что замер показал там весь неслышный мусор."""
    нашлась = False
    for семя in range(12):
        тексты = {r["text"] for r in _строфа(стенд, nlindex.ПОЗ_НАЧАЛЬНАЯ, семя)}
        if тексты == {"это было очень давно тому", "а тут совсем другое дело"}:
            нашлась = True
            break
    assert нашлась, "пара по началу строки недостижима при включённой начальной"

    for семя in range(8):
        тексты = {r["text"] for r in _строфа(стенд, nlindex.ПОЗ_КОНЕЧНАЯ, семя)}
        assert тексты != {"это было очень давно тому", "а тут совсем другое дело"}, \
            "начальная пара пролезла при «только конечная»"
