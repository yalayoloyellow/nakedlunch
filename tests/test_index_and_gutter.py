def test_lag_schitaet_imenno_otsutstvuyushie(индекс):
    """ПОЧИНКА ПОЧИНКИ. Первая версия считала разницей «фрагментов минус строк
    индекса» — и на живых данных дала «6 075 строк вне индекса» при том, что
    вне его НОЛЬ: фрагментов больше, чем разных текстов (17 886 дублей), а в
    индексе вдобавок живут тексты удалённых источников. Строка, заведённая
    против вранья, начала врать сама.

    Считать надо ровно то, что спрашивают: сколько текстов индекс не знает."""
    assert nlindex.lag(["первый", "второй", "третий"], 3) == 0
    nlindex._lag_cache = None
    assert nlindex.lag(["первый", "новая книга"], 2) == 1
    nlindex._lag_cache = None
    # текстов МЕНЬШЕ, чем строк в индексе (удалили источник) — это не отставание
    assert nlindex.lag(["первый"], 1) == 0


def test_lag_ne_schitaet_zanovo_na_kazhdyy_opros(индекс):
    """0.4 с на 2.87 млн — недорого, но не раз в полсекунды. Кэш по числу
    поданных: состав меняется только когда пользователь трогает источники."""
    считано = []

    class Считающий(list):
        def __iter__(self):
            считано.append(1)
            return super().__iter__()

    тексты = Считающий(["первый", "чужой"])
    assert nlindex.lag(тексты, 2) == 1
    assert nlindex.lag(тексты, 2) == 1
    assert len(считано) == 1, "пересчитывает на каждый опрос"


