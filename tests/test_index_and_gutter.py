# Осталась ПЕРВАЯ половина файла — про честный ответ «сколько ещё не доехало»,
# она к букве отношения не имеет.

def test_procent_okruglyaetsya_vniz():
    """«100%» обязано значить «не осталось ни одной строки». На живой машине
    пользователя было 2 868 100 из 2 874 175 — 99.79%, round давал «100%», и
    именно из этой сотни следовал вывод «книга готова», хотя шесть тысяч
    строк не доехали. Проверяем правило, а не конкретный роут: округление
    вниз — единственное, при котором сотня не врёт."""
    всего, готово = 2_874_175, 2_868_100
    assert int(100 * готово / всего) == 99
    assert round(100 * готово / всего) == 100, "round здесь и врал"


# ---- цепочка сборок: индекс печётся ПОСЛЕ кэша рифм ------------------------

def test_sledushiy_shag_zhdyot_predydushiy():
    """У загруженной книги два шага, и второй печётся ИЗ первого. Параллельно
    запускать бессмысленно: индекс испёк бы ровно то, что было ДО книги."""
    import subprocess as sp
    import jobs
    порядок = []
    p = sp.Popen([sys.executable, "-c", "import time; time.sleep(0.3)"])
    поток = jobs.then(p, lambda: порядок.append("индекс"))
    порядок.append("рифмы идут")
    поток.join(timeout=10)
    assert порядок == ["рифмы идут", "индекс"], порядок
    assert p.poll() is not None, "следующий шаг начался, не дождавшись предыдущего"


def test_padenie_sledushego_shaga_ne_molchit():
    """Оборванная цепочка без единого признака — это ровно та порода, из-за
    которой книга «загружалась» и не появлялась в выдаче."""
    import subprocess as sp
    import jobs
    беды = []
    p = sp.Popen([sys.executable, "-c", "pass"])
    поток = jobs.then(p, lambda: (_ for _ in ()).throw(RuntimeError("сборка упала")),
                      on_error=беды.append)
    поток.join(timeout=10)
    assert беды and "сборка упала" in str(беды[0])
