def test_forget_zabyvaet_index_i_karty():
    """Перепечь бессмысленна, если процесс продолжает читать старое: `_idx` и
    карта «текст → номер» живут всю жизнь процесса — значит новая книга
    появилась бы только после перезапуска окна."""
    nlindex._idx = type("И", (), {"n": 7})()
    nlindex._tried = True
    nlindex._text_ids = {"строка": 0}
    nlindex._pool_cache = (("ключ",), None)
    nlindex._lag_cache = (7, 0)
    nlindex.forget()
    assert nlindex._idx is None and nlindex._tried is False
    assert nlindex._text_ids is None and nlindex._pool_cache is None
    assert nlindex._lag_cache is None, "ответ «всё доехало» пережил перепечь"


def test_mask_of_molcha_propuskaet_neindeksnoe():
    """ПРИЧИНА бага, зафиксированная тестом: фрагмент, которого нет в индексе,
    не попадает в маску — и дальше по всему пути он невидим. Это не дефект
    `mask_of`, а её контракт; дефектом было отсутствие перепечи."""
    class Индекс:
        n = 2
    monkeypatch_texts = {"есть в индексе": 0, "тоже есть": 1}
    прежний = nlindex.text_ids
    nlindex.text_ids = lambda idx: monkeypatch_texts
    try:
        m = nlindex.mask_of(Индекс(), ["есть в индексе", "новой книги строка", "тоже есть"])
    finally:
        nlindex.text_ids = прежний
    assert int(m.sum()) == 2, "неиндексный фрагмент обязан выпасть — и это надо чинить перепечью"


