# ДОЛИ ПО ЯРУСАМ РИФМЫ (2026-08-30) — третья и последняя ось долей.
#
# требование о самом принципе: «ручки мы делаем многовыборными… может я
# хочу 20 процентов где на первое слово рифма, 50 процентов в середине и 30
# процентов в конце. В целом многовыборность это важный принцип».
#
# Ярус — свойство ПАРЫ, а не строки: его определяет совпадение двух ключей.
# Поэтому жребий тянется на рифмо-группу и платит по факту — тем ярусом,
# которым партнёр реально сошёлся с якорем.
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))
import nlindex  # noqa: E402
import доли  # noqa: E402

from опора import нужен_большой_индекс  # noqa: E402


def _расклад(заказ, маска=15, n=60, семя=5):
    """Фактический расклад ярусов в выдаче прямой тяги на ЖИВОМ корпусе."""
    idx = nlindex.load()
    таб, _ = nlindex._таблица(idx, False, False, 7)
    счёт = {}
    nlindex.тянуть_строфы(idx, таб, [(5, 9), (5, 9)], "аа", n,
                          np.random.default_rng(семя), ярусы_рифмы=маска,
                          доли_ярусов=доли.разобрать(заказ, маска) if заказ is not None else None,
                          счёт=счёт)
    к = [счёт.get(и, 0) for и in ("ярус_точных", "ярус_близких",
                                  "ярус_созвучий", "ярус_ассонансов")]
    всего = sum(к)
    assert всего, "тяга не собрала ни одной пары — замер бессмыслен"
    return [100 * x / всего for x in к], всего


@нужен_большой_индекс
def test_доля_правит_пропорцию_ярусов():
    """Заказ «точная 70 / ассонанс 30» обязан двигать расклад в свою сторону.

    Допуск широкий: пар в прогоне три десятка, одна пара весит три пункта."""
    (точн, близ, созв, ассон), _ = _расклад("1:70,8:30")
    assert точн > 55, f"точных вышло {точн:.0f}% против заказанных 70"
    assert ассон > 15, f"ассонансов вышло {ассон:.0f}% против заказанных 30"
    assert близ + созв < 20, "невостребованные ярусы получили больше минимума"


@нужен_большой_индекс
def test_доля_не_воскрешает_ярус_погашенный_чипом():
    """Маска главнее доли — на ОБОИХ рубежах, и проверяются оба.

    Первый рубеж — разборщик: `доли.разобрать` получает маску и выбрасывает
    сорта, которых в ней нет (сохранённая строка переживает выключение чипа).
    Второй — сама тяга: `_годные_к` пересекает ярус доли с маской. Второй
    рубеж не лишний: `тянуть_строфы` зовут и напрямую, минуя разборщик, — так
    её зовут отбор пачками и эти тесты."""
    assert доли.разобрать("8:100", nlindex.ЯРУС_ТОЧНАЯ) == {1: 1.0}

    # МАСКА ШИРОКАЯ, А ДОЛЯ ПРОСИТ ЧУЖОЕ. Именно здесь второй рубеж и нужен:
    # корзина кандидатов строится широчайшим горящим ярусом (тут ассонансным),
    # и внутри неё лежат ВСЕ сорта, включая погашенные чипом. При узкой маске
    # корзина и так состоит из одного сорта — ломка это показала, и тест
    # переписан на случай, где защита действительно работает.
    idx = nlindex.load()
    таб, _ = nlindex._таблица(idx, False, False, 7)
    счёт = {}
    nlindex.тянуть_строфы(idx, таб, [(5, 9), (5, 9)], "аа", 80,
                          np.random.default_rng(5),
                          ярусы_рифмы=nlindex.ЯРУС_ТОЧНАЯ | nlindex.ЯРУС_АССОНАНС,
                          доли_ярусов={nlindex.ЯРУС_БЛИЗКАЯ: 1.0}, счёт=счёт)
    чужих = счёт.get("ярус_близких", 0) + счёт.get("ярус_созвучий", 0)
    собрано = sum(счёт.get(и, 0) for и in ("ярус_точных", "ярус_ассонансов"))
    assert собрано > 0, "тяга ничего не собрала"
    assert чужих == 0, f"погашенные чипом ярусы пролезли долей: {чужих} пар"


@нужен_большой_индекс
def test_жребий_не_режет_выдачу():
    """Доли меняют ПРОПОРЦИЮ, а не количество: строк в выдаче столько же."""
    _, без = _расклад(None, маска=3)
    _, с = _расклад("1:90,2:10", маска=3)
    assert с >= без * 0.7, f"с долями собралось {с} пар против {без} без них"


# ЗАПАСНОЙ ПУТЬ ТЯГИ (найдено разбором 2026-08-30, подтверждено чтением кода).
#
# У `тянуть_строфы` два места, где открывается буква рифмы: основной путь и
# запасной — тот, что срабатывает, когда обычный отбор не дал ничего и правило
# «не повторять слова» ослабляется. С вводом долей ярусов запись выросла с трёх
# полей до четырёх, но запасной путь остался на трёх, а читатели уже
# распаковывали четыре. Если букву открывал ИМЕННО запасной путь, следующая
# строка той же буквы падала на распаковке — тяга роняла запрос целиком.

def test_запасной_путь_кладёт_запись_той_же_формы():
    """Обе ветки обязаны класть запись одной формы — иначе вторая строка той
    же буквы падает на распаковке.

    Смотрим САМ РАЗБОР исходника (`ast`), а не прогон: запасной путь открывает
    букву только при исчерпании обычного отбора, и подстроить это на живом
    корпусе значит сторожить совпадение, а не правило. И не текстом по
    регулярке: в записи есть вложенные скобки `гк[j]`, на которых текстовый
    поиск врёт."""
    import ast
    from pathlib import Path

    дерево = ast.parse((Path(__file__).resolve().parent.parent / "core"
                        / "nlindex.py").read_text("utf-8"))
    длины, читателей = [], 0
    for у in ast.walk(дерево):
        # запись: ключи_буквы.setdefault(буква, [ ... ])
        if (isinstance(у, ast.Call) and isinstance(у.func, ast.Attribute)
                and у.func.attr == "setdefault"
                and isinstance(у.func.value, ast.Name)
                and у.func.value.id == "ключи_буквы"
                and len(у.args) == 2 and isinstance(у.args[1], ast.List)):
            длины.append(len(у.args[1].elts))
        # чтение: гб, тб, кб, яб = ключи_буквы[буква]
        if (isinstance(у, ast.Assign) and len(у.targets) == 1
                and isinstance(у.targets[0], ast.Tuple)
                and isinstance(у.value, ast.Subscript)
                and isinstance(у.value.value, ast.Name)
                and у.value.value.id == "ключи_буквы"):
            читателей += 1
            длины.append(len(у.targets[0].elts))

    assert len(длины) == 4, f"мест записи и чтения стало {len(длины)} — сторож отстал"
    assert читателей == 2, f"читателей записи стало {читателей} — сторож отстал"
    assert set(длины) == {4}, f"ветки разошлись по форме записи: {sorted(длины)}"
