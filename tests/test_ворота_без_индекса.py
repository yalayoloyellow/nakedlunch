# Путей отбора два: колоночный (`nlindex`, боевой) и безиндексный
# (`filters._nl_scored(light=True)`, живёт до первой выпечки индекса). Ворота —
# это запрос владельца на СОДЕРЖАНИЕ, и он не может исполняться или нет в
# зависимости от того, испечён ли индекс.
#
# ЧТО ПОЙМАНО. `_nl_scored` ПРИНИМАЛ `внутр_рифма` и нигде его не применял —
# единственное вхождение в теле было в самой подписи. Оба вызывающих исправно
# передавали ворота (filters.py: _classic_pool и _run), а исполнял их только
# колоночный путь. То есть на свежей установке ручка «Внутренняя рифма» молча
# не действовала. Найдено при разборе тестов после сноса темы, в тот же день,
# что и молчаливый ноль классики — и это ровно та же болезнь: два пути
# разошлись, а сторожа на их согласие не было.
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))
import filters  # noqa: E402
from corpus import Corpus  # noqa: E402


СТРОКИ = {
    "должна стремиться вновь соединиться": True,    # рифма внутри строки
    "перешли туда чтобы уйти": True,
    "просто короткая строка без затей": False,
    "он сказал и вышел за дверь": False,
}


@pytest.fixture
def кэш(monkeypatch):
    """Подменяем разметку: сторож про ВОРОТА, а не про правило рифмы."""
    подмена = {т: {"banal": 3.0, "taut": False, "lemmas": т.split(),
                   "tokens": т.split(), "key": "ать", "span": None,
                   "content": 4, "inner": вн}
               for т, вн in СТРОКИ.items()}
    monkeypatch.setattr(filters, "_NL_RHYME", подмена)
    return подмена


def _светлый(внутр):
    строки, _ = filters._nl_scored(list(СТРОКИ), Corpus(), set(), light=True,
                                   внутр_рифма=внутр)
    return {r["text"] for r in строки}


def test_ворота_внутренней_рифмы_без_индекса(кэш):
    """«Только с внутренней» обязано резать и там, где колонок нет."""
    все = _светлый(0)
    assert все == set(СТРОКИ), "без ворот должны выжить все"
    только = _светлый(1)
    ждём = {т for т, вн in СТРОКИ.items() if вн}
    assert только == ждём, f"ворота не сработали: {только}"


def test_светлый_путь_возвращает_пару(кэш):
    """РЕГРЕССИЯ ТОГО ЖЕ ДНЯ: снос строгой ветки унёс общий `return` в хвосте
    функции, и светлый путь отдавал None. Оба вызывающих распаковывают пару —
    любая генерация без индекса падала с TypeError."""
    ответ = filters._nl_scored(list(СТРОКИ), Corpus(), set(), light=True)
    assert isinstance(ответ, tuple) and len(ответ) == 2, "светлый путь обязан отдать пару"
    строки, кандидаты = ответ
    assert isinstance(строки, list) and isinstance(кандидаты, dict)
