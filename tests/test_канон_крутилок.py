# Переписать было НЕ НА ЧТО: ключи `cohesion`/`explore` ядро отдаёт КОНСТАНТОЙ
# 0.5 — переходное, пока их читает core/filters.py. Сторожить константу значило
# бы поставить красный флажок тому, кто будет резать filters.py, за правильную
