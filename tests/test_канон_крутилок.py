# ---- канон имён и диапазонов ----------------------------------------------

def test_ворота_и_мнения_не_пересекаются():
    """Разделение — не оформление панели, а свойство кода: классика гасит
    мнения и подчиняется воротам. Пересечение групп означало бы, что одна
    крутилка обязана быть в классике и того, и другого."""
    assert not (set(clean.KNOB_GATES) & set(clean.KNOB_OPINIONS))
    assert set(clean.KNOB_SPEC) == set(clean.KNOB_GATES) | set(clean.KNOB_OPINIONS)


def test_профиль_всегда_полный():
    """Недостающие ключи берут дефолт: половинчатый профиль на одном звене и
    полный на другом — это тихий разнобой внутри одной цепочки.

    Заданную ручку берём ЖИВУЮ («Ярусы рифмы»): 2026-08-29 здесь стоял
    «Диссонанс», и после его удаления вместе с темой проверка зеленела бы на
    неизвестном ключе — то есть перестала бы стеречь «заданное сохранено»."""
    p = clean.knob_params({"Ярусы рифмы": 15})
    assert set(p) == set(clean.KNOB_SPEC)
    assert p["Ярусы рифмы"] == 15     # заданное сохранено
    assert p["Клаузула"] == 7         # недостающее взяло дефолт


def test_мусор_клампится_а_чужое_отбрасывается():
    # «Диссонанс: −9» (проверка пола) заменён на «Внутреннюю рифму: −9»
    # 2026-08-29: ручка ушла с темой, а пол клампа стеречь по-прежнему надо —
    # берём живые ворота с полом 0.
    p = clean.knob_params({"Мат": 5, "Клаузула": 2.7, "Внутренняя рифма": -9,
                           "Повтор": 7, "Ярусы рифмы": "чушь", "постороннее": 1})
    assert p["Мат"] == 1.0            # выше потолка
    assert p["Клаузула"] == 3         # маска: целое, округлено (муж+жен)
    assert p["Внутренняя рифма"] == 0  # ниже пола
    assert p["Повтор"] == 1           # выше потолка, целое
    assert p["Ярусы рифмы"] == 3      # нечисло → дефолт («точная+близкая»)
    assert "постороннее" not in p


def test_старая_точность_переводится_в_маску():
    """«Точность рифм» лежит в настройках и профилях на дисках — перевод
    обязан жить, пока живы старые файлы (обе стороны: 2026-08-28)."""
    # старые ярусы были ВЛОЖЕНЫ — перевод сохраняет поведение (до яруса N)
    assert clean.knob_params({"Точность рифм": 0.0})["Ярусы рифмы"] == 1
    assert clean.knob_params({"Точность рифм": 0.25})["Ярусы рифмы"] == 3
    assert clean.knob_params({"Точность рифм": 1.0})["Ярусы рифмы"] == 15
    # старая клаузула «любая» (0) — вся маска
    assert clean.knob_params({"Клаузула": 0})["Клаузула"] == 7


def test_профиль_без_имени_это_не_профиль():
    """None, а не исключение: одна битая строка в файле, который пользователь
    может открыть руками, не должна ронять весь список профилей."""
    assert clean.knob_profile({"name": "   ", "params": {}}) is None
    assert clean.knob_profile("не объект") is None
    assert clean.knob_profile({"name": "Живой"})["name"] == "Живой"


# ---- бинарная классика -----------------------------------------------------

def test_классика_не_хранит_мнений():
    """Требование: то, что не работает, лучше убрать вовсе.. Профиль в режиме
    классики не должен показывать глазами ползунки, которых режим не читает."""
    # Мнение берём ЖИВОЕ («Ярусы рифмы»). Ловушка тут повторилась дважды:
    # сначала стояла «Банальность» (удалена 2026-08-20), потом «Диссонанс»
    # (удалён 2026-08-29 вместе с темой) — и оба раза после удаления тест
    # зеленел бы на НЕИЗВЕСТНОМ ключе, а не на отброшенном мнении, то есть
    # проверял бы не то, что написано. Живых мнений осталось два: «Ярусы
    # рифмы» и «Повтор».
    p = clean.knob_profile({"name": "Сырьё", "mode": clean.MODE_CLASSIC,
                            "params": {"Ярусы рифмы": 15, "Мат": 0.5}})
    assert "Ярусы рифмы" in clean.KNOB_OPINIONS, "мнение перестало быть мнением"
    assert p["mode"] == clean.MODE_CLASSIC
    assert "Ярусы рифмы" not in p["params"]
    assert p["params"]["Мат"] == 0.5      # ворота остались: им классика подчиняется


def test_неизвестный_режим_это_алгоритм():
    assert clean.knob_profile({"name": "т", "mode": "хренотень"})["mode"] == clean.MODE_ALGO


def test_классика_доезжает_до_ядра_единицей():
    k = clean.knobs_from_profile({"name": "т", "mode": clean.MODE_CLASSIC})
    assert k["classic"] == 1.0
    assert clean.knobs_from_profile({"name": "т"})["classic"] == 0.0


