def test_прямые_шкалы_не_переворачиваются():
    """Шкала без инверсии обязана доехать до ядра ЧИСЛОМ, а не смыслом.

    «Источники»: 0.4 отсюда ушли 2026-08-29 вместе с генератором — источник
    один, и `real_text` больше не перевод, а константа (её стережёт
    `test_источник_пришпилен_и_профилем_не_двигается` ниже). Остальные прямые
    шкалы живы и проверяются числом."""
    k = clean.knobs_from_profile({"name": "т", "params": {
        "Точность рифм": 0.9, "Клаузула": 2,
        "Внутренняя рифма": 1, "Повтор": 1, "Мат": 0.5}})
    assert k["rhyme_tiers"] == 15      # старый вложенный 0.9 → все ярусы
    assert "melody" not in k and "meter" not in k   # удалена 2026-08-21
    assert k["clausula"] == 2
    assert k["inner_rhyme"] == 1
    assert k["repeat"] == 1
    assert k["mat_share"] == pytest.approx(0.5)


def test_источник_пришпилен_и_профилем_не_двигается():
    """СТОРОЖ НА ВЫРЕЗАННЫЙ ГЕНЕРАТОР (2026-08-29).

    Ручка «Источники» делила пул между грамматическим генератором (0) и
    корпусом (1). Генератор вырезан целиком, ручки нет, а ключи `real_text` и
    `nl_mix` в ядре ОСТАЛИСЬ — их читают статистика, журнал и api/server.py.
    Значит на дисках у старых настроек и профилей ключ «Источники» лежать
    может, и он обязан не значить НИЧЕГО: иначе сохранённое «Источники: 0»
    попросило бы у ядра долю из несуществующего генератора."""
    assert "Источники" not in clean.KNOB_SPEC
    for params in ({}, {"Источники": 0.0}, {"Источники": 0.4}):
        k = clean.knobs_from_profile({"name": "т", "params": params})
        assert k["real_text"] == 1.0 and k["nl_mix"] == 1.0, params


@pytest.mark.parametrize("мат, share, no_mat, only_mat", [
    (-1.0, -1.0, False, False),   # как есть — прежнее поведение корпуса
    (0.0, 0.0, True, False),      # без мата — жёсткий фильтр
    (0.5, 0.5, False, False),     # половина строк обязана быть с матом
    (1.0, 1.0, False, True),      # только мат — антифильтр
])
def test_четыре_положения_мата(мат, share, no_mat, only_mat):
    k = clean.knobs_from_profile({"name": "т", "params": {"Мат": мат}})
    assert k["mat_share"] == share
    assert k["no_mat"] is no_mat
    assert k["only_mat"] is only_mat


def test_дефолт_мата_не_режет_мат():
    """ПОЧИНКА Раунда 50: интерфейс по умолчанию слал 0, то есть жёсткое «без
    мата», хотя в референсах пользователя мата 17–21%. Ядро всегда считало
    дефолтом −1 — расходились две стороны."""
    assert clean.KNOB_GATES["Мат"][2] == -1.0
    k = clean.knobs_from_profile(None)
    assert k["no_mat"] is False and k["only_mat"] is False
