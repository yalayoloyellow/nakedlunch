# nakedlunch — РЕДКОСТЬ: две шкалы, полосы вместо порога, ворота по ним.
#
# Что сторожится и почему именно это:
#
#   · НАПРАВЛЕНИЕ ШКАЛЫ. Владелец поймал первую версию на обратном ходе: «ведь
#     0 процентов редкости это самые нередкие должны быть». У ручки с именем
#     «Редкость» ноль обязан значить «редкости нет», иначе имя врёт о шкале.
#   · ПОЛОСЫ, А НЕ ПОРОГ. «Диапазон с 5 по 10 + с 17 по 18 + с 97 по 98, и всё
#     это в выдаче участвует». Ползунок выражает один отрезок, и подменить
#     требование порогом значило бы отдать половину замысла.
#   · ОТСУТСТВИЕ ШКАЛЫ. Строка без лемм и строка с одной леммой — разные
#     случаи, и обе обязаны честно выпадать из полосы, а не притворяться нулём.
#
# Прогон: .venv/bin/python -m pytest tests/test_редкость.py -q

import sys
