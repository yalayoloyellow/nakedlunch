# ДОСТУП-ЛОГ НЕ ДОЛЖЕН ТОПИТЬ САМ СЕБЯ.
#
# Окно опрашивает `/api/status` каждые 12 секунд в покое и каждые 1.2 секунды,
# пока идёт работа. Werkzeug печатал КАЖДЫЙ такой запрос, и это уходило в
# `~/Library/Logs/nakedlunch.log` — единственное место, куда идут,
# когда что-то сломается.
#
# ЗАМЕР НА ЕГО ЖИВОМ ЖУРНАЛЕ (2026-09-02): 30 102 строки, из них 19 711 —
# «GET /api/status», то есть 65% шума. Настоящая ошибка за всё время одна
# (пятисотая 2026-08-06), и найти её среди двадцати тысяч одинаковых строк
# можно было только grep'ом.
#
# ГЛАВНОЕ ПРАВИЛО ЭТОГО ФИЛЬТРА: гасится ровно УСПЕШНЫЙ самоопрос. Именно
# строка «GET /api/status 500» однажды и объяснила падение — выбросить её
# значило бы сэкономить на том единственном, ради чего журнал ведут.
import logging
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "api"))

import server  # noqa: E402


def _строка(текст: str) -> logging.LogRecord:
    return logging.LogRecord("werkzeug", logging.INFO, "", 0, texts := текст, (), None)


def _пройдёт(текст: str) -> bool:
    return server._БезСамоопроса().filter(_строка(текст))


def test_успешный_самоопрос_гасится():
    for путь in ("/api/status", "/api/stats", "/healthz"):
        строка = f'127.0.0.1 - - [02/Sep/2026 12:00:00] "GET {путь} HTTP/1.1" 200 -'
        assert not _пройдёт(строка), f"{путь} 200 не погашен — журнал снова утонет"


def test_ошибка_самоопроса_остаётся():
    """ГЛАВНЫЙ СТОРОЖ. Единственная настоящая ошибка в живом журнале была
    именно пятисоткой на /api/status — гасить такое нельзя ни в коем случае."""
    for код in ("400", "404", "500", "503"):
        строка = f'127.0.0.1 - - [02/Sep/2026 12:00:00] "GET /api/status HTTP/1.1" {код} -'
        assert _пройдёт(строка), f"погашена ошибка {код} на самоопросе — это и есть то, ради чего журнал"


def test_обычные_запросы_остаются():
    """Заливка книг, генерация, перепечка — редкие и рассказывают, что человек
    делал. Их гасить незачем."""
    for путь in ("/api/generate", "/api/history", "/api/nl/source/add", "/"):
        строка = f'127.0.0.1 - - [02/Sep/2026 12:00:00] "POST {путь} HTTP/1.1" 200 -'
        assert _пройдёт(строка), f"погашен обычный запрос {путь}"


def test_чужие_строки_не_трогаются():
    """Фильтр висит на логгере werkzeug, но формат строки может смениться.
    Всё, что не похоже на успешный ответ, обязано проходить как есть."""
    for текст in ("nakedlunch: прогрев «корпус» — 5.1 с",
                  " * Running on http://127.0.0.1:8790",
                  "Traceback (most recent call last):"):
        assert _пройдёт(текст), f"фильтр съел постороннюю строку: {текст!r}"
