def test_stop_pryamo_vnutri_teksta(стенд):
    """Замечание: остановка «после текущей генерации» на зависшем прогоне не сработает..

    Он прав: остановка спрашивалась только МЕЖДУ текстами, и это было верно,
    пока текст стоил пятнадцать секунд. На его цепочке он стоит сорок одну
    (замерено), а на тяжёлой может и больше — сорок секунд между нажатием и
    реакцией читаются как «кнопка не работает».

    Теперь прогон получает `стоп` и бросает `pipeline.Остановлено` из середины.
    Брошенный текст просто не рождается: лист не пишется, история не трогается,
    счёт не двигается."""
    import pipeline
    серия(count=5)
    к = ФейкКорпус()
    звали = {"n": 0}

    def гнать(spec, corpus, nl_fragments):
        звали["n"] += 1
        if звали["n"] == 2:
            raise pipeline.Остановлено()     # «нажал стоп посреди второго»
        return {"variants": [{"score": 1.0, "sections": [
            {"title": "", "lines": [{"text": f"текст {звали['n']}"}, {"text": "хвост"}]}]}]}

    итог = series_run.прогнать("Ночь", к, [], прогон=гнать)
    assert итог["texts"] == 1, "первый текст обязан уцелеть"
    assert not итог["errors"], f"остановка — не ошибка: {итог['errors']}"
    assert not итог["beda"], "остановка не должна вешаться на трек как беда"
    d = стенд / "тексты" / "Серии" / "Пепел" / "дорога"
    assert len(list(d.glob("*.md"))) == 1, "брошенный посреди текст не должен родиться"


def test_stop_prohodit_do_pulov_i_perebora():
    """Проверка СКВОЗЬ: `run_pipeline` обязан спрашивать стоп в обоих местах,
    где уходит время, — иначе он опросит его один раз и снова застрянет."""
    import inspect

    import pipeline
    for имя in ("run_pipeline", "build_pools", "assemble"):
        подпись = inspect.signature(getattr(pipeline, имя))
        assert "стоп" in подпись.parameters, f"{имя} не принимает стоп"
