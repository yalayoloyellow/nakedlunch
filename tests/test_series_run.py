def test_pustaya_vydacha_ne_zaciklivaetsya(стенд):
    """Пустой ответ на звено — не повод крутиться вечно: звено бросается с
    честной причиной. Между попытками не меняется НИЧЕГО, кроме истории,
    которая пул только сужает, — то есть вторая попытка заведомо пуста тоже.

    Счётчик тут не для красоты. Первая версия теста просто ждала итога, и при
    возврате цикла вместо `break` она ЗАВИСАЛА вместо того, чтобы упасть, —
    зависший тест хуже красного: он не говорит ничего и держит прогон."""
    серия(count=100)
    к = ФейкКорпус()
    звали = {"n": 0}

    def пустой(*a, **kw):
        звали["n"] += 1
        if звали["n"] > 5:
            raise AssertionError("прогон зациклился на пустой выдаче")
        return {"variants": []}

    итог = series_run.прогнать("Ночь", к, [], прогон=пустой)
    assert звали["n"] == 1, "вторая попытка заведомо пуста — пробовать её незачем"
    assert итог["texts"] == 0
    assert any("пусто" in e for e in итог["errors"])


