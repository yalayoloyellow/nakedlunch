def фейк_прогон(тексты, баллы=None):
    """Прогон, выдающий заранее известные тексты по очереди, а дальше пустоту.

    ПРЕДОХРАНИТЕЛЬ здесь, а не в одном тесте: если прогон перестанет бросать
    звено на пустой выдаче, ВСЕ тесты, где заготовка кончается раньше плана,
    будут крутиться вечно — и набор не покраснеет, а ЗАВИСНЕТ. Зависший тест
    хуже красного: он не говорит ничего и держит прогон. Проверено: именно так
    и случилось, когда я внёс эту поломку мутацией."""
    состояние = {"i": 0}
    предел = len(тексты) + 3

    def гнать(spec, corpus, nl_fragments):
        i = состояние["i"]
        состояние["i"] += 1
        if i > предел:
            raise AssertionError("прогон зациклился на пустой выдаче")
        if i >= len(тексты):
            return {"variants": []}
        балл = (баллы or [0.5] * len(тексты))[i]
        return {"variants": [{"score": балл, "sections": [
            {"title": "", "lines": [{"text": t} for t in тексты[i]]}]}]}
    return гнать


