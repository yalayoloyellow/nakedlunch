import pymorphy3

import build_nl_rhyme as R

_morph = pymorphy3.MorphAnalyzer()


class _Акц:
    """Ключ без акцентуатора: последняя гласная и хвост. Настоящий ключ
    считает ruaccent (секунды загрузки на тест — не цена); здесь важна ЛОГИКА
    правила — фильтры и сличение ключей, — а не сами ударения."""
    class accent_model:
        @staticmethod
        def put_accent(w):
            return w
    accents = {}


def _ключ_хвостом(acc, surface, word):
    гл = [i for i, c in enumerate(word) if c in "аеёиоуыэюя"]
    return word[гл[-1]:] if гл else ""


@pytest.fixture()
def рифма(monkeypatch):
    monkeypatch.setattr(R, "_word_rhyme_key", _ключ_хвостом)
    monkeypatch.setattr(R, "_ВНУТР_ПАМЯТЬ", {})     # память помнит старый ключ
    return lambda т: R._внутренняя_рифма(_morph, _Акц, т)


def test_настоящая_рифма_ловится(рифма):
    assert рифма("сказала Рысь и почесала за ухом")          # сказала/почесала
    assert рифма("должна стремиться вновь соединиться")      # стремиться/соединиться


def test_служебные_слова_не_рифма(рифма):
    """Без фильтра знаменательных лезли «как/так», «для/меня», «кто/что» —
    служебные рифмуются тривиально, это шум, а не находка."""
    assert not рифма("как же так вышло у нас")
    assert not рифма("кто из них что понял тогда")


def test_повтор_слова_не_рифма(рифма):
    """«науке/науки» — одна лемма в разных формах. Повтор слова не рифма, а
    тавтология, и её проект казнит отдельно.

    ПАРА ПОДОБРАНА ПОД КЛЮЧ-ЗАГЛУШКУ, И ЭТО НАШЛА ЛОМКА. Первая версия брала
    «науке/науках» — у заглушки (хвост от последней гласной) их хвосты «е» и
    «ах» РАЗНЫЕ, ключи не сличались, и правило лемм не проверялось вовсе:
    ломка «леммы перестали различаться» оставалась зелёной. У «стремится/
    стремиться» хвост один («я») — сличение доходит до лемм."""
    assert not рифма("он стремится стремиться дальше всех")
    # а разные леммы с тем же хвостом — рифма
    assert рифма("сказала Рысь и почесала за ухом")


def test_память_слова_не_путает_корпуса(рифма):
    """_ВНУТР_ПАМЯТЬ живёт на процесс — фикстура обязана её чистить, иначе
    ключи от прошлого монкипатча утекут в следующий тест."""
    assert R._ВНУТР_ПАМЯТЬ is not None
    рифма("сказала и почесала")
    assert any(з[2] for з in R._ВНУТР_ПАМЯТЬ.values()), "память не наполнилась"


def test_ворота_на_живом_индексе():
    """Ворота «только с внутренней рифмой» сужают пул и не опустошают его.
    Классика подчиняется тем же воротам — как мату и клаузуле."""
    import nlindex
    idx = nlindex.load()
    if idx is None or getattr(idx, "inner", None) is None:
        pytest.skip("нет живого индекса с колонкой inner")
    без = idx.gate_mask(False)
    с = idx.gate_mask(False, False, 0, None, None, 1)
    assert 0 < с.sum() < без.sum(), (int(с.sum()), int(без.sum()))

    # НАДГРОБИЕ 2026-09-02: СТОРОЖ ОХРАНЯЛ ОТМЕНЁННЫЙ ДОГОВОР. Он требовал,
    # чтобы классика подчинялась воротам ФОРМЫ. требование: «классика
    # вообще все настройки отключает и просто даёт равную выдачу». Остались
    # только мат, чёрный список, история и активный пул — сказанное вслух про
    # СОДЕРЖАНИЕ. Разбор и замер — в надгробии внутри `nlindex.select_light`.
    # Сторож перевёрнут: держит НОВЫЙ договор.
    import inspect
    assert "внутр_рифма" not in inspect.signature(nlindex.select_light).parameters, (
        "классика снова читает внутреннюю рифму — ворота формы вернулись в "
        "режим, который форму не судит")


def test_канон_знает_ручку():
    """Профиль → ядро → ворота: «Внутренняя рифма» обязана доезжать до knobs
    тем же путём, что клаузула, и переживать классику."""
    import clean
    k = clean.knobs_from_profile({"name": "проба", "params": {"Внутренняя рифма": 1}})
    assert k["inner_rhyme"] == 1
    assert "Внутренняя рифма" in clean.KNOB_CLASSIC
    # выключено по умолчанию — ворота не закрыты
    assert clean.knobs({})["inner_rhyme"] == 0


