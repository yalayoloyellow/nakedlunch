# Замысел — бумага DESIGN-стык-рядом-рифмы + «делай» владельца. Правило: два
# слова С РАЗНЫМИ ЛЕММАМИ, оба ≥3 букв, оба знаменательные (_CONTENT_POS),
# с одинаковым непустым рифмо-ключом. Каждое ограничение снято с шума живой
