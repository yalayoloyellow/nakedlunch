def test_в_документах_нет_ссылок_на_номера_строк():
    """Ловит: пять надгробий в STATE.md ссылались на номера строк, и ВСЕ ПЯТЬ
    промахнулись — код с тех пор двигался.

    Номер строки — самая быстро протухающая ссылка из возможных, и протухает она
    молча: ссылка выглядит точной ровно до того момента, когда по ней сходят.
    Ссылаться надо на имя функции или на строку, которую можно найти grep'ом."""
    беда = []
    for p, t in документы():
        строки = t.splitlines()
        for n, s in enumerate(строки, 1):
            # раздел, описывающий САМО правило, приводит такие ссылки примерами
            if МАРКЕР.search(_раздел(строки, n - 1)) or "файл.py" in s:
                continue
            for ссылка in re.findall(r'\b([\w./\-]+\.(?:py|js|jsx)):(\d+)', s):
                беда.append(f"{p.relative_to(КОРЕНЬ)}:{n}: {ссылка[0]}:{ссылка[1]}")
    assert not беда, (
        "ссылка на номер строки в документе — она протухнет молча, "
        "ссылайся на имя функции:\n  " + "\n  ".join(беда))


