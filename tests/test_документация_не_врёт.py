# nakedlunch — документация не имеет права называть несуществующее.
#
# ЗАЧЕМ ЭТО НЕ БЮРОКРАТИЯ. В этом проекте враньё в документах уже трижды
# приводило к потере функций: решение забывалось и переизобреталось. А
# 2026-08-18 случилось хуже: СЕМЬ ЧИСЕЛ ИЗ STATE.md попали в рабочий план как
# факты и оказались выдуманными — `sheets.py` 612 строк (никогда не был), роутов
# 78→44 (на самом деле 69→44), и так далее. По ним принимались решения о том,
# что резать.
#
# Пересчитывать такое руками бессмысленно: числа устареют снова, и следующий
# разбор снова начнётся с веры в документ. Поэтому здесь сторожа СВОЙСТВ, а не
# чисел. Каждый ловит один класс вранья, который уже случался.
#
# Тесты читают файлы ТЕКСТОМ — как tests/test_scene_profile_leak.py и
# tests/test_вкладка_настроек.py. Сборка и прогон приложения тут не помогут:
# документ может врать сколько угодно, а код при этом работает.
#
# Прогон: .venv/bin/python -m pytest tests/test_документация_не_врёт.py -q

import re
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
NL = КОРЕНЬ / "interface" / "react-app" / "src" / "nl"

# Документы, которые ОПИСЫВАЮТ НЫНЕШНЕЕ положение дел, — их и сторожим.
# DECISIONS.md сюда НЕ входит нарочно: это датированный журнал решений, он
# обязан называть вырезанное по имени и переписыванию не подлежит. То же у
# аудитов с датой в имени — они снимок момента, а не описание сегодняшнего дня.
ЖИВЫЕ_ДОКУМЕНТЫ = ["ARCHITECTURE.md", "README.md",
                   "project-notes/STATE.md", "project-notes/PLAN.md"]
# BACKLOG.md сюда НЕ входит: он состоит из датированных записей «Правка #N от
# такого-то числа», то есть тоже журнал. Сторож, поставленный на журнал, требует
# от него забыть прошлое — а журнал ровно для прошлого и заведён.


def документы() -> list[tuple[Path, str]]:
    из = []
    for имя in ЖИВЫЕ_ДОКУМЕНТЫ:
        p = КОРЕНЬ / имя
        if p.exists():
            из.append((p, p.read_text("utf-8")))
    assert из, "не найдено ни одного живого документа — список ЖИВЫЕ_ДОКУМЕНТЫ устарел"
    return из


def _раздел(строки: list[str], i: int) -> str:
    """Заголовок, под которым лежит строка i. Разделы в этих документах несут
    смысл: под «Что вырезано» перечислять вырезанное — обязанность, а не ложь."""
    for j in range(i, -1, -1):
        if строки[j].lstrip().startswith("#"):
            return строки[j]
    return ""


МАРКЕР = re.compile(
    r"вырезан|удал[её]н|убран|снят|ушл[аио]|больше нет|его нет|которого нет|"
    r"не существует|никогда не|ЗДЕСЬ БЫЛ|надгроб|отменено|опроверг|устарел|"
    r"что было|прежн|раньше|история|журнал|правка #|разошёлся|разошлись|"
    r"выдуман|неверн|поймало бы|запрещен",
    re.I)


def _без_надгробий(текст: str) -> list[tuple[int, str]]:
    """Строки документа, КРОМЕ тех, что честно хоронят или разбирают прошлое.

    Отличаем по словам-маркерам в самой строке, в соседних И В ЗАГОЛОВКЕ
    РАЗДЕЛА. Узкое окно в две строки не годится: в таблице «что вырезано»
    заголовок стоит выше десятка строк, и каждая её строка выглядела бы ложью.
    На этом сторож и попался при первом же прогоне.
    """
    строки = текст.splitlines()
    живые = []
    for i, s in enumerate(строки):
        окно = " ".join(строки[max(0, i - 2):i + 2])
        if МАРКЕР.search(окно) or МАРКЕР.search(_раздел(строки, i)):
            continue
        живые.append((i + 1, s))
    return живые


