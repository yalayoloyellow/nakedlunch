def _без_кода_и_дат(s: str) -> str:
    """Строка без вставок в обратных кавычках, дат и времён.

    Внутри `` `...` `` цифры принадлежат коду («2 методa» в примере команды), а
    дата `2026-08-27` и время `23:22:25` — это семь цифр, которые любая проверка
    чисел примет за счёт чего-нибудь. Выкидываем до счёта, а не после."""
    s = re.sub(r"`[^`]*`", " ", s)
    s = re.sub(r"\d{4}-\d{2}-\d{2}", " ", s)
    s = re.sub(r"\d{1,2}:\d{2}(?::\d{2})?", " ", s)
    return s


# Число, у которого СЛЕВА стоит одно из этих слов, говорит про прошлое:
# «было 69», «стало 44», «→ 2 392 262». Такое сверять с сегодняшним кодом
# бессмысленно — оно и не должно совпадать.
СЛЕВА_ПРОШЛОЕ = re.compile(
    r"было|стало|прежде|раньше|прошл|выдуман|убран|убрал|убрано|ушл[аио]|→|->", re.I)
# ОТРИЦАНИЕ — НЕ СЧЁТ (2026-09-02). «не горит ни одна кнопка» говорит, что не
# горит НИ ОДНА, а вовсе не что кнопка на экране одна; так же «ни один пресет».
# Сторож считал это заявлением о количестве и краснел на живом документе —
# ложное срабатывание, а оно дороже пропуска: сторожу, который кричит на
# правду, перестают верить, и красноту начинают лечить правкой документа.
СЛЕВА_ОТРИЦАНИЕ = re.compile(r"\bни\s*$", re.I)
# Разделы, которые ЦЕЛИКОМ про прошлое: там каждое число — цитата.
РАЗДЕЛ_ПРОШЛОЕ = re.compile(
    r"вырезан|удал[её]н|что ушло|разош|отмен|поймало бы|надгроб|истори", re.I)

ЧИСЛИТЕЛЬНЫЕ = {
    "один": 1, "одна": 1, "одной": 1, "два": 2, "две": 2, "двумя": 2, "двух": 2,
    "три": 3, "тремя": 3, "трёх": 3, "трех": 3, "четыре": 4, "четырьмя": 4,
    "четырёх": 4, "четырех": 4, "пять": 5, "пятью": 5, "пяти": 5,
    "шесть": 6, "шестью": 6, "шести": 6, "семь": 7, "семью": 7, "семи": 7,
    "восемь": 8, "восьмью": 8, "восьми": 8, "девять": 9, "девятью": 9,
    "девяти": 9,
}


def _счёт(x: str) -> int:
    """«2 307 826» и «четырьмя» — оба про количество. Пробел внутри числа —
    типографский разделитель разрядов, а не граница между двумя числами."""
    if x[0].isdigit():
        return int(re.sub(r"[\s   ]", "", x))
    return ЧИСЛИТЕЛЬНЫЕ[x.lower()]


ЧИСЛО = r"(\d[\d    ]*\d|\d|" + "|".join(ЧИСЛИТЕЛЬНЫЕ) + ")"


def _списком(файл: str, имя: str) -> list[str]:
    """Строки из литерала `export const ИМЯ = ['a', 'b']` — единственного места,
    где этот список объявлен. Сверяться надо с ним, а не с пересказом."""
    т = (NL / файл).read_text("utf-8")
    m = re.search(r"export const " + имя + r"\s*=\s*\[([^\]]*)\]", т)
    assert m, f"{файл}: список {имя} не найден — его переписали, поправь сторожа"
    return re.findall(r"'([^']+)'", m.group(1))


def _пресеты() -> list[str]:
    """Имена пресетов из `ПРЕСЕТЫ`. Строки-комментарии выброшены нарочно:
    надгробия внутри списка называют слитые пресеты, и без этого они сошли бы
    за живые."""
    т = (NL / "methods.shelves.js").read_text("utf-8")
    н = т.index("export const ПРЕСЕТЫ = [")
    блок = т[н:т.index("\n];", н)]
    живое = "\n".join(s for s in блок.splitlines() if not s.lstrip().startswith("//"))
    имена = re.findall(r"\bname:\s*'([^']+)'", живое)
    assert имена, "в ПРЕСЕТЫ не нашлось ни одного name — изменился способ объявления"
    return имена


def test_счётные_числа_в_документах_сходятся_с_кодом():
    """Ловит: числа, которые документ переписал руками, а код с тех пор уехал.

    Это ровно тот класс вранья, из-за которого 2026-08-18 семь чисел из STATE.md
    уехали в рабочий план как факты: `sheets.py` 612 строк, роутов 78→44 вместо
    69→44, 16 клиентских функций вместо 14. По ним решали, что резать.

    Правило простое: если ответ даёт `ls`, `grep` или `meta.json` — сторож и
    спрашивает у них, а документ обязан совпасть. Числа, которых не пересчитать
    (замеры, доли, миллисекунды), сюда НЕ входят: у замера есть дата, и живёт он
    в `DECISIONS.md`."""
    сервер = (КОРЕНЬ / "api" / "server.py").read_text("utf-8")
    мета = json.loads((КОРЕНЬ / "core" / "data" / "nl_index" / "meta.json")
                      .read_text("utf-8"))
    фрагментов, источников = int(мета["n"]), len(мета["sources"])

    # (что ищем в документе, сколько на самом деле, откуда это известно)
    правила = [
        (r"\s+модул", len(list((КОРЕНЬ / "core").glob("*.py"))), "ls core/*.py"),
        (r"\s+декоратор", len(re.findall(r"@app\.(?:get|post|route)\(", сервер)),
         "@app.* в api/server.py"),
        (r"\s+различных\s+пут",
         len(set(re.findall(r'@app\.(?:get|post|route)\(\s*["\']([^"\']+)["\']', сервер))),
         "различных путей в api/server.py"),
        # «четырьмя кнопками» и «четырьмя пресетами» — одно и то же обещание
        (r"\s+(?:кнопк|пресет)", len(_пресеты()), "methods.shelves.js: ПРЕСЕТЫ"),
    ]

    беда = []
    for p, t in документы():
        строки = t.splitlines()
        for i, исходная in enumerate(строки):
            if РАЗДЕЛ_ПРОШЛОЕ.search(_раздел(строки, i)):
                continue
            s = _без_кода_и_дат(исходная)
            проверки = [(рег, факт, откуда) for рег, факт, откуда in правила]
            # корпус описывается одной фразой «N фрагментов из M книг», и обе
            # половины стоят в meta.json — сверяем только там, где сказано и то
            # и другое, иначе «подрезка 341 680 фрагментов» сойдёт за размер
            if "фрагмент" in s and ("книг" in s or "источник" in s):
                проверки = проверки + [
                    (r"\s*фрагмент", фрагментов, "meta.json: n"),
                    (r"\s*(?:книг|источник)", источников, "meta.json: len(sources)")]
            for рег, факт, откуда in проверки:
                for m in re.finditer(ЧИСЛО + рег, s):
                    слева = s[max(0, m.start() - 24):m.start()]
                    if СЛЕВА_ПРОШЛОЕ.search(слева):
                        continue
                    # «ни одна кнопка не горит» — отрицание, а не количество
                    if СЛЕВА_ОТРИЦАНИЕ.search(слева):
                        continue
                    if _счёт(m.group(1)) != факт:
                        беда.append(
                            f"{p.relative_to(КОРЕНЬ)}:{i + 1}: «{m.group(0).strip()}» — "
                            f"на самом деле {факт} ({откуда})")
    assert not беда, (
        "документ переписал руками число, которое можно СОСЧИТАТЬ — и разошёлся:\n  "
        + "\n  ".join(беда)
        + "\n(правь документ, а не сторожа: сторож спрашивает у кода и данных)")


def test_число_тестов_в_документах_запрещено():
    """Ловит: любое «N тестов» в живом документе.

    Отдельный сторож, а не частный случай предыдущего, потому что это число
    нельзя сверить — оно неверно к моменту, когда сверку допишут. Замерено на
    месте 2026-08-18: `--collect-only` дал 469 в 09:11, 474 в 09:18 и 485 в
    09:55. Разошлось за семь минут одной сессии.

    Значит числу тут не место вовсе. Оправдания ровно два, и оба — отказ от
    точного числа: «больше стольких-то» (грубая оценка не протухает) и ссылка
    на `--collect-only` (спроси у самих тестов)."""
    ОПРАВДАНИЕ = re.compile(r"больше|collect-only", re.I)
    беда = []
    for p, t in документы():
        строки = t.splitlines()
        for i, исходная in enumerate(строки):
            if РАЗДЕЛ_ПРОШЛОЕ.search(_раздел(строки, i)):
                continue
            # оправдание ищем в самой строке и в соседней: фраза про тесты
            # запросто переносится на другую строку абзаца
            окно = " ".join(строки[max(0, i - 1):i + 2])
            if ОПРАВДАНИЕ.search(окно):
                continue
            for m in re.finditer(r"(\d[\d    ]*\d|\d)\s+тест\w*", исходная):
                if _счёт(m.group(1)) > 50:
                    беда.append(f"{p.relative_to(КОРЕНЬ)}:{i + 1}: «{m.group(0)}»")
    assert not беда, (
        "число тестов записано в живой документ — оно протухает в тот же день:\n  "
        + "\n  ".join(беда)
        + "\n(вместо числа — команда `pytest --collect-only -q | tail -1` "
          "или грубое «больше стольких-то»)")


def test_имена_пресетов_ворот_и_вкладок_взяты_из_кода():
    """Ловит: документ называет пресет, ворота или вкладку, которых в коде нет.

    Дешевле некуда, а цена промаха известна: рассинхрон `CFG_TABS` со старым
    `cfgTab: "документ"` открывал панель настроек ПУСТОЙ — вкладка сохранилась в
    профиле, а списка с таким именем уже не было. Читатель документа попадает в
    ту же яму, только руками: ищет на экране кнопку, которой нет."""
    пресеты, ворота = _пресеты(), _списком("methods.shelves.js", "ВОРОТА")
    вкладки = _списком("render.settings.jsx", "CFG_TABS")

    # 1. Список мёртвых имён не должен протухнуть: если имя вернулось в код,
    #    сторож обязан замолчать, а не ловить живое.
    мёртвые = {
        # слиты и удалены 2026-08-18 и 2026-08-20, надгробия в methods.shelves.js
        "Как всегда": пресеты, "Вольная рифма": пресеты, "Разговор": пресеты,
        # вкладка настроек вырезанного редактора, 2026-08-18
        "документ": вкладки,
    }
    ожили = [имя for имя, живой in мёртвые.items() if имя in живой]
    assert not ожили, (
        f"{ожили} снова в коде — список мёртвых имён протух, поправь сторожа")

    # 2. Живой документ не называет мёртвое имя, не сказав, что оно мёртвое.
    беда = []
    for p, t in документы():
        for n, s in _без_надгробий(t):
            for имя in мёртвые:
                if f"«{имя}»" in s:
                    беда.append(f"{p.relative_to(КОРЕНЬ)}:{n}: «{имя}» — "
                                f"в коде такого нет, живые: {мёртвые[имя]}")
    assert not беда, (
        "документ обещает имя, которого нет в списках кода "
        "(methods.shelves.js: ПРЕСЕТЫ/ВОРОТА, render.settings.jsx: CFG_TABS):\n  "
        + "\n  ".join(беда))

    # 3. Тот же сговор внутри кода: имя вкладки, которое где-то присваивают,
    #    обязано быть в CFG_TABS — иначе панель откроется пустой.
    чужие = []
    for файл in sorted(NL.glob("*.js*")):
        for n, s in enumerate(файл.read_text("utf-8").splitlines(), 1):
            if s.lstrip().startswith("//"):
                continue
            for имя in re.findall(r"cfgTab:\s*['\"]([^'\"]+)['\"]", s):
                if имя not in вкладки:
                    чужие.append(f"{файл.name}:{n}: cfgTab: '{имя}'")
    assert not чужие, (
        f"вкладка присваивается мимо CFG_TABS ({вкладки}) — панель настроек "
        "откроется пустой:\n  " + "\n  ".join(чужие))
    assert ворота, "список ВОРОТА пуст — сторож потерял опору"
