def test_документы_не_называют_удал_нные_файлы_живыми():
    """Ловит: STATE.md называл живым `methods.слово.js`, удалённый в тот же день.

    Читатель такого документа идёт открывать файл, которого нет, и решает, что
    сломалось у него."""
    вырезанные = ["methods.doc.js", "methods.sheets.js", "render.doc.jsx",
                  "render.sheets.jsx", "methods.series.js", "methods.слово.js",
                  "core/sheets.py", "core/pipeline.py", "core/series.py",
                  "core/curve.py", "core/distort.py", "core/chain_profiles.py",
                  # 2026-08-18: полка профилей крутилок; надгробие в api/server.py
                  "core/knob_profiles.py"]
    # сперва убедимся, что список не протух: перечисленного и правда нет
    ещё_живы = [f for f in вырезанные if (КОРЕНЬ / f).exists() or (NL / Path(f).name).exists()]
    assert not ещё_живы, (
        f"список вырезанных протух — эти файлы существуют: {ещё_живы}. "
        "Сторож обязан сторожить правду, а не прошлогоднюю.")

    беда = []
    for p, t in документы():
        for n, s in _без_надгробий(t):
            for f in вырезанные:
                if Path(f).name in s:
                    беда.append(f"{p.relative_to(КОРЕНЬ)}:{n}: {s.strip()[:90]}")
    assert not беда, (
        "документ называет удалённый файл, не сказав, что он удалён:\n  "
        + "\n  ".join(беда))


