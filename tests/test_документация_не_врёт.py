def test_документы_не_называют_удал_нные_файлы_живыми():
    """Ловит: STATE.md называл живым `methods.слово.js`, удалённый в тот же день.

    Читатель такого документа идёт открывать файл, которого нет, и решает, что
    сломалось у него."""
    вырезанные = ["methods.doc.js", "methods.sheets.js", "render.doc.jsx",
                  "render.sheets.jsx", "methods.series.js", "methods.слово.js",
                  "core/sheets.py", "core/pipeline.py", "core/series.py",
                  "core/curve.py", "core/distort.py", "core/chain_profiles.py"]
    # сперва убедимся, что список не протух: перечисленного и правда нет
    ещё_живы = [f for f in вырезанные if (КОРЕНЬ / f).exists() or (NL / Path(f).name).exists()]
    assert not ещё_живы, (
        f"список вырезанных протух — эти файлы существуют: {ещё_живы}. "
        "Сторож обязан сторожить правду, а не прошлогоднюю.")

    беда = []
    for p, t in документы():
        for n, s in _без_надгробий(t):
            for f in вырезанные:
                if Path(f).name in s:
                    беда.append(f"{p.relative_to(КОРЕНЬ)}:{n}: {s.strip()[:90]}")
    assert not беда, (
        "документ называет удалённый файл, не сказав, что он удалён:\n  "
        + "\n  ".join(беда))


def test_документы_не_обещают_несуществующих_роутов():
    """Ловит: надгробие называло `/api/pipeline/stop` — роут, которого не было
    НИКОГДА. Надгробие, врущее о том, что похоронило, хуже отсутствующего:
    следующий читатель пойдёт искать, куда делась ручка."""
    сервер = (КОРЕНЬ / "api" / "server.py").read_text("utf-8")
    живые = set(re.findall(r'@app\.(?:get|post|route)\(\s*["\']([^"\']+)["\']', сервер))
    assert живые, "в api/server.py не нашлось ни одного роута — изменился способ объявления"

    беда = []
    for p, t in документы():
        for n, s in _без_надгробий(t):
            for путь in re.findall(r'`(/api/[a-zA-Z0-9_\-/]+)`', s):
                if путь not in живые:
                    беда.append(f"{p.relative_to(КОРЕНЬ)}:{n}: {путь}")
    assert not беда, (
        "документ называет роут, которого нет в api/server.py:\n  "
        + "\n  ".join(беда))


def test_в_документах_нет_ссылок_на_номера_строк():
    """Ловит: пять надгробий в STATE.md ссылались на номера строк, и ВСЕ ПЯТЬ
    промахнулись — код с тех пор двигался.

    Номер строки — самая быстро протухающая ссылка из возможных, и протухает она
    молча: ссылка выглядит точной ровно до того момента, когда по ней сходят.
    Ссылаться надо на имя функции или на строку, которую можно найти grep'ом."""
    беда = []
    for p, t in документы():
        строки = t.splitlines()
        for n, s in enumerate(строки, 1):
            # раздел, описывающий САМО правило, приводит такие ссылки примерами
            if МАРКЕР.search(_раздел(строки, n - 1)) or "файл.py" in s:
                continue
            for ссылка in re.findall(r'\b([\w./\-]+\.(?:py|js|jsx)):(\d+)', s):
                беда.append(f"{p.relative_to(КОРЕНЬ)}:{n}: {ссылка[0]}:{ссылка[1]}")
    assert not беда, (
        "ссылка на номер строки в документе — она протухнет молча, "
        "ссылайся на имя функции:\n  " + "\n  ".join(беда))


def test_клавиши_обещанные_документами_существуют():
    """Ловит болезнь, которой этот интерфейс болел ТРИЖДЫ: легенда обещала
    «перекатить» и «закрепить», подсказка обещала `⌘⌥↵ — серия` после того, как
    серию вырезали, а подсветка строки жила без действия за ней.

    Вся клавиатура ленты живёт в одном месте — `lentaКлавиша`. Значит и сверять
    можно с одним местом."""
    клавиши = (NL / "methods.lenta.js").read_text("utf-8")
    тело = клавиши[клавиши.index("lentaКлавиша(e) {"):]
    тело = тело[:тело.index("\n  },")]

    # Что реально разбирается: Enter плюс модификаторы. Стрелок, Shift, пробела
    # и R там нет — они вырезаны вместе с выделением строк.
    assert "e.key !== 'Enter'" in тело, (
        "lentaКлавиша больше не про Enter — сторож потерял опору, перепиши его")
    assert "altKey" in тело, "⌥ перестал что-то значить, а документы его обещают"

    мёртвые = {"ArrowUp": "стрелка вверх", "ArrowDown": "стрелка вниз",
               "shiftKey": "Shift", "' '": "пробел", "KeyR": "R"}
    ожили = [имя for k, имя in мёртвые.items() if k in тело]
    assert not ожили, (
        f"в lentaКлавиша появилось {ожили} — если клавиша ожила, её надо "
        "вписать в легенду (render.panels.jsx: legendRowsCalc), иначе она "
        "секретная; если это опечатка — убрать.")


def test_надгробие_считает_то_что_перечисляет():
    """Ловит: надгробие клиента листов в api.js объявляло «16 функций» и
    перечисляло 14. Число в надгробии — такое же утверждение, как любое другое,
    и проверяется так же."""
    api = (NL / "api.js").read_text("utf-8")
    m = re.search(r"ЗДЕСЬ БЫЛ КЛИЕНТ ЛИСТОВ.*?(\d+) функц\w*\):\n((?://[^\n]*\n)+)", api)
    assert m, "надгробие клиента листов не найдено — его переписали, поправь сторожа"
    заявлено = int(m.group(1))
    имена = re.findall(r"\b(?:sheets?[A-Z]\w*|Folder\w+|Read|Write|Create|Rename|"
                       r"Duplicate|Trash|Restore|Purge\w*|Move|OpenDir)\b", m.group(2))
    assert len(имена) == заявлено, (
        f"надгробие объявляет {заявлено}, а перечисляет {len(имена)}: {имена}")
