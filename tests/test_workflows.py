# Рабочие процессы CI — проверка самих скриптов (Раунд 61).
#
# ЗАЧЕМ. Скрипты внутри .github/workflows не проверяет никто: ошибка в них
# видна только после отправки, через двадцать минут сборки. За один день это
# стоило двух прогонов:
#
#   1. переменные названы `рифмы` и `синонимы` — bash кириллические имена
#      присваиванием не считает и пытается ВЫПОЛНИТЬ строку. Windows прошёл
#      (PowerShell кириллицу допускает), macOS и Linux упали;
#   2. до этого тот же корень дважды бил в живых проверках: `ВРЕМ=...` в zsh не
#      присвоилось и молча дало пустую строку, уведя проверку к боевым данным.
#
# Оба ловятся за секунду — `bash -n` и взгляд на имена. Здесь это делается
# автоматически, до отправки.

from __future__ import annotations

import re
import subprocess
import tempfile
from pathlib import Path

import pytest

yaml = pytest.importorskip("yaml", reason="pyyaml не установлен")

КОРЕНЬ = Path(__file__).resolve().parent.parent
ПРОЦЕССЫ = sorted((КОРЕНЬ / ".github" / "workflows").glob("*.yml"))

# Имя переменной оболочки по POSIX: буква или подчёркивание, дальше буквы,
# цифры, подчёркивания. Кириллица сюда не входит ни в каком виде.
КИРИЛЛИЧЕСКОЕ_ИМЯ = re.compile(r"^[ \t]*([А-Яа-яЁё_][А-Яа-яЁё0-9_]*)=", re.M)

# `${{ ... }}` — подстановка GitHub, до оболочки она не доходит. Меняем на
# безобидное слово, иначе `bash -n` спотыкается о фигурные скобки.
ПОДСТАНОВКА = re.compile(r"\$\{\{[^}]*\}\}")


def шаги_оболочки():
    """(файл, работа, имя шага, скрипт) для каждого bash-шага всех процессов."""
    для_проверки = []
    for файл in ПРОЦЕССЫ:
        описание = yaml.safe_load(файл.read_text(encoding="utf-8"))
        for имя_работы, работа in (описание.get("jobs") or {}).items():
            for шаг in работа.get("steps") or []:
                скрипт = шаг.get("run")
                if not скрипт or шаг.get("shell") == "pwsh":
                    continue
                для_проверки.append((файл.name, имя_работы,
                                     шаг.get("name") or "без имени", скрипт))
    return для_проверки


def test_процессы_разбираются():
    assert ПРОЦЕССЫ, "не нашлось ни одного файла .github/workflows/*.yml"
    for файл in ПРОЦЕССЫ:
        описание = yaml.safe_load(файл.read_text(encoding="utf-8"))
        assert описание.get("jobs"), f"{файл.name}: нет ни одной работы"


def test_bash_шаги_синтаксически_целы():
    """`bash -n` на каждом шаге. Ловит незакрытые кавычки, скобки и прочее —
    то, что иначе обнаружится через двадцать минут сборки."""
    беды = []
    for файл, работа, имя, скрипт in шаги_оболочки():
        with tempfile.NamedTemporaryFile("w", suffix=".sh", delete=False,
                                         encoding="utf-8") as ф:
            ф.write(ПОДСТАНОВКА.sub("подстановка", скрипт))
            путь = ф.name
        готово = subprocess.run(["bash", "-n", путь],
                                capture_output=True, text=True)
        Path(путь).unlink(missing_ok=True)
        if готово.returncode:
            беды.append(f"{файл} · {работа} · «{имя}»:\n{готово.stderr.strip()}")
    assert not беды, "синтаксис оболочки сломан:\n" + "\n".join(беды)


def test_имена_переменных_только_ascii():
    """Кириллическое имя переменной в bash — не присваивание, а попытка
    выполнить строку. Ошибка платформозависимая: PowerShell такое допускает,
    поэтому Windows проходит, а macOS и Linux падают."""
    беды = []
    for файл, работа, имя, скрипт in шаги_оболочки():
        for найдено in КИРИЛЛИЧЕСКОЕ_ИМЯ.finditer(скрипт):
            беды.append(f"{файл} · {работа} · «{имя}»: переменная "
                        f"{найдено.group(1)!r} — имена только ASCII")
    assert not беды, "\n".join(беды)
