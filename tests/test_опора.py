#
# ЧТО БЫЛО. Три файла тестов пропускались по условию `nlindex.load() is None` —
# «индекс вообще есть?». А нужен им БОЛЬШОЙ индекс: они набирают правила из
# корпуса и считают доли по выдаче. На стенде с индексом из восьми строк они не
# пропускались, а ПАДАЛИ с чужой причиной «корпус слишком мал, чтобы набрать
# правила». Поймано, когда после живой проверки в изолированном доме остался
# маленький индекс.
#
# Красный тест, который врёт о причине, хуже пропущенного: человек идёт чинить
# то, что не ломалось. Тот же класс, что и сторожа, спрашивавшие про
# существование конкретного файла вместо того, что реально будет прочитано.
#
# Прогон: .venv/bin/python -m pytest tests/test_опора.py -q

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import nlindex  # noqa: E402
import опора  # noqa: E402


class _Индекс:
    def __init__(self, n: int):
        self.n = n


def test_индекса_нет_значит_мал(monkeypatch):
    monkeypatch.setattr(nlindex, "load", lambda: None)
    assert опора.мал_или_нет_индекса() is True


def test_маленький_индекс_даёт_пропуск_а_не_падение(monkeypatch):
    """Восемь строк — это стенд живой проверки. На нём тесты, которым нужен
    настоящий корпус, обязаны ПРОПУСКАТЬСЯ."""
    monkeypatch.setattr(nlindex, "load", lambda: _Индекс(8))
    assert опора.мал_или_нет_индекса() is True


def test_боевой_размер_не_пропускается(monkeypatch):
    """2 392 262 строки — живой живой индекс. На нём тесты обязаны идти,
    иначе сторож молча перестанет сторожить: зелёный прогон, в котором всё
    пропущено, выглядит ровно как зелёный прогон, в котором всё проверено."""
    monkeypatch.setattr(nlindex, "load", lambda: _Индекс(2_392_262))
    assert опора.мал_или_нет_индекса() is False


def test_граница_названа_явно(monkeypatch):
    """Порог лежит между стендом и боевым корпусом с большим запасом с обеих
    сторон — иначе он станет подгонкой под сегодняшний размер."""
    assert 1_000 < опора.МАЛО_СТРОК < 1_000_000
    monkeypatch.setattr(nlindex, "load", lambda: _Индекс(опора.МАЛО_СТРОК - 1))
    assert опора.мал_или_нет_индекса() is True
    monkeypatch.setattr(nlindex, "load", lambda: _Индекс(опора.МАЛО_СТРОК))
    assert опора.мал_или_нет_индекса() is False


def test_причина_пропуска_говорит_про_размер():
    """Текст причины читает человек, когда видит букву s в прогоне. Он обязан
    сказать, чего не хватило, — иначе пропуск неотличим от «тест сломан»."""
    причина = опора.нужен_большой_индекс.kwargs.get("reason", "")
    assert "корпус" in причина or "строк" in причина, причина
    assert "не испечён" not in причина, (
        "причина всё ещё говорит про отсутствие индекса, а условие — про размер")
