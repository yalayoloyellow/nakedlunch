def test_progrev_ne_derzhit_port(сервер, monkeypatch):
    """ГЛАВНОЕ СВОЙСТВО ПЕРВОГО ПРАВИЛА, проверенное опытом.

    Смысл прогрева — что открытие порта его НЕ ЖДЁТ: разбор 550 МБ до порта
    однажды не уложился в сорокасекундное ожидание окна (Раунд 54). Раньше это
    стерёг текст («на уровне модуля есть threading.Thread»), и текст оказался
    плохим свидетелем дважды. Проверяем поведение: сколько бы ни длилась сама
    работа, `_поднять_прогрев` обязан вернуть управление сразу.

    Заглушка нарочно ДОЛГАЯ: на быстрой работе тест был бы зелёным и в том
    случае, если поток убрать и звать работу прямо."""
    держал = threading.Event()
    monkeypatch.setattr(сервер, "_прогрев", lambda: держал.wait(30))
    t = time.perf_counter()
    try:
        сервер._поднять_прогрев()
        прошло = time.perf_counter() - t
        assert прошло < 0.5, (
            f"_поднять_прогрев держал вызывающего {прошло:.1f} с — значит порт "
            "открывается только после прогрева, и окно снова упрётся в свой "
            "сорокасекундный потолок")
    finally:
        держал.set()
