# nakedlunch — СТАРТ: окно не должно ждать корпус (Раунд 54).
#
# ЧТО СЛУЧИЛОСЬ. Владелец запустил программу и увидел заставку с надписью
# «сервер не поднялся за отведённое время». Замер: старт до /healthz — 39.4 с
# при потолке ожидания в launch.py 40.0 с. То есть программа не сломалась —
# она годами шла впритык к своему же сроку и однажды в него не уложилась.
#
# Из 39 секунд самое дорогое — разбор ~550 МБ state.json корпуса (13-16 с),
# который стоял НА УРОВНЕ МОДУЛЯ api/server.py, то есть до открытия порта.
# Плюс «одноразовый» перенос истории, который был одноразовым только на
# словах: отметку о переносе он писал ключом, которого нет в белом списке
# core/settings.py, и та молча исчезала — в логе владельца перенос отметился
# десять раз, по разу на запуск.
#
# ЧТО СТОРОЖИТ ЭТОТ ФАЙЛ. Не время старта (оно зависит от машины и диска, и
# тест на секундах был бы то зелёным, то красным), а ПРИЧИНУ: тяжёлое не
# должно вернуться на уровень модуля. Проверка текстовая — импортировать
# api/server.py в тесте значит заплатить тот самый старт целиком.
#
# Прогон: .venv/bin/python -m pytest tests/test_boot.py -q

import re
import sys
import threading
import time
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "core"))

import nlbridge  # noqa: E402

SERVER = ROOT / "api" / "server.py"


def модуль_сервера() -> str:
    """Код api/server.py ДО первого роута — всё, что выполняется при импорте,
    то есть до открытия порта. Дальше идут функции, они ничего не стоят."""
    текст = SERVER.read_text("utf-8")
    i = текст.index("@app.get(\"/api/state\")")
    return текст[:i]


def строки_кода(текст: str) -> list[str]:
    """Только то, что ВЫПОЛНЯЕТСЯ при импорте: без комментариев, без
    docstring'ов и без тел функций. Тело функции — не цена старта: `_nl()`
    зовёт open_store законно, вопрос лишь в том, зовёт ли его кто-то до
    открытия порта."""
    без = re.sub(r'"""[\s\S]*?"""', "", текст)
    out, в_функции = [], False
    for s in без.split("\n"):
        if s and not s[0].isspace():
            в_функции = s.startswith(("def ", "class ", "@"))
        if в_функции or s.lstrip().startswith("#"):
            continue
        out.append(s)
    return out


def test_korpus_ne_gruzitsya_na_urovne_modulya():
    """ГЛАВНЫЙ. Разбор 550 МБ обязан идти фоном, а не до открытия порта."""
    строки = строки_кода(модуль_сервера())
    прямые = [s for s in строки if "open_store()" in s]
    assert not прямые, (
        "api/server.py зовёт nlbridge.open_store() при импорте: "
        f"{прямые}. Это 13-16 с ДО открытия порта — ровно то, из-за чего окно "
        "показало «сервер не поднялся за отведённое время». Нужен "
        "nlbridge.warm_background(), а сам корпус — через _nl().")
    # Именно корпус: рядом на старте греются ещё и карты индекса, и проверка
    # «есть слово прогрев» была бы зелёной и без корпуса.
    #
    # Раунд 57: сторож требовал дословно `nlbridge.warm_background()`. Прогрев
    # с тех пор стал ОДНИМ упорядоченным потоком (корпус первым, карты вторыми
    # — они спорили за процессор и растягивали друг друга втрое), и корпус в
    # нём — этап, а не свой поток. Требуем свойство: корпус упомянут на старте
    # и стартует фоновый поток, который его и разбирает.
    поток = [s for s in строки if "threading.Thread(" in s and "_прогрев" in s]
    assert поток, "прогрева фоновым потоком нет — разбор 550 МБ снова стоит до порта"
    # Корпус греет ИМЕННО он: тело `_прогрев` в `строки` не попадает (оно и не
    # должно — это не цена старта), поэтому смотрим в исходник целиком.
    i = модуль_сервера().index("def _прогрев(")
    assert "nlbridge.open_store" in модуль_сервера()[i:i + 2000], \
        "прогрев корпуса не запускается вовсе — корпус не загрузится никогда"


def test_perenos_istorii_ne_vernulsya():
    """Перенос учёта CLI в нашу историю сделан и вырезан. Если он вернётся —
    вернётся и его цена: он ТРЕБУЕТ корпус, то есть снова тянет 550 МБ на
    старт, и снова на каждый запуск, пока его отметка не научится храниться."""
    строки = строки_кода(модуль_сервера())
    assert not [s for s in строки if "used_stamps" in s or "nl_used_merged" in s], \
        "перенос истории из CLI вернулся на старт — см. Раунд 54"


def test_status_ne_zhdyot_korpus():
    """Опрос статуса идёт раз в 12 с и обязан отвечать СРАЗУ. Спроси он
    хранилище через ждущий `_nl()`, и на первых секундах индикатор фоновой
    работы висел бы ровно столько, сколько идёт та работа."""
    текст = SERVER.read_text("utf-8")
    for имя in ("_nl_store_status", "_nl_rhyme_status", "_nl_index_status"):
        i = текст.index(f"def {имя}(")
        # Docstring вон, и только потом режем окно: у _nl_store_status одно
        # объяснение длиннее семисот знаков, и проверка смотрела в него, а не
        # в код (Раунд 57 — сторож позеленел бы на пустой функции).
        тело = re.sub(r'"""[\s\S]*?"""', "", текст[i:i + 4000])[:700]
        # Раунд 57: сторож проверял ИМЯ одного конкретного нежданного вопроса
        # (`_nl_ready()`), а не свойство. Свойство — «спросить, готово ли, не
        # вставая в очередь»; с Раунда 57 это `_ПРОГРЕВ["готов"]`, потому что
        # ждать приходится не только корпус, но и карты индекса. Годится любой
        # из двух — важно, что оба отвечают мгновенно.
        assert '_ПРОГРЕВ["готов"]' in тело or "_nl_ready()" in тело, \
            f"{имя} не спрашивает готовность нежданным способом"
        assert "_nl() is None" not in тело, f"{имя} ждёт загрузки корпуса"


@pytest.fixture()
def медленный_корпус(monkeypatch):
    """Хранилище-двойник: считает, сколько раз его построили, и строится
    заметное время. Настоящее строится 13-16 с — прогонять это в тестах значит
    менять один медленный старт на другой."""
    счёт = {"n": 0}

    class Двойник:
        def __init__(self, каталог):
            счёт["n"] += 1
            time.sleep(0.4)
            self.каталог = каталог

    monkeypatch.setattr(nlbridge, "_nl_modules", lambda: (Двойник, None))
    monkeypatch.setattr(nlbridge, "_STORE", None)
    yield счёт
    nlbridge._STORE = None      # monkeypatch вернёт настоящее значение сам


def test_hranilishche_odno_na_process(медленный_корпус):
    """Замок в open_store, а не у зовущего: два экземпляра по 550 МБ — это и
    двойная память, и двойное ожидание. Проверяется гонкой: пять потоков зовут
    одновременно, построиться обязан ОДИН."""
    итог = []
    потоки = [threading.Thread(target=lambda: итог.append(nlbridge.open_store()))
              for _ in range(5)]
    for t in потоки:
        t.start()
    for t in потоки:
        t.join()
    assert медленный_корпус["n"] == 1, "корпус построился больше одного раза"
    assert len(итог) == 5 and all(x is итог[0] for x in итог)


def test_warm_background_ne_zhdyot(медленный_корпус):
    """Прогрев обязан быть неблокирующим — он затем и нужен, чтобы порт
    открылся раньше корпуса. И пока корпус не готов, store_if_ready честно
    отвечает None, а не ждёт вместе со всеми."""
    t0 = time.time()
    nlbridge.warm_background()
    прошло = time.time() - t0
    assert прошло < 0.2, f"warm_background ждал загрузку {прошло:.2f} с"
    assert nlbridge.store_if_ready() is None, "готово — хотя загрузка ещё идёт"

    дедлайн = time.time() + 5
    while nlbridge.store_if_ready() is None and time.time() < дедлайн:
        time.sleep(0.05)
    assert nlbridge.store_if_ready() is not None, "фоновая загрузка не закончилась"
    assert nlbridge.store_if_ready() is nlbridge.open_store()


