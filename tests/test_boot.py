# nakedlunch — СТАРТ: окно не должно ждать корпус (Раунд 54).
#
# ЧТО СЛУЧИЛОСЬ. При запуске появлялась заставка «сервер не поднялся за отведённое время». Замер: старт до /healthz — 39.4 с
# при потолке ожидания в launch.py 40.0 с. То есть программа не сломалась —
# она годами шла впритык к своему же сроку и однажды в него не уложилась.
#
# Из 39 секунд самое дорогое — разбор ~550 МБ state.json корпуса (13-16 с),
# который стоял НА УРОВНЕ МОДУЛЯ api/server.py, то есть до открытия порта.
# Плюс «одноразовый» перенос истории, который был одноразовым только на
# словах: отметку о переносе он писал ключом, которого нет в белом списке
# core/settings.py, и та молча исчезала — в логе пользователя перенос отметился
# десять раз, по разу на запуск.
#
# ЧТО СТОРОЖИТ ЭТОТ ФАЙЛ. Не время старта (оно зависит от машины и диска, и
# тест на секундах был бы то зелёным, то красным), а ПРИЧИНУ: тяжёлое не
# должно вернуться на уровень модуля. Проверка текстовая — импортировать
# api/server.py в тесте значит заплатить тот самый старт целиком.
#
# Прогон: .venv/bin/python -m pytest tests/test_boot.py -q

import re
import sys
import threading
import time
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "core"))

import nlbridge  # noqa: E402

SERVER = ROOT / "api" / "server.py"


def модуль_сервера() -> str:
    """Код api/server.py ДО первого роута — всё, что выполняется при импорте,
    то есть до открытия порта. Дальше идут функции, они ничего не стоят."""
    текст = SERVER.read_text("utf-8")
    i = текст.index("@app.get(\"/api/state\")")
    return текст[:i]


def строки_кода(текст: str) -> list[str]:
    """Только то, что ВЫПОЛНЯЕТСЯ при импорте: без комментариев, без
    docstring'ов и без тел функций. Тело функции — не цена старта: `_nl()`
    зовёт open_store законно, вопрос лишь в том, зовёт ли его кто-то до
    открытия порта."""
    без = re.sub(r'"""[\s\S]*?"""', "", текст)
    out, в_функции = [], False
    for s in без.split("\n"):
        if s and not s[0].isspace():
            в_функции = s.startswith(("def ", "class ", "@"))
        if в_функции or s.lstrip().startswith("#"):
            continue
        out.append(s)
    return out


def test_korpus_ne_gruzitsya_na_urovne_modulya():
    """ГЛАВНЫЙ. Разбор 550 МБ обязан идти фоном, а не до открытия порта."""
    строки = строки_кода(модуль_сервера())
    прямые = [s for s in строки if "open_store()" in s]
    assert not прямые, (
        "api/server.py зовёт nlbridge.open_store() при импорте: "
        f"{прямые}. Это 13-16 с ДО открытия порта — ровно то, из-за чего окно "
        "показало «сервер не поднялся за отведённое время». Корпус обязан "
        "греться этапом фонового `_прогрев`, а спрашиваться — через _nl().")
    # Именно корпус: рядом на старте греются ещё и карты индекса, и проверка
    # «есть слово прогрев» была бы зелёной и без корпуса.
    #
    # Раунд 57: сторож требовал дословно `nlbridge.warm_background()`. Прогрев
    # с тех пор стал ОДНИМ упорядоченным потоком (корпус первым, карты вторыми
    # — они спорили за процессор и растягивали друг друга втрое), и корпус в
    # нём — этап, а не свой поток. Требуем свойство: корпус упомянут на старте
    # и стартует фоновый поток, который его и разбирает. Сама
    # `nlbridge.warm_background` вырезана 2026-08-14 — с Раунда 57 её не звал
    # никто, а второй способ греть корпус звал развести два потока обратно.
    # ПРОГРЕВ ПЕРЕЕХАЛ В `main()` (2026-08-18), И СТОРОЖ ПЕРЕЕХАЛ ЗА НИМ.
    #
    # Здесь стояло `assert поток` по строкам УРОВНЯ МОДУЛЯ — то есть сторож
    # требовал, чтобы поток стартовал именно на импорте. Это требование
    # обернулось бедой: прогрев третьим этапом зовёт `CORPUS.save()`, и любой
    # `import server` (в том числе из теста) переписывал избранное и историю
    # пользователя. Один раз так и вышло — 2026-08-18, живой `data/corpus.json`.
    #
    # Требование осталось прежним ПО СМЫСЛУ: разбор 550 МБ идёт фоновым
    # потоком, а не до открытия порта. Изменилось место запуска — теперь его
    # пускает `main()` перед `app.run`, то есть настоящий запуск сервера, а не
    # чтение файла. Оба свойства проверяются ниже поимённо.
    assert not [s for s in строки if "_поднять_прогрев()" in s], (
        "прогрев снова запускается на уровне модуля. Он пишет в данные "
        "пользователя (`CORPUS.save()` в этапе «перепривязка истории») — "
        "значит любой импорт api/server.py переписывает избранное и историю. "
        "Его место — в main(), рядом с открытием порта.")
    # ЧТО ПРОГРЕВ ГРЕЕТ ИМЕННО КОРПУС — единственное, что здесь осталось от
    # чтения исходника, и это про СОСТАВ работы, а не про её оформление.
    # «Поток заводится вот такой строкой» отсюда убрано нарочно: этот сторож
    # уже дважды подвёл дословностью — сперва требовал буквальную
    # `nlbridge.warm_background()` (Раунд 57), потом буквальную
    # `threading.Thread(...)`, и второй раз это предписывало запуск на импорте,
    # то есть ровно тот дефект, из-за которого переписали избранное.
    # Свойство «порт не ждёт прогрева» проверяется опытом —
    # `test_progrev_ne_derzhit_port` ниже.
    # СМОТРИМ ВСЁ ТЕЛО `_прогрев`, А НЕ ПЕРВЫЕ 2000 ЗНАКОВ (2026-09-03).
    #
    # Окно в 2000 байт было произвольным, и оно подвело: склад переехал из
    # первой ступени очереди в свой поток (он больше не нужен генерации), вызов
    # оказался на 1991-м знаке — и сторож покраснел на верном коде, требуя
    # вернуть корпус на первое место. Ровно та же дословность, которой этот
    # сторож подвёл уже дважды, — про неё написано абзацем выше.
    #
    # Свойство прежнее: прогрев обязан запускать загрузку корпуса. Теперь оно и
    # проверяется — разбором, по телу функции целиком.
    import ast
    дерево = ast.parse(модуль_сервера())
    тело = next((n for n in ast.walk(дерево)
                 if isinstance(n, ast.FunctionDef) and n.name == "_прогрев"), None)
    assert тело is not None, "в api/server.py не стало функции _прогрев"
    зовут = {getattr(u.func, "attr", "") for u in ast.walk(тело) if isinstance(u, ast.Call)}
    имена = {getattr(a, "attr", "") for a in ast.walk(тело) if isinstance(a, ast.Attribute)}
    assert "open_store" in (зовут | имена), \
        "прогрев корпуса не запускается вовсе — корпус не загрузится никогда"


def test_progrev_podnimaet_main_a_ne_import():
    """Прогрев обязан подниматься там же, где открывается порт.

    Без этого он либо не поднимется вовсе (корпус не загрузится никогда), либо
    вернётся на уровень модуля — а он ПИШЕТ в данные пользователя."""
    текст = SERVER.read_text("utf-8")
    i = текст.index("def main(")
    тело = текст[i:]
    assert "_поднять_прогрев()" in тело, (
        "main() не поднимает прогрев — корпус и карты индекса не загрузятся, "
        "а история никогда не перепривяжется к изменившемуся корпусу")
    assert тело.index("_поднять_прогрев()") < тело.index("app.run("), \
        "прогрев поднимается после app.run — то есть уже никогда"


