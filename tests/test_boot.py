def test_status_ne_zhdyot_korpus():
    """Опрос статуса идёт раз в 12 с и обязан отвечать СРАЗУ. Спроси он
    хранилище через ждущий `_nl()`, и на первых секундах индикатор фоновой
    работы висел бы ровно столько, сколько идёт та работа."""
    текст = SERVER.read_text("utf-8")
    for имя in ("_nl_store_status", "_nl_rhyme_status", "_nl_index_status"):
        i = текст.index(f"def {имя}(")
        # Docstring вон, и только потом режем окно: у _nl_store_status одно
        # объяснение длиннее семисот знаков, и проверка смотрела в него, а не
        # в код (Раунд 57 — сторож позеленел бы на пустой функции).
        тело = re.sub(r'"""[\s\S]*?"""', "", текст[i:i + 4000])[:700]
        # Раунд 57: сторож проверял ИМЯ одного конкретного нежданного вопроса
        # (`_nl_ready()`), а не свойство. Свойство — «спросить, готово ли, не
        # вставая в очередь»; с Раунда 57 это `_ПРОГРЕВ["готов"]`, потому что
        # ждать приходится не только корпус, но и карты индекса. Годится любой
        # из двух — важно, что оба отвечают мгновенно.
        assert '_ПРОГРЕВ["готов"]' in тело or "_nl_ready()" in тело, \
            f"{имя} не спрашивает готовность нежданным способом"
        assert "_nl() is None" not in тело, f"{имя} ждёт загрузки корпуса"


