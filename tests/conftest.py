# Пропуск, а не смягчение: там, где артефакты есть, тесты остаются ровно
# такими же строгими. Тот же приём, что `нет_индекса` в test_nlindex.py.
def _есть(имя: str) -> bool:
    from pathlib import Path
    return (Path(__file__).resolve().parent.parent / "core" / "data" / имя).exists()


