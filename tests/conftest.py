# лежало на дочернем процессе сборки — мол, он теряет `NAKEDLUNCH_HOME`. Он его
# не теряет (см. test_izolyatsiya.py). Писал ПРОГОН ТЕСТОВ:
# `test_select_speed.py` зовёт `build_nl_rhyme.reban()` напрямую, а та по
# дороге пишет сайдкар статуса в `пути.артефакт(...)`. Без `NAKEDLUNCH_HOME`
# это боевой каталог — и «сборка идёт» оставалась в нём НАВСЕГДА: строку
# «готово» пишет `main()` сборщика, которого тест не зовёт. Шапка приложения
# показывала пользователю работу, которой никогда не было.
#
# ПОЧЕМУ СТОРОЖ ИМЕННО ТАКОЙ. Проверять «тест не забыл подменить путь» нечем:
# забыть можно в любом новом тесте, и забудут. Поэтому проверяем ИСХОД: после
# каждого теста ни один файл в двух боевых каталогах не создан, не удалён и не
# изменён. Обход — 53 записи, около миллисекунды; отпечаток снимается заново
# перед каждым тестом, поэтому одна чужая запись не красит весь прогон.
def _боевые_каталоги():
    return (_КОРЕНЬ_КОДА / "core" / "data", _КОРЕНЬ_КОДА / "data")


def _отпечаток_боевого() -> dict:
    """Путь → (размер, время правки) по всему, что лежит в боевых каталогах."""
    снимок = {}
    for корень in _боевые_каталоги():
        try:
            обход = корень.rglob("*")
        except OSError:
            continue
        for п in обход:
            try:
                с = п.lstat()
            except OSError:
                continue
            снимок[str(п)] = (с.st_size, с.st_mtime_ns)
    return снимок


# СВЕРЯТЬ НАДО ПОСЛЕ ТОГО, КАК ВСЁ ЗАПИСАНО (2026-08-18).
#
# ДЫРА, КОТОРУЮ ЭТО ЗАКРЫВАЕТ. Сторож снимал отпечаток до теста и сверял СРАЗУ
# после его тела — а запись приходила из фонового потока (`nl-warm`,
# `daemon=True`), заведённого импортом `api/server.py`, и доходила до диска уже
# после сверки. Так в живой `data/corpus.json` и попала чужая запись, при
# зелёном прогоне. Сторож, который смотрит раньше, чем происходит запись, —
# украшение, а не сторож. Дыра воспроизведена отдельно:
# `tests/test_сторож_данных.py`.
#
# ЖДЁМ ПО СПИСКУ «КТО ПОЯВИЛСЯ», А НЕ ПО СПИСКУ ИМЁН. Напрашивалось перечислить
# свои потоки («nl-warm», «nlindex-warm», ...), но в этом проекте уже дважды
# разъезжались два списка одного и того же (прогрев в Раундах 51 и 62). Список
# имён устареет ровно тогда, когда заведут новый поток, — то есть когда сторож
# нужнее всего. Поэтому имён здесь нет: ждём тех, кого В ЭТОМ ТЕСТЕ раньше не
# было. Такой список ведёт себя сам.
#
# ЦЕНА. На тесте без своих потоков это один обход `threading.enumerate()` —
# замерено 0.002 мс, то есть 426 тестов платят меньше миллисекунды суммарно.
_ПРЕДЕЛ_ОЖИДАНИЯ = 60.0     # больше — значит поток завис; пусть падает по времени


def _дождаться_новых_потоков(потоки_до, предел: float = _ПРЕДЕЛ_ОЖИДАНИЯ) -> None:
    """Дождаться потоков, заведённых САМИМ тестом. Чужие (pytest, драйверы, те,
    что жили до него) не трогаем — иначе каждый тест ждал бы весь предел."""
    крайний = _time.time() + предел
    for т in _threading.enumerate():
        if т in потоки_до or т is _threading.current_thread():
            continue
        осталось = крайний - _time.time()
        if осталось <= 0:
            break
        try:
            т.join(осталось)
        except RuntimeError:
            pass          # поток уже не жив либо это он сам — ждать нечего


