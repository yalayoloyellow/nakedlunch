# ---- барьер на повтор леммы ВНУТРИ строфы ----------------------------------

# Проверяем САМУ ТЯГУ, а не круг через filters.run. Причина не в удобстве:
# живая тяга ходит по колонкам испечённого индекса на два с лишним миллиона
# строк, и подобрать там пул, где «повтор» решает исход, а не везение
# рифмо-корзины, честно нельзя. Здесь колонки заданы прямо, и видно ровно
# одно: что делает барьер.
#
# Барьер к тому же мягкий ПО ЗАМЫСЛУ («строка важнее правила о словах», см.
# запасной путь в `тянуть_строфы`) — поэтому непротиворечивая альтернатива в
# пуле ЕСТЬ: третья строка с тем же рифмо-ключом и другими леммами. Без неё
# запасной путь разрешил бы повтор и без всякой крутилки.


class _Индекс:
    """Колонки индекса ровно те, что читает `тянуть_строфы`: рифмо-ключ, слоги,
    мат и леммы (CSR-парой lem_off/lem_ids). Больше ей ничего не нужно —
    полный индекс сюда тащить незачем, он про другое."""

    keys = ["", "ой"]
    #        текст                     леммы
    СТРОКИ = [("мой дом стоит пустой",  ("дом", "мой")),
              ("твой дом стоит большой", ("дом", "твой")),
              ("и ветер за стеной",     ("ветер", "стена"))]

    def __init__(self):
        словарь = {}
        плоско, границы = [], [0]
        for _, леммы in self.СТРОКИ:
            for л in леммы:
                плоско.append(словарь.setdefault(л, len(словарь)))
            границы.append(len(плоско))
        self.key_id = np.ones(len(self.СТРОКИ), dtype=np.int64)   # все в одной рифме
        self.syl = np.full(len(self.СТРОКИ), 6, dtype=np.int64)
        self.mat = np.zeros(len(self.СТРОКИ), dtype=np.uint8)
        self.lem_ids = np.array(плоско, dtype=np.int64)
        self.lem_off = np.array(границы, dtype=np.int64)

    def text(self, i):
        return self.СТРОКИ[i][0]


@pytest.fixture()
def тяга(monkeypatch):
    """Строфа из двух строк схемы «аа» на своём индексе. `_строки` подменена:
    настоящая разворачивает текст из blob'а, которого у заглушки нет, а тесту
    нужны только тексты выбранных строк."""
    идх = _Индекс()
    monkeypatch.setattr(nlindex, "_строки",
                        lambda idx, ids, оц, пц: [{"text": idx.text(int(i))} for i in ids])

    def отбор(повтор: bool, семя: int):
        строфа = nlindex.тянуть_строфы(
            идх, np.arange(len(идх.СТРОКИ)), [(1, 9), (1, 9)], "аа", 2,
            np.random.default_rng(семя), repeat_ok=повтор, ярусы_рифмы=1)
        return [r["text"] for r in строфа]

    return отбор


def test_bez_povtora_lemma_ne_dublируется(тяга):
    """Прежнее поведение целиком: две строки с леммой «дом» вместе не встают
    НИ РАЗУ, сколько семян ни бери. Это и есть барьер.

    Двадцать пять сёмян, а не одно: тяга берёт строку случайно из рифмо-группы,
    и на одном семени беззубый сторож зеленел бы просто потому, что «ветер»
    вытянулся сам."""
    for семя in range(25):
        тексты = тяга(False, семя)
        assert len(тексты) == 2, f"строфа не собралась (семя {семя}): {тексты}"
        assert sum(1 for t in тексты if "дом" in t) <= 1, \
            f"барьер пропустил повтор леммы (семя {семя}): {тексты}"


def test_s_povtorom_lemma_vozvraschaetsya(тяга):
    """РЕЗУЛЬТАТ, а не наличие флага: барьер снят — и повтор леммы «дом»
    СТАНОВИТСЯ ВОЗМОЖЕН. Возвращающееся слово, на котором и стоит хук.

    Проверяется парой «с ручкой / без ручки» на одних и тех же семенах: одна
    половина без другой ничего не доказывает. Без ручки повтор НЕВОЗМОЖЕН, с
    ручкой — случается; требовать его на КАЖДОМ семени нельзя, выбор внутри
    группы случаен по построению."""
    сповтором = [sum(1 for t in тяга(True, с) if "дом" in t) for с in range(25)]
    assert max(сповтором) == 2, f"с хуком повтор так и не случился ни разу: {сповтором}"

    без = [sum(1 for t in тяга(False, с) if "дом" in t) for с in range(25)]
    assert max(без) == 1, f"без хука повтор всё-таки прошёл: {без}"


def test_krutilka_dohodit_do_tyagi(monkeypatch):
    """Связка: `repeat` из knobs обязан доехать до сборки строфы. Раньше
    перехватывался `filters._select_with_rhyme`, теперь — `nlindex.select`,
    единственная дверь из каскада в тягу (она и передаёт `repeat_ok` дальше).

    Проверяется по РЕЗУЛЬТАТУ вызова, а не чтением кода: с чем ПОЗВАЛИ отбор
    при каждом положении крутилки."""
    from corpus import Corpus
    видели = []
    # Индекс подменяем пустышкой: связка «крутилка → отбор» от содержимого
    # колонок не зависит, а поднимать боевой индекс ради одного kwarg — это
    # 5.5 ГБ и минуты на проверку одного булева значения.
    monkeypatch.setattr(filters, "_index_for_current_cache", lambda: object())
    monkeypatch.setattr(nlindex, "pool_mask", lambda idx, pool: None)
    monkeypatch.setattr(nlindex, "mask_of", lambda idx, texts: None)

    def перехват(idx, **kw):
        видели.append(kw["repeat_ok"])
        return [], 0, {}, {}

    monkeypatch.setattr(nlindex, "select", перехват)
    for v in (0, 1):
        k = clean.knobs({"shortlist": 2, "repeat": v})
        filters.run([], k, Corpus(), nl_fragments=["строка корпуса"], rhyme="аа")
    assert видели == [False, True], f"крутилка не доехала до тяги: {видели}"


