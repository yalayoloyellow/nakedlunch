def test_perepechka_ne_lomaet_generaciyu(tmp_path):
    """ГЛАВНЫЙ. Перепечь индекс на живом сервере — генерация обязана
    продолжать работать, а процесс обязан перейти на НОВЫЕ колонки."""
    дом = tmp_path / "дом"
    р = _запустить("""
испечь_индекс(ДОМ, СТРОКИ_А); испечь_склад(ДОМ, СТРОКИ_А)
прогон("ДО")
print("N_ДО", nlindex.load().n, 0, "")

испечь_индекс(ДОМ, СТРОКИ_Б)            # то же делает сборщик после заливки книги
server._подхватить_свежий_индекс()      # то же делает опрос /api/status
прогон("ПОСЛЕ")
print("N_ПОСЛЕ", nlindex.load().n if nlindex.load() else -1, 0, "")
print("ВЕРДИКТ_СВЕЖИЙ",
      1 if filters._index_for_current_cache() is nlindex.load() else 0, 0, "")
""", дом)
    assert р.returncode == 0, f"стенд упал:\n{р.stdout}\n{р.stderr}"
    до, после = _строки(р, "ДО"), _строки(р, "ПОСЛЕ")
    assert до[1] == "200" and int(до[2]) > 0, \
        f"стенд сломан ещё до перепечки: {' '.join(до)}"
    assert после[1] == "200", (
        "ГЕНЕРАЦИЯ УПАЛА ПОСЛЕ ГОРЯЧЕЙ ПЕРЕПЕЧКИ ИНДЕКСА.\n"
        f"ответ: {' '.join(после)}\n"
        "Значит в процессе снова два индекса: filters держит прежний объект "
        "(его кэш обязан ключеваться САМИМ индексом, а не кэшем рифм), либо "
        "`nlindex.запрет` снова берёт индекс сам, а не из аргумента — "
        "`gate_mask` передаёт ему `self`.")
    assert int(после[2]) > 0, "после перепечки выдача пуста — работать перестало иначе"
    # Пул берётся из хранилища в памяти (там по-прежнему пять строк), поэтому
    # длина выдачи не растёт. Что подхват в самом деле случился, доказывает
    # число строк в КОЛОНКАХ.
    assert _строки(р, "N_ДО")[1] == str(len(СТРОКИ_А))
    assert _строки(р, "N_ПОСЛЕ")[1] == str(len(СТРОКИ_Б)), (
        "после перепечки процесс остался на прежних колонках — значит "
        "`nlindex.load()` вернул None сразу после перезагрузки (гонка `_tried`) "
        "или подхват не случился вовсе")
    # ОТДЕЛЬНО ОТ КОДА ОТВЕТА. Пятисотка ловит только ту половину болезни, при
    # которой длины разошлись; при совпавших длинах два индекса дали бы 200 и
    # выдачу ПО ПРЕЖНЕМУ КОРПУСУ — то есть тихую ложь. Спрашиваем личность.
    assert _строки(р, "ВЕРДИКТ_СВЕЖИЙ")[1] == "1", (
        "filters отдаёт НЕ ТОТ объект индекса, что лежит в `nlindex.load()`. "
        "Значит ключ `_index_verdict` снова не знает про индекс — он обязан "
        "держать сам индекс, а не `id/len` кэша рифм.")


