# 2. КОНТРОЛЬ: без починки тот же стенд обязан покраснеть

def test_kontrol_slomannaya_pochinka_dayot_pyatisotku(tmp_path):
    """БЕЗ ЭТОГО ТЕСТА ГЛАВНЫЙ СТЕРЁГ БЫ ПУСТОТУ.

    Тот же стенд, та же перепечка — но обе половины починки СЛОМАНЫ НАРОЧНО,
    дословно как было до 2026-08-18:
      · `запрет` снова берёт индекс сам из `load()`, а не из аргумента;
      · вердикт filters снова ключуется кэшем рифм, а не самим индексом.
    Отказ обязан воспроизвестись. Если и здесь 200 — значит стенд не ставит
    условия задачи, и зелень главного теста ничего не значит.

    Ломается ИМЕННО ПОЧИНКА, а не путь к ней: раньше здесь стоял голый
    `nlindex.reload()` в обход серверной двери, и этот контроль сторожил
    заплатку — сегодня та же строка законна и отказа не даёт."""
    дом = tmp_path / "дом"
    р = _запустить("""
испечь_индекс(ДОМ, СТРОКИ_А); испечь_склад(ДОМ, СТРОКИ_А)

# ---- ломаем починку, обе половины -----------------------------------------
целый_запрет = nlindex.запрет
# «индекс беру сам» — ровно то, из-за чего в процессе оказывалось два индекса
nlindex.запрет = lambda правила, idx=None: целый_запрет(правила, nlindex.load())

_вердикт = {}
def как_было():
    # прежний ключ: про кэш рифм и НИ СЛОВА про индекс
    ключ = (id(filters._NL_RHYME), len(filters._NL_RHYME))
    if ключ in _вердикт:
        return _вердикт[ключ]
    idx = nlindex.load()
    if idx is not None and filters._NL_RHYME:
        if len(filters._NL_RHYME) != idx.n or idx.text(0) not in filters._NL_RHYME:
            idx = None
    _вердикт.clear()
    _вердикт[ключ] = idx
    return idx
filters._index_for_current_cache = как_было
# ---------------------------------------------------------------------------

прогон("ДО")                     # заодно вердикт запоминает ПЕРВЫЙ индекс
испечь_индекс(ДОМ, СТРОКИ_Б)
nlindex.reload()
прогон("ПОСЛЕ")
""", дом)
    assert р.returncode == 0, f"стенд упал:\n{р.stdout}\n{р.stderr}"
    до = _строки(р, "ДО")
    assert до[1] == "200", f"сломанный стенд не заработал и до перепечки: {' '.join(до)}"
    после = _строки(р, "ПОСЛЕ")
    assert после[1] == "500", (
        "контрольный прогон НЕ воспроизвёл отказ на СЛОМАННОЙ починке — значит "
        f"главный тест зеленеет впустую. Ответ: {' '.join(после)}")
    assert "broadcast" in р.stdout, (
        "отказ воспроизвёлся, но другой — проверь, та ли это поломка:\n" + р.stdout)


