def испечь_индекс(дом: Path, тексты: list[str], rules: str | None = None) -> Path:
    """Мини-индекс в формате tools/build_nl_index.py: те же имена файлов, те же
    dtype, та же запись через временный каталог с переименованием (именно это
    и делает перепечку безопасной для живого mmap)."""
    d = дом / "core" / "data" / "nl_index"
    tmp = d.with_name(d.name + ".tmp")
    if tmp.exists():
        shutil.rmtree(tmp)
    tmp.mkdir(parents=True)
    n = len(тексты)

    куски, off, p = [], [0], 0
    for t in тексты:
        b = t.encode("utf-8")
        куски.append(b)
        p += len(b)
        off.append(p)

    слова, lem_flat, lem_off, tok_pairs = {}, [], [0], []
    content = np.zeros(n, dtype=np.int16)
    for i, t in enumerate(тексты):
        ws = [w for w in t.lower().split() if w]
        content[i] = len(ws)
        for w in ws:
            j = слова.setdefault(w, len(слова))
            lem_flat.append(j)
            tok_pairs.append((j, i))
        lem_off.append(len(lem_flat))

    tp = np.array(tok_pairs, dtype=np.int32) if tok_pairs else np.zeros((0, 2), np.int32)
    order = np.argsort(tp[:, 0], kind="stable") if len(tp) else np.zeros(0, np.int64)
    tokpost = tp[order, 1].copy() if len(tp) else np.zeros(0, np.int32)
    tokoff = np.zeros(len(слова) + 1, dtype=np.int64)
    if len(tp):
        np.cumsum(np.bincount(tp[:, 0], minlength=len(слова)), out=tokoff[1:])

    # рифмо-ключ подделан хвостом строки: важно не КАК он считается, а что
    # разные строки различаются (тот же приём, что в test_живость_сборки.py)
    ключи, key_id = {}, np.zeros(n, dtype=np.uint32)
    for i, t in enumerate(тексты):
        key_id[i] = ключи.setdefault(t.strip().lower()[-3:], len(ключи))
    список_ключей = [""] * len(ключи)
    for k, j in ключи.items():
        список_ключей[j] = k

    массивы = {
        "banal": np.full(n, 3.0, dtype=np.float32),
        "taut": np.zeros(n, dtype=np.uint8),
        "bind": np.zeros(n, dtype=np.float32),
        "mat": np.zeros(n, dtype=np.uint8),
        "syl": np.full(n, 8, dtype=np.uint16),
        "key_id": key_id,
        "span_a": np.full(n, -1, dtype=np.int16),
        "span_b": np.full(n, -1, dtype=np.int16),
        "lem_ids": np.array(lem_flat, dtype=np.int32),
        "lem_off": np.array(lem_off, dtype=np.int64),
        "lem2navec": np.full(len(слова), -1, dtype=np.int32),
        "tokpost": tokpost,
        "tokoff": tokoff,
        "text_off": np.array(off, dtype=np.int64),
        "src": np.zeros(n, dtype=np.int32),
        "content": content,
    }
    for имя, arr in массивы.items():
        np.save(tmp / f"{имя}.npy", arr)
    (tmp / "text_blob.bin").write_bytes(b"".join(куски))
    (tmp / "meta.json").write_text(json.dumps({
        "n": n, "rules": rules if rules is not None else nlindex.RULES,
        # Время сборки РАЗНОЕ у соседних перепечек: по нему сервер и замечает,
        # что индекс испёк кто-то другой (см. `_подхватить_свежий_индекс`).
        "built_at": time.strftime("%Y-%m-%d %H:%M:%S") + f".{time.time_ns() % 1000000}",
        "keys": список_ключей,
        "lemmas": [w for w, _ in sorted(слова.items(), key=lambda kv: kv[1])],
        "tokens": [w for w, _ in sorted(слова.items(), key=lambda kv: kv[1])],
        "sources": ["стенд"],
        "кванты": {"banal": [3.0] * 101, "bind": [0.0] * 101},
    }, ensure_ascii=False), "utf-8")

    if d.exists():
        shutil.rmtree(d)
    tmp.rename(d)
    return d


def испечь_склад(дом: Path, тексты: list[str]) -> Path:
    """Хранилище nakedlunch с одной активной книгой из этих строк."""
    from nlsrc.store import NakedLunchStore, Corpus, Fragment
    d = дом / "корпус"
    st = NakedLunchStore(d)
    st.state.corpora = [Corpus(id="c1", name="стенд", type="personal",
                               active=True, fragment_count=len(тексты))]
    st.state.fragments = [Fragment(id=f"f{i}", text=t, corpus_id="c1")
                          for i, t in enumerate(тексты)]
    st._rebuild_active_fragments()
    st._save(full=True)
    return d


