# nakedlunch — ДИСК УШЁЛ ВПЕРЁД ЗАПУЩЕННОГО ПРОЦЕССА (2026-08-18).
#
# ЧТО СЛУЧАЛОСЬ. Заливка книги через окно печёт кэш ударений, следом
# колоночный индекс, следом зовёт `nlindex.reload()` — всё в живом
# приложении. После этого КАЖДЫЙ `POST /api/generate` отвечал пятисоткой:
#
#   ValueError: operands could not be broadcast together with shapes
#               (2392262,) (2450282,)
#
# и лечилось это только перезапуском окна. То есть самый обычный сценарий
# гасил единственный режим программы.
#
# ПОЧЕМУ. Индексов в процессе оказывалось два. `filters._index_for_current_cache`
# кэширует объект индекса ключом по КЭШУ РИФМ (`id(_NL_RHYME), len(_NL_RHYME)`),
# а перезагрузка индекса этот ключ не двигает — filters вечно отдаёт прежний
# объект. `Index.gate_mask` при этом спрашивает маску чёрного списка у
# `nlindex.запрет()`, а тот берёт индекс не у `self`, а заново из `load()` — то
# есть новый. Старая колонка `&=` новая маска, и numpy честно говорит, что
# длины не сходятся. Маска строится и при ПУСТОМ чёрном списке
# (`np.zeros(idx.n)`), поэтому отказ от правил не зависел.
#
# ГДЕ ЛЕЧЕНИЕ. С 2026-08-18 оно в `core/`, у самого индекса, а не у сервера:
# `запрет(правила, idx)` берёт индекс аргументом, вердикт `filters` держит в
# ключе сам индекс, `nlindex.load()` под замком, `nlindex.reload()` —
# единственная дверь, а `nlindex.ЗАМОК` берут `filters.run` и `nlindex.воронка`
# сами. Прежняя заплатка в `api/server.py` (`_ИНДЕКС_ЗАМОК`,
# `_перечитать_индекс`) убрана целиком.
#
# ЧТО СТОРОЖИТ ЭТОТ ФАЙЛ:
#   1. перепечка на живом сервере не ломает генерацию (главный);
#   2. КОНТРОЛЬ: та же перепечка при НАРОЧНО СЛОМАННОЙ починке обязана дать
#      500 — иначе главный тест зеленел бы на пустом месте;
#   3. вырожденные данные: индекса нет, индекс пустой;
#   4. перепечка НЕ ВЛЕЗАЕТ в середину запроса (замок);
#   5. кэш ударений не остаётся от прежнего корпуса и не отвергает свежий
#      индекс — иначе генерация молча уезжает на медленный путь;
#   6. процесс, разошедшийся с диском, говорит об этом в /api/status.
#
# Пятое здесь не в гостях: это тот же вопрос — «что в памяти старше того, что
# на диске», — только вторым поводом (правка кода после запуска окна) вместо
# первого (перепечка индекса). Судья на оба повода один, `_устарел_процесс`.
#
# СТЕНД, А НЕ БОЕВОЙ ИНДЕКС. Мини-индекс на пять строк пишется здесь же по
# формату tools/build_nl_index.py: звать настоящий сборщик значило бы тянуть
# pymorphy, navec и кэш ударений — минуты и гигабайты ради пяти строк. Дом
# уводится `NAKEDLUNCH_HOME`, боевые каталоги не касаются вовсе.
#
# Прогон: .venv/bin/python -m pytest tests/test_перепечка_индекса.py -q

