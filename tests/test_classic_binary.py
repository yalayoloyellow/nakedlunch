# ПОЧЕМУ ЭТОТ ФАЙЛ ВООБЩЕ НУЖЕН. Карта Раунда 50: старые тесты передают
# `classic` дробными числами, и если бинарность сделать через bool(...), то
# 0.0 и 1.0 продолжат работать — тест останется зелёным, даже если
# промежуточные значения где-то ещё принимаются. Бинарность прежними тестами
# НЕ доказывается. Здесь проверяется именно она, и по результату: что
# классика не подчиняется рифме, слогам и теме, и что ворота (мат, клаузула,
# история, состав пула) при этом живут.
