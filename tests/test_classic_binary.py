# больше не разбирает `!слово` и не передаёт `forced` в `filters.run` вовсе,
# так что ветка `{w: "classic" for w in forced}` недостижима ни одним боевым
# запросом. Сторожить вердикт, которого некому попросить, — сторожить мёртвое.
