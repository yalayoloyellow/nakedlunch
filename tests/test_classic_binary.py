@нужен_большой_индекс
def test_форма_ответа_совпадает_с_алгоритмом(пул):
    """Оба пути обязаны отдавать одну форму — иначе разбирающему пришлось бы
    гадать, какой ярус перед ним."""
    кл = прогон(пул, rhyme="none", shortlist=4)
    ал = filters.run([], clean.knobs({"shortlist": 4, "classic": 0.0}),
                     Corpus(), nl_fragments=пул.тексты, rhyme="none")
    assert set(кл) == set(ал) == {"shortlist", "funnel", "forced_notice", "seed"}
    assert set(кл["funnel"]) == set(ал["funnel"])
    # `forced_notice` остаётся В ФОРМЕ ответа, хотя обязательного слова больше
    # нет: старый бандл в браузере владельца это поле читает.
    assert кл["forced_notice"] == ал["forced_notice"] == {}
    # Штамп семени тоже одной формы на обоих путях (Раунд 62): по нему клиент
    # решает, можно ли повторить прогон, и разная форма значила бы «на классике
    # повторить нельзя» без единого слова об этом.
    assert set(кл["seed"]) == set(ал["seed"]) == {"seed", "index", "pool", "hidden"}
    for r in кл["shortlist"] + ал["shortlist"]:
        assert {"text", "template", "lemmas", "classic", "anchor", "rhyme"} <= set(r)
        assert "_lem" not in r and "_pctl" not in r


