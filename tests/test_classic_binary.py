@нужен_большой_индекс
def test_ворота_мата_на_краях(пул):
    без = прогон(пул, rhyme="none", shortlist=len(пул.тексты), knobs={"mat_share": 0.0})
    только = прогон(пул, rhyme="none", shortlist=len(пул.тексты), knobs={"mat_share": 1.0})
