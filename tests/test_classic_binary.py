# Теперь пул собирается ИЗ НАСТОЯЩЕГО КОРПУСА — строки выбираются по колонкам
# индекса так, чтобы у каждой проверки было ровно то сырьё, которое ей нужно
# (разные рифмо-ключи, известные концовки, известный мат). Отсюда пропуск
# `нужен_большой_индекс` на всём, что трогает корпус: на чистом клоне сторож
# молчит с названной причиной, а там, где корпус есть, он строже прежнего —
# бьёт по той функции, которая работает у владельца.
#
# ═══ НАДГРОБИЕ: `test_форс_слово_в_классике_признаётся_неприменимым` ═══
# УДАЛЁН 2026-08-29. Он проверял, что «!слово» в классике получает честный
