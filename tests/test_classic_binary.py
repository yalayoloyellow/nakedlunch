# ПУЛ ИЗ НАСТОЯЩЕГО КОРПУСА. Строки выбираются по колонкам, а не по тексту:
# так у каждой проверки известны заранее мат, концовка, слоги и рифмо-ключ, и
# при этом они остаются НАСТОЯЩИМИ строками — теми, что доживают до выдачи на
# обоих путях (целые, не тавтология, не под чёрным списком, со знаменательными
# словами). Иначе тест ловил бы не ворота режима, а собственный недосмотр.

class _Пул:
    """Пул стенда и то, что о нём известно."""

    def __init__(self, тексты, мат, дактиль, в_вилке):
        self.тексты = тексты
        self.мат = мат                  # тексты с матом (колонка idx.mat)
        self.дактиль = дактиль          # тексты с дактилической концовкой (clau == 3)
        self.в_вилке = в_вилке          # тексты на 8-9 слогов


@pytest.fixture(scope="module")
def пул():
    idx = nlindex.load()
    if idx is None:
        pytest.skip("индекс не испечён")
    годн = idx.whole_mask().copy()
    годн &= np.asarray(idx.taut) == 0
    if getattr(idx, "content", None) is not None:
        годн &= np.asarray(idx.content) >= nlindex.СЛОВ_МИН
    з = nlindex.запрет(nlindex._правила(), idx)
    if з["маска"] is not None:
        годн &= ~з["маска"]
    мат = np.asarray(idx.mat) != 0
    клау = np.asarray(idx.clau)
    слоги = np.asarray(idx.syl)
    ключ = np.asarray(idx.key_id)

    # РИФМО-КЛЮЧИ У ВСЕХ РАЗНЫЕ — СОЗНАТЕЛЬНО: если классика вдруг начнёт
    # слушаться схемы, собрать из этого пула «абаб» будет физически нечем, и
    # проверка это увидит.
    занято: set = set()

    def выбрать(маска, n):
        взято = []
        for i in np.flatnonzero(маска):
            k = int(ключ[i])
            if k in занято:
                continue
            занято.add(k)
            взято.append(int(i))
            if len(взято) == n:
                break
        assert len(взято) == n, "в корпусе не нашлось сырья для стенда"
        return взято

    коротко = выбрать(годн & ~мат & (клау != 3) & (слоги >= 6) & (слоги <= 7), 4)
    в_вилке = выбрать(годн & ~мат & (клау != 3) & (слоги >= 8) & (слоги <= 9), 2)
    длинно = выбрать(годн & ~мат & (клау != 3) & (слоги >= 12) & (слоги <= 16), 4)
    матерные = выбрать(годн & мат & (клау != 3), 4)
    дактиль = выбрать(годн & ~мат & (клау == 3), 3)

    номера = коротко + в_вилке + длинно + матерные + дактиль
    п = _Пул([idx.text(i) for i in номера],
             {idx.text(i) for i in матерные},
             {idx.text(i) for i in дактиль},
             {idx.text(i) for i in в_вилке})
    # Стенд обязан отвечать за свои обещания сам: тест, у которого сырьё
    # молча выродилось, зелен и бесполезен.
    assert len(set(п.тексты)) == len(номера) == 17
    assert len({int(ключ[i]) for i in номера}) == 17, "рифмо-ключи повторились"
    return п


def прогон(пул, **kw):
    """Классика через ВЕСЬ каскад: clean.knobs → filters.run → select_light."""
    knobs = clean.knobs({"shortlist": kw.pop("shortlist", 6), "classic": 1.0,
                         **kw.pop("knobs", {})})
    return filters.run([], knobs, Corpus(), nl_fragments=пул.тексты, **kw)


