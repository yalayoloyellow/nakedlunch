        строки = [r["text"] for r in res["shortlist"]]
        матерных = sum(1 for s in строки if s in пул.мат)
        assert len(строки) == 4, строки
        assert матерных == 2, (
            f"просили половину, пришло {матерных} из 4 (семя {семя})", строки)
