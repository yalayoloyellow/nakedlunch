# Прогон: .venv/bin/python -m pytest tests/test_classic_binary.py -q

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))

import clean
import filters
import nlbridge
from corpus import Corpus, lemmatize

# рифмо-ключи разные СОЗНАТЕЛЬНО: если классика вдруг начнёт слушаться схемы,
# собрать «абаб» из этих строк будет физически нечем — и тест это увидит
ФРАГМЕНТЫ = {
    "он ушёл в ночной покой": "ой",
    "над рекою тишина": "ина",
    "я запомнил это здание": "ание",
    "дым висел над головой": "ой",
    "полная блядская хуйня": "уйня",
    "заебись как всё сложилось": "илось",
    "короткий вдох": "ох",
    "и снова длинное невыносимое молчание": "ание",
}
МАТЕРНЫЕ = {"полная блядская хуйня", "заебись как всё сложилось"}


@pytest.fixture()
def словарь(monkeypatch):
    # Банальность РАЗНАЯ (Раунд 51). Раньше у всех фрагментов стояло 3.0, а
    # самый строгий возможный потолок — 4.0 (на ручке 1.0, см. nlindex.Ворота):
    # то есть тест «банальность в классике не режет» не мог упасть НИКОГДА,
    # даже если бы классика её послушалась. Теперь половина пула выше потолка.
    fake = {t: {"banal": 3.0 if i % 2 else 5.5, "taut": False, "lemmas": lemmatize(t),
                "tokens": list(nlbridge._tokens(t)), "key": key, "span": None}
            for i, (t, key) in enumerate(ФРАГМЕНТЫ.items())}
    monkeypatch.setattr(filters, "_NL_RHYME", fake)
    monkeypatch.setattr(filters, "_index_for_current_cache", lambda *a, **k: None)
    return fake


def прогон(словарь_не_нужен=None, **kw):
    knobs = clean.knobs({"shortlist": kw.pop("shortlist", 6), "real_text": 1.0,
                         "classic": 1.0, **kw.pop("knobs", {})})
    return filters.run([], knobs, Corpus(), nl_fragments=list(ФРАГМЕНТЫ),
                       **kw)


# ---- переключатель именно БИНАРНЫЙ ------------------------------------------

@pytest.mark.parametrize("значение, классика", [
    (0.0, False), (0.2, False), (0.49, False),
    (0.5, True), (0.7, True), (1.0, True),
])
def test_порог_режима_ровно_половина(словарь, значение, классика):
    """Дробные значения приходят из старых сохранённых настроек и тестов.
    Трактовать 0.7 как «алгоритм» было бы враньём о том, что просили."""
    k = clean.knobs({"shortlist": 4, "real_text": 1.0, "classic": значение})
    res = filters.run([], k, Corpus(), nl_fragments=list(ФРАГМЕНТЫ), rhyme="none")
    # у классического пути строгий ярус не считается вовсе
    assert (res["funnel"]["nl_survived"] == 0) is классика
    assert all(r["classic"] is классика for r in res["shortlist"])


def test_профиль_настроек_даёт_ровно_ноль_или_единицу():
    assert clean.knobs_from_profile({"name": "т", "mode": clean.MODE_CLASSIC})["classic"] == 1.0
    assert clean.knobs_from_profile({"name": "т", "mode": clean.MODE_ALGO})["classic"] == 0.0


# ---- «без ничего»: мнения не действуют --------------------------------------

def test_классика_не_подчиняется_рифмовке(словарь):
    """Гарантия Раунда 35, которую легко потерять при вырезании смешивания:
    сырьё не обязано рифмоваться. Ключи фрагментов подобраны так, что «абаб»
    из них не собрать — если бы схема действовала, выдача бы схлопнулась."""
    res = прогон(rhyme="абаб", shortlist=8)
    assert len(res["shortlist"]) == len(ФРАГМЕНТЫ)


def test_классика_не_подчиняется_вилке_слогов(словарь):
    """Спека требует ровно 8-9 слогов; в пуле такие есть далеко не все.
    Классика обязана отдать всё, а не только подходящее по длине."""
    спека = [{"letter": "а", "min_syl": 8, "max_syl": 9}] * 4
    res = прогон(rhyme="аааа", stanza=спека, shortlist=8)
    слоги = {r["syllables"] for r in res["shortlist"]}
    assert len(res["shortlist"]) == len(ФРАГМЕНТЫ)
    assert слоги - {8, 9}, "в выдаче обязаны быть строки вне вилки — иначе слоги действуют"


def test_классика_не_считает_тему(словарь):
    """Тема РАНЖИРУЕТ, а классика не ранжирует: у всех строк оценка одна.

    Раньше тест просил 8 строк из пула ровно в 8 — состав совпадал всегда, что
    бы код ни делал, и упасть он не мог. Теперь проверяется само свойство:
    оценка плоская и не зависит от темы."""
    a = прогон(tags=["ночь"], shortlist=4)
    b = прогон(tags=["деньги"], shortlist=4)
    оценки = {r["score"] for r in a["shortlist"]} | {r["score"] for r in b["shortlist"]}
    assert оценки == {0.6}, f"в классике оценка обязана быть плоской, а не {оценки}"
    # и тема не должна оставлять следа в самих строках
    for r in a["shortlist"] + b["shortlist"]:
        assert r["template"] == "nakedlunch"


def test_банальность_в_классике_не_режет(словарь):
    """Банальность — мнение extendo о качестве, классика их не знает.

    Тест ЗНАЧИМ только если в пуле есть фрагменты выше строгого потолка:
    на ручке 1.0 потолок 4.0 (nlindex.ворота_банальности). В фикстуре
    половина строк с banal=5.5 — они обязаны пережить классику и обязаны
    отсеяться алгоритмом. Раньше у всех стояло 3.0, и тест не мог упасть."""
    выше_потолка = {t for t, e in словарь.items() if e["banal"] > 4.0}
    assert выше_потолка, "фикстура бессмысленна: нечему отсеиваться"

    строгая = прогон(shortlist=8, knobs={"banality": 1.0})
    assert len(строгая["shortlist"]) == len(ФРАГМЕНТЫ), "классика не судит о качестве"
    assert выше_потолка <= {r["text"] for r in строгая["shortlist"]}

    # контроль: тот же потолок в АЛГОРИТМЕ обязан их вырезать — иначе тест
    # доказывает не «классика не режет», а «потолок вообще не работает»
    k = clean.knobs({"shortlist": 8, "real_text": 1.0, "classic": 0.0, "banality": 1.0})
    алго = filters.run([], k, Corpus(), nl_fragments=list(ФРАГМЕНТЫ), rhyme="none")
    assert not (выше_потолка & {r["text"] for r in алго["shortlist"]}), \
        "потолок банальности не режет даже в алгоритме — тест ничего не доказывает"


def test_в_классике_нет_грамматических_строк(словарь):
    """«Источники» в классике неприменимы: генератора extendo в режиме нет.
    Даже при Источники=0 выдача обязана быть корпусной, а не пустой и не
    грамматической (карта Раунда 50 поймала это как молчаливую ловушку)."""
    k = clean.knobs_from_profile({"name": "т", "mode": clean.MODE_CLASSIC,
                                  "params": {"Источники": 0.0}})
    k["shortlist"] = 6
    res = filters.run([], k, Corpus(), nl_fragments=list(ФРАГМЕНТЫ), rhyme="none")
    assert res["shortlist"], "классика при Источники=0 не должна давать пустоту"
    assert all(r["template"] == "nakedlunch" for r in res["shortlist"])


# ---- ворота живут -----------------------------------------------------------

def test_ворота_мата_на_краях(словарь):
    без = прогон(shortlist=8, knobs={"mat_share": 0.0})
    только = прогон(shortlist=8, knobs={"mat_share": 1.0})
    assert not ({r["text"] for r in без["shortlist"]} & МАТЕРНЫЕ)
    assert {r["text"] for r in только["shortlist"]} <= МАТЕРНЫЕ
    assert только["shortlist"], "антифильтр не должен обнулять выдачу"


def test_доля_мата_в_середине_шкалы(словарь):
    """Без рифмо-схемы раскладывать по позициям нечего — просто набираем
    нужное количество матерных и добираем остальным."""
    res = прогон(shortlist=4, knobs={"mat_share": 0.5})
    матерных = sum(1 for r in res["shortlist"] if r["text"] in МАТЕРНЫЕ)
    assert len(res["shortlist"]) == 4
    assert матерных == 2


def test_доля_мата_не_сжимает_выдачу_при_нехватке(словарь):
    """Матерных в пуле всего два. Просим 80% из шести — лучше промахнуться по
    проценту, чем отдать три строки вместо шести."""
    res = прогон(shortlist=6, knobs={"mat_share": 0.8})
    assert len(res["shortlist"]) == 6


def test_ворота_клаузулы_в_классике(словарь):
    res = прогон(shortlist=8, knobs={"clausula": 3})
    assert {r["text"] for r in res["shortlist"]} == {
        "я запомнил это здание", "и снова длинное невыносимое молчание"}


def test_история_вычитается(словарь, monkeypatch):
    monkeypatch.setattr(Corpus, "hidden_set", lambda self: {"короткий вдох", "над рекою тишина"})
    res = прогон(shortlist=8)
    тексты = {r["text"] for r in res["shortlist"]}
    assert "короткий вдох" not in тексты and "над рекою тишина" not in тексты
    assert len(тексты) == len(ФРАГМЕНТЫ) - 2


# ---- честность о пределах ---------------------------------------------------

def test_форс_слово_в_классике_признаётся_неприменимым(словарь):
    """Раньше «!слово» в классике молча получало вердикт «нет подходящей
    строки в базе» — враньё о причине. Тема в режиме не действует вовсе."""
    res = прогон(shortlist=6, tags=["ночь"], forced={"ночь"})
    assert res["forced_notice"] == {"ночь": "classic"}


def test_форма_ответа_совпадает_с_алгоритмом(словарь):
    """Оба пути обязаны отдавать одну форму — иначе разбирающему пришлось бы
    гадать, какой ярус перед ним."""
    кл = прогон(shortlist=4)
    ал = filters.run([], clean.knobs({"shortlist": 4, "real_text": 1.0, "classic": 0.0}),
                     Corpus(), nl_fragments=list(ФРАГМЕНТЫ), rhyme="none")
    assert set(кл) == set(ал) == {"shortlist", "funnel", "forced_notice"}
    assert set(кл["funnel"]) == set(ал["funnel"])
    for r in кл["shortlist"] + ал["shortlist"]:
        assert {"text", "template", "lemmas", "classic", "anchor", "rhyme"} <= set(r)
        assert "_lem" not in r and "_pctl" not in r


def test_смешивания_ярусов_больше_нет():
    """Слой смешивания вырезан целиком: если он вернётся, вернётся и молчаливое
    «половина строфы рифмуется, половина нет»."""
    assert not hasattr(filters, "_classic_slot_plan")
    import inspect
    подпись = inspect.signature(filters._select_with_rhyme).parameters
    assert "classic_quota" not in подпись
