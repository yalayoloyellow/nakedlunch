# nakedlunch — сторожа на снятые глушители ошибок.
#
# ЗАЧЕМ. В складе стояло два `except Exception: pass` вокруг чтения маленьких
# файлов состояния. Оба глушили сбой, у которого есть видимое последствие:
#
#   · `active.json` — какие книги включены. Не прочитался — ВСЕ книги
#     считаются включёнными. Человек выключил половину склада, файл побился,
#     и выключенное молча вернулось в выдачу. Со стороны это «генератор снова
#     тащит мусор», и причина невидима;
#   · `dynamic.json` — история показов. Не прочиталась — программа забыла всё,
#     что уже показывала, и начинает повторять. Со стороны это «история
#     сломалась».
#
# Оба случая раньше выглядели как исправная работа. Теперь склад называет беду
# вслух в поле `последняя_беда`, а сама программа продолжает работать: молчать
# нельзя, падать тоже незачем.
#
# Прогон: .venv/bin/python -m pytest tests/test_молчаливые_сбои.py -q

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "core"))

from nlsrc.store import NakedLunchStore   # noqa: E402


def завести(tmp_path):
    s = NakedLunchStore(tmp_path)
    s.add_corpus("книга", "Стояла зима. Мороз был крепок. " * 40)
    return s


def test_целый_склад_ни_на_что_не_жалуется():
    """Контроль: на здоровых файлах поле беды пустое.

    Без этого сторожа два теста ниже зеленели бы и на сломанном коде, который
    жалуется всегда."""
    import tempfile
    with tempfile.TemporaryDirectory() as д:
        s = завести(Path(д))
        s2 = NakedLunchStore(Path(д))
        assert s2.последняя_беда == "", (
            "целый склад жалуется на пустом месте: " + s2.последняя_беда)
        assert s2.state.corpora, "книга не поднялась"


def test_битые_флаги_книг_не_молчат(tmp_path):
    """`active.json` испорчен — склад обязан сказать, а не включить всё молча."""
    s = завести(tmp_path)
    cid = s.state.corpora[0].id
    s.toggle_active(cid)                      # выключили книгу, флаг записан
    assert s.active_path.exists()
    s.active_path.write_text("{это не json", encoding="utf-8")

    свежий = NakedLunchStore(tmp_path)
    assert свежий.последняя_беда, (
        "флаги книг не прочитались, а склад промолчал — выключенные книги "
        "вернулись в выдачу без единого следа")
    assert "флаги" in свежий.последняя_беда.lower(), (
        "беда названа, но не про флаги: " + свежий.последняя_беда)
    # и работать он при этом продолжает
    assert свежий.state.corpora, "склад упал вместо того, чтобы пожаловаться"


def test_битая_история_показов_не_молчит(tmp_path):
    """`dynamic.json` испорчен — склад обязан сказать, что история пуста."""
    s = завести(tmp_path)
    s.dynamic_path.write_text('{"used_lines": {"а": "не число"}}', encoding="utf-8")

    свежий = NakedLunchStore(tmp_path)
    assert свежий.последняя_беда, (
        "история показов не прочиталась, а склад промолчал — программа начнёт "
        "повторять показанное, и причина будет невидима")
    assert "истори" in свежий.последняя_беда.lower(), (
        "беда названа, но не про историю: " + свежий.последняя_беда)
    assert свежий.state.corpora, "склад упал вместо того, чтобы пожаловаться"
