# nakedlunch — отказ по расчёту вместо свопа на слабой машине.
#
# ЗАЧЕМ. У программы есть один расход, который зависит от железа, а не от
# запроса: когда колоночного индекса нет, запасной путь поднимает словарь рифм
# ЦЕЛИКОМ. Замерено — файл в 946 МБ даёт около 5.5 ГБ резидентной памяти на
# весь срок жизни процесса. На шестнадцати гигабайтах это заметно, на восьми —
# своп, и не «медленно», а намертво: система выгружает сама себя, а человек
# видит зависшее окно без единого слова о причине.
#
# Поэтому загрузка теперь начинается с расчёта. Не помещается — честный отказ
# с числами и выходом, а не попытка и смерть.
#
# Прогон: .venv/bin/python -m pytest tests/test_память_машины.py -q

import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "core"))

import filters   # noqa: E402
import память    # noqa: E402


ГБ = 1024 ** 3


@pytest.fixture
def словарь(tmp_path, monkeypatch):
    """Подставной файл словаря заданного размера.

    Файл РАЗРЕЖЕННЫЙ (`os.truncate`): на диске он занимает ноль, а `st_size`
    отвечает честно. Подменять сам `stat` нельзя — у `Path` атрибуты не
    ставятся, — да и незачем: проверяется путь, который спрашивает файл."""
    import os

    def завести(гигабайт: float):
        ф = tmp_path / "nl_rhyme.jsonl"
        ф.write_bytes(b"")
        os.truncate(ф, int(гигабайт * ГБ))
        return ф
    return завести


def test_на_слабой_машине_отказ_с_числами(словарь, monkeypatch):
    """Восемь гигабайт и словарь на гигабайт: шесть нужно, пять можно — отказ."""
    файл = словарь(1.0)
    monkeypatch.setattr(память, "озу_байт", lambda: 8 * ГБ)
    with pytest.raises(память.НеХватит) as беда:
        память.проверить_словарь(файл)
    текст = str(беда.value)
    # отказ обязан называть ЧИСЛА и ВЫХОД, иначе он не лучше зависания
    assert "6.0 ГБ" in текст, "не сказано, сколько нужно: " + текст
    assert "8.0 ГБ" in текст, "не сказано, сколько есть: " + текст
    assert "nl_index" in текст, "не назван выход — привезти индекс: " + текст


def test_на_сильной_машине_молчит(словарь, monkeypatch):
    """Шестнадцать гигабайт и тот же словарь: шесть нужно, тринадцать можно."""
    файл = словарь(1.0)
    monkeypatch.setattr(память, "озу_байт", lambda: 16 * ГБ)
    память.проверить_словарь(файл)      # не бросает — этого и ждём


def test_система_не_ответила_не_повод_отказывать(словарь, monkeypatch):
    """Ноль от `озу_байт` — это «не знаю», а не «нисколько».

    Отказать по незнанию значит сломать машину, на которой всё бы работало."""
    файл = словарь(4.0)
    monkeypatch.setattr(память, "озу_байт", lambda: 0)
    память.проверить_словарь(файл)


def test_проверку_можно_снять(словарь, monkeypatch):
    """Тот, кто знает, что делает, обязан иметь ключ."""
    файл = словарь(4.0)
    monkeypatch.setattr(память, "озу_байт", lambda: 8 * ГБ)
    monkeypatch.setenv("NAKEDLUNCH_ПАМЯТЬ", "не_спрашивай")
    память.проверить_словарь(файл)


def test_озу_байт_отвечает_правдоподобно():
    """Проба самой машины: ответ либо ноль (не знаю), либо разумный объём."""
    b = память.озу_байт()
    assert b == 0 or 1 * ГБ <= b <= 2048 * ГБ, f"неправдоподобный объём: {b}"


# ---------------------------------------------------------------- запускальщик

def test_запускальщик_отказывает_до_старта_ядра(tmp_path, monkeypatch):
    """Отказ обязан родиться В ЗАПУСКАЛЬЩИКЕ, а не в дочернем ядре.

    Из ядра он выглядел бы как «Ядро не ответило за отведённое время» — таймаут
    вместо причины, а причина осталась бы в журнале, куда человек не пойдёт."""
    import os
    sys.path.insert(0, str(КОРЕНЬ))
    import launch

    дом = tmp_path / "прога"
    (дом / "core" / "data").mkdir(parents=True)
    словарь = дом / "core" / "data" / "nl_rhyme.jsonl"
    словарь.write_bytes(b"")
    os.truncate(словарь, 2 * ГБ)              # 2 ГБ на диске → 12 ГБ в памяти
    monkeypatch.setattr(launch, "HERE", дом)
    monkeypatch.setattr(память, "озу_байт", lambda: 8 * ГБ)

    беда = launch.не_потянет()
    assert беда, "запускальщик промолчал — человек увидит таймаут вместо причины"
    assert "12.0 ГБ" in беда and "8.0 ГБ" in беда, "отказ без чисел: " + беда


def test_с_индексом_запускальщик_не_мешает(tmp_path, monkeypatch):
    """Индекс на месте — тяжёлый путь не включается, спрашивать нечего."""
    import os
    sys.path.insert(0, str(КОРЕНЬ))
    import launch

    дом = tmp_path / "прога"
    (дом / "core" / "data" / "nl_index").mkdir(parents=True)
    (дом / "core" / "data" / "nl_index" / "meta.json").write_text("{}", encoding="utf-8")
    словарь = дом / "core" / "data" / "nl_rhyme.jsonl"
    словарь.write_bytes(b"")
    os.truncate(словарь, 4 * ГБ)
    monkeypatch.setattr(launch, "HERE", дом)
    monkeypatch.setattr(память, "озу_байт", lambda: 8 * ГБ)

    assert launch.не_потянет() == "", "индекс есть, а запускальщик всё равно отказал"
