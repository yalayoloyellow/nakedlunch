# Пул на замер: каждая восьмая строка корпуса. Не весь корпус — чтобы список
# текстов строился за полсекунды, — но и не игрушка: 288 тысяч, то есть на
# порядок больше боевого замера, где сборщик умирал (38 779 кандидатов, 688 с).
@pytest.fixture(scope="module")
def боевой_пул():
    idx = nlindex.load()
    return [idx.text(i) for i in range(0, idx.n, 8)]


@pytest.fixture(scope="module")
def прогретый(боевой_пул):
    """Один холостой прогон ДО замера — и это не поблажка.

    Первое обращение к индексу в процессе платит за то, что в работе платит
    старт сервера, а не запрос: карту «текст → номер» (~7 с на 2.3 млн) и маску
    целых фрагментов (~5 с). Сервер греет их фоном (`nlindex.warm_background`),
    поэтому мерить их здесь значило бы мерить не то, что переживает
    пользователь. Замер ниже — цена САМОЙ СБОРКИ."""
    _прогон(боевой_пул, "абаб", (6, 9), 100, семя=0)
    return боевой_пул


def _прогон(пул, схема, вилка, size, семя):
    строфа = [{"letter": б, "min_syl": вилка[0], "max_syl": вилка[1]} for б in схема]
    knobs = clean.knobs({"shortlist": size, "classic": 0.0})
    return filters.run([], knobs, Corpus(), nl_fragments=пул,
                       rhyme=схема, stanza=строфа, семя=семя)


@нужен_большой_индекс
def test_ода_не_квадратична(прогретый):
    """Сторож сложности на ТОЙ САМОЙ форме, где было 688 секунд: Одическая
    строфа в десять строк, двести строк выдачи, пул в 288 тысяч.

    Порог 3 секунды намеренно щедрый — сторож ловит возврат О(size × пул), а не
    колебания машины. Замер на этом же стенде 2026-08-29: 0.04 с, то есть запас
    в семьдесят пять раз. Если он когда-нибудь съестся, это будет означать
    ровно одно: сборка снова смотрит на всех кандидатов ради каждой строки."""
    t = time.time()
    res = _прогон(прогретый, "абабввгддг", (8, 9), 200, семя=1)
    прошло = time.time() - t
    # Пустая выдача уложилась бы в любой порог: без этой проверки секундомер
    # сторожил бы скорость ничегонеделания.
    assert len(res["shortlist"]) == 200, "строфа не собралась — замер бессмыслен"
    assert прошло < 3.0, f"сборка заняла {прошло:.1f}с — вернулся перебор пула"


@нужен_большой_индекс
def test_одиночная_строфа_не_медленнее(прогретый):
    """Сторож ПОВСЕДНЕВНОГО пути — обычной генерации «абаб» одним вызовом, а не
    длинной оды.

    Он стоит отдельно с тех пор, как первая версия ускорения вынесла правила
    отбора в функцию-предикат: на длинной схеме летало, а здесь давало
    РЕГРЕССИЮ (15.8 → 20.6 секунды на боевом пуле) — вызов на каждого кандидата
    съедал выигрыш там, где ранний выход не срабатывает. Тесты на совпадение
    выдачи этого поймать не могли: строки были те же.

    Форма сохранена дословно: много кандидатов, короткая схема, небольшой
    size. Замер 2026-08-29: 0.04 с."""
    t = time.time()
    res = _прогон(прогретый, "абаб", (6, 9), 100, семя=2)
    прошло = time.time() - t
    assert len(res["shortlist"]) == 100, "строфа не собралась — замер бессмыслен"
    assert прошло < 2.0, f"одиночная генерация заняла {прошло:.1f}с"


