def test_nichi_ne_zavisyat_ot_nomera_no_ball_glavnee():
    """ПРАВИЛО НИЧЬИХ ПЕРЕПИСАНО (Раунд 57). Раньше тест требовал: при равных
    оценках выбирается кандидат с МЕНЬШИМ номером. Это правило и убило
    разнообразие — Раунд 56 заменил обход перемешанного пула на обход
    отсортированного списка, номер стал вторым ключом, и при одних настройках
    выдача пошла по одному и тому же списку сверху вниз. Отчёт: выдача не строгая, повторяется почти дословно., причём БЕЗ темы.

    Новое правило: балл главнее всего, а между равными выбор случаен. Проверяем
    обе половины — что балл побеждает и что ничьи разъезжаются."""
    def пул(баллы):
        return [{"text": f"строка {i}", "template": "nakedlunch", "meter": None,
                 "rhyme": "ана", "rhyme_span": None, "syllables": 8,
                 "score": b, "_lem": {f"л{i}"}, "mat": False,
                 "clausula": 1, "classic": False, "_pctl": b}
                for i, b in enumerate(баллы)]

    # балл главнее: единственный лучший обязан быть выбран при любом семени
    for семя in (1, 2, 3, 4, 5):
        filters.закрепить_разброс(семя)
        выдача = filters._select_with_rhyme(пул([0.6] * 30 + [0.9]), "аа", 2, precision=0.0)
        assert выдача, "лучший по баллу не выбран вовсе"
        assert "строка 30" in {r["text"] for r in выдача}, f"балл проигран номеру, семя {семя}"

    # ничьи: на разных семенах выдача обязана РАЗЛИЧАТЬСЯ хотя бы иногда
    видели = set()
    for семя in range(40):
        filters.закрепить_разброс(семя)
        выдача = filters._select_with_rhyme(пул([0.6] * 50), "аа", 2, precision=0.0)
        видели.add(tuple(r["text"] for r in выдача))
    filters.закрепить_разброс(20260806)
    assert len(видели) > 1, "ничьи решаются одинаково — разнообразие снова мертво"



