#
# Сторож стоял на гарантии «!слово» — на единственном месте, где у обещания был
# соблазн взять показанную строку. Гарантии больше нет, а правило осталось, и
# теперь оно проверяется там, где вычитание живёт на самом деле: на обоих путях
# отбора. Их ровно два, и разойтись им нельзя.

@нужен_большой_индекс
def test_история_вычитается_на_обычном_пути():
    """Колоночный путь (он же боевой): показанное не возвращается.

    Бьём в `nlindex.select` напрямую, а не через весь каскад: так сторож не
    зависит ни от схемы, ни от вилки слогов и остаётся быстрым."""
    idx = nlindex.load()
    пул = [idx.text(i) for i in range(0, 4000, 7)]
    показано = set(пул[::2])
    строки, выжило, _, _ = nlindex.select(
        idx, pool_mask=nlindex.pool_mask(idx, пул),
        hidden_mask=nlindex.mask_of(idx, показано),
        no_mat=False, only_mat=False, clausula=0,
        cap=len(пул), reserve_n=0, syllable_spec=None, per_bucket=1, seed=1)
    тексты = {r["text"] for r in строки}
    assert тексты, "выдача пуста — тест ничего не проверил"
    assert not (тексты & показано), (
        f"показанное вернулось: {sorted(тексты & показано)[:3]}")
    # И вычли РОВНО показанное, а не заодно половину пула: выжившие плюс
    # показанные обязаны покрывать весь пул за вычетом отсева ворот.
    assert выжило == len(тексты), "жребий потерял строки помимо истории"


def test_история_вычитается_и_без_индекса():
    """Путь БЕЗ колонок — тот, что работает до первой выпечки индекса.

    Он живой: `filters._run` и `filters._classic_pool` уходят сюда, когда
    `_index_for_current_cache()` отдаёт None. Правило истории на нём обязано
    быть тем же — иначе выдача зависела бы от того, испечён индекс или нет, а
    это ровно тот класс расхождения, из-за которого маску клаузулы в классике
    не поймали ни одним тестом."""
    class Корпус:
        def __init__(self, скрытые): self._h = set(скрытые)
        def hidden_set(self): return set(self._h)
        def blacklist_set(self): return set()

    показано = {f"строка {i} про снег и дом" for i in range(0, 40, 2)}
    пул = [f"строка {i} про снег и дом" for i in range(40)]
    ответ = filters._nl_scored(пул, Корпус(показано), показано, light=True)
    assert ответ is not None, (
        "_nl_scored(light=True) вернул None вместо пары (строки, кандидаты): "
        "в светлой ветке нет `return out, forced_candidates` — путь без "
        "индекса падает TypeError у обоих вызывающих (filters.py:751 и :1171)")
    выдача, _ = ответ
    тексты = {r["text"] for r in выдача}
    assert тексты, "выдача пуста — тест ничего не проверил"
    assert not (тексты & показано), (
        f"показанное вернулось: {sorted(тексты & показано)[:3]}")
    assert len(тексты) == 20, f"вычли не только показанное: осталось {len(тексты)}"


