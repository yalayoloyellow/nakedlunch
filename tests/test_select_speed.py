def test_bolshoy_pul_ne_kvadratichen():
    """Сторож сложности. Десять тысяч кандидатов и схема оды: до ускорения это
    полный перебор на каждой якорной позиции, после — обход до первого
    подходящего.

    Порог 5 секунд намеренно щедрый — тест ловит возврат О(size × пул), а не
    колебания машины. Замер на боевом пуле (38 779 кандидатов, size=500):
    688.4 секунды до, 8.6 после."""
    rnd = random.Random(7)
    кандидаты = [кандидат(rnd, i) for i in range(10_000)]
    t = time.time()
    выдача = filters._select_with_rhyme(кандидаты, "абабввгддг", 200,
                                        set(range(200)), precision=0.25,
                                        theme_anchor=True,
                                        syllable_spec=[(8, 9)] * 10)
    прошло = time.time() - t
    assert len(выдача) == 200
    assert прошло < 5.0, f"отбор занял {прошло:.1f}с — вернулся полный перебор"


def test_odinochnaya_stopa_ne_medlennee():
    """Сторож ПОВСЕДНЕВНОГО пути — обычной одиночной генерации (25 строф
    «абаб» одним вызовом), а не ночного пайплайна.

    Первая версия ускорения выносила правила отбора в отдельную функцию-
    предикат: на пайплайне летало, а здесь давала РЕГРЕССИЮ (замерено на
    боевом пуле: 15.8 → 20.6 секунды) — вызов Python-функции на каждого
    кандидата съедал выигрыш там, где ранний выход не срабатывает. Тесты
    эквивалентности этого поймать не могли: выдача была та же.

    Форма здесь та же, что у регрессии: много кандидатов, короткая схема,
    небольшой size — то есть якорей мало, а идти по порядку приходится
    далеко."""
    rnd = random.Random(11)
    кандидаты = [кандидат(rnd, i) for i in range(10_000)]
    t = time.time()
    выдача = filters._select_with_rhyme(кандидаты, "абаб", 100, set(range(100)),
                                        precision=0.25, theme_anchor=True,
                                        syllable_spec=[(6, 9)] * 4)
    прошло = time.time() - t
    assert len(выдача) == 100
    assert прошло < 3.0, f"одиночная генерация заняла {прошло:.1f}с"


