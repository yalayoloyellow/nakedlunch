# extendo — ЭКВИВАЛЕНТНОСТЬ отбора после ускорения (Раунд 56).
#
# ЗАЧЕМ ЭТОТ ФАЙЛ. Замер на цепочке пользователя: один текст серии — 777 секунд,
# и 688 из них уходит на ОДНО звено (Одическая строфа в десять строк). Разбор:
# `_select_with_rhyme` ищет максимум ранга ПОЛНЫМ перебором пула, а пул после
# слогового резерва — 41-74 тысячи кандидатов; якорных позиций в оде пять на
# блок плюс тематическая, блоков пятьдесят.
#
# Ускорение построено на тождестве, а не на компромиссе: когда связность
# выключена, ранг кандидата от позиции не зависит, значит первый подходящий в
# порядке (-ранг, номер) и есть argmax полного перебора. Ничьи разрешаются так
# же, как их разрешал строгий `rank > best_rank`, — в пользу меньшего номера.
#
# Тождество надо ДОКАЗЫВАТЬ, а не обещать. Здесь лежит эталон, снятый с кода
# ДО правки (tests/data/select_golden.json): 24 случая — разные схемы (включая
# десятибуквенную оду), размеры, вилки слогов, точности рифм, доли мата,
# включённая и выключенная связность, тематический якорь, разрешённый повтор.
# Оценки в эталоне НАРОЧНО грубые (четыре значения на весь пул), чтобы ничьих
# было много: именно порядок их разрешения — самое хрупкое место правки.
#
# Прогон: .venv/bin/python -m pytest tests/test_select_speed.py -q

