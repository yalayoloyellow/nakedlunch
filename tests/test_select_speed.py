def test_banalnost_ne_nagrazhdaet_imena():
    """Имя собственное не делает строку «редкой» (Раунд 57).

    Опознаётся МОРФОЛОГИЕЙ, а не заглавной буквой: в отчёте были строки целиком капсом — «ТАМ ДОСТАЛ НОЖ — РЕЖЬ» — и сказал «это не плохо, что оно
    капсом; там главное не имя». По регистру «ТИМОН» от «ЖИЗНЬ» не отличить.
    """
    import corpus as _c
    from wordfreq import zipf_frequency

    # сам разделитель: помета не зависит от регистра
    assert _c.имя_ли("ТИМОН") and _c.имя_ли("тимон") and _c.имя_ли("Дольмансе")
    assert not _c.имя_ли("ЖИЗНЬ") and not _c.имя_ли("НОЖ") and not _c.имя_ли("жизнь")

    def банал(текст):
        пары = _c.lemmatize_pairs(текст)
        леммы = [l for _, l, _ in пары]
        годные = [l for _, l, имя in пары if not имя] or леммы
        return min((zipf_frequency(l, "ru") for l in годные), default=9.0)

    assert банал("я надеюсь на Дольмансе") == банал("я надеюсь на тепло"), (
        "имя собственное всё ещё тянет банальность вниз, то есть даёт бонус")

    # строка целиком капсом — обычный материал, а не «сплошь имена»
    пары = _c.lemmatize_pairs("ТАМ ДОСТАЛ НОЖ РЕЖЬ")
    assert all(not имя for _, _, имя in пары), "капс принят за имена собственные"


def test_reban_menyaet_tolko_dve_grafy(tmp_path):
    """Пересчёт формулы качества не смеет трогать данные (Раунд 57).

    `--reban` существует ровно потому, что перепечка целиком стоит час, а
    формула банальности к ударениям отношения не имеет. Цена ошибки здесь
    высокая: проход переписывает весь кэш на 2.4 млн записей. Значит сторож
    обязан проверить, что меняются РОВНО banal и content, а ключ, ударения,
    span, леммы и токены остаются байт в байт."""
    import importlib.util
    корень = Path(__file__).resolve().parent.parent
    # `_accent` лежит рядом со сборщиком и подхватывается им по имени модуля —
    # мой аудит «осиротевших инструментов» его не увидел именно поэтому: искал
    # упоминание ИМЕНИ ФАЙЛА, а импорт идёт по имени модуля.
    sys.path.insert(0, str(корень / "tools"))
    спец = importlib.util.spec_from_file_location("bnr", корень / "tools" / "build_nl_rhyme.py")
    bnr = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(bnr)
    # САЙДКАР СТАТУСА — ВО ВРЕМЕННУЮ ПАПКУ (2026-08-18). `reban()` — на вид
    # чистое преобразование словаря, но по дороге она зовёт `_write_status`, а
    # тот пишет в `пути.артефакт("nl_rhyme.status.json")`. Без подмены это
    # БОЕВОЙ core/data, и там оставалось «сборка идёт» с номером мёртвого
    # процесса: строку «готово» пишет `main()` сборщика, которого тест не зовёт.
    # Пользователь видел в шапке приложения работу, которой не было.
    bnr.STATUS = tmp_path / "nl_rhyme.status.json"

    было = {
        "я надеюсь на Дольмансе": {
            "key": "СЕ", "span": [10, 18], "banal": 0.0, "taut": False,
            "lemmas": ["надеяться", "дольмансе"], "tokens": ["я", "надеюсь", "на", "дольмансе"],
        },
    }
    стало = bnr.reban({k: dict(v) for k, v in было.items()})
    з, с = было["я надеюсь на Дольмансе"], стало["я надеюсь на Дольмансе"]

    for поле in ("key", "span", "taut", "lemmas", "tokens"):
        assert с[поле] == з[поле], f"reban тронул «{поле}» — а не должен ни одного байта"
    assert с["banal"] > з["banal"], "банальность не пересчиталась"
    assert с["content"] >= 1, "поле content не появилось"
