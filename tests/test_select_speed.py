# ЖЕЛЕЗНОЕ ПРАВИЛО ИСТОРИИ (Раунд 57). Правило, заданное дословно: что в истории — не повторяется и не генерится, пока история не
# очищена; в любых обстоятельствах. Нет материала на тему — честный отказ..
#
# Сторож нужен именно на ОБЯЗАТЕЛЬНОЕ слово: это единственный путь в коде, где
# у гарантии был соблазн взять показанную строку, лишь бы обещание выполнить.
# Первая моя правка так и сделала — оставила показанных «на крайний случай».

def test_obyazatelnoe_slovo_ne_beryot_iz_istorii():
    """Показанное не возвращается даже ради `!слово` — честный отказ вместо."""
    def строка(t):
        return {"text": t, "template": "nakedlunch", "meter": None, "rhyme": "ана",
                "rhyme_span": None, "syllables": 8, "score": 0.6, "_lem": {"л"},
                "mat": False, "clausula": 1, "classic": False}

    shortlist = [строка("чужая строка раз"), строка("чужая строка два")]
    кандидаты = {"кит": [строка("кит уже показывался"), строка("кит тоже показывался")]}

    # без истории — обещание выполнено
    итог = filters._ensure_forced([dict(r) for r in shortlist], {"кит"},
                                  {"кит": [dict(c) for c in кандидаты["кит"]]},
                                  "none", 0.0, hidden=set())
    assert итог["кит"] == "ok", "без истории обязательное слово обязано встать"

    # вся выдача по слову уже в истории — отказ, а не тихий повтор
    история = {c["text"] for c in кандидаты["кит"]}
    список = [dict(r) for r in shortlist]
    итог = filters._ensure_forced(список, {"кит"},
                                  {"кит": [dict(c) for c in кандидаты["кит"]]},
                                  "none", 0.0, hidden=история)
    # «shown» — тот же отказ, только с честной причиной (см. соседний тест)
    assert итог["кит"] == "shown", "гарантия протащила показанную строку"
    assert not (история & {r["text"] for r in список}), "показанное попало в выдачу"


def test_dva_raznyh_otkaza_ne_putayutsya():
    """«Нет в базе» и «всё показано» — разные ответы (Раунд 57).

    Для пользователя это разные действия: в первом случае заливать источники, во
    втором чистить историю. Пока оба назывались `missing`, подсказка врала в
    половине случаев."""
    def строка(t):
        return {"text": t, "template": "nakedlunch", "meter": None, "rhyme": "ана",
                "rhyme_span": None, "syllables": 8, "score": 0.6, "_lem": {"л"},
                "mat": False, "clausula": 1, "classic": False}

    shortlist = [строка("чужая раз"), строка("чужая два")]

    # слова нет в базе вовсе
    итог = filters._ensure_forced([dict(r) for r in shortlist], {"кит"}, {"кит": []},
                                  "none", 0.0, hidden=set())
    assert итог["кит"] == "missing"

    # слово есть, но всё показано
    канд = [строка("кит показывался")]
    итог = filters._ensure_forced([dict(r) for r in shortlist], {"кит"},
                                  {"кит": [dict(c) for c in канд]},
                                  "none", 0.0, hidden={"кит показывался"})
    assert итог["кит"] == "shown", "«всё показано» выдаётся как «нет в базе»"


def test_osnovnoy_put_ne_vozvrashchaet_pokazannoe():
    """Железное правило проверяется и на ОБЫЧНОМ пути, не только на `!слово`.

    Сторож стоял только на гарантии обязательного слова — то есть на
    единственном месте, где я сама сделала послабление. Основной отбор историю
    вычитает (`_nl_scored`), но своего теста на это не имел. Бьём прямо туда,
    где вычитание живёт, а не через весь каскад: так тест не зависит от
    кэша ударений и остаётся быстрым и честным.
    """
    class Корпус:
        def __init__(self, скрытые): self._h = set(скрытые)
        def hidden_set(self): return set(self._h)
        def blacklist_set(self): return set()

    показано = {f"строка {i}" for i in range(0, 40, 2)}
    пул = [f"строка {i}" for i in range(40)]
    # `light=True` — путь классики: он же самый короткий и историю обязан
    # уважать ровно так же, как алгоритмический.
    # `_nl_scored` отдаёт пару (строки, кандидаты обязательных слов)
    выдача, _ = filters._nl_scored(пул, Корпус(показано), показано, nlindex.Ворота(), light=True)
    тексты = {r["text"] for r in выдача}
    assert тексты, "выдача пуста — тест ничего не проверил"
    assert not (тексты & показано), (
        f"показанное вернулось: {sorted(тексты & показано)[:3]}")
    assert len(тексты) == 20, f"вычли не только показанное: осталось {len(тексты)}"


def test_banalnost_ne_nagrazhdaet_imena():
    """Имя собственное не делает строку «редкой» (Раунд 57).

    Опознаётся МОРФОЛОГИЕЙ, а не заглавной буквой: в отчёте были строки целиком капсом — «ТАМ ДОСТАЛ НОЖ — РЕЖЬ» — и сказал «это не плохо, что оно
    капсом; там главное не имя». По регистру «ТИМОН» от «ЖИЗНЬ» не отличить.
    """
    import corpus as _c
    from wordfreq import zipf_frequency

    # сам разделитель: помета не зависит от регистра
    assert _c.имя_ли("ТИМОН") and _c.имя_ли("тимон") and _c.имя_ли("Дольмансе")
    assert not _c.имя_ли("ЖИЗНЬ") and not _c.имя_ли("НОЖ") and not _c.имя_ли("жизнь")

    def банал(текст):
        пары = _c.lemmatize_pairs(текст)
        леммы = [l for _, l, _ in пары]
        годные = [l for _, l, имя in пары if not имя] or леммы
        return min((zipf_frequency(l, "ru") for l in годные), default=9.0)

    assert банал("я надеюсь на Дольмансе") == банал("я надеюсь на тепло"), (
        "имя собственное всё ещё тянет банальность вниз, то есть даёт бонус")

    # строка целиком капсом — обычный материал, а не «сплошь имена»
    пары = _c.lemmatize_pairs("ТАМ ДОСТАЛ НОЖ РЕЖЬ")
    assert all(not имя for _, _, имя in пары), "капс принят за имена собственные"



def test_reban_menyaet_tolko_dve_grafy():
    """Пересчёт формулы качества не смеет трогать данные (Раунд 57).

    `--reban` существует ровно потому, что перепечка целиком стоит час, а
    формула банальности к ударениям отношения не имеет. Цена ошибки здесь
    высокая: проход переписывает весь кэш на 2.4 млн записей. Значит сторож
    обязан проверить, что меняются РОВНО banal и content, а ключ, ударения,
    span, леммы и токены остаются байт в байт."""
    import importlib.util
    корень = Path(__file__).resolve().parent.parent
    # `_accent` лежит рядом со сборщиком и подхватывается им по имени модуля —
    # мой аудит «осиротевших инструментов» его не увидел именно поэтому: искал
    # упоминание ИМЕНИ ФАЙЛА, а импорт идёт по имени модуля.
    sys.path.insert(0, str(корень / "tools"))
    спец = importlib.util.spec_from_file_location("bnr", корень / "tools" / "build_nl_rhyme.py")
    bnr = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(bnr)

    было = {
        "я надеюсь на Дольмансе": {
            "key": "СЕ", "span": [10, 18], "banal": 0.0, "taut": False,
            "lemmas": ["надеяться", "дольмансе"], "tokens": ["я", "надеюсь", "на", "дольмансе"],
        },
    }
    стало = bnr.reban({k: dict(v) for k, v in было.items()})
    з, с = было["я надеюсь на Дольмансе"], стало["я надеюсь на Дольмансе"]

