# «Разных рифм» в форме пула — корзинами ЯРУСА ТОЧНОСТИ, не целыми ключами
# (2026-08-28, требование: «выбор типа рифмы не отражается на количестве строк
# в показателях»). Отбор сравнивает префиксы ключей (filters._rhyme_prefix_len),
# значит и цифра обязана считаться теми же корзинами: шире ярус — корзин
# меньше и каждая толще.
import sys
from pathlib import Path

import numpy as np
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))
import nlindex  # noqa: E402


class _Стуб:
    """Ровно то, что форма_пула трогает у индекса: ключи, номера, ворота."""

    def __init__(self, keys, key_id):
        self.keys = list(keys)
        self.key_id = np.asarray(key_id, dtype=np.int32)

    def gate_mask(self, *a, **k):
        return np.ones(len(self.key_id), dtype=bool)


def _форма(префикс):
    идх = _Стуб(["ание", "аний", "атый", "ор"], [0, 0, 1, 2, 3])
    n = len(идх.key_id)
    return nlindex.форма_пула(
        идх, pool_mask=np.ones(n, dtype=bool), hidden_mask=np.zeros(n, dtype=bool),
        рифма_префикс=префикс)


def test_точная_считает_целыми_ключами():
    ф = _форма(None)
    assert ф["строк"] == 5
    assert ф["ключей"] == 4              # ание·аний·атый·ор — все разные
    assert ф["крупнейшая_корзина"] == 2  # «ание» стоит у двух строк


def test_ярусы_сливают_корзины():
    """близкая (3 знака): ание+аний — одна корзина; ассонанс (1 знак): к ним
    приливает и атый — считается только ударная гласная."""
    близкая = _форма(3)
    assert (близкая["ключей"], близкая["крупнейшая_корзина"]) == (3, 3)
    ассонанс = _форма(1)
    assert (ассонанс["ключей"], ассонанс["крупнейшая_корзина"]) == (2, 4)
    # строк ярус не отсеивает — он про пары, не про ворота
    assert близкая["строк"] == ассонанс["строк"] == 5


# НА СКОЛЬКО СТРОФ ХВАТИТ (2026-08-31, требование: «пусть говорит заранее
# и рекомендует увеличить количество источников»).
#
# Повод — замер: ворота переклички оставляют 6 980 строк, а в катрен 8-9 слогов
# из них влезают 58. Человек, глядя на число ворот, ждёт вечера работы, а
# упирается в «строки кончились» на пятнадцатом нажатии — и упирается насовсем
# на 180 дней, потому что показанное не возвращается.

def test_запас_считается_по_вилке_формы_а_не_по_воротам():
    """Число ворот и запас формы — разные вещи, и в узких настройках они
    расходятся на порядки. Сторож требует, чтобы запас считался по СЛОГАМ."""
    idx = nlindex.load()
    if idx is None or getattr(idx, "syl", None) is None:
        pytest.skip("нет живого индекса")
    пул = np.ones(idx.n, dtype=bool)
    нет = np.zeros(idx.n, dtype=bool)

    без = nlindex.форма_пула(idx, pool_mask=пул, hidden_mask=нет)
    assert "хватит_строф" not in без, "без формы запас считать не из чего"

    узко = nlindex.форма_пула(idx, pool_mask=пул, hidden_mask=нет,
                              вилки=[(8, 9)] * 4)
    широко = nlindex.форма_пула(idx, pool_mask=пул, hidden_mask=нет,
                                вилки=[(4, 20)] * 4)
    assert узко["строк_в_строфе"] == 4
    assert узко["под_форму"] < узко["строк"], "вилка обязана сужать"
    assert узко["хватит_строф"] == узко["под_форму"] // 4
    assert широко["под_форму"] > узко["под_форму"] * 3, \
        "широкая вилка обязана давать заметно больший запас"


def test_запас_падает_вместе_с_воротами():
    """Ворота звукописи режут запас на порядки — именно это число и должно
    доходить до экрана, иначе предупреждать не о чем."""
    idx = nlindex.load()
    if idx is None or getattr(idx, "echo", None) is None:
        pytest.skip("нет живого индекса с колонкой echo")
    пул = np.ones(idx.n, dtype=bool)
    нет = np.zeros(idx.n, dtype=bool)
    вилки = [(8, 9)] * 4
    обычно = nlindex.форма_пула(idx, pool_mask=пул, hidden_mask=нет, вилки=вилки)
    с_воротами = nlindex.форма_пула(idx, pool_mask=пул, hidden_mask=нет,
                                    вилки=вилки, перекличка=1)
    assert с_воротами["хватит_строф"] < обычно["хватит_строф"] / 100, \
        (с_воротами["хватит_строф"], обычно["хватит_строф"])
