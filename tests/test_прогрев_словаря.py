# nakedlunch — СЛОВАРЬ УДАРЕНИЙ НЕ ПОДНИМАЕТСЯ НА ИМПОРТЕ (2026-08-18).
#
# ЧТО БЫЛО. `api/server.py` звал `wordsuggest.warm_caches()` на уровне модуля.
# Перемерено на этой машине (.venv, три прогона подряд, `ru_maxrss`):
#
#   импорт api/server.py со строкой прогрева   5.76 / 5.75 / 5.67 с,  2456 МБ
#   он же без неё                              3.02 / 2.96 / 2.95 с,  1907 МБ
#   разница                                    **2.75 с и 549 МБ**
#
#   сам `warm_caches()` отдельным процессом:   **2.28 с**, RSS 40.6 → 792.2 МБ
#
# Платил это КАЖДЫЙ, кто просто импортировал файл, — в том числе прогон
# тестов. Ради попапа по слову, экран которого вырезан 2026-08-18:
# `methods.слово.js` удалён целиком, во фронте от него осталась одна обёртка с
# надгробием, вызывающих у неё нет.
#
# ЧТО СТОРОЖИТ ЭТОТ ФАЙЛ — три свойства, и все три проверяются ИСХОДОМ, а не
# чтением кода:
#   1. импорт `server` в отдельном процессе словарь не поднимает;
#   2. отказ 400 (нет слова, чужая вкладка) за словарь не платит;
#   3. настоящий запрос словарь поднимает САМ и отвечает по делу.
#
# Третий здесь не «ещё один тест», а КОНТРОЛЬ к первым двум: без него «словарь
# не поднят» было бы зелено и на доме, где словаря вовсе нет на диске.
#
# ПОЧЕМУ ОТДЕЛЬНЫМ ПРОЦЕССОМ. Проверяется свойство САМОГО ИМПОРТА, а в общем
# прогоне `server` уже импортирован соседними файлами — здесь он не исполнил
# бы ни строки заново. Тот же приём, что в test_история_перепривязка.py.
#
# Прогон: .venv/bin/python -m pytest tests/test_прогрев_словаря.py -q

import os
import subprocess
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
СЛОВАРЬ = КОРЕНЬ / "core" / "data" / "rhyme_index.json"

нет_словаря = pytest.mark.skipif(
    not СЛОВАРЬ.exists(),
    reason="нет core/data/rhyme_index.json — собери tools/build_rhyme_index.py")


# Всё в ОДНОМ дочернем процессе: он один и стоит (импорт с заглушками ~0.6 с,
# подъём словаря 2.3 с). Три отдельных ребёнка платили бы это трижды ради тех
# же трёх чисел.
_СЦЕНАРИЙ = """
import sys, time
sys.path.insert(0, {core!r})
sys.path.insert(0, {api!r})
# Заглушаем ЧУЖИЕ тяжёлые прогревы (навек — 1.6 ГБ, кэш рифм — до 5.5 ГБ), но
# НЕ `wordsuggest`: он и есть предмет проверки.
import embeddings, filters, generate
for м in (embeddings, filters, generate):
    м.warm_caches = lambda: None
import wordsuggest

т0 = time.time()
import server
print("СЕКУНД_ИМПОРТА", round(time.time() - т0, 3))
print("СЛОВ_ПОСЛЕ_ИМПОРТА", len(wordsuggest._WORDS))

к = server.app.test_client()

о = к.post("/api/word/suggest", json={{"tab": "рифмы"}})
print("КОД_БЕЗ_СЛОВА", о.status_code)
о = к.post("/api/word/suggest", json={{"word": "вода", "tab": "чудеса"}})
print("КОД_ЧУЖАЯ_ВКЛАДКА", о.status_code)
print("СЛОВ_ПОСЛЕ_ОТКАЗОВ", len(wordsuggest._WORDS))

т0 = time.time()
о = к.post("/api/word/suggest", json={{"word": "вода", "tab": "рифмы", "line": ""}})
print("СЕКУНД_ПЕРВОГО_ЗАПРОСА", round(time.time() - т0, 3))
print("КОД_ПО_ДЕЛУ", о.status_code)
print("НАШЛОСЬ", len((о.get_json() or {{}}).get("items") or []))
print("СЛОВ_ПОСЛЕ_РОУТА", len(wordsuggest._WORDS))

т0 = time.time()
к.post("/api/word/suggest", json={{"word": "мороз", "tab": "рифмы", "line": ""}})
print("СЕКУНД_ВТОРОГО_ЗАПРОСА", round(time.time() - т0, 3))
"""


@pytest.fixture(scope="module")
def замер(tmp_path_factory):
    дом = tmp_path_factory.mktemp("дом-словаря")
    код = _СЦЕНАРИЙ.format(core=str(КОРЕНЬ / "core"), api=str(КОРЕНЬ / "api"))
    р = subprocess.run(
        [sys.executable, "-c", код],
        env={**os.environ, "NAKEDLUNCH_HOME": str(дом), "PYTHONIOENCODING": "utf-8"},
        cwd=str(КОРЕНЬ), capture_output=True, text=True, timeout=600)
    assert р.returncode == 0, f"дочерний процесс упал:\n{р.stdout}\n{р.stderr}"
    итог = {}
    for строка in р.stdout.splitlines():
        части = строка.split()
        if len(части) == 2 and части[0].isupper():
            итог[части[0]] = float(части[1])
    return итог


def test_импорт_ne_podnimaet_slovar(замер):
    """ГЛАВНЫЙ. Импорт файла не имеет права стоить 2.28 с и 751 МБ тому, кто
    его всего лишь прочитал."""
    assert замер["СЛОВ_ПОСЛЕ_ИМПОРТА"] == 0, (
        "`import server` поднял словарь ударений — значит `wordsuggest."
        "warm_caches()` снова стоит на уровне модуля. Это 2.28 с и 751 МБ на "
        "каждый импорт, включая прогон тестов, ради роута, у которого во "
        "фронте ноль вызывающих. Место прогрева — `_прогреть_словарь()` по "
        "первому обращению к роуту.")


def test_otkaz_400_ne_platit_za_slovar(замер):
    """Валидация идёт ДО прогрева. Иначе кривой запрос стоил бы столько же,
    сколько настоящий."""
    assert замер["КОД_БЕЗ_СЛОВА"] == 400
    assert замер["КОД_ЧУЖАЯ_ВКЛАДКА"] == 400
    assert замер["СЛОВ_ПОСЛЕ_ОТКАЗОВ"] == 0, (
        "отказ 400 поднял словарь на 751 МБ — `_прогреть_словарь()` стоит "
        "выше проверок входа")


@нет_словаря
def test_rout_gret_slovar_sam(замер):
    """КОНТРОЛЬ К ДВУМ ПРЕДЫДУЩИМ. Без него они зеленели бы и на доме, где
    словаря нет вовсе: `wordsuggest.suggest` на пустом словаре не падает и не
    жалуется — он честно отдаёт [] по всем пяти вкладкам, то есть 200 и
    пустоту.

    Значит доказывать надо ОБА конца: до запроса словаря нет, после — есть, и
    ответ не пустой."""
    assert замер["КОД_ПО_ДЕЛУ"] == 200
    assert замер["НАШЛОСЬ"] > 0, (
        "роут ответил 200 и пустотой — значит словарь так и не поднялся, "
        "а два сторожа выше стерегут пустое место")
    assert замер["СЛОВ_ПОСЛЕ_РОУТА"] > 100_000, (
        f"после запроса в словаре {замер['СЛОВ_ПОСЛЕ_РОУТА']:.0f} слов — "
        "боевой rhyme_index.json держит 660 169")


@нет_словаря
def test_gret_odin_raz_za_process(замер):
    """Второй запрос платить не должен: разбор 68.8 МБ на каждый клик — это
    хуже, чем прогрев на старте, а не лучше.

    Порог грубый нарочно (в десять раз): числа на разных машинах разные, а
    проверяется здесь не скорость, а то, что работа не делается заново."""
    первый, второй = замер["СЕКУНД_ПЕРВОГО_ЗАПРОСА"], замер["СЕКУНД_ВТОРОГО_ЗАПРОСА"]
    assert второй * 10 < первый, (
        f"первый запрос {первый:.2f} с, второй {второй:.2f} с — словарь "
        "разбирается заново на каждом обращении (потерян флаг в "
        "`_прогреть_словарь`)")
