@нет_индекса
def test_колоночный_путь_тоже_повторяется():
    """Отдельно от старого: 100% воспроизводимость появилась именно тогда, когда
    семя дошло до `nlindex.select`, и проверять это надо на настоящем индексе."""
    пул = [ИНДЕКС.text(i) for i in range(0, ИНДЕКС.n, max(1, ИНДЕКС.n // 20_000))]
    knobs = clean.knobs({"shortlist": 8, "real_text": 1.0})

