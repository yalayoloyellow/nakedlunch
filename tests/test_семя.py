# ── сторож на роут, который тестами не зовётся ───────────────────────────────

def test_роут_зовёт_существующие_имена():
    """api/server.py тестами не импортируется (подъём корпуса — 69 секунд и
    правка настоящей истории), и именно там уже умирала вся генерация: роут
    читал ключ воронки, которого больше не было. Здесь проверяется дёшево и
    статически: всё, что роут зовёт по имени из clean и filters, существует.

    Разбор через `ast`, а не регуляркой: первая версия искала по тексту и
    спотыкалась о `core/filters.py` в комментарии — требовала атрибут `py`.
    Дерево видит только настоящие обращения."""
    дерево = ast.parse((КОРЕНЬ / "api" / "server.py").read_text("utf-8"))
    # nlindex добавлен в сторожа вместе с роутом формы пула (Раунд 62): роут
    # зовёт `nlindex.форма_пула`, и опечатка в имени умерла бы так же тихо, как
    # умирал `funnel["gen"]["used"]` — то есть 500-й после сборки выдачи.
    модули = {"clean": clean, "filters": filters, "nlindex": nlindex}
    найдено = 0
    for узел in ast.walk(дерево):
        if (isinstance(узел, ast.Attribute) and isinstance(узел.value, ast.Name)
                and узел.value.id in модули):
            найдено += 1
            assert hasattr(модули[узел.value.id], узел.attr), \
                f"api/server.py зовёт {узел.value.id}.{узел.attr}, которого нет"
    assert найдено > 10, "разбор ничего не нашёл — сторож спит, а не сторожит"


def test_modul_gruzitsya_bez_pomoshchi_testov():
    """СТОРОЖ НА СЛЕПОЕ ПЯТНО ВСЕГО НАБОРА (2026-08-18).

    `conftest.py` автоматическим приспособлением зовёт `filters.закрепить_разброс`
    перед КАЖДЫМ тестом, а та делает `global _РАЗБРОС_СЕМЯ` и тем самым СОЗДАЁТ
    имя. Значит любой модульный уровень, потерянный при правке, в прогоне тестов
    останется невидимым: приспособление подставит его за код.

    Так и вышло: откат правки снёс объявление `_РАЗБРОС_СЕМЯ = None`, 447 тестов
    остались зелёными, а живое приложение отдавало 500 на КАЖДУЮ генерацию —
    `NameError` в первой же строке разбора запроса.

    Здесь модуль поднимается ОТДЕЛЬНЫМ ПРОЦЕССОМ и дёргается ровно тем путём,
    которым его дёргает роут, — без единого приспособления. Проверяется исход
    (семя выдалось), а не наличие имени: имя можно объявить и не использовать."""
    import subprocess
    код = (
        "import sys; sys.path.insert(0, %r)\n"
        "import filters\n"
        "a = filters.семя_прогона(None)\n"
        "b = filters.семя_прогона(777)\n"
        "assert isinstance(a, int) and 0 <= a < (1 << 30), a\n"
        "assert b == 777, b\n"
        "print('ok')\n"
    ) % str(КОРЕНЬ / "core")
    p = subprocess.run([sys.executable, "-c", код], capture_output=True, timeout=120)
    ошибки = (p.stderr or b"").decode("utf-8", "replace")
    assert p.returncode == 0, f"модуль не работает без приспособлений тестов:\n{ошибки}"
