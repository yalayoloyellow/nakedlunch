# nakedlunch — СЕМЯ ОДНО НА ПРОГОН (Раунд 62).
#
# Требование: «раз уж я выбираю настройку, я должен выбирать конкретный
# результат, и он должен воспроизводиться в точности».
#
# ЧТО БЫЛО ЗАМЕРЕНО ДО ПРАВКИ (2026-08-13, полный индекс 2 434 632, схема
# абаб, 8 строк): два ОДИНАКОВЫХ вызова подряд совпадали на 0.0% по местам и
# на 0.0% по составу. Путей случайности оказалось ЧЕТЫРЕ, а не три, как было
# записано в плане:
#   1. пять `random.shuffle` на глобальном модуле в filters;
#   2. `filters._мешок` — разведение равных в _select_with_rhyme;
#   3. `np.random.default_rng` внутри nlindex.select / select_light;
#   4. грамматический генератор `generate.generate(seed=None)` — и его зовёт
#      НЕ filters, а вызывающий, раньше filters.run.
# Закрепление по одному: только 1+2 → 0.0% по местам, 12.5% по составу; плюс
# третий → 100%. Четвёртый живёт снаружи, поэтому семя выбирается в
# api/server.py и передаётся в оба конвейера.
#
# ИЗ ЧЕТЫРЁХ ПУТЕЙ ОСТАЛСЯ ОДИН (2026-08-29). Сборщик `_select_with_rhyme` с
# его `_мешок` вырезан, грамматический генератор вырезан вместе с файлом
# core/generate.py. Вся случайность прогона теперь живёт в третьем — в
# `np.random.default_rng(семя)` внутри `nlindex.select`, откуда её берёт прямая
# тяга (`nlindex.тянуть_строфы`). Требование от этого не изменилось ни на
# букву, поэтому и сторожа остались все: изменилось только МЕСТО, где они
# стоят.
#
# ПРОГОНЫ ПЕРЕВЕДЕНЫ НА ПРЯМУЮ ТЯГУ (2026-08-29). Раньше они шли по
# безиндексному пути: фикстура подменяла кэш ударений синтетическим словарём и
# гасила `filters._index_for_current_cache`. Тот путь жив (так работает
# установка до первой выпечки индекса), но живой работы на нём не бывает — а семя
# ему нужно там, где он живёт. Теперь пул берётся из НАСТОЯЩЕГО индекса и
# передаётся строфа, то есть `filters._run` уходит в `_прямая_тяга` — ровно то,
# что делает `POST /api/generate` в окне. Синтетика на четырёх однородных
# строках сошлась бы к одному ответу и при полностью сломанном семени.
#
# ЧЕГО ЗДЕСЬ НЕТ И УЖЕ НЕ БУДЕТ. Цепь (core/pipeline.py) семенем сознательно
# не покрывалась: у неё звеньев несколько, и одно семя на всю цепь сделало бы
# звенья эхом друг друга. Работа отложилась навсегда — цепь вырезана
# 2026-08-18 (29 её прогонов против 587 одиночных строф за 10 живых дней).
#
# Прогон: .venv/bin/python -m pytest tests/test_семя.py -q

import ast
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "core"))

import clean
import filters
import nlindex
from corpus import Corpus

ИНДЕКС = nlindex.load()
нет_индекса = pytest.mark.skipif(ИНДЕКС is None,
                                 reason="индекс не испечён (tools/build_nl_index.py)")

# ПУЛ — настоящие строки корпуса, прорежённые ровным шагом до ~20 тысяч. Не
# весь корпус: маска пула строится по текстам, и два с лишним миллиона строк
# стоили бы минуты на каждый прогон, ничего не добавляя. Не горстка синтетики:
# на однородных строках любой отбор сходится к одному ответу сам, и сторож
# зеленел бы при полностью сломанном семени.
ПУЛ = ([ИНДЕКС.text(i) for i in range(0, ИНДЕКС.n, max(1, ИНДЕКС.n // 20_000))]
       if ИНДЕКС is not None else [])

# Строфа — через `clean.stanza_spec`, а не руками: так тест берёт ровно ту
# форму, что доезжает до `filters.run` из окна, и слоговая вилка включает
# ПРЯМУЮ ТЯГУ (`filters._прямая_тяга` требует индекс, вилку и схему).
СТРОФА = clean.stanza_spec([{"letter": б, "min_syl": 5, "max_syl": 11}
                            for б in "абаб"])
СХЕМА = clean.stanza_letters(СТРОФА)

# Тексты для сторожей БУХГАЛТЕРИИ истории (`тексты_прогона`): им корпус не
# нужен вовсе — они про то, что запомнил `Corpus`, а не про то, что выбрал
# отбор. Поэтому индекса не требуют и работают на чистом клоне.
СЛЕД = [f"строка номер {i} про воду и камень" for i in range(8)]


def прогон(семя, *, размер=8, корпус=None, схема=СХЕМА, строфа=СТРОФА):
    """Ровно то, что делает `POST /api/generate`: прямая тяга по колонкам."""
    knobs = clean.knobs({"shortlist": размер})
    итог = filters.run([], knobs, корпус if корпус is not None else Corpus(),
                       nl_fragments=ПУЛ, rhyme=схема, stanza=строфа, семя=семя)
    return [r["text"] for r in итог["shortlist"]], итог["seed"]


# ── что принимается за номер прогона ─────────────────────────────────────────

def test_номер_из_запроса_разбирается():
    assert clean.семя(12) == 12
    assert clean.семя("12") == 12
    assert clean.семя(12.0) == 12                 # JSON шлёт числа числами
    assert clean.семя(-1) == (1 << 30) - 1        # в диапазон, а не в отказ
    assert clean.семя((1 << 30) + 5) == 5


def test_мусор_это_новый_прогон_а_не_отказ():
    """Испорченный номер не должен ронять самое частое действие приложения."""
    for мусор in (None, "", "абв", {}, [], float("nan")):
        assert clean.семя(мусор) is None
    # True в Python — это 1; без отдельной проверки `{"seed": true}` молча
    # стал бы прогоном номер один
    assert clean.семя(True) is None and clean.семя(False) is None


