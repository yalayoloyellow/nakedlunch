def test_povtor_perezhivaet_istoriyu(словарь):
    """ТОТ САМЫЙ СЛУЧАЙ, НА КОТОРОМ ВСЁ ЛОМАЛОСЬ ЖИВЬЁМ.

    Прогон кладёт свои строки в историю, история вычитается из пула — и тот же
    номер сразу после прогона давал СЛЕДУЮЩИЕ строки, а не те же. Поймано не
    рассуждением, а в интерфейсе: счётчик истории 4 → 8, выдача другая.

    Разрешение (corpus.тексты_прогона): собственный след прогона от него самого
    не прячется. Здесь проверяется и это, и что инвариант при этом цел —
    ОБЫЧНАЯ генерация показанное не возвращает."""
    корпус = Corpus()
    knobs = clean.knobs({"shortlist": 8, "real_text": 1.0})

    def прогнать(семя):
        итог = filters.run([], knobs, корпус, nl_fragments=list(ФРАГМЕНТЫ),
                           rhyme="абаб", семя=семя)
        return [r["text"] for r in итог["shortlist"]], итог["seed"]["seed"]

    filters.закрепить_разброс(None)
    try:
        первый, номер = прогнать(None)
        assert len(первый) == 8
        # ровно то, что делает интерфейс в момент показа
        корпус.mark_shown([{"text": t, "template": "nakedlunch"} for t in первый],
                          семя=номер)
        assert len(корпус.hidden_set()) == 8, "история не записалась — тест ни о чём"

        повтор, номер2 = прогнать(номер)
        assert номер2 == номер
        assert повтор == первый, "номер не вернул свой же прогон"

        # инвариант цел: без номера показанное не возвращается
        свежий, _ = прогнать(None)
        assert not (set(свежий) & set(первый)), "показанное вернулось в обычную выдачу"
    finally:
        filters.закрепить_разброс(20260806)


def test_chuzhoy_nomer_ne_otkryvaet_istoriyu(словарь):
    """Открывается ТОЛЬКО свой след. Иначе любой номер работал бы отмычкой ко
    всей истории, и инвариант держался бы на честном слове."""
    корпус = Corpus()
    корпус.mark_shown([{"text": t, "template": "nakedlunch"} for t in list(ФРАГМЕНТЫ)[:8]],
                      семя=111)
    assert корпус.тексты_прогона(111) == set(list(ФРАГМЕНТЫ)[:8])
    assert корпус.тексты_прогона(222) == set()
    assert корпус.тексты_прогона(None) == set()


def test_izbrannoe_iz_svoego_progona_tozhe_vozvrashchaetsya(словарь):
    """Строку из прогона потом добавили в избранное — повтор обязан её вернуть.
    Избранное прячет от НОВОЙ выдачи, а не от собственного прогона строки."""
    корпус = Corpus()
    строки = list(ФРАГМЕНТЫ)[:4]
    корпус.mark_shown([{"text": t, "template": "nakedlunch"} for t in строки], семя=333)
