# Фрагментов НАРОЧНО много и они однородны: на четырёх строках любой отбор
# сойдётся к одному ответу сам, и тест был бы зелёным при полностью сломанном
# семени. Здесь выбор реально есть, и без семени два прогона расходятся.
ФРАГМЕНТЫ = {f"строка номер {i} про воду и камень": "ень" if i % 2 else "оду"
             for i in range(120)}


@pytest.fixture()
def словарь(monkeypatch):
    fake = {t: {"banal": 3.0, "taut": False, "lemmas": lemmatize(t),
                "tokens": list(nlbridge._tokens(t)), "key": key, "span": None}
            for t, key in ФРАГМЕНТЫ.items()}
    monkeypatch.setattr(filters, "_NL_RHYME", fake)
    # Старый путь НАРОЧНО: колоночный проверяется отдельно и только там, где
    # индекс есть. Смешивать их в одном тесте значило бы не знать, какой из
    # двух он на самом деле проверил.
    monkeypatch.setattr(filters, "_index_for_current_cache", lambda *a, **k: None)
    return fake


def прогон(семя, *, размер=8, схема="абаб"):
    knobs = clean.knobs({"shortlist": размер, "real_text": 1.0})
    итог = filters.run([], knobs, Corpus(), nl_fragments=list(ФРАГМЕНТЫ),
                       rhyme=схема, семя=семя)
    return [r["text"] for r in итог["shortlist"]], итог["seed"]


# ── что принимается за номер прогона ─────────────────────────────────────────

def test_номер_из_запроса_разбирается():
    assert clean.семя(12) == 12
    assert clean.семя("12") == 12
    assert clean.семя(12.0) == 12                 # JSON шлёт числа числами
    assert clean.семя(-1) == (1 << 30) - 1        # в диапазон, а не в отказ
    assert clean.семя((1 << 30) + 5) == 5


def test_мусор_это_новый_прогон_а_не_отказ():
    """Испорченный номер не должен ронять самое частое действие приложения."""
    for мусор in (None, "", "абв", {}, [], float("nan")):
        assert clean.семя(мусор) is None
    # True в Python — это 1; без отдельной проверки `{"seed": true}` молча
    # стал бы прогоном номер один
    assert clean.семя(True) is None and clean.семя(False) is None


