# ЗВУКОПИСЬ: перекличка согласных и плотность (2026-08-30).
#
# Слово владельца: «не только гласные, но и согласные могут иметь
# художественный эффект. То есть если там нету рифмы, но они все имеют
# сочетание звуковое ТРСК и прочие разные, любые… это тоже работает».
#
# Каждый сторож здесь стоит против конкретного шума, который лез наверх на
# живых замерах, — а не против воображаемого. Строки в пробах взяты из тех
# самых замеров.
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))
import звукопись as з  # noqa: E402


def фон_из(строки, повторы=400):
    """Фон, где кластеры проб редки, а суффиксы языка часты.

    Повторяем «языковой» кусок, чтобы у его сочетаний была та частота, какая
    бывает у морфем: порог редкости меряет ДОЛЮ слов корпуса."""
    корпус = list(строки) + ["действительно средство государство"] * повторы
    return з.частоты_кластеров(корпус)


def test_редкое_сочетание_согласных_считается_перекличкой():
    фон = фон_из(["испытал головокружение и чуть не споткнулся"])
    assert з.перекличка("испытал головокружение и чуть не споткнулся", фон) == 1


def test_общая_морфема_перекличкой_не_считается():
    """Общий буквенный кусок в четыре знака — корень, а не звук.

    Пары взяты с верхушки живого замера, где правила морфемы ещё не было:
    «окончательно… покончим» (конч), «в принципе воспринимаешь» (прин),
    «пятнадцатого, шестнадцатого» (надцатого)."""
    for пара in ("окончательно покончим", "принципе воспринимаешь",
                 "пятнадцатого шестнадцатого"):
        assert з.перекличка(пара, фон_из([пара])) == 0, пара


def test_суффикс_языка_не_редкость():
    # «дств» в «производством/предоставлением» встречается в корпусе часто —
    # порог редкости обязан его отбросить, хотя кусок длинный.
    фон = фон_из(["производством и предоставлением информации"])
    assert з.перекличка("производством и предоставлением информации", фон) == 0


def test_общее_окончание_это_грамматика_а_не_звук():
    """Кластер, стоящий В КОНЦЕ у обоих слов, — падеж, а не перекличка.

    Правило живо само по себе, а не поглощено правилом морфемы: на живом
    прогоне 60 000 строк оно отбивает 61 пару из 1964, до которых морфема не
    дотягивается, — «многосторонних жизненных» (ннх), «морщинистым усатым»
    (стм). Общих четырёх букв у таких пар нет, общее у них — окончание."""
    for пара in ("многосторонних жизненных", "морщинистым усатым"):
        assert з.перекличка(пара, фон_из([пара])) == 0, пара


def test_балл_не_измеритель_длины():
    """Одно совпадение в длинной строке стоит МЕНЬШЕ, чем в короткой.

    Ровно этим сюрприз отличается от голого счёта пар, на котором наверх
    лезли длинные книжные периоды (разброс по длине 70 раз)."""
    фон = {"счёт": {}, "слов": 1000, "доля_пар": 0.0004}
    коротко = з.сюрприз(1, 4, фон["доля_пар"])
    длинно = з.сюрприз(1, 20, фон["доля_пар"])
    assert коротко > длинно > 0


def test_балл_не_измеритель_короткости():
    """Два совпадения весомее одного при той же длине — иначе балл мерил бы
    не звук, а обрывочность строки (ловушка z-балла)."""
    доля = 0.0004
    assert з.сюрприз(2, 8, доля) > з.сюрприз(1, 8, доля) > 0


def test_плотность_требует_трёх_разных_слов():
    """Согласный в ДВУХ словах — ещё не заливка.

    Без этого требования одна редкая буква в короткой строке даёт z≈4-7, и
    наверх лезет «в вифсфагию к горе елеонстей»."""
    assert з.плотность("цирк царь дом") == 0.0     # «ц» и «р» в двух словах из трёх
    залито = з.плотность("шуршит шёлковый шёпот шалый")
    assert залито > 0


def test_короткая_строка_без_шкалы_плотности():
    assert з.плотность("да нет") == float(з.НЕТ_ШКАЛЫ)


def test_шкалы_дают_ровные_полосы_и_метку_без_шкалы():
    строки = [f"слово{i} строка{i} проба{i} текст{i}" for i in range(200)]
    строки += ["да", "нет"]           # у этих шкалы нет: короче трёх слов
    фон = з.частоты_кластеров(строки)
    пер, пло = з.шкалы(строки, фон)
    assert len(пер) == len(пло) == len(строки)
    assert (пло < 0).sum() == 2
    # процентиль ровный: в любые десять процентов попадает десятая часть
    имеющие = пло[пло >= 0]
    в_полосе = ((имеющие >= 40) & (имеющие < 50)).sum()
    assert abs(в_полосе - len(имеющие) / 10) <= 2


def test_ожидание_кладётся_в_фон():
    """Сюрприз считать не от чего, пока неизвестна доля перекликающихся пар
    корпуса. Печка обязана оставить её в фоне — тем же числом меряет прогон."""
    строки = ["испытал головокружение и чуть не споткнулся",
              "в коридоре продребезжал звонок",
              "обычная строка без всякого звука вовсе"]
    фон = фон_из(строки)
    з.шкалы(строки, фон)
    assert 0.0 <= фон["доля_пар"] <= 1.0
