# 2. ТОЖДЕСТВО. Ускорение принимается только как то же самое, а не как «почти».

@нет_индекса
def test_maska_iz_kuskov_ta_zhe_chto_pri_chestnom_pereschyote(чистый_кэш):
    """Маска, собранная из кэшированных кусков, обязана быть ПОБИТОВО той же,
    что честный пересчёт всех правил с нуля.

    Это и есть цена вопроса: кэш на правило выигрывает секунды ровно до тех
    пор, пока он отдаёт то же самое. Сверяем и после добавления, и после
    удаления — состояния кэша там разные."""
    idx = nlindex.load()
    правила = _правила(idx, 12)

    def честно(список):
        nlindex.забыть_запрет()
        nlindex._ПРАВИЛО_КЭШ.clear()        # ни одного готового куска
        з = nlindex.запрет(список)
        return з["маска"].copy(), dict(з["счёт"])

    # состояние «пользователь добавил правило к посчитанному списку»
    nlindex.забыть_запрет()
    nlindex._ПРАВИЛО_КЭШ.clear()
    nlindex.запрет(правила[:11])
    nlindex.забыть_запрет()
    з = nlindex.запрет(правила)
    из_кусков, счёт_кусков = з["маска"].copy(), dict(з["счёт"])
    эталон, счёт_эталон = честно(правила)
    assert np.array_equal(из_кусков, эталон), "маска после добавления разошлась с пересчётом"
    assert счёт_кусков == счёт_эталон, "счётчик после добавления разошёлся с пересчётом"
    assert эталон.any(), "правила не запретили ни одной строки — проверять нечего"

    # состояние «пользователь убрал правило из середины»
    #
    # УБИРАЕМ ТО, ЧТО ПРАВДА ЧТО-ТО ДЕРЖИТ (починка 2026-08-18). Здесь стояло
    # «убрать пятое» — допущение, что пятое правило запрещает хоть одну строку
    # в одиночку. Правила берутся из корпуса, и после перепечки корпуса они
    # стали ПЕРЕКРЫВАТЬСЯ: строки пятого запрещались и другими, счётчик после
    # удаления не менялся, и контрольная проверка падала — при полностью
    # исправном кэше. Тест сторожил не то, что думал.
    #
    # Теперь правило для удаления ВЫЧИСЛЯЕТСЯ: берём то, у которого есть хоть
    # одна собственная строка. Нет такого — сравнивать нечего, и честнее
    # сказать это вслух, чем проверить совпадение двух одинаковых чисел.
    полная, _ = честно(правила)
    свои = -1
    for i in range(len(правила)):
        без_него, _ = честно(правила[:i] + правила[i + 1:])
        if int(без_него.sum()) < int(полная.sum()):
            свои = i
            break
    if свои < 0:
        pytest.skip("на этом корпусе все правила перекрываются — отпускать нечего")

    без_него_список = правила[:свои] + правила[свои + 1:]
    nlindex.забыть_запрет()
    з = nlindex.запрет(без_него_список)
    из_кусков, счёт_кусков = з["маска"].copy(), dict(з["счёт"])
    эталон, счёт_эталон = честно(без_него_список)
    assert np.array_equal(из_кусков, эталон), "маска после удаления разошлась с пересчётом"
    assert счёт_кусков == счёт_эталон, "счётчик после удаления разошёлся с пересчётом"
    # удаление обязано ОТПУСТИТЬ строки, иначе сверху проверялось бы совпадение
    # двух одинаково неверных масок
    assert int(эталон.sum()) < int(полная.sum()), "убранное правило продолжает запрещать"


@нет_индекса
def test_pechyonaya_karta_form_sovpadaet_s_razborom(чистый_кэш):
    """Начальные формы, поднятые с диска, обязаны совпадать с разбором.

    Печёная карта — единственное место, где ответ берётся не из pymorphy, а из
    файла. Ошибись здесь порядком, кодировкой или смещением на единицу — чёрный
    список начнёт ловить чужие слова, и ни один другой тест этого не заметит:
    выдача останется правдоподобной.

    ЧТО ИМЕННО СВЕРЯЕТСЯ, СКАЗАНО ПРЯМО: 2 000 словоформ, а не все 231 837.
    Полная сверка — это тот самый разбор на 15 секунд, который здесь и убран, и
    платить его на каждом прогоне ради того же ответа незачем. Выборка взята не
    случайной горстью, а РОВНЫМ ШАГОМ по всему словарю плюс оба края: смещение,
    перестановка и обрыв — ошибки не точечные, они видны на любом шаге.
    """
    idx = nlindex.load()
    from corpus import _morph
    морф = _morph()

    nlindex._карта_форм(idx)                      # карта в памяти, памятка при ней
    памятка = nlindex._ФОРМЫ_КЭШ[2]
    карта = nlindex._карта_форм(idx)

    шаг = max(1, len(idx.tokens) // 2000)
    номера = list(range(0, len(idx.tokens), шаг))
    номера += [0, len(idx.tokens) - 1]             # края отдельно: там ломается чаще
    for i in номера:
        слово = idx.tokens[i]
        try:
            нф = морф.parse(слово)[0].normal_form
        except Exception:
            нф = слово
        assert памятка[слово] == нф, (
            f"словоформа №{i} «{слово}»: в печёной карте «{памятка[слово]}», "
            f"разбор даёт «{нф}»")
        # и номер словоформы стоит там, где ему положено, — иначе правило по
        # начальной форме соберёт постинги чужих слов
        assert i in карта.get(нф, ()), f"словоформа №{i} «{слово}» потеряна в карте"


