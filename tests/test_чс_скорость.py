@нет_индекса
def test_dobavlenie_pravila_ne_pereschityvaet_spisok(чистый_кэш):
    """Добавить двадцатое правило к девятнадцати.

    Замер: 9.3 с до, 0.12 с после. Порог 2 с — прежнее поведение начиналось от
    2.6 с уже на четырёх правилах, так что возврат виден наверняка."""
    idx = nlindex.load()
    правила = _правила(idx, 20)
    nlindex.запрет(правила[:19])            # список пользователя уже посчитан

    nlindex.забыть_запрет()                 # ровно это делает api/server.py на правке
    t = time.perf_counter()
    з = nlindex.запрет(правила)
    прошло = time.perf_counter() - t

    assert len(з["счёт"]) == 20
    assert прошло < 2.0, (
        f"добавление одного правила к девятнадцати заняло {прошло:.1f}с — "
        f"список считается заново целиком")


@нет_индекса
def test_tsena_pravki_ne_rastyot_vmeste_so_spiskom(чистый_кэш):
    """ОДНО И ТО ЖЕ правило, добавленное к четырём и к девятнадцати, обязано
    стоить одинаково.

    Порог в секундах этого не ловит и ловить не может: после того как разбор
    ушёл в памятку, даже полный пересчёт двадцати правил укладывается в 0.4 с —
    интерфейс не мёрзнет, а цена правки всё равно растёт со списком, и на
    полусотне правил это снова станет заметно. Сравниваем два замера на ОДНОЙ
    машине и с ОДНИМ добавляемым правилом, поэтому от её скорости отношение не
    зависит.

    Замер 2026-08-18: 1.0 когда строки правил живут по отдельности, 3.8 когда
    список считается заново целиком (0.11 с против 0.50 с на девятнадцати)."""
    idx = nlindex.load()
    правила = _правила(idx, 21)
    новое = правила[-1]

    def правка(база):
        # берём лучшее из трёх: мерим ОТНОШЕНИЕ, и случайная заминка машины в
        # одном из двух замеров исказила бы его сильнее всего
        лучшее = None
        for _ in range(3):
            nlindex._ПРАВИЛО_КЭШ.clear()
            nlindex.забыть_запрет()
            nlindex.запрет(база)
            nlindex.забыть_запрет()
            t = time.perf_counter()
            nlindex.запрет(база + [новое])
            прошло = time.perf_counter() - t
            лучшее = прошло if лучшее is None else min(лучшее, прошло)
        return лучшее

    к_четырём = правка(правила[:4])
    к_девятнадцати = правка(правила[:19])
    assert к_четырём > 0.005, "добавляемое правило ничего не стоит — отношение бессмысленно"
    assert к_девятнадцати < к_четырём * 2.0, (
        f"то же правило к 19 стоит {к_девятнадцати:.3f}с против {к_четырём:.3f}с к 4 — "
        f"правка снова считает весь список")


