# ЗАЧЕМ ЭТОТ ФАЙЛ. Замер 2026-08-18 на полном индексе (2 434 632 строки,
# 231 837 словоформ): одно правило стоило 15.5 секунды в свежем процессе, а
# двадцать — 23.4. Хуже была не разовая цена, а правка: маска кэшировалась ОДНИМ
# куском на весь список, поэтому добавление двадцатого правила заново считало
# девятнадцать посчитанных — 9.3 секунды на одно нажатие, и интерфейс всё это
# время стоял.
#
# Разбор по частям показал две статьи, обе на `pymorphy3.parse` (101.7 мкс на
# слово, своего кэша нет):
#   · карта начальных форм всего словаря индекса — 15.4 с на процесс;
#   · проверка «слова идут подряд» у словосочетания — 0.89 с на КАЖДОЕ правило
#     (разбирались все слова всех строк-кандидатов).
# Пересечения постингов (0.012 с) и построение самой маски (0.0001 с) не стоят
# ничего: подозрение на них было проверено замером и снято.
#
# Стало: карта печётся один раз и лежит рядом с индексом (0.23 с чтением против
# 15.4 с разбором), слова строк берутся из той же карты (0.0014 с против 0.89),
# строки каждого правила живут отдельно, поэтому правка считает ровно одно новое
# правило.
#
# СТОРОЖ ЗДЕСЬ СТЕРЕЖЁТ ИСХОД, А НЕ УСТРОЙСТВО. Ни одна проверка не спрашивает,
# существует ли такая-то функция или лежит ли такой-то файл: спрашивается
# сколько СЕКУНД стоит то, что делает пользователь, и ТА ЖЕ ЛИ выдача. Любую из
# трёх правок можно переписать как угодно, пока эти два ответа не изменились.
#
# Пороги намеренно щедрые — втрое-впятеро от замера. Тест обязан ловить возврат
# прежнего поведения (секунды и десятки секунд), а не колебания машины.
#
