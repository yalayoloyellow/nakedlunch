# 3. СВЕЖИЙ ПРОЦЕСС. Главная статья была именно здесь: карта начальных форм
#    строилась заново на КАЖДЫЙ запуск, и первое же правило стоило 15 секунд.

@нет_индекса
def test_svezhiy_process_ne_stroit_kartu_form_zanovo():
    """Двадцать правил в только что запущенном процессе.

    Проверяется отдельным процессом, а не в этом: кэш карты живёт в памяти, и
    внутри одного процесса цена старта не видна вовсе.

    Замер: 23.4 с до, 0.54 с после. Порог 5 с — прежнее поведение не умещалось
    в него даже на одном правиле (15.5 с).

    Карту сперва печём здесь: если её ещё нет (свежий клон, только что
    перепечённый индекс), первый разбор — законные пятнадцать секунд, и платить
    их обязан не сторож, а тот, кто их измеряет."""
    idx = nlindex.load()
    nlindex._карта_форм(idx)

    правила = _правила(idx, 20)
    скрипт = (
        "import sys, time, json\n"
        f"sys.path.insert(0, {str(КОРЕНЬ / 'core')!r})\n"
        "import nlindex\n"
        # запрет() зовётся со списком напрямую — чёрный список пользователя тут
        # ни при чём, и трогать его файл сторож не должен
        f"правила = json.loads({json.dumps(json.dumps(правила))})\n"
        "t = time.perf_counter()\n"
        "з = nlindex.запрет(правила)\n"
        "print(time.perf_counter() - t, int(з['маска'].sum()))\n"
    )
    ответ = subprocess.run([sys.executable, "-c", скрипт], capture_output=True,
                           text=True, cwd=str(КОРЕНЬ), timeout=300)
    assert ответ.returncode == 0, f"дочерний процесс упал:\n{ответ.stderr[-2000:]}"
    прошло, запрещено = ответ.stdout.split()
    assert int(запрещено) > 0, "правила ничего не запретили — тест ничего не измерил"
    assert float(прошло) < 5.0, (
        f"свежий процесс потратил {float(прошло):.1f}с на двадцать правил — "
        f"pymorphy снова зовётся на каждую словоформу (карта форм строится "
        f"разбором, или слова строк разбираются в проверке «подряд»)")


@нет_индекса
def test_karta_form_gretsya_progrevom_a_ne_polzovatelem(чистый_кэш):
    """Карту форм платит ПРОГРЕВ, а не человек первым правилом.

    Она печётся внутри каталога индекса и потому не переживает перепечку: любая
    пересборка сносит её вместе с каталогом, и следующий процесс платит разбор
    231 837 словоформ — 15.4 секунды замерено. Если этой строки не будет в
    `прогреть`, счёт предъявят человеку, добавившему первое правило.

    Сторож на ИСХОД: после прогрева карта обязана быть готова, то есть браться
    мгновенно. Проверять наличие вызова в тексте функции бессмысленно — вызвать
    можно и не туда."""
    import time
    idx = nlindex.load()
    nlindex.прогреть(idx)
    t = time.perf_counter()
    nlindex._карта_форм(idx)
    сек = time.perf_counter() - t
    assert сек < 0.5, f"после прогрева карта форм строится заново ({сек:.1f} с)"
