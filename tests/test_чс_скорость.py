# ПРАВИЛА БЕРУТСЯ ИЗ САМОГО КОРПУСА, а не написаны в тесте.
#
# Зашитые слова («сент-анж», «госпожа») стерегут только тот корпус, что лежит у
# автора: на чужом они не поймают ничего, правило вернётся пустым мгновенно, и
# тест будет зелёным, ничего не измерив. Частые слова индекса и пары соседних
# слов настоящих строк дают заведомо непустую работу на ЛЮБОМ корпусе.

def _правила(idx, сколько: int) -> list[str]:
    """Половина одиночных слов, половина словосочетаний — как в живом списке.

    Повторы выброшены: список чёрного списка их не допускает (blacklist._канон),
    и в счётчике два одинаковых правила схлопнулись бы в одну графу."""
    длины = np.diff(np.asarray(idx.tokoff))
    # Не самые-самые частые: у «и», «в», «не» постинги в миллионы строк, и
    # правило по ним запрещает пол-корпуса — это не типичная запись, а край.
    порядок = np.argsort(длины)[::-1][200:200 + сколько * 8]

    готово: list[str] = []
    видели: set[str] = set()

    def добавить(п: str) -> None:
        if п and п.lower() not in видели:
            видели.add(п.lower())
            готово.append(п)

    for т in порядок[:сколько * 4]:
        добавить(idx.tokens[int(т)])
        if len(готово) >= сколько - сколько // 2:
            break
    for т in порядок:
        # строка, где это слово есть, и в ней два соседних слова подряд
        строки = np.asarray(idx.tokpost[idx.tokoff[int(т)]:idx.tokoff[int(т) + 1]])
        for i in строки[:20].tolist():
            токены = nlindex._подряд(idx.text(int(i)))
            if len(токены) >= 2:
                добавить(" ".join(токены[:2]))
                break
        if len(готово) >= сколько:
            break
    assert len(готово) >= сколько, "корпус слишком мал, чтобы набрать правила"
    return готово[:сколько]


