# Ярусы точности рифмы — ИСКЛЮЧАЮЩИЕ полосы, не вложенные пороги
# (2026-08-28, владелец: «если я выбираю только точные — я хочу только
# точные, и т.д.»). «Близкая» — три знака общих, но ключи не тождественны;
# «созвучие» — два, но не три; «ассонанс» — ударная гласная, но не два.
# Один день ярусы жили вложенными — владелец переиграл в тот же вечер.
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))
import filters  # noqa: E402


def _р(ключ, слово):
    return {"rhyme": ключ, "text": "x " + слово}


def _пара(к1, к2, маска):
    return filters._rhymes(_р(к1, "первое"), _р(к2, "второе"), маска)


def test_точная_требует_ключ_целиком():
    assert _пара("апки", "апки", 1) is True
    assert _пара("апки", "апка", 1) is False


def test_близкая_отвергает_точные():
    assert _пара("апки", "апка", 2) is True       # «апк» общий, ключи разные
    assert _пара("апки", "апки", 2) is False      # точная пара — не близкая
    assert _пара("апки", "анки", 2) is False      # третий знак разошёлся


def test_созвучие_отвергает_близкие():
    assert _пара("апки", "апра", 4) is True       # «ап» общий, «апк»≠«апр»
    assert _пара("апки", "апка", 4) is False      # это близкая, не созвучие
    assert _пара("апки", "анки", 4) is False      # второй знак разошёлся


def test_ассонанс_отвергает_созвучия():
    assert _пара("апки", "анса", 8) is True       # «а» общая, «ап»≠«ан»
    assert _пара("апки", "апра", 8) is False      # это созвучие, не ассонанс


def test_маска_объединяет_полосы():
    """«Хочу только ассонанс и точные» — 1|8: годятся оба своих сорта,
    а промежуточные («близкая», «созвучие») — нет."""
    м = 1 | 8
    assert _пара("апки", "апки", м) is True       # точная горит
    assert _пара("апки", "анса", м) is True       # ассонанс горит
    assert _пара("апки", "апка", м) is False      # близкая не выбрана
    assert _пара("апки", "апра", м) is False      # созвучие не выбрано


def test_тяга_разводит_пару_на_близкой(monkeypatch):
    """Прямая тяга (nlindex.тянуть_строфы) сводила пары ТОЛЬКО тождественными
    ключами — при вложенных ярусах это сходило с рук, исключающим она обязана
    дать пару, совпавшую на ярусе и разошедшуюся строже."""
    import numpy as np
    import nlindex

    class _Идх:
        keys = ["", "апки", "апка"]

        def __init__(self):
            #                텍текст      ключ слоги
            строки = [("мягкие лапки",   1, 5),
                      ("тёплые шапки",   1, 5),
                      ("рваные тапки",   1, 5),
                      ("ни шатко ни валко", 2, 5)]
            self.key_id = np.array([k for _, k, _ in строки])
            self.syl = np.array([s for _, _, s in строки])
            self.mat = np.zeros(len(строки), dtype=np.uint8)
            self.lem_off = np.arange(len(строки) + 1)   # по своей лемме на строку
            self.lem_ids = np.arange(len(строки))
            self._т = [т for т, _, _ in строки]

        def text(self, i):
            return self._т[i]

    идх = _Идх()
    monkeypatch.setattr(nlindex, "_строки", lambda idx, ids, оц, пц: [
        {"rhyme": idx.keys[int(idx.key_id[i])], "text": idx.text(int(i))}
        for i in ids])
    # двадцать сёмян, не одно: на одном семени беззубый сторож зеленел —
    # случайный партнёр И БЕЗ запрета попадал в валидного (поймано ломкой)
    for семя in range(20):
        rng = np.random.default_rng(семя)
        строфа = nlindex.тянуть_строфы(
            идх, np.arange(4), [(1, 9), (1, 9)], "аа", 2, rng, ярусы_рифмы=2)
        assert len(строфа) == 2
        к1, к2 = строфа[0]["rhyme"], строфа[1]["rhyme"]
        assert к1 != к2, f"тяга на «близкой» свела точную пару (семя {семя})"
        assert к1[:3] == к2[:3]


def test_отбор_не_берёт_точную_пару_на_близкой():
    """Корзина широкого префикса на «близкой» содержит и тождественные ключи —
    они больше не пара. Якорь обязан пройти мимо корзины, где все соседи
    «слишком точные», и взять настоящую близкую пару."""
    def строка(ключ, текст, лемма):
        return {"rhyme": ключ, "text": текст, "_lem": {лемма}, "score": 1.0,
                "template": "nakedlunch", "syllables": 5}

    кандидаты = [
        # ловушка: три строки с ТОЖДЕСТВЕННЫМ ключом (точные пары, на
        # «близкой» не годятся) и лучшим баллом
        строка("апки", "мягкие лапки", "лапка"),
        строка("апки", "тёплые шапки", "шапка"),
        строка("апки", "рваные тапки", "тапка"),
        # настоящая близкая пара: «орл» общий, ключи разные
        строка("орлом", "летел орлом", "орёл"),
        строка("орлов", "город Орлов", "город"),
    ]
    for л in кандидаты[:3]:
        л["score"] = 9.0
    выбор = filters._select_with_rhyme(кандидаты, "аа", 2, ярусы=2)
    ключи = [r.get("rhyme") for r in выбор]
    assert len(выбор) == 2
    assert ключи[0] != ключи[1], "на «близкой» встала точная пара"
    assert ключи[0][:3] == ключи[1][:3]
