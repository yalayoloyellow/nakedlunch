ПОЛКИ = КОРЕНЬ / "interface" / "react-app" / "src" / "nl" / "methods.shelves.js"


def node(тело: str):
    """Выполнить кусок ES-модуля рядом с полками и вернуть разобранный JSON,
    который он напечатает. Пропускаем тест, если node не установлен: это
    проверка фронта, а не повод красить бэкенд в красный."""
    if shutil.which("node") is None:
        pytest.skip("node не установлен — проверка фронта пропущена")
    src = f"import {{ shelfMethods }} from '{ПОЛКИ.as_uri()}';\n{тело}"
    # ВЫВОД ДЕКОДИРУЕМ САМИ, В UTF-8 (Раунд 61). При text=True питон берёт
    # кодировку локали, и на Windows кириллица из node приходила мойбейком —
    # поймано первым же прогоном тестов на трёх системах. node печатает UTF-8
    # всегда, гадать тут нечего.
    p = subprocess.run(["node", "--input-type=module", "-e", src],
                       capture_output=True, timeout=60)
    вывод = (p.stdout or b"").decode("utf-8", "replace")
    ошибки = (p.stderr or b"").decode("utf-8", "replace")
    assert p.returncode == 0, f"node упал:\n{ошибки}"
    assert вывод.strip(), f"node ничего не напечатал. stderr:\n{ошибки}"
    return json.loads(вывод)


ЗОВ = """
const кто = (st) => {
  const self = Object.assign(Object.create(shelfMethods), { state: st });
  return shelfMethods.linkKnobs.call(self, 0);
};
const база = {
  knobForms: { builtin: [], custom: [{ name: 'Свой', mode: 'классика', params: { 'Мат': 1 } }] },
  chainKnobs: [], refChain: [], knobMode: 'алгоритм', params: { 'Мат': -1, 'Клаузула': 0 },
};
"""


# ---- 1. три ступени, и референс среди них ----------------------------------

def test_поряд_ок_ступеней_крутилок_звена():
    """Свой профиль → референс → мастерская. Порядок именно такой: назначенный
    вручную профиль главнее замера, замер главнее того, что открыто в
    мастерской.

    Раунд 55: третья ступень называется «мастерская» и осталась только
    СТРАХОВКОЙ — у звена всегда есть свой профиль, а сюда доходит один случай:
    профиль удалили с полки."""
    реф = "{ mode: 'алгоритм', params: { 'Клаузула': 2 } }"
    res = node(ЗОВ + f"""
    console.log(JSON.stringify({{
      страховка: кто(база),
      референс: кто({{ ...база, refChain: [{реф}] }}),
      звено: кто({{ ...база, chainKnobs: ['Свой'], refChain: [{реф}] }}),
    }}));
    """)
    assert res["страховка"]["source"] == "мастерская"
    assert res["страховка"]["params"]["Мат"] == -1
    assert res["референс"]["source"] == "референс"
    assert res["референс"]["params"]["Клаузула"] == 2
    assert res["звено"]["source"] == "звено"
    assert res["звено"]["mode"] == "классика"


def test_регрессия_референс_не_проваливается_в_панель():
    """ТОТ САМЫЙ БАГ. Звену не назначен профиль, референс намерил клаузулу —
    крутилки обязаны быть референсными. Раньше здесь возвращалась панель, и
    одиночная генерация звучала так, будто текста не вставляли вовсе."""
    res = node(ЗОВ + """
    console.log(JSON.stringify(кто({ ...база,
      refChain: [{ mode: 'алгоритм', params: { 'Клаузула': 2, 'Мат': 0.2 } }] })));
    """)
    assert res["source"] != "мастерская", "референс снова проваливается в мастерскую"
    assert res["params"] == {"Клаузула": 2, "Мат": 0.2}


def test_мастерская_в_звено_прогона_не_дублируется():
    """`source` нужен прогону: мастерскую он и так шлёт глобально, и класть её
    копию в каждое звено значило бы сделать фолбэк pipeline.resolve_chain
    недостижимым, оставив его живым на вид."""
    res = node(ЗОВ + "console.log(JSON.stringify(кто(база)));")
    assert res["source"] == "мастерская"


# ---- 2. референс переразмечает цепочку целиком -----------------------------

def test_снятие_референса_чистит_профили_звеньев():
    """РЕГРЕССИЯ. Цепочка была из трёх звеньев со своими профилями, референс
    дал два — старые имена не должны остаться лежать по индексам."""
    res = node("""
    const self = Object.assign(Object.create(shelfMethods), {
      state: { chainKnobs: ['Свой', 'Свой', 'Свой'],
               chain: ['куплет', 'припев', 'мост'], chainForms: ['Катрен', null, null] },
    });
    console.log(JSON.stringify(
      shelfMethods.refPatch.call(self, [{ spec: [] }, { spec: [] }], ['свободно'], { частей: 2 })));
    """)
    assert res["chainKnobs"] == [None, None], "профили прежней цепочки пережили референс"
    assert res["chain"] == ["", ""] and res["chainForms"] == [None, None]
    assert res["junctions"] == ["свободно"]


def test_выбор_звена_вырезан():
    """Раунд 55. `openLink` жил ради одного вопроса — «к какому звену
    относится редактор под цепочкой», — а редактора под цепочкой больше нет:
    полки правятся в меню «Строфа», звенья набираются в меню «Пайплайн».
    Если ключ вернётся, вернётся и весь класс ошибок «правка относится
    непонятно к чему»."""
    res = node("""
    const self = Object.assign(Object.create(shelfMethods), { state: {} });
    console.log(JSON.stringify(shelfMethods.refPatch.call(self, [], [], null)));
    """)
    assert "openLink" not in res, "выбор звена вернулся в перекладку модели"
    текст = ПОЛКИ.read_text("utf-8")
    assert "selectLink(" not in текст, "selectLink вернулся"


# ---- лист как референс -----------------------------------------------------

def лист_в_референс(rows) -> str:
    return node(f"""
    console.log(JSON.stringify(shelfMethods.docAsReference.call(
      {{}}, {json.dumps(rows, ensure_ascii=False)})));
    """)


def test_лист_становится_референсом():
    """Заголовки («куплет», «припев») — границы частей, а не строки.

    Если бы они попали в текст, измеритель посчитал бы каждый строкой: у
    каждого куплета появилась бы лишняя односложная строка в схеме рифмовки
    и в среднем числе слогов."""
    rows = [
        {"type": "role", "text": "куплет"},
        {"type": "line", "text": "кот сидел на окне"},
        {"type": "line", "text": "пёс лежал во дворе"},
        {"type": "role", "text": "припев"},
        {"type": "line", "text": "ночь была коротка"},
    ]
    assert лист_в_референс(rows) == "кот сидел на окне\nпёс лежал во дворе\n\nночь была коротка"


def test_пустые_строки_тоже_делят_части_и_не_плодят_дыр():
    """Пустая строка — граница части, но две подряд не должны давать пустую
    часть: измеритель бы её пропустил, а звено в цепочке уже посчиталось бы."""
    rows = [
        {"type": "role", "text": "куплет"},
        {"type": "line", "text": "первая"},
        {"type": "line", "text": ""},
        {"type": "line", "text": "   "},
        {"type": "line", "text": "вторая"},
        {"type": "role", "text": "хвост"},
    ]
    assert лист_в_референс(rows) == "первая\n\nвторая"


def test_лист_из_одних_заголовков_даёт_пустоту():
    """Пустой ответ — сигнал кнопке сказать «брать не из чего», а не отправить
    измерителю пустой текст и получить 400-ю."""
    assert лист_в_референс([{"type": "role", "text": "куплет"}]) == ""
    assert лист_в_референс([]) == ""


def test_длинный_текст_обрезается_и_говорит_об_этом():
    """Кнопка «взять из листа» даёт цепочку сразу на весь лист, а у цепочки
    есть предел. Без числа `обрезано` интерфейс показал бы 12 звеньев вместо
    двадцати молча, а прогон упал бы 400-й уже ПОСЛЕ нажатия «прогон»."""
    проф = json.loads(json.dumps(ПРОФИЛЬ))
    проф["части"] = проф["части"] * 20
    проф["стыки"] = ["свободно"] * 19
    вышло = refprofile.цепочка(проф, 1.0)
    предел = clean._PIPE_CHAIN_MAX
    assert len(вышло["chain"]) == предел
    assert вышло["обрезано"] == 20 - предел
    # стыков ровно звеньев−1: иначе валидатор молча отрежет лишние
    assert len(вышло["junctions"]) == предел - 1
    # и цепочка обязана пройти валидатор прогона, а не упасть 400-й
    clean.pipeline_spec({"theme": "", "chain": вышло["chain"], "junctions": вышло["junctions"]})


def test_короткий_текст_ничего_не_теряет():
    вышло = refprofile.цепочка(ПРОФИЛЬ, 1.0)
