def test_части_референса_совпадают_со_звеньями_цепочки():
    """Сквозной смысл кнопки: сколько кусков в листе — столько звеньев в
    цепочке. Меряет уже питоновский измеритель, тот же, что и на роуте."""
    rows = [
        {"type": "role", "text": "куплет"},
        {"type": "line", "text": "кот сидел на окне"},
        {"type": "line", "text": "пёс лежал во дворе"},
        {"type": "role", "text": "припев"},
        {"type": "line", "text": "ночь была коротка"},
        {"type": "line", "text": "тень была высока"},
    ]
    проф = refprofile.профиль(лист_в_референс(rows))
