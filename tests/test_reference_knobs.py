#
# Требование (2026-08-03): пайплайн принимает референтный текст и процент референтности и
# сам назначает структуру.. Аудит нашёл, что до генерации из этого доезжал только
# КАРКАС, и в трёх местах сразу:
#
#   1. Одиночная генерация и фристайл брали крутилки резолвером, у которого
#      ступени «референс» не было вовсе: свой профиль звена → ПАНЕЛЬ. Каркас
#      при этом брался из референса (linkSpec его знает). То есть вставленный
#      текст задавал длину строк и схему рифмовки, а его же замеренные мат,
#      клаузула, связность и точность рифм молча выбрасывались — и ползунок
#      «референтность» в самом частом действии не значил ничего, кроме ширины
#      слоговой вилки.
#   2. applyRef не чистил chainKnobs. Референс переразмечает цепочку целиком,
#      а имена профилей оставались лежать ПО ИНДЕКСАМ уже другой цепочки —
#      и первая ступень резолвера перебивала замеренное чужим профилем.
#   3. Нулевая референтность ставила ЖЁСТКИЕ ворота вопреки своему докстрингу
#      («от референса остаётся только каркас»): «Мат» уезжал в 0, а это не
#      «не задано», а сплошной фильтр «без мата»; «Связность» уезжала в 0, а
#      это не «выключено» (−1), а включённое мнение с мишенью «соседние
#      строки максимально не связаны».
#
# Фронт проверяется НЕ чтением исходников: резолвер и перекладка модели —
# чистые функции, и pytest гоняет их настоящим node. Сборка тут не помогла бы
# (она зелёная и при утечке), а грепом по тексту нельзя доказать порядок
# ступеней.
#
# Прогон: .venv/bin/python -m pytest tests/test_reference_knobs.py -q

