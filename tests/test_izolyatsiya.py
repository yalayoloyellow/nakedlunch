# СТОРОЖ ПО ИСХОДУ: НАСТОЯЩАЯ СБОРКА В ПЕСОЧНИЦЕ (2026-08-18).
#
# Проверять пути по отдельности мало: путь может быть правильным, а запись всё
# равно уйдёт не туда (временный файл, `mkdir` у соседа, лог сборки). Поэтому
# здесь проверяется ИСХОД — настоящий сборщик запускается настоящей командой в
# изолированном доме, и после него в боевых каталогах не изменился ни один файл.
#
# Сборка идёт по-настоящему, а не понарошку: в песочницу кладётся построчный кэш
# на две записи, и `--reban` честно проходит его насквозь — тот самый режим,
# сайдкар которого и завёлся однажды в боевом `core/data`.

_НАСТОЯЩАЯ_СБОРКА = """
import subprocess, sys
sys.path.insert(0, {core!r})
import дочерний
# ТОТ ЖЕ ВЫЗОВ, ЧТО В api/server.py:313 — env ребёнку не передаётся.
реб = subprocess.Popen(дочерний.команда("ударения") + ["--reban"], cwd={корень!r})
sys.exit(реб.wait())
"""

БОЕВЫЕ = (КОРЕНЬ / "core" / "data", КОРЕНЬ / "data")


def _отпечаток() -> dict:
    снимок = {}
    for корень in БОЕВЫЕ:
        try:
            обход = корень.rglob("*")
        except OSError:
            continue
        for п in обход:
            try:
                с = п.lstat()
            except OSError:
                continue
            снимок[str(п)] = (с.st_size, с.st_mtime_ns)
    return снимок


def test_настоящая_сборка_в_изоляции_не_трогает_боевое(tmp_path):
    """При заданной NAKEDLUNCH_HOME боевые core/data и data не меняются."""
    дом = tmp_path / "дом"
    (дом / "core" / "data").mkdir(parents=True)
    (дом / "core" / "data" / "nl_rhyme.jsonl").write_text(
        "\n".join(json.dumps(з, ensure_ascii=False) for з in (
            {"t": "я надеюсь на тепло", "key": "ЛО", "span": [12, 17], "banal": 0.0,
             "taut": False, "lemmas": ["надеяться", "тепло"],
             "tokens": ["я", "надеюсь", "на", "тепло"]},
            {"t": "он достал свой нож", "key": "ОЖ", "span": [15, 18], "banal": 0.0,
             "taut": False, "lemmas": ["достать", "нож"],
             "tokens": ["он", "достал", "свой", "нож"]},
        )) + "\n", encoding="utf-8")

    сценарий = tmp_path / "сборка.py"
    сценарий.write_text(_НАСТОЯЩАЯ_СБОРКА.format(
        core=str(КОРЕНЬ / "core"), корень=str(КОРЕНЬ)), encoding="utf-8")

    чистая = {k: v for k, v in os.environ.items() if not k.startswith("NAKEDLUNCH_")}
    чистая["NAKEDLUNCH_HOME"] = str(дом)

    до = _отпечаток()
    готово = subprocess.run([sys.executable, str(сценарий)], env=чистая,
                            capture_output=True, text=True, cwd=str(КОРЕНЬ), timeout=600)
    после = _отпечаток()

    assert готово.returncode == 0, готово.stderr[-1500:]

    # СНАЧАЛА УТЕЧКА. Если сборка ушла в боевое, сказать надо именно это, а не
    # «в песочнице чего-то не хватает»: второе — следствие, и оно уводит от
    # причины на полчаса, как уже было.
    беда = [("создан", п) for п in sorted(set(после) - set(до))] + \
           [("удалён", п) for п in sorted(set(до) - set(после))] + \
           [("изменён", п) for п in
            sorted(п for п in set(до) & set(после) if до[п] != после[п])]
    assert not беда, ("сборка шла в песочнице, а тронула БОЕВЫЕ данные:\n"
                      + "\n".join(f"  {что}: {п}" for что, п in беда))

    # И только теперь — что сборка правда состоялась. Иначе сторож был бы зелен
    # потому, что не случилось вообще ничего.
    сайдкар = дом / "core" / "data" / "nl_rhyme.status.json"
    assert сайдкар.exists(), (
        "сборка отработала без единой жалобы и не оставила статуса в "
        f"песочнице ({сайдкар}) — значит проверять было нечего:\n"
        + готово.stdout[-800:])
    статус = json.loads(сайдкар.read_text(encoding="utf-8"))
    assert статус["state"] == "done" and статус["mode"] == "reban", статус


