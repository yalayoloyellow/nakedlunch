# ГРАНИЦА ПРОЦЕССА — ГЛАВНОЕ МЕСТО, ГДЕ ИЗОЛЯЦИЯ МОЖЕТ КОНЧИТЬСЯ (2026-08-18).
#
# Сборщики живут отдельными процессами: `api/server.py` зовёт `subprocess.Popen`
# с командой из `core/дочерний.py`. Родитель считает корни при импорте — и на
# этом его власть кончается. Если ребёнку не достанется `NAKEDLUNCH_HOME`, он
# посчитает свои корни заново и от умолчания, то есть испечёт кэш и напишет
# сайдкар статуса в БОЕВОЙ `core/data`, пока родитель думает, что работает в
# песочнице.
#
# Сегодня ребёнок среду наследует: `Popen` без `env=` отдаёт ему `os.environ`
# целиком. Именно это и караулим — достаточно дописать в один вызов свой `env=`,
# и утечка станет настоящей, а заметить её будет нечем: снаружи всё работает.

_ЗАПУСК_РЕБЁНКА = """
import subprocess, sys
sys.path.insert(0, {core!r})
import дочерний
# ТОТ ЖЕ ВЫЗОВ, ЧТО В api/server.py: cwd задан, env НЕ передаётся. Питон берём у
# настоящей команды роли, а вместо сборщика подсовываем пробу: спрашиваем не
# «испеклось ли», а «где ребёнок считает свои корни».
реб = subprocess.Popen(дочерний.команда("ударения")[:1] + [{проба!r}], cwd={корень!r})
sys.exit(реб.wait())
"""

_ПРОБА = """
import sys, pathlib
sys.path.insert(0, str(pathlib.Path({корень!r}) / "core"))
import пути
print(пути.ЗАПИСЬ)
print(пути.АРТЕФАКТЫ)
print(пути.ДАННЫЕ)
"""


def test_ребёнок_видит_те_же_корни(tmp_path):
    """Дочерний процесс сборки обязан считать корни там же, где родитель."""
    проба = tmp_path / "проба.py"
    проба.write_text(_ПРОБА.format(корень=str(КОРЕНЬ)), encoding="utf-8")
    родитель = tmp_path / "родитель.py"
    родитель.write_text(_ЗАПУСК_РЕБЁНКА.format(
        core=str(КОРЕНЬ / "core"), проба=str(проба), корень=str(КОРЕНЬ)), encoding="utf-8")

    дом = tmp_path / "дом"
    чистая = {k: v for k, v in os.environ.items() if not k.startswith("NAKEDLUNCH_")}
    чистая["NAKEDLUNCH_HOME"] = str(дом)
    готово = subprocess.run([sys.executable, str(родитель)], env=чистая,
                            capture_output=True, text=True, cwd=str(КОРЕНЬ), timeout=180)
    assert готово.returncode == 0, готово.stderr[-800:]
    корни = [с for с in готово.stdout.splitlines() if с.strip()]
    assert len(корни) == 3, f"ребёнок не отчитался о трёх корнях: {готово.stdout!r}"
    снаружи = [п for п in корни if str(дом) not in п]
    assert not снаружи, ("ребёнок потерял изоляцию родителя и будет писать в "
                         f"боевые каталоги: {снаружи}")


