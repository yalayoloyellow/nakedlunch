# СТОРОЖ ПО ВЫЗОВУ: РЕБЁНКУ НЕ ПОДСОВЫВАЮТ ЧУЖУЮ СРЕДУ (2026-08-18).
#
# Изоляция ребёнка держится на одном свойстве `subprocess`: без `env=` он
# получает `os.environ` родителя целиком. Свойство молчаливое — сломать его
# можно одной доброй правкой («почищу среду, чтобы ребёнок не унаследовал
# мусор»), и ни один тест на пути этого не заметит: корни-то у РОДИТЕЛЯ
# останутся правильные, а писать в боевое будет ребёнок.
#
# Поэтому смотрим на сами места запуска. Разрешено ровно два вида: без `env=`
# вовсе или с `env`, слепленным из `os.environ` (так делает `child_env()` в
# launch.py — ему нужно дописать PATH). Всё остальное — отказ с именем файла и
# номером строки.
_ЗАПУСКАЮЩИЕ = ("api/server.py", "launch.py")


def _места_запуска_ролей(файл: Path):
    """(строка, выражение env) для каждого запуска дочерней роли в файле."""
    дерево = ast.parse(файл.read_text("utf-8"))
    свои = {у.name: у for у in ast.walk(дерево) if isinstance(у, ast.FunctionDef)}
    # Команду роли часто кладут в переменную («args = дочерний.команда(...)»),
    # и тогда у самого Popen в аргументах уже нет ни слова про роль.
    имена = {ц.id for у in ast.walk(дерево) if isinstance(у, ast.Assign)
             and "дочерний" in ast.unparse(у.value)
             for ц in у.targets if isinstance(ц, ast.Name)}
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Call):
            continue
        if ast.unparse(узел.func).split(".")[-1] not in ("Popen", "run"):
            continue
        аргс = " ".join(ast.unparse(а) for а in узел.args)
        if "дочерний" not in аргс and not (имена & set(аргс.split())):
            continue
        среда = next((к.value for к in узел.keywords if к.arg == "env"), None)
        yield узел.lineno, среда, свои


def test_запуск_ребёнка_не_подменяет_среду():
    for отн in _ЗАПУСКАЮЩИЕ:
        файл = КОРЕНЬ / отн
        if not файл.exists():
            continue
        места = list(_места_запуска_ролей(файл))
        assert места, (f"в {отн} не нашлось ни одного запуска дочерней роли — "
                       "сторож ослеп, а не поле чистое")
        for строка, среда, свои in места:
            if среда is None:
                continue                      # среда наследуется целиком — то, что надо
            текст = ast.unparse(среда)
            если_своя = свои.get(текст.split("(")[0])
            родом_из_среды = "environ" in текст or (
                если_своя is not None and "os.environ" in ast.unparse(если_своя))
            assert родом_из_среды, (
                f"{отн}:{строка} запускает сборщика со своей средой `{текст}`, "
                "не сделанной из os.environ. Значит ребёнок не получит "
                "NAKEDLUNCH_HOME и напишет кэш и статус в БОЕВОЙ core/data, "
                "пока родитель работает в песочнице.")
