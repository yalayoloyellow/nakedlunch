#
# ЧТО БЫЛО. Интерфейс при открытии окна спрашивает `/api/nl/state`, а тот звал
# `list_corpora()` — то есть требовал разобранного `state.json` на 363 МБ.
# Разбор стоит пяти секунд и, что важнее, идёт одним непрерывным `json.loads`:
# он держит GIL и душит всё рядом. Первая генерация ждала шесть секунд, считаясь
# сама за 0.34.
#
# ЧТО СТАЛО. Рядом лежит опись — те же книги, 7 КБ. Флаги активности в неё НЕ
# кладутся: они меняются чаще всего и живут в своём `active.json`; здесь только
# то, что меняется при заливке и удалении. Панель отвечает по описи, пока склад
# не понадобился по-настоящему.
#
# ГЛАВНОЕ ПРАВИЛО: опись — СЛЕПОК, а не истина. Склад дочитан — отвечаем по
# нему. Описи нет или она битая — честно ждём склад, как раньше.
import json
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "core"))
sys.path.insert(0, str(КОРЕНЬ / "core" / "nlsrc"))

import nlbridge  # noqa: E402


class _Склад:
    def list_corpora(self):
        return [{"id": "к1", "name": "Книга первая", "type": "fb2",
                 "added_at": 1, "fragment_count": 10, "active": True},
                {"id": "к2", "name": "Книга вторая", "type": "txt",
                 "added_at": 2, "fragment_count": 5, "active": False}]

    def get_active_pool(self):
        return ["строка"] * 10


@pytest.fixture
def дом(tmp_path, monkeypatch):
    monkeypatch.setattr(nlbridge.пути, "ДАННЫЕ", tmp_path)
    monkeypatch.setattr(nlbridge, "NAKEDLUNCH_DATA", tmp_path)
    nlbridge.забыть_опись()
    yield tmp_path
    nlbridge.забыть_опись()


def test_описи_нет_отдаём_None(дом):
    """Честный отказ, а не пустой список: зовущий обязан уйти к складу."""
    assert nlbridge.опись_книг() is None


def test_запись_и_чтение(дом):
    nlbridge.записать_опись(_Склад())
    (дом / "active.json").write_text(json.dumps({"к1": True, "к2": False}), "utf-8")
    nlbridge.забыть_опись()
    книги = nlbridge.опись_книг()
    assert [к["name"] for к in книги] == ["Книга первая", "Книга вторая"]
    assert [к["active"] for к in книги] == [True, False]
    assert nlbridge.пул_из_описи() == 10


def test_активность_берётся_из_своего_файла(дом):
    """ГЛАВНЫЙ СТОРОЖ. Флаги активности меняются при каждом клике по книге, а
    опись переписывается только при смене состава. Держать флаги в описи
    значило бы показывать вчерашние: включил книгу — панель говорит, что она
    выключена, и генерация с панелью расходятся."""
    nlbridge.записать_опись(_Склад())
    (дом / "active.json").write_text(json.dumps({"к1": False, "к2": True}), "utf-8")
    nlbridge.забыть_опись()
    книги = nlbridge.опись_книг()
    assert [к["active"] for к in книги] == [False, True], (
        "опись отдала свои флаги вместо нынешних — панель покажет вчерашнее")
    assert nlbridge.пул_из_описи() == 5


def test_битая_опись_не_роняет(дом):
    (дом / "книги.json").write_text("{это не json", "utf-8")
    nlbridge.забыть_опись()
    assert nlbridge.опись_книг() is None


def test_пустая_опись_не_принимается(дом):
    """Пустой список — не «книг нет», а «слепок не удался». Иначе панель
    молча показала бы пустой корпус при полном складе."""
    (дом / "книги.json").write_text(json.dumps({"книги": []}), "utf-8")
    nlbridge.забыть_опись()
    assert nlbridge.опись_книг() is None


def test_запись_целиком_или_никак(дом):
    """Опись пишется через временный файл: оборванная запись не должна
    оставить половину — панель поверила бы обрубку."""
    nlbridge.записать_опись(_Склад())
    assert (дом / "книги.json").exists()
    assert not list(дом.glob("*.tmp")), "временный файл остался рядом"
