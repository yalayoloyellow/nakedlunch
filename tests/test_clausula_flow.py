# nakedlunch — ВОРОТА клаузулы и связности (Раунд 50).
#
# Обе крутилки существовали с Раунда 44, но добраться до них можно было ТОЛЬКО
# через референс (core/refprofile.цепочка). Раунд 50 даёт им собственные ручки
# в профиле настроек — и вместе с этим делает достижимыми пути, которые до сих
# пор не исполнялись ни разу.
#
# Карта Раунда 50 нашла в одном из них настоящий баг: в light-ярусе (классика
# без колоночного индекса) проверка клаузулы стояла ДО присваивания `key` —
# первый фрагмент давал UnboundLocalError, остальные отсеивались по клаузуле
# ПРЕДЫДУЩЕГО фрагмента. Баг был невидим, потому что на машине владельца
# индекс испечён и режим уходит в nlindex.select_light. Тест ниже гоняет
# именно светлый путь, без индекса.
#
# Проверяется РЕЗУЛЬТАТ, а не наличие поля: связность до этого раунда была
# покрыта только двумя парс-ассертами («значение доехало»), то есть весь
# код ранжирования можно было отключить, не уронив ни одного теста.
#
# Прогон: .venv/bin/python -m pytest tests/test_clausula_flow.py -q

import sys
from pathlib import Path

import pytest
from conftest import нет_словаря_рифм, нет_векторов  # noqa: F401

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))

import clean
import filters
import nlbridge
import scan
from corpus import Corpus, lemmatize

# ключ = хвост от ударной гласной, число гласных в нём = номер слога от конца
МУЖСКИЕ = {"он ушёл в ночной покой": "ой", "я не помню этот бой": "ой"}
ЖЕНСКИЕ = {"над рекою тишина": "ина", "и уходит тишина": "ина"}
ДАКТИЛЬ = {"я запомнил это здание": "ание", "было позднее свидание": "ание"}
ВСЕ = {**МУЖСКИЕ, **ЖЕНСКИЕ, **ДАКТИЛЬ}


@pytest.fixture()
def словарь_рифм(monkeypatch):
    """Подменяем офлайн-словарь рифм своим: настоящий весит ~950 МБ и в тестах
    не поднимается. Форма записи — как у tools/build_nl_rhyme.py."""
    fake = {t: {"banal": 3.0, "taut": False, "lemmas": lemmatize(t),
                "tokens": list(nlbridge._tokens(t)), "key": key, "span": None}
            for t, key in ВСЕ.items()}
    monkeypatch.setattr(filters, "_NL_RHYME", fake)
    # колоночного индекса нет — значит светлый путь идёт через _nl_scored,
    # а не через nlindex.select_light. Это и есть починенная ветка.
    monkeypatch.setattr(filters, "_index_for_current_cache", lambda *a, **k: None)
    return fake


def test_ключи_рифм_фикстуры_дают_ожидаемую_клаузулу():
    """Опора всего файла: если scan.clausula считает не то, остальные тесты
    зелёные и бессмысленные."""
    assert {scan.clausula(k) for k in МУЖСКИЕ.values()} == {1}
    assert {scan.clausula(k) for k in ЖЕНСКИЕ.values()} == {2}
    assert {scan.clausula(k) for k in ДАКТИЛЬ.values()} == {3}


# ---- починенный баг ---------------------------------------------------------

@pytest.mark.parametrize("клаузула, ожидание", [
    (0, ВСЕ), (1, МУЖСКИЕ), (2, ЖЕНСКИЕ), (3, ДАКТИЛЬ),
])
def test_ворота_клаузулы_в_светлом_ярусе(словарь_рифм, клаузула, ожидание):
    """РЕГРЕССИЯ. До Раунда 50 этот вызов падал UnboundLocalError на первом же
    фрагменте: проверка клаузулы читала `key` до присваивания."""
    out, _ = filters._nl_scored(list(ВСЕ), Corpus(), set(), 9.0,
                                light=True, clausula=клаузула)
    assert {r["text"] for r in out} == set(ожидание)


def test_фрагмент_без_ключа_не_проходит_ворота(словарь_рифм):
    """Клаузула у неизвестного фрагмента — 0, угадывать нечем. Он честно
    отсеивается, а не проскакивает «за неимением возражений»."""
    out, _ = filters._nl_scored(list(ВСЕ) + ["чужой фрагмент без ключа"],
                                Corpus(), set(), 9.0, light=True, clausula=2)
    assert {r["text"] for r in out} == set(ЖЕНСКИЕ)


def test_клаузула_ноль_никого_не_режет(словарь_рифм):
    out, _ = filters._nl_scored(list(ВСЕ) + ["чужой фрагмент без ключа"],
                                Corpus(), set(), 9.0, light=True, clausula=0)
    assert len(out) == len(ВСЕ) + 1


# ---- ворота живут и в классике ---------------------------------------------

def test_классика_подчиняется_воротам_клаузулы(словарь_рифм):
    """Классика отключает МНЕНИЯ о строке, но не ВОРОТА: клаузула — про то,
    что содержится, а не про то, насколько хорошо."""
    k = clean.knobs({"shortlist": 6, "real_text": 1.0, "classic": 1.0, "clausula": 2})
    res = filters.run([], k, Corpus(), nl_fragments=list(ВСЕ), rhyme="none")
    got = {r["text"] for r in res["shortlist"]}
    assert got, "ворота клаузулы не должны убивать выдачу целиком"
    assert got <= set(ЖЕНСКИЕ), f"чужая клаузула просочилась в классику: {got - set(ЖЕНСКИЕ)}"


def test_алгоритм_подчиняется_воротам_клаузулы(словарь_рифм):
    k = clean.knobs({"shortlist": 6, "real_text": 1.0, "classic": 0.0, "clausula": 1})
    res = filters.run([], k, Corpus(), nl_fragments=list(ВСЕ), rhyme="none")
    got = {r["text"] for r in res["shortlist"]}
    assert got <= set(МУЖСКИЕ), f"чужая клаузула просочилась в алгоритм: {got - set(МУЖСКИЕ)}"


# ---- связность: −1 это «выключено», а 0 — требование разрыва ---------------

def test_ноль_связности_это_не_выключено():
    """Ловушка шкалы: flow=0 означает «требовать максимально несвязные
    соседние строки», а «не задано» — только −1. Ползунок 0..1 без отдельного
    выключателя сделал бы крайнее левое положение активным требованием."""
    assert clean.knobs({})["flow"] == -1.0
    assert clean.knobs({"flow": 0.0})["flow"] == 0.0
    assert clean.KNOB_OPINIONS["Связность"][2] == -1.0
    assert clean.knobs_from_profile(None)["flow"] == -1.0


def test_связность_это_мнение_и_классику_не_переживает():
    """nlindex.select_light не принимает flow вовсе — значит связность двигает
    ранжир, а не режет пул, и в классике её не существует. Клаузула наоборот:
    она в списке того, что классика соблюдает."""
    assert "Связность" in clean.KNOB_OPINIONS
    assert "Связность" not in clean.KNOB_CLASSIC
    assert set(clean.KNOB_CLASSIC) == {"Мат", "Клаузула"}
    п = clean.knob_profile({"name": "т", "mode": clean.MODE_CLASSIC,
                            "params": {"Связность": 0.5, "Клаузула": 2}})
    assert "Связность" not in п["params"]
    assert п["params"]["Клаузула"] == 2


def test_связность_доезжает_из_профиля_настроек():
    k = clean.knobs_from_profile({"name": "т", "params": {"Связность": 0.45}})
    assert k["flow"] == pytest.approx(0.45)


def test_клаузула_доезжает_из_профиля_настроек():
    for v in (0, 1, 2, 3):
        assert clean.knobs_from_profile({"name": "т", "params": {"Клаузула": v}})["clausula"] == v


# ---- клаузула по НАСТОЯЩЕМУ ударению (Раунд 51) ---------------------------

@нет_словаря_рифм
def test_klauzula_referensa_po_udareniyu():
    """РЕГРЕССИЯ. В refprofile стояло своё угадывание: хвост резался от
    предпоследней гласной, значит в нём ВСЕГДА ровно две гласных — функция
    физически не могла вернуть 3, а для любого неодносложного слова отвечала 2.
    То есть это был детектор односложности, а не клаузула (верна в 58% против
    ruaccent на 34 501 слове). Теперь ответ берётся из словаря ударений,
    который и так поднят в память процесса."""
    import refprofile
    # ударение на последнем слоге → мужская, даже если слово длинное
    assert refprofile._клаузула("далеко за молоко") == 1
    assert refprofile._клаузула("в тишине окно") == 1
    # на предпоследнем → женская
    assert refprofile._клаузула("высокое небо") == 2
    # на третьем от конца → ДАКТИЛИЧЕСКАЯ: эта ветка раньше была недостижима
    assert refprofile._клаузула("она выговаривала") == 3
    assert refprofile._клаузула("большое здание") == 3
    # слова нет в словаре — честный ноль, а не догадка
    assert refprofile._клаузула("зюмбрлыкает") == 0
    assert refprofile._клаузула("") == 0


@нет_словаря_рифм
def test_klauzula_ne_vsegda_dvoyka():
    """Прежний измеритель отвечал 2 почти всегда — это и была его поломка.
    Настоящий обязан давать РАЗНЫЕ значения на разных словах."""
    import refprofile
    строки = ["в тишине окно", "высокое небо", "она выговаривала", "тёмный дом"]
    ответы = {refprofile._клаузула(s) for s in строки}
    assert len(ответы) >= 3, f"измеритель не различает клаузулы: {ответы}"


@нет_словаря_рифм
def test_slovar_udareniy_odin_na_proekt():
    """Словарь ударений — ЕДИНСТВЕННЫЙ источник: раньше в проекте жили три
    независимых угадывания, каждое со своей точностью."""
    import wordsuggest
    assert wordsuggest.rhyme_key_of("небо") == "еба"
    assert wordsuggest.rhyme_key_of("дом") == "ом"
    assert wordsuggest.rhyme_key_of("зюмбрлыкает") == ""
