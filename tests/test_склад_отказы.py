# «Документы» без разрешения — обычное дело на новой машине), объявлялся
# ПОВРЕЖДЁННЫМ, и человеку предлагалось «почини или удали вручную». Совет
# указывал на state.json в сотни мегабайт со всеми его книгами.
#
# Послушайся он совета — потерял бы всё, притом что с файлом ничего не
# случилось. Философия проекта — «честные ошибки»; отказ, который врёт о
# причине и подсказывает неверное действие, — её прямая противоположность.
import json
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "core"))
sys.path.insert(0, str(КОРЕНЬ / "core" / "nlsrc"))

from nlsrc.store import NakedLunchStore  # noqa: E402


def _склад(tmp_path, содержимое: str):
    (tmp_path / "state.json").write_text(содержимое, encoding="utf-8")
    return tmp_path


def test_битый_склад_называется_битым(tmp_path):
    """Настоящая порча — прежнее сообщение, слово в слово: сбрасывать такой
    файл молча нельзя, и это правило остаётся."""
    д = _склад(tmp_path, "{это не json")
    with pytest.raises(RuntimeError) as e:
        NakedLunchStore(д)
    assert "повреждён" in str(e.value)
    assert "удали" in str(e.value)


def test_нет_доступа_не_называется_порчей(tmp_path, monkeypatch):
    """ГЛАВНЫЙ СТОРОЖ. Отказ в доступе — своя причина и СВОЙ совет.

    Слова «повреждён» здесь быть не должно вовсе, а «удалять нечего» — должно:
    файл цел, и трогать его нельзя."""
    д = _склад(tmp_path, json.dumps({"corpora": [], "fragments": []}))

    исходный = Path.read_text

    def отказ(self, *a, **k):
        if self.name == "state.json":
            raise PermissionError(13, "Permission denied")
        return исходный(self, *a, **k)

    monkeypatch.setattr(Path, "read_text", отказ)
    with pytest.raises(RuntimeError) as e:
        NakedLunchStore(д)
    текст = str(e.value)
    assert "нет доступа" in текст.lower(), f"причина названа неверно: {текст}"
    assert "повреждён" not in текст, "целый файл назван повреждённым"
    assert "УДАЛЯТЬ ЗДЕСЬ НЕЧЕГО" in текст, "не сказано, что удалять не надо"


def test_прочая_ошибка_ввода_вывода_не_советует_удалять(tmp_path, monkeypatch):
    """Диск отключили, файл занят — файл при этом цел. Совета удалять быть не
    должно; должно быть предложение сперва проверить, что он открывается."""
    д = _склад(tmp_path, json.dumps({"corpora": [], "fragments": []}))
    исходный = Path.read_text

    def отказ(self, *a, **k):
        if self.name == "state.json":
            raise OSError(5, "Input/output error")
        return исходный(self, *a, **k)

    monkeypatch.setattr(Path, "read_text", отказ)
    with pytest.raises(RuntimeError) as e:
        NakedLunchStore(д)
    текст = str(e.value)
    assert "не читается" in текст
    assert "повреждён" not in текст
    assert "прежде чем что-то" in текст


# ── ЖИВОЙ СЕРВЕР С ОШИБКОЙ — НЕ МЁРТВОЕ ЯДРО ────────────────────────────────
#
# ЧТО БЫЛО (разбор 2026-09-02). `statusTick` ловил ЛЮБУЮ неудачу опроса и после
# трёх подряд поднимал панель «ядро не отвечает · закрой и открой заново».
# Пятисотая от РАБОТАЮЩЕГО сервера попадала туда же: человек закрывал и
# открывал программу, ничего не менялось — причина лежала в коде на диске.
# Хуже того, кнопка «скопировать отчёт» на той панели копирует местный журнал
# окна, куда эту ошибку никто не писал: отчёт уходил пустым.
#
# Единственная неисправность, которую программа умеет назвать ТОЧНО, доходила
# до владельца как бесполезный совет. Проверяется чтением исходников: сборка
# зелёная и при разрыве.

def _нл(имя: str) -> str:
    return (КОРЕНЬ / "interface" / "react-app" / "src" / "nl" / имя).read_text("utf-8")


def test_ответ_сервера_помечается_живым():
    """`api.req` обязан отличать ответ сервера от его отсутствия."""
    src = _нл("api.js")
    н = src.find("if (!res.ok || (data && data.error))")
    assert н > 0, "не найдено место, где бросается ошибка ответа"
    кусок = src[н:н + 700]
    assert "живой" in кусок, (
        "ошибка ответа не помечена: вызывающий не отличит «ядро умерло» от "
        "«ядро живо, но в коде ошибка»")


def test_опрос_не_хоронит_живой_сервер():
    """`statusTick` не смеет поднимать панель смерти, когда сервер ответил."""
    src = _нл("methods.corpus.js")
    н = src.find("async statusTick()")
    assert н > 0
    кусок = src[н:н + 4000]
    assert "e.живой" in кусок, (
        "statusTick не проверяет, ответил ли сервер, — пятисотая от живого "
        "ядра снова будет показана как его смерть")
    # и настоящая причина обязана попасть в журнал окна: иначе кнопка
    # «скопировать отчёт» копирует пустоту
    assert "__журналОкна" in кусок, (
        "причина не пишется в журнал окна — отчёт уйдёт пустым")
