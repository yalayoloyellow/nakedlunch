#
# Принята в трактовке, разобранной с владельцем: это НЕ второй движок
# компоновки, а ПОСТАВЩИК КРУТИЛОК ЗВЕНЬЕВ — тот же слот, куда садится
# референс. Поэтому и проверяется в первую очередь СОВМЕСТИМОСТЬ ФОРМЫ: если
# ответ кривой перестанет быть тем же, что у референса, фронт разберёт его
# наполовину и молча.
#
# Ось одна и называется плотность: к припеву плотнее (строки цепляются,
# лексика обычнее), к бриджу реже. Четыре независимых кривых по крутилкам
# владелец не смог бы ни услышать по отдельности, ни объяснить себе.
#
# Прогон: .venv/bin/python -m pytest tests/test_curve.py -q

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))

import clean
import curve
import refprofile


# ---- форма ответа: тот же слот, что у референса ----------------------------

def test_forma_otveta_ta_zhe_chto_u_referensa():
    """ГЛАВНОЕ. Фронт кладёт ответ в тот же слот и разбирает тем же
    резолвером. Разойдись формы — половина полей молча не доехала бы."""
    к = curve.цепочка(3)["chain"][0]
    проф = {"частей": 1, "строк": 2, "точность": 0.5, "стыки": [],
            "части": [{"строк": 2, "схема": "аа", "слогов": 8.0, "разброс": 1.0,
                       "клаузула": 0, "связность": 0.3, "мат": 0.0}]}
    р = refprofile.цепочка(проф, 1.0)["chain"][0]
    assert set(к) <= set(р), f"кривая отдаёт поля, которых нет у референса: {set(к) - set(р)}"
    assert к["mode"] == р["mode"] == clean.MODE_ALGO


def test_krivaya_ne_zadayot_karkas():
    """Спеки нет НАМЕРЕННО: каркас остаётся тот, что владелец выбрал у звена.
    `linkSpec` при отсутствии спеки честно падает на форму строфы."""
    for з in curve.цепочка(4)["chain"]:
        assert "spec" not in з


def test_krivaya_ne_trogaet_styki():
    """Чем строфы склеены — отдельное решение владельца. Молча переписать их
    значило бы менять песню там, где просили менять плотность."""
    assert "junctions" not in curve.цепочка(4)


def test_krutilki_prohodyat_perevodchik():
    """Что кривая отдала — то ядро и получит: проверяем РЕЗУЛЬТАТ перевода, а
    не наличие ключей."""
    з = curve.цепочка(3, "нарастание", 1.0)["chain"]
    низ = clean.knobs_from_profile({"name": "к", "mode": з[0]["mode"], "params": з[0]["params"]})
    верх = clean.knobs_from_profile({"name": "к", "mode": з[2]["mode"], "params": з[2]["params"]})
    assert низ["flow"] < верх["flow"], "связность обязана расти"
    # Раунд 58: шкала прямая и двусторонняя, меньше = банальнее. К припеву
    # (плотнее) лексика обязана становиться ОБЫЧНЕЕ, то есть значение падать.
    assert низ["banality"] > верх["banality"]


# ---- сами формы ------------------------------------------------------------

def test_narastanie_i_spad_zerkalny():
    р = curve.плотность(5, "нарастание", 1.0)
    с = curve.плотность(5, "спад", 1.0)
    assert р == sorted(р) and р[0] < р[-1]
    assert с == list(reversed(р))


def test_proval_eto_ne_perevyornutaya_volna():
    """У волны один подъём и один спад, у провала края высокие, середина
    низкая. Для песни это разные вещи: «бридж проседает» и «второй куплет
    тише» звучат по-разному."""
    в = curve.плотность(5, "волна", 1.0)
    п = curve.плотность(5, "провал", 1.0)
    assert п[0] == max(п) and п[-1] == max(п) and п[len(п) // 2] == min(п)
    assert в != п and в != list(reversed(п))


def test_sila_nol_daet_rovnuyu_cepochku():
    """Сила 0 — это «формы нет», а не «форма с краю»: кривая качает ОТ
    середины, поэтому ноль оставляет всё ровным."""
    р = curve.плотность(6, "волна", 0.0)
    assert len(set(р)) == 1 and р[0] == curve.СЕРЕДИНА


@pytest.mark.parametrize("форма", curve.ФОРМЫ)
def test_lyubaya_forma_derzhitsya_v_shkale(форма):
    for сила in (0.0, 0.3, 1.0):
        assert all(0.0 <= v <= 1.0 for v in curve.плотность(9, форма, сила))


def test_odno_zveno_seredina_a_ne_kray():
    """Одиночная строфа — это цепочка из одного звена, и формы у неё нет по
    определению: вести нечего. Край здесь означал бы, что одиночная генерация
    молча уехала в крайние настройки."""
    assert curve.плотность(1, "нарастание", 1.0) == [curve.СЕРЕДИНА]
    assert curve.плотность(1, "спад", 1.0) == [curve.СЕРЕДИНА]


def test_pustaya_cepochka_nichego_ne_pridumyvaet():
    assert curve.плотность(0) == []
    assert curve.цепочка(0)["chain"] == []


def test_chuzhaya_forma_ne_padaet_a_beryot_pervuyu():
    """Имя формы приходит из браузера. Падать из-за опечатки в необязательном
    поле — хуже, чем взять названную первой.

    Решение об этом живёт в ОДНОМ месте — `_форма`. Сначала такой же выбор
    стоял и в `плотность`, и мутационная проверка показала, что второй
    экземпляр ничего не сторожит: его сняли, и ни один тест не заметил."""
    assert curve.плотность(4, "чушь", 1.0) == curve.плотность(4, curve.ФОРМЫ[0], 1.0)


def test_sila_klampitsya():
    assert curve.плотность(4, "нарастание", 99) == curve.плотность(4, "нарастание", 1.0)
    assert curve.плотность(4, "нарастание", -5) == curve.плотность(4, "нарастание", 0.0)


def test_banalnost_vedyotsya_v_polose_a_ne_do_upora():
    """Края шкалы банальности — уже не форма, а ВОРОТА: на нуле потолок самый
    строгий, и одно звено песни молча осталось бы без кандидатов, а владелец
    увидел бы «пусто на звене» вместо задуманной формы.

    Живая проверка так и показала: «нарастание» на полной силе давало первому
    звену Банальность 0.0."""
    з = curve.цепочка(6, "нарастание", 1.0)["chain"]
    б = [x["params"]["Банальность"] for x in з]
    низ, верх = curve.БАНАЛЬНОСТЬ_ПОЛОСА
    assert min(б) == низ and max(б) == верх, б
    # УБЫВАЕТ, а не растёт (Раунд 58): «нарастание» ведёт к припеву, у припева
    # лексика обычнее, а по новой двусторонней шкале обычнее — это МЕНЬШЕ.
    # Форма сохранена: монотонность та же, направление шкалы под ней другое.
    assert б == sorted(б, reverse=True), "форма обязана сохраниться внутри полосы"


def test_svyaznost_ne_zhmyotsya():
    """Это цель ранжира, а не отсев: ноль значит «соседние строки максимально
    не связаны» — законное звучание для бриджа, и запрещать его было бы
    решением за владельца."""
    з = curve.цепочка(6, "нарастание", 1.0)["chain"]
    с = [x["params"]["Связность"] for x in з]
    assert min(с) == 0.0 and max(с) == 1.0, с


def test_polosa_ne_lomaet_seredinu():
    """Сила 0 — ровная цепочка и в полосе тоже: середина полосы, а не край."""
    з = curve.цепочка(4, "волна", 0.0)["chain"]
    б = {x["params"]["Банальность"] for x in з}
    assert len(б) == 1
    низ, верх = curve.БАНАЛЬНОСТЬ_ПОЛОСА
    assert abs(б.pop() - (низ + верх) / 2) < 1e-6
