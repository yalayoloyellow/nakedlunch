def test_пресетов_немного_и_они_названы():
    """Замер: из 103 наборов крутилок в 822 живых прогонах различимых на слух
    двадцать. Лишний пресет — снова тот выбор, который человек не слышит.

    Состав списком НЕ фиксируем. Так было до 2026-08-18: сторож требовал ровно
    четырёх поимённо и покраснел, когда «Вольная рифма» слилась с «Как всегда»
    (почему слияние верное — в следующей проверке). Сторож, требующий
    конкретного состава, запрещает думать; сторожим границы."""
    имена = [п["name"] for п in пресеты_из_фронта()]
    assert 2 <= len(имена) <= 5, f"пресетов {len(имена)}: {имена}"
    assert len(set(имена)) == len(имена), f"повтор имени: {имена}"
    assert all(и.strip() and и[0].isupper() for и in имена), имена


def test_пресет_не_дублирует_ручку_которая_и_так_на_экране():
    """ПРАВИЛО, КОТОРОЕ ПОЙМАЛО БЫ «ВОЛЬНУЮ РИФМУ» СРАЗУ.

    Она отличалась от «Как всегда» ровно одним числом — точностью рифм. Пока
    точности не было на экране, это было честно: пресет служил ЕДИНСТВЕННЫМ
    способом до неё дотянуться. Как только точность стала отдельными воротами с
    четырьмя названными ярусами, пресет остался кнопкой-дублем: нажать его и
    нажать «созвучие» значило одно и то же, а выглядело двумя решениями.

    Формулировка узкая нарочно. Запрещено не «отличаться одним ключом» вообще —
    запрещено отличаться одним ключом, КОТОРЫЙ И ТАК ВЫСТАВЛЯЕТСЯ ОТДЕЛЬНО.
    Первая версия сторожа была шире и тут же обвинила «Разговор» (он отличается
    одной «Банальностью»), хотя тот — единственный путь к своей половине шкалы:
    ручки банальности на экране нет. Широкий сторож заставляет городить
    исключения, а через два раунда исключения становятся правдой вместо правила.

    Что выставляется отдельно — читаем с САМОГО ЭКРАНА: список рядом разошёлся
    бы с ним при первой же правке."""
    экран = (NL / "render.gen.jsx").read_text("utf-8")
    сами = set(re.findall(r"c\.setKnob\('([^']+)'", экран))
    assert сами, "на экране не нашлось ни одного setKnob — сторож потерял опору"

    пр = [п for п in пресеты_из_фронта() if п["params"]]
    for i in range(len(пр)):
        for j in range(i + 1, len(пр)):
            a, b = пр[i], пр[j]
            разошлись = [к for к in set(a["params"]) | set(b["params"])
                         if abs(a["params"].get(к, 0.0) - b["params"].get(к, 0.0)) > 1e-6]
            if len(разошлись) != 1:
                continue
            ключ = разошлись[0]
            assert ключ not in сами, (
                f"«{a['name']}» и «{b['name']}» отличаются одной «{ключ}», а она и "
                "так выставляется на экране отдельно — значит пресет стал "
                "кнопкой-дублем. Слей их: выбор уже есть у самой ручки.")


def test_пресеты_переводятся_в_ядро_ровно_так_как_замерено():
    """СКВОЗНАЯ ПРОВЕРКА. Числа фронта → `clean.knobs_from_profile` → таблица
    §9.2 замера, выданная production-кодом. Здесь ловится и опечатка во
    фронте, и сдвиг дефолта в ядре: `knobs_from_profile` добивает недостающее
    дефолтами `KNOB_SPEC`, поэтому таблица держит обе стороны разом."""
    ждём = {
        # `rhyme_precision` тут — НЕ значение пресета, а дефолт `KNOB_SPEC`:
        # точность рифм ушла из наборов в отдельные ворота 2026-08-18, и
        # `knobs_from_profile` добивает её сам. Строку оставляем именно затем,
        # чтобы сдвиг дефолта в ядре был виден отсюда.
        #
        # ЗДЕСЬ БЫЛА «ВОЛЬНАЯ РИФМА» (слита 2026-08-18): она отличалась от «Как
        # всегда» ровно одной точностью рифм, и с появлением ярусов на экране
        # стала кнопкой-дублем. Ожидание для неё висело бы мёртвым: цикл ниже
        # идёт по пресетам ФРОНТА, а не по ключам этого словаря, — то есть
        # молча ничего не проверял бы.
        "Как всегда":    {"real_text": 1.0, "classic": 0.0, "rhyme_precision": 0.25, "banality": 0.65},
        "Разговор":      {"real_text": 1.0, "classic": 0.0, "rhyme_precision": 0.25, "banality": 0.30},
        # В классике всё, кроме ворот, ядро игнорирует: `filters.run` уходит в
        # `_run_classic` → `nlindex.select_light`, который не принимает ни
        # ворот, ни тегов, ни слоговой вилки. Значения там стоят потому, что
        # `knobs_from_profile` добивает недостающее дефолтами. Сторожим ровно
        # два числа, которые в этом режиме что-то значат.
        "Классика":      {"real_text": 1.0, "classic": 1.0},
    }
    # общее у всех — ворота на нейтрали и мнения, которых нет на экране
    общее = {"mat_share": -1.0, "clausula": 0, "flow": -1.0, "melody": 0.35,
             "cohesion": 0.3, "repeat": 0, "no_mat": False, "only_mat": False}
    for п in пресеты_из_фронта():
        ядро = clean.knobs_from_profile(п)
        for ключ, знач in {**общее, **ждём[п["name"]]}.items():
            # Числа сверяем с допуском: `cohesion` считается как 1 − Диссонанс,
            # и 1 − 0.7 в двоичной арифметике даёт 0.30000000000000004.
            # Требовать здесь точного равенства значило бы сторожить формат
            # double, а не значение крутилки.
            сошлось = (ядро[ключ] is знач if isinstance(знач, bool)
                       else abs(ядро[ключ] - знач) < 1e-9)
            assert сошлось, f"{п['name']}: {ключ} = {ядро[ключ]}, ждали {знач}"


def test_ворота_не_входят_ни_в_один_пресет():
    """ЕДИНСТВЕННЫЙ МЕХАНИЗМ, которым держится «мат и клаузула не сбрасываются
    при смене пресета»: чего в наборе нет, того `pickПресет` и не
    перезаписывает. Впиши сюда «Мат» с любым значением — и переключатель начнёт
    молча съезжать на каждое нажатие кнопки."""
    # «Точность рифм» добавлена в этот список 2026-08-18: она стала третьими
    # воротами (четыре названных яруса рядом с матом и клаузулой), и на неё
    # распространяется то же правило — пресет её не трогает. В `KNOB_CLASSIC`
    # её нет и быть не должно: тот список про другое — что переживает
    # «Классику», а точность рифм в классике как раз не действует.
    ворота_экрана = tuple(clean.KNOB_CLASSIC) + ('Точность рифм',)
    for п in пресеты_из_фронта():
        for ворота in ворота_экрана:
            assert ворота not in п["params"], \
                f"{п['name']} перезапишет ворота «{ворота}» при выборе пресета"


