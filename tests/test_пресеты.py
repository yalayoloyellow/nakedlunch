def test_мёртвых_ползунков_в_меню_ленты_не_осталось():
    """Приговор замера. Мелодичность не работает НИГДЕ (при Источники 0.5 весь
    ход ручки даёт жаккар 0.904, при Источники ≥ 0.9 — ноль, а это 89.2% его
    прогонов). Источники 0.9 и 1.0 на четверостишии неразличимы. Повтор не
    двигался ни разу. Их ключи в ядре остались — их читают `filters.run` и
    `_select_with_rhyme`, — но на экране ленты их быть не должно.

    Смотрим КОД без комментариев: все надгробия называют убранное поимённо."""
    код = без_комментариев(МЕНЮ.read_text("utf-8"))
    # «Банальность» из списка снята 2026-08-20: она не «убрана с экрана», а
    # УДАЛЕНА ЦЕЛИКОМ, и сторожит её теперь `test_банальности_нет_нигде` ниже —
    # тот проверяет весь фронт и ядро, а не одно меню.
    # «Мелодичность» из списка снята 2026-08-21: удалена целиком, сторожит её
    # test_удалённых_ручек_нет_нигде ниже.
    # «Источники» сняты 2026-08-29 по той же причине: ручка удалена целиком
    # вместе с грамматическим генератором, и её тоже стережёт
    # test_удалённых_ручек_нет_нигде. Список остался из одного имени, и это
    # не ослабление: правило про то, что убранное с экрана не возвращается, —
    # заведут вторую убранную ручку, впишется сюда же.
    for мёртвое in ("Повтор",):
        assert f"'{мёртвое}'" not in код and f'"{мёртвое}"' not in код, \
            f"в меню ленты снова рисуется «{мёртвое}»"


