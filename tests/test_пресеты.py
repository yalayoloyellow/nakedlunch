def test_фристайл_рисует_все_девять_крутилок_из_общих_констант():
    """ГЛАВНАЯ ОПАСНОСТЬ ЭТОЙ ПРАВКИ. `render.fspanels.jsx` строит свою панель
    как `ВОРОТА.concat(МНЕНИЯ)`. Урезать эти списки ради ленты значило бы молча
    переделать и панель фристайла, которую владелец просил не трогать
    дословно: «режим фристайла крутой, пусть остаётся, я его вообще не трогаю».

    Поэтому лента перестала их читать вовсе, а списки остались полными —
    зеркалом `core/clean.py`."""
    полки = без_комментариев(ПОЛКИ.read_text("utf-8"))
    имена = set()
    for имя_списка in ("ВОРОТА", "МНЕНИЯ"):
        m = re.search(rf"export const {имя_списка} = \[(.*?)\];", полки, flags=re.S)
        assert m, f"список {имя_списка} пропал — фристайл рисует панель из него"
        имена |= set(re.findall(r"'([^']+)'", m.group(1)))
    assert имена == set(clean.KNOB_SPEC), \
        f"ВОРОТА+МНЕНИЯ разошлись с core/clean.py: {имена ^ set(clean.KNOB_SPEC)}"
    фс = без_комментариев(ФРИСТАЙЛ.read_text("utf-8"))
    assert "ВОРОТА.concat(МНЕНИЯ)" in фс, "фристайл перестал рисовать все девять"


def test_лента_не_читает_общих_списков_крутилок():
    """Развязка сделана не обещанием, а отсутствием импорта: меню ленты не
    берёт ни `ВОРОТА`, ни `МНЕНИЯ`, ни `В_КЛАССИКЕ`, ни `ШКАЛЫ`. Пока это так,
    любая правка списков не может задеть ленту, а любая правка ленты — панель
    фристайла."""
    код = без_комментариев(МЕНЮ.read_text("utf-8"))
    импорт = re.search(r"import \{(.*?)\} from './methods\.shelves\.js';", код, flags=re.S)
    assert импорт, "меню ленты вообще не берёт ничего из полок — разбор устарел"
    взято = {x.strip() for x in импорт.group(1).split(",") if x.strip()}
    assert not (взято & {"ВОРОТА", "МНЕНИЯ", "В_КЛАССИКЕ", "ШКАЛЫ", "имяКрутилки"}), \
        f"лента снова читает общие списки крутилок: {взято}"


