#
# Что сторожит этот файл. Панель ленты больше не показывает девять крутилок:
# на экране четыре кнопки пресетов, двое ворот и тема (с Диссонансом, когда
# тема заполнена). Значения пресетов зашиты во фронте — `methods.shelves.js`,
# константа `ПРЕСЕТЫ` — и это ТРЕТЬЕ место, где написаны числа крутилок
# (первые два: `core/clean.py: KNOB_SPEC` и `methods.panels.js:
# PARAM_DEFAULTS`). Третье место, написанное числами, всегда разъезжается с
# остальными: на расхождении белых списков проект уже обжигался («Отбор» и
# «Мат» молча не сохранялись месяцами).
#
# Поэтому проверка не «пресеты существуют», а СКВОЗНАЯ: числа из фронта
# прогоняются через тот самый `clean.knobs_from_profile`, который переводит их
# на пути `/api/generate`, и сверяются с таблицей §9.2 замера. Разъедется
# любая сторона — упадёт здесь.
#
# Отдельно сторожится ГЛАВНАЯ ОПАСНОСТЬ этой правки: панель фристайла рисует
# крутилки из ТЕХ ЖЕ констант `ВОРОТА`/`МНЕНИЯ`. Владелец дословно: «режим
# фристайла крутой, пусть остаётся, я его вообще не трогаю». Урежь общий
# список ради ленты — и его панель молча похудеет.
#
# Проверка текстовая: числа живут в JS, сборка зелёная и при расхождении.
#
