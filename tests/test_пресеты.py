def без_комментариев(текст: str) -> str:
    """Код без `//`-строк и без блоков `/* */` (в том числе JSX-комментариев).

    Нужно затем, что все надгробия этой правки НАЗЫВАЮТ убранные крутилки
    поимённо — и наивный поиск «есть ли в файле слово Мелодичность» находил бы
    именно надгробие. Проверять надо код, а не память о нём."""
    текст = re.sub(r"/\*.*?\*/", " ", текст, flags=re.S)
    return "\n".join(s for s in текст.split("\n") if not s.lstrip().startswith("//"))


def пресеты_из_фронта() -> list[dict]:
    """`ПРЕСЕТЫ` из methods.shelves.js как список {name, mode, params}.

    Разбор нарочно тупой и узкий: он читает ровно ту форму, в которой константа
    написана, и падает, если её перепишут иначе. Умный разбор здесь был бы
    хуже — он молча пережил бы переименование ключа и перестал сторожить."""
    код = без_комментариев(ПОЛКИ.read_text("utf-8"))
    m = re.search(r"export const ПРЕСЕТЫ = \[(.*?)\n\];", код, flags=re.S)
    assert m, "константа ПРЕСЕТЫ не найдена — разбор устарел или пресеты снесли"
    тело = m.group(1)
    # РЕЖИМЫ приходят символами (РЕЖИМ_АЛГО/РЕЖИМ_КЛАССИКА) — раскрываем их
    # значениями из ядра, а не своими строками: имя режима это контракт.
    режимы = {"РЕЖИМ_АЛГО": clean.MODE_ALGO, "РЕЖИМ_КЛАССИКА": clean.MODE_CLASSIC}
    из = []
    for кусок in re.finditer(r"\{\s*name:\s*'([^']+)',\s*mode:\s*(\w+),(.*?)params:\s*\{(.*?)\}\s*\},",
                             тело, flags=re.S):
        имя, режим, _, поля = кусок.groups()
        params = {к: float(v) for к, v in re.findall(r"'([^']+)':\s*(-?[\d.]+)", поля)}
        из.append({"name": имя, "mode": режимы[режим], "params": params})
    return из


