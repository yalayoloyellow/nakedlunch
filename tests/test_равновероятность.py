# nakedlunch — кандидаты равновероятны среди подходящих форме.
#
# ЧТО БЫЛО. Кандидаты набирались двумя кучами: `cap` случайных из ВСЕГО пула
# плюс «слоговой резерв» — по ОДНОЙ строке на рифмо-ключ, взятой сортировкой без
# всякого шума. Резерв выходил побитово один и тот же каждый прогон.
#
# ЗАМЕРЕНО на живом индексе: два прогона на РАЗНЫХ сёмнах делили 97.9%
# материала. Случайные 300 тянулись из всего пула, где подходящих по слогам
# 6.1%, то есть менялось ~18 строк — 0.1%. В строках это значило: на каждую
# рифму человек видел одну и ту же строку (пятисложных 41 696 при 6 868 ключах —
# одна из 6.1). Отсюда «разные настройки, а выдача та же»: выдача разная, а
# СЛОВАРЬ один и тот же навсегда.
#
# РЕШЕНИЕ ВЛАДЕЛЬЦА: «равновероятно всё, главный принцип — равновероятность для
# всего. как в классике всё равновероятно, так и тут».
#
# Прогон: .venv/bin/python -m pytest tests/test_равновероятность.py -q

import sys
from pathlib import Path

import numpy as np
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))
import nlindex  # noqa: E402


class _Индекс:
    """Крошечный двойник: отбору нужны только слоги, ключи и список ключей."""

    def __init__(self, syl, key_id, keys):
        self.syl = np.asarray(syl)
        self.key_id = np.asarray(key_id)
        self.keys = keys


def _стенд(групп: int, в_группе: int, слогов: int = 5) -> _Индекс:
    """`групп` рифмо-ключей по `в_группе` строк, плюс пустой ключ под номером 0."""
    keys = [""] + [f"к{i}" for i in range(групп)]
    key_id, syl = [], []
    for g in range(групп):
        key_id += [g + 1] * в_группе
        syl += [слогов] * в_группе
    return _Индекс(syl, key_id, keys)


def _выбор(idx, спец, схема, cap, семя):
    ids = np.arange(len(idx.syl))
    rng = np.random.default_rng(семя)
    return nlindex._равновероятно_по_форме(idx, ids, спец, схема, cap, rng)


# ---- вырожденные данные ----------------------------------------------------

def test_пустая_вилка_и_нулевой_предел_не_роняют():
    idx = _стенд(10, 4)
    assert _выбор(idx, [(5, 5)], "абв", 0, 1) == []
    assert _выбор(idx, [(99, 99)], "абв", 100, 1) == [], "вилка, под которую нет строк"


def test_строки_без_рифмо_ключа_не_берутся():
    """Пустой ключ означает «ударение не проставлено». Такая строка не может
    ни рифмоваться, ни встать в схему — брать её значило бы выдать заведомо
    негодного кандидата."""
    idx = _Индекс(syl=[5, 5, 5], key_id=[0, 0, 1], keys=["", "к"])
    из = _выбор(idx, [(5, 5)], "абв", 10, 1)
    assert из == [2], из


def test_схема_из_одной_буквы_требует_партн_ров():
    """«аааа» — все четыре строки обязаны рифмоваться между собой, значит нужна
    группа минимум из четырёх. Группы поменьше не годятся."""
    idx = _Индекс(syl=[5] * 6, key_id=[1, 1, 1, 1, 2, 2], keys=["", "к1", "к2"])
    из = _выбор(idx, [(5, 5)], "аааа", 100, 1)
    assert set(из) == {0, 1, 2, 3}, f"взята группа не того размера: {из}"


# ---- собственно равновероятность -------------------------------------------

def test_без_рифмы_каждая_строка_равновероятна():
    """Схема без повторяющихся букв — плоский жребий, ровно как в классике.
    Проверяем не «примерно», а по разбросу частот на многих прогонах."""
    idx = _стенд(групп=50, в_группе=4)          # 200 строк
    счёт = np.zeros(200, dtype=int)
    ПРОГОНОВ, CAP = 400, 20
    for семя in range(ПРОГОНОВ):
        for j in _выбор(idx, [(5, 5)], "абв", CAP, семя):
            счёт[j] += 1
    ожидание = ПРОГОНОВ * CAP / 200
    откл = abs(счёт - ожидание).max() / ожидание
    assert счёт.min() > 0, "какая-то строка не выпала ни разу"
    assert откл < 0.45, (
        f"разброс частот {откл:.2f} при ожидании {ожидание:.0f} — выборка не плоская")


def test_с_рифмой_размер_группы_не_даёт_преимущества():
    """ГЛАВНАЯ ПРОВЕРКА для рифмующихся схем. Наивное «случайный ключ, потом
    строки в нём» дало бы строке из группы в 2 штуки шанс в 25 раз выше, чем
    строке из группы в 50. Ключ выбирается ПРОПОРЦИОНАЛЬНО размеру группы,
    поэтому `P = (n/N) × (m/n) = m/N` — размер сокращается."""
    # две маленькие группы по 2 и две большие по 50
    key_id = [1, 1, 2, 2] + [3] * 50 + [4] * 50
    idx = _Индекс(syl=[5] * len(key_id), key_id=key_id, keys=["", "к1", "к2", "к3", "к4"])
    счёт = np.zeros(len(key_id), dtype=int)
    ПРОГОНОВ, CAP = 600, 4
    for семя in range(ПРОГОНОВ):
        for j in _выбор(idx, [(5, 5)], "абаб", CAP, семя):
            счёт[j] += 1
    малые = счёт[:4].mean()
    большие = счёт[4:].mean()
    отношение = малые / большие if большие else float("inf")
    assert 0.6 < отношение < 1.6, (
        f"строка из малой группы выпадает в {отношение:.2f} раза чаще — "
        "ключ выбирается не пропорционально размеру группы")


def test_две_сёмны_дают_разный_материал():
    """Сторож на саму болезнь. Раньше два прогона на разных сёмнах делили 97.9%
    материала; теперь пересечение обязано быть близко к теоретическому для двух
    независимых выборок — cap/N."""
    idx = _стенд(групп=500, в_группе=4)          # 2000 строк
    CAP = 200
    a = set(_выбор(idx, [(5, 5)], "абв", CAP, 11))
    b = set(_выбор(idx, [(5, 5)], "абв", CAP, 22))
    доля = len(a & b) / CAP
    ожидание = CAP / 2000                        # 10%
    assert доля < 0.35, f"пересечение {доля:.0%} — материал всё ещё заморожен"
    assert abs(доля - ожидание) < 0.15, (
        f"пересечение {доля:.0%} против ожидаемых {ожидание:.0%} — выборка не независима")
