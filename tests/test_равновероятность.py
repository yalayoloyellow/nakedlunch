# ---- прямая тяга: без пачки кандидатов вообще -------------------------------

from опора import нужен_большой_индекс  # noqa: E402


def _боевой():
    from pathlib import Path
    return nlindex.Index(Path("core/data/nl_index"))


@нужен_большой_индекс
def test_тяга_даёт_ровно_нужное_и_по_форме():
    """Прямая тяга разворачивает в строку ТОЛЬКО выбранное. Ни пачки, ни
    перебора: если она вернула девять строк, значит материализовано девять."""
    idx = _боевой()
    ids = np.flatnonzero(idx.gate_mask(False, False, 0))
    спец = [(5, 5), (7, 7), (5, 5)]
    строки = nlindex.тянуть_строфы(idx, ids, спец, "абв", 9,
                                   np.random.default_rng(1), счёт={})
    assert len(строки) == 9
    гласные = "аеёиоуыэюяАЕЁИОУЫЭЮЯ"
    for i, r in enumerate(строки):
        lo, hi = спец[i % 3]
        слогов = sum(1 for ch in r["text"] if ch in гласные)
        assert lo <= слогов <= hi, f"{слогов} слогов вместо {lo}–{hi}: {r['text']!r}"


@нужен_большой_индекс
def test_тяга_держит_рифму_и_не_повторяет():
    """Схема, запрет дубля по тексту и запрет общего слова — всё это тяга
    проверяет ПОСЛЕ выбора, поэтому набирать кучу заранее незачем."""
    idx = _боевой()
    ids = np.flatnonzero(idx.gate_mask(False, False, 0))
    for семя in range(12):
        строки = nlindex.тянуть_строфы(idx, ids, [(8, 9)] * 4, "абаб", 4,
                                       np.random.default_rng(семя), счёт={})
        assert len(строки) == 4, f"строфа не собралась на семени {семя}"
        а = {(строки[0]["rhyme"] or "")[:3], (строки[2]["rhyme"] or "")[:3]}
        б = {(строки[1]["rhyme"] or "")[:3], (строки[3]["rhyme"] or "")[:3]}
        assert len(а) == 1 and len(б) == 1, f"схема сломана на семени {семя}"
        тексты = [r["text"] for r in строки]
        assert len(set(тексты)) == 4, "одна и та же строка дважды в строфе"


def test_тяга_не_повторяет_строку_ЧЕРЕЗ_ГРАНИЦУ_БЛОКА():
    """ВТОРАЯ ПОЛОВИНА ТОГО ЖЕ ДЕФЕКТА (2026-08-25).

    Множество взятых текстов заводилось ВНУТРИ цикла по блокам, а блок — это
    длина схемы. У «аб» он равен двум, и в строфе на тридцать строк запрет
    обнулялся пятнадцать раз.

    На рабочих рабочих строфах (три-четыре строки) это не всплывало: блок
    совпадал со строфой. Замер на узкой вилке в 776 строк:

        «аб» × 30 строк   без правки 10 строф с дублем из 40 → с правкой 0
        «а»  × 40 строк              22 из 40, 33 лишних     → 0
        «абв» × 24 строки             4 из 40                → 0

    Докстринг `тянуть_строфы` обещал «тот же текст в строфе дважды — запрещён
    ВСЕГДА»: обещание было, исполнения не было."""
    idx = _боевой()
    ids = np.flatnonzero(idx.gate_mask(False, False, 0))
    for схема, длина in (("аб", 30), ("а", 40)):
        for семя in range(12):
            строки = nlindex.тянуть_строфы(idx, ids, [(2, 2)] * длина, схема, длина,
                                           np.random.default_rng(семя), счёт={})
            тексты = [r["text"] for r in строки]
            assert len(тексты) == len(set(тексты)), (
                f"дубль в строфе «{схема}» × {длина} на семени {семя}: "
                f"{[т for т in тексты if тексты.count(т) > 1][:2]}")


def test_развилка_прямой_тяги_требует_формы_и_не_знает_исключений():
    """СТОРОЖ НА РАЗВИЛКУ. Читаем условие ТЕКСТОМ: поведенческий тест на каждую
    ветку потребовал бы поднимать разные сценарии, а свойство здесь — СОСТАВ
    условия.

    ЧТО СТЕРЕЖЁТ СЕГОДНЯ. Тяга требует ровно трёх вещей — колоночный индекс,
    слоговую вилку и схему рифмы. Пропадёт любая — тяга включится там, где ей
    нечего тянуть (без вилки не из чего выбирать форму, без схемы нечем держать
    рифму), и молча отдаст строфу не той формы.

    ПОЧЕМУ БОЛЬШЕ НЕТ СПИСКА ИСКЛЮЧЕНИЙ (звался
    `test_развилка_прямой_тяги_называет_ровно_свои_исключения`). Раньше тяга
    была ВТОРЫМ путём рядом со сборщиком `_select_with_rhyme` и уступала ему
    четыре обязанности, которых не несла: связность (снята 2026-08-21),
    обязательное слово, тематический якорь и подмешивание строк генератора
    (`nl_mix`). Все четыре механизма вырезаны 2026-08-29 вместе со сборщиком —
    путь остался ОДИН, и уступать стало некому. Список проверяется теперь
    наоборот: ни одно из четырёх имён не имеет права вернуться в условие, иначе
    развилка ссылалась бы на несуществующую ветку."""
    from pathlib import Path
    src = (Path(__file__).resolve().parent.parent / "core" / "filters.py").read_text("utf-8")
    i = src.index("_прямая_тяга = bool(")
    условие = src[i:src.index("\n", i)]
    for что, зачем in (("_idx", "колоночный индекс"),
                       ("syllable_spec", "слоговая вилка"),
                       ("rhyme", "схема рифмы")):
        assert что in условие, (
            f"из условия прямой тяги пропало требование «{зачем}» ({что}) — "
            f"тяга включится там, где ей нечего тянуть: {условие!r}")
    for что in ("flow", "forced", "use_theme_anchor", "nl_mix"):
        assert что not in условие, (
            f"в условии прямой тяги снова стоит «{что}» — механизм вырезан, "
            "значит развилка уводит в ветку, которой нет")
