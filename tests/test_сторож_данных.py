# ЧТО СЛУЧИЛОСЬ. `tests/conftest.py` заведён затем, чтобы ни один тест не
# изменил `data/` и `core/data/` пользователя. 2026-08-18 запись в живой
# `data/corpus.json` всё-таки произошла — а сторож промолчал.
#
# ПРИЧИНА НЕ В ЗАБЫВЧИВОСТИ, А ВО ВРЕМЕНИ. Сторож снимает отпечаток до теста и
# сверяет СРАЗУ после его тела. Запись же приходила из ФОНОВОГО ПОТОКА
# (`nl-warm`, `daemon=True`), заведённого импортом `api/server.py`: поток живёт
# своей жизнью и доходит до диска через доли секунды — то есть уже после
# сверки. Сторож, который проверяет раньше, чем происходит запись, — украшение,
# а не сторож.
#
# ЗДЕСЬ ДЫРА СНАЧАЛА ВОСПРОИЗВОДИТСЯ, И ТОЛЬКО ПОТОМ ЧИНИТСЯ. Непроверенная
# дыра — предположение; проверенная — находка. Проверяем на ВРЕМЕННОМ каталоге
# тем же механизмом, которым сторож смотрит на боевой: настоящие данные для
# этого трогать не нужно и нельзя.

from __future__ import annotations

import threading
import time
from pathlib import Path

import conftest


def _снимок(каталог: Path) -> dict:
    """Тот же отпечаток, что снимает сторож, но по указанному каталогу."""
    снимок = {}
    for п in каталог.rglob("*"):
        try:
            с = п.lstat()
        except OSError:
            continue
        снимок[str(п)] = (с.st_size, с.st_mtime_ns)
    return снимок


def _отложенная_запись(файл: Path, задержка: float) -> threading.Thread:
    """Демон, который пишет НЕ СРАЗУ — ровно так ведёт себя `nl-warm`."""
    def работа():
        time.sleep(задержка)
        файл.write_text("запись из фонового потока", "utf-8")
    т = threading.Thread(target=работа, name="nl-warm", daemon=True)
    т.start()
    return т


def test_дыра_воспроизводится_отложенная_запись_проходит_мимо(tmp_path):
    """ВОСПРОИЗВЕДЕНИЕ. Сверка сразу после тела теста НЕ ВИДИТ записи, которая
    случится через мгновение. Это и есть та дыра, через которую в живой
    `data/corpus.json` попала чужая запись."""
    (tmp_path / "data").mkdir()
    цель = tmp_path / "data" / "corpus.json"
    цель.write_text("исходное", "utf-8")

    до = _снимок(tmp_path)
    поток = _отложенная_запись(цель, 0.3)
    после_наивно = _снимок(tmp_path)          # ровно то, что делает сторож сегодня

    assert после_наивно == до, (
        "отложенная запись успела до сверки — подними задержку, иначе "
        "воспроизведение ничего не доказывает")

    поток.join(10)
    после_честно = _снимок(tmp_path)
    assert после_честно != до, "поток так и не записал — проверка бессмысленна"


def test_ожидание_потоков_дыру_закрывает(tmp_path):
    """ПОЧИНКА. Если перед сверкой дождаться потоков, заведённых САМИМ тестом,
    отложенная запись становится видна."""
    (tmp_path / "data").mkdir()
    цель = tmp_path / "data" / "corpus.json"
    цель.write_text("исходное", "utf-8")

    потоки_до = set(threading.enumerate())
    до = _снимок(tmp_path)
    _отложенная_запись(цель, 0.3)

    conftest._дождаться_новых_потоков(потоки_до)
    после = _снимок(tmp_path)
    assert после != до, (
        "сторож всё ещё не видит отложенную запись — значит "
        "`_дождаться_новых_потоков` не дожидается фоновых потоков теста")


def test_ожидание_не_ждёт_чужих_потоков():
    """Ждать надо ТОЛЬКО то, что завёл сам тест. Иначе поток, живший до него
    (pytest, драйверы, чужие демоны), задержал бы прогон на весь предел."""
    вечный = threading.Event()
    долгий = threading.Thread(target=вечный.wait, name="чужой-долгий", daemon=True)
    долгий.start()
    try:
        потоки_до = set(threading.enumerate())      # долгий уже здесь — он «чужой»
        t = time.perf_counter()
        conftest._дождаться_новых_потоков(потоки_до)
        прошло = time.perf_counter() - t
        assert прошло < 1.0, f"ожидание задержало прогон на {прошло:.1f} с"
    finally:
        вечный.set()
        долгий.join(5)


def test_ожидание_на_пустом_месте_ничего_не_стоит():
    """Цена сторожа на обычном тесте — он платится 426 раз за прогон."""
    потоки_до = set(threading.enumerate())
    t = time.perf_counter()
    for _ in range(100):
        conftest._дождаться_новых_потоков(потоки_до)
    мс = (time.perf_counter() - t) * 1000 / 100
    assert мс < 1.0, f"ожидание стоит {мс:.3f} мс на тест — это заметно на прогоне"
