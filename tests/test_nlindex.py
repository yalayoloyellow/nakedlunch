@нет_индекса
def test_гейты_режут_ровно_по_предикатам():
    в = nlindex.Ворота(слова_верх=4.875)
    m = ИНДЕКС.gate_mask(в, True)
    b, t, mt = (np.asarray(x) for x in (ИНДЕКС.banal, ИНДЕКС.taut, ИНДЕКС.mat))
    # Раунд 51: к предикатам добавились ВОРОТА ЦЕЛОСТНОСТИ — фрагмент не должен
    # быть обрывком дефисного слова. Нарезчик годами резал «какая-нибудь»
    # пополам, и обрывки безупречны по слогам и клаузуле, поэтому отбор их
    # любил, а на слух это мусор.
    # Раунд 57: и ВОРОТА ПО ЗНАМЕНАТЕЛЬНЫМ СЛОВАМ — строка обязана иметь их не
    # меньше двух. «Г-ЖА ДЕ СЕНТ-АНЖ. — Я» проходила всё вышеперечисленное
    # честно: не клише, не тавтология, не мат, слово целое. Она не стих, а
    # ремарка, и отличается именно этим.
    ждём = (b <= 4.875) & (t == 0) & (mt == 0) & ИНДЕКС.whole_mask()
    if getattr(ИНДЕКС, "content", None) is not None:
        import nlindex as _ni
        ждём = ждём & (np.asarray(ИНДЕКС.content) >= _ni.СЛОВ_МИН)
    # Раунд 57: и ЧЁРНЫЙ СПИСОК — правила пользователя убирают строки из выдачи
    # навсегда. Сторож обязан учитывать его, иначе он станет падать на всякий
    # непустой список, то есть ровно тогда, когда пользователь им пользуется.
    з = nlindex.запрет(nlindex._правила())
    if з["маска"] is not None:
        ждём = ждём & ~з["маска"]
    assert np.array_equal(m, ждём)
    # без фильтра мата выживших не меньше
    assert int(ИНДЕКС.gate_mask(в, False).sum()) >= int(m.sum())


@нет_индекса
def test_vorota_celostnosti_otsevayut_obryvki():
    """РЕЗУЛЬТАТ, а не наличие маски: обрывок обязан быть отсеян, а целая
    строка с дефисом внутри — пройти."""
    цел = ИНДЕКС.whole_mask()
    отсеяно = int((~цел).sum())
    # Порог поднят с 5% до 25% (Раунд 58) — и это не смягчение, а расширение
    # правила. Ворота целостности ловили ТОЛЬКО обрывки дефисных слов (1.3%);
    # теперь они ловят и оборванные фразы — строку, кончающуюся словом, которому
    # нечего присоединять. Замер: 399 390 строк, 16.4% корпуса.
    assert 0 < отсеяно < ИНДЕКС.n * 0.25, f"отсеяно {отсеяно} — не похоже на брак нарезки"
    # Ни один отсеянный не должен быть целой фразой. Спрашиваем МОДУЛЬ, а не
    # свою копию правила: здесь стояла переписанная руками регулярка, и когда
    # правило расширилось, тест начал проверять прошлогоднее (Раунд 58).
    битые = [ИНДЕКС.text(int(i)) for i in np.flatnonzero(~цел)[:200]]
    обрыв = lambda t: bool(nlindex.Index._оборвана(t) or nlindex.Index._ОБРЫВОК_НАЧАЛО.match(t))
    assert all(обрыв(t) for t in битые), "в отсев попало что-то целое"
    # и наоборот: слово с дефисом ВНУТРИ фразы отсеиваться не должно
    целые = [ИНДЕКС.text(int(i)) for i in np.flatnonzero(цел)[:5000]]
    сдефисом = [t for t in целые if "-" in t]
    assert сдефисом, "в корпусе обязаны быть целые фразы с дефисом"


