# ОБОРВАННАЯ ФРАЗА (Раунд 58). В выдаче на максимальной свежести встречалось: «в этих сладостных битвах... В», «чтобы всё познать. Я не»,
# «моих криков: О». Строка кончается словом, которому нечего присоединять.
#
# Почему это лезло ИМЕННО в свежую выдачу: целая русская фраза почти всегда
# содержит затасканное сочетание, а обрубок — нет, и по обеим осям ручки он
# выглядит свежим. То есть верхний край «Банальности» ОТБИРАЛ обрывки.
#
# Проверка чистая, без индекса: правило — свойство строки, а не корпуса.

def test_oborvannaya_fraza_ne_prohodit():
    о = nlindex.Index._оборвана
    for t in ["в этих сладостных битвах... В", "чтобы всё познать. Я не",
              "моих криков: О", "я слышу? Стучат. Кто же", "верят до сих пор в",
              "нас в данном случае не",
              "имеет то же", "разъясняют, но", "к чему-то и", "а также то",
              "смотрел на", "пришёл с", "думал про", "ждал у",
              # поймано живой генерацией: «вряд» без «ли» не существует
              "меч правосудия, вряд"]:
        assert о(t), f"обрыв не пойман: {t!r}"


def test_zakonnyy_konec_frazy_zhivyot():
    """Список закрытый: слова, которыми фраза кончается ЗАКОННО, не трогаем.

    «мало» и «какой» выброшены пользователем ещё в Раунде 51 — ими фраза
    кончается по-русски («и всё мало», «Воздух-то какой»). Сомнительные
    союзы («однако», «хотя», «словно») в список не вошли по той же причине."""
    о = nlindex.Index._оборвана
    for t in ["и всё мало", "Воздух-то какой", "короткий вдох", "моим чередом",
              "о плодах любви", "и снова длинное невыносимое молчание",
              "не тот ли садовник лет", "из-за угла", "он пришёл, однако",
              "прежнему плохо",
              # расширенная выборка вернула эти три в законные окончания
              "Пусть будет так", "Именно так", "не такой уж"]:
        assert not о(t), f"законный конец назван обрывом: {t!r}"


@нет_индекса
def test_obryvki_ne_dozhivayut_do_svezhey_vydachi():
    """Та же проверка на живом корпусе и на той самой ручке, с которой пришла
    жалоба: ни одна строка выдачи не смеет кончаться висящим словом."""
    idx = ИНДЕКС
    m = idx.gate_mask(nlindex.ворота_банальности(0.95, idx), no_mat=False)
    выжившие = np.flatnonzero(m)
    rng = np.random.default_rng(11)
    проба = rng.choice(выжившие, size=min(3000, len(выжившие)), replace=False)
    плохие = [idx.text(int(i)) for i in проба if nlindex.Index._оборвана(idx.text(int(i)))]
    assert not плохие, f"обрывки дожили до выдачи: {плохие[:5]}"
