# правил), ворота режут ровно по своим предикатам, обрывки не доживают до
# выдачи, кэш подготовки невидим, а прогрев греет то, что зовёт генерация.
# Плюс защита версии правил: индекс, испечённый по другим правилам, читать
# нельзя, и загрузчик обязан честно вернуть None.
#
# НАДГРОБИЕ 2026-08-29: ЧЕТЫРЕ СТОРОЖА ТЕМЫ СНЯТЫ ВМЕСТЕ С НЕЙ.
#
# Тема вырезана из ядра целиком (решение владельца), и с нею — оба метода
# `Index`, на которых эти тесты стояли: `relevance` (среднее косинусов лемм к
# вектору темы) и `pctl` (ранг стабильной сортировки, делённый на n−1). Ни
# один из четырёх нельзя переписать «на живое»: у них нет живого — считалась
# ИМЕННО близость к теме.
#   · `test_релевантность_совпадает_с_поштучной` — векторное среднее по
#     колонкам обязано совпасть с поштучной `embeddings.relevance` старого
