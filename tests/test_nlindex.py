# nakedlunch — колоночный индекс корпуса (core/nlindex.py, печёт
# tools/build_nl_index.py). Полная сверка старого и нового пути идёт по
# полному пулу и стоит минуты — она разовая, её числа в DECISIONS.md
# (Раунд 31, шаг 1: 0 расхождений из 1 761 809 строк). Здесь — быстрые тесты
# на ТРИ места, где ошибка была бы семантической и тихой:
#   1) релевантность: среднее по УНИКАЛЬНЫМ леммам в словаре navec;
#   2) перцентиль: ранг стабильной сортировки, делённый на n−1;
#   3) запечённые флаги клише и мата совпадают с пересчётом по тексту —
#      то есть индекс не устарел относительно правил.
# Плюс защита версии правил: индекс, испечённый по другим правилам, читать
# нельзя, и загрузчик обязан честно вернуть None.
#
# Прогон: .venv/bin/python -m pytest tests/test_nlindex.py -q

