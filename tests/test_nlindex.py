# полному пулу и стоит минуты — она разовая, её числа в DECISIONS.md
# (Раунд 31, шаг 1: 0 расхождений из 1 761 809 строк). Здесь — быстрые тесты
# на места, где ошибка была бы семантической и тихой: запечённый флаг мата
