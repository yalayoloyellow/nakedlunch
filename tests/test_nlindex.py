@нет_индекса
def test_классика_не_судит_о_качестве():
    """Главное отличие «классики» от строгого яруса: extendo НЕ высказывает
    мнения о качестве. Банальные, тавтологичные и клишированные фрагменты
    обязаны проходить — иначе крутилка теряет весь смысл."""
    строгие = int(ИНДЕКС.gate_mask(True).sum())
    все = ИНДЕКС.n
    assert все - строгие > 0, "на этом корпусе нечего проверять"
    строки, выжило, _ = nlindex.select_light(
        ИНДЕКС, pool_mask=np.ones(все, dtype=bool),
        hidden_mask=np.zeros(все, dtype=bool), no_mat=False, only_mat=False, cap=50, seed=1)
    # Раунд 51: классика подчиняется ВОРОТАМ, и целостность — ворота, а не
    # мнение о качестве: обрывок дефисного слова это брак нарезки.
    # Раунд 59: и чёрный список — это тоже не мнение о качестве, а сказанное
    # вслух «мне такого не надо», ровно как доля мата рядом.
    ждём = ИНДЕКС.whole_mask().copy()
    з = nlindex.запрет(nlindex._правила())
    if з["маска"] is not None:
        ждём &= ~з["маска"]
    assert выжило == int(ждём.sum()), \
        "без истории и мата отсеиваются только обрывки и запрещённое"
    # 0.75, а не 0.9 (Раунд 58): ворота целостности теперь режут и оборванные
    # фразы — 16.4% корпуса. Смысл сторожа тот же: классика обязана оставлять
    # ПОДАВЛЯЮЩУЮ часть пула, потому что мнений о качестве она не высказывает.
    assert выжило > все * 0.75, "ворота целостности не должны выкашивать пул"
    assert len(строки) == 50


@нет_индекса
def test_классика_равномерно_случайна():
    """Раунд 35: «классика» = изначальный нейкедланч, то есть rng.sample по
    пулу. Значит оценка у всех одна (сортировать нечем), а два прогона с
    разными зёрнами обязаны дать разные выборки — иначе это не случайность,
    а верхушка какого-то скрытого рейтинга."""
    пул = np.ones(ИНДЕКС.n, dtype=bool)
    пусто = np.zeros(ИНДЕКС.n, dtype=bool)
    a, _, _ = nlindex.select_light(ИНДЕКС, pool_mask=пул, hidden_mask=пусто,
                                no_mat=False, only_mat=False, cap=40, seed=1)
    b, _, _ = nlindex.select_light(ИНДЕКС, pool_mask=пул, hidden_mask=пусто,
                                no_mat=False, only_mat=False, cap=40, seed=2)
    assert all(abs(r["score"] - 0.6) < 1e-9 for r in a), "оценка обязана быть плоской"
    assert {r["text"] for r in a} != {r["text"] for r in b}
    # то же зерно — та же выборка (воспроизводимость важнее «побольше хаоса»)
    c, _, _ = nlindex.select_light(ИНДЕКС, pool_mask=пул, hidden_mask=пусто,
                                no_mat=False, only_mat=False, cap=40, seed=1)
    assert [r["text"] for r in a] == [r["text"] for r in c]


@нет_индекса
def test_классика_помечена_своим_ярусом():
    """Строка обязана НЕСТИ на себе, каким ярусом она собрана.

    ПРЕЖНИМ ПРИЗНАКОМ БЫЛ `_pctl` (2026-08-29 — сторож переписан). По его
    наличию `_select_with_rhyme` отличал алгоритмическую строку от
    классической, чтобы не поставить классику тематическим якорем. Ни сборщика,
    ни якоря, ни темы больше нет, и отсутствие `_pctl` у классики перестало
    что-либо значить: служебное поле всё равно снимается перед ответом на обоих
    путях (`filters._run` и `_run_classic` делают `pop`).

    Живой признак — `classic`, и он в форме ответа нарочно, «чтобы разбирающему
    не приходилось гадать, какой ярус перед ним». Поэтому спрашиваем ОБА пути:
    флаг-константа прошла бы одностороннюю проверку и не различала бы ничего."""
    пул = np.ones(ИНДЕКС.n, dtype=bool)
    пусто = np.zeros(ИНДЕКС.n, dtype=bool)
    классика, _, _ = nlindex.select_light(
        ИНДЕКС, pool_mask=пул, hidden_mask=пусто,
        no_mat=True, only_mat=False, cap=20, seed=2)
    алгоритм, _, _, _ = nlindex.select(
        ИНДЕКС, pool_mask=пул, hidden_mask=пусто,
        no_mat=True, only_mat=False, cap=20, reserve_n=0,
        syllable_spec=None, per_bucket=4, seed=2, clausula=0)
    assert классика and all(r["classic"] is True for r in классика)
    assert алгоритм and all(r["classic"] is False for r in алгоритм)


@нет_индекса
def test_мат_отсекается_и_в_классике():
    """«Без мата» — не мнение о качестве, а явный запрос пользователя на
    содержание, поэтому действует и здесь (в отличие от банальности)."""
    пул = np.ones(ИНДЕКС.n, dtype=bool)
    пусто = np.zeros(ИНДЕКС.n, dtype=bool)
    _, с_матом, _ = nlindex.select_light(ИНДЕКС, pool_mask=пул, hidden_mask=пусто,
                                      no_mat=False, only_mat=False, cap=5, seed=3)
    _, без_мата, _ = nlindex.select_light(ИНДЕКС, pool_mask=пул, hidden_mask=пусто,
                                       no_mat=True, only_mat=False, cap=5, seed=3)
    # считаем только по целым: обрывки отсеяны на обоих путях одинаково
    цел = ИНДЕКС.whole_mask().copy()
    # Раунд 59: классика слушается и чёрного списка — разница считается по тому
    # же множеству, иначе сторож ловил бы запрещённые строки как «матерные».
    з = nlindex.запрет(nlindex._правила())
    if з["маска"] is not None:
        цел &= ~з["маска"]
    assert с_матом - без_мата == int(((np.asarray(ИНДЕКС.mat) != 0) & цел).sum())


