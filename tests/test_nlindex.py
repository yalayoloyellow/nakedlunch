@нет_индекса
def test_drugie_vorota_drugaya_tablica():
    """В ключе кэша обязано стоять ВСЁ, что двигает ворота.

    ЧТО СТОРОЖИЛОСЬ РАНЬШЕ И ПОЧЕМУ ПЕРЕПИСАНО (2026-08-29). Здесь крутился
    консонанс (`cohesion`, «Диссонанс» на экране) — цель полосы ТЕМЫ. Темы нет,
    полосы нет, ручки нет; параметра в подписи тоже. Но СМЫСЛ сторожа жив и
    важен ровно так же: таблица одна на процесс (одна запись, десятки мегабайт),
    и стоит ключу забыть хоть одно условие — пользователь получит выдачу от
    ЧУЖИХ ворот, молча. Поэтому крутим то, что ворота двигает сегодня: мат и
    клаузулу.

    Вторая половина — про оценку. Ранжировать без темы нечем (замер Раунда 62:
    сортировка по нулям давала не выбор, а номер фрагмента в корпусе, то есть
    кусок одной книги вместо выборки), поэтому оценка обязана быть ПЛОСКОЙ —
    одна на всех. Появись здесь разброс, отбор снова начал бы выдавать
    «верхушку» неизвестно чего."""
    idx = ИНДЕКС
    nlindex.забыть_таблицу()
    настежь = nlindex._таблица(idx, False, False, 0)
    n_настежь = len(настежь[0])
    assert len(set(np.asarray(настежь[1]).tolist())) == 1, \
        "оценка обязана быть одна на всех — ранжировать без темы нечем"

    без_мата = nlindex._таблица(idx, True, False, 0)
    assert без_мата[0] is not настежь[0], "кэш отдал таблицу от ДРУГИХ ворот"
    assert len(без_мата[0]) < n_настежь, "«без мата» обязано сужать выживших"

    клаузула = nlindex._таблица(idx, False, False, 1)   # только мужская
    assert len(клаузула[0]) < n_настежь, "клаузула обязана сужать выживших"

    # И обратно: тот же ключ обязан давать те же числа, а не последние
    # посчитанные. Кэш на одну запись — самое место для такой ошибки.
    снова = nlindex._таблица(idx, False, False, 0)
    assert len(снова[0]) == n_настежь, "кэш подсунул чужие ворота под своим ключом"


