@нет_индекса
def test_релевантность_совпадает_с_поштучной():
    """Векторное среднее обязано совпасть с embeddings.relevance, которую
    старый путь звал на каждый фрагмент отдельно."""
    import embeddings
    embeddings.warm_caches()
    vec = embeddings.theme_vector(["ночь"])
    if vec is None:
        pytest.skip("navec недоступен")
    sims = embeddings.theme_similarities(vec)
    быстро = ИНДЕКС.relevance(sims)
    rng = np.random.default_rng(11)
    for i in rng.integers(0, ИНДЕКС.n, 400):
        i = int(i)
        поштучно = embeddings.relevance(sims, ИНДЕКС.lemma_set(i))
        assert abs(поштучно - float(быстро[i])) < 1e-9, ИНДЕКС.text(i)


@нет_индекса
def test_фрагмент_без_лемм_даёт_ноль():
    """Пустой сегмент — ловушка np.add.reduceat: он возвращает соседний
    элемент, а не ноль. Проверяем, что заглушено."""
    длины = np.diff(np.asarray(ИНДЕКС.lem_off))
    пустые = np.flatnonzero(длины == 0)
    if not len(пустые):
        pytest.skip("в корпусе нет фрагментов без лемм")
    sims = np.arange(500002, dtype=np.float64)      # заведомо ненулевые косинусы
    r = ИНДЕКС.relevance(sims)
    assert np.all(r[пустые] == 0.0)


def test_перцентиль_повторяет_сортировку():
    """Ранг/(n−1) при стабильной сортировке; равные значения сохраняют
    исходный порядок — как sorted() в старом пути."""
    idx = nlindex.load()
    if idx is None:
        idx = nlindex.Index.__new__(nlindex.Index)      # только метод, без данных
    sem = np.array([0.5, 0.1, 0.5, 0.9, 0.1], dtype=np.float64)
    alive = np.arange(5)
    got = nlindex.Index.pctl(idx, sem, alive)
    порядок = sorted(range(5), key=lambda i: sem[i])     # stable, как в filters
    ждём = [0.0] * 5
    for ранг, i in enumerate(порядок):
        ждём[i] = ранг / 4
    assert list(got) == ждём


def test_перцентиль_на_одной_строке():
    idx = nlindex.load() or nlindex.Index.__new__(nlindex.Index)
    got = nlindex.Index.pctl(idx, np.array([0.7]), np.arange(1))
    assert list(got) == [0.5]


