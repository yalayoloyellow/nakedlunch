#   · `test_фрагмент_без_лемм_даёт_ноль` — ловушка `np.add.reduceat`: на
#     пустом сегменте она отдаёт соседний элемент, а не ноль. Ловушка жила
#     внутри `relevance`, вместе с ней и ушла;
#   · `test_перцентиль_повторяет_сортировку` и
#     `test_перцентиль_на_одной_строке` — арифметика `Index.pctl` (стабильный
