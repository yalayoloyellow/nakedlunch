# ---- полка кнопок корпуса --------------------------------------------------
#
# Требование владельца дословно: «чтобы они не повторяли логику друг друга,
# чтобы понятно было, какими пользоваться, чтобы не делать лишних нажатий».
#
# Кнопки расползаются не сразу, а по одной за раунд: каждая появляется под
# конкретную находку и кажется дешёвой. Так и набралось четыре пересчёта, из
# которых один был подмножеством другого. Сторожа ниже держат ФОРМУ полки, а не
# подписи: сколько кнопок, что ни одна не требует нажать следом другую, и что
# снятое не вернулось.

def _настройки() -> str:
    return (КОРЕНЬ / "interface" / "react-app" / "src" / "nl"
            / "render.settings.jsx").read_text("utf-8")


def _без_комментариев(код: str) -> str:
    import re
    код = re.sub(r"\{/\*.*?\*/\}", "", код, flags=re.S)
    код = re.sub(r"/\*.*?\*/", "", код, flags=re.S)
    return re.sub(r"^\s*//.*$", "", код, flags=re.M)


def test_у_корпуса_ровно_три_действия():
    """Три вопроса владельца — три кнопки, и больше ни одной:
       «новая книга» · «в корпусе мусор» · «что-то не так, переделай всё».
    Плюс «папка», которая ничего не считает.

    Число проверяется НАРОЧНО: пятая кнопка появится не как решение, а как
    ещё один частный случай, и заметить это глазами уже не выйдет."""
    код = _без_комментариев(_настройки())
    действия = [и for и in ("c.addBooks(", "c.cleanCorpus()", "c.rebuildRhyme()",
                            "c.openCorpusDir()") if и in код]
    assert len(действия) == 4, f"полка корпуса изменилась: {действия}"
    for снятое in ("c.rebanQuality", "rhymeReban", "reban=True"):
        assert снятое not in код, f"вернулась снятая кнопка: {снятое}"


def test_ни_одна_кнопка_не_требует_второго_нажатия():
    """ЛОВУШКА, КОТОРУЮ ЧИНИЛИ. Чистка меняет текст, а кэш рифм ключуется
    текстом — до пересчёта подрезанные строки молча пропадают из выдачи. Пока
    подсказка говорила «теперь жми прогнать всё заново», забыть второе нажатие
    значило потерять сорок тысяч строк и не узнать об этом.

    Проверяется ИСХОД: роут чистки сам запускает пересчёт."""
    сервер = (КОРЕНЬ / "api" / "server.py").read_text("utf-8")
    тело = сервер[сервер.index("def api_nl_clean():"):]
    тело = тело[:тело.index("def _выбросить_из_кэша")]
