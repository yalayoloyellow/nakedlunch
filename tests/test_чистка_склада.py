def test_у_чистки_есть_вызывающий():
    """ГЛАВНЫЙ СТОРОЖ ЭТОГО ФАЙЛА, и он не про поведение, а про ДОСТУПНОСТЬ.

    `strip_names` и `strip_index_junk` рядом в складе — правильный код, верные
    правила, ноль вызывающих. Их написали под находку, прогнали раз из консоли
    и забыли; правила потом улучшали, а склад оставался прежним. Ровно на это
    владелец и указал: «очистка существующего должна быть чтоб я мог
    пересчитывать».

    Функция, до которой нельзя дотянуться из приложения, — это не функция, а
    заметка. Поэтому здесь проверяется цепочка целиком: кнопка → метод клиента
    → роут → склад. Порвётся любое звено — тест покраснеет, а не чистка молча
    станет мёртвой во второй раз."""
    из_фронта = (КОРЕНЬ / "interface" / "react-app" / "src" / "nl")
    настройки = (из_фронта / "render.settings.jsx").read_text("utf-8")
    методы = (из_фронта / "methods.corpus.js").read_text("utf-8")
    клиент = (из_фронта / "api.js").read_text("utf-8")
    сервер = (КОРЕНЬ / "api" / "server.py").read_text("utf-8")

    assert "c.cleanCorpus()" in настройки, "с экрана настроек пропала кнопка чистки"
    assert "async cleanCorpus()" in методы, "у кнопки пропал обработчик"
    assert "api.corpusClean" in методы, "обработчик перестал звать клиента"
    assert "corpusClean" in клиент and "/api/nl/clean" in клиент, "клиент потерял роут"
    assert "/api/nl/clean" in сервер, "сервер потерял роут чистки"
    assert ".почистить(" in сервер, "роут перестал звать сам проход"


