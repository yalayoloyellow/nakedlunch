def test_второй_проход_ничего_не_меняет(склад):
    """ИДЕМПОТЕНТНОСТЬ. Проверяется ИСХОДОМ, а не обещанием в докстринге:
    прогоняем дважды и сверяем состав склада побайтно."""
    заполнить(склад, [
        "Из-за каждой обиды нельзя отрекаться от друга",
        "за каждой обиды нельзя отрекаться от друга",
        "затеять новую революцию. И я бы не",
        "141, 573 Хазан В. II 468, 670 торн и контратака",
        "Во всяком случае", "во всяком случае",
        "настоящее время Сашенька Зеленский ждет свою мамочку",
        "Мамин голос — спокойный и ровный",
    ])
    первый = склад.почистить()
    после_первого = тексты(склад)
    второй = склад.почистить()
    assert тексты(склад) == после_первого, "второй проход изменил склад"
    assert второй["было"] == второй["стало"] == первый["стало"]
    for правило in ("указатель", "имя_вырезано", "хвост_подрезан",
                    "осыпалось", "двойник", "обломок"):
        assert второй[правило] == 0, f"второй проход снова сработал правилом «{правило}»"


