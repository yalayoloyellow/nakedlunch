# ---- полка кнопок корпуса --------------------------------------------------
#
# Требование владельца дословно: «чтобы они не повторяли логику друг друга,
# чтобы понятно было, какими пользоваться, чтобы не делать лишних нажатий».
#
# Кнопки расползаются не сразу, а по одной за раунд: каждая появляется под
# конкретную находку и кажется дешёвой. Так и набралось четыре пересчёта, из
# которых один был подмножеством другого. Сторожа ниже держат ФОРМУ полки, а не
# подписи: сколько кнопок, что ни одна не требует нажать следом другую, и что
# снятое не вернулось.

def _настройки() -> str:
    return (КОРЕНЬ / "interface" / "react-app" / "src" / "nl"
            / "render.settings.jsx").read_text("utf-8")


def _без_комментариев(код: str) -> str:
    import re
    код = re.sub(r"\{/\*.*?\*/\}", "", код, flags=re.S)
    код = re.sub(r"/\*.*?\*/", "", код, flags=re.S)
    return re.sub(r"^\s*//.*$", "", код, flags=re.M)


def test_на_виду_только_повседневное():
    """РАЗОВЫЕ ОПЕРАЦИИ УБРАНЫ ПОД «ОБСЛУЖИВАНИЕ» (2026-08-21, решение
    владельца: «пометь эту кнопку, спрячь в расширенный раздел»).

    На виду остаются заливка и папка — их трогают постоянно. Чистка нужна ОДИН
    РАЗ, для книг, залитых до 21 августа; полный прогон — только если что-то
    разошлось. Кнопка, которую жмут раз в жизни, рядом с повседневной — это
    приглашение нажать не ту.

    Проверяется ПОРЯДОК В ФАЙЛЕ: обе разовые обязаны стоять ПОСЛЕ разворота
    раздела, то есть внутри него."""
    код = _без_комментариев(_настройки())
    for и in ("c.addBooks(", "c.openCorpusDir()", "c.cleanCorpus()", "c.rebuildRhyme()"):
        assert и in код, f"пропало действие {и}"
    разворот = код.index("обслуживание: !st.обслуживание")
    for разовое in ("c.cleanCorpus()", "c.rebuildRhyme()"):
        assert код.index(разовое) > разворот, (
            f"{разовое} снова на виду, а не под «обслуживанием»")
    assert код.index("c.addBooks(") < разворот, "заливка уехала под обслуживание"
    for снятое in ("c.rebanQuality", "rhymeReban", "reban=True"):
        assert снятое not in код, f"вернулась снятая кнопка: {снятое}"


