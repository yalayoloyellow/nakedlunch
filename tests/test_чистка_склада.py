    было = ["которую я встречал…", "Я был враг, вторгшийся на её территорию…"]
    заполнить(склад, было)
    итог = склад.почистить()
    assert тексты(склад) == было, "чистка съела многоточие"
    assert итог["хвост_подрезан"] == 0


