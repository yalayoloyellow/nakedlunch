def test_счёт_монотонен(склад):
    """Счётчик, который пятится, читается как сбой. Знаменатель обязан быть
    один на всю операцию, а не свой у каждого этапа.

    ФИКСТУРА НАРОЧНО С ОБЛОМКАМИ: без них поиск близнецов проходит один круг, и
    тест зеленел бы на самом опасном месте. С ними цикл идёт до неподвижной
    точки — и на живой проверке счётчик там прыгал с 97% назад на 50%, потому
    что каждый круг докладывал от своего начала."""
    # БЕЗ ЦИФР: с 2026-08-21 фрагмент с цифрой выбрасывается (см. `есть_цифра`),
    # и прежняя фикстура «строка номер 17…» вымирала целиком — цикл не доходил
    # до второго круга, а тест зеленел на самом опасном месте.
    слова = ["ясного", "мутного", "долгого", "краткого", "тихого", "громкого",
             "тёплого", "мёрзлого", "первого", "прочего"]
    хвосты = [f"{a} {b}" for a in слова for b in слова]                       # 100 штук
    строки = [f"строка про {x} дело такое" for x in хвосты]
    строки += [f"про {x} дело такое" for x in хвосты]                        # обломки
    строки += [f"тут строка про {x} дело такое" for x in хвосты]
    заполнить(склад, строки)
    доклады = []
    склад.почистить(применить=False, прогресс=lambda э, с, в: доклады.append((э, с, в)))
    assert any(э == "проверяю ещё раз" for э, _, _ in доклады), (
        "цикл до неподвижной точки не пошёл — тест не проверил опасное место")
    знаменатели = {в for _, _, в in доклады}
    assert len(знаменатели) == 1, f"знаменатель менялся по ходу: {знаменатели}"
    сделано = [с for _, с, _ in доклады]
    assert сделано == sorted(сделано), f"счётчик пятился: {сделано}"


