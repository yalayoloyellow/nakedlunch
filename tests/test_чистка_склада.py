def test_разные_длины_одной_фразы_остаются_обе(склад):
    """ГРАНИЦА ПРАВИЛА, и она важнее самого правила. Кусок длинной фразы на
    девять слогов — рабочий материал для строфы, а сама фраза на шестнадцать в
    строку не влезет. Поэтому режется только пара, различающаяся не больше чем
    на два слога; всё, что разошлось сильнее, — разные строки, а не близнецы.

    Без этой границы чистка съела бы 58.4% корпуса вместо 15.8% и вынесла бы
    вместе с мусором весь короткий материал."""
    длинная = "Нами через пропасть прямо к коммунизму перекинут мост, длиною — во сто лет"
    короткая = "прямо к коммунизму перекинут мост"
    заполнить(склад, [длинная, короткая])
    итог = склад.почистить()
    assert set(тексты(склад)) == {длинная, короткая}, "срезан материал другой длины"
    assert итог["обломок"] == 0


