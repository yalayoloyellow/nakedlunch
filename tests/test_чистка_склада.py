# nakedlunch — ОДИН ПОВТОРЯЕМЫЙ ПРОХОД ЧИСТКИ СКЛАДА (2026-08-21).
#
# ЗАЧЕМ ОН ВООБЩЕ ПОЯВИЛСЯ. Требование владельца дословно: «и обогащение и
# очистка существующего должна быть чтоб я мог пересчитывать и старое
# пересчитывалось плохое вырезалось».
#
# Правила чистки в коде БЫЛИ и до этого — `strip_names`, `strip_index_junk` в
# складе, подрезка хвоста в `nlindex`. Но их не звал НИКТО: обе функции
# написаны под конкретную находку, запущены один раз из консоли и с тех пор
# мертвы (проверено grep по всему дереву — ни одного вызывающего). Правило
# улучшали, а данные оставались как есть. `почистить()` собирает их в одну
# операцию, которую можно жать сколько угодно раз.
#
# ГЛАВНОЕ СВОЙСТВО, КОТОРОЕ ЗДЕСЬ СТОРОЖИТСЯ — ИДЕМПОТЕНТНОСТЬ. Кнопку,
# которая при втором нажатии режет ещё, жать страшно; а страшную кнопку не
# жмут, и чистка снова станет разовым проходом из консоли.
#
# Прогон: .venv/bin/python -m pytest tests/test_чистка_склада.py -q

import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "core"))

from nlsrc.store import Fragment, NakedLunchStore  # noqa: E402


@pytest.fixture()
def склад(tmp_path):
    """Пустой склад во временном каталоге — боевого не касаемся никогда."""
    return NakedLunchStore(tmp_path / "корпус")


def заполнить(с: NakedLunchStore, тексты: list[str]) -> None:
    с.state.fragments = [Fragment(id=f"ф{i}", text=t, corpus_id="к")
                         for i, t in enumerate(тексты)]
    с._rebuild_active_fragments()


def тексты(с: NakedLunchStore) -> list[str]:
    return [f.text for f in с.state.fragments]


