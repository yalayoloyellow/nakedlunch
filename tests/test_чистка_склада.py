def test_оборванный_хвост_подрезается(склад):
    """Ради этого правила проход и затевался: 42 632 строки индекса
    выбрасывались из пула целиком как обрывки, а 84% из них подрезка
    превращает в годную строку (замер 2026-08-21)."""
    заполнить(склад, ["затеять новую революцию. И я бы не"])
    итог = склад.почистить()
    assert тексты(склад) == ["затеять новую революцию. И я"]
    assert итог["хвост_подрезан"] == 1


def test_многоточие_не_считается_обрывком(склад):
    """ПОЙМАНО ГЛАЗАМИ НА ЖИВОЙ ПРОБЕ, а не придумано. `подрезать_хвост`
    начинается с `rstrip` по знакам и возвращает уже ободранный текст даже
    когда резать нечего — для сверки истории это правильно (обе стороны
    нормализуются одинаково), но здесь результат ПИШЕТСЯ В СКЛАД, и авторская
    пунктуация исчезала молча: «которую я встречал…» становилось «которую я
    встречал». Правило: принимаем подрезку, только если ушло СЛОВО."""
    было = ["которую я встречал…", "Я был враг, вторгшийся на её территорию…"]
    заполнить(склад, было)
    итог = склад.почистить()
    assert тексты(склад) == было, "чистка съела многоточие"
    assert итог["хвост_подрезан"] == 0


def test_полное_имя_снимается(склад):
    заполнить(склад, ["настоящее время Сашенька Зеленский ждет свою мамочку"])
    склад.почистить()
    assert тексты(склад) == ["настоящее время ждет свою мамочку"]


def test_мусор_указателя_режется(склад):
    заполнить(склад, ["141, 573 Хазан В. II 468, 670 торн и контратака",
                      "Мамин голос — спокойный и ровный"])
    итог = склад.почистить()
    assert тексты(склад) == ["Мамин голос — спокойный и ровный"]
    assert итог["указатель"] == 1


def test_точный_двойник_снимается_а_первый_остаётся(склад):
    """Двойники различаются только регистром и пунктуацией — по словам они одно
    и то же. Остаётся ПЕРВЫЙ: порядок склада это порядок книг, и оставлять
    последнего значило бы тихо предпочитать книгу, залитую позже."""
    заполнить(склад, ["Во всяком случае", "во всяком случае", "… Во всяком случае"])
    итог = склад.почистить()
    assert тексты(склад) == ["Во всяком случае"]
    assert итог["двойник"] == 2


def test_обломок_снимается_а_целая_остаётся(склад):
    """СЕРДЦЕ ПРОХОДА. Нарезка идёт скользящим окном (окно 7 слов, шаг 3),
    поэтому соседние окна делят 4 слова из 7. Короткий близнец при этом
    систематически ОБЛОМОК с отрезанным первым словом — и он рифмуется с
    целой строкой, потому что кончается так же."""
    заполнить(склад, ["Из-за каждой обиды нельзя отрекаться от друга",
                      "за каждой обиды нельзя отрекаться от друга"])
    итог = склад.почистить()
    assert тексты(склад) == ["Из-за каждой обиды нельзя отрекаться от друга"]
    assert итог["обломок"] == 1


def test_разные_длины_одной_фразы_остаются_обе(склад):
    """ГРАНИЦА ПРАВИЛА, и она важнее самого правила. Кусок длинной фразы на
    девять слогов — рабочий материал для строфы, а сама фраза на шестнадцать в
    строку не влезет. Поэтому режется только пара, различающаяся не больше чем
    на два слога; всё, что разошлось сильнее, — разные строки, а не близнецы.

    Без этой границы чистка съела бы 58.4% корпуса вместо 15.8% и вынесла бы
    вместе с мусором весь короткий материал."""
    длинная = "Нами через пропасть прямо к коммунизму перекинут мост, длиною — во сто лет"
    короткая = "прямо к коммунизму перекинут мост"
    заполнить(склад, [длинная, короткая])
    итог = склад.почистить()
    assert set(тексты(склад)) == {длинная, короткая}, "срезан материал другой длины"
    assert итог["обломок"] == 0


