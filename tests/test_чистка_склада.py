def test_второй_проход_ничего_не_меняет(склад):
    """ИДЕМПОТЕНТНОСТЬ. Проверяется ИСХОДОМ, а не обещанием в докстринге:
    прогоняем дважды и сверяем состав склада побайтно."""
    заполнить(склад, [
        "Из-за каждой обиды нельзя отрекаться от друга",
        "за каждой обиды нельзя отрекаться от друга",
        "затеять новую революцию. И я бы не",
        "141, 573 Хазан В. II 468, 670 торн и контратака",
        "Во всяком случае", "во всяком случае",
        "настоящее время Сашенька Зеленский ждет свою мамочку",
        "Мамин голос — спокойный и ровный",
    ])
    первый = склад.почистить()
    после_первого = тексты(склад)
    второй = склад.почистить()
    assert тексты(склад) == после_первого, "второй проход изменил склад"
    assert второй["было"] == второй["стало"] == первый["стало"]
    for правило in ("указатель", "имя_вырезано", "хвост_подрезан",
                    "осыпалось", "двойник", "обломок"):
        assert второй[правило] == 0, f"второй проход снова сработал правилом «{правило}»"


def test_сухой_прогон_не_трогает_склад(склад):
    """Кнопка сперва СЧИТАЕТ и показывает цену, и только потом спрашивает.
    Если сухой прогон что-нибудь изменит, подтверждение станет обманом."""
    было = ["Из-за каждой обиды нельзя отрекаться от друга",
            "за каждой обиды нельзя отрекаться от друга",
            "затеять новую революцию. И я бы не"]
    заполнить(склад, было)
    итог = склад.почистить(применить=False)
    assert тексты(склад) == было, "сухой прогон изменил склад"
    assert итог["стало"] < итог["было"], "сухой прогон не посчитал убыль"


def test_счётчики_сходятся_с_составом(склад):
    """Число в подтверждении обязано совпасть с тем, что произойдёт. Доля,
    посчитанная не по тому множеству, — самая частая ошибка этого проекта."""
    заполнить(склад, [
        "Из-за каждой обиды нельзя отрекаться от друга",
        "за каждой обиды нельзя отрекаться от друга",
        "141, 573 Хазан В. II 468, 670 торн и контратака",
        "Во всяком случае", "во всяком случае",
        "Мамин голос — спокойный и ровный",
    ])
    итог = склад.почистить(применить=False)
    ушло = итог["указатель"] + итог["осыпалось"] + итог["двойник"] + итог["обломок"]
    assert итог["было"] - итог["стало"] == ушло, (
        "сумма счётчиков не равна убыли — значит подтверждение показало бы "
        "не то число, по которому владелец принимает решение")


def test_счёт_фрагментов_у_книги_пересчитан(склад):
    """Склад держит `fragment_count` у каждой книги отдельно от самих
    фрагментов. Забыть его — значит показать в списке источников число, которого
    больше нет; на рассинхроне двух счётчиков проект уже обжигался."""
    from nlsrc.store import Corpus
    склад.state.corpora = [Corpus(id="к", name="книга", type="personal", fragment_count=3)]
    заполнить(склад, ["Во всяком случае", "во всяком случае",
                      "Мамин голос — спокойный и ровный"])
    склад.почистить()
    assert склад.state.corpora[0].fragment_count == len(склад.state.fragments) == 2


