#
# ЗАЧЕМ. В журнале 7 935 прогонов, и 7 113 из них — один всплеск 17 июля длиной
# 21 минуту, медиана паузы 0.14 с. Все, кто считал доли, делили на 7 935 и мерили
# машину. Из-за этого В ПЛАН ПОПАЛИ КАК ФАКТЫ два неверных числа: «одно значение
# крутилки держится в 91% прогонов» (на самом деле 57.2%) и «тема задана в 13.3%»
# (на самом деле 30.9%). На них принимались решения, какие ручки резать.
#
# Пороги замерены, а не назначены: развёртка даёт плато 2–4 с, где ответ не
# меняется вовсе (см. комментарий в core/stats.py). Здесь сторожатся СВОЙСТВА
# разделителя, а не конкретные числа живого журнала — журнал растёт.
#
# Прогон: .venv/bin/python -m pytest tests/test_живые_прогоны.py -q

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))
import stats  # noqa: E402


def очередь(начало: float, шаг: float, сколько: int) -> list[dict]:
    return [{"kind": "generate", "t": начало + i * шаг} for i in range(сколько)]


# ---- вырожденные данные: с них начинается любая метрика в этом проекте ------

def test_пустой_журнал_не_роняет():
    живые, машина = stats.разделить_на_живое_и_машину([])
    assert живые == [] and машина == []
    assert stats.всплески([]) == []


def test_один_прогон_живой():
    """Одна запись не может быть всплеском — не с чем сравнивать паузу."""
    живые, машина = stats.разделить_на_живое_и_машину(очередь(1000.0, 0, 1))
    assert len(живые) == 1 and not машина


def test_записи_без_времени_считаются_живыми():
    """Неизвестное время — не повод объявить запись роботом. Молчаливое
    зачисление в машину выбросило бы человека из знаменателя, а это ровно та
    ошибка, от которой заведён весь этот разделитель."""
    живые, машина = stats.разделить_на_живое_и_машину(
        [{"kind": "generate"}, {"kind": "generate", "t": None}])
    assert len(живые) == 2 and not машина


def test_все_прогоны_в_одну_секунду_не_роняют():
    """Нулевые паузы — законный вход: журнал пишется с точностью до
    миллисекунд, и подряд идущие записи могут совпасть."""
    живые, машина = stats.разделить_на_живое_и_машину(очередь(1000.0, 0.0, 50))
    assert not живые and len(машина) == 50


# ---- собственно правило -----------------------------------------------------

def test_редкие_прогоны_человека_остаются_живыми():
    живые, машина = stats.разделить_на_живое_и_машину(очередь(1000.0, 11.4, 200))
    assert len(живые) == 200 and not машина


def test_длинная_частая_очередь_машинная():
    живые, машина = stats.разделить_на_живое_и_машину(очередь(1000.0, 0.14, 500))
    assert not живые and len(машина) == 500


def test_короткая_быстрая_очередь_ЖИВАЯ():
    """Пять нажатий подряд — это человек, и ради этого в ленте буфер
    предзагрузки. Считать их роботом значило бы вычесть из статистики самый
    характерный способ работы владельца."""
    живые, машина = stats.разделить_на_живое_и_машину(очередь(1000.0, 0.2, 5))
    assert len(живые) == 5 and not машина


def test_граница_длины_цепочки_не_плавает():
    """На единицу короче минимума — живое, ровно минимум — машина. Граница
    названа явно, чтобы её нельзя было сдвинуть незаметно."""
    короче = очередь(1000.0, 0.2, stats.ДЛИНА_ВСПЛЕСКА - 1)
    ровно = очередь(1000.0, 0.2, stats.ДЛИНА_ВСПЛЕСКА)
    assert not stats.разделить_на_живое_и_машину(короче)[1]
    assert not stats.разделить_на_живое_и_машину(ровно)[0]


def test_всплеск_не_съедает_соседей():
    """Человек нажал, потом ушёл машинный прогон, потом человек вернулся.
    Обе живые записи обязаны уцелеть: всплеск вычитается, а не всё вокруг."""
    события = ([{"kind": "generate", "t": 0.0}]
               + очередь(100.0, 0.1, 300)
               + [{"kind": "generate", "t": 900.0}])
    живые, машина = stats.разделить_на_живое_и_машину(события)
    assert len(живые) == 2, "живые соседи всплеска потерялись"
    assert len(машина) == 300
    assert {e["t"] for e in живые} == {0.0, 900.0}


def test_разделение_ничего_не_теряет_и_не_двоит():
    """Сумма частей равна целому. Метрика, теряющая события, покажет красивую
    долю и соврёт — в этом проекте такое случалось трижды за один день."""
    события = (очередь(0.0, 30.0, 40) + очередь(5000.0, 0.1, 400)
               + [{"kind": "generate"}] + очередь(9000.0, 12.0, 7))
    живые, машина = stats.разделить_на_живое_и_машину(события)
    assert len(живые) + len(машина) == len(события)
    все_id = {id(e) for e in живые} | {id(e) for e in машина}
    assert len(все_id) == len(события), "какое-то событие попало в обе стороны"


def test_описание_всплеска_совпадает_с_разделением():
    """`всплески()` и `разделить_на_живое_и_машину()` обязаны видеть одно и то
    же. Два ответа на один вопрос в этом проекте расходятся с гарантией."""
    события = очередь(0.0, 30.0, 10) + очередь(5000.0, 0.1, 300)
    _, машина = stats.разделить_на_живое_и_машину(события)
    описания = stats.всплески(события)
    assert len(описания) == 1
    assert описания[0]["прогонов"] == len(машина) == 300
    assert описания[0]["секунд"] == pytest.approx(29.9, abs=0.2)


def test_порог_взят_с_плато_а_не_с_края():
    """Замер дал плато 2–4 с, где ответ не меняется. Порог обязан лежать внутри
    него: на краю плато любое движение данных сдвинет ответ, и число снова
    станет подгонкой."""
    assert 2.0 <= stats.ПОРОГ_ВСПЛЕСКА_С <= 4.0, (
        f"порог {stats.ПОРОГ_ВСПЛЕСКА_С} с вышел за замеренное плато 2–4 с — "
        "если данные изменились, пересними развёртку и перепиши комментарий "
        "в core/stats.py, а не двигай число молча")


