# «Прошлый запуск завершился аварийно» — вердикт, а не живое состояние диска
# (2026-08-28). Отметка чистого выхода снимается В НАЧАЛЕ сессии, поэтому живой
# вызов не_закрыто() во время работы отвечал «аварийно» после КАЖДОГО запуска —
# и красная строка в логе горела даже после честного выхода. Экран лгал.
# Вердикт снимается один раз на старте; эти сторожа держат обе стороны.
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))
import журнал  # noqa: E402


@pytest.fixture
def жур(tmp_path, monkeypatch):
    monkeypatch.setattr(журнал, "ПАПКА", tmp_path)
    monkeypatch.setattr(журнал, "АРХИВ", tmp_path / "журнал")
    monkeypatch.setattr(журнал, "ФАЙЛ", tmp_path / "сессия.log")
    monkeypatch.setattr(журнал, "ПРОШЛЫЙ", tmp_path / "сессия-прошлая.log")
    monkeypatch.setattr(журнал, "ОТМЕТКА", tmp_path / "сессия.закрыта")
    # вердикт прошлой сессии — заново для каждого теста; raising=False, чтобы
    # сторож на коде без поля ПАДАЛ красным, а не ошибкой фикстуры
    monkeypatch.setattr(журнал, "_прошлый_упал", None, raising=False)
    monkeypatch.delenv("NAKEDLUNCH_PREV_CRASHED", raising=False)
    yield журнал
    # начать_сессию ставит переменную УЖЕ ВНУТРИ теста — delenv про неё не
    # знает и на разборе не снимет; без pop вердикт утёк бы в соседние тесты
    import os
    os.environ.pop("NAKEDLUNCH_PREV_CRASHED", None)


def test_чистый_выход_не_красит_новую_сессию(жур):
    """Прошлый запуск закрылся штатно → новая сессия НЕ говорит «аварийно»,
    сколько бы раз её ни спрашивали по ходу работы."""
    жур.ФАЙЛ.write_text("00:00:00 запуск сессия начата\n", "utf-8")
    жур.закрыть_сессию()
    assert жур.ОТМЕТКА.exists()
    жур.начать_сессию()
    # отметка снята стартом — но вердикт о ПРОШЛОМ запуске от этого не меняется
    assert not жур.ОТМЕТКА.exists()
    assert жур.не_закрыто() is False
    assert жур.не_закрыто() is False   # и на втором опросе тоже


def test_аварийный_выход_виден(жур):
    """Прошлый запуск убит (отметки нет) → новая сессия честно говорит об этом."""
    жур.ФАЙЛ.write_text("00:00:00 запуск сессия начата\n", "utf-8")
    жур.начать_сессию()
    assert жур.не_закрыто() is True


def test_вердикт_доезжает_до_сервера_ребёнка(жур):
    """Сессию открывает launch.py, а /api/status отвечает server.py — ДРУГОЙ
    процесс (Popen, env=child_env()). Глобал туда не доедет; вердикт обязан
    ехать средой. Здесь «ребёнок» — тот же модуль со сброшенным глобалом:
    ровно то, что видит свежий импорт журнала в сервере."""
    жур.ФАЙЛ.write_text("00:00:00 запуск сессия начата\n", "utf-8")
    жур.закрыть_сессию()
    жур.начать_сессию()                      # чистый выход → вердикт «не упал»
    жур._прошлый_упал = None                 # свежий процесс: глобала нет
    assert жур.не_закрыто() is False         # env унаследован — экран не врёт


# ── ОТМЕТКА СТАВИТСЯ НА БОЕВОМ ПУТИ, А НЕ ТОЛЬКО ПРИ ПРЯМОМ ВЫЗОВЕ ────────────
#
# ЧЕГО НЕ ХВАТАЛО СТОРОЖАМ ВЫШЕ (найдено разбором 2026-09-02). Все они зовут
# `закрыть_сессию` РУКАМИ и потому были зелёными всё время, пока боевой путь
# отметку не ставил вовсе: единственным вызывающим был `atexit.register` в
# `launch.main`, а окно закрывается через `os._exit(0)` в `on_closed`, где
# atexit не отрабатывает. Итог на живых данных владельца — 30 архивных файлов
# из 30 помечены аварийными, и метка означала не «упал», а «запускался».
#
# Проверять это исполнением нельзя: `os._exit` убивает интерпретатор вместе с
# набором, а `cleanup` — замыкание внутри `main`, снаружи его не позвать.
# Поэтому сторож читает ИСХОДНИК разбором, а не текстом: ищет функцию
# `cleanup` в `launch.py` и требует, чтобы внутри неё стоял вызов
# `закрыть_сессию`. Регистрация в `atexit` при этом обязана остаться — ранние
# возвраты из `main` (интерфейс не собрался, «уже запущен и свеж», идёт
# запись) до `cleanup` не доходят и закрываются как раз через неё.

def _разбор_launch():
    import ast
    src = (Path(__file__).resolve().parent.parent / "launch.py").read_text("utf-8")
    return ast.parse(src)


def _зовут_внутри(узел) -> set:
    """Имена всех вызовов внутри узла — включая `ж.закрыть_сессию()`."""
    import ast
    имена = set()
    for n in ast.walk(узел):
        if isinstance(n, ast.Call):
            ф = n.func
            имена.add(ф.attr if isinstance(ф, ast.Attribute) else getattr(ф, "id", ""))
    return имена


def test_отметку_ставит_путь_закрытия_окна_а_не_только_atexit():
    """`cleanup` в launch.py обязан звать `закрыть_сессию`.

    Именно через `cleanup` уходит закрытие окна (`on_closed` → `cleanup()` →
    `os._exit(0)`) — то есть ОСНОВНОЙ выход программы. Без этого вызова
    отметка чистого выхода не ставится никогда, и вердикт «аварийно»
    получается перевёрнутым: нормальная сессия помечается падением, а
    неудачный старт — чистым выходом."""
    import ast
    дерево = _разбор_launch()
    cleanups = [n for n in ast.walk(дерево)
                if isinstance(n, ast.FunctionDef) and n.name == "cleanup"]
    assert cleanups, "в launch.py нет функции cleanup — сторож смотрит не туда"
    зовут = set().union(*(_зовут_внутри(c) for c in cleanups))
    assert "закрыть_сессию" in зовут, (
        "cleanup не ставит отметку чистого выхода. Закрытие окна уходит через "
        "os._exit(0), где atexit не отрабатывает, — значит отметка не будет "
        "поставлена никогда, и каждый журнал получит имя ...-аварийно.log")


def test_регистрация_в_atexit_осталась():
    """Ранние возвраты из `main` до `cleanup` не доходят: интерфейс не
    собрался, «уже запущен и свеж», идёт запись фристайла. Это тоже штатные
    выходы, и отметку им ставит `atexit` — снимать его нельзя."""
    import ast
    дерево = _разбор_launch()
    for n in ast.walk(дерево):
        if isinstance(n, ast.Call) and getattr(n.func, "attr", "") == "register":
            for а in n.args:
                if getattr(а, "attr", "") == "закрыть_сессию":
                    return
    raise AssertionError(
        "atexit.register(закрыть_сессию) пропал: ранние возвраты из main "
        "(до создания cleanup) перестали помечаться как чистый выход")


def test_замок_отметки_снимается_новой_сессией(жур):
    """Две сессии в одном процессе обязаны получить по своей отметке.

    Замок в `закрыть_сессию` стоит затем, что зовут её теперь из двух мест
    (cleanup и atexit) и запись «сессия закрыта штатно» не должна двоиться.
    Но держаться он обязан на СЕССИЮ: на процесс его вешать нельзя — вторая
    сессия осталась бы без отметки и следующий запуск объявил бы её падением.
    """
    жур.ФАЙЛ.write_text("00:00:00 запуск сессия начата\n", "utf-8")
    жур.закрыть_сессию()
    жур.закрыть_сессию()                      # второй раз в ТОЙ ЖЕ сессии
    строк = жур.ФАЙЛ.read_text("utf-8").count("сессия закрыта штатно")
    assert строк == 1, f"запись задвоилась: {строк} строк вместо одной"

    жур.начать_сессию()                       # новая сессия снимает и замок, и отметку
    assert not жур.ОТМЕТКА.exists()
    жур.закрыть_сессию()
    assert жур.ОТМЕТКА.exists(), "вторая сессия в том же процессе осталась без отметки"
