# МАСКА АКТИВНОГО ПУЛА — ИЗ КОЛОНКИ, А НЕ ИЗ СПИСКА ТЕКСТОВ (2026-09-03).
#
# ЧТО БЫЛО. Склад отдавал активный пул СПИСКОМ ТЕКСТОВ (2.3 млн строк), а
# `mask_of` переводил их в номера строк через словарь «текст → номер». Замер
# этого пути на живых данных:
#
#     загрузка склада (state.json, 363 МБ)   5.3 с
#     постройка словаря                      5.4 с
#     сама маска                             1.5 с
#     ----------------------------------------------
#     карты индекса (настоящая работа)       0.4 с
#
# То есть двенадцать секунд из двенадцати с половиной уходили на вычисление
# того, что уже лежит в индексе колонкой `src` и достаётся за 0.01 с.
#
# ДВА СТОРОЖА, И ВТОРОЙ ВАЖНЕЕ ПЕРВОГО. Первый — что маски совпадают. Второй —
# что при НЕСОВПАДЕНИИ состава новый путь отдаёт None и зовущий уходит на
# старый, а не выдаёт пустую маску. Пустая маска здесь означала бы ноль строк
# в выдаче без единого слова о причине: тот самый молчаливый ноль, который в
# этом проекте уже случался (клаузула в классике, 2026-08-29).
import sys
from pathlib import Path

import numpy as np
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))
import nlindex  # noqa: E402


class _Идх:
    n = 6
    #        книга 0, 0, 1, 1, 2, 2
    src = np.array([0, 0, 1, 1, 2, 2], dtype=np.int16)
    sources = ["книга-А", "книга-Б", "книга-В"]

    def text(self, i):
        return f"строка {i}"


@pytest.fixture
def идх():
    return _Идх()


def test_маска_по_включённым_книгам(идх):
    nlindex.forget_pool()
    м = nlindex.маска_книг(идх, {"книга-А", "книга-В"})
    assert м is not None
    assert list(м) == [True, True, False, False, True, True]


def test_ни_одной_книги_не_сошлось_отдаём_None(идх):
    """ГЛАВНЫЙ СТОРОЖ. Чужие флаги активности (другое хранилище, индекс из
    другого состава) обязаны дать None, а не пустую маску: зовущий тогда уйдёт
    на путь через тексты, который сверяется с самим индексом.

    На этом и поймали: тестовый стенд с синтетическим индексом получил боевой
    `active.json`, и генерация молча отдала ноль строк."""
    nlindex.forget_pool()
    assert nlindex.маска_книг(идх, {"чужая-книга", "и-эта-чужая"}) is None


def test_без_колонки_или_без_списка_отдаём_None(идх):
    """Индекс, испечённый до появления колонки `src`, и вызов без списка книг —
    оба обязаны честно уйти на старый путь."""
    nlindex.forget_pool()
    assert nlindex.маска_книг(идх, None) is None

    class БезКолонки(_Идх):
        src = None
    nlindex.forget_pool()
    assert nlindex.маска_книг(БезКолонки(), {"книга-А"}) is None


def test_пустая_история_не_строит_словарь():
    """`mask_of` на пустом списке обязан вернуть пустую маску, не трогая
    словарь: его постройка стоит 5.4 с, и на свежей установке это была вся цена
    первой генерации."""
    класс = type("Пустой", (), {"n": 5})
    м = nlindex.mask_of(класс(), [])
    assert м.shape == (5,) and not м.any()
    м = nlindex.mask_of(класс(), None)
    assert not м.any()


@pytest.mark.skipif(nlindex.load() is None, reason="индекс не испечён")
def test_на_живом_индексе_оба_пути_совпадают():
    """Сверка на настоящих данных: маска колонкой обязана совпасть с маской
    текстами ПОБИТОВО. Разойдутся — выдача поедет, и виноват будет невидимый
    переключатель пути."""
    import nlbridge
    idx = nlindex.load()
    склад = nlbridge.open_store()
    книги = склад.list_corpora()
    все = склад.get_all_fragments()
    for выкл in (0, 3):
        акт = {к["id"] for к in книги[выкл:]}
        тексты = [ф["text"] for ф in все if ф.get("corpus_id") in акт]
        nlindex.forget_pool()
        колонкой = nlindex.маска_книг(idx, акт)
        текстами = nlindex.pool_mask(idx, тексты)
        assert колонкой is not None, "колонка не сработала на живом индексе"
        assert int((колонкой != текстами).sum()) == 0, (
            f"пути разошлись при {выкл} выключенных книгах: "
            f"колонкой {int(колонкой.sum())}, текстами {int(текстами.sum())}")
