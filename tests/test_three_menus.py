# НАДГРОБИЕ 2026-08-18. Файл назывался «три меню, а не один попап» (Раунд 55)
# и сторожил раскладку, которую пользователь сформулировал так:
#
#   СТРОФА     мастерская  — делаются детали: формы и профили настроек
#   ПАЙПЛАЙН   сборка      — из готовых деталей собирается текст
#   СЕРИЯ      конвейер    — готовая сборка повторяется много раз
#
# Двух этажей больше нет. Основание — замер журнала событий за 10 живых дней:
# 29 прогонов цепи против 587 одиночных строф, один к двадцати, при медиане
# цепи 24.2 с и 98.7 с на девяностом процентиле. Серия в журнал не писалась
# вовсе, числа по ней нет: её убрал сам владелец решением от 2026-08-18
# («строфа единственным режимом»), и это решение, а не замер.
#
# Отсюда ушли проверки: три меню экспортируются, три кнопки в шапке, пайплайн
# не правит полки, выбор звена не вернулся, новое звено наследует у соседа и у
# двойника-повтора, звено без полки подписано, кривая не живёт в пайплайне,
# строка серии везде зовётся треком.
#
# ОСТАЛОСЬ ТО, ЧТО ПРО САМУ СТРОФУ, и осталось нарочно: правило «зависимость
# только вперёд» умерло вместе со вторым этажом, а вот «одиночная генерация
# берёт форму из СВОЕЙ мастерской» — это по-прежнему единственный живой путь
# приложения, и он обязан быть проверен.
#
# Проверка текстовая там, где речь о структуре модулей: сборка тут не помогает,
# она зелёная и при утечке.
#
