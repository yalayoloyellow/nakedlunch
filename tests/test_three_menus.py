import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
NL = КОРЕНЬ / "interface" / "react-app" / "src" / "nl"
МЕНЮ = NL / "render.gen.jsx"
# СТАТУСНАЯ СТРОКА ПЕРЕЕХАЛА В ЛЕНТУ (2026-08-18). `genStanza` вырезана вместе
# с документом, единственный производитель теперь `lentaСтрофа`. Сторож обязан
# смотреть туда, где строка ЖИВЁТ, а не туда, где она была.
ГЕНЕРАЦИЯ = NL / "methods.lenta.js"

sys.path.insert(0, str(КОРЕНЬ / "core"))


def тело_метода(текст: str, имя: str) -> str:
    """Кусок файла от объявления метода до следующего объявления на том же
    отступе. Грубо, но достаточно: нам нужно знать, что метод ЧИТАЕТ."""
    i = текст.index(имя)
    хвост = текст[i:]
    m = re.search(r"\n  (?:async )?[A-Za-zА-Яа-я_][\w]*\(", хвост[len(имя):])
    return хвост[:len(имя) + m.start()] if m else хвост


def test_одиночная_строфа_берёт_форму_из_своей_мастерской():
    """ГЛАВНЫЙ И ЕДИНСТВЕННЫЙ ОСТАВШИЙСЯ. В Раунде 51 genStanza читал
    linkSpec(0)/linkKnobs(0) — каркас и крутилки ПЕРВОГО ЗВЕНА ЦЕПИ. Это было
    верно, пока строфа и пайплайн жили в одном попапе: тогда «цепочка из одного
    звена» и «одиночная строфа» обязаны были совпадать.

    Цепи больше нет вовсе, и чтение её остатков было бы уже не связью этажей, а
    обращением к пустоте: строфа набиралась бы неизвестно чем и молча.

    2026-08-18: сам метод переименован. `genStanza` вырезана вместе с
    документом, единственный производитель — `lentaСтрофа` в ленте. Свойство,
    которое здесь сторожится, не изменилось ни на слово."""
    # ПРОВЕРЯЕМ МОДУЛЬ ЦЕЛИКОМ, А НЕ ОДИН МЕТОД. Раньше вся генерация жила в
    # `genStanza`, и куска файла хватало. В ленте она разложена на два шага:
    # `lentaНабрать` собирает запрос (и берёт форму), `lentaСтрофа` выдаёт
    # готовое из буфера. Смотреть в один метод — значит сторожить половину.
    тело = ГЕНЕРАЦИЯ.read_text("utf-8")
    код = [s for s in тело.split("\n") if not s.lstrip().startswith("//")]
    for мёртвое in ("linkSpec(", "linkKnobs(", "state.chain"):
        assert not [s for s in код if мёртвое in s], \
            f"генерация читает {мёртвое} — этого этажа больше нет"
    assert "this.curSpec()" in тело, "строфа не берёт форму из своей мастерской"


def test_polka_karkasa_nazyvaetsya_formoy():
    """«Строфа» — это РЕЗУЛЬТАТ, а полка про каркас. Отсюда половина путаницы
    «где строфа, а где цепочка»: одно слово значило две вещи. Цепочки не стало,
    а различие осталось: форма — то, по чему строфу собирают."""
    текст = МЕНЮ.read_text("utf-8")
    тело = текст[текст.index("export function renderStanzaMenu("):]
    assert ">форма<" in тело, "полка каркаса снова называется строфой"
    assert "своя форма" in текст


def test_tema_a_ne_klyuch():
    """Одно понятие — одно слово. На разных этажах она звалась то «ключом», то
    «темой». Бэк и статистика зовут её темой — значит тема."""
    ген = ГЕНЕРАЦИЯ.read_text("utf-8")
    assert "'без темы'" in ген and "'тема: «'" in ген
    assert "без ключа" not in ген, "статусная строка снова говорит «ключ»"
