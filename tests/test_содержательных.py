# nakedlunch — счёт содержательных слов и его граница с леммами.
#
# ЧТО БЫЛО. Ворота «не меньше двух содержательных слов» держались на
# `len(обычные)` из `lemmatize_pairs`, а тот считает ровно шесть частей речи:
# существительное, прилагательное (полное и краткое), глагол, инфинитив,
# причастие, деепричастие. НАРЕЧИЙ и СРАВНИТЕЛЬНЫХ СТЕПЕНЕЙ там нет — и строка
# «Дальше — хуже» получала НОЛЬ, то есть выбрасывалась наравне с архивным
# шифром «РГАЛИ. Ф. 155. Оп».
#
# ЗАМЕР (случайная проба 20 000 строк живого индекса, 2026-08-18):
#   порогом >=2 режется 8.62% годных строк;
#   39% из них возвращаются одним лишь расширением списка частей речи;
#   на корпусе это ~79 900 строк, из которых ~70 700 реально доходят до пула
#   при его рабочей Банальности 0.65 (остальные держит запасное banal=9.0).
#
# ПОЧЕМУ СПИСКА ДВА, А НЕ ОДИН РАСШИРЕННЫЙ. `_CONTENT_POS` служит ещё и
# множеством ЛЕММ — для темы, разнообразия соседей, тавтологии и эха в
# избранном. Там наречия вредны: «очень», «уже», «дальше» совпадали бы у всего
# подряд и размывали бы и тему, и близость строк. Счётчику же они нужны: на них
# держится целая короткая строка. Один список не может отвечать на два разных
# вопроса — за это в проекте уже платили дважды.
#
# Прогон: .venv/bin/python -m pytest tests/test_содержательных.py -q

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))
import corpus  # noqa: E402


# ---- вырожденные данные ----------------------------------------------------

def test_пустая_строка_и_мусор_дают_ноль():
    for т in ("", "   ", "—", "...", "!!!", "«»", "- – —"):
        assert corpus.содержательных(т) == 0, repr(т)


def test_одни_служебные_слова_дают_ноль():
    """Предлоги, союзы, частицы и местоимения содержательными не считаются ни
    в старом списке, ни в новом: расширение добавило знаменательные части речи,
    а не отменило разбор."""
    assert corpus.содержательных("и в на же ли бы у от") == 0


def test_имена_собственные_не_считаются():
    """Редкость имени — свойство имени, а не находка автора (правило Раунда 57).
    Строка из одной фамилии обязана остаться пустой, иначе список актёров пьесы
    пройдёт ворота как полноценная строка."""
    assert corpus.содержательных("Вишневецкая") == 0


# ---- собственно починка ----------------------------------------------------

def test_наречия_и_сравнительные_степени_считаются():
    """Та самая строка, ради которой всё затевалось. «дальше» и «хуже» —
    сравнительные степени; до 2026-08-18 они давали ноль."""
    assert corpus.содержательных("Дальше — хуже") == 2


def test_разговорные_строки_проходят_порог():
    """Живые примеры из выдачи, которые порог >=2 выбрасывал."""
    for т in ("Нет у меня денег", "ты очень ошибаешься", "Надо же, как я ошибался"):
        assert corpus.содержательных(т) >= 2, т


def test_мусор_по_прежнему_режется():
    """Расширение списка не должно открыть ворота архивным шифрам и обрывкам —
    иначе починка одного признака сломала бы его же смысл."""
    for т in ("РГАЛИ. Ф. 155. Оп", "для рекламы", "Dijon, 1947"):
        assert corpus.содержательных(т) < 2, т


# ---- граница между счётом и леммами ----------------------------------------

def test_леммы_не_получили_наречий():
    """ГЛАВНЫЙ СТОРОЖ РАЗДЕЛЕНИЯ. Если наречия просочатся в `lemmatize`, молча
    поедут четыре механизма разом: тема, разнообразие соседей, тавтология и
    эхо лемм в избранном. Проверяем на словах, которые счётчик ТЕПЕРЬ считает,
    а множество лемм считать не должно."""
    for т in ("Дальше — хуже", "очень быстро", "надо же"):
        assert corpus.содержательных(т) >= 1, f"счётчик перестал видеть {т!r}"
    assert corpus.lemmatize("Дальше — хуже") == [], (
        "наречия и компаративы просочились в леммы — это сдвинет тему, "
        "разнообразие и тавтологию; расширять надо ТОЛЬКО счётчик")
    assert "очень" not in corpus.lemmatize("очень быстро")


def test_у_счётчика_свой_список_а_не_общий():
    """Списки обязаны быть РАЗНЫМИ объектами с разным составом: сравнявшись,
    они перестанут отвечать на два вопроса и вернут исходную болезнь."""
    assert set(corpus._CONTENT_POS) < set(corpus._СЧЁТНЫЕ_POS), (
        "счётный список перестал быть строго шире — проверь, не слили ли их")
    добавка = set(corpus._СЧЁТНЫЕ_POS) - set(corpus._CONTENT_POS)
    assert {"ADVB", "COMP"} <= добавка, добавка


def test_разбор_токенов_совпадает_с_леммами():
    """Счётчик и `lemmatize_pairs` обязаны резать текст на слова ОДИНАКОВО.
    Разойдись они на пунктуации — и два счёта одного и того же начнут спорить;
    на пунктуации в этом проекте уже теряли слова целиком (см. `_STRIP_CHARS`:
    75 строк из 2406 теряли слова из-за прилипшего многоточия)."""
    for т in ("ночь…", "морфия…", "слово, — сказал", "«тишина»"):
        леммы = len(corpus.lemmatize_pairs(т))
        счёт = corpus.содержательных(т)
        assert счёт >= леммы, (
            f"{т!r}: счётчик {счёт} < лемм {леммы} — значит он потерял слово "
            "на пунктуации, хотя его список ШИРЕ")
