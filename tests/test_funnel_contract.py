def воронка(**kw) -> dict:
    """НАСТОЯЩАЯ воронка из домена — не словарь, набранный руками.

    Путь тут БЕЗИНДЕКСНЫЙ (см. фикстуру `словарь`), и это не лень: он живой —
    так работает установка до первой выпечки индекса, — а читателям воронки
    достаётся именно он же в самый неудобный момент, на пустой выдаче первого
    запуска. Ступеней на нём не бывает, поэтому всё, что про ступени, стоит
    ниже отдельно и на настоящем индексе.

    `real_text` из knobs убран 2026-08-29: ручка «Источники» удалена, ключ
    пришпилен к 1.0, и передавать его значило бы делать вид, что выбор есть."""
    knobs = clean.knobs({"shortlist": 4, **kw.pop("knobs", {})})
    return filters.run([], knobs, Corpus(), nl_fragments=list(ФРАГМЕНТЫ),
                       rhyme="none", **kw)["funnel"]


