def test_причина_не_сваливается_в_общую_фразу(словарь):
    """РЕГРЕССИЯ. Пока функция читала вложенный вид, ВСЕ ветки давали одну
    общую фразу. Одного «называет клаузулу» мало: надо, чтобы разные пустоты
    объяснялись РАЗНО.

    СЛУЧАИ ПЕРЕСОБРАНЫ 2026-08-29 по живым веткам. Два прежних (обе про
    генератор) слились в один ответ, как только генератор вырезали, — и тест
    падал, честно показывая, что сторожит несуществующее. Взамен разведены
    ворота: клаузула, «без мата», «только мат» и просто ворота — это четыре
    РАЗНЫХ настройки, каждая называется своим именем, и слипнись любые две,
    человек снова не узнал бы, какую ручку крутить."""
    ворота = dict(shortlist=0, pool_available=100, nl_survived=0, nl_classic_survived=0)
    случаи = [
        (dict(воронка(), shortlist=0, pool_available=0), {}),
        (dict(воронка(), **ворота), {"Клаузула": 2}),
        (dict(воронка(), **ворота), {"Мат": 0}),
        (dict(воронка(), **ворота), {"Мат": 1}),
        (dict(воронка(), **ворота), {}),
        (dict(воронка(), shortlist=0, nl_fetched=0), {}),
    ]
    ответы = [почему(ф, п) for ф, п in случаи]
    assert len(set(ответы)) == len(ответы), f"причины не различаются: {ответы}"
    assert ОБЩАЯ not in ответы


# ---- читатель 3: КАРТА ВОРОНКИ В ОКНЕ (render.gen.jsx, `пул_и_воронка`) ----
#
# Ступени завелись в Раунде 62, когда замер нашёл в воронке ложь: крупнейшей
# ступени каскада не было вовсе — между `nl_survived` и `shortlist` читалось
# «из 1.5 млн выбрано 8», а на деле «из 1 564 599 СЛУЧАЙНО взято 300, и уже из
# 300 схема собрала 8». Сторож проверяет ИСХОД: цепочка обязана быть настоящей
# цепочкой, то есть числа обязаны сужаться сверху вниз.
#
# ИНДЕКС ЗДЕСЬ НАСТОЯЩИЙ, А НЕ СИНТЕТИКА ФИКСТУРЫ (2026-08-29). Ступени
# рождаются ТОЛЬКО на колоночном пути: с подменённым кэшем ударений они
# приходят пустым словарём, и прежняя проверка стояла под условием
# «если ступени есть у обеих веток» — то есть не выполнялась НИ РАЗУ. Сторож,
# который сам себя выключает, — украшение.

@нет_индекса
def test_obe_vetki_dayut_kartu_voronki():
    """На ОБЕИХ ветках окно обязано суметь нарисовать карту воронки.

    ЧТО ИМЕННО ЧИТАЕТ ОКНО (render.gen.jsx): по `ступени['корпус']` оно решает,
    рисовать ли карту вообще (`естьВоронка`), дальше берёт «всего», «мои книги»,
    «минус показанное», «прошло ворота» и «выдано» (`тяга`, иначе `в_сборку`), а
    рядом читает `f.gen_ran`. Отсутствующие ступени оно отбрасывает само
    (`.filter(ш[1] != null)`) — значит обязательны ровно те, без которых карта
    либо не появится, либо соврёт: `корпус`, `пул` и число выданного.

    ПРЕЖДЕ ТУТ СТОЯЛО РАВЕНСТВО МНОЖЕСТВ ИМЁН, И ОНО СНЯТО 2026-08-29 — не как
    смягчение, а потому что требовало неправды. Классика не знает ни
    «твои_книги», ни «показано» (`select_light` их не считает) и при этом тащит
    мёртвый ключ `тема_буквально`, оставшийся от вырезанной темы. Требовать
    совпадения имён значило бы требовать выдумывать числа, которых никто не
    считал, — ровно та ложь, ради устранения которой ступени и заведены.
    Настоящий контракт — не одинаковые имена, а «карта рисуется на обеих и не
    врёт»."""
    пул = [ИНДЕКС.text(i) for i in range(0, ИНДЕКС.n, max(1, ИНДЕКС.n // 20_000))]

    def прогон(**k):
        return filters.run([], clean.knobs({"shortlist": 4, **k}), Corpus(),
                           nl_fragments=пул, rhyme="аабб", семя=17)["funnel"]

    for ярус, ф in (("алгоритм", прогон()), ("классика", прогон(classic=1.0))):
        assert "gen_ran" in ф, ярус
        ст = ф["ступени"]
        assert ст.get("корпус"), f"{ярус}: окно не станет рисовать карту вовсе"
        выдано = ст["тяга"] if ст.get("тяга") is not None else ст.get("в_сборку")
        # Числа обязаны СУЖАТЬСЯ: карта читается сверху вниз как отсев, и
        # ступень крупнее предыдущей означала бы, что подписи стоят не на своих
        # числах. Берём ровно ту цепь, которую рисует окно, и ни одним числом
        # больше: «минус показанное» — счётчик скрытого, а не выживших, а
        # `ворота` окно не показывает вовсе, потому что считается оно по ВСЕМУ
        # корпусу, а не по включённым книгам (нарочно, см. nlindex.select).
        цепь = [ст["корпус"], ст.get("твои_книги"), ст["пул"],
                выдано, ф["shortlist"]]
        цепь = [x for x in цепь if x is not None]
        assert цепь == sorted(цепь, reverse=True), f"{ярус}: ступени не сужаются: {цепь}"
        assert ф["shortlist"] > 0, f"{ярус}: стенд ничего не собрал — сторожить нечего"


