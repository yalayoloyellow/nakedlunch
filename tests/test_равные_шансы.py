#
# Требование: «темы тоже равные шансы, но после ранжирования по теме всего
# корпуса вообще»; и отдельно — машина не имеет права работать хуже
# классического `rng.sample`.
#
# ЧТО БЫЛО ЗАМЕРЕНО (2026-08-13, полный индекс, пул за воротами 1 564 599, 40
# книг, 60 прогонов по 8 строк):
#   · без темы вся выдача шла из ОДНОЙ книги (3.9% пула, перекос 25.8×),
#     номера фрагментов одного прогона укладывались в окно 293 подряд из
#     2 434 632 — верхушка ранжира была КУСКОМ КОРПУСА;
#   · `rng.sample` по тому же пулу давал 34 книги из 40, самая частая 9.4%;
#   · после правки: 37 книг из 40, самая частая 10.8%.
# С темой, 25 прогонов на тему, три темы: разных строк из 200 было 72–75,
# стало 142–148 (полоса ±0.002).
#
# ПОЧЕМУ ЭТОТ ФАЙЛ. Остальные тесты проверяют КОНКРЕТНУЮ выдачу и слепы к
# распределениям — эталон был зелёным всё то время, пока выдача сползала в одну
# книгу. Тот же приём, что в tests/test_разнообразие.py, только на НАСТОЯЩЕМ
# корпусе и против настоящего рандома как планки.
#
# Прогон: .venv/bin/python -m pytest tests/test_равные_шансы.py -q

import collections
import sys
from pathlib import Path

import numpy as np
import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(КОРЕНЬ / "core"))

import clean
import filters
import nlindex

ИНДЕКС = nlindex.load()
нет_индекса = pytest.mark.skipif(ИНДЕКС is None or getattr(ИНДЕКС, "src", None) is None,
                                 reason="нет индекса или колонки src")

ПРОГОНОВ = 30
РАЗМЕР = 8


class ПустойКорпус:
    def hidden_set(self):
        return set()


def выдача(пул, семя, *, тема=(), связность=0.5):
    knobs = clean.knobs({"real_text": 1.0, "shortlist": РАЗМЕР, "cohesion": связность})
    итог = filters.run([], knobs, ПустойКорпус(), nl_fragments=пул, rhyme="абаб",
                       tags=list(тема), forced=set(), семя=семя)
    return [r["text"] for r in итог["shortlist"]]


@pytest.fixture(scope="module")
def корпус():
    tid = nlindex.text_ids(ИНДЕКС)
    return tid, list(tid.keys()), np.asarray(ИНДЕКС.src)


@нет_индекса
def test_bez_temy_ne_huzhe_randoma(корпус):
    """Планка — классический `rng.sample` по тому же пулу.

    Именно это и было сломано: машина брала всё из одной книги там, где рандом
    брал из тридцати четырёх. Сравнение идёт с рандомом, а не с придуманным
    порогом, чтобы тест не пришлось «калибровать» под очередной корпус."""
    tid, пул, src = корпус
    строки = [t for с in range(ПРОГОНОВ) for t in выдача(пул, с)]
    книги = collections.Counter(int(src[tid[t]]) for t in строки if t in tid)

    живые = np.flatnonzero(ИНДЕКС.gate_mask(False, False, 0))
    rng = np.random.default_rng(4242)
    рандом = collections.Counter(
        src[rng.choice(живые, size=len(строки), replace=False)].tolist())

    assert len(книги) >= 0.8 * len(рандом), \
        f"книг у машины {len(книги)}, у рандома {len(рандом)} — машина беднее"
    доля_маш = max(книги.values()) / len(строки)
    доля_рнд = max(рандом.values()) / len(строки)
    assert доля_маш <= 2 * доля_рнд, \
        f"самая частая книга: машина {доля_маш:.1%}, рандом {доля_рнд:.1%}"


@нет_индекса
def test_bez_temy_vydacha_ne_kusok_korpusa(корпус):
    """Прямой сторож на ту самую поломку: номера фрагментов одного прогона не
    имеют права лежать в узком окне корпуса."""
    tid, пул, _ = корпус
    номера = sorted(tid[t] for t in выдача(пул, 777) if t in tid)
    assert len(номера) >= 4
    размах = номера[-1] - номера[0]
    assert размах > ИНДЕКС.n // 10, \
        f"вся выдача из окна в {размах} фрагментов из {ИНДЕКС.n}"


@нет_индекса
def test_svyaznost_bez_temy_ne_deystvuet(корпус):
    """Заявлено — значит проверено. Без темы связности не на чем работать, и
    ручку надо гасить в интерфейсе, а не делать вид, что она что-то делает."""
    _, пул, _ = корпус
    assert выдача(пул, 5, связность=0.1) == выдача(пул, 5, связность=0.9)


@нет_индекса
def test_svyaznost_s_temoy_deystvuet(корпус):
    """Обратная сторона: с темой ручка обязана двигать выдачу, иначе «починка»
    просто убила бы её целиком."""
    _, пул, _ = корпус
    тема = ("ночь", "город")
    a = выдача(пул, 5, тема=тема, связность=0.15)
    b = выдача(пул, 5, тема=тема, связность=0.85)
    assert a != b


@нет_индекса
def test_polosa_temy_daet_ravnyh():
    """Внутри полосы оценка ОДНА — иначе «равные шансы» остались бы словами.

    Проверяется по таблице, а не по выдаче: так видно саму полосу, а не её
    последствие, прошедшее через рифму и барьер повторов."""
    sims = np.arange(500002, dtype=np.float64) / 500002.0
    nlindex.забыть_таблицу()
    _, pctl, score = nlindex._таблица(ИНДЕКС, {"тема"}, sims,
                                      False, False, 0, 0.5, 0.8)
    лучших = int(np.count_nonzero(score >= score.max() - 1e-9))
    внутри = int(np.count_nonzero(np.abs(pctl - 0.5) <= nlindex.ПОЛОСА_ТЕМЫ))
    # РАВНЫХ ЧУТЬ БОЛЬШЕ, ЧЕМ В ПОЛОСЕ, И ЭТО ОКРУГЛЕНИЕ, А НЕ ОШИБКА. Оценка
    # округляется до четырёх знаков (так во всём каскаде — на этом стоит
    # разведение ничьих), поэтому за краем полосы в 0.6 попадает ещё каёмка
    # шириной 0.00005/0.8 = 6.25e-5 ранжира с каждой стороны. На полном корпусе
    # это ~220 строк из ~7100, то есть 3% полосы. Требуем: полоса не сузилась и
    # не расползлась дальше этой каёмки.
    каёмка = int(2 * (0.00005 / 0.8) * len(score)) + 2
    assert внутри <= лучших <= внутри + каёмка, \
        f"равных {лучших}, в полосе {внутри}, допустимая каёмка округления {каёмка}"
    # полоса ±0.002 — это 0.4% ранжира; на полном корпусе счёт идёт на тысячи,
    # и «равных» обязано быть много, иначе жребию не из чего тянуть
    assert лучших > 1000, f"в полосе всего {лучших} строк — тянуть не из чего"
    nlindex.забыть_таблицу()


# ── ступени воронки: проверять на НАСТОЯЩЕМ индексе ────────────────────────
#
# В test_funnel_contract.py фикстура нарочно уводит на старый путь (там
# проверяется форма ответа), и цепочка ступеней там пуста. Здесь индекс
# настоящий — значит и цепочка настоящая.

@нет_индекса
def test_stupeni_voronki_nastoyashchaya_tsepochka(корпус):
    """Крупнейшая ступень каскада обязана быть ВИДНА и обязана быть жребием.

    Замер 2026-08-13: между `nl_survived` и `shortlist` пропадал переход
    1 564 599 → 300. Пользователь читал «из полутора миллионов выбрано восемь»,
    а на деле — «случайно взято триста, и уже из трёхсот схема собрала восемь»."""
    _, пул, _ = корпус
    knobs = clean.knobs({"real_text": 1.0, "shortlist": 8})
    итог = filters.run([], knobs, ПустойКорпус(), nl_fragments=пул, rhyme="абаб",
                       семя=1)
    ст = итог["funnel"]["ступени"]
    порядок = ["корпус", "ворота", "пул", "жребий"]
    значения = [ст[к] for к in порядок]
    assert значения == sorted(значения, reverse=True), \
        f"ступени не убывают: {dict(zip(порядок, значения))}"
    assert ст["корпус"] == ИНДЕКС.n
    assert ст["жребий"] >= len(итог["shortlist"]), "собрано больше, чем вытянуто"
    # и главное: жребий обязан быть НАМНОГО меньше пула — иначе ступень
    # незаметна, а она решает 99.98% исхода
    assert ст["жребий"] < ст["пул"] / 100, \
        f"жребий {ст['жребий']} против пула {ст['пул']} — ступень потерялась"


@нет_индекса
def test_stupeni_ne_vrut_pro_temu(корпус):
    """`пул` снимается ДО отсева повторов темы. Раньше снимался после, и с
    темой воронка врала на 3 528 строк: они прошли все ворота честно, а в
    счётчике их не было, и потеря выглядела как ужесточение ворот."""
    _, пул, _ = корпус
    knobs = clean.knobs({"real_text": 1.0, "shortlist": 8})
    без = filters.run([], knobs, ПустойКорпус(), nl_fragments=пул, rhyme="абаб",
                      семя=1)["funnel"]["ступени"]
    с_темой = filters.run([], knobs, ПустойКорпус(), nl_fragments=пул, rhyme="абаб",
                          tags=["ночь", "город"], семя=1)["funnel"]["ступени"]
    assert без["тема_буквально"] == 0
    assert с_темой["тема_буквально"] > 0, "ограничитель темы не виден в воронке"
    # ворота от темы не зависят — значит и «пул» обязан совпасть
    assert без["пул"] == с_темой["пул"], "тема не имеет права двигать ворота"
