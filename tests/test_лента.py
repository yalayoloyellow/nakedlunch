def test_goliy_enter_dayot_strofu_a_ne_tolko_command():
    """ПРЯМАЯ ЖАЛОБА: «я сказал нажатие на интер даёт строфу, а у тебя строфа
    на комманд интер». Причина была в порядке проверок: `if (!mod) return;`
    стояло РАНЬШЕ проверки Enter, и голый ↵ до неё не доходил.

    ⌘↵ обязан продолжать работать — мышечная память; ⌥ остаётся единственным
    модификатором со смыслом (обязательное слово темы)."""
    d = node(ДВОЙНИК + """
const c = держатель([]);
c.lentaСтрофа = function (ж) { c._строф.push(!!ж); };   // сеть не трогаем
const голый = c.lentaКлавиша(событие({ key: 'Enter' }));
const командой = c.lentaКлавиша(событие({ key: 'Enter', metaKey: true }));
const контролом = c.lentaКлавиша(событие({ key: 'Enter', ctrlKey: true }));
const жёстко = c.lentaКлавиша(событие({ key: 'Enter', altKey: true }));
const жёсткоС = c.lentaКлавиша(событие({ key: 'Enter', altKey: true, metaKey: true }));
console.log(JSON.stringify({голый, командой, контролом, жёстко, жёсткоС, флаги: c._строф}));
""")
    assert d["голый"] is True, "голый ↵ снова не даёт строфу"
    assert d["командой"] is True and d["контролом"] is True, "⌘↵ / Ctrl+↵ перестали работать"
    assert d["жёстко"] is True and d["жёсткоС"] is True
    assert d["флаги"] == [False, False, False, True, True], \
        f"⌥ должен и только он означает «обязательное слово темы»: {d['флаги']}"


