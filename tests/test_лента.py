def test_na_ekrane_vsegda_odna_strofa():
    """ГЛАВНОЕ ТРЕБОВАНИЕ ЭКРАНА. Дословно: «Я жму интер — оно должно старое
    убирать». Раньше здесь копился список, и он ругался: «ты мне в ленте
    показываешь подряд и старые не уходят».

    Пять вызовов в ОДНОМ круге событий — тот же случай, что пять нажатий
    подряд: на экране обязана остаться последняя строфа целиком, а не хвост из
    двадцати строк и не обрывок."""
    d = node(ДВОЙНИК + """
const c = держатель([]);
for (let i = 0; i < 5; i++) c.lentaПоложить(строки(4, i + 1), { вид: 'строфа' });
c.слить();                                  // один круг событий на все пять
console.log(JSON.stringify({строк: c.state.lenta.length,
                            тексты: c.state.lenta.map(r => r.text),
                            блоков: new Set(c.state.lenta.map(r => r.блок)).size,
                            блок: c.state.lenta[0].блок}));
""")
    assert d["строк"] == 4, f"на экране {d['строк']} строк вместо одной строфы"
    assert d["блоков"] == 1, "на экране смешались строки разных строф"
    assert d["блок"] == 5, "показана не последняя строфа"
    assert d["тексты"] == ["строка 5.0", "строка 5.1", "строка 5.2", "строка 5.3"]


def test_istoriya_pishetsya_po_faktu_pokaza():
    """Владелец дословно: «мы показываем то, что показываем, добавляется в
    историю, а то, чего нет на экране, не добавляется».

    Это не мелочь: запись в историю НАВСЕГДА вычёркивает строку из выдачи.
    Строфа, которую вытеснили раньше, чем она попала на экран, вычеркнула бы
    четыре строки, которых он не видел.

    Отсюда два сторожа разом: `lentaПоложить` не отмечает НИЧЕГО (отмечает
    отрисовка), и повторная перерисовка того же блока не отмечает его дважды."""
    d = node(ДВОЙНИК + """
const c = держатель([]);
c.lentaПоложить(строки(4, 1), { вид: 'строфа' });
c.lentaПоложить(строки(4, 2), { вид: 'строфа' });   // вытеснила первую до отрисовки
const доОтрисовки = c._отметок;
c.слить();
c.lentaОтметитьПоказ();      // так её зовёт componentDidUpdate — ПОСЛЕ отрисовки
c.lentaОтметитьПоказ();      // лишняя перерисовка (часы в шапке, статус, что угодно)
console.log(JSON.stringify({доОтрисовки, отметок: c._отметок, отмечено: c._отмечено}));
""")
    assert d["доОтрисовки"] == 0, "строфа ушла в историю до того, как её показали"
    assert d["отметок"] == 1, f"историю дёрнули {d['отметок']} раз вместо одного"
    assert d["отмечено"] == [["строка 2.0", "строка 2.1", "строка 2.2", "строка 2.3"]], \
        f"в историю ушло не то, что на экране: {d['отмечено']}"


