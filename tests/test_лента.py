#
# ЗАЧЕМ ЭТОТ ФАЙЛ. Лента — единственная поверхность выдачи, и главное в ней не
# отрисовка, а несколько чистых решений: что показывается, что уходит в
# историю, что кладётся в избранное и какая клавиша вообще считается своей.
# Именно они ломаются молча: на экране «как-то не так», а не ошибка.
#
# ПЕРЕПИСАН 2026-08-18 (волна «экран»). До этого лента копилась списком, и
# здесь стояли сторожа движения курсора, диапазона выделения Shift'ом и границ
# блока при перекате. Курсора, выделения и переката больше нет — владелец
# дословно: «там сейчас можно бессмысленно выделить строку одну, и с этим ни
# хуя не делается. Это просто графическое выражение, это бред». Сторожа ушли
# вместе с предметом; список того, что именно ушло, — в надгробии внизу файла.
#
# ПОЧЕМУ НАСТОЯЩИЙ NODE, А НЕ ТЕКСТОВАЯ СВЕРКА. Здесь речь о ПОВЕДЕНИИ, а не о
# структуре модулей: текстовая проверка была бы зелёной при любой ошибке в
# арифметике индексов. Приём тот же, что в tests/test_three_menus.py.
#
# ЧЕГО ЗДЕСЬ НЕТ. Буфера и предзагрузки: они ходят в сеть, их место — живая
