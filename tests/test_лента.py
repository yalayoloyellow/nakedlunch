def test_vyrezannye_klavishi_molchat():
    """СТОРОЖ НА ВРАНЬЁ ИНТЕРФЕЙСА. В этой программе легенда трижды обещала
    несуществующее («перекатить строку», «закрепить строку», «⌘⌥↵ — серия»), и
    каждый раз это ловилось только чтением кода: неработающая клавиша молчит.

    Стрелки, Shift, пробел и R вырезаны вместе с выделением строк и перекатом.
    Здесь проверяется обратное направление той же честности: лента обязана
    вернуть false, то есть НЕ считать это событие своим, — иначе она молча
    съест клавишу, которую могло бы обработать окно."""
    d = node(ДВОЙНИК + """
const c = держатель([]);
c.lentaПоложить(строки(4, 1), { вид: 'строфа' }); c.слить();
const было = JSON.stringify(c.state);
const ответы = ['ArrowDown', 'ArrowUp', ' ', 'Escape'].map(k => c.lentaКлавиша(событие({ key: k })));
ответы.push(c.lentaКлавиша(событие({ key: 'r', code: 'KeyR' })));
ответы.push(c.lentaКлавиша(событие({ key: 'c', code: 'KeyC', metaKey: true })));
c.слить();
console.log(JSON.stringify({ответы, целостность: JSON.stringify(c.state) === было,
                            методы: ['lentaШаг','lentaВыбор','lentaСохранить','lentaКопировать','lentaПерекатить']
                                      .filter(m => typeof c[m] === 'function')}));
""")
    assert d["ответы"] == [False] * 6, f"вырезанная клавиша всё ещё считается своей: {d['ответы']}"
    assert d["целостность"], "вырезанная клавиша меняет состояние"
    assert d["методы"] == [], f"вырезанные методы выделения ещё живы: {d['методы']}"


