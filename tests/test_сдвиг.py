# ── АРТЕФАКТ АДРЕСОВ: ГДЕ ЕГО ИЩУТ И КОГДА ЕМУ НЕ ВЕРЯТ ──────────────────────
#
# Две беды, найденные разбором 2026-09-02, обе про молчание.
#
# 1. КОРЕНЬ. `адреса()` спрашивала `пути.артефакт` — корень ЗАПИСИ, — а спека
#    кладёт адреса рядом со встроенными таблицами, в корень ЧТЕНИЯ. В исходниках
#    корни совпадают и расхождения не видно; в СОБРАННОМ приложении 77 МБ ехали
#    мёртвым грузом, а удлинение строки было выключено навсегда и молча.
#
# 2. ДЛИНА. Докстринга обещала, что перепечка индекса адреса не обесценивает.
#    Неверно: перепечка меняет ЧИСЛО строк (залили книгу, почистили склад), и
#    колонка адресов остаётся короче индекса. Первое же обращение к строке с
#    номером больше её длины роняло генерацию `IndexError` — вместо обещанной
#    тихой деградации пятисотая на ровном месте.

def test_адреса_ищутся_тем_же_путём_что_встроенные_таблицы():
    """`пути.таблица`, а не `пути.артефакт`.

    Первая смотрит СНАЧАЛА в корень записи (свежеиспечённое), потом во
    встроенное из бандла; вторая — только в корень записи. В бандле это
    разница между «работает» и «молча выключено»."""
    import ast
    from pathlib import Path
    src = (Path(__file__).resolve().parent.parent / "core" / "nlindex.py").read_text("utf-8")
    дерево = ast.parse(src)
    for n in ast.walk(дерево):
        if isinstance(n, ast.FunctionDef) and n.name == "адреса":
            зовут = {getattr(u.func, "attr", "") for u in ast.walk(n)
                     if isinstance(u, ast.Call)}
            assert "таблица" in зовут, (
                "адреса() спрашивает не тем путём: в собранном приложении корень "
                "чтения и корень записи разные, и `артефакт` не найдёт то, что "
                "спека положила рядом со встроенными таблицами")
            assert "артефакт" not in зовут, "остался старый путь через артефакт"
            return
    raise AssertionError("функция адреса() не найдена — сторож смотрит не туда")


def test_адреса_короче_индекса_не_принимаются(monkeypatch):
    """Артефакт, отставший от индекса, обязан отдаться как «нет артефакта».

    Иначе удлинение лезет по номеру строки за конец колонки и роняет
    генерацию, хотя докстринга обещает: «нет артефакта — удлинение просто не
    работает, всё остальное работает как работало»."""
    import numpy as np
    import nlindex as nl
    if nl.load() is None:
        import pytest
        pytest.skip("индекс не испечён")

    настоящие = nl.адреса()
    if настоящие is None:
        import pytest
        pytest.skip("артефакт адресов не собран")

    книга, a, b, блоб, оф = настоящие
    # укорачиваем ровно на одну строку — так выглядит артефакт, отставший от
    # перепечки, и именно на этом падало
    monkeypatch.setattr(nl, "_АДРЕСА", None)
    исходный_load = nl.load

    class _Короче:
        n = len(книга) + 1
        def __getattr__(self, имя):
            return getattr(исходный_load(), имя)

    monkeypatch.setattr(nl, "load", lambda: _Короче())
    assert nl.адреса() is None, (
        "артефакт короче индекса принят — первое же удлинение уйдёт за конец "
        "колонки и уронит генерацию IndexError")


# ── ИСХОДНЫЙ ТЕКСТ ДОХОДИТ ДО ИСТОРИИ ────────────────────────────────────────
#
# Отбор подрезает длинную строку и наращивает короткую под слоговую вилку
# (коммиты 679ad70, 324e961). Показанный обрезок обязан сжечь ПОЛНУЮ строку
# корпуса, иначе она выпадет ещё раз — уже целиком, и обещание «показанное не
# возвращается» ломается на каждой подрезанной строке.
#
# ЯДРО ЭТО УМЕЛО ВСЁ ВРЕМЯ: `nlindex.тянуть_строфы` кладёт `_исходный` на
# строку, `corpus.mark_shown` его читает и пишет в `в_корпусе`, `corpus._ключ`
# по нему и прячет. Терялось поле ВО ФРОНТЕ — разбор 2026-09-02 нашёл разрыв в
# трёх местах сразу: в буфере ленты, в очереди показа и в теле запроса.
# Поэтому сторожа два: один на ядро (что оно и правда прячет полную), другой —
# структурный, на все четыре звена фронта.

def test_подрезанная_строка_прячет_полную():
    """Ядро: показали обрезок — полная строка считается показанной."""
    from corpus import Corpus
    к = Corpus()
    полная = "это была очень длинная строка про воду и камень"
    обрезок = "очень длинная строка про воду и камень"
    к.mark_shown([{"text": обрезок, "template": "nakedlunch", "_исходный": полная}])
    спрятано = к.hidden_set()
    assert полная in спрятано, "полная строка осталась непоказанной — выпадет снова"
    # показываем при этом по-прежнему обрезок: человек видел именно его
    assert к.history[-1]["text"] == обрезок
    assert к.history[-1]["в_корпусе"] == полная


