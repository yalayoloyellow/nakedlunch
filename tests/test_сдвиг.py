def test_печкин_модуль_поднимается_из_исходников():
    """ВОРОТА ВНУТРЕННЕЙ РИФМЫ ПОСЛЕ РЕЗА НЕ РАБОТАЛИ ИЗ ИСХОДНИКОВ (2026-09-04).

    `сдвиг._печкин_модуль()` грузит `tools/build_nl_rhyme.py`, а тот делает
    `from _accent import stress_index`. Файл `tools/_accent.py` лежит рядом, но
    `tools` в sys.path не попадает: и launch.py, и api/server.py кладут туда
    только `core`. Модуль падал с ModuleNotFoundError, его глотал
    `except Exception`, функция возвращала None — и ворота молча гасли.

    Из сборки дефекта не видно: PyInstaller кладёт всё в одно пространство
    имён. То есть поведение ручки зависело от способа запуска.

    Тест НЕ требует ruaccent: на уровне модуля он не импортируется, он нужен
    только внутри `акцентуатор()`.
    """
    мод = сдвиг._печкин_модуль()
    assert мод is not None, (
        "печкин модуль не поднялся — ворота внутренней рифмы после реза "
        "молча не проверяются"
    )
    assert hasattr(мод, "_внутренняя_рифма"), (
        "поднялся не тот модуль: правила внутренней рифмы в нём нет"
    )
