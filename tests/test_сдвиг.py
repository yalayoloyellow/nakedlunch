def test_подрезка_доводит_длинную_строку_до_вилки():
    вышло = nlindex._подрезать("и вот тогда он понял всё это разом навсегда", (8, 9), {})
    assert вышло is not None
    assert 8 <= sum(1 for ч in вышло.lower() if ч in "аеёиоуыэюя") <= 9
    assert "и вот тогда".split()[0] not in вышло.split()[:1], "режется голова"


def test_подрезка_не_вытягивает_короткую():
    """Рез умеет только укорачивать. Короткая строка не станет длиннее."""
    assert nlindex._подрезать("короткая строка", (12, 14), {}) is None


def test_подрезка_уважает_ворота():
    """ГЛАВНЫЙ СТОРОЖ ПОДРЕЗКИ. Мат живёт в хвосте, а режется голова — значит
    подрезанная строка может оказаться матерной там, где исходная проходила
    ворота «без мата» по длине. Движок обязан такой рез не делать."""
    грязная = "длинное вступление бля сильный ветер дул"
    assert nlindex._подрезать(грязная, (5, 7), {}) == "бля сильный ветер дул"
    assert nlindex._подрезать(грязная, (5, 7), {"no_mat": True}) is None


@нужен_большой_индекс
def test_запасной_путь_тоже_режет():
    """РЕГРЕССИЯ, ПОЙМАННАЯ ЖИВЫМ ПРОГОНОМ 2026-09-01. Срез кандидатов стал
    ШИРЕ вилки нарочно — в него попадают длинные строки под рез. Запасной путь
    тяги (ослабление запрета на повтор слов) брал из этого среза как есть, и в
    строфу на 8-9 слогов встала строка на 12. Ослаблять там можно правило о
    словах, но не форму: вилка — это то, что человек заказал."""
    idx = nlindex.load()
    # ВОРОТА ПЕРЕКЛИЧКИ ВЗЯТЫ НАРОЧНО: подрезка включается только на голоде
    # (поле меньше `ПОРОГ_ПОДРЕЗКИ`), а на обычных настройках в вилку 8-9 и так
    # попадают 218 042 строки — резать нечего, и сторожить было бы нечего.
    таб, _ = nlindex._таблица(idx, False, False, 7, перекличка=1)
    счёт = {}
    строки = nlindex.тянуть_строфы(idx, таб, [(8, 9)] * 4, "абаб", 60,
                                   np.random.default_rng(4), счёт=счёт,
                                   подрезка={"ворота": {"echo": 1}})
    вне = [x for x in строки if x and not (8 <= x["syllables"] <= 9)]
    assert not вне, f"строк вне вилки: {[x['text'] for x in вне][:3]}"
    assert счёт.get("подрезано", 0) > 0, "подрезка не сработала — сторожить нечего"


@нужен_большой_индекс
def test_подрезка_молчит_на_обычных_настройках():
    """Подрезка — лекарство от голода, а не постоянная надбавка к цене.
    Расширенный срез в пять раз больше, и рифмо-корзины по нему строятся
    сортировкой: цена прогона росла со 114 до 492 мс на строфу. На обычных
    настройках в вилку 8-9 попадают 218 042 строки — резать нечего."""
    idx = nlindex.load()
    таб, _ = nlindex._таблица(idx, False, False, 7)
    счёт = {}
    nlindex.тянуть_строфы(idx, таб, [(8, 9)] * 4, "абаб", 40,
                          np.random.default_rng(4), счёт=счёт,
                          подрезка={"ворота": {}})
    assert счёт.get("подрезано", 0) == 0, "подрезка полезла туда, где материала вдоволь"


@нужен_большой_индекс
def test_подрезка_расширяет_узкий_пул():
    """То, ради чего всё делалось: при воротах переклички в вилку 8-9 попадают
    60 строк из 6 983 прошедших ворота — 98.8% материала отбрасывалось за одну
    только длину."""
    idx = nlindex.load()
    таб, _ = nlindex._таблица(idx, False, False, 7, перекличка=1)
    def собрать(подрезка):
        счёт = {}
        строки = nlindex.тянуть_строфы(idx, таб, [(8, 9)] * 4, "абаб", 60,
                                       np.random.default_rng(4), счёт=счёт,
                                       подрезка=подрезка)
        return len([x for x in строки if x])
    без = собрать(None)
    с = собрать({"ворота": {"echo": 1}})
    assert с > без, (без, с)
