import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "core"))
import сдвиг  # noqa: E402


def test_режется_первое_слово_а_не_последнее():
    """Замер на 40 000 строк: отрезать первое слово меняет рифмо-ключ у 0.98%
    строк, последнее — у 73.1%. Ключ берётся с последнего знаменательного
    слова, поэтому режем голову."""
    из = "и вот тогда он понял всё разом"
    вышло = сдвиг.рез(из, {})
    assert вышло["можно"]
    assert вышло["текст"] == "вот тогда он понял всё разом"
    assert из.split()[-1] == вышло["текст"].split()[-1], "хвост обязан остаться на месте"


def test_слогов_считается_заново():
    вышло = сдвиг.рез("тихо падал первый снег", {})
    assert вышло["можно"]
    assert вышло["слогов"] == sum(1 for ч in вышло["текст"] if ч in "аеёиоуыэюя")


def test_одно_слово_не_режется():
    assert сдвиг.рез("одно", {})["можно"] is False


def test_после_реза_не_остаётся_обрывка_слова():
    """`nlindex` выбрасывает строки, начинающиеся с «нибудь», «либо», «таки» —
    это половинки разорванного слова. Рез не имеет права такую породить."""
    вышло = сдвиг.рез("какой нибудь гнусный тип", {})
    assert вышло["можно"] is False
    assert "обрывк" in вышло["почему"]


def test_рез_не_обходит_ворота_мата():
    """СТОРОЖ НА КОНТРОЛ-ОБМАНКУ. Строка отобрана при «без мата» — значит мата
    в ней нет; но первое слово могло быть единственным нематерным."""
    import filters
    # три слова нарочно: после реза должно остаться два, иначе откажет не мат,
    # а правило «строка из одного слова — не строка»
    грязная = "хорошая тихая ночная " + next(w for w in ("бля", "хуй", "пизда")
                                             if filters.has_mat(w))
    assert filters.has_mat(грязная)
    вышло = сдвиг.рез(грязная, {"no_mat": True})
    assert вышло["можно"] is False
    assert "мат" in вышло["почему"]
    # без этих ворот — тот же рез разрешён
    assert сдвиг.рез(грязная, {})["можно"] is True


def test_полосные_оси_гасят_ручку():
    """Процентиль плотности назначен ЖРЕБИЕМ внутри групп равных значений (155
    разных значений на два миллиона строк, треть корпуса — один и тот же ноль),
    поэтому пересчитать его для сдвинутой строки нельзя. Врать числом хуже, чем
    не дать нажать."""
    строка = "тихо падал первый снег"
    for ось in ("dens", "rare_pair", "rare_word"):
        вышло = сдвиг.рез(строка, {ось: "90-100"})
        assert вышло["можно"] is False, ось
    assert сдвиг.рез(строка, {"dens": ""})["можно"] is True


def test_остаётся_не_меньше_двух_знаменательных():
    """Ворота корпуса требуют двух знаменательных слов — «Г-ЖА ДЕ СЕНТ-АНЖ. — Я»
    проходит все прочие проверки, но это ремарка пьесы, а не строка. Рез не
    имеет права породить такую.

    Слов в строке при этом ХВАТАЕТ (три), иначе откажет другое правило, и
    сторож стерёг бы не то."""
    вышло = сдвиг.рез("красивая глубина и вот", {})
    assert вышло["можно"] is False
    assert "знаменательн" in вышло["почему"]
