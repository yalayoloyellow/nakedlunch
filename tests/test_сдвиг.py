def test_режется_первое_слово_а_не_последнее():
    """Замер на 40 000 строк: отрезать первое слово меняет рифмо-ключ у 0.98%
    строк, последнее — у 73.1%. Ключ берётся с последнего знаменательного
    слова, поэтому режем голову."""
    из = "и вот тогда он понял всё разом"
    вышло = сдвиг.рез(из, {})
    assert вышло["можно"]
    assert вышло["текст"] == "вот тогда он понял всё разом"
    assert из.split()[-1] == вышло["текст"].split()[-1], "хвост обязан остаться на месте"


