def test_рез_не_обходит_ворота_мата():
    """СТОРОЖ НА КОНТРОЛ-ОБМАНКУ. Строка отобрана при «без мата» — значит мата
    в ней нет; но первое слово могло быть единственным нематерным."""
    import filters
    # три слова нарочно: после реза должно остаться два, иначе откажет не мат,
    # а правило «строка из одного слова — не строка»
    грязная = "хорошая тихая ночная " + next(w for w in ("бля", "хуй", "пизда")
                                             if filters.has_mat(w))
    assert filters.has_mat(грязная)
    вышло = сдвиг.рез(грязная, {"no_mat": True})
    assert вышло["можно"] is False
    assert "мат" in вышло["почему"]
    # без этих ворот — тот же рез разрешён
    assert сдвиг.рез(грязная, {})["можно"] is True


