# ПОДРЕЗКА ХВОСТА — одно правило на корпус и на историю
def test_подрезка_снимает_служебный_хвост():
    assert ПОДРЕЗАТЬ("не имеет никакой связи с") == "не имеет никакой связи"
    assert ПОДРЕЗАТЬ("и другой — с искаженной рожей, в") == "и другой — с искаженной рожей"


def test_подрезка_снимает_несколько_слов_подряд():
    """Одного шага мало: «Ну, и» — два служебных слова подряд, и `_оборвана`
    (та отвечает про ОДНО слово) здесь бы остановилась на первом."""
    assert ПОДРЕЗАТЬ("что снимает мерку Ну, и") == "что снимает мерку Ну"


def test_подрезка_идемпотентна():
    """Ровно это свойство позволяет сверять запись со строкой, которую УЖЕ
    подрезали, — и переживать вторую подрезку корпуса."""
    for т in ("не имеет никакой связи с", "холодный ветер", "что снимает мерку Ну, и"):
        один = ПОДРЕЗАТЬ(т)
        assert ПОДРЕЗАТЬ(один) == один, т


def test_подрезка_на_вырожденном_не_падает():
    """Строка целиком из служебных слов, пустая, из одних знаков — всё это
    приходит из реального корпуса, и ответ обязан быть пустым, а не взрывом."""
    for т in ("", "   ", "и", "не в", "...", "«»"):
        assert ПОДРЕЗАТЬ(т) == "" or ПОДРЕЗАТЬ(т).strip(), repr(т)


def test_подрезка_не_ест_законное_окончание():
    """«мало» и «какой» — законные концы фразы, решение Раунда 51. Если их
    когда-нибудь внесут в `_ХВОСТ`, подрезка начнёт РЕЗАТЬ ХОРОШИЕ строки, и
    история перепривяжется к чужим."""
    assert ПОДРЕЗАТЬ("и все мало") == "и все мало"
    assert ПОДРЕЗАТЬ("Воздух-то какой") == "Воздух-то какой"


