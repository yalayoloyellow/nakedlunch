_ПРЕАМБУЛА = """
import sys
sys.path.insert(0, {core!r})
sys.path.insert(0, {api!r})
# Тяжёлые прогревы вон: они не при чём, а без заглушек импорт стоит гигабайты
# (тот же приём, что в test_живость_сборки.py).
import embeddings, filters, generate, nlbridge, wordsuggest
for м in (embeddings, filters, generate, wordsuggest):
    м.warm_caches = lambda: None
nlbridge.open_store = lambda: None
import server
# ДОЖДАТЬСЯ ПРОГРЕВА, ЕСЛИ ОН ВСЁ-ТАКИ СТАРТОВАЛ. Он демон: без ожидания
# процесс успел бы выйти раньше записи, и сторож зеленел бы по гонке, а не по
# свойству. Ждём поимённо тот поток, который заводит `_поднять_прогрев`.
import threading
for _т in threading.enumerate():
    if _т.name == "nl-warm":
        _т.join(60)
"""

_ДЁРНУТЬ = """
# Контроль: тот же дом, тот же штамп — но работу ЗОВУТ явно. Если и здесь файл
# не изменится, значит проверка выше зеленеет впустую.
server._перепривязать_историю()
"""


def _дом_с_расхождением(tmp_path: Path) -> tuple[Path, Path]:
    """Изолированный дом: крошечный индекс + история под ЧУЖИМ штампом."""
    дом = tmp_path / "дом"
    (дом / "data").mkdir(parents=True)
    испечь_индекс(дом / "core" / "data" / "nl_index",
                  ["холодный ветер", "она ушла", "дом на горе"])
    склад = дом / "data" / "corpus.json"
    склад.write_text(json.dumps({
        "accepted": [{"text": "она ушла не", "lemmas": [], "rhyme": "", "ts": 1.0}],
        "history": [{"text": "холодный ветер и", "template": "nakedlunch",
                     "tags": [], "shown_at": 1.0, "restored_at": None}],
        "retention_days": 180.0,
        "index_stamp": "999999@ffffffffffffffff",
    }, ensure_ascii=False), "utf-8")
    return дом, склад


def _слепок(каталог: Path) -> dict:
    """Содержимое И метка времени по ВСЕМУ каталогу данных — не по одному
    файлу. Импорт обязан молчать целиком: и склад, и журнал сессии, и любой
    сайдкар, который заведут завтра. Проверять один известный файл значит
    ловить только ту запись, о которой уже знаешь."""
    снимок = {}
    for п in sorted(каталог.rglob("*")):
        if п.is_dir():
            continue
        снимок[str(п.relative_to(каталог))] = (
            hashlib.sha256(п.read_bytes()).hexdigest(), п.stat().st_mtime_ns)
    return снимок


def _запустить(код: str, дом: Path) -> subprocess.CompletedProcess:
    среда = {**os.environ, "NAKEDLUNCH_HOME": str(дом), "PYTHONIOENCODING": "utf-8"}
    return subprocess.run([sys.executable, "-c", код], env=среда, cwd=str(КОРЕНЬ),
                          capture_output=True, text=True, timeout=600)


@pytest.fixture()
def дом_и_код(tmp_path):
    дом, склад = _дом_с_расхождением(tmp_path)
    преамбула = _ПРЕАМБУЛА.format(core=str(КОРЕНЬ / "core"), api=str(КОРЕНЬ / "api"))
    return дом, склад, преамбула


def test_импорт_сервера_не_трогает_склад(дом_и_код):
    """ГЛАВНЫЙ СТОРОЖ. `import server` при несовпадающем штампе обязан оставить
    избранное и историю нетронутыми — байт в байт и с той же меткой времени."""
    дом, склад, преамбула = дом_и_код
    до = _слепок(дом / "data")
    р = _запустить(преамбула, дом)
    assert р.returncode == 0, f"импорт упал:\n{р.stdout}\n{р.stderr}"
    assert _слепок(дом / "data") == до, (
        "ГОЛЫЙ ИМПОРТ api/server.py ЗАПИСАЛ В ДАННЫЕ ПОЛЬЗОВАТЕЛЯ.\n"
        "Значит работа, которая пишет в данные человека, снова поднимается на "
        "уровне модуля. Её место — в `main()`, рядом с открытием порта "
        "(см. `_поднять_прогрев`).")


def test_контроль_дёрнутая_перепривязка_склад_меняет(дом_и_код):
    """КОНТРОЛЬ К ПРЕДЫДУЩЕМУ. Тот же дом и тот же чужой штамп, но перепривязку
    зовут явно — файл обязан измениться. Без этого теста предыдущий не отличить
    от зелени на пустом месте: он был бы зелёным и на доме без индекса."""
    дом, склад, преамбула = дом_и_код
    до = _слепок(дом / "data")
    р = _запустить(преамбула + _ДЁРНУТЬ, дом)
    assert р.returncode == 0, f"вызов упал:\n{р.stdout}\n{р.stderr}"
    assert _слепок(дом / "data") != до, (
        "перепривязка не изменила склад даже когда её позвали явно — значит "
        "проверка выше стережёт пустоту, а не свойство импорта")
