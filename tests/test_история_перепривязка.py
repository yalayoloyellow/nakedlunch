# nakedlunch — история переживает правку корпуса (2026-08-18).
#
# ЧТО ЗДЕСЬ СТЕРЕЖЁТСЯ И ПОЧЕМУ ИМЕННО ЭТО.
#
# 1. ПЕРЕПРИВЯЗКА. Ретро-подрезка обрывков укоротила 341 680 фрагментов, и
#    1 017 записей истории из 4 571 (22.2%) перестали находить свою строку:
#    сверка идёт по тексту точным совпадением. Инвариант «показанное не
#    возвращается» на них молча перестал действовать.
#
#    ОПОРОЙ СТАЛ НЕ НОМЕР СТРОКИ, И ЭТО ЗАМЕР. Старый `nl_rhyme.json` (6 авг,
#    2 434 632 записи) против живого индекса (18 авг, 2 392 262): номер
#    указывает на ТУ ЖЕ строку у 7 454 из 2 392 262 — **0.312%**. Первое
#    расхождение на номере 268. Номер — позиция в `dict(кэш.поток())`, поэтому
#    любое схлопывание дублей сдвигает весь хвост. Разбор — в
#    `core/corpus.py`, у `перепривязать`.
#
# 2. ИМПОРТ НЕ ПИШЕТ В ДАННЫЕ ЧЕЛОВЕКА. Перепривязка живёт в фоновом прогреве,
#    а тот стартовал НА УРОВНЕ МОДУЛЯ — то есть `import server` из любого теста
#    мог переписать избранное и историю. Между импортом и перезаписью копилки
#    стояла ровно одна проверка совпадения штампа, а в момент перепечи корпуса
#    штампы как раз не совпадают. Поэтому тест ставит НЕСОВПАДАЮЩИЙ штамп: на
#    совпадающем баг не воспроизводится и сторож зеленел бы впустую.

