# ---------------------------------------------------------------------------
# Крошечный индекс на диске. Настоящий весит 745 МБ, а свойства, которые здесь
# проверяются, не зависят от размера — зависят от того, что индекс НАСТОЯЩИЙ:
# его читает тот же `nlindex.Index`, и `load()` сверяет `rules`.
def испечь_индекс(каталог: Path, тексты: list[str]) -> None:
    каталог.mkdir(parents=True, exist_ok=True)
    n = len(тексты)
    блоб = b""
    смещения = [0]
    for t in тексты:
        блоб += t.encode("utf-8")
        смещения.append(len(блоб))
    (каталог / "text_blob.bin").write_bytes(блоб or b"\0")
    колонки = {
        "banal": np.zeros(n, np.float32), "taut": np.zeros(n, np.uint8),
        "mat": np.zeros(n, np.uint8), "syl": np.ones(n, np.uint16),
        "key_id": np.zeros(n, np.uint32),
        "span_a": np.full(n, -1, np.int16), "span_b": np.full(n, -1, np.int16),
        "lem_ids": np.zeros(0, np.int32), "lem_off": np.zeros(n + 1, np.int64),
        "lem2navec": np.zeros(0, np.int32),
        "tokpost": np.zeros(0, np.int32), "tokoff": np.zeros(1, np.int64),
        "text_off": np.array(смещения, np.int64),
        "src": np.zeros(n, np.int32), "content": np.ones(n, np.int16),
    }
    for имя, arr in колонки.items():
        np.save(каталог / f"{имя}.npy", arr)
    (каталог / "meta.json").write_text(json.dumps({
        "n": n, "rules": nlindex.RULES, "built_at": "2026-08-18 00:00:00",
        "keys": ["а"], "lemmas": [], "tokens": [], "sources": ["книга"],
    }, ensure_ascii=False), "utf-8")


@pytest.fixture()
def индекс(tmp_path, monkeypatch):
    """Живой `nlindex` на крошечном индексе. Модуль держит загруженный индекс в
    глобальной переменной, поэтому после подмены каталога его надо забыть — и
    забыть ОБРАТНО после теста, иначе следующий тест получит наш."""
    каталог = tmp_path / "nl_index"
    испечь_индекс(каталог, ["холодный ветер", "она ушла", "дом на горе"])
    monkeypatch.setattr(nlindex, "INDEX_DIR", каталог)
    nlindex.forget()
    yield nlindex.load()
    nlindex.forget()


def свод(idx):
    """`есть` и `подрезать` в том виде, в каком их передаёт сервер."""
    тексты = nlindex.text_ids(idx)
    return тексты.__contains__, ПОДРЕЗАТЬ


