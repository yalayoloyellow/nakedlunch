def test_сохранение_и_чтение_помнят_штамп_и_привязку(индекс, tmp_path, monkeypatch):
    """Перепривязка обязана пережить перезапуск. Иначе проход шёл бы заново на
    каждом запуске — и каждый раз писал бы файл."""
    import corpus as corpus_mod
    monkeypatch.setattr(corpus_mod, "DATA_DIR", tmp_path)
    monkeypatch.setattr(corpus_mod, "CORPUS_PATH", tmp_path / "corpus.json")
    c = Corpus()
    c.mark_shown([{"text": "холодный ветер и", "template": "nakedlunch"}])
    есть, подрезать = свод(индекс)
    c.перепривязать(nlindex.штамп(индекс), есть, подрезать)
    c.save()

    снова = Corpus.load()
    assert снова.index_stamp == nlindex.штамп(индекс)
    assert "холодный ветер" in снова.hidden_set()
    assert снова.перепривязать(nlindex.штамп(индекс), есть, подрезать)["нужна"] is False


