def test_подрезка_корпуса_больше_не_сиротит_запись(индекс):
    """ГЛАВНЫЙ. Запись снята ДО подрезки — с длинным текстом; в корпусе с тех
    пор лежит короткий. Раньше строка возвращалась в выдачу; теперь прячется."""
    c = Corpus()
    c.mark_shown([{"text": "холодный ветер и", "template": "nakedlunch"}])
    assert "холодный ветер" not in c.hidden_set(), "проверка началась не с той точки"

    есть, подрезать = свод(индекс)
    итог = c.перепривязать(nlindex.штамп(индекс), есть, подрезать)

    assert итог["нужна"] is True
    assert итог["история"] == 1
    assert итог["сироты"] == 0
    assert "холодный ветер" in c.hidden_set(), "строка так и не спрятана"
    assert c.history[0]["text"] == "холодный ветер и", \
        "показанное подменили задним числом — человек видел другое"


def test_перепривязка_чинит_и_избранное(индекс):
    """Избранное прячет строку навсегда («никуда не пропадает никогда пока я
    сам не удалю») — и осиротело от той же подрезки: 20 записей из 57."""
    c = Corpus()
    c.accept("она ушла не")
    есть, подрезать = свод(индекс)
    итог = c.перепривязать(nlindex.штамп(индекс), есть, подрезать)
    assert итог["избранное"] == 1
    assert "она ушла" in c.hidden_set()


def test_второй_запуск_на_том_же_штампе_не_работает(индекс):
    """Штамп совпал — работы нет. Иначе проход шёл бы на каждом запуске и на
    каждом писал бы файл пользователя."""
    c = Corpus()
    c.mark_shown([{"text": "холодный ветер и", "template": "nakedlunch"}])
    есть, подрезать = свод(индекс)
    c.перепривязать(nlindex.штамп(индекс), есть, подрезать)
    второй = c.перепривязать(nlindex.штамп(индекс), есть, подрезать)
    assert второй["нужна"] is False
    assert второй["история"] == 0


def test_своя_нумерация_прогона_переживает_перепривязку(индекс):
    """`тексты_прогона` вычитается из скрытого, чтобы повтор по семени отдавал
    те же строки. Если бы она осталась на исходном тексте, а `hidden_set`
    ушла на перепривязанный, вычитание перестало бы совпадать — и повтор по
    номеру молча сломался бы (Раунд 62)."""
    c = Corpus()
    c.mark_shown([{"text": "холодный ветер и", "template": "nakedlunch"}], семя=777)
    есть, подрезать = свод(индекс)
    c.перепривязать(nlindex.штамп(индекс), есть, подрезать)
    assert c.hidden_set() - c.тексты_прогона(777) == set(), \
        "свой след прогона больше не вычитается из скрытого"


