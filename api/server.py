# ПОЧЕМУ ОДИН СУДЬЯ НА ДВА ПОВОДА. Устаревшим процесс бывает не только по
# коду: после перепечки индекса он остаётся с ПРЕЖНИМ кэшем ударений в памяти
# (`filters._NL_RHYME` грузится один раз на импорте и не перечитывается
# никогда), и тогда `filters` честно отказывается от свежего индекса —
# генерация продолжает работать, но медленным путём, и молчит об этом. Повод
# другой, вывод для человека тот же: перезапусти. Поэтому судья один — ровно
# та же дисциплина, что у `_сборка_идёт` (см. tests/test_живость_сборки.py:
# «сторож на причину, а не на следствие»).
#
# ЦЕНА. Обход `core/**/*.py`, `api/*.py`, `main.py`, `launch.py` — 28 файлов,
# **0.60 мс** (замер, 200 повторов). Опрос статуса идёт раз в 1.2 с, то есть
# 0.05% времени. Разбирать `meta.json` в соседней проверке стоило 44 мс — вот
# это было дорого, и оно там же и починено.
_ИСХОДНИКИ = (("core", "**/*.py"), ("api", "*.py"))
_ИСХОДНИКИ_ОТДЕЛЬНО = ("main.py", "launch.py")


def _отпечаток_кода() -> tuple:
    """(сколько файлов кода, самая поздняя правка). Пустой — судить нечем:
    так бывает в собранном приложении, где .py не лежат вовсе."""
    сколько, поздняя = 0, 0
    for корень, шаблон in _ИСХОДНИКИ:
        try:
            обход = list((ROOT / корень).glob(шаблон))
        except OSError:
            continue
        for п in обход:
            if "__pycache__" in п.parts:
                continue
            try:
                с = п.stat()
            except OSError:
                continue
            сколько += 1
            поздняя = max(поздняя, с.st_mtime_ns)
    for имя in _ИСХОДНИКИ_ОТДЕЛЬНО:
        try:
            с = (ROOT / имя).stat()
        except OSError:
            continue
        сколько += 1
        поздняя = max(поздняя, с.st_mtime_ns)
    return (сколько, поздняя)


# Снимается ПРИ ИМПОРТЕ — то есть ровно тогда, когда этот процесс прочитал
# модули в память. Чистое чтение (`stat`), ничего не создаёт: сторож
# «импорт ничего не пишет» (test_boot.py) остаётся в силе.
_КОД_ПРИ_СТАРТЕ = _отпечаток_кода()


def _устарел_процесс() -> str:
    """Чем запущенный экземпляр разошёлся с диском. Пустая строка — не
    разошёлся. Единственный судья: оба повода ведут к одному действию."""
    сейчас = _отпечаток_кода()
    if _КОД_ПРИ_СТАРТЕ[0] and сейчас != _КОД_ПРИ_СТАРТЕ:
        return ("код программы на диске изменился после запуска этого окна — "
                "оно работает по прежнему и может сохранить данные старой формой")
    # Индекс есть, а filters от него отказался — значит в памяти прежний кэш
    # ударений, и генерация идёт медленным путём, не сказав об этом.
    try:
        if nlindex.load() is not None and filters._index_for_current_cache() is None:
            return ("индекс корпуса пересобран, а это окно печёт по прежнему "
                    "кэшу ударений — генерация идёт медленным путём")
    except Exception:
        pass
    return ""


def _устарелость_статус() -> dict | None:
    причина = _устарел_процесс()
    if not причина:
        return None
    return {"id": "устарело", "label": "Перезапусти окно", "state": "error",
            "done": 0, "total": 0, "pct": 0, "detail": причина}


