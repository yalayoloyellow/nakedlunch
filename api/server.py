@app.post("/api/nl/clean")
def api_nl_clean():
    """ОДИН повторяемый проход чистки склада всеми правилами разом.

    ЗАЧЕМ ОТДЕЛЬНОЙ КНОПКОЙ, а не частью перепечки. Чистка МЕНЯЕТ СКЛАД —
    правит и выбрасывает фрагменты, — а перепечка только пересчитывает
    производное и склад не трогает. Смешать их значило бы сделать безобидную
    кнопку разрушительной, и однажды кто-то нажал бы её не глядя.

    ПОСЛЕ ЧИСТКИ НУЖНА ПЕРЕПЕЧКА, и ответ об этом говорит прямо: тексты
    изменились, а кэш рифм ключуется текстом — пока не перепечёшь, подрезанные
    строки останутся без рифмо-ключа. Автоматически её не запускаем: она
    длинная, и решать, когда отдать под неё машину, — дело человека.

    Разбор правил и замеры — в докстринге `NakedLunchStore.почистить`."""
    err = _nl_guard()
    if err:
        return err
    if _ЧИСТКА["state"] == "running":
        return {"ok": False, "busy": True, "detail": "чистка уже идёт"}
    # ОТКАЗ, ЕСЛИ ПЕРЕСЧЁТ УЖЕ ИДЁТ, И ПРОВЕРКА ДО, А НЕ ПОСЛЕ (2026-08-21).
    #
    # Первый вариант чистил склад и ТОЛЬКО ПОТОМ пробовал поднять пересчёт;
    # занятый сборщик отвечал отказом, `пересчёт` уходил в False, а статус
    # говорил просто «готово». Итог: склад почищен, а кэш рифм не знает
    # подрезанных текстов — те же сорок тысяч строк молча пропадают из выдачи.
    # Ровно та ловушка двух нажатий, которую здесь и чинили, только на редком
    # пути и без единого признака.
    #
    # И это ещё гонка: сборщик читает склад с диска ребёнком, а чистка
    # переписывает `state.json` целиком. Чистить под идущей перепечкой нельзя
    # в любом случае.
    if _сборка_сейчас():
        return {"ok": False, "busy": True,
                "detail": "идёт пересчёт — дождись его и нажми снова"}
    # И ЗАЛИВКА ТОЖЕ (2026-08-21). Замок был только на вторую чистку и на
    # пересчёт, а заливка шла мимо — при том что обе пишут ОДИН список
    # фрагментов и ОДИН `state.json` из разных потоков. Чистка забирает список,
    # фильтрует и кладёт обратно; всё, что заливка успела дописать за это
    # время, молча исчезает вместе с книгой.
    if _IMPORT["state"] == "running":
        return {"ok": False, "busy": True,
                "detail": "идёт заливка книги — дождись её и нажми снова"}
    считать_только = bool((request.get_json(force=True, silent=True) or {}).get("сухой"))
    # ДВА НАЖАТИЯ В ОДНУ МИЛЛИСЕКУНДУ — ОДИН ПОТОК, А НЕ ДВА (bug_002
    # ультраревью). Проверка «state == running» выше и запуск потока ниже
    # разделены чтениями диска — два запроса могли пройти оба. Тот же приём,
    # что у заливки (_IMPORT_LOCK): неблокирующий замок, второму — отказ.
    # Двое в _чистка_поток кончаются дракой за nl_rhyme.jsonl.новый — см.
    # комментарий у _выбросить_из_кэша.
    if not _CLEAN_LOCK.acquire(blocking=False):
        return {"ok": False, "busy": True, "detail": "чистка уже идёт"}
    try:
        if _ЧИСТКА["state"] == "running":
            return {"ok": False, "busy": True, "detail": "чистка уже идёт"}
        _ЧИСТКА.update({"state": "running", "этап": "начинаю", "done": 0, "total": 0,
                        "итог": None, "сухой": считать_только, "done_at": 0})
        threading.Thread(target=_чистка_поток, args=(считать_только,), daemon=True).start()
    finally:
        _CLEAN_LOCK.release()
    return {"ok": True, "пошло": True, "сухой": считать_только}


# ---- ЧИСТКА КАК ФОНОВАЯ РАБОТА (2026-08-21) --------------------------------
#
# ПОЧЕМУ НЕ СИНХРОННЫМ РОУТОМ, КАК БЫЛО. Проход идёт две минуты, и первая же
# живая проверка кончилась так: «просто всплывает надпись „посчитаю“
# … и я просто жду на экране, на котором ничего не происходит… непонятно, чего
# я жду, какой у этого прогресс в реальном времени». Его правило, дословно:
# «если что-то происходит где-то, это мне отображается». Синхронный роут на
# минуты — сам по себе дефект проектирования: ожидание без обратной связи
# неотличимо от зависания.
#
# ЛЕНТА РАБОТ УЖЕ ЕСТЬ, ВТОРУЮ НЕ ЗАВОДИМ. `/api/status` отдаёт список работ,
# шапка опрашивает его раз в секунду и рисует кружок с процентом — там же живут
# заливка книги, сборка ударений и перепечка индекса. Чистка становится ещё
# одной записью этого списка, а не собственным механизмом: два способа
# рассказать о фоновой работе разойдутся при первой же правке.
def _сборка_сейчас() -> bool:
    """Идёт ли пересчёт ударений или перепечка индекса ПРЯМО СЕЙЧАС.

    Судья один на оба вопроса — тот же `_сборка_идёт`, что решает, можно ли
    запускать вторую сборку. Свой ответ здесь разошёлся бы с ним при первой же
    правке правил «жив ли сайдкар»."""
    for путь in (_NL_RHYME_STATUS_PATH, _ИНДЕКС_СБОРКА_ПУТЬ):
        try:
            if путь.exists() and _сборка_идёт(json.loads(путь.read_text(encoding="utf-8"))):
                return True
        except Exception:                       # noqa: BLE001
            continue
    if _NL_RHYME_PROC is not None and _NL_RHYME_PROC.poll() is None:
        return True
    return False


_ЧИСТКА = {"state": None, "этап": "", "done": 0, "total": 0,
           "итог": None, "сухой": False, "done_at": 0}
_ЧИСТКА_ДЕРЖИМ = 600.0      # сколько показывать завершённую, как у заливки


# Сторож двух одновременных нажатий «почистить» — см. bug_002 в роуте.
_CLEAN_LOCK = threading.Lock()


def _чистка_поток(считать_только: bool) -> None:
    def доклад(этап: str, сделано: int, всего: int) -> None:
        _ЧИСТКА.update({"этап": этап, "done": сделано, "total": всего})
    try:
        if not считать_только:
            _ЧИСТКА["этап"] = "делаю снимок склада"
            _снимок_склада()
        with nlindex.ЗАМОК:
            итог = _nl().почистить(применить=not считать_только, прогресс=доклад)
        _ЧИСТКА["итог"] = итог
        if not считать_только:
            _после_чистки(итог)
        # «ГОТОВО» СТАВИТСЯ ПОСЛЕДНИМ, И ЭТО НЕ ПОРЯДОК СТРОК, А ЗАМОК.
        # Пока состояние «идёт», сторож устарелости в `_nl_index_status` не
        # трогает цепочку (см. там). Поставь «готово» раньше — и опрос статуса,
        # который идёт РАЗ В СЕКУНДУ, увидит «склад ушёл вперёд индекса» и
        # запустит СВОЮ сборку прямо поверх подчистки кэша. Ровно это и
        # случилось на первом сквозном прогоне: два писателя подрались за один
        # временный файл `nl_rhyme.jsonl.новый`, и сборка упала с ENOENT.
        _ЧИСТКА.update({"state": "done", "done_at": time.time(), "этап": "готово"})
    except Exception as e:                      # noqa: BLE001
        # bug_001 ультраревью: вызов с ОДНИМ аргументом при двух обязательных
        # сам поднимал TypeError, строка ниже не выполнялась — и чистка
        # навсегда оставалась «running», кнопка отвечала «уже идёт» до
        # перезапуска окна. Обработчик ошибки, который сам падает, хуже
        # отсутствующего.
        журнал.ошибка("чистка", f"чистка корпуса: {e}", e)
        _ЧИСТКА.update({"state": "error", "этап": str(e)[:120],
                        "done_at": time.time()})


def _снимок_склада() -> None:
    """Копия `state.json` рядом, под именем `.до-чистки`.

    ЗАЧЕМ. Чистка выбрасывает 348 тысяч фрагментов и правит текст ещё у сорока
    тысяч. Подтверждение с числами защищает от нажатия мимо, но не от «согласился,
    посмотрел и передумал». Приём в проекте уже свой: рядом лежит
    `data/settings.json.копия`, заведённая ровно по этой причине.

    Молча переживает неудачу: не смогли скопировать — чистка всё равно должна
    пройти, иначе отсутствие места на диске отменяло бы работу целиком. Но в
    журнал это уходит: «сделал без страховки» — не то, о чём молчат."""
    try:
        путь = _nl().state_path
        if путь.exists():
            копия = путь.with_suffix(путь.suffix + ".до-чистки")
            копия.write_bytes(путь.read_bytes())
    except Exception as e:                      # noqa: BLE001
        журнал.ошибка("чистка", f"снимок склада перед чисткой не сделан: {e}", e)


def _после_чистки(итог: dict) -> None:
    nlindex.forget_pool()
    # ПЕРЕСЧЁТ ЦЕПЛЯЕТСЯ САМ, И ЭТО НЕ УДОБСТВО, А ПОЧИНКА ЛОВУШКИ.
    #
    # Раньше ответ говорил «теперь жми прогнать всё заново», и это было
    # ДВА нажатия с обязательным порядком: кэш рифм ключуется ТЕКСТОМ, а
    # чистка текст меняет, — значит до перепечки у подрезанных строк нет ни
    # рифмо-ключа, ни лемм, и они молча пропадают из выдачи. Забыл второе
    # нажатие — потерял 40 тысяч строк и не узнал об этом.
    #
    # И перепечка нужна НЕ ПОЛНАЯ. Полный прогон (`--full`) заново считает
    # ударения по всему корпусу — час. А после чистки не хватает ровно тех
    # текстов, которых нет в кэше: подрезанных и с вырезанным именем, около
    # сорока тысяч. Инкрементальный режим считает ровно их (`build_nl_rhyme`:
    # `if text in out: skip`) и следом сам цепляет перепечку индекса. Минуты.
    _ЧИСТКА["этап"] = "подчищаю кэш"
    # ПО ВСЕМУ СКЛАДУ, А НЕ ПО АКТИВНОМУ ПУЛУ (bug_005 ультраревью).
    # Здесь стоял `get_active_pool()` — и тексты ВЫКЛЮЧЕННЫХ книг вылетали
    # из кэша ударений, хотя чистка их фрагменты не трогала: включаешь книгу
    # обратно — а её строки часами пересчитываются заново. Чистка работает по
    # state.fragments целиком, значит и подчистка кэша обязана мерить тем же
    # множеством — иначе два источника правды об одном «что живо».
    итог["из_кэша_убрано"] = _выбросить_из_кэша(
        f.text for f in _nl().state.fragments)
    итог["пересчёт"] = bool(_nl_rhyme_ensure_running())
    _ЧИСТКА["этап"] = "готово, пересчёт пошёл" if итог["пересчёт"] else "готово"


def _чистка_статус() -> dict | None:
    """Запись чистки для ленты работ. Форма — как у заливки (`_import_status`):
    список читает один рендер, и своя форма у каждой записи означала бы правку
    рендера на каждую новую работу."""
    if _ЧИСТКА["state"] is None:
        return None
    if (_ЧИСТКА["state"] != "running"
            and time.time() - _ЧИСТКА.get("done_at", 0) > _ЧИСТКА_ДЕРЖИМ):
        return None
    всего, сделано = _ЧИСТКА["total"], _ЧИСТКА["done"]
    pct = int(100 * сделано / всего) if всего else 0
    что = "Считаю чистку" if _ЧИСТКА["сухой"] else "Чищу корпус"
    подробно = _ЧИСТКА["этап"]
    if всего and _ЧИСТКА["state"] == "running":
        подробно = f"{_ЧИСТКА['этап']} · {сделано:,} из {всего:,}".replace(",", " ")
    return {"id": "clean", "label": что, "state": _ЧИСТКА["state"],
            "done": сделано, "total": всего, "pct": pct, "detail": подробно,
            "итог": _ЧИСТКА["итог"]}


def _выбросить_из_кэша(живые_тексты) -> int:
    """Убрать из кэша ударений тексты, которых больше нет в складе.

    ЗАЧЕМ. Колоночный индекс печётся ИЗ КЭША, а не из склада (см.
    tools/build_nl_index.py: `for i, (text, e) in enumerate(R.items())`), и
    склад там спрашивают только чтобы проставить книгу. Значит выброшенные
    чисткой 348 тысяч строк остались бы в индексе мёртвым грузом: в выдачу они
    не попадут (сшивка пула идёт по тексту склада), но ворота, маски и чёрный
    список будут честно считаться по ним на каждом прогоне.

    Поток, а не словарь в память: кэш это 824 МБ, и `reban` в своё время падал
    молча ровно на попытке поднять его целиком (см. `reban_потоком`)."""
    import кэш
    if not кэш.есть_строчный():
        return 0
    # ВТОРОЙ ПИСАТЕЛЬ НА ОДИН ВРЕМЕННЫЙ ФАЙЛ — ЭТО ПАДЕНИЕ, а не гонка «кто
    # успел». `кэш.Писатель` пишет в `nl_rhyme.jsonl.новый` с ФИКСИРОВАННЫМ
    # именем и подменяет им кэш; двое разом — и один переименовывает файл
    # из-под другого. Поймано сквозным прогоном: сборка упала с
    # «No such file or directory: nl_rhyme.jsonl.новый».
    if _сборка_сейчас():
        журнал.ошибка("чистка", "кэш ударений не подчищен: идёт сборка")
        return 0
    живые = set(живые_тексты)
    убрано = 0
    with кэш.Писатель() as п:
        for текст, поля in кэш.поток():
            if текст in живые:
                п.запиши(текст, поля)
            else:
                убрано += 1
    return убрано


def _подписать_источники(shortlist) -> None:
    """Дописать каждой строке выдачи имя книги, откуда она (Раунд 57).

    Требование: при выделении строки видно, из какой она книги, и книгу можно
    отсюда же отключить.

    Делается ЗДЕСЬ, а не в отборе, и это не срезка угла: отбору источник не
    нужен ни для одного решения, а у сервера уже есть и карта «текст → номер
    строки индекса» (nlindex.text_ids), и колонка источника, и имена книг из
    хранилища. Класть в горячий путь то, что нужно только для показа, значило
    бы платить за это каждой генерацией.
    """
    if not shortlist:
        return
    idx = nlindex.load()
    if idx is None or getattr(idx, "src", None) is None:
        return
    try:
        карта = nlindex.text_ids(idx)
        номера = getattr(idx, "sources", []) or []
        имена = {}
        активна = {}
        for c in (_nl().list_corpora() if _nl() else []):
            имена[c.get("id")] = c.get("name") or c.get("id")
            активна[c.get("id")] = bool(c.get("active"))
        сироты_подписи = []
        for r in shortlist:
            i = карта.get(r.get("text"))
            if i is None:
                continue
            s_i = int(idx.src[i])
            if 0 <= s_i < len(номера):
                cid = номера[s_i]
                # ДУБЛЬ МЕЖДУ КНИГАМИ (bug_011 ультраревью). Один и тот же
                # текст лежит в двух книгах (0.63% текстов — идиомы, латынь,
                # общие обороты), а индекс хранит ОДИН источник на текст: тот,
                # чей фрагмент выиграл при печати. Выключишь его — строка
                # честно придёт из ВТОРОЙ, активной книги, но подпись называла
                # первую, и «отключить эту книгу отсюда» щёлкал по УЖЕ
                # выключенной. Ручка, которая меняет не то, что обещает
                # подпись, — контрол-обманка.
                #
                # Правда восстанавливается доразметкой: подпись выключенной
                # книгой на строке из АКТИВНОГО пула — противоречие по
                # построению, значит текст лежит и в какой-то активной книге.
                # Ищем её ОДНИМ проходом по складу на все такие строки разом —
                # и только когда противоречие есть: обычная выдача этого
                # прохода не платит.
                if not активна.get(cid, True):
                    сироты_подписи.append(r)
                    continue
                r["source_id"] = cid
                r["source"] = имена.get(cid, cid)
        if сироты_подписи:
            нужные = {r.get("text") for r in сироты_подписи}
            найдено = {}
            for f in _nl().state.fragments:
                if f.text in нужные and активна.get(f.corpus_id)                         and f.text not in найдено:
                    найдено[f.text] = f.corpus_id
                    if len(найдено) == len(нужные):
                        break
            for r in сироты_подписи:
                cid = найдено.get(r.get("text"))
                if cid:
                    r["source_id"] = cid
                    r["source"] = имена.get(cid, cid)
    except Exception as e:                                       # noqa: BLE001
        # Подпись — удобство показа. Не смогли — выдача уходит без неё, а не
        # падает пятисотой: цена ошибки здесь не стоит сломанной генерации.
        print(f"nakedlunch: источники к выдаче не приписались ({e})", flush=True)


