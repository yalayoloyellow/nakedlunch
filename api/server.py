# «СКОЛЬКО ОСТАЛОСЬ», А НЕ «СКОЛЬКО ПРОШЛО» (2026-08-28, требование: «зачем
# отсчитывать время сколько загружается, если нужно время сколько осталось и
# чёткое понимание этого»). Темп меряется с ПЕРВОГО наблюдения этой сборки
# этим сервером; откат done назад — новая сборка, точка сбрасывается. Пока
# темпа не видно (первые секунды) — честное «оцениваю остаток», а не ноль.
_ТЕМП: dict = {}


def _осталось(идент: str, done: int, total: int) -> str:
    т = time.time()
    т0, д0 = _ТЕМП.get(идент, (т, done))
    if done < д0:
        т0, д0 = т, done
    _ТЕМП[идент] = (т0, д0)
    if not total or done <= д0 or т - т0 < 3:
        return "оцениваю остаток…"
    ост = max(0.0, (total - done) * (т - т0) / (done - д0))
    if ост < 90:
        return f"осталось ~{int(ост)} с"
    if ост < 5400:
        return f"осталось ~{max(1, int(round(ост / 60)))} мин"
    return f"осталось ~{ост / 3600:.1f} ч"


