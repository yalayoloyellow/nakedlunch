_ВЕС_УМОЛЧАНИЕ = {"корпус": 5.0, "карты индекса": 12.0, "перепривязка истории": 0.5}
_ВЕС_ФАЙЛ = пути.ДАННЫЕ / "прогрев.json"


def _веса() -> dict:
    """Длительности прошлого запуска, а нет их — зашитые умолчания."""
    веса = dict(_ВЕС_УМОЛЧАНИЕ)
    try:
        прошлые = json.loads(_ВЕС_ФАЙЛ.read_text("utf-8"))
        for имя in веса:
            с = float(прошлые.get(имя, 0) or 0)
            if с > 0:
                веса[имя] = с
    except Exception:
        pass          # нет файла, битый, чужой формат — идём на умолчаниях
    return веса


_ВЕС_ЭТАПА = _веса()
_ЭТАП_ПОДПИСЬ = {"корпус": "поднимаю корпус",
                 "карты индекса": "строю карты индекса",
                 "перепривязка истории": "свожу историю с корпусом"}


def _прогрев_статус() -> dict | None:
    """Прогрев в общей ленте работ.

    ЗАЧЕМ. Требование 2026-08-21: «лучше мне показывать загрузочный
    экран… пока не загрузится вообще все, с информацией о том, что именно
    грузится». До этого прогрев был виден только в логе: приложение открывалось,
    ↵ ничего не делал шестнадцать секунд, и объяснения не было нигде.

    Держим запись ещё несколько секунд после готовности — иначе она исчезнет
    ровно в тот момент, когда человек на неё посмотрел."""
    if _ПРОГРЕВ["готов"] and time.time() - _ПРОГРЕВ.get("кончен", 0) > 4:
        return None
    сделано = sum(_ВЕС_ЭТАПА.get(и, 0.5) for и, _ in _ПРОГРЕВ["этапы"])
    всего = sum(_ВЕС_ЭТАПА.values())
    прошло = time.time() - _ПРОГРЕВ["начат"]
    if not _ПРОГРЕВ["готов"]:
        # Внутри идущего этапа считаем по его собственному замеру — иначе
        # процент стоял бы на месте по двенадцать секунд подряд.
        свой = _ВЕС_ЭТАПА.get(_ПРОГРЕВ["этап"], 0.5)
        внутри = прошло - sum(с for _, с in _ПРОГРЕВ["этапы"])
        сделано += min(свой, max(0.0, внутри))
    pct = int(100 * min(1.0, сделано / всего)) if всего else 0
    подпись = _ЭТАП_ПОДПИСЬ.get(_ПРОГРЕВ["этап"], _ПРОГРЕВ["этап"])
    # `done` и `total` — В ОДНИХ ЕДИНИЦАХ (2026-09-02). Здесь стояло
    # `int(прошло)` — секунды на часах, — а `total` был суммой ВЕСОВ. Кольцо в
    # шапке считает свой процент как done/total (methods.corpus.js), поэтому
    # оно упиралось в 100% раньше готовности и спорило с процентом из этой же
    # записи: кольцо 100%, строка ленты 88%. Два индикатора, называющие разные
    # числа об одном событии, — та же ложь экрана, что и молчание.
    return {"id": "warmup", "label": "Запуск",
            "state": "done" if _ПРОГРЕВ["готов"] else "running",
            # БЕЗ ОКРУГЛЕНИЯ ДО ЦЕЛОГО: `int()` здесь и был второй половиной
            # того же дефекта. При долгом прогреве `сделано` подходит к `всего`
            # вплотную (96.8% на выросшем корпусе), а два целых из этого
            # выходят равными — и кольцо снова показывало сто раньше срока.
            # Эти два поля читает ровно один потребитель и ровно для дроби
            # (`methods.corpus.js`: done/total), целыми им быть незачем.
            "done": round(сделано, 1), "total": round(всего, 1),
            "pct": 100 if _ПРОГРЕВ["готов"] else pct,
            "detail": "готово" if _ПРОГРЕВ["готов"]
                      else f"{подпись} · осталось ~{max(0.0, всего - сделано):.0f} с"}


def _перепривязать_историю() -> None:
    """Свести историю и избранное с нынешним составом корпуса — РАЗ на штамп.

    ЗАЧЕМ ЗДЕСЬ. Подрезка корпуса меняет сами строки, а история сверяется по
    тексту — 1 017 записей из 4 571 (22.2%) перестали находиться, и «показанное
    не возвращается» на них молча перестало действовать (замер 2026-08-18,
    BACKLOG.md п.3). Разбор, почему опорой стал не номер строки, а подрезанный
    текст, — в `core/corpus.py`, у самого `перепривязать`.

    ПОЧЕМУ В ПРОГРЕВЕ, А НЕ НА УРОВНЕ МОДУЛЯ. Проходу нужны карта «текст →
    номер» (9.8 с) и загруженный индекс: на уровне модуля он либо платил бы
    этим временем за ОТКРЫТИЕ ПОРТА (окно ждёт здоровья сервера 40 с — Раунд 54
    ровно про то, как в этот потолок однажды не уложились), либо строил бы
    карту второй раз. Здесь он идёт следом за этапом, который эту карту и
    греет, — то есть бесплатно.

    Пишет на диск только когда что-то поменялось: `перепривязать` метит записи
    в памяти, сохранение — здесь."""
    idx = nlindex.load()
    if idx is None:
        return                      # индекса нет — сверять не с чем
    тексты = nlindex.text_ids(idx)
    итог = CORPUS.перепривязать(nlindex.штамп(idx), тексты.__contains__, _как_чистит)
    if not итог["нужна"]:
        return
    CORPUS.save()
    журнал.запись("история",
                  f"перепривязка к корпусу {итог['штамп']}: на месте "
                  f"{итог['на_месте']}, перепривязано {итог['история']} истории "
                  f"и {итог['избранное']} избранного, сирот {итог['сироты']}")


def _как_чистит(текст: str) -> str:
    """Привести текст ТЕМ ЖЕ правилом, каким его правит чистка склада.

    Перепривязка ищет сохранённую строку в новом корпусе и, не найдя, пробует
    нормализованную форму. Форма обязана совпадать с тем, что чистка ДЕЛАЕТ,
    иначе запись истории становится сиротой и уже показанная строка
    возвращается в выдачу.

    СНЯТИЕ ИМЁН УБРАНО ОТСЮДА 2026-08-27 — тем же днём, что и из
    `NakedLunchStore.почистить` (надгробие там): после пересборки корпуса из
    исходников пофрагментный нож имён только портил названия. Держать шаг
    здесь, когда чистка его не делает, значило бы нормализовать строку в
    форму, которой в складе никогда не будет, — ровно та рассинхронизация двух
    правил, от которой этот проект бегает всю жизнь.

    Идемпотентно, как и требует `перепривязать`."""
    return nlindex.Index.подрезать_хвост(текст)


def _прогрев() -> None:
    def этап(имя, работа):
        _ПРОГРЕВ["этап"] = имя
        t = time.time()
        try:
            работа()
        except Exception as e:                                   # noqa: BLE001
            # Молчать нельзя: без корпуса не работает ни генерация, ни статус,
            # и пользователь должен увидеть причину в логе, а не пустую выдачу.
            print(f"nakedlunch: прогрев «{имя}» не удался ({e})", flush=True)
        сек = round(time.time() - t, 1)
        _ПРОГРЕВ["этапы"].append([имя, сек])
        print(f"nakedlunch: прогрев «{имя}» — {сек} с", flush=True)

    def карты():
        # ЧТО ИМЕННО ГРЕТЬ — ЗНАЕТ nlindex, А НЕ РОУТ (Раунд 62). Здесь стоял
        # свой список из двух строк, и он дважды отставал от того, что
        # генерация считает на самом деле: сперва забыли маску целостности
        # (9.2 с), потом маску чёрного списка (**17.4 с** — столько стоила
        # первая генерация после КАЖДОГО запуска, при уже написанном «прогрев
        # завершён»). Два списка одного и того же расходятся всегда; список
        # теперь один, и живёт он там же, где то, что он греет.
        idx = nlindex.load()
        if idx is None:
            return           # индекса нет — генерация идёт старым путём
        nlindex.прогреть(idx)

    этап("корпус", nlbridge.open_store)
    этап("карты индекса", карты)
    этап("перепривязка истории", _перепривязать_историю)
    _ПРОГРЕВ["готов"] = True
    _ПРОГРЕВ["кончен"] = time.time()
    # ЗАПОМИНАЕМ СВОИ ЧИСЛА СЛЕДУЮЩЕМУ ЗАПУСКУ (см. `_веса` выше): так оценка
    # «осталось ~N с» калибруется сама и не протухает вместе с ростом корпуса.
    try:
        _ВЕС_ФАЙЛ.parent.mkdir(parents=True, exist_ok=True)
        _ВЕС_ФАЙЛ.write_text(json.dumps({и: с for и, с in _ПРОГРЕВ["этапы"]},
                                        ensure_ascii=False), "utf-8")
    except Exception:
        pass          # замер — удобство, а не работа: молча уступаем
    print("nakedlunch: прогрев завершён за "
          f"{round(time.time() - _ПРОГРЕВ['начат'], 1)} с", flush=True)


