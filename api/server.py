_ГАСИМ_СВОИХ = False        # «его убили мы» — см. `_проследить_за_сборкой`


def _погасить_детей(timeout: float = 3.0) -> None:
    """Снять сборки, запущенные ЭТИМ процессом. Сперва вежливо и ВСЕМ сразу,
    потом жёстко — тот же порядок, что у `stop_pids` в launch.py: SIGTERM даёт
    сборщику дописать чекпойнт, SIGKILL нужен на случай, когда он застрял в
    чужом коде (ONNX не проверяет сигналы посреди прогона тензора).

    Общий срок на всех, а не по сроку на каждого: launch.py даёт серверу пять
    секунд до SIGKILL, и просрочить их значит снова осиротить детей — теперь
    уже наверняка, потому что SIGKILL нам самим обработать нечем."""
    global _ГАСИМ_СВОИХ
    # Флаг ставится ДО первого сигнала: сторожевой поток просыпается на смерти
    # ребёнка, и к этому мигу он уже обязан знать, что смерть наша.
    _ГАСИМ_СВОИХ = True
    дети = [p for p in (_NL_RHYME_PROC, _NL_INDEX_PROC)
            if p is not None and p.poll() is None]
    for p in дети:
        try:
            p.terminate()
        except Exception:
            pass
    крайний = time.time() + timeout
    for p in дети:
        try:
            p.wait(timeout=max(0.05, крайний - time.time()))
        except Exception:
            try:
                p.kill()
            except Exception:
                pass        # уже мёртв или номер занят другим — не наша беда


def _гасить_детей_при_выходе() -> None:
    """Зарегистрировать гашение на ВСЕХ выходах, а не на одном.

    ОДНОГО `atexit` МАЛО, и это главное здесь. launch.py гасит сервер через
    `proc.terminate()`, то есть SIGTERM, а на него процесс по умолчанию умирает
    мгновенно — `atexit` не отрабатывает вовсе. Ровно та же ловушка уже описана
    в launch.py у `cleanup`: «именно здесь, а не в atexit». Поэтому оба сигнала
    перехватываются сами, а `atexit` остаётся вторым рубежом на путь без
    сигнала (Ctrl-C, обычный возврат из `app.run`).

    Зовётся ТОЛЬКО из `main()` — как `_поднять_прогрев` и по той же причине:
    импорт этого модуля тестом не имеет права ни подменять обработчики сигналов
    в чужом процессе, ни обещать гашение того, чего он не запускал."""
    import atexit
    import signal

    atexit.register(_погасить_детей)

    def по_сигналу(номер, _кадр):
        _погасить_детей()
        # `sys.exit`, а не `os._exit`: сокет и журнал должны закрыться
        # по-человечески. Повторный заход из atexit безвреден — гасить уже
        # некого, список живых детей к тому мигу пуст.
        sys.exit(128 + номер)

    for сиг in (signal.SIGINT, signal.SIGTERM):
        try:
            signal.signal(сиг, по_сигналу)
        except (ValueError, OSError, AttributeError):
            pass        # не главный поток либо платформа без такого сигнала


