_СЛОВАРЬ_ЗАМОК = threading.Lock()
_СЛОВАРЬ_ГРЕЛИ = False


def _прогреть_словарь() -> None:
    """Поднять словарь ударений — один раз за процесс, по первому обращению.

    Замок, а не голый флаг: `warm_caches` разбирает 68.8 МБ и не защищён
    внутри ничем, два одновременных клика построили бы два словаря по 750 МБ
    рядом. Ровно та же дисциплина, что у карты «текст → номер» в
    `nlindex.text_ids`."""
    global _СЛОВАРЬ_ГРЕЛИ
    with _СЛОВАРЬ_ЗАМОК:
        if _СЛОВАРЬ_ГРЕЛИ:
            return
        wordsuggest.warm_caches()
        # ФЛАГ — ТОЛЬКО ПОСЛЕ УСПЕХА (bug_006 ультраревью). Стоял ДО вызова:
        # упавший прогрев (OSError, битый файл, MemoryError — сборщик рифм
        # на 16 ГБ система иногда убивает) оставлял флаг взведённым, и все
        # следующие запросы шли на непрогретом словаре — suggest честно
        # отдаёт [] по всем вкладкам, то есть молча врёт вместо работы,
        # навсегда до перезапуска.
        _СЛОВАРЬ_ГРЕЛИ = True


